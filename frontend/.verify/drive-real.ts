  抄下的.ChatPanel.播放.跳到(8)
  await 稳(120)
  断言(
    问过的句数('S00025', 需求起).join(',') === '1',
    `跳过起演格、她这一次来访开第一句，问的是第 1 句（实际 ${问过的句数('S00025', 需求起).join(',') || '一条没问'}）`,
  )
  断言(放('S00025#1', '要赠品'), '放行 S00025 第 1 句那一版')
