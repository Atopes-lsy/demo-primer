  const 二 = await 等到((k) => k.格 >= 2)
  报('④ 客服那句上屏', 二.见过的)
  断言(二.停 === null, '松手之后没有立刻又被刹住（第 2 格不是客服话（轮 1 的第一条））')
  断言(二.消息[1]?.message_text === 话术1, '第一轮的客服气泡＝刚发出去的那句')
  断言(二.共 === 6 && 二.消息.length <= 6, `总格数没涨、消息没多一条（${二.消息.length}/${二.共}）`)
  断言(
    问过的句数().join(',') === '1',
    `她还没说第二句（第 2 格是客服那句），不重问（实际 ${问过的句数().join(',')}）`,
  )

