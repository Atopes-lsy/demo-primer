  /* `已代发` 那一栏**不在这一格证** —— 这一轮 `主卡: null`，右栏走的是空态，
     根本没有卡可挂。它要的是一轮里既有代发、又有一张卡（第三幕那种），
     见下面 `报备卡` 那两条断言。 */
  断言(
    五.消息[4]?.message_text === 目标.消息[3].message_text,
    '日志里第 2 轮那句原话往后挪了一格，一个字没改',
  )
  断言(
    判定请求.map((r) => r.轮次).join(',') === '1,2,3',
    `三轮各问了一次、按顺序（实际 ${判定请求.map((r) => r.轮次).join(',')}）`,
  )
  // ⑦-丙 一路问过来：说一句问一次，而且「答不上来」时留着上一版
  断言(
    问过的句数().join(',') === '1,2,3',
    `她每说一句问一次、按顺序（实际 ${问过的句数().join(',')}）`,
  )
  断言(
    需求请求.filter((r) => r?.会话ID === 'S00001').length === 3,
    '一个句数只问一次（没有重复问第 1 句）',
  )
  断言(
    五.要什么 === '泵头坏了 ＋ 急',
    `第 2、3 句还没答上来，那一行留着上一版（实际 ${JSON.stringify(五.要什么)}）`,
  )
  断言(放('S00001#3', '要赔付'), '放行第 3 句那一版')
  断言((await 行变成('要赔付')) === '要赔付', '第 3 句一落地就换成它')
  断言(放('S00001#2', '想要张图'), '放行第 2 句那一版（晚到的那一份）')
  断言(
    (await 行变成('要赔付')) === '要赔付',
    '晚到的第 2 句**盖不回**那一行（往回扫是先近后远，不是先到先得）',
  )

  // ⑥ 再走一遍，演到头
  抄下的.PrimerPanel.onUseScript()
  await 稳(80)
  断言(看().草稿 === 话术3, '第三轮［采用］灌的是第三轮的话术')
  抄下的.ChatPanel.onSend(看().草稿)
  const 完 = await 等到((k) => k.格 >= k.共)
  报('⑥ 演到头', 完.见过的)
  断言(完.格 === 6 && 完.停 === null, '演到第 6 条，不欠谁一个按钮')
  /* 演到头也还是 7 条：第 2 轮那条代发一直插在下标 3，日志第 3 轮那句挪到 6。 */
  断言(完.消息[6]?.message_text === 话术3, '第三轮的客服气泡＝刚发出去的那句')
  断言(完.共 === 6, `两条发出去的话都没往消息表尾巴上加（共 ${完.共} 条）`)
  断言(完.消息.length === 7, `屏幕上有 7 条（6 条日志 ＋ 1 条代发），实际 ${完.消息.length}`)
  断言(完.要什么 === '要赔付', '演到头那一行留在第 3 句那一版上（不算串到别的会话）')

