  抄下的.ChatPanel.播放.播放()
  const 待报 = await 等到((k) => k.停 === '一键报备')
  报('③ 停在［一键报备］', 待报.见过的)
  断言(!待报.超时 && 待报.格 === 1, `停在第一条客服话之前＝第 1 格（实际 ${待报.格}）`)
  断言(待报.建议形态 === '需要授权', `右栏是「需要授权」那张卡（实际 ${待报.建议形态}）`)
