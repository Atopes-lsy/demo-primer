/**
 * 播放器状态机 —— 会话回放的进度、播放/暂停、速度。
 *
 * # 数的是「格」，不是「条」
 *
 * 一格 = 一次节拍，由调用方给的总格数定。**一格是什么由会话自己决定**：
 *
 *   - 有剧本的会话：一格是**剧本的一步**。一步可以带消息，也可以不带
 *     （「系统翻出上一次的记录」「六源扫描」「逾期浮出」这些拍子屏幕上不涨消息，
 *     变的是右栏）。所以步数和消息条数根本不是一回事。
 *   - 普通会话：没有剧本，时间线就是「一条消息一步」，一格 = 一条。
 *
 * **这个区分是真的，不是命名洁癖。** 早先这里叫「条数」，因为当时那份剧本恰好
 * 一步一条消息（`条到步(n) === n`），两个单位看着可以互换。换成有「空步」的
 * 剧本之后，按条数走就会把整拍空步跳过 —— 右栏的报备、逾期、入库全都演不出来。
 *
 * # 速度是「一格几秒」，不是倍速
 *
 * 早先这里是倍速（0.5x/1x/2x/4x），乘在**剧本每一步自己写的 `间隔`** 上。演示
 * 下来两处都不合用：一是要心算（「这一步 2.6 秒，2 倍速是多久」），二是每步各
 * 定各的间隔，整片的节奏没法一眼说清，讲快了讲慢了都得回去翻剧本改。
 *
 * 现在只有 `间隔选项` 那三档，**选了几秒就是一格几秒**。剧本不再自定节奏，
 * 所以 `剧本事件` 上那个 `间隔` 字段也一并删了 —— 留着就是第二个真相。
 *
 * 状态只有两个：「播到第几格」和「用户想不想放」，其余全是派生的。特别是
 * **不存「当前是第几格」的副本** —— 进度条的值直接来自 `已播格数`，拖动就直接
 * 写它。少一份会不同步的状态，就少一类「拖完不回弹」的 bug。
 *
 * `在放` 是派生的（`播放中 && 还没播完 && 没被外部停格按住`），不是存的。播到
 * 最后一格时 `在放` 自己变成 false，不需要在 effect 里再 setState 一次 —— 那会
 * 多渲染一轮，而且「播完了」本来就是「位置到了头」的同义词，不该另存一个标志位
 * 去追它。真窗口那颗卡也是同一个道理：卡在等就按住，不另记「我停住了没有」。
 *
 * 定时器归 `useEffect` 管：`已播格数` 一变，旧定时器就清掉重排，所以拖进度条
 * 等于「取消当前这一跳，从新位置重新起跳」。不需要额外的暂停逻辑。
 *
 * **函数名是英文的，别改回 `use播放器`。** React 靠 `/^use[A-Z0-9]/` 认自定义
 * Hook，中文开头认不出来 —— 认不出来就不会检查依赖数组，也不会被 React
 * Compiler 优化。文件名、变量名、返回类型都还是中文，只有这个前缀必须是 ASCII。
 */

import { useCallback, useEffect, useState } from 'react'

/**
 * 可选速度：**每一格停多久**（毫秒）。三档对应播放器上的 `1s / 3s / 10s`。
 *
 * 1s 跳过铺垫，10s 留着讲细节。演示的人知道自己这一步有多少话要讲，直接挑一档。
 */
export const 间隔选项 = [1000, 3000, 10000] as const
export type 格间隔 = (typeof 间隔选项)[number]

/** 开屏用哪一档。取中间那档 —— 1s 讲不完一句，10s 冷场。 */
export const 默认格间隔: 格间隔 = 3000

/**
 * `停在` 的一个**特殊值**：不是「等你点某个按钮」，是「后端还在判，谁也点不了」。
 *
 * 真窗口的时间线要在**每一轮客服那句之前**停住（那一句上屏等于发出去了），而
 * 「这一轮怎么处理」是 `POST /api/判定` 几秒后才答上来的。那几秒里没有任何按钮
 * 可点 —— 报成「等你点［…］」是假话，报成「已暂停」又会被演示的人当成卡死，
 * 然后去按 ▶。两种错法都会把「建议得先被采纳」这条规矩当场绕过去。
 *
 * 所以它做一个**哨兵值**混在同一个字段里：调用方（`App.真窗口停`）判定还在飞时
 * 返回它，`播放器` 认出来就原样显示，不套「等你点［］」那个壳。不另开一个布尔
 * 参数，是因为「要停」这件事只能有一个答案 —— 分两个字段的话，两个都给值的
 * 那一天就是两处优先级各说各话。
 */
export const 判定中提示 = '正在判定…'

/**
 * 「它现在为什么不动」那一句话。**播放器和真窗口标题栏那颗小按钮都念它。**
 *
 * 两处各拼一遍的话，同一件事会在两个地方写成两种字（一边「等你点［采用］」、
 * 一边「等待采用」），而两边看着都像是对的 —— 这一行是演示的人唯一的提示，
 * 字对不上就是提示对不上。`判定中提示` 那个哨兵值不套「等你点［］」的壳，
 * 理由见它自己的文档串。
 *
 * 前面那个 `⏸` 是「**它是故意停的**」，不是「播放器坏了」：没有它，演示的人
 * 会去按 ▶ 把该点的那一下绕过去。
 *
 * 参数**不收 `null`**：调用方先判空再调，省得返回值还要调用方再判一次。
 */
export function 停的样子(停在: string): string {
  return `⏸ ${停在 === 判定中提示 ? 判定中提示 : `等你点［${停在}］`}`
}

export interface 播放状态 {
  /** 屏幕上应当演到第几格。0 表示一格没演，等于空会话。 */
  已播格数: number
  /** 总共几格。有剧本时是步数，没有时是消息条数。 */
  总格数: number
  在放: boolean
  /** 当前每一格停多久。 */
  格间隔: 格间隔
  播放: () => void
  暂停: () => void
  /** 播放/暂停切换。空格键和按钮都走它。 */
  切换: () => void
  /**
   * 跳到第 n 格（n 是已播格数）。手动跳会顺带暂停。
   *
   * `上限` 给得出就按它夹，不再看 `总格数`。**切会话时必须给**，理由见实现处。
   */
  跳到: (格: number, 上限?: number) => void
  重置: () => void
  /** 单步：演下一格。停在末格时按它是重新开始，不是死按钮。 */
  下一跳: () => void
  设格间隔: (v: 格间隔) => void
  /**
   * 现在在等客服点界面上的哪个按钮。没在等就是 null。
   *
   * 播放器拿它把「已暂停」改写成「等你点［一键报备］」—— 光停在那一格不说
   * 停的原因，演示的人会以为播放器卡死了。
   *
   * 两个来源：剧本停在第几格（`停格`）、真窗口上有张主卡等着（`外部停格`）。
   * 演到头了都算不在等 —— 详见实现处。
   */
  停在: string | null
  /**
   * 接着放。**和 `播放` 的区别是演到头了不会重头再来。**
   *
   * 给「在等人点按钮」续放用：点了按钮，时间线接着走，不是重播。只在**真的在
   * 等某个按钮**时才生效 —— 剧本停在某一格上（`停格`）也好、真窗口那颗卡还等着
   * （`外部停格`）也好；别的时候点一下卡片就把时间线带走，是另一类惊吓。
   */
  继续: () => void
}

/** 没有要停的格子时用这一份。常量，保证引用稳定 —— 它进 effect 的依赖数组。 */
const 无停格: ReadonlyMap<number, string> = new Map()

/**
 * @param 总格数 一共几格。有剧本的会话给步数，普通会话给消息条数。
 * @param 停格 第几格要停下来等人点按钮，值是要点的那个按钮的字（`剧本.等点击`）。
 *   **必须是稳定引用**（调用方 `useMemo` 出来）—— 它进定时器 effect 的依赖数组，
 *   每次渲染现造一个 Map 的话，每次渲染都会把定时器清掉重排，播放会被渲染拖慢。
 * @param 外部停格 **算「这一格停不停」的那条规则** —— 传进来的那一刻现调，返回
 *   要等的那行字（非空即停）。**真窗口专用。**
 *
 *   为什么是规则不是值（2026-10-04 改的）：规则要用到「现在第几格」，而那个数
 *   **就在这个 hook 里**。传值的话调用方得在调用之前算好，可它拿不到这个数 ——
 *   绕不出来。传规则进来，`已播格数` 在这边现取，那一圈就不存在了。
 *
 *   剧本那张 `停格` 表是按格号写死的（第 3 格等［发送］、第 6 格等［一键报备］），
 *   因为演示的节奏是编排好的。真窗口没有剧本：这一轮判出什么、什么时候判回来，
 *   都由 `POST /api/判定` 说了算 ——「第几格停」得**按格算出**来（真窗口的规则
 *   在 `App.真窗口停` 里，判据是「下一格是某一轮的客服话、而这一轮还没处理」）。
 *
 *   **非 null 就是「按住」：时间线不自己往前。**（`在放` 里多出来那一个 `&&`）
 *   这一格到了，正在跑的定时器在下一轮渲染里被清掉，进度原样停在那儿；提示行写
 *   「等你点［X］」。客服点了那个按钮，规则这边返回 `null`，时间线接着走。
 *
 *   和 `停格` 那条路**有一处不一样，是故意的**：`停格` 的停只在**到达**那一刻
 *   发生一次，之后按 ▶ 照样往下放（那儿的注释写着为什么）；`外部停格` 是派生的，
 *   只要规则还要求停，▶ 就按不动。真窗口这条规矩是「建议得先被采纳」，不是
 *   「演示的人可以跳过去」—— 想放行，点卡上那个按钮。（手动单步和拖刻度不受
 *   影响：那两下是人在说话，不是时间线自己跑。）
 *
 *   ⚠️ 它**不进定时器 effect 的依赖数组**，也不必进：`在放` 本来就在里面，而它
 *   一变这边的 `在放` 就跟着变。所以每次渲染现造一个函数传进来（调用方就是这么
 *   写的）不会把定时器清掉重排 —— 播放不会被它拖慢。
 *
 * 传数而不是传一张每格各自的间隔表：速度现在是全局的一档，不再按格定制。
 * 早先那张表的存在理由就是「每步停多久由剧本自己定」，那个设计已经去掉了。
 */
export function usePlayer(
  总格数: number,
  停格: ReadonlyMap<number, string> = 无停格,
  外部停格: ((格: number) => string | null) | null = null,
): 播放状态 {
  const [已播格数, set已播格数] = useState(0)
  const [播放中, set播放中] = useState(false)
  const [格间隔, set格间隔] = useState<格间隔>(默认格间隔)

  const 演完了 = 已播格数 >= 总格数

  // `外部停格` 这一格给得出字 = 正等着人点 = **按住不放**（见上面 `@param`）。
  //
  // **这一条就是「该停的那一格停住」的全部实现。** 不另存一个「停住了」的标志，
  // 也不在别处喊暂停：规则一给字，`在放` 翻假，定时器 effect 的依赖跟着变，
  // 正在等的那一跳被清掉，进度原样停在那儿。同理，客服点了卡上的按钮、规则
  // 变回 `null` 的那一刻，它自己就接着放。
  const 在放 = 播放中 && !演完了 && !外部停格?.(已播格数)

  const 跳到 = useCallback(
    (格: number, 上限?: number) => {
      // `上限` 是「**这次跳**的上限」，不给才退回本 hook 的总格数。
      //
      // # 为什么切会话非得显式传它（2026-10-03）
      //
      // `选会话` 里 `setActiveId(id)` 和这一跳在**同一次事件处理**里，重渲染
      // 还没发生 —— 所以这个闭包里的 `总格数` 还是**上一条会话**的。拿它夹的话：
      //
      //   - 上一条更长：新会话的起点夹不住，原样落下去 —— 而那个起点是
      //     `起演格`，本该落在新会话里，现在落到了它的**后面**，回放直接从
      //     中间开始，前面几条消息一条不演；
      //   - 上一条更短：起点被夹小到上一条的格数，同样演不全。
      //
      // 两种都**不会报错**，屏幕上只是「这条会话的回放看着有点怪」。调用方算好
      // 新会话的格数传进来，就不依赖闭包里的旧值了。
      const 顶 = 上限 ?? 总格数
      set已播格数(Math.max(0, Math.min(顶, 格)))
      // 手动拖进度 = 接管节奏。停下来等演示的人讲完再按播放，比抢着往下演好。
      set播放中(false)
    },
    [总格数],
  )

  const 重置 = useCallback(() => 跳到(0), [跳到])
  const 暂停 = useCallback(() => set播放中(false), [])

  const 播放 = useCallback(() => {
    // 已经演到头时按播放 = 从头再演一遍。少了这一下，演示演完一轮之后再点播放
    // 就毫无反应 —— 而那正是最常按的一次。
    set已播格数((n) => (n >= 总格数 ? 0 : n))
    set播放中(true)
  }, [总格数])

  const 切换 = useCallback(() => {
    if (播放中) 暂停()
    else 播放()
  }, [播放中, 播放, 暂停])

  const 下一跳 = useCallback(() => {
    // 单步也接管节奏：在播的时候点单步，计时器和手会抢着推进。
    set播放中(false)
    set已播格数((n) => (n >= 总格数 ? 1 : n + 1))
  }, [总格数])

  // 空格键 = 播放/暂停。演示时手不用够鼠标。
  // 打字的时候不能触发：焦点在输入框里，空格就是个空格。
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.code !== 'Space') return
      const t = e.target as HTMLElement | null
      if (t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.isContentEditable)) return
      e.preventDefault()
      切换()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [切换])

  // 演到最后一格，`在放` 派生为 false，这个 effect 自己就不再排下一个定时器了。
  useEffect(() => {
    if (!在放) return
    // 第 0 格立刻出现（按了播放就该有反应），之后每一格停满一档。
    const 当前 = 已播格数
    const t = setTimeout(
      () => {
        const 下一 = 当前 + 1
        set已播格数(下一)
        // 演到「要等人点界面」的那一步就把「在放」收掉，停在这儿。**停在它上面
        // 而不是停在它前面** —— 那一步的产出（报备卡、变红的主卡）正是他要对着
        // 点的东西，得先露出来。
        //
        // 「停」在这里只发生一次：判断写在**到达**的那一刻，不是从 `已播格数`
        // 派生的。派生的话，停在那一格时按播放会被立刻按回去 —— 死按钮。
        if (停格.has(下一)) set播放中(false)
      },
      当前 === 0 ? 0 : 格间隔,
    )
    return () => clearTimeout(t)
  }, [在放, 已播格数, 格间隔, 停格])

  // 停在这一格等谁点、还是根本没在等。派生，不另存 —— 存一份就多一处要跟
  // `已播格数` 同步的状态。
  //
  // 剧本那张表按格号查得到就用它；查不到再看 `外部停格` 这条规则（真窗口那条
  // 路）。两者不会同时成立：真窗口没有剧本，`停格` 是空表。
  //
  // **演到头就不算「在等」了。** 卡上屏之后一直在（点了［采用］卡也不撤），
  // 客服点完它、时间线一路放到末格 —— 那时该说的是「已播完」，不是催他再去点
  // 一个刚点过的按钮。空会话（总格数 0）也落在这条上，本来就没有可等的。
  //
  // ⚠️ 副作用只有一处：**剧本最后一步要是标了 `等点击`，它会不显示。** 现在
  // 两条演示线的停格都在中间（线一 3/7/8 步、线二第 1 步），没有踩到；将来
  // 往末步加停格的话，得回来改这儿。
  //
  // 真窗口那条规则**在这一句里被再调一次**（`在放` 已经调过）—— 纯函数，两次
  // 同参必得同解，不必为它开一份缓存。
  const 停在 = 在放 || 演完了 ? null : (停格.get(已播格数) ?? 外部停格?.(已播格数) ?? null)

  const 继续 = useCallback(() => {
    // 只在真的在等某个按钮时才续放。别的时候（比如正暂停在第 3 格，演示的人顺手
    // 点了下卡片）不该把时间线带走。
    if (已播格数 >= 总格数) return
    // 两个「停」都得认：剧本停在格号上，真窗口停在 `外部停格` 那条规则上。少了
    // 后半个，真窗口那边客服点了［发送］也放不动 —— 时间线卡住，而屏幕上写着
    // 「等你点」。
    if (!停格.has(已播格数) && !外部停格?.(已播格数)) return
    set播放中(true)
  }, [已播格数, 总格数, 停格, 外部停格])

  return {
    已播格数,
    总格数,
    在放,
    格间隔,
    播放,
    暂停,
    切换,
    跳到,
    重置,
    下一跳,
    设格间隔: set格间隔,
    停在,
    继续,
  }
}
