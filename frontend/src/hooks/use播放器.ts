/**
 * 播放器状态机 —— 会话回放的进度、播放/暂停、速度。
 *
 * # 数的是「格」，不是「条」
 *
 * 一格 = 一次节拍，由调用方给的总格数定。**一格是什么由会话自己决定**：
 *
 *   - 有剧本的会话：一格是**剧本的一步**。一步可以带消息，也可以不带
 *     （「系统翻出上一次的记录」「六源扫描」「逾期浮出」这些拍子屏幕上不涨消息，
 *     变的是右栏）。所以步数和消息条数根本不是一回事。
 *   - 普通会话：没有剧本，时间线就是「一条消息一步」，一格 = 一条。
 *
 * **这个区分是真的，不是命名洁癖。** 早先这里叫「条数」，因为当时那份剧本恰好
 * 一步一条消息（`条到步(n) === n`），两个单位看着可以互换。换成有「空步」的
 * 剧本之后，按条数走就会把整拍空步跳过 —— 右栏的报备、逾期、入库全都演不出来。
 *
 * # 速度是「一格几秒」，不是倍速
 *
 * 早先这里是倍速（0.5x/1x/2x/4x），乘在**剧本每一步自己写的 `间隔`** 上。演示
 * 下来两处都不合用：一是要心算（「这一步 2.6 秒，2 倍速是多久」），二是每步各
 * 定各的间隔，整片的节奏没法一眼说清，讲快了讲慢了都得回去翻剧本改。
 *
 * 现在只有 `间隔选项` 那三档，**选了几秒就是一格几秒**。剧本不再自定节奏，
 * 所以 `剧本事件` 上那个 `间隔` 字段也一并删了 —— 留着就是第二个真相。
 *
 * 状态只有两个：「播到第几格」和「用户想不想放」，其余全是派生的。特别是
 * **不存「当前是第几格」的副本** —— 进度条的值直接来自 `已播格数`，拖动就直接
 * 写它。少一份会不同步的状态，就少一类「拖完不回弹」的 bug。
 *
 * `在放` 是派生的（`播放中 && 还没播完`），不是存的。播到最后一格时 `在放`
 * 自己变成 false，不需要在 effect 里再 setState 一次 —— 那会多渲染一轮，而且
 * 「播完了」本来就是「位置到了头」的同义词，不该另存一个标志位去追它。
 *
 * 定时器归 `useEffect` 管：`已播格数` 一变，旧定时器就清掉重排，所以拖进度条
 * 等于「取消当前这一跳，从新位置重新起跳」。不需要额外的暂停逻辑。
 *
 * **函数名是英文的，别改回 `use播放器`。** React 靠 `/^use[A-Z0-9]/` 认自定义
 * Hook，中文开头认不出来 —— 认不出来就不会检查依赖数组，也不会被 React
 * Compiler 优化。文件名、变量名、返回类型都还是中文，只有这个前缀必须是 ASCII。
 */

import { useCallback, useEffect, useState } from 'react'

/**
 * 可选速度：**每一格停多久**（毫秒）。三档对应播放器上的 `1s / 3s / 10s`。
 *
 * 1s 跳过铺垫，10s 留着讲细节。演示的人知道自己这一步有多少话要讲，直接挑一档。
 */
export const 间隔选项 = [1000, 3000, 10000] as const
export type 格间隔 = (typeof 间隔选项)[number]

/** 开屏用哪一档。取中间那档 —— 1s 讲不完一句，10s 冷场。 */
export const 默认格间隔: 格间隔 = 3000

export interface 播放状态 {
  /** 屏幕上应当演到第几格。0 表示一格没演，等于空会话。 */
  已播格数: number
  /** 总共几格。有剧本时是步数，没有时是消息条数。 */
  总格数: number
  在放: boolean
  /** 当前每一格停多久。 */
  格间隔: 格间隔
  播放: () => void
  暂停: () => void
  /** 播放/暂停切换。空格键和按钮都走它。 */
  切换: () => void
  /**
   * 跳到第 n 格（n 是已播格数）。手动跳会顺带暂停。
   *
   * `上限` 给得出就按它夹，不再看 `总格数`。**切会话时必须给**，理由见实现处。
   */
  跳到: (格: number, 上限?: number) => void
  重置: () => void
  /** 单步：演下一格。停在末格时按它是重新开始，不是死按钮。 */
  下一跳: () => void
  设格间隔: (v: 格间隔) => void
  /**
   * 这一格在等演示的人点界面上的哪个按钮。没在等就是 null。
   *
   * 播放器拿它把「已暂停」改写成「等你点［一键报备］」—— 光停在那一格不说
   * 停的原因，演示的人会以为播放器卡死了。
   */
  停在: string | null
  /**
   * 接着放。**和 `播放` 的区别是演到头了不会重头再来。**
   *
   * 给「停在某格等人点」续放用：点了按钮，时间线接着走，不是重播。只在真的
   * 停在一格上时才生效 —— 别的时候点卡片按钮把时间线带走，是另一类惊吓。
   */
  继续: () => void
}

/** 没有要停的格子时用这一份。常量，保证引用稳定 —— 它进 effect 的依赖数组。 */
const 无停格: ReadonlyMap<number, string> = new Map()

/**
 * @param 总格数 一共几格。有剧本的会话给步数，普通会话给消息条数。
 * @param 停格 第几格要停下来等人点按钮，值是要点的那个按钮的字（`剧本.等点击`）。
 *   **必须是稳定引用**（调用方 `useMemo` 出来）—— 它进定时器 effect 的依赖数组，
 *   每次渲染现造一个 Map 的话，每次渲染都会把定时器清掉重排，播放会被渲染拖慢。
 *
 * 传数而不是传一张每格各自的间隔表：速度现在是全局的一档，不再按格定制。
 * 早先那张表的存在理由就是「每步停多久由剧本自己定」，那个设计已经去掉了。
 */
export function usePlayer(总格数: number, 停格: ReadonlyMap<number, string> = 无停格): 播放状态 {
  const [已播格数, set已播格数] = useState(0)
  const [播放中, set播放中] = useState(false)
  const [格间隔, set格间隔] = useState<格间隔>(默认格间隔)

  const 演完了 = 已播格数 >= 总格数
  const 在放 = 播放中 && !演完了

  const 跳到 = useCallback(
    (格: number, 上限?: number) => {
      // `上限` 是「**这次跳**的上限」，不给才退回本 hook 的总格数。
      //
      // # 为什么切会话非得显式传它（2026-10-03）
      //
      // `选会话` 里 `setActiveId(id)` 和这一跳在**同一次事件处理**里，重渲染
      // 还没发生 —— 所以这个闭包里的 `总格数` 还是**上一条会话**的。拿它夹的话：
      //
      //   - 上一条更长：新会话的起点夹不住，原样落下去 —— 而那个起点是
      //     `起演格`，本该落在新会话里，现在落到了它的**后面**，回放直接从
      //     中间开始，前面几条消息一条不演；
      //   - 上一条更短：起点被夹小到上一条的格数，同样演不全。
      //
      // 两种都**不会报错**，屏幕上只是「这条会话的回放看着有点怪」。调用方算好
      // 新会话的格数传进来，就不依赖闭包里的旧值了。
      const 顶 = 上限 ?? 总格数
      set已播格数(Math.max(0, Math.min(顶, 格)))
      // 手动拖进度 = 接管节奏。停下来等演示的人讲完再按播放，比抢着往下演好。
      set播放中(false)
    },
    [总格数],
  )

  const 重置 = useCallback(() => 跳到(0), [跳到])
  const 暂停 = useCallback(() => set播放中(false), [])

  const 播放 = useCallback(() => {
    // 已经演到头时按播放 = 从头再演一遍。少了这一下，演示演完一轮之后再点播放
    // 就毫无反应 —— 而那正是最常按的一次。
    set已播格数((n) => (n >= 总格数 ? 0 : n))
    set播放中(true)
  }, [总格数])

  const 切换 = useCallback(() => {
    if (播放中) 暂停()
    else 播放()
  }, [播放中, 播放, 暂停])

  const 下一跳 = useCallback(() => {
    // 单步也接管节奏：在播的时候点单步，计时器和手会抢着推进。
    set播放中(false)
    set已播格数((n) => (n >= 总格数 ? 1 : n + 1))
  }, [总格数])

  // 空格键 = 播放/暂停。演示时手不用够鼠标。
  // 打字的时候不能触发：焦点在输入框里，空格就是个空格。
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.code !== 'Space') return
      const t = e.target as HTMLElement | null
      if (t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.isContentEditable)) return
      e.preventDefault()
      切换()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [切换])

  // 演到最后一格，`在放` 派生为 false，这个 effect 自己就不再排下一个定时器了。
  useEffect(() => {
    if (!在放) return
    // 第 0 格立刻出现（按了播放就该有反应），之后每一格停满一档。
    const 当前 = 已播格数
    const t = setTimeout(
      () => {
        const 下一 = 当前 + 1
        set已播格数(下一)
        // 演到「要等人点界面」的那一步就把「在放」收掉，停在这儿。**停在它上面
        // 而不是停在它前面** —— 那一步的产出（报备卡、变红的主卡）正是他要对着
        // 点的东西，得先露出来。
        //
        // 「停」在这里只发生一次：判断写在**到达**的那一刻，不是从 `已播格数`
        // 派生的。派生的话，停在那一格时按播放会被立刻按回去 —— 死按钮。
        if (停格.has(下一)) set播放中(false)
      },
      当前 === 0 ? 0 : 格间隔,
    )
    return () => clearTimeout(t)
  }, [在放, 已播格数, 格间隔, 停格])

  // 停在这一格等谁点、还是根本没在等。派生，不另存 —— 存一份就多一处要跟
  // `已播格数` 同步的状态。
  const 停在 = (在放 ? undefined : 停格.get(已播格数)) ?? null

  const 继续 = useCallback(() => {
    // 只在真的停在一格上时才续放。别的时候（比如正暂停在第 3 格，演示的人顺手
    // 点了下卡片）不该把时间线带走。
    if (已播格数 >= 总格数) return
    if (!停格.has(已播格数)) return
    set播放中(true)
  }, [已播格数, 总格数, 停格])

  return {
    已播格数,
    总格数,
    在放,
    格间隔,
    播放,
    暂停,
    切换,
    跳到,
    重置,
    下一跳,
    设格间隔: set格间隔,
    停在,
    继续,
  }
}
