import type { Disposition, OutputKind } from '../../types'

/** 输出类型在「本轮处置」里的说法。主卡显示动词，这里要的是**已经发生的状态**。 */
const 说法: Record<OutputKind, string> = {
  AI直发: '已由 Primer 自动回复',
  客服点发送: '待你确认后发送',
  报备: '已报备',
  转交: '已转交',
}

/**
 * **没有剧本**的会话（真窗口）用这一套。
 *
 * # 为什么非分两套不可
 *
 * 两条路的**时态**不一样，而上面那张表是**过去式**的：
 *
 *   - **演示两条线**：那些事剧本真的演过了。演到第 6 格，「已报备」说的是刚刚
 *     屏幕上发生的事 —— 报备卡、单号、状态徽标都跟着一起出来的。台词就是叙事
 *     本身，一个字都不能改（2026-10-04 拍：先只改真窗口）。
 *   - **真窗口**：这一屏上**一件事都还没发生过**，而且不会自己发生 ——
 *     聊天区一个字节都不动，`App.handleSendPending` 对它们直接空手而回。
 *     所以「已报备」在那批会话上是**假话**。
 *
 * 假话的代价不是不好看，是**客服不去点**了：屏上写着「已报备」，他会以为这一轮
 * 已经报完，于是既不点［一键报备］也不往下问 —— 而那张报备单根本不存在。
 * 2026-10-04 实测 S00001：判定答的是 `报备`，屏幕上就写「已报备」，
 * **一次报备都没发生过。**
 *
 * # `AI直发` 也归「待你确认」—— 2026-10-04 改，此前写的是「建议直接发送」
 *
 * 四格里 `客服点发送` 那句本来就是将来式，照抄；另三格是「已 X」改成
 * 「待你确认后 X」，一句话里只动了时态。
 *
 * **`AI直发` 和 `客服点发送` 在这里撞成同一句是故意的。** 早先它单独写成
 * 「建议直接发送」，想留住的差别是「这条不用你改」。那个理由在演示线上成立
 * （那句话真发出去了），在真窗口上**不成立**：那里没有东西会自己发出去，
 * 成稿就躺在主卡里等［采用］—— 两张卡要点的是同一个按钮。留着「直接发」
 * 那三个字，客服读到的仍然是「这条没经过我就出去了」，而这正是它要修的那句话。
 *
 * 两条**都留着**，别顺手合并：上面那张表是演示线的，这一张是真窗口的，
 * 合并的那一刻演示线第 3 格就会跟着一起改掉。
 */
const 说法待确认: Record<OutputKind, string> = {
  AI直发: 'AI 可直接发送',
  客服点发送: '待你确认后发送',
  报备: '待你确认后报备',
  转交: '待你确认后转交',
}

/** 每种输出的强调色，和主卡保持一致。 */
const 配色: Record<OutputKind, string> = {
  AI直发: 'text-ai-ink',
  客服点发送: 'text-ink-2',
  报备: 'text-hold-ink',
  转交: 'text-risk-ink',
}

type Props = {
  items: Disposition[]
  /**
   * 这一屏**还没有任何事发生过** —— 每条处置都还只是建议，等客服动手。
   *
   * 由 `ChatPanel` 按「这条会话有没有剧本」定：有剧本的演示线演过就是演过，
   * 没有剧本的真窗口从没发生过。**别在这里现推** —— 这个组件是纯展示的，
   * 它不该知道「剧本」是什么东西。
   */
  待确认?: boolean
  /**
   * 「客服点发送」那一条，**话已经发出去了**（见 `App` 的 `本轮已发`）。
   *
   * 31 §3.7 那张表的最后一行就是这一格：S10 后「把『孕妇能否用』改成 已发送」。
   * 同样是纯展示的入参 —— 谁发的、发没发过，都由调用方算好了递进来。
   */
  已发本轮?: boolean
}

/**
 * 本轮处置清单。
 *
 * 一轮可能拆出多条主张、产出不同输出，主卡只显示最高态。没有这块，客服会
 * 以为 AI 抢了他的活，或者漏做了什么 —— 所以每条主张的处置都要能查到。
 */
export default function RoundPanel({ items, 待确认, 已发本轮 }: Props) {
  if (items.length === 0) return null

  const 表 = 待确认 ? 说法待确认 : 说法

  /**
   * `客服点发送` 那一格的三态：`待你确认后发送` →（客服按了发送）→ `已发送`。
   *
   * 只换这一格：另三格（`AI直发`／`报备`／`转交`）本来就是「已经发生了什么」的
   * 说法，和客服手上这一下无关。`已发本轮` 为真时那一轮等的就是这一条 ——
   * 话出去了，这一行不该还挂着将来式。
   */
  const 念 = (d: Disposition) =>
    已发本轮 && d.输出 === '客服点发送' ? '已发送' : 表[d.输出]

  return (
    <div className="primer-round-summary border-t border-line-soft bg-canvas px-3 py-2">
      <p className="text-note font-medium text-ink-2">
        本轮处置
        <span className="ml-1 font-normal text-ink-4">
          主卡只显示最高态，其余在这里可查
        </span>
      </p>

      <ul className="mt-1.5 space-y-1">
        {items.map((d) => (
          <li key={d.主张} className="flex items-baseline gap-1.5 text-body">
            <span className="shrink-0 text-ink-4">◆</span>
            <span className="shrink-0 text-ink">{d.主张}</span>
            <span className="shrink-0 text-ink-4">→</span>
            <span className={配色[d.输出]}>{念(d)}</span>
            {d.说明 ? (
              <span className="truncate text-note text-ink-4">（{d.说明}）</span>
            ) : null}
          </li>
        ))}
      </ul>
    </div>
  )
}
