/**
 * 消息发送方。
 *
 * `AI` 是 Primer 自动发出的消息（输出①），xlsx 里没有这类。
 * `系统推送` 是店铺的营销推送（「满 300 减 50 券」「积分兑换」），聊天记录里有
 * 16 条 —— 既不是买家说的也不是客服说的，归到哪一边都会让判定层读错。
 */
export type SenderRole = '买家' | '客服' | 'AI' | '系统推送'

/** 消息内容类型。数据里目前只出现「文本」和「图片」，需要时在此扩展。 */
export type ContentType = '文本' | '图片'

/**
 * 聊天记录工作表的一行，一行一条消息。
 *
 * `chat_content` 是形如 `[{"index":0,"content":"..."}]` 的 JSON 字符串；
 * `message_text` 是同一内容的纯文本提取，UI 优先用它，省掉解析。
 */
export interface ChatMessage {
  会话ID: string
  消息序号: number
  message_id: string
  发送时间: string
  角色: SenderRole
  买家昵称: string
  发送方: string
  店铺: string
  scene_major: string
  scene_minor: string
  is_target_buyer_message: boolean
  message_text: string
  内容类型: ContentType
  chat_content: string
  category: string
  /** 仅「图片」类型有值，形如 `mock_images/broken_pump/S00001_03.jpg`。 */
  image_path: string
  关联订单号: string
  关联工单号: string
  /**
   * 仅 `角色 === 'AI'` 的消息有值：署名行，如
   * `Primer 自动发送 · 依据「口径表 K10」`。
   *
   * 这一列不在 xlsx 里，是界面的扩展字段 —— 渲染图要求把 AI 代发的出处
   * 标在气泡下面，让客服一眼看出哪句不是自己说的。
   */
  署名?: string
}

