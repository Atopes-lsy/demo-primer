/**
 * `POST /api/需求分解` 的前端入口 —— 右栏「这次要什么」那一行的值。
 *
 * # 那一行原来是把顾客原话攒起来
 *
 * 三次开口就是三句引文连成一串，中间还夹着「在吗」「好的，谢谢啦」。2026-10-04
 * 起交给模型拆成几个短需求，用 ` ＋ ` 连起来。**拆分和连法都在后端**
 * （`llm/拆需求.py` 拆、`api/需求分解.py` 连），这边一个字符都不拼 —— 拼一份
 * 就是第二份真相，两边漏改一处，屏幕上那一行会换一种排版。
 *
 * # 什么时候问（两条路、两个口径）
 *
 *   - **演示两条线：跟着她的话走。** 屏幕上多一句买家话就问一次，
 *     `看到几句买家话` 就是屏幕上演到的那一句的序号 —— 线一第 1 格她开口、
 *     第 6 格她提起赠品、第 9 格她道谢，这一行跟着动三次，多一条需求就多一截；
 *   - **112 个真窗口：打开哪个问哪个**，不带那个参数（＝ 整趟都看得见）。
 *
 * 为什么不塞进 `GET /api/会话列表` 一起问：那条路一次装 114 个窗口、纯规则
 * 18 ms，加上模型就是 114 次调用排在一个请求里，而模型没答上来时它连原来那份
 * 原话都给不出去（`api/需求分解.py` 文件头的两条取舍）。
 *
 * # 它盖在谁上面
 *
 * 盖在**判定刚写上去的值**上面，也盖在剧本写的那个值上面。三层的先后由
 * `App.贴判定` 排：剧本 →（判定接口）→ 需求分解。模型一答上来，屏幕上那一行
 * 就是模型的值；模型没答上来，留着的还是原来那份，一个字都不动。
 *
 * ⚠️ **失败是安静的，这是有意的。** 后端没起、超时、答得不合法、这一趟她一句
 * 买家话都没有 —— 一律 `null`，调用方什么都不改。演示当天模型出任何岔子，
 * 整屏仍然是完整的（这是本文件唯一的失败策略，没有第二个分支）。
 *
 * ⚠️ **但也正因为安静，光看那一行分不出跑没跑过** —— 演示线上的剧本值
 * （`剧本.ts` 里手写的 `精华含不含乙醇 ＋ 怀孕能不能用`）和模型值长得几乎一样。
 * 「有没有真跑过」由右栏顶上那行标记说话（`App` 的 `需求兜底`）。
 */

import type { StateRow } from '../types'

/**
 * 响应体，**逐字照 `backend/app/api/schemas.py` 的 `需求分解响应`**。
 *
 * 和 `判定响应` 同一个理由：这个形状是右栏自己消费的，不进 `types/index.ts`
 * （那个文件归接口线独占，`backend/tests/test_schemas.py` 直接解析它）。字段名
 * 一个字都不许改 —— 两边漂移**不会让任何东西报错**，右栏那一行只是不变。
 *
 * **只有 `值`，没有「需求列表」那一份**：同一件事传两遍，两份一旦不同步，
 * 右栏两处会显示不一样的内容，而两处都「看着对」。分隔符也归后端。
 */
export interface 需求分解响应 {
  会话ID: string
  值: string
}

/**
 * 超时。和 `判定.ts` 同一个数。
 *
 * **没有这一条的话，后端半死（进程在、不响应）会让那一行永远停在原话上** ——
 * 而这和「模型今天不灵」长得一模一样。超了就什么都不改，回落的那份还在。
 */
const 超时毫秒 = 12_000

/**
 * 取一次需求分解。**任何失败都返回 `null`，不抛。**
 *
 * 和 `取判定` 同一套：调用方（`App` 那个 effect）对四种失败的处理完全一样，
 * 抛的话每个调用点都要包一层 try，而漏掉的那一个会在演示当天变成一个没接住的
 * 拒绝。`值` 是空串也在调用方那一层挡住 —— 那是「没拆出来」的另一半。
 *
 * `看到几句买家话` 是**买家话的条数，不是消息条数**。两边对同一条会话的编号
 * 对不上（后端多一条开头的客服承诺、剧本多一条现场发的），而买家话的顺序两边
 * 一样。不给就是「整趟都看得见」——**这个字段缺省掉是 `JSON.stringify` 干的**
 * （`undefined` 的键它自己丢掉），不是这边拼了一个少了键的对象。
 */
export async function 取需求分解(
  会话ID: string,
  看到几句买家话?: number,
): Promise<需求分解响应 | null> {
  try {
    const 答 = await fetch('/api/需求分解', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ 会话ID, 看到几句买家话 }),
      signal: AbortSignal.timeout(超时毫秒),
    })
    if (!答.ok) return null
    return (await 答.json()) as 需求分解响应
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿。故意不分类：调用方的处理完全一样。
    return null
  }
}

/**
 * 那一次请求的缓存键：`会话ID#看到几句`，整趟就是 `会话ID#整趟`。
 *
 * **为什么键里要带句数。** 演示那条路是「她说一句问一次」，线一九格里问三次、
 * 三次的值不一样。只按会话存的话，往回拖到第 1 格右栏还挂着她说完赠品之后
 * 那个值 —— `判定表` 按轮次存，防的正是同一件事（那边写着拖回上一轮会撞上
 * 什么）。真窗口那边句数恒为「整趟」，所以一个窗口一辈子一条。
 *
 * 句数用 `#` 隔开而不是拼成数字串：`S_DEMO_A1` 和 `S_DEMO_A#1` 不会撞。
 */
export function 需求分解键(会话ID: string, 看到几句买家话?: number): string {
  return `${会话ID}#${看到几句买家话 ?? '整趟'}`
}

/**
 * 「这次要什么」的行标签。
 *
 * **同一个字面值在四个地方出现**：后端 `api/需求分解.py` 的 `这次要什么`、
 * 这里、`判定.ts` 的 `剧本说了算的行`、`剧本.ts` 每一步的快照。改的话一起改 ——
 * 改漏这一处的后果是**什么都不发生**（找不到那一行就原样返回，见下）。
 */
const 行标签 = '这次要什么'

/**
 * 把模型拆出来的值贴到那一行上。
 *
 * **只换 `值`**，`备注`／`警示`／`时限` 原样留着 —— 那些不是模型给的，也不该
 * 跟着动（这一行本来就只有 `值`，写全是为了别人照着这个函数改别的行时不出错）。
 *
 * 两种情况原样返回，都不报错：
 *
 *   - **`值` 是空的** ＝ 没拆出来。**留原来那份**是这一整条路的兜底策略，
 *     在这儿挡住，`App` 那边就不用再判一次；
 *   - **行里没有「这次要什么」**（`行们` 是 `undefined`、或者剧本第 1 格那种
 *     只有三行的快照）。此时**不加一行**：行数与顺序归剧本（`判定.合顾客情况`），
 *     这里只改值。真窗口那 114 个窗口是后端装配的五整行，永远找得到。
 */
export function 合需求分解(
  行们: StateRow[] | undefined,
  值: string | undefined,
): StateRow[] | undefined {
  if (!行们 || !值?.trim()) return 行们
  return 行们.map((行) => (行.标签 === 行标签 ? { ...行, 值 } : 行))
}
