/**
 * `POST /api/需求分解` 的前端入口 —— 右栏「这次要什么」那一行的值。
 *
 * # 那一行原来是把顾客原话攒起来
 *
 * 三次开口就是三句引文连成一串，中间还夹着「在吗」「好的，谢谢啦」。2026-10-04
 * 起交给模型拆成几个短需求，用 ` ＋ ` 连起来。**拆分和连法都在后端**
 * （`llm/拆需求.py` 拆、`api/需求分解.py` 连），这边一个字符都不拼 —— 拼一份
 * 就是第二份真相，两边漏改一处，屏幕上那一行会换一种排版。
 *
 * # 什么时候问：**两条线都跟着她的话走**
 *
 * 屏幕上多一句买家话就问一次，`看到几句买家话` 就是她**这一次来访**说到第几句 ——
 * 演示线一第 1 格她开口、第 5 格她提起赠品、第 8 格她道谢，这一行跟着动三次，
 * 多一条需求就多一截。
 *
 * **真窗口也是这一条（2026-10-04 改的）。** 原先它开窗就问整趟，两处不对：
 *
 *   - **剧透** —— 她后面几句还没演到，整趟拆出来的需求已经摆在右栏上了；
 *   - **问完就不动了** —— 回放整趟走一遍，那一行一个字节都不变，而它演的明明
 *     是「她说着说着，系统就懂了」。
 *
 * 接口上 `看到几句买家话` 仍旧可以不给（＝ 整趟），`api/需求分解.py` 那条路也
 * 还在，**前端不用它了**（`取需求分解` 的参数写着）。真窗口那个数由
 * `App` 数出来 —— 数的时候要刨掉窗口里更早几次来访的买家话（`起演格` 之前那段），
 * 后端切的是「本次来访」（`api/需求分解.py` 第 2 步），两边对不上就是多问了一句
 * 她还没说的话，而屏幕上和「模型今天灵得很」长得一样。
 *
 * 为什么不塞进 `GET /api/会话列表` 一起问：那条路一次装 114 个窗口、纯规则
 * 18 ms，加上模型就是 114 次调用排在一个请求里，而模型没答上来时它连原来那份
 * 原话都给不出去（`api/需求分解.py` 文件头的两条取舍）。
 *
 * # 它盖在谁上面
 *
 * 盖在**判定刚写上去的值**上面，也盖在剧本写的那个值上面。三层的先后由
 * `App.贴判定` 排：剧本 →（判定接口）→ 需求分解。模型一答上来，屏幕上那一行
 * 就是模型的值。
 *
 * **模型没答上来时留着什么，两条线不一样，这是有意的：**
 *
 *   - **演示线留着剧本那份**（`剧本.ts` 手写的 `精华含不含乙醇 ＋ 怀孕能不能用`）。
 *     剧本本来就是按「她说到这里」写死的，所以它**就是**这一格的正确答案；
 *   - **真窗口留着上一版**（`最近一版`）—— 她刚开口、这一句还没算出来的那几秒里，
 *     屏幕上留的是她上一句算出来的那份。**空着起步**：她这一趟还没开口时，
 *     `App.贴判定` 会把列表给的那份「整趟」原话抹掉（`抹掉要什么行`）——
 *     那份里连她后面才要说的话都有。
 *
 * ⚠️ **失败是安静的，这是有意的。** 后端没起、超时、答得不合法、这一趟她一句
 * 买家话都没有 —— 一律 `null`，调用方什么都不改。演示当天模型出任何岔子，
 * 整屏仍然是完整的（这是本文件唯一的失败策略，没有第二个分支）。
 *
 * ⚠️ **但也正因为安静，光看那一行分不出跑没跑过** —— 演示线上的剧本值
 * 和模型值长得几乎一样。真窗口上留的又是上一版（也是模型算的）。
 * 「有没有真跑过」由右栏顶上那行标记说话（`App` 的 `需求兜底`）。
 */

import type { StateRow } from '../types'

/**
 * 响应体，**逐字照 `backend/app/api/schemas.py` 的 `需求分解响应`**。
 *
 * 和 `判定响应` 同一个理由：这个形状是右栏自己消费的，不进 `types/index.ts`
 * （那个文件归接口线独占，`backend/tests/test_schemas.py` 直接解析它）。字段名
 * 一个字都不许改 —— 两边漂移**不会让任何东西报错**，右栏那一行只是不变。
 *
 * **只有 `值`，没有「需求列表」那一份**：同一件事传两遍，两份一旦不同步，
 * 右栏两处会显示不一样的内容，而两处都「看着对」。分隔符也归后端。
 */
export interface 需求分解响应 {
  会话ID: string
  值: string
}

/**
 * 超时。
 *
 * **没有这一条的话，后端半死（进程在、不响应）会让那一行永远停在原话上** ——
 * 而这和「模型今天不灵」长得一模一样。超了就什么都不改，回落的那份还在。
 *
 * ⚠️ **2026-10-06 起它不再和 `判定.ts` 同一个数了**（那条从 12s 放到了 20s）。
 * 分开是**有意的**，不是漏改：这一条只发**一次**模型调用（实测 0.6～0.8 秒），
 * 12s 已经是十几倍余量；判定那条是**十次**、实测 13.4 秒。两个数绑在一起的话，
 * 判定那边一慢就要把这条也一起拽上去，而它多出来的每一秒都只是「后端半死时
 * 干等的时间」—— 那正是这条超时唯一要挡的东西。
 */
const 超时毫秒 = 12_000

/**
 * 取一次需求分解。**任何失败都返回 `null`，不抛。**
 *
 * 和 `取判定` 同一套：调用方（`App` 那个 effect）对四种失败的处理完全一样，
 * 抛的话每个调用点都要包一层 try，而漏掉的那一个会在演示当天变成一个没接住的
 * 拒绝。`值` 是空串也在调用方那一层挡住 —— 那是「没拆出来」的另一半。
 *
 * `看到几句买家话` 是**买家话的条数，不是消息条数**。两边对同一条会话的编号
 * 对不上（后端多一条开头的客服承诺、剧本多一条现场发的），而买家话的顺序两边
 * 一样。
 *
 * **参数是必给的**（2026-10-04 收窄，和 `取判定` 的 `轮次` 同一天）。接口上不给
 * 就是「整趟都看得见」，那条路留在后端（`api/需求分解.py`），**前端两条线都不用**
 * —— 它问的是「她一开口就算出全部」，正是这一改要去掉的那件事。
 */
export async function 取需求分解(
  会话ID: string,
  看到几句买家话: number,
): Promise<需求分解响应 | null> {
  try {
    const 答 = await fetch('/api/需求分解', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ 会话ID, 看到几句买家话 }),
      signal: AbortSignal.timeout(超时毫秒),
    })
    if (!答.ok) return null
    return (await 答.json()) as 需求分解响应
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿。故意不分类：调用方的处理完全一样。
    return null
  }
}

/**
 * 那一次请求的缓存键：`会话ID#看到几句`。
 *
 * **为什么键里要带句数。** 两条路现在都是「她说一句问一次」（真窗口 2026-10-04
 * 起），线一八格里问三次、三次数值不一样。只按会话存的话，往回拖到第 1 格右栏
 * 还挂着她说完赠品之后那个值 —— `判定表` 按轮次存，防的正是同一件事（那边写着
 * 拖回上一轮会撞上什么）。
 *
 * 句数用 `#` 隔开而不是拼成数字串：`S_DEMO_A1` 和 `S_DEMO_A#1` 不会撞。
 */
export function 需求分解键(会话ID: string, 看到几句买家话: number): string {
  return `${会话ID}#${看到几句买家话}`
}

/**
 * **真窗口用的那一版值：她说到第 N 句，模型还没答上来，屏幕上该留着哪一份。**
 *
 * 往回找，第一个有答案的句数就是它 —— 也就是「她上一句时算出来的那份」。
 * 一句都没答过时是 `undefined`，那一行空着（这是对的：她这一趟还没开口，
 * 或者开了口但模型还没答过任何一版）。
 *
 * # 为什么演示线不用它
 *
 * 演示线的回落是**剧本写的那个值**，而剧本是**跟着她的台词一格一格写死的** ——
 * 第 5 格那句「＋ 赠品补发」在她说完的同一格就上屏了。拿这个函数去套，反倒会
 * 把屏幕上已经添上的那一截**退回**到第 1 句那一版，她说了话那一行反而少一截
 * （`判定.ts` 的 `剧本说了算的行` 防的是同一件事）。所以演示线照旧**按格取准数**
 * （`需求分解键(会话ID, 看到几句)` 直查），只有真窗口走这儿。
 *
 * **为什么不干脆把「上一版」另存一个不带句数的键**：那样拖回第 1 格时，屏幕上
 * 会出现**第 3 句那一版** —— 键里带着句数就是为了防这个（上一段），再开一个不带
 * 句数的键，等于把刚堵上的口子从旁边挖开。往回扫一遍只是几个字典查找。
 */
export function 最近一版(
  表: Record<string, string>,
  会话ID: string,
  看到几句买家话: number,
): string | undefined {
  for (let 句数 = 看到几句买家话; 句数 >= 1; 句数 -= 1) {
    const 值 = 表[需求分解键(会话ID, 句数)]
    if (值) return 值
  }
  return undefined
}

/**
 * 「这次要什么」的行标签。
 *
 * **同一个字面值在四个地方出现**：后端 `api/需求分解.py` 的 `这次要什么`、
 * 这里、`判定.ts` 的 `剧本说了算的行`、`剧本.ts` 每一步的快照。改的话一起改 ——
 * 改漏这一处的后果是**什么都不发生**（找不到那一行就原样返回，见下）。
 */
const 行标签 = '这次要什么'

/**
 * 把模型拆出来的值贴到那一行上。
 *
 * **只换 `值`**，`备注`／`警示`／`时限` 原样留着 —— 那些不是模型给的，也不该
 * 跟着动（这一行本来就只有 `值`，写全是为了别人照着这个函数改别的行时不出错）。
 *
 * 两种情况原样返回，都不报错：
 *
 *   - **`值` 是空的** ＝ 没拆出来。**留原来那份**是这一整条路的兜底策略，
 *     在这儿挡住，`App` 那边就不用再判一次；
 *   - **行里没有「这次要什么」**（`行们` 是 `undefined`、或者剧本第 1 格那种
 *     只有三行的快照）。此时**不加一行**：行数与顺序归剧本（`判定.合顾客情况`），
 *     这里只改值。真窗口那 114 个窗口是后端装配的五整行，永远找得到。
 */
export function 合需求分解(
  行们: StateRow[] | undefined,
  值: string | undefined,
): StateRow[] | undefined {
  if (!行们 || !值?.trim()) return 行们
  return 行们.map((行) => (行.标签 === 行标签 ? { ...行, 值 } : 行))
}

/**
 * **真窗口专用**：把这一行的值抹掉，留一个空壳。
 *
 * 列表给的「这次要什么」是**整趟**买家话攒起来的（`装配.这次要什么`，
 * `已说完=True`）—— 真窗口一打开，她那几句还没演到的需求就摆在右栏上了。
 * 真窗口这一行改跟着回放走之后（见文件头），那份**不能再当底**，所以在这一层
 * 抹掉，改由 `合需求分解` 拿模型的值填 —— 她还没开口时就是空的。
 *
 * **只抹值，不删行**：行数与顺序归后端装配的五行（`判定.合顾客情况` 那一套），
 * 删一行会让下面的折叠条跟着挪位置。备注／警示／时限也原样留着。
 *
 * 抹成 `''` 而不是 `undefined`：`判定.合一行` 对「这次要什么」走的是
 * `剧本的.值 ?? 接口的.值`，`??` 只在 `null`／`undefined` 上让路 —— 抹成空串，
 * 判定接口给的那份「到本轮为止的原话」就也盖不上来了。**这是要的**：那一行现在
 * 只有模型一个产出者（选的是「保持上一版」，见 `最近一版`），中间不该再插一层
 * 原话进来闪一下。
 */
export function 抹掉要什么行(行们: StateRow[] | undefined): StateRow[] | undefined {
  return 行们?.map((行) => (行.标签 === 行标签 ? { ...行, 值: '' } : 行))
}
