/**
 * 演示剧本 —— 给一个会话加一条时间线，可以在界面上播放、调速、拖进度。
 *
 * **为什么要可拖拽。** 每步存的是「相对上一步的改动」而不是「这一刻的完整状态」，
 * 于是任意进度都能从基底重放出来：
 *
 *     第 N 步的会话 = 把前 N 步的改动用 fold 叠到基底上
 *
 * 这样拖动进度条不需要回退逻辑，也不会因为来回拖而把状态拖脏。代价是每步只写
 * 变化的部分 —— 内容会啰嗦一点，但换来的是「进度 = 纯函数(步数)」。
 *
 * # 一步不一定有消息
 *
 * **这是这份剧本和上一版的根本区别。** 上一版恰好一步一条消息，于是「步」和
 * 「条」看着可以互换（`条到步(n) === n`），播放器数条数也照样跑得动。新版里
 * 「系统翻出上一次的记录」「六源扫描」「逾期浮出」「审批回来」这些拍子**没有
 * 新消息** —— 屏幕上什么都没多，变的是右栏。一旦有这种步，步和条就不再是一
 * 回事，播放器必须**按步走**（见 `use播放器` 的「格」）。
 *
 * 最极端的一步是线一的第五步「这条得你来发」：**没有消息，也没有改动**，整格
 * 的内容就是「停在这儿等客服点发送」。它连右栏都不变，纯粹是给演示的人留的
 * 一口气 —— 这种步按条数根本数不出来，只有按步走才存在。
 *
 * # 剧本管什么、不管什么
 *
 * 只管叙事：消息、顾客情况、主卡、本轮处置。**排除的是三个按钮状态**
 * （`草稿` / `报备` / `转交`）—— 那些是演示时现场点的，让观众看见「一键报备」
 * 真的按下去才有意义。类型上用 `Omit` 把它们排除掉，写错了编译不过。
 *
 * `消息` 则不限角色：`造消息` 收 `SenderRole`，客服的话也能写进剧本。
 * 线二第二步就是这么写的（转交话术）。线一那句客服的话不在这儿 —— 它要等客服
 * 点一下才发得出去，归 `待发` 管。
 *
 * # 两条线
 *
 * 线一 `S00005` 顾客 A：含乙醇 ＋ 孕期 → 报备 → 正常收尾 → 入先例库。
 * 线二 `S00006` 顾客 B：**同一件事**，只是她说的是「我要投诉」→ 整轮转交。
 *
 * 两条线共用同一段历史（见下面的常量），这正是「同一件事，两种命运」的字面
 * 意思。改承诺日或时限时两条线一起动，抄成两份迟早会漂开。
 */

import type { ChatMessage, Evidence, Session, StateRow } from '../types'
import { 造消息 } from './msg'

/** 剧本里一步能改的字段。客服那三个按钮状态不在内，见文件头。 */
export type 可改动字段 = Omit<
  Partial<Session>,
  '消息' | '草稿' | '报备' | '转交' | '会话ID'
>

export interface 剧本事件 {
  /** 这一步在做什么。显示在播放器上，也是演示时讲解的提示词。 */
  标题: string
  /** 补充说明，播放器上以小字显示。留空则不显示。 */
  备注?: string
  /**
   * 这一步要**停下来等人点界面上的按钮**，值就是那个按钮的字。
   *
   * 演到这一步，播放器不再自动往下走，提示行改成「等你点［一键报备］」；
   * 演示的人真按了那个按钮，时间线才继续（见 `use播放器` 的 `继续`）。
   *
   * **为什么写进剧本而不是让人现场按暂停**：按暂停要记「该停了」这件事，而记
   * 这件事的代价是演示时得盯着播放器；写进剧本，节奏就是数据的一部分。这也正是
   * 这一份剧本存在的理由 —— 演到哪儿、停在哪、等你点哪个，全都在一个地方。
   *
   * **标了就必须真的有那个按钮**：提示行会把它念出来（「等你点［X］」），屏幕上
   * 没有 X 的话演示就断在这儿了。标之前先确认那一步主卡的形态对得上。
   */
  等点击?: string
  /** 这一步新到的消息，追加到会话末尾。**可以没有** —— 见文件头。 */
  消息?: ChatMessage[]
  /**
   * 这一步**备好、但等客服点了才发**的话。
   *
   * 和 `消息` 的区别只有时序：`消息` 演到这一步就出现；`待发` **不自己出现** ——
   * 要等客服真按了界面上那个按钮（`等点击` 指的那个），它才被搬进现场消息里发
   * 出去（见 `App` 的发送处理）。
   *
   * **为什么要压着不发**：这两步演的正是「需要客服点一下才发得出去」这件事。
   * 剧本先把话替客服说了，那一拍就白演了 —— 屏幕上多一句话，观众却看不见有人
   * 按过任何东西。压着它，「点了才发」才是看得见的。
   *
   * `演到` **不读这个字段**，这是它和 `消息` 唯一要紧的区别：写错了地方，
   * 消息就会在演到这一步时自己冒出来。
   */
  待发?: ChatMessage[]
  /** 对会话其余字段的改动。数组字段是整体替换，不是追加。 */
  改动?: 可改动字段
  /**
   * 这一步往先例库里存了一条 —— 演到这儿，顶栏那个计数 +1。
   *
   * **不写成「已入库的会话 ID 列表」之类的累计状态。** 先例库的条数是**从播放
   * 进度派生**的（见 `已入库条数`）：拖回上一步它自己就退回去，不需要谁去记账。
   * 和 `use播放器` 里 `在放` 是派生的同一个理由 —— 少一份会不同步的状态。
   *
   * 规格 §八 的规矩：**只有正常收尾且没越界才回写先例库**。所以线二（转交出去
   * 的那条）整份剧本里没有这个标记，这是对的，不是漏了。
   */
  入库?: boolean
}

export interface 剧本 {
  会话ID: string
  事件: 剧本事件[]
}

/**
 * 这份剧本里第几格要停下来等人点 → 要点的那个按钮的字。
 *
 * 放在剧本这一侧而不是 `App` 里：**「第几步要人动手」是剧本的编排**，和「这一步
 * 说什么话」是一类东西。App 只是把它递给播放器。
 *
 * 格子号是 **1 起**的，和 `已播格数` 同一个口径 —— 步 5 停了，`已播格数` 就是 5，
 * 两者要能直接比。下标（0 起）在这儿加 1，出不了这个函数。
 */
export function 停格(剧本: 剧本 | undefined): Map<number, string> {
  return new Map(
    剧本?.事件.flatMap((e, i) => (e.等点击 ? [[i + 1, e.等点击] as const] : [])) ?? [],
  )
}

/**
 * 演示过程中**客服现场发出去的一条消息**，记着它是停在第几步时发的。
 *
 * 为什么非得记步号：`演到` 是按剧本的顺序拼消息的。现场消息要是一律排在最后，
 * 客服停在第 5 步发的那句，走到第 8 步就会跑到「好的，谢谢啦」后面去 —— 时间线
 * 当场就乱了。记着步号，它就能插回原位；而拖动进度时它跟着自己的步进退，
 * `演到` 仍然是「进度 = 纯函数(步数)」。
 */
export interface 现场消息 {
  步: number
  消息: ChatMessage
}

/**
 * 把剧本演到第 N 步。
 *
 * - `已演步数` 是**已应用的步数**，不是下标：0 表示一步没演，等于基底。
 * - `现场` 是客服在演示过程中自己发出去的消息（见 `现场消息`），每条带着自己
 *   的步号，插在那一步的消息后面。步号还没演到的**不出现** —— 往回拖它就自己
 *   消失了，不需要谁去回退。
 * - `活.消息` 是上一版留下的一条老路（现场消息一律排在最后），留着是为了不改变
 *   没有 `现场` 时的行为。走剧本的会话不该再往 `活.消息` 里写东西，否则又绕回
 *   那个「插在买家消息中间」的老问题。
 */
export function 演到(
  活: Session,
  剧本: 剧本 | null | undefined,
  已演步数: number,
  现场: 现场消息[] = [],
): Session {
  let 会话: Session = { ...活, 消息: [] }
  const 事件 = 剧本?.事件 ?? []
  const 演到第 = Math.max(0, Math.min(已演步数, 事件.length))

  for (let i = 0; i < 演到第; i++) {
    const e = 事件[i]
    const 这一步发的 = 现场.filter((现) => 现.步 === i + 1).map((现) => 现.消息)
    会话 = {
      ...会话,
      ...e.改动,
      消息: [...会话.消息, ...(e.消息 ?? []), ...这一步发的],
    }
  }

  return { ...会话, 消息: [...会话.消息, ...活.消息] }
}

