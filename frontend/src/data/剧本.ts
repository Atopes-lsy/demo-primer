/**
 * 演示剧本 —— 给一个会话加一条时间线，可以在界面上播放、调速、拖进度。
 *
 * **为什么要可拖拽。** 每步存的是「相对上一步的改动」而不是「这一刻的完整状态」，
 * 于是任意进度都能从基底重放出来：
 *
 *     第 N 步的会话 = 把前 N 步的改动用 fold 叠到基底上
 *
 * 这样拖动进度条不需要回退逻辑，也不会因为来回拖而把状态拖脏。代价是每步只写
 * 变化的部分 —— 内容会啰嗦一点，但换来的是「进度 = 纯函数(步数)」。
 *
 * **剧本管什么、不管什么。** 只管叙事：消息、顾客情况、主卡、本轮处置。客服自己
 * 的动作（草稿、报备、转交）不在剧本里 —— 那些是演示时现场点的，让观众看见
 * 「一键报备」真的按下去才有意义。类型上用 `Omit` 把它们排除掉，写错了编译不过。
 */

import type { ChatMessage, Session } from '../types'
import { 造消息 } from './msg'

/** 剧本里一步能改的字段。客服状态那三个不在内，见文件头。 */
export type 可改动字段 = Omit<
  Partial<Session>,
  '消息' | '草稿' | '报备' | '转交' | '会话ID'
>

export interface 剧本事件 {
  /** 这一步在做什么。显示在播放器上，也是演示时讲解的提示词。 */
  标题: string
  /** 补充说明，播放器上以小字显示。留空则不显示。 */
  备注?: string
  /**
   * 这一步出现后停留多久，再演下一步。播放时除以倍速。
   *
   * 是**停留时长**不是「距上一步」：第一步的间隔决定它和第二步之间隔多久，
   * 最后一步的间隔用不上（演完就停在那儿等人点按钮）。
   */
  间隔: number
  /** 这一步新到的消息，追加到会话末尾。 */
  消息?: ChatMessage[]
  /** 对会话其余字段的改动。数组字段是整体替换，不是追加。 */
  改动?: 可改动字段
}

export interface 剧本 {
  会话ID: string
  事件: 剧本事件[]
}

/**
 * 把剧本演到第 N 步。
 *
 * - `已演步数` 是**已应用的步数**，不是下标：0 表示一步没演，等于基底。
 * - `活.消息` 里装的是客服在演示过程中自己发出的消息，它们一定发生在已演到的
 *   进度之后，所以排在剧本消息的后面。不这么处理的话，客服一发消息就会插到
 *   几条买家消息中间。
 */
export function 演到(活: Session, 剧本: 剧本 | null | undefined, 已演步数: number): Session {
  let 会话: Session = { ...活, 消息: [] }

  for (const e of 剧本?.事件.slice(0, 已演步数) ?? []) {
    会话 = {
      ...会话,
      ...e.改动,
      消息: e.消息 ? [...会话.消息, ...e.消息] : 会话.消息,
    }
  }

  return { ...会话, 消息: [...会话.消息, ...活.消息] }
}

