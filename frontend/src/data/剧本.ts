// ── 先例库计数 ──────────────────────────────────────────────
//
// 顶栏那个「先例库 56」。演示走到「入先例库」那一步它跳到 57 —— 那一跳就是
// 「这一次服务，留了下来」。

/**
 * 演示开始时的条数。真实系统里它由后端给，这里是个示例值。
 *
 * **基数和增量分开两处是有意的**：这一份是常量，增量从播放进度派生，
 * 由 `App` 把各条剧本的数加起来（见那边的 `先例库总数`）—— 计数是全店的，
 * 不是某一条会话的，加总这件事得在看得见全部会话的地方做。
 */
export const 先例库基数 = 56

/**
 * 这份剧本演到第 N 步时，往先例库里存了几条。
 *
 * **从进度派生，不另存一个计数。** 存的话就得有人负责「往回拖的时候减回去」，
 * 而那份逻辑一定会漏 —— 和 `use播放器` 里把 `在放` 派生的理由一样。
 *
 * 没有剧本的会话返回 0：普通会话不产先例。
 */
export function 已入库条数(本: 剧本 | undefined, 已播步数: number): number {
  if (!本) return 0
  return 本.事件.slice(0, 已播步数).filter((e) => e.入库).length
}
