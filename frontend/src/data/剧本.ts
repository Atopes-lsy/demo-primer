/**
 * 演示剧本 —— 给一个会话加一条时间线，可以在界面上播放、调速、拖进度。
 *
 * **为什么要可拖拽。** 每步存的是「相对上一步的改动」而不是「这一刻的完整状态」，
 * 于是任意进度都能从基底重放出来：
 *
 *     第 N 步的会话 = 把前 N 步的改动用 fold 叠到基底上
 *
 * 这样拖动进度条不需要回退逻辑，也不会因为来回拖而把状态拖脏。代价是每步只写
 * 变化的部分 —— 内容会啰嗦一点，但换来的是「进度 = 纯函数(步数)」。
 *
 * # 一步不一定有消息
 *
 * **这是这份剧本和上一版的根本区别。** 上一版恰好一步一条消息，于是「步」和
 * 「条」看着可以互换（`条到步(n) === n`），播放器数条数也照样跑得动。新版里
 * 「系统翻出上一次的记录」「六源扫描」「逾期浮出」「审批回来」这些拍子**没有
 * 新消息** —— 屏幕上什么都没多，变的是右栏。一旦有这种步，步和条就不再是一
 * 回事，播放器必须**按步走**（见 `use播放器` 的「格」）。
 *
 * 最极端的一步是线一的第四步「这条得你来发」：**没有消息，也没有改动**，连右栏
 * 都不变，纯粹是给旁白留的一口气。这种步按条数根本数不出来，只有按步走才存在。
 *
 * # 剧本管什么、不管什么
 *
 * 只管叙事：消息、顾客情况、主卡、本轮处置。**排除的是三个按钮状态**
 * （`草稿` / `报备` / `转交`）—— 那些是演示时现场点的，让观众看见「一键报备」
 * 真的按下去才有意义。类型上用 `Omit` 把它们排除掉，写错了编译不过。
 *
 * `消息` 则不限角色：`造消息` 收 `SenderRole`，客服的话也能写进剧本。
 * 线二第二步就是这么写的（转交话术）。线一那句客服的话不在这儿 —— 它要等客服
 * 点一下才发得出去，归 `待发` 管。
 *
 * # 两条线
 *
 * 线一 `S_DEMO_A` 顾客 A（小鹿）：含乙醇 ＋ 孕期 → 报备 → 正常收尾 → 入先例库。
 * 线二 `S_DEMO_B` 顾客 B（阿沅）：**同一件事**，只是她说的是「我要投诉」→ 整轮转交。
 *
 * 两条线共用同一段历史（见下面的常量），这正是「同一件事，两种命运」的字面
 * 意思。改承诺日或时限时两条线一起动，抄成两份迟早会漂开。
 */

import type { ChatMessage, Evidence, Session, StateRow } from '../types'
import { 造消息 } from './msg'

/** 剧本里一步能改的字段。客服那三个按钮状态不在内，见文件头。 */
export type 可改动字段 = Omit<
  Partial<Session>,
  '消息' | '草稿' | '报备' | '转交' | '会话ID'
>

/**
 * 一条「我方说的话」从接口的哪一块取文字。**住在 `剧本.ts` 而不是 `判定.ts`：**
 * 它是 `剧本事件.话术来源` 的值，而 `判定.ts` 反过来要 import `剧本` 那个类型 ——
 * 声明在那边就成了循环引用。
 *
 * 字段的含义写在 `剧本事件.话术来源` 上，两处不要各说各话。
 */
export interface 接口话术 {
  /**
   * 取第几轮的结果。
   *
   * ⚠️ **和 `剧本事件.判定轮次` 不是一回事**，两者可以差一拍 —— 那条写这条的
   * 文档串去，别在这儿再讲一遍。
   */
  轮次: number
  /** 取主卡哪一块。 */
  取: '已代发' | '主卡话术'
}

export interface 剧本事件 {
  /** 这一步在做什么。显示在播放器上，也是演示时讲解的提示词。 */
  标题: string
  /** 补充说明，播放器上以小字显示。留空则不显示。 */
  备注?: string
  /**
   * 这一步要**停下来等人点界面上的按钮**，值就是那个按钮的字。
   *
   * 演到这一步，播放器不再自动往下走，提示行改成「等你点［一键报备］」；
   * 演示的人真按了那个按钮，时间线才继续（见 `use播放器` 的 `继续`）。
   *
   * **为什么写进剧本而不是让人现场按暂停**：按暂停要记「该停了」这件事，而记
   * 这件事的代价是演示时得盯着播放器；写进剧本，节奏就是数据的一部分。这也正是
   * 这一份剧本存在的理由 —— 演到哪儿、停在哪、等你点哪个，全都在一个地方。
   *
   * **标了就必须真的有那个按钮**：提示行会把它念出来（「等你点［X］」），屏幕上
   * 没有 X 的话演示就断在这儿了。标之前先确认那一步主卡的形态对得上。
   *
   * **主卡第一次上屏的那一格必须标（2026-10-04 补的规矩）。** 卡露脸之后、客服
   * 点它之前，屏幕上不许再冒出任何以我方名义的话 —— 不标那一下，时间线就接着
   * 走，下一格那条消息会当着演示的人的面自己发出去，而他从头到尾没点过东西。
   * 三张主卡（需要话术／需要授权／有风险）各有一个停格，且都落在卡出现的那一格。
   */
  等点击?: string
  /** 这一步新到的消息，追加到会话末尾。**可以没有** —— 见文件头。 */
  消息?: ChatMessage[]
  /**
   * 这一步**备好、但等客服点了才发**的话。
   *
   * 和 `消息` 的区别只有时序：`消息` 演到这一步就出现；`待发` **不自己出现** ——
   * 要等客服真按了界面上那个按钮（`等点击` 指的那个），它才被搬进现场消息里发
   * 出去（见 `App` 的发送处理）。
   *
   * **为什么要压着不发**：这两步演的正是「需要客服点一下才发得出去」这件事。
   * 剧本先把话替客服说了，那一拍就白演了 —— 屏幕上多一句话，观众却看不见有人
   * 按过任何东西。压着它，「点了才发」才是看得见的。
   *
   * `演到` **不读这个字段**，这是它和 `消息` 唯一要紧的区别：写错了地方，
   * 消息就会在演到这一步时自己冒出来。
   */
  待发?: ChatMessage[]
  /**
   * 这一格起，右栏的内容改由 `POST /api/判定` 的第 N 轮提供。
   *
   * **为什么粒度是「轮次」而不是「字段」。** 接口一轮一答 —— 一次给整轮的
   * 顾客情况 ＋ 本轮处置 ＋ 主卡，没有「只给这一行的值」这种问法。所以
   * 触发点只能按轮标，一轮标一次。
   *
   * **标在「这一轮的结果第一次上屏」那一格，不是标在收尾格。** 第 8 步
   * 「顾客道谢」的顾客情况写的是 `已收尾 · 补发已登记，待发出` —— 那是**事情
   * 办完之后**的状态，接口答不出来（它只知道这一轮顾客说了什么）。给它标上，
   * 问回来的就是一句收尾语，等于把最后一拍演砸。
   * （2026-10-04 补：原先那句「「这次要什么」会从收尾语退回顾客原话」现在
   * 不成立了 —— 这一行已经是 `判定.剧本说了算的行`，接口盖不动它。规矩照旧，
   * 理由收窄成上面那半句：标在收尾格只是白问一轮。）
   *
   * **这一格露哪几块仍归剧本。** 接口给的是整轮，剧本是一格一格露的：
   * 第 1 步只露三行、第 2 步五行、第 3 步才露建议。合并时**行数与顺序取剧本、
   * 内容取接口**（见 `判定.合顾客情况`）—— 整份盖上去的话，这套分步露出
   * 连同「查历史中…」那个假中间态会一起消失，而它们是片子的一部分。
   */
  判定轮次?: number
  /**
   * 这一步里**以我方名义说出去的话**，文字改由接口给。
   *
   * 键是消息序号（`造消息` 的第 2 个参数），值是取接口哪一块：
   *
   *   `已代发`   → `主卡.已代发` 里的一条（`内容` 换文字、`署名` 换署名行）
   *   `主卡话术` → `主卡.话术`
   *
   * **不在表里的消息一个字都不动**，接口没答上来时也一个字都不动
   * （见 `判定.合消息`）。所以这张表只声明「哪几条归接口管」，
   * 「这一步露不露这块」仍旧归剧本 —— 和 `判定轮次` 同一套分工。
   *
   * ⚠️ **`轮次` 是必填的，且和上面的 `判定轮次` 不是一回事。** 那是「右栏
   * 什么时候更新」，这是「这句话是哪一轮判出来的」，两者**可以差一拍**。
   * 线一是现成的例子：第 5 格那句安抚话术属于第 2 轮（它回答的正是第 2 轮
   * 顾客那句「赠品还没发」），而 `判定轮次: 2` 标在第 6 格上。照 `判定轮次`
   * 推的话，这句话会配到第 1 轮的 `已代发` 上，屏幕上换成的就是第 3 格
   * 那句讲乙醇的。
   *
   * `待发` 里的消息也认这张表 —— 序号是会话级的，同一个号在两处指的是同一条。
   */
  话术来源?: Record<number, 接口话术>
  /** 对会话其余字段的改动。数组字段是整体替换，不是追加。 */
  改动?: 可改动字段
  /**
   * 这一步往先例库里存了一条 —— 演到这儿，顶栏那个计数 +1。
   *
   * **不写成「已入库的会话 ID 列表」之类的累计状态。** 先例库的条数是**从播放
   * 进度派生**的（见 `已入库条数`）：拖回上一步它自己就退回去，不需要谁去记账。
   * 和 `use播放器` 里 `在放` 是派生的同一个理由 —— 少一份会不同步的状态。
   *
   * 规格 §八 的规矩：**只有正常收尾且没越界才回写先例库**。所以线二（转交出去
   * 的那条）整份剧本里没有这个标记，这是对的，不是漏了。
   */
  入库?: boolean
}

export interface 剧本 {
  会话ID: string
  事件: 剧本事件[]
}

/**
 * 这份剧本里第几格要停下来等人点 → 要点的那个按钮的字。
 *
 * 放在剧本这一侧而不是 `App` 里：**「第几步要人动手」是剧本的编排**，和「这一步
 * 说什么话」是一类东西。App 只是把它递给播放器。
 *
 * 格子号是 **1 起**的，和 `已播格数` 同一个口径 —— 步 5 停了，`已播格数` 就是 5，
 * 两者要能直接比。下标（0 起）在这儿加 1，出不了这个函数。
 */
export function 停格(剧本: 剧本 | undefined): Map<number, string> {
  return new Map(
    剧本?.事件.flatMap((e, i) => (e.等点击 ? [[i + 1, e.等点击] as const] : [])) ?? [],
  )
}

/**
 * 演到第 N 格时，右栏该问接口要第几轮。`undefined` = 整格归剧本。
 *
 * **往回扫，不是只看当前格。** 第 4、5、7、8 步没标 `判定轮次`（那几步是过场、
 * 顾客说话、审批回来、收尾），但它们的右栏显示的仍是上一轮的结果。只看当前格的话，
 * 走过第 3 步右栏就退回剧本那份 —— 「接上接口」在半路断掉，而画面上只是
 * 某几行的值悄悄变回旧的，不会报任何错。
 */
export function 当前判定轮次(剧本: 剧本 | undefined, 已播格数: number): number | undefined {
  const 事件 = 剧本?.事件 ?? []
  for (let i = Math.min(已播格数, 事件.length) - 1; i >= 0; i--) {
    const 轮 = 事件[i].判定轮次
    if (轮 !== undefined) return 轮
  }
  return undefined
}

/**
 * 演示过程中**客服现场发出去的一条消息**，记着它是停在第几步时发的。
 *
 * 为什么非得记步号：`演到` 是按剧本的顺序拼消息的。现场消息要是一律排在最后，
 * 客服停在第 3 步发的那句，走到第 8 步就会跑到「好的，谢谢啦」后面去 —— 时间线
 * 当场就乱了。记着步号，它就能插回原位；而拖动进度时它跟着自己的步进退，
 * `演到` 仍然是「进度 = 纯函数(步数)」。
 */
export interface 现场消息 {
  步: number
  消息: ChatMessage
}

/**
 * 把剧本演到第 N 步。
 *
 * - `已演步数` 是**已应用的步数**，不是下标：0 表示一步没演，等于基底。
 * - `现场` 是客服在演示过程中自己发出去的消息（见 `现场消息`），每条带着自己
 *   的步号，插在那一步的消息后面。步号还没演到的**不出现** —— 往回拖它就自己
 *   消失了，不需要谁去回退。
 * - `活.消息` 是上一版留下的一条老路（现场消息一律排在最后），留着是为了不改变
 *   没有 `现场` 时的行为。走剧本的会话不该再往 `活.消息` 里写东西，否则又绕回
 *   那个「插在买家消息中间」的老问题。
 */
export function 演到(
  活: Session,
  剧本: 剧本 | null | undefined,
  已演步数: number,
  现场: 现场消息[] = [],
): Session {
  let 会话: Session = { ...活, 消息: [] }
  const 事件 = 剧本?.事件 ?? []
  const 演到第 = Math.max(0, Math.min(已演步数, 事件.length))

  for (let i = 0; i < 演到第; i++) {
    const e = 事件[i]
    const 这一步发的 = 现场.filter((现) => 现.步 === i + 1).map((现) => 现.消息)
    会话 = {
      ...会话,
      ...e.改动,
      消息: [...会话.消息, ...(e.消息 ?? []), ...这一步发的],
    }
  }

  return { ...会话, 消息: [...会话.消息, ...活.消息] }
}

/**
 * 给一条**现场消息**挑一个 `消息序号` —— 最小的、还没被占掉的正整数。
 *
 * # 为什么不能拿「现在几条了」+1
 *
 * 原先 `App.handleSend` 用的是 `active.消息.length + 1`。它假设**屏幕上已经有的
 * 条数**就是序号里已经用掉的那些 —— 可剧本的序号是 `造消息` 一步一条**写死**的，
 * 和「演到第几格」不是一回事：线一的号是 `1,2,4,5,6,7`，**第 3 号是留给谁的、
 * 第几步才出现**，都只有剧本自己知道。第 2 格屏幕上只有买家那一句，那时候按
 * `length + 1` 发一句客服话，给的是 **2** —— 那正是第 3 格那条 AI 直发的号，
 * 它还没上屏，号却已经被占了。
 *
 * 后果不在这一层，在 `判定.合消息`：它拿序号当钥匙（`话术来源表` 按号查「这条
 * 归接口管」），于是**两条都叫 2 的消息被一起换了文字和署名**。屏幕上就是
 * 「亲，这款不含乙醇哦～」以客服和 AI 两个身份各发一遍，而没有任何一处报错。
 *
 * # 为什么是「最小空号」而不是「最大号 + 1」
 *
 * 序号是给人读的编排号（线一从 1 走到 7，剧本还专门留了 3 号那一格），
 * 取最小空号填进去，线一的号才是**连续**的：1 买家、2 AI 直发、**3 客服在这
 * 一格发的**、4 买家……最大号 + 1 会给出 8，屏幕上第一句客服话挂着「8 号」，
 * 排在 2 号前面 —— 加进来一条消息，号却跳了一大截。
 *
 * # 两处都要算
 *
 * - **剧本**：每步的 `消息` 和 `待发`。`待发` 也算 —— 它和 `消息` 共用同一张
 *   `话术来源` 表（第 7 格那句答复的号是 6），漏掉它就会撞上第 7 格。
 * - **已经发过的现场消息**：客服在同一个会话里发第二条时要避开第一条。
 *   传的是 `现场消息表[会话ID]` 那一整串，**不是屏幕上看得见的那些** ——
 *   现场消息要等自己的步号演到才出现，拿可见的那几条算，拖回去再发一句就会
 *   重新挑回同一个号。
 */
export function 下一个消息序号(剧本: 剧本 | null | undefined, 已发的现场: readonly 现场消息[] = []): number {
  const 占的 = new Set<number>()
  for (const e of 剧本?.事件 ?? []) {
    for (const m of [...(e.消息 ?? []), ...(e.待发 ?? [])]) 占的.add(m.消息序号)
  }
  for (const 现 of 已发的现场) 占的.add(现.消息.消息序号)

  let 号 = 1
  while (占的.has(号)) 号++
  return 号
}

