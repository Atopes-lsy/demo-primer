/** 会话 ID → 剧本。没有条目就是普通会话，界面上不显示播放器。 */
export const 剧本表: Record<string, 剧本> = {
  [演示剧本.会话ID]: 演示剧本,
}

/**
 * 剧本按 1 倍速播完要多久（毫秒）。播放器上标个时长。
 *
 * 末步的间隔不计 —— 演完最后一步播放器就停了，不会再去等那一下。
 */
export function 总时长(剧本: 剧本): number {
  return 剧本.事件.slice(0, -1).reduce((和, e) => 和 + e.间隔, 0)
}

// ── 条 ↔ 步 ────────────────────────────────────────────────
//
// 播放器数的是**消息条数**（「第 N / 共 M 条」），剧本演的是**步**。两者要能互相
// 换算，因为普通会话也挂了播放器：那种会话没有剧本，它的时间线就是「一条消息
// 一步」，换算退化成恒等式。
//
// 为什么不干脆让播放器也数步：普通会话没有步。给每个普通会话现造一份剧本倒是
// 也能凑出「步」，但那份剧本的消息和 `活.消息` 是同一批 —— `演到` 会把
// `活.消息` 再追加一遍，屏幕上每条消息出现两次。所以普通会话走截断，不走剧本。

/** 剧本演到第 `步` 步时，屏幕上应当有几条消息。 */
export function 步到条(剧本: 剧本, 步: number): number {
  return 剧本.事件.slice(0, 步).reduce((条, e) => 条 + (e.消息?.length ?? 0), 0)
}

/**
 * 屏幕上要出现 `条` 条消息，剧本该演到第几步。
 *
 * 用「够到就停」而不是「正好等于」：一步里带几条消息是剧本自己定的，条形长度
 * 落不到步的边界上时，取**已经包含了这一条**的那一步 —— 少演一步比多演一步糟，
 * 少演会让右栏停在上一轮的状态上，对不上屏幕。
 */
export function 条到步(剧本: 剧本, 条: number): number {
  if (条 <= 0) return 0
  let 累计 = 0
  for (let i = 0; i < 剧本.事件.length; i++) {
    累计 += 剧本.事件[i].消息?.length ?? 0
    if (累计 >= 条) return i + 1
  }
  return 剧本.事件.length
}
