/**
 * 演示开始时的条数。真实系统里它由后端给，这里是个示例值。
 *
 * **基数和增量分开两处是有意的**：这一份是常量，增量从播放进度派生，
 * 由 `App` 把各条剧本的数加起来（见那边的 `先例库总数`）—— 计数是全店的，
 * 不是某一条会话的，加总这件事得在看得见全部会话的地方做。
 */
