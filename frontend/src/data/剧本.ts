/**
 * 「答应过什么」这一行。
 *
 * 函数而不是常量：剧本每步存的是**那一刻的快照**，`改动` 里的数组是整体替换。
 * 共用一个对象引用的话，后一步的改动会顺着引用改到前面几步上去 —— 拖动进度
 * 就不再是纯函数了。每次调用给一份新的。
 *
 * 不带 `警示`：逾期是**演到线一步 6** 才浮出来的（那一拍专门演 H3），
 * 出现在第 2 步的话，第 2 步的右栏就已经在报警了。
 */
function 答应过什么(): StateRow {
  return { 标签: '答应过什么', 值: `${承诺日} 承诺「${承诺话术}」`, 备注: `时限：${时限}` }
}

