/**
 * 交接包 —— 报备／转交时自动带全的那张单，组长或专员要的东西全在上面。
 *
 * 和 `查禁语`／`查事实` 一样，**派生逻辑待在 `data/`，组件只管画**。放组件文件里
 * 会让那个文件同时导出组件和一个普通函数，React 的热更新就认不出它了
 * （`react/only-export-components`）—— 不是风格问题，是工具看不见它。
 *
 * # 两份来源：接口是正路，算出来那份是兜底
 *
 * 这张单子 2026-10-03 之前是纯前端算的；接上 `api/动作.py` 之后接口会连七行带
 * 单号一起回（两边同名同形，`schemas.交接包` ↔ 这个文件）。**但没有把算的那份
 * 删掉** —— 判定的兜底是 `剧本.ts` 那份已知正确的数据，交接包没有对应的那一份，
 * 删了它后端一挂，［一键报备］点下去右栏**什么都不出现**（不是出错，是安静地
 * 少一块），而那是演示当天最贵的一种失败。
 *
 * 代价是两份实现可能漂开 —— 和判定那条路是同一个形状、同一个代价。**所以兜底
 * 态必须看得见**：右栏顶上常驻一行标记，写「接口 · 已连」还是「剧本兜底 · 动作」。
 */

import type { 报备态 } from '../components/plugin/AdviceCard'
import type { Disposition, Session } from '../types'
import { 演示今天 } from './剧本'

/** 交接包里的一行。`来源` 只给排障看，不上屏。 */
export interface 交接行 {
  标签: string
  值: string
  /** 这一行是打哪几个字段拼出来的。改字段名时照着它找。 */
  来源: string
}

/**
 * 交接包走到哪一步了。
 *
 * - `等待审批`：报备交上去了，组长还没批；
 * - `已完成`：批准了、话也发出去了，这一单算走完；
 * - `已转出`：不是审批流，是**交出去了** —— 转交没有「完成」这回事，
 *   对话归了别人，客服这一侧的活到此为止。
 */
export type 交接包态 = '等待审批' | '已完成' | '已转出'

export interface 交接包 {
  状态: 交接包态
  行: 交接行[]
  单号: string
}

/**
 * 打动作接口的结果。
 *
 * **「后端没答上来」和「后端说不行」必须分开。** 这是这一块最容易合错的一处：
 * 照 `取判定` 那个 `交接包 | null` 抄的话，`409 第 2 轮没有要报备的主张` 会跟
 * 「后端没起」落进同一个分支 —— 于是右栏顶上挂起「剧本兜底」，**同时摆出一张
 * 后端刚刚拒掉的单子**。两个信号互相打架，而那个组合在屏幕上看着完全正常。
 *
 * 三态各对应一句不同的界面行为（见 `App` 的 `走动作`）：
 *
 *   - `成`      用接口那张单子；
 *   - `未连`    本地造一张，右栏顶上写「剧本兜底 · 动作」；
 *   - `后端说不` **不造单子**，把后端那句话原样摆出来。
 */
export type 动作结果<T> =
  | { 态: '成'; 值: T }
  | { 态: '未连' }
  | { 态: '后端说不'; 说明: string }

/**
 * 接口没答上来时，本地给这张单子拼一个号。
 *
 * **前缀一律 `JJ`，报备和转交同一种号**（`api/台账.py:108`，2026-10-03 拍的口径）。
 * 前端原来拼的是 `BH`，而 31 §3.6 底部给 A 的那个号也是 `JJ…` —— 跟着后端走，
 * 别再把 `BH` 写回来。
 *
 * **日期取 `演示今天`，不取 `new Date()`。** 演示整条时间线落在 9/29，录制却在
 * 别的日子 —— 取真实时钟的话，屏幕上会并排出现「9/29 已逾期 2 天」和一张
 * `JJ20261003…` 的单子，那是台下最容易看见的一种对不上。（这一段原来是
 * `App.生成单号` 的注释，函数搬进这儿，理由跟着搬。）
 *
 * **序号不能从会话 ID 里抠数字**：早先的 ID 是 `S00005`，尾三位正好是序号；
 * 换成 `S_DEMO_A` 之后 `replace(/\D/g,'')` 得到空串，两位顾客会拿到同一个
 * `000`。这里按 ID 求个稳定的三位数 —— 它只负责让单号看着像单号，**不承担
 * 唯一性**，也不承担「和接口那个号对不对得上」：兜底和接口本来就该分得出来，
 * 而分这件事归右栏顶上那行标记（见 `App` 的 `兜底`），不归号本身。
 */
export function 兜底单号(会话ID: string): string {
  const 序号 = String([...会话ID].reduce((和, c) => 和 + c.charCodeAt(0), 0) % 1000).padStart(
    3,
    '0',
  )
  return `JJ${演示今天.replace(/-/g, '')}${序号}`
}

/** 报备／转交那几条主张的原话。这是「这单是为什么立起来的」最直接的来源。 */
function 立单主张(处置: Disposition[]): string[] {
  return 处置.filter((d) => d.输出 === '报备' || d.输出 === '转交').map((d) => d.主张)
}

/**
 * 从这一条会话算出交接包。没有报备也没有转交 → `null`，这一块不出现。
 *
 * **为什么是算出来的，不是存的一份。** 交接包的七行全是别的字段的投影：
 * 商品取自订单、答应过什么取自顾客情况、单号取自报备／转交。再存一份的话，
 * 订单状态一改，右栏的「这单」变了、交接包里那行还是旧的 —— 而这张单子正是
 * 要拿给组长看的，错一行比不显示更糟。和 `报备态` 一个道理：能推出来的状态
 * 不另存。
 *
 * **类型定义在这儿，不在 `types/`。** `types/index.ts` 归接口线独占
 * （`backend/tests/test_schemas.py` 直接解析它），交接包又不进后端契约 —— 它是
 * 右栏给自己看的一张单。
 *
 * **接上接口之后它没有退休，是转成了兜底**（模块文档串那段）。调用点一律写成
 * `接口那份 ?? 建交接包(...)`，所以单号是接口的还是这儿拼的，进函数之前就定了：
 * 这里读 `session.报备?.工单号`，而 `App` 在**两条路上都会**把它写上
 * （接口那条写接口的号，兜底那条写 `兜底单号`）—— 不写的话兜底当场失效。
 */
export function 建交接包(session: Session, 报备态: 报备态): 交接包 | null {
  const 单号 = session.转交?.工单号 ?? session.报备?.工单号
  if (!单号) return null

  const 转交 = Boolean(session.转交)
  const 行 = session.顾客情况 ?? []
  const 取 = (标签: string) => 行.find((r) => r.标签 === 标签)

  const 答应 = 取('答应过什么')
  const 办过 = 取('办过什么')
  const 订单 = session.订单
  const 工单 = session.工单?.ticket
  const 主张 = 立单主张(session.本轮处置 ?? [])

  // 工单类型只有补发换货那张表有。别的类型落进来时这一格退成大类名，不硬凑。
  const 补发类型 = 工单 && '工单类型' in 工单 ? 工单.工单类型 : ''

  // 升级分类：报备和转交走的不是一套。
  //   报备 → 这条补发是什么事 ＋ 有没有逾期，组长扫一眼就知道急不急
  //          （「漏发赠品（已逾期 2 天）」）；
  //   转交 → 该归哪个专家队列，取自规则层判出来的 `交接分类`（见 `Disposition`）。
  // 交接分类可能是空的 —— 规则层认不出就留空、不猜（见那边的注释），
  // 空的时候这一行只留分类名，不拿一个默认值顶上。
  const 转交分类 = [
    ...new Set((session.本轮处置 ?? []).filter((d) => d.输出 === '转交').map((d) => d.交接分类)),
  ].filter(Boolean)
  const 报备分类 = [补发类型, 答应?.警示].filter(Boolean).join('（') + (答应?.警示 ? '）' : '')

  const 行表: 交接行[] = [
    {
      标签: '工单类型',
      值:
        转交
          ? '转交工单'
          : ['补发工单', 补发类型].filter(Boolean).join('（') + (补发类型 ? '）' : ''),
      来源: 'session.工单.ticket.工单类型',
    },
    {
      标签: '商品',
      值: 订单 ? `${订单.商品货号} ${订单.商品名称}` : '—',
      来源: 'session.订单.商品货号 ／ 商品名称',
    },
    {
      标签: '诉求',
      值: 主张.length ? 主张.join(' · ') : '—',
      来源: 'session.本轮处置（输出为报备／转交那几条的主张）',
    },
    {
      标签: '答应过什么',
      值: [答应?.值, 答应?.警示].filter(Boolean).join(' · ') || '—',
      来源: 'session.顾客情况「答应过什么」的值与警示',
    },
    { 标签: '办过什么', 值: 办过?.值 ?? '—', 来源: 'session.顾客情况「办过什么」的值' },
    // 这行不上屏取值，是一句**规矩**：补发单不重新采集收件信息，按原订单发。
    // 写死在这里是有意的 —— 真去拼一遍省市区只是换个地方重复同一句话。
    { 标签: '收件信息', 值: '按原订单（不重新采集）', 来源: '固定文案' },
    {
      标签: '升级分类',
      值: (转交 ? 转交分类.join('／') : 报备分类) || '—',
      来源: '转交：本轮处置的交接分类；报备：工单类型＋警示',
    },
  ]

  return {
    状态: 转交 ? '已转出' : 报备态 === '已答复' ? '已完成' : '等待审批',
    行: 行表,
    单号,
  }
}

// ── 接口 ────────────────────────────────────────────────────
//
// 上面那一份是**兜底**，下面这一份是**正路**。两个来源长得几乎一样，这正是
// 最要命的地方（`工单交接_给前端线_B.md` §六 第 6 条：兜底和接口真的通了长得
// 一模一样）。所以每一处都留着名字上的差别，并且右栏顶上常驻一行「接口 · 已连」
// ／「剧本兜底 · …」—— 分得清这件事由那行标记负责，不靠人记。

/**
 * 超时。
 *
 * 报备／转交只在服务端读一次台账、拼七行，不跑模型 —— 正常是几十毫秒。
 * 给 8 秒是**留给慢机器和冷启动**的余量，不是预期耗时。
 *
 * **没有这一条的话，后端半死（进程在、不响应）会让三个按钮一直没反应。**
 * 和 `取判定` 那条同一个理由：那种状态和「点下去什么都没发生」长得一模一样。
 */
const 超时毫秒 = 8_000

/**
 * 读后端那句错误文案；读不出来退回状态码。
 *
 * ⚠️ **键名是 `错误`／`详情`，不是 FastAPI 默认的 `detail`。**
 * `main.py` 的 `装异常处理` 把 HTTPException 和参数校验错收敛成了同一个中文形状，
 * 那个函数的文档串里写着为什么：「前端要写两个分支去取错误文案，但界面上只有
 * 一个地方显示错误，第二个分支永远不会被写；出错时界面上什么都不显示。」
 *
 * **这一段不是美化，是这条错误唯一的用途。** `api/动作.py` 三个接口的文案都是
 * 给人看的整句（「这些处置 id 不在第 2 轮：…」／「…第 2 轮没有要报备的主张」），
 * 前端要是只写「请求失败」，看的人得开 DevTools 才知道后端说了什么 —— 而那句话
 * 恰恰是唯一能解释「为什么这张单子不该出现」的东西。
 *
 * 两个键都读：`错误` 是那句话，`详情` 是排障补充（参数校验错才非空）。
 * 第一版只读了 `detail`，真打时 400 和 409 全退成了光秃秃的 `HTTP 400`。
 */
async function 后端说明(答: Response): Promise<string> {
  try {
    const 体 = (await 答.json()) as { 错误?: unknown; 详情?: unknown }
    const 句 = [体.错误, 体.详情].filter((x): x is string => typeof x === 'string' && x !== '')
    if (句.length) return 句.join(' · ')
  } catch {
    // 不是 JSON（网关错误页那种）—— 退回状态码。
  }
  return `HTTP ${答.status}`
}

/**
 * 打一个动作接口。**网络层失败归 `未连`，后端回了非 2xx 归 `后端说不`。**
 *
 * `体` 不给就是空 POST —— 报备／转交的请求体本来就没有东西（这也是坑 1 的
 * 由来：请求里既没有轮次也没有别的，后端只能拿台账里最后那一轮）。
 */
async function 打动作<T>(路径: string, 体?: unknown): Promise<动作结果<T>> {
  try {
    const 答 = await fetch(路径, {
      method: 'POST',
      ...(体 === undefined
        ? {}
        : { headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(体) }),
      signal: AbortSignal.timeout(超时毫秒),
    })
    if (!答.ok) return { 态: '后端说不', 说明: await 后端说明(答) }
    return { 态: '成', 值: (await 答.json()) as T }
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿。故意不分类：调用方的处理完全一样。
    return { 态: '未连' }
  }
}

/**
 * 报备／转交，拿回那张自动带全的交接包。
 *
 * ⚠️ **路径段过 `encodeURIComponent`。** 会话 ID 现在是 ASCII（`S_DEMO_A`），
 * 但中文拼进路径会**静默 404** 这个坑本项目吃过（`api/动作.py` 文件头写着另一
 * 个形状的同一件事）—— 报错信息是「Not Found」，看着像路由没挂上，而路由挂着。
 */
export function 取交接包(会话ID: string, 动作: '报备' | '转交'): Promise<动作结果<交接包>> {
  return 打动作<交接包>(`/api/会话/${encodeURIComponent(会话ID)}/${动作}`)
}

/**
 * 把「这句话术兑现了哪几条主张」报给后端留痕。
 *
 * 返回的 `兑现主张` 右栏目前不显示 —— 它进的是服务端台账，给复盘和测试看。
 * 这里仍把它取出来，是为了**别把接口答的东西丢掉**：真要用的时候不用回头改签名。
 */
export async function 记发送(
  会话ID: string,
  采用的处置id: string[],
  话术: string,
): Promise<动作结果<string[]>> {
  const 果 = await 打动作<{ 兑现主张: string[] }>(
    `/api/会话/${encodeURIComponent(会话ID)}/发送`,
    { 采用的处置id, 话术 },
  )
  return 果.态 === '成' ? { 态: '成', 值: 果.值.兑现主张 } : 果
}
