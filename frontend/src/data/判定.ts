/**
 * `POST /api/判定` 的前端入口 —— 一句话进来，右栏出什么。
 *
 * # 为什么接，接到什么程度
 *
 * `开发步骤.md` 步骤 1 立这条接口的理由是「验证前后端能通」（Vite 代理、CORS、
 * 中文 JSON 往返），而**这个理由直到前端真的 fetch 它才成立**。在此之前跨域坑
 * 一直压着，等判定接口写完再撞上，排查时分不清是代理、是路径、还是判定逻辑。
 *
 * # 粒度不一样，这是接的时候最要紧的一件事
 *
 * 接口**一轮一答**：一次给整轮的顾客情况 ＋ 本轮处置 ＋ 主卡。
 * 剧本**一格一露**：第 1 步只露三行、其中「这是谁」还是 `查历史中…` 这个演示
 * 用的假中间态，第 2 步换成真值，第 3 步才露建议。
 *
 * 整份盖上去等于把 `剧本.ts` 那套分步露出连根拔掉 —— 而那是片子的一部分。
 * 所以分工是：**剧本管「这一格露哪几块、哪几行」，接口管「那一块的内容」。**
 * 合并规则见 `合顾客情况` / `合建议`，一句话是**逐字段：接口非空就用接口的**。
 *
 * # 接口是空的字段留在剧本上，不是偷懒
 *
 * 这条规矩是 `Advice.话术` **恒为 `None`** 那阵子立的（`话术生成` 当时还没建）：
 * 照字面取的话，主卡［采用］点了不带字 —— 而脚本 S7 整拍就是「采用 → 改出禁语
 * → 被拦 → 才发送」，那一拍会当场演不出来。空字段回落剧本，缺口照旧可见
 * （`依据` 的条数、`风险标签` 的有无都会露出来），但片子不会断。
 *
 * ⚠️ **`话术` 现在不再是恒 `None` 了**（2026-10-01 `话术生成` 建起来之后，
 * `判定.py` 对走 3c 的主张会填它；这段注释到 2026-10-02 还在说「恒为 None」，
 * 是过时的）。**但回落那条规矩不变、也仍然要用**：`报备`／`转交` 的 `话术`
 * 依旧是 `None`，而 `判断`／`标题`／`说明` 三句后端**至今没有真源**，
 * 现在是调用方填的（`接口契约.md` §七 挂着的未定项）。
 */

import type { Advice, ChatMessage, Disposition, StateRow } from '../types'
import type { 接口话术, 剧本 } from './剧本'

