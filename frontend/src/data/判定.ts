/**
 * `POST /api/判定` 的响应体。
 *
 * **这个类型不写进 `types/index.ts`。** 那个文件归接口线独占
 * （`backend/tests/test_schemas.py` 直接解析它），而这个形状是右栏自己消费的 ——
 * 和 `交接包` 一个路子。字段名逐字照 `schemas.py`，一个字都不许改：
 * 两边漂移**不会让任何东西报错**，只是右栏某一块悄悄不显示了。
 */
export interface 判定响应 {
  会话ID: string
  轮次: number
  看到消息数?: number | null
  顾客情况: StateRow[]
  安全事件: 安全事件条目[]
  触发: 触发条目[]
  本轮处置: Disposition[]
  主卡: Advice | null
  闸门: 闸门命中[]
}

/**
 * 超时。
 *
 * **没有这一条的话，后端半死（进程在、不响应）会让右栏一直空着** —— 而这和
 * 「这一轮没有要客服动手的事」长得一模一样。超了就回落剧本，至少是完整的。
 *
 * # 从 12s 放到 20s（2026-10-06）
 *
 * 原注释写的是「判定要跑**三次**模型，正常是几秒」，`12_000` 就是照那个量级定的
 * —— 而这句话早就不成立了。链路现在的形状是**最多十次**（`api/判定.py` 文件头
 * 自己写着「要花十几次 API 调用」）：`认诉求` 和 `生成话术` 各**按条数**算。
 * 实测演示线一轮次1（两条主张）：10 次调用共 **13.4 秒**，其中 `生成话术` 两次
 * 就占 **9.9 秒**（每条主张一次，每次里还裹着一次先例召回的嵌入调用）——
 * 后端稳稳地越过 12s，浏览器当场 `AbortSignal` 掐断，右栏回落剧本。
 *
 * 12s 是**照着实测的最大值定的，一分余量没有**（`App.tsx` 那个 effect 的注释里
 * 留着作者当时的实测「4.7／4.9／12.0 秒」）。20s 留出的余量是按「模型慢一半
 * 也还过得去」取的，不是又一次照着实测的最大值定。
 *
 * **它挡的是「后端半死」，不是「模型慢」** —— 所以别拿它当性能预算使：
 * 真想治那 13.4 秒，治的是链路（十次串行调用、`生成话术` 逐主张各写一遍），
 * 不是把这条线再往上调。
 */
const 超时毫秒 = 20_000

/**
 * 取一轮判定。**任何失败都返回 `null`，不抛。**
 *
 * 后端没起、超时、404（会话不在服务端）、响应不是合法 JSON —— 对调用方都是
 * 同一件事：这一轮拿不到，用剧本的。抛的话每个调用点都要包一层 try，而漏掉的
 * 那一个会在演示当天变成一个右栏白屏。
 *
 * `当前时间` 必须传。**取服务器时间的话整条演示线一条都不会命中** ——
 * 演示的「今天」是 2026-09-29，录制却在别的日子，`H3 承诺逾期` 直接不成立，
 * 而屏幕上看起来就是「今天没有逾期」（`判定.py` 文件头写着这条）。
 *
 * # `轮次` 接口上可省，**前端一律给准数**（2026-10-04）
 *
 * 协议里这个键仍然可省（`判定.py` 第 2 步：`轮次 = 请求.轮次 或 切轮(...)[-1]`），
 * 后端自己取末轮。**但前端不许走那条**：真窗口的轮次现在由 `data/轮次.ts`
 * 自己数（判据同后端 `切轮`），走到第几轮就报第几轮。省掉的话，屏幕停在
 * 第 1 轮、判的却是末轮 —— 右栏挂着另一轮的建议，屏幕上不报任何错。
 *
 * 所以参数是必给的 `number`。**别改回 `number | undefined`**：那个宽度是给
 * 「打之前不知道有几轮」留的口子（真窗口早先就是这个情形），而它现在知道了。
 *
 * 轮次**超范围**时后端夹到末轮（不报错），所以给准数这件事的责任在前端 ——
 * 算错了不会炸，只会静静地判成另一轮。`App.问一轮` 的文档串写着谁负责算。
 */
export async function 取判定(
  会话ID: string,
  轮次: number,
  当前时间: string,
  看到消息数?: number,
): Promise<判定响应 | null> {
  try {
    const 请求体: Record<string, unknown> = { 会话ID, 轮次, 当前时间 }
    if (看到消息数 !== undefined) 请求体.看到消息数 = 看到消息数
    const 答 = await fetch('/api/判定', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(请求体),
      signal: AbortSignal.timeout(超时毫秒),
    })
    if (!答.ok) return null
    return (await 答.json()) as 判定响应
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿。故意不分类：调用方的处理完全一样。
    return null
  }
}

/** 「接口没给」的判据。`0` 和 `false` 不算空 —— 它们是值，只是长得像假。 */
function 空(值: unknown): boolean {
  if (值 === null || 值 === undefined) return true
  if (typeof 值 === 'string') return 值.trim() === ''
  if (Array.isArray(值)) return 值.length === 0
  return false
}

/** 逐字段取非空：接口给了就用接口的，空就留剧本的。 */
function 取字段<T>(剧本的: T | undefined, 接口的: T | undefined): T | undefined {
  return 空(接口的) ? 剧本的 : 接口的
}

/**
 * **唯一一行不让判定接口盖的：`这次要什么`。**
 *
 * 别处是「接口非空就用接口的」（`取字段`），这一行反过来。两个原因，各自都够：
 *
 * 1. **形状不一样。** 剧本写的是**攒**——`精华含不含乙醇 ＋ 怀孕能不能用
 *    ＋ 赠品补发`；判定接口给的是**末轮买家原话**（`装配.这次要什么` 的文档串：
 *    那个形状是 H2 要看的）。一个是总结，一个是引文，盖上去就是把总结换成引文。
 * 2. **时机也不一样。** 判定**一轮一答**：第 2 轮一开口就把新值端上来，而
 *    `当前判定轮次` 是**往回扫**的 —— 第 5 格她刚说完赠品，右栏读的仍是第 1 格
 *    落下的那一轮。照通用规矩办，就是拿第 1 轮的原话把剧本刚添上的「＋ 赠品补发」
 *    盖回去：她说了话，那一行反而**退回去了**。
 *
 * # 2026-10-04：这一行归模型了，可这条例外**照旧要留**
 *
 * 模型拆出来的值在 `App.贴判定` 里**最后盖**一层（三层先后见 `data/需求分解.ts`），
 * 所以原先那句「接口真算出来的值进不了演示线」—— 那说的是判定接口 —— 现在没有
 * 了：这一行最终显示的是模型拆的需求。
 *
 * 但例外不能删。删掉之后模型答上来之前那零点几秒里（第 1 格就要等：判定轮次 1
 * 也在第 1 格），屏幕上那一行会先被判定接口的**原话**顶上去，等模型答上来再换成
 * 短需求 —— 观众看见的是那一行闪一下引文，而它本来该从剧本那份直接换成模型那份。
 *
 * 同理，模型没答上来时留着的是**剧本手写的那份**，不是原话：这一行的回落值
 * 一直是它（真窗口那边没有剧本，回落的是 `GET /api/会话列表` 给的原话）。
 */
const 剧本说了算的行 = '这次要什么'

/**
 * 合并一行顾客情况。
 *
 * **按 `标签` 找对应行，不是按下标。** 剧本第 1 步刻意少露两行、还插了一个
 * 假中间态「查历史中…」—— 下标对不上，而 `标签` 对得上。接口没有的那一行
 * （假中间态就是）原样留剧本的，它本来就是演示道具，不该由接口负责。
 */
function 合一行(剧本的: StateRow, 接口的: StateRow | undefined): StateRow {
  if (!接口的) return 剧本的
  return {
    标签: 剧本的.标签,
    值:
      剧本的.标签 === 剧本说了算的行
        ? (剧本的.值 ?? 接口的.值)
        : (取字段(剧本的.值, 接口的.值) ?? 剧本的.值),
    备注: 取字段(剧本的.备注, 接口的.备注),
    /**
     * **这一格和别的不一样：剧本没给 `警示`，接口给了也不上。**
     *
     * 接口是**一轮一结**，第 1 轮就把 H3 算出来了，`警示` 当场给「已逾期 2 天」。
     * 剧本是**一格一演**：「逾期浮出来」是线一第 6 步那一拍的全部内容
     * （`剧本.ts` 的 `答应过什么` 函数上写着为什么前三步不带它）。
     *
     * 照「接口非空就用」的规矩办，第 3 步右栏就开始飘红 —— 第 6 步那一拍
     * 还没演就已经演完了，而屏幕上不会报任何错。
     *
     * 代价写在这儿：**接口新算出来的、剧本没写的警示会被压掉。** 在这个演示里
     * 两者本来就是同一个值，压掉不丢东西；真接了实时数据之后要重新想 ——
     * 那时候「什么时候该报警」不该由一份演示脚本来决定。
     */
    警示: 剧本的.警示 === undefined ? undefined : 取字段(剧本的.警示, 接口的.警示),
    时限: 取字段(剧本的.时限, 接口的.时限),
  }
}

/**
 * 合并顾客情况。
 *
 * **行数和顺序全归剧本** —— 这是「剧本管什么时候露哪几行」那一半。
 * 接口多给的行不加（第 1 步只该露三行），少给的行保留剧本的。
 */
export function 合顾客情况(
  剧本的: StateRow[] | undefined,
  接口的: StateRow[] | undefined,
): StateRow[] | undefined {
  if (!剧本的) return undefined
  if (!接口的?.length) return 剧本的
  const 按标签 = new Map(接口的.map((行) => [行.标签, 行]))
  return 剧本的.map((行) => 合一行(行, 按标签.get(行.标签)))
}

/**
 * 合并主卡。
 *
 * **`依据` 是整块替换，不逐条合并。** 后端只返回查到的源（`接口契约.md` §五），
 * 空位由前端补成 `用上: false` —— 这是前端欠的活，见 `补六源空位`。
 * 逐条合并的话，「上一次命中、这一次没命中」的那条会留在屏幕上，
 * 而它正是要露出来的东西：`N/6` 会虚高。
 */
export function 合建议(
  剧本的: Advice | undefined,
  接口的: Advice | null | undefined,
): Advice | undefined {
  if (!接口的) return 剧本的
  /**
   * ⚠️ **剧本说没有，就是没有。** 这里原来写的是 `return 接口的`，2026-10-02 改。
   *
   * 主卡不是「后端有就显示」——它是**第 3 步那一拍的全部内容**（`剧本.ts` 第 3 步
   * 的备注：「主卡在这里出现，依据块跟着一起」）。剧本前两步没有 `建议`，
   * 那不是「这一格的内容留空待填」，是「**这一步还不该露**」。
   *
   * 照原来那条跑，后端（或代理）一起，第 1 步主卡就上屏了：八步的露出节奏当场
   * 作废，而且 `已代发` 会把第三步那条 AI 直发提前剧透掉 ——
   * 屏幕上没有任何东西报错。这违反的正是本文件开头那句「**剧本管「这一格露哪几块、
   * 哪几行」，接口管「那一块的内容」**」。
   *
   * 实测（把本文件编译出来直接调）：`合建议(undefined, 接口主卡)` 返回的是整张
   * 接口主卡，`已代发` 一并带出。
   *
   * **影响面只有第 1、2 步。** `演到` 是累积的，第 3 步一设 `建议` 就一直在，
   * 所以后面每一格 `剧本的` 都非空，走的都是逐字段那条路。
   *
   * 代价：剧本真漏写 `建议` 的那一格，接口也不再兜。这个演示里不存在那种格，
   * 而「安静地少显示一块」比「提前一屏剧透」好查。
   */
  if (!剧本的) return undefined
  return {
    形态: 接口的.形态,
    判断: 取字段(剧本的.判断, 接口的.判断) ?? 剧本的.判断,
    标题: 取字段(剧本的.标题, 接口的.标题) ?? 剧本的.标题,
    说明: 取字段(剧本的.说明, 接口的.说明) ?? 剧本的.说明,
    话术: 取字段(剧本的.话术, 接口的.话术),
    风险标签: 取字段(剧本的.风险标签, 接口的.风险标签),
    话术建议: 取字段(剧本的.话术建议, 接口的.话术建议),
    依据: 补六源空位(接口的.依据),
    已代发: 取字段(剧本的.已代发, 接口的.已代发),
  }
}

/**
 * 没有剧本的会话（112 个真窗口）拿到的那张主卡。
 *
 * # 为什么不复用 `合建议`
 *
 * `合建议` 是「**剧本管露哪几块、接口管那一块的内容**」的合并器，第一参数是
 * 剧本那份，而且它**没有剧本时按设计返回 `undefined`**（文档串里写着理由：
 * 剧本说没有主卡的那一格，是「这一步还不该露」，不是「待填」）。
 *
 * 真窗口没有「哪一格该露」这回事 —— 点开就判，判出什么就是什么。拿
 * `合建议(undefined, 主卡)` 去凑会拿到 `undefined`，右栏永远空白，
 * 而屏幕上和「这一轮 AI 自己处理了、不用客服动手」长得一模一样。
 *
 * # `依据` 照旧过 `补六源空位`
 *
 * 后端只回报**查到的**源（`接口契约.md` §五），空位是前端欠的活。两处各补一遍
 * 的话，`N/6` 那个分母会在两条路上对不上 —— 它同时是展示元素和「六源」这个
 * 设计前提的证据。
 *
 * `主卡` 为 `null` = 这一轮没有要客服动手的事，返回 `undefined`，和剧本那条路
 * 的「没有主卡」是同一个意思。
 */
export function 接口建议(主卡: Advice | null | undefined): Advice | undefined {
  if (!主卡) return undefined
  return { ...主卡, 依据: 补六源空位(主卡.依据) }
}

/**
 * 合并本轮处置。
 *
 * **剧本给的是「这一步该露哪几条」（按 `输出` 数），接口给的是「判定真判出了
 * 什么」。** 所以按剧本要的输出逐个取接口的：剧本要几条某种输出，就取接口那种
 * 输出的前几条。
 *
 * **为什么不能整块替换。** 接口一轮一结，剧本一格一露。线一第 6 步（「逾期浮出来」
 * 那一格）剧本攒了**两轮**的三条 —— 第 1 轮的 AI 直发 ＋ 客服点发送，加上第 2 轮
 * 那条报备 —— 而接口的轮次 2 只回它自己那一条。整块替换会让那一屏从三条缩成
 * 一条：上半场那两条凭空消失。反过来，接口一轮答多了，整块替换也会把剧本压根
 * 没打算在这一格露的东西端上屏幕。
 *
 * **为什么不能按 `id` 对齐。** 两边的 id 长得一样，指的不是一回事：剧本的
 * `S_DEMO_A-1-1` 是「孕妇能否用」，接口的同名 id 是「这款精华是否含有乙醇」。
 * 剧本那一列是回放的格子编号，不是契约字段（`演示会话.py` 文件头也这么写）。
 *
 * **为什么要跨轮攒。** 第 6 步那一屏是两轮加起来的（乙醇 ＋ 孕期 ＋ 补发），
 * 而接口一次只答一轮。所以 `各轮` 要按轮次升序全传进来，不能只传当前轮。
 */
export function 合本轮处置(
  剧本的: Disposition[] | undefined,
  各轮: Disposition[][],
): Disposition[] | undefined {
  if (!剧本的?.length) return undefined
  const 料 = 各轮.flat()
  // 一次都没答上来 → 整块留剧本（和 `合建议` 同一条兜底）。
  if (!料.length) return 剧本的

  const 取到第几条 = new Map<string, number>()
  return 剧本的.map((模板) => {
    const 第几条 = 取到第几条.get(模板.输出) ?? 0
    const 命中 = 料.filter((d) => d.输出 === 模板.输出)[第几条]
    取到第几条.set(模板.输出, 第几条 + 1)
    // 接口这一种输出不够数时留剧本那条，不让整行凭空消失。
    return 命中 ?? 模板
  })
}

/**
 * 把后端返回的 `依据` 补成六个来源，缺的填 `用上: false`。
 *
 * **这是前端的活，`接口契约.md` §五 明写。** 后端只返回 `exists=True` 的那些，
 * 它**不需要知道前端要补几个空位**。不补的话 `N/6 源命中` 的分母会跟着后端
 * 这一次查到了几条走 —— 线一轮次 1 实测只回 3 条，屏幕上是「3/3 源命中」，
 * 而那句话要说的是「六个来源我都查过了，命中 3 个」。
 *
 * 空位的 `摘要` 由 `AdviceCard` 按 `序号` 给（它那儿有一张六源表），
 * 这里只补形状 —— 在这里写摘要就成第二份真源了。
 */
/**
 * 消息序号 → 该从接口取哪一块。整份剧本扫一遍。
 *
 * 序号是**会话级**的（`造消息` 的第 2 个参数），所以 `消息` 和 `待发` 共用这一张表，
 * 不用分两套。
 */
function 话术来源表(剧本: 剧本 | null | undefined): Map<number, 接口话术> {
  const 表 = new Map<number, 接口话术>()
  for (const e of 剧本?.事件 ?? []) {
    for (const [号, 归谁] of Object.entries(e.话术来源 ?? {})) {
      表.set(Number(号), 归谁)
    }
  }
  return 表
}

/**
 * 换一条消息的文字。
 *
 * `chat_content` 一并换掉：它和 `message_text` 是同一份内容的两种写法
 * （`ChatMessage` 的文档串写着），只换一处就是埋一个「两处都看着对」的坑。
 * 界面现在只读 `message_text`，所以这一行是给下一个来读这份数据的人留的。
 */
function 换文字(条: ChatMessage, 文: string, 署名?: string): ChatMessage {
  return {
    ...条,
    message_text: 文,
    chat_content: JSON.stringify([{ index: 0, content: 文 }]),
    ...(署名 === undefined ? {} : { 署名 }),
  }
}

/**
 * 把「以我方名义说出去的话」的文字换成接口给的。
 *
 * # 只换文字，不管露出
 *
 * **不在 `话术来源` 里的消息一个字都不动** —— 顾客说的话、客服现场手打的、
 * 剧本没声明归接口管的，全部原样返回。这一条和 `合建议` 那句「剧本说没有，
 * 就是没有」是同一个方向：**露出节奏归剧本，接口只管那一块的内容**。
 *
 * `待发` 也认同一张表，所以对 `消息` 和 `待发` 各调一次就行，不用分两套。
 *
 * # 接口没答上来一律留剧本
 *
 * `各轮` 里没有那一轮、`主卡` 是 `null`、`已代发` 第 n 条不存在、`话术`
 * 是空串 —— 四种都原样返回。**兜底是留着的正常路径，不是万一**，
 * 和 `取判定` 返回 `null` 同一条规矩。
 *
 * # 为什么按「消息序号」找，不按顺序数
 *
 * `已代发` 是**按轮**给的，而一屏上可能同时躺着两轮的话（线一第 6 格往后，
 * 第 3 格那句讲乙醇的和第 5 格那句安抚的都在）。按顺序数的话，往回拖一拖
 * 序号就整个错位，而屏幕上只是文字悄悄换了，不报任何错。
 */
export function 合消息(
  消息们: ChatMessage[],
  剧本: 剧本 | null | undefined,
  各轮: Record<number, 判定响应> | undefined,
): ChatMessage[] {
  const 表 = 话术来源表(剧本)
  if (!表.size || !各轮) return 消息们

  // `已代发` 按轮消耗：某一轮里的第 n 条 AI 消息取那一轮的 `已代发[n]`。
  const 用掉几条 = new Map<number, number>()

  return 消息们.map((条) => {
    const 归谁 = 表.get(条.消息序号)
    if (!归谁) return 条
    const 答 = 各轮[归谁.轮次]
    if (!答?.主卡) return 条

    if (归谁.取 === '主卡话术') {
      const 文 = 答.主卡.话术
      // `文` 是 `string | undefined`（`Advice.话术` 可选），先窄掉再传下去。
      if (!文 || 空(文)) return 条
      return 换文字(条, 文)
    }

    const n = 用掉几条.get(归谁.轮次) ?? 0
    用掉几条.set(归谁.轮次, n + 1)
    const 代发 = 答.主卡.已代发?.[n]
    // 署名跟着内容一起换 —— 序号相同，两处说的本来就是同一条消息。
    return 代发 && !空(代发.内容) ? 换文字(条, 代发.内容, 代发.署名) : 条
  })
}

/**
 * 真窗口：客服自己按了［发送］的那些轮，**一轮只留一条答复**。
 *
 * 两件事一起做：把这一轮的**第一条**客服气泡换成客服真发出去的那句，**这一轮
 * 剩下的客服话一条不留**（垫话丢掉）。
 *
 * # 为什么真窗口不能用 `合消息`
 *
 * `合消息` 按 `话术来源表(剧本)` 找要换哪几条 —— 那张表整份来自剧本，真窗口一条
 * 都没有（`表.size` 是 0），一个字都不换。而真窗口恰恰最需要换：它的聊天区原来是
 * 把原始日志一条条重播，客服那句是**历史里真实的那句**，和右栏 primer 给的话术
 * 根本是两句话。
 *
 * # 为什么是「第一条」而不是「最后一条」
 *
 * 一轮里可能有两句客服话（先「稍等，我查一下」再给结论）。时间线是**一格一格
 * 走**的，走一格屏上多一条。答复落在**第一条**的位置，那一格就上屏了；落在最后
 * 一条的位置则会出现「走了一格，屏上什么也没多」的空拍（垫话被丢掉，而答复还
 * 没轮到）。落在第一条，屏上读起来是「客服发了一句，紧接着顾客的下一句」，
 * 一样对。
 *
 * # ⚠️ 2026-10-06：只换不丢是不够的（这一条是用户第三次报同一个 bug 的根）
 *
 * 原来只把第一条换成客服发出去的那句，**第二条及以后原样留着**。那几句没有授权：
 * 没走卡（卡只批了一条），也没走绿气泡（`丢直发轮的话` 只丢 `主卡` 为 `null`
 * 的那几轮，而这一轮有卡）。屏幕上于是出现一句**谁都没发过**的客服话 ——
 * 用户报的原话：「还是有没有经过绿色气泡发出的话」。实测踩得到的形状：482 轮里
 * 63 轮（56/112 条窗口），S00006 轮 1（「好的亲，马上为您查询…」＋「亲，麻烦您
 * 拍一下外箱面单…」）就是。
 *
 * 用户当天拍板的是**一轮只留一条答复**：垫话丢掉，客服发出去的那句落在第一条
 * 的位置。以前那段注释说「比另外两种错法都轻」—— 那是把不变量当成了取舍，
 * 这一条现在不做了。
 *
 * # 没发过的轮，一个字不动
 *
 * `现场话` 里没有第 N 轮就原样返回。三条路都会走到这儿，都不该换：
 * `AI直发`（客服没动手）、`报备`（接口明说 `话术` 是 `None`，安抚话术由客户端发）、
 * 以及客服压根没点那个按钮的时候。
 *
 * ⚠️ **「原样返回」是这一条函数自己的行为，不等于那几句都会留在屏幕上。**
 * `AI直发` 那一轮后来还得过一道 `丢直发轮的话` —— 那一轮 Primer 自己答了，
 * 日志里那句客服话谁都没授权，最后是不上屏的。别拿这里那句「留着的都是历史
 * 原文」当结论去改 `丢直发轮的话`。
 *
 * # ⚠️ 丢了一条就得连 `归属` 一起丢（和 `丢直发轮的话` 同一条规矩）
 *
 * `归属` 是**按下标**对的表。丢掉一条却不丢它对应的那一格，后面每一条的轮次就
 * 整体错开一位 —— 绿气泡落到下一句买家话后面去。返回的是两条，调用方两个都要
 * 接着往下传。
 */
export function 一轮留一条答复(
  消息们: ChatMessage[],
  归属: number[],
  现场话: Record<number, string> | undefined,
): { 消息: ChatMessage[]; 归属: number[] } {
  if (!现场话) return { 消息: 消息们, 归属 }

  const 换过 = new Set<number>()
  const 出的条: ChatMessage[] = []
  const 出的轮: number[] = []
  // **两个数组在这一趟里同时对**（`丢直发轮的话` 那段写着为什么）。
  消息们.forEach((条, i) => {
    const 轮 = 归属[i]
    const 话 = 轮 ? 现场话[轮] : undefined
    if (!话 || 条.角色 !== '客服') {
      出的条.push(条)
      出的轮.push(归属[i])
      return
    }
    // 这一轮的答复已经留过了 —— 这条是垫话（或者客服补的第二句），不上屏。
    if (换过.has(轮)) return
    换过.add(轮)
    出的条.push(换文字(条, 话))
    出的轮.push(归属[i])
  })
  return { 消息: 出的条, 归属: 出的轮 }
}

/**
 * 真窗口：**Primer 自己答了的轮，日志里那句客服话不上屏。**
 *
 * # 它挡的是什么
 *
 * `AI直发` 那一轮不做卡（那一档的定义就是「客服什么都不用做」，见 `Advice`），
 * 于是那一轮日志原有的客服话**谁都拿不出授权**：不是 Primer 发的（绿气泡才是，
 * 那是 `插代发` 插的），也没有人点过任何一张卡。留着它，屏幕上就是同一轮里
 * 两句答复 —— 后一句还查不出是谁发的。用户 2026-10-05 报的原话：
 * 「有没有经过primer自动和三张卡的客服的话出现，这是不允许的」。
 *
 * # 判据由调用方给，这里只管丢
 *
 * `直发轮` 是**这一轮 Primer 真发出过话**（`真代发` 里有它）**而且这一轮没有卡**
 * （`主卡` 是 `null`）的那些轮次（`App.直发轮` 算的）。这时候绿气泡就是这一轮的
 * 答复，日志里那句是同义的第二句 —— 顶掉它，画面上反而少一句重复。
 *
 * 只丢 `角色 === '客服'` 的：买家的话、系统推送都不是「我方说的话」，一条不动。
 *
 * # 两种**不能**丢的情形（`直发轮` 的判据挡着它们）
 *
 * （标题原写「三种」，底下只列了两条 —— 2026-10-06 顺手改成两条。`git log -p` 里
 * 看不出第三条是什么，也没在别处留下过，按当下真实的行为写。）
 *
 *   - **这一轮有卡**（`主卡` 不是 `null`）：②③④ 那三档的客服话是客服自己发出去／
 *     点出去的，卡就是它的授权 —— 日志原话该留着。③ 那一档尤其别动：卡上摆着的
 *     `待发句` 就是它，`handleSendPending` 放行之后要一个字不改地播出来。
 *   - **Primer 这一轮没有成稿**（`真代发` 里没有这一轮）：那就没有东西能顶替它，
 *     留着日志原文比留个洞强。判定还没答上来、或者往回拖之后对不上版本号，
 *     走的都是这一条 —— 兜底，和 `真窗口停` 判不出轮次时照走是同一种兜底。
 *
 *     ⚠️ **这一条 2026-10-06 窄过一次，读的时候别只读标题。** 原来「没有成稿」
 *     还包着**判完了、只是没拆出主张**的那一类（寒暄／道谢／收场白，`主卡: null`
 *     ＋ `本轮处置: []`）—— 那一类正是用户当天的报单「还是有没有走primer三张卡
 *     也没有走绿色气泡直接发出去的话」。现在 `真代发` 会把**日志原话本身**当成
 *     那一轮的代发稿，所以那一类**有成稿了**，落不到这一条上：原话被顶掉，
 *     换成一条带署名的绿气泡（内容同一个字）。
 *
 *     剩下走这一条的只有**真的没有东西可说**的那几种：判定还没答上来、
 *     往回拖之后版本号对不上、转交之后的那几轮（用户拍的例外，
 *     `App.现场转交轮`），以及这一轮压根没有客服话（实测 482 轮里 48 轮）。
 *
 * # 和 `换客服话` 的分工
 *
 * `换客服话` 换的是**客服自己按了发送**的那一句（② 那一档，文字换成他发的那句）；
 * 这一条丢的是**客服压根没动手**的那一句。一个轮次只会落到其中一边。
 *
 * 顺序上它在 `插代发` **之前**：那一句没了，绿气泡的落点才落回这一轮末尾
 * （`插代发` 第一遍扫的就是「这一轮第一条客服话」）。
 *
 * # ⚠️ `归属` 必须跟着一起丢，**返回的是两条**
 *
 * `归属` 是**按下标**对的表（`轮次归属` 的文档串：下标和 `消息们` 对齐）。丢掉一条
 * 却不丢它对应的那一格，后面每一条的轮次就整体错开一位 —— 而错开的样子是：
 * 这一轮的买家话被当成**上一轮**的，绿气泡于是落到她的**下一句买家话之后**
 * （2026-10-05 当天实测：丢之前写的是「返回 `ChatMessage[]`」，跑 `drive-real`
 * 第 ⑤ 幕红在「第二轮插进来那条是 AI 发的（实际角色 买家）」）。
 *
 * 回来的 `归属` **和回来的 `消息` 一样长**：只对齐这一屏的条数。传进来的 `归属`
 * 可能更长（它按**整条窗口**算，而这一屏只是前缀，见 `贴判定`）—— 那截尾巴在这
 * 两个数组里对不上号，不带出来。用它的地方只有 `插代发`，它也只看这一屏。
 */
export function 丢直发轮的话(
  消息们: ChatMessage[],
  归属: number[],
  直发轮: ReadonlySet<number>,
): { 消息: ChatMessage[]; 归属: number[] } {
  if (!直发轮.size) return { 消息: 消息们, 归属 }

  const 出的条: ChatMessage[] = []
  const 出的轮: number[] = []
  // **两个数组在这一趟里同时对**：各 filter 各的迟早只改一处，改漏的那一半
  // 就是上面写的那个错位。
  消息们.forEach((条, i) => {
    if (直发轮.has(归属[i]) && 条.角色 === '客服') return
    出的条.push(条)
    出的轮.push(归属[i])
  })
  return { 消息: 出的条, 归属: 出的轮 }
}

/**
 * 真窗口：把**这一轮已经自动发出去的话**插进聊天区。
 *
 * # 补的是什么
 *
 * ① `AI直发` 那一档在真窗口上**一个字都没发出去过**：聊天区是把原始日志一条条
 * 重播，而日志里没有 AI 说的话（业务数据里压根没有这一类行），后端算好的成稿只
 * 到了右栏的「本轮处置」里。于是客服看到的建议和顾客收到的回复是两回事 ——
 * 而屏幕上两处都看着正常。
 *
 * # 为什么插，不换（和 `换客服话` 的分工）
 *
 * `换客服话` 顶掉的是**日志里那句真发生过的客服话**，而那一句正是顾客的下一句在
 * 接的东西 —— 顶掉它，对话就断在那儿。实测 23 轮 ② 里就有 5 轮是这个形状
 * （S00001·1 日志那句在要照片，成稿在给承诺，顾客下一句「喏，图发你了」接的是照片）。
 *
 * 而自动发出去的那句话**日志里本来就没有**，它是加的一句 —— 加了之后，顾客的
 * 下一句接不接得上由那句历史原文说了算，不归这一句管。所以两条路分得开：
 * **只有客服自己按了发送的那一句才走换字**（`换客服话`），AI 代发的走插。
 *
 * 线一第 3 格就是这个形状：`[买家, AI「不含乙醇」, 客服承诺, 买家]`。
 *
 * # 落在哪儿：这一轮**第一条客服话之前**
 *
 * 和刹车停的位置是同一个点（`轮次.在等的轮`）—— 时间线停在客服那句之前，那几句
 * AI 已经发出去了，屏幕上就该看得见它们。
 *
 * ⚠️ **那一条客服话还没播到的时候，落点在这一轮末尾**（`消息们` 是日志的前缀，
 * 还没切到那一格）。两处落点**画出来是同一个顺序**：末尾和前一位之间只差那句客服
 * 话，而它下一拍就上屏。所以气泡是**待在原地往下走**，不会随回放往前跳一格 ——
 * 这一条是回归点，别为了「两个字面量统一」把没播到的那些挪到别处去。
 *
 * 2026-10-05 起，`丢直发轮的话` 会在这一步**之前**把 `AI直发` 那一轮的客服话
 * 丢掉（那一轮没有卡，日志原话谁都没授权）。于是那几轮**一定是**走末尾这个落点
 * ——第一遍扫描在那一轮找不到客服话了，这不是漏了，是那一条路的常态。
 *
 * 这一轮没有客服格时（实测 482 轮里 48 轮），只剩末尾那个落点，正好。
 *
 * # `代发们` 是「这一轮以 AI 的名义发过什么」，不是「日志里有什么」
 *
 * 它和后端 `_已代发` 是同一条规矩（`AI直发`／`报备` 这两种输出），只是那边从日志
 * 里挑（真窗口上挑不到），这边由 `App` 照 `本轮处置` 现造。
 *
 * # 没落在这一屏上的轮次，一个字都不插
 *
 * 往回拖之后，`代发们` 里还留着后面几轮的（`判定表` 按轮缓存），而它们的格子在
 * `消息们` 里已经没了 —— 第二遍扫描找不到落点，整轮跳过。这一条是**必须**的：
 * 漏了它，拖回去屏幕上会提前冒出她还没听到的那句话。
 */
export function 插代发(
  消息们: ChatMessage[],
  归属: number[],
  代发们: Record<number, ChatMessage[]>,
): ChatMessage[] {
  const 要插 = Object.entries(代发们)
    .filter(([, 条]) => 条?.length)
    .map(([轮]) => Number(轮))
  if (!要插.length) return 消息们

  const 落点 = new Map<number, number>()
  // 第一遍：这一轮的**第一条客服话**在哪儿。有它，就插在它前面。
  for (let i = 0; i < 消息们.length; i += 1) {
    const 轮 = 归属[i]
    if (要插.includes(轮) && 消息们[i].角色 === '客服' && !落点.has(轮)) 落点.set(轮, i)
  }
  // 第二遍：没有客服话的那些轮，落在这一轮末尾。**从后往前扫** —— 第一条命中的
  // 就是最后一格，`+1` 才是「末尾之后」。
  for (let i = 消息们.length - 1; i >= 0; i -= 1) {
    const 轮 = 归属[i]
    if (要插.includes(轮) && !落点.has(轮)) 落点.set(轮, i + 1)
  }

  const 出: ChatMessage[] = []
  for (let i = 0; i <= 消息们.length; i += 1) {
    for (const 轮 of 要插) {
      if (落点.get(轮) === i) 出.push(...代发们[轮])
    }
    if (i < 消息们.length) 出.push(消息们[i])
  }
  return 出
}

function 补六源空位(依据: Advice['依据'] | undefined): Advice['依据'] {
  const 有 = 依据 ?? []
  const 已给 = new Set(有.map((e) => e.序号))
  const 空位 = (['①', '②', '③', '④', '⑤', '⑥'] as const)
    .filter((序号) => !已给.has(序号))
    .map((序号) => ({ 序号, 出处: '', 摘要: '', 用上: false }))
  // 排序按六源编号，不按后端返回顺序 —— 后端先给 ① 再给两条 ② 是它查表的顺序，
  // 屏幕上该是 ①②③④⑤⑥。
  return [...有, ...空位].sort((a, b) => a.序号.localeCompare(b.序号))
}
