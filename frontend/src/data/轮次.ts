/**
 * 真窗口的「轮」—— 每条消息属于第几轮，以及「屏幕上这一拍在第几轮」。
 *
 * # 为什么前端要自己数一遍
 *
 * **判定是按轮问的**：`POST /api/判定` 一次只答一轮，请求里带 `轮次`。演示线上
 * 那个号写在剧本里（`剧本事件.判定轮次`），真窗口没有剧本 —— 只能从消息流自己
 * 推。而「问第几轮」这件事一旦算错，屏幕上**不会有任何东西报错**：右栏挂着的是
 * **另一轮**的建议，看着和这一轮的一样可信。所以下面这条判据必须和后端
 * `rules/pipeline.切轮` 逐字一致。
 *
 * # 判据（和后端同一条）
 *
 * **买家发言开始一轮，非买家发言结束当前轮。** 连续几条买家消息归**同一轮** ——
 * 那正是 H2 连发检测要看的形状（后端的文档串写着为什么判定入口是轮不是条）。
 *
 * 两条推论，都得照做：
 *
 *   - **客服／系统推送／AI 发言不属于「新的一轮」**，它归**它结束的那一轮**。
 *     第一条买家话之前那种（有的窗口一上来是客服开场白），归 0 —— 那是「还不
 *     在任何一轮里」，不是第 1 轮。
 *   - **末尾那段没人回的买家话也算一轮。** 后端 `切轮` 函数最后那一句 `收尾()`
 *     写着「它正是要判定的那一轮」—— 顾客刚说完、客服还没答，这一轮恰恰是最
 *     该判的。
 *
 * 后端另有一条「相邻两条买家消息属于不同诉求时切开」的判据（`归属` 参数，
 * 来自 `llm.认诉求`）。**前端不重放那一条**：它是模型给的，前端拿不到同一份
 * `归属` 表，重算必然分叉。好在它只做**加法** —— 认诉求切得更碎时，后端的
 * 轮数只会比这里**多**，而前端问的轮次是按屏幕上演到哪来定的（见 `演到第几轮`），
 * 多出来的那几轮前端根本不会去问。真撞上那种会话，症状是「这一轮的粒度比屏幕上
 * 的一拍细」，不是错位。
 */

import type { ChatMessage } from '../types'

/**
 * 每条消息属于第几轮。**下标和 `消息们` 对齐**，`0` = 还不属于任何一轮。
 *
 * 返回的是**逐条**的表，不是「每轮有哪几条」：调用方要知道的都是「屏幕上第 k 条
 * 是第几轮」这种问题（下一格要不要停、这一屏该显示哪一轮的卡）。
 */
export function 轮次归属(消息们: ChatMessage[]): number[] {
  const 表: number[] = []
  let 轮 = 0
  /** 上一条是不是买家话。买家话开始一轮，别的一律结束当前轮 —— 和 `切轮` 同一个开关。 */
  let 在轮里 = false

  for (const 条 of 消息们) {
    if (条.角色 === '买家') {
      if (!在轮里) 轮 += 1
      在轮里 = true
    } else {
      在轮里 = false
    }
    // 非买家消息跟着 `轮` 走：它结束的就是刚刚那一轮；一条买家话都没见过时
    // `轮` 还是 0，于是开场白落在 0 上。
    表.push(轮)
  }

  return 表
}

/**
 * 屏幕上这一拍在第几轮 —— `已播格数` 条消息已经上屏，**最后那条**属于第几轮。
 *
 * 0 表示还不在任何一轮里（一格没走，或者走到的是客服开场白）。
 *
 * **取「最后一条」而不是「下一条」**：下一条可能是下一轮的买家话，而这一屏右边
 * 该显示的是客服**手上这一轮**的建议 —— 顾客刚开口那一拍，判的就是她这一句
 * （这和后端 `切轮` 末尾那句「不收尾就没有可判的轮」是同一件事的两面）。
 */
export function 演到第几轮(归属: number[], 已播格数: number): number {
  if (已播格数 <= 0) return 0
  return 归属[Math.min(已播格数, 归属.length) - 1] ?? 0
}

/**
 * **这一屏正停在第几轮上等客服动手**，没在等就是 0。
 *
 * 判据是「**下一格就是这一轮的第一条客服话**」，两个条件都得成立：
 *
 *   - 下一格是客服话 —— 客服那一句就是这一轮的答复，它上屏等于「发出去了」，
 *     所以时间线必须**在它前面**停住等人点按钮；
 *   - 而且是这一轮的**第一条** —— 一轮里可能有两句客服话（实测 482 轮里 63 轮
 *     是这样，多半是先「稍等，我查一下」再给结论）。第二条再停一次的话，客服
 *     点完按钮还得再点一次，而那一下没有任何新东西可看。
 *
 * # 客服话在末格的窗口停不了
 *
 * 顾客说完话、这场对话就结束的窗口（实测 482 轮里 48 轮），**没有客服格可停**，
 * 一路演到底。那不是漏了：`usePlayer` 的 `停在` 在演到头时恒为 `null`（那儿写着
 * 为什么），而且这一轮本来也没有「发出去」这个动作可等。右栏照样显示它的卡，
 * 客服要回一句还是回得了（走 `handleSend` 的追加那一路）。
 */
export function 在等的轮(归属: number[], 消息们: ChatMessage[], 已播格数: number): number {
  const 下一条 = 消息们[已播格数]
  if (!下一条 || 下一条.角色 !== '客服') return 0

  const 轮 = 归属[已播格数] ?? 0
  if (轮 <= 0) return 0

  // 上一格已经播过这一轮的客服话了 —— 那是第二轮及以后的那几句，不再停。
  const 上一条 = 消息们[已播格数 - 1]
  if (上一条 && 上一条.角色 === '客服' && 归属[已播格数 - 1] === 轮) return 0

  return 轮
}
