/**
 * `GET /api/先例库` —— 右栏最下面那行「历史相似对话 N 条」的那个 N。
 *
 * # 它接的是真库，不是剧本里编的 56（2026-10-07 换的）
 *
 * 那一行原来读 `先例库基数 = 56`（`data/剧本.ts`）再加演到第几步，和盘上那个库
 * 一点关系都没有：库里真实有 139 条，屏幕上从 56 起步、演完到 57。换掉之后
 * **只有一个来源** —— 后端 `len(取库())`，也就是召回先例正在用的那个库。
 *
 * # 它会动 —— 「弹一下」那一拍有真数据可演（2026-10-07 实测）
 *
 * ⚠️ 这里原来写的是「回写一条都没有，所以这个数在演示里是静态的」，
 * **当天就被实测推翻了**：盘上那 139 条确实全是取材，但 `回写` 写的是**另一个
 * 地方** —— `api/判定.py` 收尾正常时 `append` 进**进程内**那个列表，所以每有
 * 一个新的「会话 × 轮次」干净收尾，这个数就 +1。实测：重启后端报 139，浏览器
 * 一开演示线（那一下会判 `S_DEMO_A` 轮 1）就报 **140**。
 *
 * **但重启后端就回到 139** —— 盘上那份文件没人写（写它的只有 `--重建`）。
 * 所以 `App` 每轮判定后重拉一次**不是为将来准备的，它现在就在用**；
 * 而讲的时候别把这个数说成「攒下来的」。
 *
 * 细节见 `docs/接口契约.md` §二之三；后端那条接口的文档串也写着。
 *
 * # 拿不到就整行不显示，**不回落到那个 56**
 *
 * 回落的话屏幕上那个数就又开始撒谎了 —— 而「库里有多少条」正是这一行唯一
 * 要说的事。后端没起的时候左栏只剩两条演示线、右栏顶上也写着「剧本兜底」，
 * 少这一行和那些信号是同一件事，不差它一个。
 *
 * 所以返回 `null` 的三种情形（后端没起、超时、响应不是那个形状）都不算错，
 * 调用方拿到 `null` 就维持原样。
 */

import type { 先例库 } from '../types'

/**
 * 5 秒。
 *
 * **它不是性能预算**（后端读的是已经加载进内存的那个列表，答的是一道算术题），
 * 它挡的是「后端半死」—— 进程在、不响应。那种情况下右栏这一行晚 5 秒不显示，
 * 而不是永远挂着一个说不清的数。
 */
const 超时毫秒 = 5_000

/**
 * 取一次库里有多少条。**任何失败都返回 `null`，不抛。**
 *
 * 和 `取会话列表`／`取判定` 同一条规矩：网络层、超时、JSON 解析都归一处，
 * 调用方的处理完全一样，所以这里不分类型。
 *
 * ⚠️ **`0` 是值，不是「没取到」。** 后端那边读不到库文件、或者库里的嵌入模型
 * 和当前配置对不上时都会报 0（`app/检索/先例库.py` 的 `取库` 文档串写着为什么）。
 * 报 0 是对的：那个库当时一条也召不回来。这里照实传出去，别写成 `|| null`。
 */
export async function 取先例库条数(): Promise<number | null> {
  try {
    const 答 = await fetch('/api/先例库', { signal: AbortSignal.timeout(超时毫秒) })
    if (!答.ok) return null
    const 体 = (await 答.json()) as Partial<先例库> | null
    return typeof 体?.条数 === 'number' ? 体.条数 : null
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿。
    return null
  }
}
