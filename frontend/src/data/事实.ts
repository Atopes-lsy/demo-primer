/**
 * 事实对照 —— 客服打的那句话和系统记录对不上时，把它拦下来。
 *
 * 和 `koujing.查禁语` 是**两道不同的检查**，别合并：
 *
 *   检查一 · 禁语   管**措辞** —— 这个词不许说（「绝对不刺激」「放心使用」）。
 *                   命中只提示，换一个说法就过去了，事实本身没错。
 *   检查二 · 事实   管**真相** —— 这句说的是假的（「已经发出了」，可仓库没发）。
 *                   换说法没用，得改口供。
 *
 * 一句话可能同时犯两条：既说了禁语、事情也不存在。两条各管各的，都要出。
 *
 * 为什么这一层必须有：客服不是存心说假话，是**记岔了**。「这单拖了几天」这种
 * 印象一旦形成，手就会打出「已经发出」。顾客那边收到的是一句承诺过的话，
 * 而我们这边记录是空的 —— 等到顾客按这句话来要货，才发现根本没人发。
 */

import type { Order, Session } from '../types'

/** 一句话和记录对不上。 */
export interface 事实冲突 {
  /** 说出口的那几个字，显示在「你说：」。 */
  你说: string
  /** 记录里那件事的真实状态，显示在「系统查到：」。 */
  记录: string
  /** 建议改成什么。**不是换措辞，是换一个不撒谎的说法。** */
  建议: string
}

/** 一条断言：什么样的话算「说了一件已经发生的事」，以及记录里该对哪一格。 */
interface 断言 {
  /** 排障用。 */
  名: string
  /**
   * 命中「这件事已经发生了」的说法。
   *
   * **必须带上完成标记（已／已经／了）**，这是这张表唯一容易写错的地方：
   * 「今天安排发出」「会尽快发出」里也有「发出」，可那是**对将来的承诺**，
   * 记录里当然是空的。把它们一起拦下来，就是在冤枉一个说对话的客服 ——
   * 而拦错一次，客服下次就不看这条提示了。
   */
  匹配: RegExp
  /** 记录说这件事已经发生了吗。 */
  成立: (订单: Order) => boolean
  /** 「系统查到」那一行。`承诺` 由调用方从顾客情况里取，可能为空。 */
  记录: (订单: Order, 承诺: string) => string
  建议: string
}

/** `2026-09-25 10:02:04` → `9/25`。 */
function 月日(时间: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(时间)
  return m ? `${Number(m[2])}/${Number(m[3])}` : 时间
}

/** 订单记录那一行的公共部分：什么时候下的单 ＋ 承诺过什么 ＋ 现在什么状态。 */
function 订单行(订单: Order, 承诺: string): string {
  return [`订单 ${月日(订单.下单时间)} 下单`, 承诺, 订单.订单状态].filter(Boolean).join(' · ')
}

/**
 * 「货已发出」那一行。**最后一格不是订单状态，是「还没发出去的那件」。**
 *
 * 这一单是两件货两条命：正装早发了、已签收（`订单.订单状态`），赠品漏发、
 * 补发到今天还没出去（`订单.发货时间` 是空串）。客服要是打「赠品已经发出了」，
 * 该对的是**赠品**那一件，不是整单 —— 拿 `订单状态` 去拼会拼出一句「已签收」，
 * 那就等于告诉客服她说得对，红框反而该响的时候不响。
 *
 * 所以：`发货时间` 空 → 还没发出去的那件没发 → 「未发货」。这个「空」和上面
 * 那条断言的 `成立` 判据是**同一个字段**，两处天然一致，不会一处说没发、
 * 一处说发了。
 *
 * （「货已签收」仍然用 `订单行`：签收说的是整单，正装确实签收了，
 * 客服说「已签收」是句真话，不该拦。）
 */
function 发货记录(订单: Order, 承诺: string): string {
  const 状态 = 订单.发货时间 ? 订单.订单状态 : '未发货'
  return [`订单 ${月日(订单.下单时间)} 下单`, 承诺, 状态].filter(Boolean).join(' · ')
}

const 断言表: 断言[] = [
  {
    名: '货已发出',
    匹配: /(?:已经|已)\s*(?:发出|发货|寄出|发走)|(?:发出|发货|寄出)了/,
    成立: (订单) => Boolean(订单.发货时间),
    记录: 发货记录,
    建议: '我马上帮您核实发出时间，有结果第一时间告诉您',
  },
  {
    名: '货已签收',
    匹配: /(?:已经|已)\s*签收/,
    成立: (订单) => 订单.订单状态.includes('签收'),
    记录: 订单行,
    建议: '我先帮您核实一下物流签收情况，稍后回复您',
  },
]

/**
 * 「答应过什么」那一行里写的时限。
 *
 * 备注的原文是 `时限：9/27 24:00`，取冒号后面那截。**这是读数据层自己写的标签**，
 * 不是从给人看的句子里猜意思 —— 那个前缀是 `剧本.答应过什么` 拼的，两边一起改。
 */
function 承诺时限(会话: Session): string {
  const 答应 = (会话.顾客情况 ?? []).find((r) => r.标签 === '答应过什么')
  const 时限 = 答应?.备注?.replace(/^时限：/, '')
  return 时限 ? `承诺 ${时限} 前发出` : ''
}

/**
 * 查草稿里有没有和订单记录对不上的话。没有 → `null`，红框不出现。
 *
 * 每个会话每次渲染现算，和 `查禁语` 一样（见 `ChatPanel`）：客服改一个字，
 * 红框就该跟着收掉 —— 存进状态的话，改完还挂着旧提示。
 *
 * 没有订单的会话直接跳过。**不知道的事不拦**：这条规矩比「多拦一句」重要，
 * 系统没记录的时候它没资格说客服讲错了。
 */
export function 查事实(草稿: string, 会话: Session | null | undefined): 事实冲突 | null {
  const 订单 = 会话?.订单
  if (!订单 || !草稿.trim()) return null

  const 承诺 = 承诺时限(会话)

  for (const a of 断言表) {
    const 命中 = a.匹配.exec(草稿)
    if (!命中) continue
    if (a.成立(订单)) continue // 记录说确实办到了 —— 那就不是冲突，是件好事
    return { 你说: 命中[0].trim(), 记录: a.记录(订单, 承诺), 建议: a.建议 }
  }

  return null
}
