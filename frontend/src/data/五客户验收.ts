/**
 * UI 验收专用的五位固定顾客。
 *
 * 这不是生产数据，也不会替代真实后端。它只在
 * `VITE_UI_REVIEW_MODE=five` 时启用，让每一轮 UI PR 都能用同一组场景做前后对比。
 */

import type { Session } from '../types'
import { 演到, 线一会话, 线一剧本, 线二会话, 线二剧本 } from './剧本'

function 改成验收顾客(
  会话: Session,
  会话ID: string,
  买家昵称: string,
  摘要: string,
  最近时间: string,
  覆盖: Partial<Session> = {},
): Session {
  return {
    ...会话,
    会话ID,
    买家昵称,
    摘要,
    最近时间,
    消息: 会话.消息.map((消息) => ({
      ...消息,
      会话ID,
      message_id: `${会话ID}-${消息.消息序号}`,
      买家昵称,
      发送方: 消息.角色 === '买家' ? 买家昵称 : 消息.发送方,
    })),
    订单: 会话.订单
      ? { ...会话.订单, 会话ID, 买家昵称 }
      : undefined,
    工单: 会话.工单
      ? { ...会话.工单, ticket: { ...会话.工单.ticket, 会话ID, 买家昵称 } }
      : undefined,
    ...覆盖,
  }
}

