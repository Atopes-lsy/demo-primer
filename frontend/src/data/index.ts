/**
 * `GET /api/会话列表` 的前端入口。
 *
 * 返回 **114 条 —— 两位演示顾客 ＋ 112 个真实窗口**。**任何失败都返回 `null`，
 * 不抛**，和 `判定.取判定` 同一条规矩：后端没起、超时、响应不是数组，对调用方是
 * 同一件事（这一份拿不到，用剧本那份），而漏掉的那个 catch 会在演示当天变成左栏空白。
 *
 * # 「窗口」不是「会话」（2026-10-03）
 *
 * 138 条真会话里，同一个人来过 2–3 次的有 24 组，接口按 `买家昵称` 把它们并成
 * 一个窗口（`data/顾客窗口.py`）—— 合成窗口的 `以前` 就是那些更早的来访
 * （2026-10-04 起不再单独成块，只用来填五行）。所以 **112 ＋ 2 = 114**，
 * 而 `/healthz` 报的仍然是 **140**：
 * 那一个是装载器的口径（原始会话数），这一个是被合并过的口径。两个数不一样是
 * **有意的**，不是谁算错了。
 *
 * ⚠️ **没并过的那 88 个单段窗口，接口给的是 `以前: []`** —— 2026-10-04 起这一支
 * 到了界面上是「初次会话」那张小卡，五行一片都不渲染，直到 `stage` 被写成
 * `历史联系`（`会话已结束`）。真数据里没人写它，所以这 88 个就停在那儿。见
 * `docs/superpowers/specs/2026-10-04-初次会话与结束-design.md` §四。
 *
 * **这个响应体有 876KB**（114 条窗口的全部消息，含 `chat_content` 那一列 JSON 串）。
 * 合并只是把条目并了，消息一条没少（1008 条）。本地 18ms，一次性开销，不卡演示 ——
 * 但它不是一个小接口，别在循环里调。
 *
 * ⚠️ **给这个数标一个日期。** 它一直在动：850KB（只有会话）→ 913KB（2026-10-03
 * 加上每条会话的顾客情况五行）→ 876KB（2026-10-03 合并窗口，条数从 140 掉到 114）。
 * 别看到数字涨了就以为接口变重了：**涨的是内容，不是耗时**（仍是 18ms 量级），
 * 超时也还是下面那 10 秒。
 */
export async function 取会话列表(): Promise<Session[] | null> {
  if (UI验收模式) return 五客户验收会话
  try {
    const 答 = await fetch('/api/会话列表', { signal: AbortSignal.timeout(10_000) })
    if (!答.ok) return null
    const 体 = (await 答.json()) as unknown
    return Array.isArray(体) ? (体 as Session[]) : null
  } catch {
    // 网络层、超时、JSON 解析 —— 都归这儿，调用方处理完全一样。
    return null
  }
}

/**
 * 合并会话列表：演示两条 ＋ 接口给的真实会话。
 *
 * # 演示两条用剧本那份，不用接口那份
 *
 * 接口返回的 `S_DEMO_A` 带着 7 条真消息，而**剧本那条的 `消息` 是空的**。回放靠
 * `演到` 从剧本折出来，并且把它一律排在 `活.消息` 的**末尾** —— 用接口那份的话，
 * 整段历史会在片子演完之后再重放一遍（`App.tsx` 文件头也记着这件事）。
 * 订单／工单／摘要本来就在剧本里，接口那份一个字段都用不上。
 *
 * ⚠️ **`顾客情况` 也归这一条管，而且非这样不可。** 2026-10-03 起接口给每条会话
 * （包括这两条）都装配了顾客情况，但它装的是**整条会话结束时**的五行 ——
 * 而演示要的是「这一步该露哪几行」，格 0 一格都没演。用接口那份的话，
 * 开屏第一帧右栏就是满的，「这是谁」也就不会在 S4 那一下自己变值了。
 *
 * # 顺序
 *
 * - **演示两条钉最前，A 在 B 前。** 按 `最近时间` 倒序的话 B（10:22）会压过
 *   A（10:12），而片子里线一先演、演完才「换一位顾客」切线二 —— 列表顺序得和
 *   叙事顺序同向，否则演示的人每次都要往下找。
 * - 其余按 `最近时间` 倒序。实测接口本来就是这么排的，这里**显式再排一次**：
 *   左栏的可读性不该依赖服务端的排序实现，那是它没承诺过的东西。
 * - **顾客把同一件事说了两遍的那几条垫底**（`重复会话.ts` 记着是哪几条、凭什么）。
 *   一句话问两遍、客服也答两遍，回放到那儿屏幕上就是重复——片子里左栏露在
 *   镜头前，所以把这类窗口从前面挪开。**一条数据都没动**，只是左栏的顺序。
 *   两段**各自**仍是最近时间倒序：`filter` 保序，不用再排一次。
 *
 * 接口没答上来时传 `[]`，返回的还是那两条演示会话 —— 左栏不至于空掉，片子的
 * 两条线一条不少。
 */
export function 合会话列表(接口的: Session[]): Session[] {
  if (UI验收模式) return 五客户验收会话
  const 演示两条 = [线一会话, 线二会话]
  const 演示的ID = new Set(演示两条.map((s) => s.会话ID))
  const 其余 = 接口的
    .filter((s) => !演示的ID.has(s.会话ID))
    .sort((a, b) => (b.最近时间 ?? '').localeCompare(a.最近时间 ?? ''))
  const 反复的 = 其余.filter((s) => 重复会话.has(s.会话ID))
  return [...演示两条, ...其余.filter((s) => !重复会话.has(s.会话ID)), ...反复的]
}
