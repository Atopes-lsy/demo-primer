/**
 * 真窗口上 AI 代发的那一格（见 `插代发`）。
 *
 * **时间戳跟着锚走，不是真实时钟。** 真数据全是五月的，写成今天的话屏幕上会冒出一条
 * 十月的气泡夹在五月的对话里 —— 和 `最近时间` 那条注释防的是同一件事的另一面
 * （那边更硬：写错了判定会当场满屏逾期）。
 *
 * `消息序号` 沿用锚那一格：真窗口没有 `话术来源` 表（`合消息` 那张表整份来自剧本，
 * 这边是空的），所以序号不参与任何替换；留着是因为它是「这条消息在会话里的位置」
 * 这个契约字段，而 AI 代发那句话就发生在锚那一下。
 */
function buildAutoMessage(
  会话: Session,
  锚: ChatMessage,
  文: string,
  署名: string,
  第几条 = 0,
): ChatMessage {
  return {
    ...buildAgentMessage(会话, 文, 锚.消息序号),
    // 自己的 id：**不能沿用 `buildAgentMessage` 那个**，那个是「客服在界面上发了一条」
    // 的记号，会和客服真发出去的那条撞上（`MessageList` 拿它当 key）。
    //
    // ⚠️ **`第几条` 是 2026-10-06 补的，不能省。** 一条轮次里可能不止一句代发的话
    // （无卡无稿那一轮是按日志原话一句一条地补的，一轮里有两句客服话的实测占 63/482）。
    // 只拿锚的下标当 id 的话，同一轮里那几条**共用一个 key** —— 而 `MessageList`
    // 就是拿它当 key 的，React 那边表现为少画一条、或者两条互相顶掉，
    // 而屏幕上不报任何错。
    message_id: `${会话.会话ID}${本地记号}AI-${锚.消息序号}-${第几条}`,
    发送时间: 锚.发送时间,
    角色: 'AI',
    发送方: 'Primer',
    署名,
  }
}

/**
 * 给真窗口那张主卡补上 `已代发`。
 *
 * 后端有一份 `_已代发`（`判定.py`），但它**是从对话里挑 `角色 == "AI"` 的消息** ——
 * 真窗口的日志是客服端的导出，里头一条 AI 行都没有，所以那份恒为空。而右栏那句
 * 「已代发 · 以你的名义」恰恰是**必须说**的那种话：顾客那边收到了话，客服这边右栏
 * 一片安静，等顾客回一句「你刚才不是说可以退吗」就彻底对不上（`SentList` 的文档串）。
 *
 * 所以真窗口这一档由前端把**它自己造出来的那几条**（`真代发`）配进去，1:1 对得上：
 * 聊天区里插了几条，右栏就列几条。
 *
 * ⚠️ **接口给了就不动它。** 逐字段「接口非空就用接口的」是这一整条链的规矩
 * （`data/判定.ts` 文件头）。将来日志里真有 AI 行了，后端那份才是权威 —— 它给得出
 * 每句话配的是哪几条依据（`_已代发` 那段「依据是配出来的」），这份给不出。
 */
function 带代发(卡: Advice | undefined, 话们: ChatMessage[] | undefined): Advice | undefined {
  if (!卡 || 卡.已代发?.length || !话们?.length) return 卡
  return {
    ...卡,
    // `依据` 留空：真窗口上拿不到「这一句话引了哪几条」（接口只回报本轮的六源命中，
    // `api/证据.py` 的模块文档串专门说了那不是一回事）。空着一眼看得出没有，编一个
    // 出处上去看不出来。`SentList` 那一行空了就不渲染。
    已代发: 话们.map((m) => ({ 内容: m.message_text, 署名: m.署名 ?? '', 依据: [] })),
  }
}

