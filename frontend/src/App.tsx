/** 客服发出的消息。字段从会话最后一条消息沿用，只覆盖真正变化的部分。 */
function buildAgentMessage(session: Session, text: string, 序号: number): ChatMessage {
  const template = session.消息.at(-1)
  const now = new Date()
  const pad = (n: number) => String(n).padStart(2, '0')

  return {
    会话ID: session.会话ID,
    消息序号: 序号,
    message_id: `${session.会话ID}-local-${序号}`,
    发送时间: `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(
      now.getHours(),
    )}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`,
    角色: '客服',
    买家昵称: session.买家昵称,
    发送方: `${session.店铺}:${agent.昵称}`,
    店铺: session.店铺,
    scene_major: template?.scene_major ?? '',
    scene_minor: template?.scene_minor ?? '',
    is_target_buyer_message: false,
    message_text: text,
    内容类型: '文本',
    chat_content: JSON.stringify([{ index: 0, content: text }]),
    category: template?.category ?? 'service',
    image_path: '',
    关联订单号: session.订单?.订单号 ?? '',
    关联工单号: session.工单?.ticket.工单号 ?? '',
  }
}

export default function App() {
  const [sessions, setSessions] = useState<Session[]>(seedSessions)

  /**
   * 开屏停在**第一条演示线**上，不是列表第一条。
   *
   * 演示是从 S3「顾客 A 进线」开始的，前面那几条静态会话不在片子里，选中它们
   * 只会让演示的人多一次点击。更要紧的是先例库计数：S11 要的是「56 → 57 轻跳」，
   * 而**非当前会话一律按演到底算**（见 `格数`）—— 开屏要是停在一条没有剧本的会话
   * 上，线一就成了「非当前」，一进来计数就是 57，那一跳就白跳了。
   */
  const [activeId, setActiveId] = useState(
    seedSessions.find((s) => 剧本表[s.会话ID])?.会话ID ?? seedSessions[0]?.会话ID ?? '',
  )

  /**
   * 演示过程中**客服现场发出去的消息**，按会话分开存（见 `剧本.现场消息`）。
   *
   * 只有**有剧本的会话**用它。普通会话的消息直接往 `sessions` 里长，不需要这一份。
   *
   * 为什么不直接塞进 `sessions`：那样它就成了 `活.消息`，而 `演到` 把 `活.消息`
   * 一律排在剧本消息**后面**。客服停在第 5 步发的那句，走到第 8 步就会跑到
   * 「好的，谢谢啦」后面去 —— 时间线当场就乱。记着步号，它才插得回原位。
   */
  const [现场消息表, set现场消息表] = useState<Record<string, 现场消息[]>>({})

  /**
   * `POST /api/判定` 取回来的结果，按 `会话ID → 轮次` 存着。
   *
   * **按轮缓存，不是只存最后一份。** 往回拖进度时右栏要跟着退回去 —— 只看
   * 最后一次的话，拖回第 3 步右栏还挂着第 7 步的报备。同一轮问一次就够了，
   * 判定几秒钟一次，来回拖不该反复打。
   */
  const [判定表, set判定表] = useState<Record<string, Record<number, 判定响应>>>({})

  /**
   * 接口回来的那张交接包，按 `会话ID` 存。
   *
   * **不往 `Session` 上加字段。** 判定的产物就是这么放的（`判定表` 是
   * `会话ID → 轮次` 的一张平行表），而且 `types/index.ts` 归接口线独占 ——
   * 往 `Session` 上加一个 `交接包`，后端 `tests/test_schemas.py` 那条镜像断言
   * 当场红（它要求两边的字段集**只差 `草稿` 一个**）。
   *
   * 一个会话只存一张：报备和转交在这个演示里是互斥的两条路，真同时发生时后一张
   * 盖掉前一张，而右栏本来就只画得下一张。
   */
  const [交接包表, set交接包表] = useState<Record<string, 交接包>>({})

  /**
   * 判定接口答不上来（后端没起／超时）。判定是**一轮一问**的，所以它自己会恢复：
   * 下一轮再问一次，答上来就灭掉。
   */
  const [判定未连, set判定未连] = useState(false)

  /**
   * `GET /api/会话列表` 没答上来。**和判定那个分开存。**
   *
   * 合成一个布尔的话，后一个成功的会把前一个失败的痕迹擦掉：会话列表拉失败了，
   * 左栏悄悄只剩两条演示会话，而屏幕上看不出少了一百多条 —— 那正是这个标记
   * 要防的那种错。列表只拉一次，所以它一旦亮起来就不会自己灭。
   */
  const [列表未连, set列表未连] = useState(false)

  /**
   * 动作接口（报备／转交／发送）**没答上来过**的那些会话。
   *
   * **按会话存，不存一个全局布尔。** 全局的话，后一条会话成功了会把前一条的
   * 痕迹擦掉 —— 那是 `列表未连` 那段注释说的同一件事，只是换了个方向；而这一条
   * 更要紧：兜底造的那张单子**还在屏幕上摆着**，标记却写着「已连」。
   *
   * 同一个会话里下一次动作真打通了就灭掉：它答的是「这一屏的正路通没通」，
   * 不是「历史上出过事没有」。
   */
  const [动作兜底, set动作兜底] = useState<Record<string, true>>({})

  /**
   * 后端**明确拒了**（404／409／400）的那句话。`undefined` = 没有。
   *
   * **和上面那三个分开。** 那三个是「后端没答上来，界面回落剧本」，这个是
   * 「后端答了、说这件事办不了」—— 混在一起的话，一张被后端拒掉的单子会被
   * 当成兜底正常演出来，而屏幕上那两个信号（兜底标记 ＋ 那张单子）看着都成立。
   */
  const [动作被拒, set动作被拒] = useState<string>()

  /**
   * 已经问过的 `会话ID-轮次`。
   *
   * 拦的是**同一格的重复请求**：这个 effect 的依赖里有 `已播格数`，而拖动、
   * 自动播放、点按钮都会改它。没有这一层，一次演示会打出十几次判定 ——
   * 每次都是三次模型调用。
   *
   * 失败时**从集合里删掉**，所以「后端晚起一会儿」不至于让整场演示再也接不上：
   * 下一步会再试一次。
   */
  const 已问过 = useRef(new Set<string>())

  const 剧本 = 剧本表[activeId]
  const 活条数 = sessions.find((s) => s.会话ID === activeId)?.消息.length ?? 0

  /**
   * 播放器的总格数。**有剧本的会话要按步数，不能按消息条数。**
   *
   * 有剧本的会话，一格是**剧本的一步**。一步带不带消息不影响格子数：没有消息的
   * 步（「六源扫描」「逾期浮出」）照样占一格，照样要停下来让人讲。这正是不能按
   * 消息条数数的原因。
   *
   * 没有剧本的会话一条消息一停，总格数就是消息条数。
   *
   * 每一格停多久不在这儿 —— 那是播放器上的 `1s / 3s / 5s` 那一档，见 `use播放器`。
   * 早先这里给的是一张「每步各自的间隔」表，**那张表已经删了**：速度现在全片
   * 统一，节奏由演示的人当场挑。
   */
  const 总格数 = 剧本 ? 剧本.事件.length : 活条数

  /**
   * 第几格要停下来等人点按钮（见 `剧本.停格`）。
   *
   * `useMemo` 不是性能考虑，是**正确性**：这一份进 `usePlayer` 定时器 effect 的
   * 依赖数组，每次渲染现造一个 Map 的话，每次渲染都会把定时器清掉重排，播放就
   * 被自己的渲染拖慢了。剧本是模块常量，所以这个 Map 一个会话里只建一次。
   */
  const 停格表 = useMemo(() => 停格(剧本), [剧本])

  const 播放 = usePlayer(总格数, 停格表)

  /**
   * 走到新的格子就问一次判定。
   *
   * **`当前时间` 传的是 `演示此刻`（2026-09-29 10:06），不是现在。** 让后端取
   * 服务器时间的话，演示的「今天」和录制的「今天」对不上，H3 承诺逾期不命中 ——
   * 而屏幕上和「今天没逾期」一模一样，看不出是没算还是没到。
   */
  useEffect(() => {
    const 轮 = 当前判定轮次(剧本, 播放.已播格数)
    if (!剧本 || 轮 === undefined) return

    const 键 = `${activeId}-${轮}`
    if (已问过.current.has(键)) return
    已问过.current.add(键)

    void 取判定(activeId, 轮, 演示此刻).then((答) => {
      if (!答) {
        已问过.current.delete(键)
        set判定未连(true)
        return
      }
      set判定未连(false)
      set判定表((prev) => ({
        ...prev,
        [activeId]: { ...prev[activeId], [轮]: 答 },
      }))
    })
  }, [剧本, activeId, 播放.已播格数])

  /**
   * 拉一次真实会话列表（138 条），和剧本那两条合并。
   *
   * **失败时什么都不做**，左栏留着 `seedSessions` —— 那正好是片子的全部，演示
   * 照常。这条兜底比右栏那条更隐蔽：少了一百多条会话，屏幕上看着完全正常
   * （两条演示线本来就是主角），所以靠 `列表未连` 在开发态留痕迹。
   *
   * **按 `会话ID` 保留已经有状态的那一份，不整表换掉。** 这个请求有 850KB，
   * 后端刚起或者网慢的时候可能几百毫秒才回来 —— 那时演示的人可能已经点过
   * 「报备」了。整表换掉的话 `prev` 里那份带报备态的会话被模块常量盖回去，
   * 右栏的交接包**当场消失**，而屏幕上不会报任何错。
   */
  useEffect(() => {
    void 取会话列表().then((答) => {
      if (!答) {
        set列表未连(true)
        return
      }
      set列表未连(false)
      setSessions((prev) => {
        const 活的 = new Map(prev.map((s) => [s.会话ID, s]))
        return 合会话列表(答).map((s) => 活的.get(s.会话ID) ?? s)
      })
    })
  }, [])

  /**
   * 这条会话该演到第几格。**当前会话按真实进度，其余一律演到底。**
   *
   * 抽出来是因为 `展示` 和先例库计数要按同一套规矩算 —— 两处各写一遍的话，
   * 有一处改了另一处没跟上，「列表里都演完了」和「先例库还差一条」就会打架。
   */
  const 格数 = (s: Session): number => {
    const 本 = 剧本表[s.会话ID]
    if (s.会话ID !== activeId) return 本 ? 本.事件.length : Number.POSITIVE_INFINITY
    return 播放.已播格数
  }

  /**
   * 顶栏那个先例库计数。
   *
   * **要把所有剧本都算进来，不能只看当前这一条。** 演示到「换一位顾客」时
   * 会切到线二，那时线一已经入过库了 —— 只看当前会话的话，一切走计数就从
   * 57 掉回 56，屏幕上「存进去了」和「又没了」同时发生。
   *
   * 非当前会话按演到底算，和 `展示` 同一套规矩：在这套演示里，它们本来就是
   * 全演出来的。
   */
  const 先例库总数 = sessions.reduce(
    (和, s) => 和 + 已入库条数(剧本表[s.会话ID], 格数(s)),
    先例库基数,
  )

  /**
   * 顶部指标条。**只有「先例库」那一项是活的** —— 演到「入先例库」那一步
   * 自己从 56 跳到 57。剩下的全是当日常量，混在同一个数组里没人看得出哪个
   * 能动，所以那个计数单列了一个 `先例库指标`，只在这儿拼进来。
   */
  const 指标 = useMemo(
    () => [先例库指标(先例库总数), ...shopMetrics],
    [先例库总数],
  )

  /**
   * 渲染用的会话列表。
   *
   * 屏幕上演到哪儿，由播放器的进度决定 —— **两种会话都归它管**：
   *   - 有剧本：进度的单位本来就是步，直接喂给 `演到`，右栏跟着一起变；
   *   - 没剧本：一格一条，直接从消息列表里截前 N 条。
   *
   * 这里**不做步和条的换算**。早先中间隔了一层 `条到步`，那是因为当时那份剧本
   * 恰好一步一条消息，换算看着是恒等式；换成有「空步」的剧本之后，它会拿步数
   * 当条数再换一次，把整拍空步跳过去 —— 右栏的报备、逾期、入库全演不出来。
   *
   * 普通会话不能也走剧本那条路。给它现造一份「一条消息一步」的剧本看着更统一，
   * 但那份剧本的消息和 `活.消息` 是同一批 —— `演到` 会把 `活.消息` 再追加一遍，
   * 屏幕上每条消息出现两次。
   *
   * 「当前会话按真实进度、其余演到底」这条规矩在 `格数` 里，不在这儿 ——
   * 先例库计数也要用它。非当前会话演到底是因为它们只是列表里的一行摘要，
   * 没播完会显示成一条空会话，演示的人反而找不到它。当前会话按真实进度走，
   * 所以选中它时摘要会先空一下再随播放长回来 —— 这个「重演」的观感正是想要的。
   */
  /**
   * 把接口的判定结果贴到演出来的会话上。
   *
   * **贴的是「内容」，不是「什么时候露哪几块」** —— 后者归剧本
   * （见 `剧本事件.判定轮次`）。三块各按各的规矩合：
   *   - `顾客情况` 按 `标签` 逐行对齐，**行数与顺序全取剧本**（第 1 步只该露三行，
   *     还有「查历史中…」那个演示道具，接口答不出也不该答）；
   *   - `建议` 逐字段，接口空的字段留剧本的（`话术` 现在恒为 `None`）；
   *   - `本轮处置` 按 `输出` 补位 —— 剧本说这一步露几条，就从接口取几条
   *     （见 `合本轮处置`，那一头写着为什么不能整块替换）。
   *
   * 拿不到结果就原样返回。**这是兜底，不是失败处理**：后端没起时右栏回到剧本
   * 那份，屏幕上仍是完整的一屏。录片子的时候后端一抖不至于开天窗，而缺的那几块
   * 在开发态有痕迹（见 `PrimerPanel`）。
   */
  const 贴判定 = (s: Session, 本: 剧本类型 | undefined): Session => {
    const 轮 = 本 ? 当前判定轮次(本, 播放.已播格数) : undefined
    if (轮 === undefined) return s
    const 答表 = 判定表[s.会话ID]
    const 答 = 答表?.[轮]
    if (!答) return s

    // `本轮处置` 要**跨轮**攒：第 7 步那一屏是两轮加起来的，而接口一次只答一轮。
    // 取到当前轮为止、按轮次升序 —— 顺序错了「本轮处置」里几条主张的先后就乱了。
    const 各轮处置 = Object.keys(答表)
      .map(Number)
      .filter((n) => n <= 轮)
      .sort((a, b) => a - b)
      .map((n) => 答表[n].本轮处置)

    return {
      ...s,
      顾客情况: 合顾客情况(s.顾客情况, 答.顾客情况),
      建议: 合建议(s.建议, 答.主卡),
      本轮处置: 合本轮处置(s.本轮处置, 各轮处置),
    }
  }

  const 展示: Session[] = sessions.map((s) => {
    const 本 = 剧本表[s.会话ID]
    const 格 = 格数(s)
    const 演过的 = 本
      ? 演到(s, 本, 格, 现场消息表[s.会话ID] ?? [])
      : { ...s, 消息: s.消息.slice(0, 格) }
    // 判定只对**当前会话**取（别的会话不发起请求），所以也只贴当前会话。
    return s.会话ID === activeId ? 贴判定(演过的, 本) : 演过的
  })

  const active = 展示.find((s) => s.会话ID === activeId) ?? null

  /**
   * 报备卡现在是哪个状态（见 `AdviceCard` 的 `报备态`）。
   *
   * **从「演到第几步」和现场消息推出来，不另存。** 三个状态分别对应：
   *   - `等审批`：报备交上去了还没回来 —— 第 7 步报备之后、第 8 步之前；
   *   - `等发送`：审批回来了，话压在手上等客服点［一键发送］—— 第 8 步；
   *   - `已答复`：那句话发出去了。
   *
   * 为什么扫一整段而不是只看当前这一步有没有 `待发`：第 8 步发完之后时间线走到
   * 第 9 步，而第 9 步没有 `待发` —— 只看当前步的话，卡片会在顾客道谢那一下从
   * 「审批回来了」倒回「等待组长审批」，屏幕上就成了「刚发完又回到等审批」。
   *
   * 判「发过没有」用的是 `message_id`：`待发` 是模块常量，发出去的那一份进了
   * `现场消息表`，两边同一个 ID。往回拖不会把它变回没发 —— 也没有发出去的话
   * 还能收回来的道理。而在第 7 步上它又是「等审批」，因为那句话还没进消息流
   * （`演到` 按步裁），两处看到的是一致的。
   */
  /** 这条会话已经现场发出去的消息 ID。判「那句话发过没有」用它。 */
  const 已发现场 = useMemo(
    () => new Set((现场消息表[activeId] ?? []).map((现) => 现.消息.message_id)),
    [现场消息表, activeId],
  )

  const 报备态 = useMemo((): 报备态 => {
    let 见过待发 = false
    for (let i = 0; i < 播放.已播格数; i++) {
      const 待发 = 剧本?.事件[i]?.待发
      if (!待发?.length) continue
      见过待发 = true
      if (待发.some((m) => !已发现场.has(m.message_id))) return '等发送'
    }
    return 见过待发 ? '已答复' : '等审批'
  }, [剧本, 播放.已播格数, 已发现场])

  /**
   * 审批回来、**还没发出去**的那句话。
   *
   * 门开在 `报备态` 上而不是自己再判一遍：它等于「等发送」时，当前这一步
   * 必然就是那个带 `待发` 的步，直接取就是了。
   */
  const 待发句 =
    报备态 === '等发送'
      ? 剧本?.事件[播放.已播格数 - 1]?.待发?.find((m) => !已发现场.has(m.message_id))
      : undefined

  /**
   * 这一屏哪几块是剧本兜的底，拼给右栏顶上那行常驻标记（见 `PrimerPanel.兜底`）。
   *
   * **顺序写死在这儿，不按出事的先后。** 标记只有一行小字，同一件事每次读到的
   * 顺序都该一样 —— 不然它就成了每次都要重新读的东西，而它唯一的作用是扫一眼。
   *
   * `动作` 取当前会话那一条，不取全局：兜底造的那张单子是摆在**这一屏**上的，
   * 换一条会话就该按那条会话的实际情况说话。
   */
  const 兜底: 兜底来源[] = []
  if (判定未连) 兜底.push('判定')
  if (列表未连) 兜底.push('会话列表')
  if (动作兜底[activeId]) 兜底.push('动作')

  /**
   * 切会话就把播放器归零。
   *
   * 归零放在这里而不是 `usePlayer` 的 effect 里：切会话是**这个点击**造成的，
   * 在造成变化的地方顺手清掉，比等渲染完再补一次 setState 少一轮渲染，也不会
   * 先闪一帧上一条会话的进度。顺带一个好处 —— 重复点当前会话 = 重播。
   */
  const 选会话 = (id: string) => {
    setActiveId(id)
    播放.重置()
  }

  /**
   * 改**指定的**那条会话。插件产出的一切状态（草稿、报备、转交）都落在会话上。
   *
   * 为什么按钮那边要显式传 ID：三个动作按钮现在都要 `await` 一轮接口，回来时
   * `activeId` 可能已经换人了。默认写当前那条的话，A 的报备单会落到 B 头上，
   * 而屏幕上看着完全正常 —— 和这一单在防的其它几件事是同一个形状。
   */
  const 落一笔 = (会话ID: string, fn: (s: Session) => Session) => {
    setSessions((prev) => prev.map((s) => (s.会话ID === 会话ID ? fn(s) : s)))
  }

  /** 改**当前**这条会话。不跨 `await` 的地方都用它。 */
  const patch = (fn: (s: Session) => Session) => 落一笔(activeId, fn)

  /**
   * 这轮「客服说出去的那句话」兑现的是哪几条主张。**按 `输出` 挑，不按下标** ——
   * 两边的下标不是一回事（见 `合本轮处置`）。
   */
  const 兑现的 = (输出: OutputKind): string[] =>
    (active?.本轮处置 ?? []).filter((d) => d.输出 === 输出).map((d) => d.id)

  /**
   * 把这句发出去的话报给后端留痕（`POST /api/会话/{sid}/发送`）。
   *
   * **不挡着发送。** 话是客服真按下去了的，留痕是事后补的账 —— 那边慢、或者
   * 干脆没起，都不该让这一句发不出去。所以这儿 fire-and-forget，只把结果记进
   * 右栏顶上那行标记。
   *
   * **一条主张都没兑现时不打。** 普通会话（138 条真会话）右栏本来就没判过，
   * `本轮处置` 是空的 —— 打了就是一次必然 409 的往返，还会把那句「还没判定过」
   * 顶到屏幕上，而它跟客服刚做的这件事没有任何关系。
   */
  const 记一笔发送 = (话术: string, 输出: OutputKind) => {
    const 编号 = 兑现的(输出)
    if (!编号.length) return
    void 记发送(activeId, 编号, 话术).then((果) => {
      if (果.态 === '成') return
      // `未连` 和 `后端说不` 分开记：前者是说「这一屏的正路没通」，后者是说
      // 「后端不认这条话术兑现的主张」—— 两个的排查方向正好相反。
      if (果.态 === '未连') set动作兜底((prev) => ({ ...prev, [activeId]: true }))
      else set动作被拒(`发送没记上 —— ${果.说明}`)
    })
  }

  /**
   * 客服按了输入框上那个「发送」。**有剧本和没剧本的会话走的不是同一条路。**
   *
   * 有剧本的会话（演示会话）：这条是**现场消息**，得记着停在第几步发的，才能照
   * 顺序插回原位（见 `现场消息`）。它**不改 `摘要` / `最近时间`** —— 那两样在
   * 剧本里是叙事的一部分（第 9 步要写「好的，谢谢啦」），而现场消息带的是真实
   * 时钟上的时间戳，写进去就等于把「2026-10-01 14:23」塞进一条 9/29 的时间线。
   * 有剧本的会话，左边列表那一行归剧本管。
   *
   * 普通会话：还是老办法，直接往 `sessions` 里长。
   *
   * 两种都要接着放：第 5 步正停着等客服按这一下（`剧本.等点击`）。点了发送，
   * 这一拍才算走完。
   */
  const handleSend = (text: string) => {
    const 内容 = text.trim()
    if (!内容) return

    if (剧本 && active) {
      const 条 = buildAgentMessage(active, 内容, active.消息.length + 1)
      set现场消息表((prev) => ({
        ...prev,
        [activeId]: [...(prev[activeId] ?? []), { 步: 播放.已播格数, 消息: 条 }],
      }))
      // 发出去就把草稿清掉，否则输入框里还挂着刚发的那句话。
      patch((s) => ({ ...s, 草稿: '' }))
      记一笔发送(内容, '客服点发送')
      播放.继续()
      return
    }

    patch((s) => {
      const sent = buildAgentMessage(s, 内容, s.消息.length + 1)
      return {
        ...s,
        消息: [...s.消息, sent],
        草稿: '',
        摘要: 内容,
        最近时间: sent.发送时间.slice(5, 16),
      }
    })
    记一笔发送(内容, '客服点发送')
  }

  /**
   * 主卡［一键发送］：把这一步备好的话（`剧本事件.待发`）发出去。
   *
   * 这就是报备走完一圈的那一下（脚本 S11）。搬进 `现场消息表` 之后，它和客服
   * 自己发的一条没有区别 —— 也该没有：报备走到底，客服也就是「按了一下」。
   *
   * 这里**写 `摘要` / `最近时间`**（第 5 步那条现场消息不写）：这句是从剧本里
   * 搬出来的，自带 9/29 10:08 的时间戳，写进列表那一行正好接上第 9 步。
   */
  const handleSendPending = () => {
    const 待发 = 剧本?.事件[播放.已播格数 - 1]?.待发
    if (!待发?.length) return
    const 步 = 播放.已播格数
    set现场消息表((prev) => ({
      ...prev,
      [activeId]: [
        ...(prev[activeId] ?? []),
        ...待发.map((m) => ({ 步, 消息: m })),
      ],
    }))
    patch((s) => ({
      ...s,
      草稿: '',
      摘要: 待发[0].message_text,
      最近时间: 待发[0].发送时间.slice(5, 16),
    }))
    // 这句是 ③报备 走完一圈发出去的 —— 所以兑现的是 `报备` 那几条主张，
    // 不是客服手上那条（`兑现的` 按输出挑，正是为了把这两种分开）。
    记一笔发送(待发[0].message_text, '报备')
    播放.继续()
  }

  /**
   * 三个主卡按钮都做两件事：改会话状态，然后**接着放**。
   *
   * 后半句是给「停在这一步等你点」用的（见 `剧本.等点击`）：点了按钮时间线就
   * 往下走，演示的人不用再去够播放键。没停在那一格时 `继续` 什么也不做，所以
   * 顺手点一下卡片不会把时间线带走。
   */

  /**
   * 主卡［采用］：只把话术带进输入框 —— **不发**。
   *
   * 发不发由客服决定。他可能改，也可能像脚本 S7 那样改出个禁语被拦下来。
   *
   * 所以这里**不调 `播放.继续()`**：那会让时间线在客服还没按发送时就往下走，
   * 把「他按了发送」这一拍抢掉。第 4 步的续放交给 `handleSend`。
   */
  const handleUseScript = () => {
    const 话术 = active?.建议?.话术
    if (!话术) return
    patch((s) => ({ ...s, 草稿: 话术 }))
  }

  /**
   * 报备／转交都走这儿：**打接口，拿那张自动带全的交接包。**
   *
   * 三个态各走各的路（见 `动作结果`），分得清是这里唯一要做的事：
   *
   *   - **接口回了** → 整张包进 `交接包表`，单号用接口那个；
   *   - **接口没答上来** → 本地拼个号（`兜底单号`），`动作兜底` 点亮这个会话，
   *     整张包交给 `PrimerPanel` 那个 `?? 建交接包(...)` 兜出来。**这一条必须
   *     能演完**（工单 §五 验收 4：把后端关掉，整条线再演一遍，且看得出是兜底）；
   *   - **后端说不**（404／409） → **不造单子，也不往下走**。回落本地那张的话，
   *     屏幕上会出现一张后端刚刚拒掉的单子，而它看着和真的一模一样。
   *
   * 两条造出单子的路**都要写 `session.报备`／`转交`**：`AdviceCard` 认它画报备
   * 卡，兜底那条路的单号也是从那儿取的（`建交接包` 第 55 行）—— 不写，兜底当场失效。
   */
  const 走动作 = async (动作: '报备' | '转交') => {
    const 会话ID = activeId // 先钉住：`await` 之后它可能已经换人了。
    const 果 = await 取交接包(会话ID, 动作)

    if (果.态 === '后端说不') {
      set动作被拒(`${动作}没办成 —— ${果.说明}`)
      return
    }
    set动作被拒(undefined)

    const 单号 = 果.态 === '成' ? 果.值.单号 : 兜底单号(会话ID)
    if (果.态 === '成') {
      set交接包表((prev) => ({ ...prev, [会话ID]: 果.值 }))
      set动作兜底((prev) => {
        if (!prev[会话ID]) return prev // 没亮过就别造一个新对象。
        const 其余 = { ...prev }
        delete 其余[会话ID]
        return 其余
      })
    } else {
      set动作兜底((prev) => ({ ...prev, [会话ID]: true }))
    }

    落一笔(会话ID, (s) =>
      动作 === '报备'
        ? { ...s, 报备: { 等待分钟: 0, 工单号: 单号 } }
        : { ...s, 转交: { 工单号: 单号 } },
    )
    播放.继续()
  }

  /** 主卡「一键报备」：对话还在客服手里，顾客无感知。 */
  const handleReport = () => void 走动作('报备')

  /** 主卡「立即转交」：对话交出去，客服不再跟进。 */
  const handleHandover = () => void 走动作('转交')

  return (
    <div className="flex h-full w-full overflow-hidden">
      <IconRail />
      <SessionPanel sessions={展示} activeId={activeId} onSelect={选会话} />
      <ChatPanel
        session={active}
        agent={agent}
        metrics={指标}
        onSend={handleSend}
        onDraftChange={(text) => patch((s) => ({ ...s, 草稿: text }))}
        剧本={剧本}
        播放={播放}
        // 普通会话的提示行要显示「刚出现的那条」。截断之后最后一条就是它。
        // 有剧本的会话不走这个 —— 它的提示行是剧本的标题和备注。
        当前消息={剧本 ? undefined : active?.消息.at(-1)}
      />
      <PrimerPanel
        session={active}
        onUseScript={handleUseScript}
        onReport={handleReport}
        onHandover={handleHandover}
        onSendPending={handleSendPending}
        报备态={报备态}
        待发句={待发句}
        /* 接口回来的那张。拿不到时 `PrimerPanel` 自己回落 `建交接包` —— 工单 §一 拍 1.1 乙。 */
        接口交接包={交接包表[activeId]}
        兜底={兜底}
        动作被拒={动作被拒}
        /* 判定只接了两条演示线，其余 138 条一次都没跑过 —— 见 `PrimerPanel.未判定`。 */
        未判定={!剧本}
      />
    </div>
  )
}
