"""一条主张 → 一个权限条目编号（第 2 层「这件事归谁办」）。

# 为什么换掉了关键词

`rules/permissions.认权限` 是子串匹配（`关键词` 列表里命中，取最长的那条）。
它认得出「漏发」这种**和表里用词一模一样的**主张，认不出顾客真会说的话：
「上次那个赠品你还没给我发」里没有「漏发」两个字，认不上；
而右栏不会显示任何异常 —— 第 2 层静默判成「未列明」，然后**继续往第 3 层走**
（`permissions.权限判定.能否继续第3层`）。该报备的没报备，看起来一切正常。

# 为什么不走向量

权限矩阵只有 22 行、其中可认的 17 行。17 行上的向量检索是负优化，还要多背
一个 embedding 模型、一层索引、一份「索引和表不同步」的新故障模式。
**每次全塞 prompt**（同 `认口径.py` 那段）。

# 只喂「可认」的 17 行

`可认=False` 那 5 行（`E01–E04`／`X01`）描述的是**超额度的后果**，不是顾客会说的话。
它们不进 prompt，也不在 `_挑` 的合法编号里 —— **不收的就不给看。**
给了再指望模型别选，是在赌它每次都听话。

# 够不着模型 → 退回关键词（**不是**退回 `None`）

这一条和 `认口径.py` 正相反，也是这个文件最容易看错的地方。

`认口径` 够不着模型就返回 `None` ＝「认不出」，这次调用白跑，右栏少一行依据；
`认权限` 返回的 `None` 有**下游后果** —— 未列明，继续第 3 层。
所以够不着模型时退到 `rules.permissions.认权限`（那条老路还在，没删）：
`工单交接_给模型线_C.md` §八 第 3 条，**离线演示靠它。**

> ⚠️ **退回只在 `LLM不可用` 时发生，模型回 `NONE` 通常不算。** 模型回 `NONE` 是
> 一个**真答案**（系统提示里那句「拿不准就回 NONE」），拿关键词去覆盖它等于
> 把关键词的错认又放回来 —— 而换掉关键词正是这个文件存在的理由。唯一的例外是
> 代码能确认「赠品类对象 + 明确缺失」时，固定护栏会压过 `NONE`，否则漏发会
> 静默落到第 3 层。
>
> **一个例外（2026-10-05）：本轮的闸门行在场时（`E05` 活着的回合），词表跟着
> 一起说话** —— 那条规矩在 `permissions._认到条目` 里，不在这个文件里。
> 理由和这里的原则不冲突：闸门行要判的那件事（「有一件答应过的事逾期了」）
> **句子里没有**，是 `承诺时限` 比出来的，所以「模型回 NONE」对那几行并不算
> 真答案。实测往 prompt 里补那件事越补越糟（「要找主管」「赠品追加」都被洒成
> E05），所以补在词表那一侧。没有闸门行的回合，上面这条契约照旧。
"""

from __future__ import annotations

from collections.abc import Sequence

from ..rules.permissions import 权限条目, 认权限 as 关键词认权限
from .客户端 import LLM不可用, 问模型, 问答函数

系统提示 = (
    "你在把电商客服场景里的一条「主张」认到最贴切的一条权限条目上。\n"
    "只回一个权限条目编号（如 L01），或回 NONE。**不要解释，不要回别的字。**\n"
    "拿不准就回 NONE —— 认错比认不出更糟。"
)

#: 表的表头。列名和 `权限条目` 的字段名对齐，模型看到的和代码里读的是同一套词。
_表头 = "编号 | 事项 | 层级 | 限额 | 去向"

#: 这些是业务上方向相反、但模型最容易混在一起的两类表达。
#:
#: 「赠品没看到／还没给我发」是漏发（L01）；「再追加一个／多送」才是追加
#: （L03）。L03 的关键词里有一个宽泛的「赠品」，只靠子串会把两件相反的事
#: 判到同一行。这里保留一条小而明确的语义护栏：只处理“赠品类对象 + 明确缺失”，
#: 不把所有近似表达都硬猜成补发。
_赠品类词: tuple[str, ...] = ("赠品", "小样", "礼物", "赠送")
_缺失表达: tuple[str, ...] = (
    "漏发",
    "少发",
    "没收到",
    "未收到",
    "没有收到",
    "没看到",
    "未看到",
    "没见到",
    "没到",
    "未到",
    "没给我发",
    "还没给我发",
    "没有给我发",
    "没发给我",
    "未发给我",
    "尚未发出",
    "没发",
    "未发",
    "缺少",
    "缺件",
)
_追加表达: tuple[str, ...] = (
    "追加",
    "多送",
    "加送",
    "再要",
    "多给",
    "额外要",
    "再来",
)


def _明确漏发编号(
    主张: str, 可认的: Sequence[权限条目]
) -> str | None:
    """返回一条足够明确的漏发护栏，否则交给模型。"""
    文本 = "".join(主张.split())
    if not any(词 in 文本 for 词 in _赠品类词):
        return None
    if not any(词 in 文本 for 词 in _缺失表达):
        return None
    # 同一句同时说“没收到”和“再追加”时可能是两个主张，不能替模型合并。
    if any(词 in 文本 for 词 in _追加表达):
        return None
    return next((k.编号 for k in 可认的 if k.编号 == "L01"), None)


def 认权限(
    主张: str,
    权限矩阵: Sequence[权限条目],
    *,
    问: 问答函数 = 问模型,
) -> str | None:
    """把一条主张认到某个权限条目编号上，**认不出返回 `None`**。

    返回的是**编号**（`str`）不是条目，和 `认口径` 同构。

    ⚠️ **`权限矩阵` 是调用方递下来的那张活矩阵**（`permissions.活矩阵` 滤过），
    不是模块常量 `权限条目表` —— 2026-10-04 之前 `deps` 里有个转接头把整张表
    提前绑死，于是这里挑得中 `E05`、而回头在活矩阵里查不到它，落成未列明、
    `L01` 的限额被整个绕过。现在模型看到的、`_挑` 收的、够不着时退回关键词
    用的，是**同一张表**。

    矩阵里一条可认的都没有（空表也算）直接返回 `None`，**一次网络调用都不发**。
    """
    可认的 = [k for k in 权限矩阵 if k.可认]
    if not 可认的:
        return None
    明确漏发 = _明确漏发编号(主张, 可认的)

    try:
        回答 = 问(_提示(主张, 可认的), 系统提示)
    except LLM不可用:
        # 够不着模型 → 退回关键词那条老路。**不抛** —— 抛的后果是演示当天
        # 模型一抖、`POST /api/判定` 直接 500、右栏整个白掉。
        #
        # 读的是**传进来的这张矩阵**，不是模块里的 `权限条目表`：调用方喂小表
        # 时不能拿到一个它没定义的编号。所以 `可认的` 往下传，不是原表。
        if 明确漏发 is not None:
            return 明确漏发
        条目 = 关键词认权限(主张, 可认的)
        return 条目.编号 if 条目 is not None else None

    # 模型仍然照常被调用并留痕；遇到这组高代价的方向冲突时，明确规则压过
    # 模型的 L03／NONE，避免“漏发”被误判成“追加”或静默掉到第 3 层。
    return 明确漏发 or _挑(回答, 可认的)


def _提示(主张: str, 可认的: Sequence[权限条目]) -> str:
    """权限表 ＋ 主张。**可认的 17 行全在里面**，不做筛选。

    每行给的是「编号 | 事项 | 层级 | 限额 | 去向」—— 事项是给人看的全称，
    只给编号等于让模型背一张它没见过的表；去向是它判错的代价所在，也给它。
    """
    行们 = "\n".join(
        f"{k.编号} | {k.事项} | {k.层级} | {k.限额} | {k.去向.value}" for k in 可认的
    )
    return f"权限表：\n{_表头}\n{行们}\n\n主张：{主张}"


def _挑(回答: str, 可认的: Sequence[权限条目]) -> str | None:
    """从模型那串回答里挑出编号。

    取**最先出现**的那个合法编号，而不是要求整个回答就等于编号 ——
    「编号：L01。」和「L01」是同一个意思，为这点格式差异判成「认不出」太亏。

    **只认传进来那批里真有的编号。** 模型回 L99 时返回 `None`，不照单全收：
    照收的后果是第 2 层拿着一个查无此条的编号去找条目 —— 要么炸，要么静默
    判成未列明，而**右栏两种都不显示**。
    """
    已知 = [k.编号 for k in 可认的]
    出现 = [(回答.find(号), -len(号), 号) for 号 in 已知 if 号 in 回答]
    if not 出现:
        return None
    # `-len(号)` 是为了让 L01 / L010 这种前缀关系在同一起点上取长的那个。
    # 现在的编号都是两位，加它是因为**这个函数不该依赖「编号永远是两位」**。
    return min(出现)[2]
