"""一次来访里顾客说过的话 → 需求列表。**「这次要什么」那一行的产出者。**

# 为什么不是「一条消息一次」

`拆主张` 是**一条消息**一次，拆的是「能独立处置的事实点」，喂给三层判定用。
这一行要的是**另一样东西**：这位顾客这一趟**想办哪几件事**。

粒度差在两头：

- 输入是一整趟（这一趟她说的每一句都在里面），不是一句 —— 三次开口是同一件事
  的话，得并成一条。真数据里 `S00025` 那三句（「在吗?」「618 有什么活动呀…」
  「emmm，那赠品会跟正装一起发吗啊」）拆出来该是一条或两条，不是三条引文。
- 输出要**短**：这一行在右栏是一行文字（**控制在一行以内**，前端截断兜底），
  原话攒起来会撑成一大坨，而「在吗」「好的，谢谢啦」这种字一个都不该占位置。

# 和 `拆主张` 的分工写在这儿，别混

| 谁 | 输入 | 输出 | 干什么用 |
|---|---|---|---|
| `拆主张` | 一条买家消息 | 事实点 | 三层判定的归因单元 |
| **本模块** | 一趟的买家话 | 需求短语 | 右栏「这次要什么」那一行 |

**本模块的输出不进判定链路**，也没有任何规则读它（
`pipeline.个体差异所在行` 说的是「这是谁」）。它是**给人看的一行字**。

# 模型出岔子先退到「没有」

退成空列表 = 调用方回落到**原话攒法**（`装配.这次要什么`）——
那是这一行在 2026-10-04 之前的样子，难看但真。**不退到「整段话算一条需求」**：
那是一句原话顶在「需求」的位置上，比难看更坏 —— 它看着像是拆过的。

（和 `拆主张._兜底` 的方向相反，因为两处的下家不同：那边空列表会让判定没有
归因单元，这边空列表只是让这一行回到原话。）
"""

from __future__ import annotations

import json
from collections.abc import Sequence

from .客户端 import (
    LLM不可用,
    问JSON,
    问答函数,
    需求分解地址,
    需求分解密钥,
    需求分解模型,
)

#: 一条需求最多几个字。**提示词里写死，代码里不校验** ——
#: 校验就得决定「超了是砍掉还是整条扔掉」，两个都比特长的一条更坏
#: （砍掉可能砍出半个意思，扔掉就是丢了一条需求）。
#: 真正兜底的是前端那一行截断（`CustomerStateCard`）。
最长字数 = 12

#: 最多几条。真数据里一趟最多五句买家话（实测 400 句 / 114 个窗口），
#: 四件事已经够满一行了。
最多条数 = 4

系统提示 = (
    "你把客服对话里买家**这一趟**说过的话，拆成几条「需求」。\n"
    "一条需求 ＝ 顾客想办的**一件事**。同一件事说过几遍的，并成一条。\n"
    "寒暄、道谢、催促、收场白**不算需求**：「在吗」「好的，谢谢啦」"
    "「还要多久」都不要单独成条。\n"
    f"每条写成一句简短的中文短语，**不超过 {最长字数} 个字**，不要加序号，不要引号。\n"
    f"最多 {最多条数} 条，宁少勿多。\n"
    '只输出 JSON：{"需求": ["...", "..."]}'
)


def _问需求(提示: str, 系统: str) -> str:
    """默认那个 `问`：**这一位自己的模型**在这儿传下去。

    不写在 `拆需求` 的调用点上，是为了让 `问答函数` 这个两参数形状继续成立 ——
    测试里的假模型写一个两参数函数就顶得上（和 `话术生成._问话术` 同一个分法）。
    单看下面三个取值全绿、却没传到 `model=` 上，是这一改最可能的坏法。
    """
    return 问JSON(
        提示,
        系统,
        模型=需求分解模型(),
        地址=需求分解地址(),
        密钥=需求分解密钥(),
    )


def 拆需求(
    买家话们: Sequence[str],
    顾客情况: Sequence[tuple[str, str]] = (),
    *,
    问: 问答函数 = _问需求,
) -> list[str]:
    """这一趟顾客说过的话 → 需求列表。

    `顾客情况` 是 `(标签, 值)` 的行（和 `三层判定` 收的是同一个形状）——
    同一句「能用吗」，孕妇和普通顾客拆出来不是一件事。

    **一句买家话都没有时返回 `[]`**（不打模型）：没有可拆的输入，
    问一次也只会得到一句客套的废话，而那一趟本来就该显示原话兜底那份。

    **模型出任何岔子都返回 `[]`**（`LLM不可用` ／ JSON 不合法 ／ 字段不对），
    由调用方回落到原话 —— 见模块文档串。
    """
    话们 = [句.strip() for 句 in 买家话们 if 句 and 句.strip()]
    if not 话们:
        return []

    try:
        需求 = _解析(问(_提示(话们, 顾客情况), 系统提示))
    except (LLM不可用, ValueError, TypeError):
        return []

    return _去重(需求)[:最多条数]


def _提示(话们: Sequence[str], 顾客情况: Sequence[tuple[str, str]]) -> str:
    """**一句一行**，不合成一段。

    合成一段的话模型会去猜哪儿是一句话的结尾（真数据的买家消息有的一口气
    写三件事、有的没标点），而这个模块的整件事就是「边界由谁定」。
    """
    情况 = "\n".join(f"{标签}：{值}" for 标签, 值 in 顾客情况)
    说过 = "\n".join(f"- {句}" for 句 in 话们)
    return f"顾客情况：\n{情况 or '（没有）'}\n\n她这一趟说过：\n{说过}"


def _解析(回答: str) -> list[str]:
    """模型那串 JSON → 需求列表。**字段不对就抛，让调用方走兜底。**

    `response_format` 只保证「是个合法 JSON 对象」，不保证里面有 `需求`、
    更不保证它是数组 —— 那三件事得自己查。
    """
    原始 = json.loads(回答)
    if not isinstance(原始, dict):
        raise TypeError(f"要的是 JSON 对象，拿到 {type(原始).__name__}")
    需求 = 原始.get("需求")
    if not isinstance(需求, list):
        raise TypeError(f"`需求` 不是数组：{需求!r}")
    return [str(条).strip() for 条 in 需求]


def _去重(需求: Sequence[str]) -> list[str]:
    """去掉空条目和重复项，**保持原顺序**。

    顺序是顾客开口的先后 —— 重排会让客服对不上她刚说的那句。
    模型偶尔会把同一条写两遍（「赠品补发」和「赠品补发」），这一行只有一行宽，
    重复的那条直接把别人的位置挤掉。
    """
    见过: set[str] = set()
    结果: list[str] = []
    for 条 in 需求:
        if 条 and 条 not in 见过:
            见过.add(条)
            结果.append(条)
    return 结果
