"""一条消息 → 它属于哪个诉求（节点 3.5）。**链路里的第七个模型位置。**

# 三个词，别混

诉求 ⊃ 轮 ⊃ 主张（`一句话进来的流程.md` 的术语节）：

| 词 | 定义 | 粒度 | 谁定 |
|---|---|---|---|
| **诉求** | 顾客要办的那一件事 | 可跨轮、跨天 | 本模块 ＋ 装配层 |
| **轮** | 围绕同一诉求、双方往来的多条消息 | 跨消息、跨双方 | 本模块 ＋ `pipeline.切轮` |
| **主张** | 一条消息里一个能独立处置的事实点 | 消息内，N 条 | `拆主张` |

# 为什么不能并进 `拆主张`

**催促可能拆不出任何主张** ——「还要多久」不是一个能独立处置的事实点，
按 v8 §二该拆出零条。但它的归属是必须的：H2 的窗口要它、G4 防重复要它、
小卡要它。**归属问题在主张列表为空时依然存在**，所以不能靠 `拆主张` 的输出来带。

# 清单由调用方传，这里不存状态

「本会话当前未解决的诉求清单」是**会话级状态**，归装配层
（`app/data/装配.py`）。所以本模块是纯函数，**不缓存、不做全局状态** ——
存了的话 `认诉求` 就从「同样输入同样输出」变成「取决于这个进程之前跑过什么」，
留痕再也解释不了某一轮为什么判成那样。

> ⚠️ **和 `permissions.py` 里那个「诉求」不是一条链。** 那边指的是**权限矩阵的
> 一行**（补发／换货／价差…），是**主张粒度**的办事类目 —— `认权限(主张)` 在
> 第 2 层逐主张调用（`pipeline._判一条`）。诉求比它粗（诉求 ⊃ 主张），
> 而且盖不住咨询类（「含乙醇吗」在矩阵里没有对应行，会落到「未列明」）。
> 所以**不能拿本模块的输出去喂 `认权限`**。
>
> 另一处容易看花眼：`api/判定.判重复要求` 里那个 `诉求们` 用**权限矩阵的关键词**
> 算「同一诉求提过几次」。那是同一个词在另一个问题上的近似，不是同一条链
> —— 它数的是「提过几次」，这里判的是「属于哪一件」。
"""

from __future__ import annotations

from collections.abc import Sequence

from .客户端 import LLM不可用, 问模型, 问答函数

#: 模型够不着时统一退到这个标签。
#:
#: **退到「同一个」是关键。** 退成「每条消息一个新标签」的话，每条消息各自成了
#: 一轮 —— 而「轮」正是 H2 连发检测要看到的形状（顾客连发「在吗」「在吗？」
#: 「在吗！」时，各自成轮就永远凑不到阈值 3）。全落进一个诉求等于**不分组**，
#: `切轮` 跟着退化成今天那条纯结构的切法（工单 §3.3 要的正是这个退路）。
认不出 = "（未识别）"

#: 包在最外面的成对引号／括号。**只剥成对的、只剥最外面一层。**
_成对: dict[str, str] = {
    "「": "」", "『": "』", "“": "”", "‘": "’",
    "《": "》", "〈": "〉", "【": "】",
    "（": "）", "(": ")", "[": "]", "{": "}",
    '"': '"', "'": "'",
}

系统提示 = (
    "你在判断客服对话里买家的一条消息，属于下面「已有诉求」里的哪一个。\n"
    "属于其中某一个：**原样照抄那一条的字，一个字都不要改写**，不要加引号或标点。\n"
    "都不属于：起一个简短的中文短语当新诉求（如「赠品补发」「孕期能否使用」）。\n"
    "只回这一条，不要解释，不要回序号。"
)


def 认诉求(
    消息文本: str,
    已有诉求: Sequence[str],
    *,
    问: 问答函数 = 问模型,
) -> str:
    """这条消息属于哪个诉求。命中了返回清单里那一个（**逐字**），否则给个新标签。

    `已有诉求` 由调用方传（装配层的会话状态）—— **本函数不存它**。

    **空消息返回空串**：没有诉求可谈。不返回 `认不出` —— 那会把一条纯图片
    也塞进「当前未解决的诉求」里。

    **模型不可用退到 `认不出`**，理由见那个常量的文档串。
    """
    干净 = 消息文本.strip()
    if not 干净:
        return ""

    try:
        回答 = 问(_提示(干净, 已有诉求), 系统提示)
    except LLM不可用:
        # 够不着模型 ≈ 判不出归属。**不抛** —— 抛的后果是演示当天模型一抖，
        # 整条链断在这一环；而「判不出」本来就有一个安全的答案（见 认不出）。
        return 认不出

    return _归(回答, 已有诉求)


def _提示(消息: str, 已有诉求: Sequence[str]) -> str:
    """消息 ＋ 已有诉求清单。**两个都要进 prompt。**

    清单为空时**要写出来**，不能渲染成一片空白 —— 模型看到空的那一节会以为
    内容被截断了，然后回一句「请提供诉求清单」之类的东西。
    """
    清单 = "\n".join(f"- {条}" for 条 in 已有诉求) or "（暂无 —— 这是本会话第一个诉求）"
    return f"已有诉求：\n{清单}\n\n买家消息：\n{消息}"


def _归(回答: str, 已有诉求: Sequence[str]) -> str:
    """模型的回答 → 诉求标签。

    **逐字相同才算命中。** 模型回了个近义的说法就当新诉求起一条 ——
    替它归并等于替它决定「这两件事是一件事」，而那正是它会出错的地方。
    代价是模型不听话时多分一轮，比把两件事并成一件**便宜得多**：
    并错了的那一轮，H2 和 G4 从此都看着一个错的窗口。
    """
    洗 = _剥引号(回答.strip())
    if not 洗:
        return 认不出

    for 条 in 已有诉求:
        if 洗 == 条:
            # 返回清单里那一个本身，不是 `洗` —— 清单是跨消息存活的那一份，
            # 逐字相同这一条得由这里保证。
            return 条
    return 洗


def _剥引号(文本: str) -> str:
    """剥掉包在最外面的成对引号／括号。

    剥的是**格式脏**（模型在「引用」它的答案），不改动中间任何一个字 ——
    所以它和「别归一化」不冲突：改写标签的措辞是另一件事，那件事这里不做。

    只剥成对的（`「x」` 剥，`(x]` 不剥），只剥最外面一层。
    """
    while len(文本) >= 2 and _成对.get(文本[0]) == 文本[-1]:
        文本 = 文本[1:-1].strip()
    return 文本
