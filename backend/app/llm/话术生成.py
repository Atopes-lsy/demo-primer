"""一条主张 → 一句能发给顾客的话，**写完还要过一遍闸门**。

# 这一层在链路的哪儿

三层判定跑完之后、发给顾客之前。`判成` 已经说了「这条该谁办、能不能直发」，
这里负责把那句话写出来 —— 而写出来之后**必须**走 `guards.过闸门`：
**这套闸门是话术模型不必完美的原因**（`guards.py` 的文件头）。模型每次都在赌，
所以每一次产出都要验。

# 循环（spec §六）

```
组装 prompt（第一次不带反馈）
  ↓
问模型 → 话术
  ↓
过闸门
  ├─ 放行                      → 定稿（去向按降级去向压低）
  ├─ 重生成可行 且 已试 < 3    → 把**高危**命中塞回 prompt，重来
  └─ 否则                      → 降级
```

**「2 次」指重试 2 次**：初次 ＋ 2 次重试 ＝ 最多 3 次模型调用（`最多调用`）。
两种读法都通，这里定死为前者，测试按 3 次断言。

**重试只喂高危命中。** 中危不阻断，喂进去会让模型去改本来没问题的句子。

**封顶之后走降级不是因为模型没救，是因为再问下去只是烧钱。** 改不动的两类
（`可重生成=False`）一次都不重试，理由写在 `guards.重生成可行` 里。

# 放行 ≠ 可以 AI 直发（4.3）

`是否放行` 只看高危，而 `待核对`（口径表里业务方没确认的时效数字）是
**中危 ＋ 有降级去向 ＋ 可重生成=False**：放行、也不值得重生成，但
`guards.py` 明说了「不阻断不等于可以 AI 直发」。**没有任何现成函数替调用方
算这件事**，所以这一层要同时看两样 —— `可直发` 就是那个判据。

不认这个字段的后果：屏幕上显示「AI 直发」配一句没人确认过的时效承诺。

# 两种去向不归这一层

`转交` 由 `rules/handover.py` 的 `转交话术表` 给，`报备` 由 `rules/安抚话术.py`
给（spec §6.5）。**都不能让模型重写一遍** —— 那两句是固定表、导入时就校验过
三条硬边界的，而且都是**先于客服点发送发出去**的，说死了收不回来。
传进来就抛（`不支持的去向`），**抛之前一次网络调用都不发**。
"""

