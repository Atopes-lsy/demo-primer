#: 最多的模型调用次数 ＝ 初次 ＋ 2 次重试（spec §六）。
最多调用 = 3

#: 3c 只管这两种去向，其余两种有各自的固定表（模块文档串）。
_管的去向 = frozenset({输出类型.AI直发, 输出类型.客服点发送})


class 不支持的去向(ValueError):
    """`判成.输出` 是 `转交` 或 `报备` —— 那两种话术有固定表，不走模型。

    抛而不是静默生成：这是**调用方分派错了**（`判成.输出` 上明明写着），
    静默走模型会产出一句没人校验过的转交话术，而它是自动发给顾客的。
    """


@dataclass(frozen=True, slots=True)
class 生成结果:
    """一句成稿，连同它是怎么来的。"""

    话术: str
    """成稿。`降级` 非空时这里是**最后一次被拦的原文**（客服在这上面改，不是从零写）。"""

    去向: 输出类型
    """**可能和 `判成.输出` 不同。** 压低（4.3）会让 AI直发 变成客服点发送。"""

    命中: tuple[闸门命中, ...]
    """最后一次的闸门结果，进 `判定响应.闸门`。空元组表示干净。"""

    用到的依据: tuple[str, ...]
    """**模型自报**的出处，如 `("口径表 K01", "不良反应工单 · BLFY70604980")`。

    右栏拼 `Evidence.用上` 用它，**不是** `源记录.用上` —— 见 spec §6.4。
    模型没按格式回时是空元组，那不代表没依据，只代表它没自报。
    """

    降级: 降级结果 | None = None
    """非 None 表示走到了降级。"""

    调用次数: int = 1
    """调了几次模型（1–3）。**留痕要记** —— `开发步骤.md:325` 要求留痕能回答
    「闸门拦了几次、重生成试了几轮」。不在这里带出去，留痕层就查不到。"""


def 可直发(命中: Sequence[闸门命中]) -> bool:
    """这一稿能不能不经过客服、直接自动发出去（spec §4.3）。

    **＝ 放行 且 没有任何一条降级去向。** 两个条件差的就是「中危但带降级去向」
    那一格 —— `待核对` 正是那一格：不阻断（中危），但不许自动发。

    它是**给调用方的公开判据**（右栏那个「AI 直发」的角标、接口线分派去向都由它
    说话）；本模块内部控制循环用的是 `是否放行`，因为「要不要重生成」和
    「能不能自动发」是两个问题，混成一个会让待核对触发一轮没用的重试。

    不往 `guards` 里加：`guards` 判「这句对不对」，这一条判「3c 拿它怎么办」，
    是调用方的知识。
    """
    return 是否放行(命中) and not any(h.降级去向 for h in 命中)


def 归一用上(依据: Sequence[依据条目]) -> tuple[依据条目, ...]:
    """把 `用上` 统一置 `True` 后传 `过闸门`（spec §6.4）。

    **这不是糊弄闸门，是弥合两个本来就不一致的谓词。** `判成` 第 1 层走
    `六源结果.有记录()`（只看 `exists`），G3 判「有没有材料」走 `用上`。
    不归一的话，检索召回到了、`判成` 说能直发，G3 却每次都判「没有任何依据」——
    两个结论自相矛盾。

    G3 那一问的意图是「**检索**有没有召回到材料」，而检索有没有召回到，
    `判成` 第 1 层已经认证过了。至于「这句话**引用**了哪几条」，是
    `生成结果.用到的依据` 回答的另一个问题（模型自报，进右栏）。
    """
    return tuple(replace(e, 用上=True) for e in 依据)


def _问话术(提示: str, 系统: str = "") -> str:
    """`生成话术` 的默认口子 —— 走**它自己那套**模型配置。

    四个模型位里只有它分家（见 `客户端` 模块文档串）。想知道为什么，
    看 `工单交接_给模型线_C.md` §三：那三个位干的是分类和切分，
    只有它是**写作文**，而且它一次判定里花钱最多。

    **别把它直接改成 `问JSON`。** 改了就等于没分家，而单看变量取值全绿 ——
    `tests/test_选型.py` 里有三条从不同角度钉着这件事。
    """
    return 问JSON(
        提示,
        系统,
        模型=话术生成模型(),
        地址=话术生成地址(),
        密钥=话术生成密钥(),
    )


def 生成话术(
    判成: 判成,
    顾客情况: Sequence[tuple[str, str]] = (),
    触发列表: Sequence[object] = (),
    口径表: 口径表数据 | None = None,
    已发出: Sequence[str] = (),
    *,
    召回先例: 召回函数 = 召回先例,
    问: 问答函数 = _问话术,
) -> 生成结果:
    """写一句话，过闸门，必要时重写，写不动就降级。

    **`问=` 是给测试的口子** —— 循环控制是纯规则，塞个假模型进去就能断言
    「重试几次、什么时候降级、喂什么回去」。真模型那条路跑演示剧本，人看，
    不验文案。

    **模型出任何岔子都不抛，退到降级。** 和 `认口径`（退到 `None`）、
    `拆主张`（退到整条当一条）同一条：抛的后果是演示当天模型一抖，
    `POST /api/判定` 直接 500、右栏整个白掉。降级至少给客服一张纸。
    """
    if 判成.输出 not in _管的去向:
        raise 不支持的去向(
            f"{判成.输出} 的话术不归 3c 管："
            "转交走 `rules/handover.转交话术表`，报备走 `rules/安抚话术.查安抚话术`。"
            "那两句是导入时就校验过的固定表，而且先于客服点发送发出去，"
            "让模型重写一遍等于把那些边界再赌一次。"
        )

    可引用 = 取可引用(判成, 口径表)
    待核对 = 口径表.待核对数字() if 口径表 is not None else ()
    材料 = 归一用上(判成.依据)
    # 先例取一次就够：重试改的是措辞，不是「参照谁家的说法」。每轮重取的话，
    # 模型两稿之间的参照物会变，反馈说「改这里」而它照的是另一份先例。
    先例 = tuple(召回先例(判成.主张, 召回条数))

    上一稿 = ""
    意见: Sequence[闸门命中] = ()
    命中: tuple[闸门命中, ...] = ()
    用到的: tuple[str, ...] = ()
    调用次数 = 0

    while True:
        # ⚠️ **`顾客情况` 不往 `组装提示` 传**（signature 也收不下）：
        # 它是**闸门**的输入 —— 下面 `过闸门` 那一行的第 5 个参数才是它。
        # 进 prompt 的话模型会照着「答应过什么」里的逾期天数写，而那个数字
        # 在本条主张的依据里没有出处，G3 每次都判「找不到」。
        # 见 `组装提示` 的文件头「写手只看得见有出处的东西」。
        提示 = 组装提示(
            判成, 触发列表, 口径表, 已发出, 先例, 上一稿, 意见
        )
        调用次数 += 1

        try:
            回答 = 问(提示, 系统提示)
        except LLM不可用:
            # 够不着模型 ≈ 这一轮没有稿子。上一稿（如果有）就是**最后一次被拦的
            # 原文**，交给客服改比给一张白纸强。
            return _收尾(判成, 上一稿, 命中, 用到的, 调用次数, 降级=True)

        话术, 用到的 = _解析(回答, 判成)
        if not 话术:
            # 模型回了个空的 —— 和够不着模型是同一件事。**不能拿空串去过闸门**：
            # 空话术一条都碰不到，四道闸门会一致放行，然后发出去一条空消息。
            return _收尾(判成, 上一稿, 命中, 用到的, 调用次数, 降级=True)

        命中 = tuple(
            过闸门(话术, 材料, 可引用, 已发出, 顾客情况, 待核对, 判成.涉及个体差异)
        )

        if 是否放行(命中):
            # 放行就定稿 —— **包括「放行但有待核对」那一格**：那句本身没问题，
            # 要压的是去向，不是重写它。压去向在 `_收尾` 里做。
            return _收尾(判成, 话术, 命中, 用到的, 调用次数, 降级=False)

        if not 重生成可行(命中) or 调用次数 >= 最多调用:
            return _收尾(判成, 话术, 命中, 用到的, 调用次数, 降级=True)

        上一稿 = 话术
        # 只喂高危：中危不阻断，喂进去会让模型去改本来没问题的句子。
        意见 = [h for h in 命中 if h.严重度 == "高"]


def _收尾(
    判: 判成,
    话术: str,
    命中: tuple[闸门命中, ...],
    用到的: tuple[str, ...],
    调用次数: int,
    降级: bool,
) -> 生成结果:
    """两条出口共用的收口：算去向、造降级包。

    去向在这里**只升不降**（`优先级` 数值大的赢）——
    `转交`／`报备` 进不来（顶上抛过了），所以实际效果是：
    AI直发 被任何一条 `降级去向` 压成客服点发送；降级时再加一层地板。
    """
    去向 = _压低(判.输出, 命中, 地板=输出类型.客服点发送 if 降级 else None)
    return 生成结果(
        话术=话术,
        去向=去向,
        命中=命中,
        用到的依据=用到的,
        降级=造降级(话术, 命中, 依据=判.依据) if 降级 else None,
        调用次数=调用次数,
    )


def _压低(
    基准: 输出类型,
    命中: Sequence[闸门命中],
    地板: 输出类型 | None = None,
) -> 输出类型:
    """把去向压到 `基准`、所有 `降级去向`、`地板` 里最高的那个。

    **`降级去向` 空串是有意义的取值，不是缺省**：它表示「这一条不改变去向」
    （G2 措辞那种只提示的中危就是空串）。当成「必须压」的话，
    每一条中危提示都会把 AI直发 变成客服点发送，那个字段就失去了分辨力。
    """
    值 = [基准, *(输出类型(h.降级去向) for h in 命中 if h.降级去向)]
    if 地板 is not None:
        值.append(地板)
    return max(值, key=lambda o: 优先级[o])


def _解析(回答: str, 判: 判成) -> tuple[str, tuple[str, ...]]:
    """模型那串回答 → (话术, 模型自报的出处)。

    **解析失败就整段当话术**，不退到空 —— 空等于把成稿丢了，客服从零写。
    退化成「一句格式难看的话」是可以接受的：它还要过四道闸门。

    自报的出处**只认 `判成.依据` 里真有的**，且按 `判成.依据` 的顺序返回。
    和 `认口径` 不收编造的 K99 是同一条：照收的后果是右栏挂一条
    「依据：口径表 K99」，点进去什么都没有，而整个链路没有一处会报错。
    顺序也照 `判成.依据` 走 —— 右栏那份依据清单是按这个顺序渲染的。

    ⚠️ 比对用**包含**不是相等。真模型（2026-10-01 实测 qwen-plus）回的是
    `"口径表 K05：已核实漏发，会为您安排补发……"` —— prompt 里那块的格式是
    `- 出处：摘要`，它把**整行**当成出处抄回来了。整串相等会一条都认不出，
    而后果不是报错：右栏 `N/6` 恒为 `0/6`、`Evidence.用上` 全灭，**没有东西会响**。
    （`认口径` 那条「取第一个真在表里的编号」是同一个路数。）
    """
    干净 = 回答.strip()
    try:
        原始 = json.loads(干净)
    except (ValueError, TypeError):
        return 干净, ()

    if not isinstance(原始, dict) or not isinstance(原始.get("话术"), str):
        return 干净, ()

    话术 = 原始["话术"].strip() or 干净
    报的 = 原始.get("依据")
    if not isinstance(报的, list):
        return 话术, ()
    抄的 = [str(x) for x in 报的]
    return 话术, tuple(e.出处 for e in 判.依据 if any(e.出处 in x for x in 抄的))
