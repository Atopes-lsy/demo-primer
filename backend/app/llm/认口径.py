"""一条主张 → 一个口径编号。

# 为什么换掉了关键词

`rules/pipeline.认口径` 是关键词匹配（话题名按 `()/` 切段后做子串匹配），
**实测 5 条真主张 0 条认得出**（`docs/开发步骤.md` §一 有那张表）：
「孕妇能否用」认不出 K01（K01 的话题名里写的是「孕期」）、
「含乙醇」认不出 K10（K10 是「成分安全(酒精/香精)」）。**别花时间修关键词。**

# 为什么不走向量

口径表只有 20 条。20 条上的向量检索是负优化，还要多背一个 embedding 模型、
一层索引、一份「索引和表不同步」的新故障模式。**每次全塞 prompt**，让模型选
一个编号或说不知道，20 条撑死几百个 token。

# 认不出就 `None`，不要猜

`依据编号` 空着比挂错强。挂错了客服翻回口径表对不上账，而且**不会有任何东西
报错** —— 右栏只是安安静静地显示一个错的编号。

> ⚠️ **这个文件是给 `判成.依据编号` 用的，不决定输出。** 从 v9 起
> 「口径编号 → 输出类型」那张表已经退役了（`pipeline._口径输出` 的文档串记着
> 三处硬冲突），决定输出的是第 3 层算的话术属性。别把这张表接回来。
"""

from __future__ import annotations

from collections.abc import Sequence

from ..rules.koujing import 口径条目
from .客户端 import LLM不可用, 问模型, 问答函数

系统提示 = (
    "你在把电商客服场景里的一条「主张」认到最贴切的一条口径上。\n"
    "只回一个口径编号（如 K10），或回 NONE。**不要解释，不要回别的字。**\n"
    "拿不准就回 NONE —— 认错比认不出更糟。"
)

#: 表的表头。列名和 `口径条目` 的字段名对齐，模型看到的和代码里读的是同一套词。
_表头 = "编号 | 话题 | 可以说"


def 认口径(
    主张: str,
    口径表: Sequence[口径条目],
    *,
    问: 问答函数 = 问模型,
) -> str | None:
    """把一条主张认到某个口径编号上，**认不出返回 `None`**。

    `口径表` 空着直接返回 `None`，一次网络调用都不发。
    """
    if not 口径表:
        return None

    try:
        回答 = 问(_提示(主张, 口径表), 系统提示)
    except LLM不可用:
        # 够不着模型 ≈ 认不出。**不抛** —— 抛的后果是演示当天模型一抖，
        # `POST /api/判定` 直接 500、右栏整个白掉；而「认不出」本来就是
        # 一个合法答案，`None` 会让这条主张照常往下走（只是右栏少一行依据）。
        return None

    return _挑(回答, 口径表)


def _提示(主张: str, 口径表: Sequence[口径条目]) -> str:
    """口径表 ＋ 主张。**20 条全在里面**，不做筛选。"""
    行们 = "\n".join(f"{k.编号} | {k.话题} | {k.可以说}" for k in 口径表)
    return f"口径表：\n{_表头}\n{行们}\n\n主张：{主张}"


def _挑(回答: str, 口径表: Sequence[口径条目]) -> str | None:
    """从模型那串回答里挑出编号。

    取**最先出现**的那个合法编号，而不是要求整个回答就等于编号 ——
    「编号：K10。」和「K10」是同一个意思，为这点格式差异判成「认不出」太亏。

    **只认表里真有的编号。** 模型回 K99 时返回 `None`，不照单全收：
    照收的后果是右栏挂一条查无此条的「依据：口径表 K99」，点进去什么都没有。
    """
    已知 = [k.编号 for k in 口径表]
    出现 = [(回答.find(号), -len(号), 号) for 号 in 已知 if 号 in 回答]
    if not 出现:
        return None
    # `-len(号)` 是为了让 K10 / K100 这种前缀关系在同一起点上取长的那个。
    # 现在的编号都是两位，加它是因为**这个函数不该依赖「编号永远是两位」**。
    return min(出现)[2]
