"""一句话 → 事实点列表。**链路里最先跑的那个模型位。**

# 没有它，判定跑不起来

`三层判定` 的入参是 `主张列表`，而**全项目没有任何东西产出这个列表**
（工单 §3.4）。`tests/test_judge.py` 那些用例全是拿字面量喂进去的，
所以测试全绿也掩盖不住这个洞 —— 只有真的打一次 `/api/判定` 才会暴露。

# 为什么是模型不是规则

一句话里可能同时有「问成分」「要补发」「投诉」三件事，规则拆不开：
分词不知道哪儿是边界，标点也不可靠（演示那句话就没有标点）。
`response_format` 把它约束成一个 JSON 对象，字段再由本模块校验。

# 一条主张 ＝ 一个事实点

2026-10-01 定的粒度：**一个能独立处置的点**。
「含乙醇」和「孕妇能用」是**两条** —— 它们是否属于同一**诉求**是节点 3.5 的事，
不影响条数。

# 寒暄不是事实点（2026-10-05）

系统提示里那两句是实测逼出来的。原先什么话都拆，于是**每一条会话的收场白
都换成了一张卡**：S00002「能，谢谢推荐」被拆成「确认接受推荐」「表达感谢」
两条主张，第 1 层两条都查不到依据 → 兜底 `客服点发送`（`pipeline.兜底输出`）
→ 右栏弹一张蓝卡要客服点一下，还挂着 G3「这句没有任何依据支撑」。
「顾客最后一句是收场白」是**普遍现象**不是个案：`data/装配.这次要什么`
那边量过，24 个多段窗口的末句 **24/24 全是收场白**。

**所以「空数组」从这一版起是一个真答案，不再是失败。** 从前 `{"主张": []}`
无条件走 `_兜底`（整条消息算一条），理由是「沉默比空白好」—— 那条理由对
**答坏了**成立（吐白话、字段不对、够不着模型，这些照旧兜底），对**答得出来
并且说没有**不成立：模型说没有可处置的事，就是没有。

这是拿一次误报换一次可能的漏报，换得有理由：误报是**确定的**（每条会话
结尾都来一次），漏报是**模型的**（prompt 明写了「夹着一件要办的事照拆」，
且只在模型答得又空又错时才发生）。前者的代价是客服学会无视卡片，
后者是客服自己去读那句话。

# 两个不能忘的约束

**H1 命中时也照跑。** 别因为「反正要转交」就短路它 —— 风险要**归到哪一条主张上**
才有的展示，不拆就没有归因单元（`rules/triggers.py` 的文件头为这件事专门写了注）。

**主张文本就是主键。** 前端拿它当 React key（`key={d.主张}`），同一轮里
两条主张文本相同就撞 key，右栏**少显示一条**且不报错。所以这里自己再去一次重，
不指望模型每次都听话。
"""

from __future__ import annotations

import json
from collections.abc import Sequence

from .客户端 import LLM不可用, 问JSON, 问答函数

系统提示 = (
    "你把客服对话里买家的一条消息拆成若干「事实点」。\n"
    "一条事实点 ＝ 一个能独立处置的点。买家说「赠品没到、脸还过敏了、要开发票」，"
    "那是三条。\n"
    "「这款含乙醇吗」和「孕妇能用吗」是两条 —— 它们是不是同一个诉求不影响条数。\n"
    "每条事实点写成一句简短的中文短语，**不要重复**，不要加序号。\n"
    # ── 下面这两句是 2026-10-05 加的，理由见 `拆主张` 的文档串「寒暄不是事实点」──
    "**纯寒暄、道谢、收场白不是事实点**：「谢谢」「麻烦了」「好的」「行吧」"
    "「收到了」「等你们消息」这类话没有可办的事，不拆。\n"
    "整条消息都没有可办的事时，输出**空数组**；只要夹着一件要办的事"
    "（「谢谢，顺便帮我催一下发货」），那件事照拆。\n"
    '只输出 JSON：{"主张": ["...", "..."]}'
)

def 拆主张(
    消息: str,
    顾客情况: Sequence[tuple[str, str]] = (),
    *,
    问: 问答函数 = 问JSON,
) -> list[str]:
    """买家的一条消息 → 主张列表。

    `顾客情况` 是 `(标签, 值)` 的行（和 `三层判定` 收的是同一个形状）——
    同一句「能用吗」，孕妇和普通顾客拆出来的事实点不一样，模型得知道这是谁在问。

    **空消息返回空列表**（纯图片、或者只有空格）；**模型出任何岔子都退到
    「整条消息算一条主张」**，退不到就沉默这件事不接受 —— 见 `_兜底`。
    """
    干净 = 消息.strip()
    if not 干净:
        return []

    try:
        # `_解析` 抛 = 模型够不着或者答坏了 → 兜底；解析得过 = **这已经是答案**，
        # 里面是空的也算答案（见下面「寒暄不是事实点」）。
        return _去重(_解析(问(_提示(干净, 顾客情况), 系统提示)))
    except (LLM不可用, ValueError, TypeError):
        return _兜底(干净)


def _提示(消息: str, 顾客情况: Sequence[tuple[str, str]]) -> str:
    情况 = "\n".join(f"{标签}：{值}" for 标签, 值 in 顾客情况)
    return f"顾客情况：\n{情况 or '（没有）'}\n\n买家消息：\n{消息}"


def _解析(回答: str) -> list[str]:
    """模型那串 JSON → 主张列表。**字段不对就抛，让调用方走兜底。**

    `response_format` 只保证「是个合法 JSON 对象」，不保证里面有 `主张`、
    更不保证它是数组 —— 那三件事得自己查。
    """
    原始 = json.loads(回答)
    if not isinstance(原始, dict):
        raise TypeError(f"要的是 JSON 对象，拿到 {type(原始).__name__}")
    主张 = 原始.get("主张")
    if not isinstance(主张, list):
        raise TypeError(f"`主张` 不是数组：{主张!r}")
    return [str(条).strip() for 条 in 主张]


def _去重(主张: Sequence[str]) -> list[str]:
    """去掉空条目和重复项，**保持原顺序**。

    顺序有意义：右栏「本轮处置」是按顺序渲染的，而模型给的顺序通常是
    买家说话的顺序 —— 重排会让客服对不上刚看的那句话。
    """
    见过: set[str] = set()
    结果: list[str] = []
    for 条 in 主张:
        if 条 and 条 not in 见过:
            见过.add(条)
            结果.append(条)
    return 结果


def _兜底(消息: str) -> list[str]:
    """**模型够不着或者答坏了**时，整条消息算一条主张。

    **不能返回空列表。** 空的后果是这一轮一条主张都没有：右栏一片空白，
    客服以为没事，而顾客刚才说了一整段。整条当一条至少让三层判定跑起来
    —— 大概率判成「客服点发送」（要么有承诺、要么涉个体差异），偶尔判成报备。
    保守，但不是沉默。

    ⚠️ **只有抛出来的才走这里**（2026-10-05 起）。`{"主张": []}` 是一个
    **真答案**，不再兜底 —— 两件事的区别和取舍写在模块文档串「寒暄不是事实点」
    那一节，别只看这一边的理由就往回改。

    （消息本身是空的走不到这里，`拆主张` 顶上已经返回 `[]` 了。）
    """
    return [消息.strip()]
