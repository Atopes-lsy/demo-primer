"""把六块输入拼成 prompt。

# 为什么单独一个模块

六块的**来源各不相同**：主张／依据／依据编号来自 `判成`，顾客情况和触发来自
装配层，先例来自 ③。拼在一起是这一层唯一的事 —— 而它值得单独放，因为它同时是
**硬约束的落脚点**：「事实只能来自依据」「不许抄判定说明」这类要求写在
`系统提示` 里，组 prompt 的人和写循环的人不一定是同一个人。

# 七块，不是六块

spec §五 列了六块。实现里在两处动了它：

- **多一块：「已经对他说过的话」**（`已发出`）。理由不是好看 —— G4 判
  「和之前发过的话高度重复」是**中危**，中危既不阻断（`是否放行` 只看高危）
  也不触发重试，所以模型不知道的话，同一句话会被一直发出去，而且每一次都
  畅通无阻。**这条约束除了 prompt 没有别的地方能给。**
- **少一块：`顾客情况`。** spec §五 那一格写的是「顾客情况 ＋ 触发」，
  实现里只留触发。理由见下一节。

# 写手只看得见有出处的东西

**「事实只能来自依据」这句约束靠的不是叮嘱，是别给它别的东西抄。**

进来的每一块都有出处：主张是顾客自己说的，依据和口径是查到的，先例标注了
「别抄事实」，已发出是这家店自己说过的话。**没出处的不进**，两块：

- **`顾客情况`** —— 它是**闸门的输入**（spec §6.3 的输入表：「原样转给
  `G4防矛盾` 找『办过什么』行」），不是写手的素材。摆进来的后果不是「模型多看
  了一点背景」，是它**照着写**：线一第 1 轮「答应过什么」那行带着 `已逾期 2 天`，
  模型把这句写进讲成分的话，`G3来源可查` 判「这个数字在依据里找不到」——
  **判得对**（它就该拦），但它是**我们请它抄的**。重试两轮还是同一句，最后降级，
  而整个链路没有一处报错。
- **`触发.说明`** —— 和 `判成.说明` 同一类文本：内部话。真数据的 H3 说明是
  「H3 命中：9/26 的承诺已逾期 2 天」，既带内部记号，又带一个**该主张的依据里
  没有的数字**（一样会撞 G3）。触发本身还是要说的 —— 模型得知道这轮是为哪件事
  ——所以给编号／名称／严重度／证据，只把 `说明` 摘掉。

`顾客情况` 参数**根本不收**（不是收了不用）：一个被静默忽略的参数，
和「传错了口径表」是同一类坑 —— 传的人以为它生效了。

# 判定说明一个字都不进

`判成.说明` 不进 prompt。做法不是「叮嘱模型别抄」，是**根本不给它抄的东西**：
给了再叮嘱，赌的是模型每次都听话；不给，就没有可抄的。
见 `tests/test_话术生成.test_判成说明不进prompt也不进话术`。

# 第 3／4 块和第 6 块不是一回事

- 第 3、4 块是**公司写好的规范话**（20 条固定、全店共用、不带情绪）
- 第 6 块是**真人客服打出来的字**（口语、有称呼、有节奏）

**照第 3、4、6 块学语气和边界，照第 2 块写事实。** 先例里的事实是**别的买家**的，
对这个顾客不成立，照搬正好命中 G4。
"""

