def 取可引用(判成: 判成, 口径表: 口径表数据 | None) -> tuple[str, ...]:
    """按 `判成.依据编号` 取口径表里允许引用的原文 —— **闸门 `可引用` 的取值。**

    取的是 `可以说` ＋ `标准话术` 两处。`组装提示` 里那两块读的是**同一对字段**，
    没有第二份拷贝：spec §6.3 要求「同一份『可以说／标准话术』文本走两条路……
    两处必须是同一份原文」，取岔了会出现「prompt 里能说、闸门说数字没出处」
    这种自相矛盾 —— 模型照着 prompt 写，闸门照着另一份判，两边都觉得自己对。

    `依据编号` 是空的时候返回空元组，**不是「把整张表塞进去」**：那样的话
    任何一条口径里的数字都能替话术里的数字背书，闸门等于自己把门拆了。

    编造的编号（表里查无此条）静默跳过 —— 和 `认口径` 不接受 K99 同一个口径，
    这一侧不需要再报一次错。
    """
    if 口径表 is None or not 判成.依据编号:
        return ()

    文: list[str] = []
    for 号 in 判成.依据编号:
        条 = 口径表.取(号)
        if 条 is None:
            continue
        文.append(条.可以说)
        if 条.标准话术:
            文.append(条.标准话术)
    return tuple(文)


def _先例行(条目: 召回条目) -> str:
    """一条先例摆进 prompt 长什么样 —— **两个子块共用这一个拼法**。

    「`买家：… ／ 客服：…`」这个拼法是从 `检索/先例库.召回先例` 搬过来的：
    从前它拼好字符串再交出来，现在它交 `召回条目`。搬家不是收拾 ——
    **摆成什么样要看这条是哪来的**（两个子块），那是渲染的事，不是检索的事。
    """
    return f"- 买家：{条目.情境} ／ 客服：{条目.答法}"


def 组装提示(
    判成: 判成,
    触发列表: Sequence[object] = (),
    口径表: 口径表数据 | None = None,
    已发出: Sequence[str] = (),
    先例: Sequence[召回条目] = (),
    上一稿: str = "",
    意见: Sequence[object] = (),
) -> str:
    """拼一段 prompt。**这里不校验输入** —— 每一块都可能是空的，
    少哪一块都不能炸（`test_组装提示收得下空输入`）。

    **不收 `顾客情况`**（模块文档串「写手只看得见有出处的东西」）：
    它是 `过闸门` 的输入，`话术生成` 自己留着传过去。

    `上一稿` ＋ `意见` 是重试那一轮的反馈，第一次生成时都空着。
    """
    段: list[str] = [f"【要回应的事】\n{判成.主张}"]

    # ── 2 依据 · **事实的唯一来源** ──
    #
    # 不过滤 `用上`：那是「检索有没有召回」的标记（`源记录.用上`），
    # 不是「模型用没用过」。全部摆给模型看，用没用由它自己报（`用到的依据`）。
    依 = "\n".join(f"- {e.出处}：{e.摘要}" for e in 判成.依据)
    段.append(
        "【依据 · 事实只能从这里来】\n"
        + (依 or "（这一条没有任何依据 —— 那就不要写任何事实，只回应情绪）")
    )

    # ── 3／4 口径的「可以说」与「标准话术」 ──
    if 口径表 is not None:
        可以 = [k.可以说 for k in (口径表.取(号) for 号 in 判成.依据编号) if k is not None]
        范例 = [k.标准话术 for k in (口径表.取(号) for 号 in 判成.依据编号) if k and k.标准话术]
        if 可以:
            # 括号注记那句紧贴在文本旁边，不放在系统提示里 —— 实测放在系统提示里
            # 喊不住（模型逐字照抄时不会回头看系统提示），贴在要抄的那行旁边才有用。
            段.append(
                "【公司允许说到哪一步 · 这是上界】\n"
                "（每条的括号注记是给客服看的出处说明，不是话术的一部分）\n"
                + "\n".join(f"- {x}" for x in 可以)
            )
        if 范例:
            段.append("【公司写好的范例 · 照着这个语气写】\n" + "\n".join(f"- {x}" for x in 范例))

    # ── 5 触发 ──
    #
    # **只给 `str(t)`（编号／名称／严重度／证据），不给 `t.说明`。** 说明是内部话，
    # H3 那句是「H3 命中：9/26 的承诺已逾期 2 天」—— 里面那个「2 天」在这条主张的
    # 依据里没有出处，模型抄进话术就撞 G3。和 `判成.说明` 同一条禁令。
    #
    # 顾客情况**不在这里**：它是闸门的输入，见模块文档串。
    if 触发列表:
        段.append("【本次触发】\n" + "\n".join(f"- {t}" for t in 触发列表))

    # ── 6 ③ 先例库 · **按来源分两个子块** ──
    #
    # 为什么非分不可：`回写` 收的是**模型自己上一轮写的那一稿**（spec §六），
    # 而这块的抬头写的是「真人客服是怎么说的」。混在一块就是**假出处**，后果是
    # 自我强化 —— 模型看到顶着「真人客服」的名、其实是自己上一遍的稿子，于是
    # 照抄一遍，抄出来的又被 `回写` 收进去（`S00226` 轮 2 现场）。
    #
    # **两个抬头是这一层的载重件，不是排版。** 它们说的是「这段话是谁写的」，
    # 而这正是模型**没法从内容里看出来**的那一件事。
    #
    # 顺序：先「别人家怎么说的」（可参照的范例），再「本店自己写过什么」，
    # 最后才是第 7 块「已经对他说过的话」—— 从远到近。
    if 先例:
        真人 = [t for t in 先例 if t.来源 == 取材来源]
        本店 = [t for t in 先例 if t.来源 == 回写来源]
        if 真人:
            段.append(
                "【别人家同类场景里，真人客服是怎么说的 · 学答法和句式，事实照本单依据】\n"
                + "\n".join(_先例行(t) for t in 真人)
            )
        if 本店:
            # **「写过」不是「说过」。** 召回是**全库**的（库不按会话分），别的
            # 会话的回写条目也会被召回到这一块来 —— 抬头写成「对同一个顾客说过
            # 的话」就是**新造一个假出处**，正是这一拆要治的那类错。
            # 「本店有人写过这句」是这一块敢保证的，别再往上加。
            段.append(
                "【本店自己前几轮写过的话 · 不是范例：别再写一遍】\n"
                + "\n".join(_先例行(t) for t in 本店)
            )

    # ── 第 7 块：已经说过的话 ──
    if 已发出:
        段.append("【已经对他说过的话 · 不要再说一遍】\n" + "\n".join(f"- {x}" for x in 已发出))

    # ── 重试的反馈 ──
    #
    # 措辞要说清「这是修改要求不是新任务」（spec §6.1）—— 不说的话模型会另起
    # 一句全新的，上一稿白写。只喂**高危**命中：中危不阻断，喂进去会让模型
    # 去改本来没问题的句子（`话术生成` 那边过滤，这里只负责渲染）。
    if 意见:
        条 = "\n".join(f"- {h.闸门} {h.名称}：{h.详情}。{h.建议}" for h in 意见)
        段.append(
            "【上一稿被闸门拦下了 · 这是修改要求，不是新任务】\n"
            f"不要另起一句，就改下面这几处：\n{条}"
        )
    if 上一稿:
        段.append(f"【上一稿】\n{上一稿}")

    return "\n\n".join(段)
