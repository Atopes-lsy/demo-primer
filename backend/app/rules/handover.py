"""转交时给顾客的话术（规格 v9 §七「转交时给客服的对客话术」）。

**为什么转交不是「点一下按钮就完事」。** 客服必须对顾客说一句话。这句话里
只要出现时限，它就是**我们对顾客的承诺** —— 和「今天一定到账」是同一个性质
的东西，属于本产品该管的范围。所以转交这一步也得有话术、也得过闸门。

**下面这些话不是我编的。** 全部来自官方数据里 16 个转交类会话的客服原话
（不良反应 10 ／ 风控核实 3 ／ 质疑正品 3）。时限也不是编的，是数据里客服
已经在说的。

> §七 那张表是**六类**，这里是**七类**（2026-10-05 加 `质疑正品`）。加的那一类
> 不是新开的话题 —— 它正是上面那 16 个会话里的「质疑正品 3」，原先三类数据里
> 只有它没有落点：顾客报完批次号说「查不出来我就去平台举报」，H1 命中、
> 整轮转交，而六类话术里没有哪一句是给这种对话的。补法照老规矩：先翻原话，
> 再定量，最后才写表。规格下一版要把这一行收进去。

# 三条硬边界（违反就是越权承诺）

**1 · 「24 小时」是对「回访」的承诺，不是对「解决」的承诺。**
话术里只能写「回访／联系您」，**绝不能写成「24 小时内解决」**。这条由
`校验转交话术` 的正则兜着 —— 它是 §6.4 那类禁语的同族（时限＋承诺动词），
只是没进禁语表，因为它约束的是**转交话术**这个局部。

**2 · 风控类、丢件类禁止给具体时限。** 数据里客服自己都刻意只写「第一时间」，
我们不比客服更敢说。见 `不给具体时限`。

**3 · 这些话术一律走「② 客服点发送」，不走「① AI 直接发送」。**
这条的落地方式就是 `认转交话术` 被 `三层判定` 调用（2026-10-02 接上）——
在此之前这张表没有任何生产调用方，「不得直发」只写在自检里，不在判定路径上，
**等于没有约束力**：自检保证的是「话术表里没写错」，不是「判定时不会把它们发出去」。
接上之后 `判成.转交话术` 只在 `输出 == 转交` 时非空，而 `转交` 不是
`api/判定.py` 里 `_AI的名义` 的一员 —— 它压根不产出 AI 消息。

> ⚠️ **关于第 3 条的一处存疑，记在这里别丢。** 规格给的理由是「因为它们含承诺
> （有明确时限）」—— 但那个理由**只对不良反应两行严格成立**；风控核实、物流丢件、
> 投诉升级、承诺逾期四行的 `时限` 都是 `None`（规格自己要求它们不给具体时限）。
> 所以这四行严格说没有「明确时限」。
>
> 结论按规格走（六行全部 → 客服点发送），但理由要换成更站得住的那条：
> **它们都含「软承诺」**（「第一时间联系您」「按规则处理」「会优先处理」）——
> 话一旦说出去，顾客就会等。所以 `含软承诺` 认的就是这些词，而不是时限。
> 这处存疑已经报给队长，规格下一版可能会改措辞。
"""

