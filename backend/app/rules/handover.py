"""转交时给顾客的话术（规格 v9 §七「转交时给客服的对客话术」）。

**为什么转交不是「点一下按钮就完事」。** 客服必须对顾客说一句话。这句话里
只要出现时限，它就是**我们对顾客的承诺** —— 和「今天一定到账」是同一个性质
的东西，属于本产品该管的范围。所以转交这一步也得有话术、也得过闸门。

**下面这些话不是我编的。** 全部来自官方数据里 16 个转交类会话的客服原话
（不良反应 10 ／ 风控核实 3 ／ 质疑正品 3）。时限也不是编的，是数据里客服
已经在说的。

# 三条硬边界（违反就是越权承诺）

**1 · 「24 小时」是对「回访」的承诺，不是对「解决」的承诺。**
话术里只能写「回访／联系您」，**绝不能写成「24 小时内解决」**。这条由
`校验转交话术` 的正则兜着 —— 它是 §6.4 那类禁语的同族（时限＋承诺动词），
只是没进禁语表，因为它约束的是**转交话术**这个局部。

**2 · 风控类、丢件类禁止给具体时限。** 数据里客服自己都刻意只写「第一时间」，
我们不比客服更敢说。见 `不给具体时限`。

**3 · 这些话术一律走「② 客服点发送」，不走「① AI 直接发送」。**
这条的落地方式就是 `认转交话术` 被 `三层判定` 调用（2026-10-02 接上）——
在此之前这张表没有任何生产调用方，「不得直发」只写在自检里，不在判定路径上，
**等于没有约束力**：自检保证的是「话术表里没写错」，不是「判定时不会把它们发出去」。
接上之后 `判成.转交话术` 只在 `输出 == 转交` 时非空，而 `转交` 不是
`api/判定.py` 里 `_AI的名义` 的一员 —— 它压根不产出 AI 消息。

> ⚠️ **关于第 3 条的一处存疑，记在这里别丢。** 规格给的理由是「因为它们含承诺
> （有明确时限）」—— 但那个理由**只对不良反应两行严格成立**；风控核实、物流丢件、
> 投诉升级、承诺逾期四行的 `时限` 都是 `None`（规格自己要求它们不给具体时限）。
> 所以这四行严格说没有「明确时限」。
>
> 结论按规格走（六行全部 → 客服点发送），但理由要换成更站得住的那条：
> **它们都含「软承诺」**（「第一时间联系您」「按规则处理」「会优先处理」）——
> 话一旦说出去，顾客就会等。所以 `含软承诺` 认的就是这些词，而不是时限。
> 这处存疑已经报给队长，规格下一版可能会改措辞。
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from .triggers import 触发编号


@dataclass(frozen=True, slots=True)
class 转交话术:
    类型: str
    触发: str
    """什么触发的这类转交。给人看的，对应 `triggers.触发编号` 或口径编号。"""
    话术: str
    时限: str | None
    """给顾客的时限。`None` = 刻意不给具体时限（见 `不给具体时限`）。"""
    时限出处: str
    """这个时限凭什么。数据里的会话数或口径表原文。"""


#: 刻意不给具体时限的转交类型。硬边界 2。
#:
#: 判据是**规格的意图**不是文本特征 —— 风控和丢件属于「结果不可控」，
#: 给了时限反而制造二次违约。所以这是白名单，不是正则扫出来的。
不给具体时限: frozenset[str] = frozenset(
    {"风控核实", "物流丢件赔付", "投诉升级", "承诺逾期"}
)

#: 时限**不能**挂在这些动作上。硬边界 1。
#:
#: **为什么是黑名单不是白名单。** 这里最初写的是「允许的动作」白名单
#: （回访／联系／答复…），上线前自检直接炸了两条**合法**话术：
#: 「24 小时内**电话回访**」（动作是「电话回访」，前缀不是「回访」）
#: 和「退款 1-3 个工作日**回到原支付渠道**」（规格第二行明确要这么写）。
#: 合法说法是开放集合，列不完；而越权说法是**封闭**的一小撮 —— 就是
#: 「把时限承诺到结果上」。所以按黑名单查。
_禁止承诺的动作: tuple[str, ...] = (
    "解决", "处理完", "处理好", "修好", "搞定", "弄好", "查清", "查明", "恢复",
)

#: 软承诺词。虽然没给具体时限，但话一出口顾客就会等 —— 所以也必须客服点发送。
#: 见模块文档串里那条存疑。
软承诺词: tuple[str, ...] = ("第一时间", "会优先处理", "按规则处理", "会安排", "会有专人")

_数字时限 = re.compile(r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)")
# 时限后面那截话。取 8 个字够覆盖「电话回访」「回到原支付渠道」这类，
# 又不至于把下一句也吞进来。
_时限后接动词 = re.compile(
    r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)\s*(?:内|之内|以内)?\s*"
    r"(?:会|能|可以|保证|肯定|一定)?\s*"
    r"([^\s，。；,;]{0,8})"
)


def 含软承诺(话术文本: str) -> bool:
    """这段话里有没有「顾客会因此开始等」的表述。

    转交话术必须都返回 True —— 见硬边界 3。
    """
    return bool(_数字时限.search(话术文本)) or any(w in 话术文本 for w in 软承诺词)


