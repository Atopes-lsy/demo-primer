#: 时限**不能**挂在这些动作上。硬边界 1。
#:
#: **为什么是黑名单不是白名单。** 这里最初写的是「允许的动作」白名单
#: （回访／联系／答复…），上线前自检直接炸了两条**合法**话术：
#: 「24 小时内**电话回访**」（动作是「电话回访」，前缀不是「回访」）
#: 和「退款 1-3 个工作日**回到原支付渠道**」（规格第二行明确要这么写）。
#: 合法说法是开放集合，列不完；而越权说法是**封闭**的一小撮 —— 就是
#: 「把时限承诺到结果上」。所以按黑名单查。
_禁止承诺的动作: tuple[str, ...] = (
    "解决", "处理完", "处理好", "修好", "搞定", "弄好", "查清", "查明", "恢复",
)

#: 软承诺词。虽然没给具体时限，但话一出口顾客就会等 —— 所以也必须客服点发送。
#: 见模块文档串里那条存疑。
软承诺词: tuple[str, ...] = ("第一时间", "会优先处理", "按规则处理", "会安排", "会有专人")

_数字时限 = re.compile(r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)")
# 时限后面那截话。取 8 个字够覆盖「电话回访」「回到原支付渠道」这类，
# 又不至于把下一句也吞进来。
_时限后接动词 = re.compile(
    r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)\s*(?:内|之内|以内)?\s*"
    r"(?:会|能|可以|保证|肯定|一定)?\s*"
    r"([^\s，。；,;]{0,8})"
)


def 含软承诺(话术文本: str) -> bool:
    """这段话里有没有「顾客会因此开始等」的表述。

    转交话术必须都返回 True —— 见硬边界 3。
    """
    return bool(_数字时限.search(话术文本)) or any(w in 话术文本 for w in 软承诺词)


