"""转交时给顾客的话术（规格 v9 §七「转交时给客服的对客话术」）。

**为什么转交不是「点一下按钮就完事」。** 客服必须对顾客说一句话。这句话里
只要出现时限，它就是**我们对顾客的承诺** —— 和「今天一定到账」是同一个性质
的东西，属于本产品该管的范围。所以转交这一步也得有话术、也得过闸门。

**下面这些话不是我编的。** 全部来自官方数据里 16 个转交类会话的客服原话
（不良反应 10 ／ 风控核实 3 ／ 质疑正品 3）。时限也不是编的，是数据里客服
已经在说的。

# 三条硬边界（违反就是越权承诺）

**1 · 「24 小时」是对「回访」的承诺，不是对「解决」的承诺。**
话术里只能写「回访／联系您」，**绝不能写成「24 小时内解决」**。这条由
`校验转交话术` 的正则兜着 —— 它是 §6.4 那类禁语的同族（时限＋承诺动词），
只是没进禁语表，因为它约束的是**转交话术**这个局部。

**2 · 风控类、丢件类禁止给具体时限。** 数据里客服自己都刻意只写「第一时间」，
我们不比客服更敢说。见 `不给具体时限`。

**3 · 这些话术一律走「② 客服点发送」，不走「① AI 直接发送」。**

> ⚠️ **关于第 3 条的一处存疑，记在这里别丢。** 规格给的理由是「因为它们含承诺
> （有明确时限）」—— 但那个理由**只对不良反应两行严格成立**；风控核实、物流丢件、
> 投诉升级、承诺逾期四行的 `时限` 都是 `None`（规格自己要求它们不给具体时限）。
> 所以这四行严格说没有「明确时限」。
>
> 结论按规格走（六行全部 → 客服点发送），但理由要换成更站得住的那条：
> **它们都含「软承诺」**（「第一时间联系您」「按规则处理」「会优先处理」）——
> 话一旦说出去，顾客就会等。所以 `含软承诺` 认的就是这些词，而不是时限。
> 这处存疑已经报给队长，规格下一版可能会改措辞。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class 转交话术:
    类型: str
    触发: str
    """什么触发的这类转交。给人看的，对应 `triggers.触发编号` 或口径编号。"""
    话术: str
    时限: str | None
    """给顾客的时限。`None` = 刻意不给具体时限（见 `不给具体时限`）。"""
    时限出处: str
    """这个时限凭什么。数据里的会话数或口径表原文。"""


#: 刻意不给具体时限的转交类型。硬边界 2。
#:
#: 判据是**规格的意图**不是文本特征 —— 风控和丢件属于「结果不可控」，
#: 给了时限反而制造二次违约。所以这是白名单，不是正则扫出来的。
不给具体时限: frozenset[str] = frozenset(
    {"风控核实", "物流丢件赔付", "投诉升级", "承诺逾期"}
)

#: 时限**不能**挂在这些动作上。硬边界 1。
#:
#: **为什么是黑名单不是白名单。** 这里最初写的是「允许的动作」白名单
#: （回访／联系／答复…），上线前自检直接炸了两条**合法**话术：
#: 「24 小时内**电话回访**」（动作是「电话回访」，前缀不是「回访」）
#: 和「退款 1-3 个工作日**回到原支付渠道**」（规格第二行明确要这么写）。
#: 合法说法是开放集合，列不完；而越权说法是**封闭**的一小撮 —— 就是
#: 「把时限承诺到结果上」。所以按黑名单查。
_禁止承诺的动作: tuple[str, ...] = (
    "解决", "处理完", "处理好", "修好", "搞定", "弄好", "查清", "查明", "恢复",
)

#: 软承诺词。虽然没给具体时限，但话一出口顾客就会等 —— 所以也必须客服点发送。
#: 见模块文档串里那条存疑。
软承诺词: tuple[str, ...] = ("第一时间", "会优先处理", "按规则处理", "会安排", "会有专人")

_数字时限 = re.compile(r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)")
# 时限后面那截话。取 8 个字够覆盖「电话回访」「回到原支付渠道」这类，
# 又不至于把下一句也吞进来。
_时限后接动词 = re.compile(
    r"\d+\s*(?:个)?\s*(?:小时|天|工作日|分钟|周)\s*(?:内|之内|以内)?\s*"
    r"(?:会|能|可以|保证|肯定|一定)?\s*"
    r"([^\s，。；,;]{0,8})"
)


def 含软承诺(话术文本: str) -> bool:
    """这段话里有没有「顾客会因此开始等」的表述。

    转交话术必须都返回 True —— 见硬边界 3。
    """
    return bool(_数字时限.search(话术文本)) or any(w in 话术文本 for w in 软承诺词)


# ══════════════════════════════════════════════════════════
# 六类转交话术（§七 表格逐行）
# ══════════════════════════════════════════════════════════

转交话术表: dict[str, 转交话术] = {
    t.类型: t
    for t in (
        转交话术(
            类型="不良反应",
            触发="H1 风险词",
            话术="已为您登记不良反应记录单，专员会在 24 小时内回访跟进。"
            "建议您先停用，若持续加重请及时就医。",
            时限="24 小时（回访）",
            时限出处="数据里 7 个会话原话一致",
        ),
        转交话术(
            类型="不良反应已就医",
            触发="H1 ＋ 已就医",
            话术="已为您建立不良反应专项工单并升级处理，专员会在 24 小时内电话回访；"
            "退款 1-3 个工作日回到原支付渠道。",
            时限="24 小时（回访）＋ 1-3 个工作日（退款）",
            时限出处="数据里 3 个会话原话",
        ),
        转交话术(
            类型="风控核实",
            触发="H4 ／ 包裹类型＝风控核实",
            话术="已提交核实工单，有结果我们会第一时间联系您；请您先保留外箱和面单。",
            时限=None,
            时限出处="数据里 3 个会话原话（客服用「第一时间」）",
        ),
        转交话术(
            类型="物流丢件赔付",
            触发="H1 丢件",
            话术="已为您登记物流异常，会安排核实；确认丢件后按规则处理，有进展第一时间同步您。",
            时限=None,
            时限出处="口径表 K16「不会轻易承诺」",
        ),
        转交话术(
            类型="投诉升级",
            触发="K20",
            话术="非常抱歉给您不好的体验，已为您升级，会有专人跟进回复。",
            时限=None,
            时限出处="口径表 K20 推荐话术",
        ),
        转交话术(
            类型="承诺逾期",
            触发="H3",
            话术="抱歉让您等了这么久。这边已经把情况升级给专员，会优先处理。",
            # H3 强制先道歉 —— 这句话以道歉开头，不是可选的措辞。
            时限=None,
            时限出处="H3 强制先道歉规则",
        ),
    )
}


#: H3 转交时要带的分类（§三：「带分类（产品／物流／公关）」）→ 用哪条话术。
#: 这三类都落到「承诺逾期」那一条 —— 分类是给**内部交接单**用的，
#: 对顾客说的话是同一句（都先道歉）。别把分类泄进对客话术里。
H3分类话术: dict[str, str] = {
    "产品": "承诺逾期",
    "物流": "承诺逾期",
    "公关": "承诺逾期",
}


class 转交话术越界(ValueError):
    """话术违反了三条硬边界之一。数据自己讲不通，不是调用方能兜住的。"""


def 校验转交话术() -> list[str]:
    """查六条话术有没有越过三条硬边界，返回违规说明（空列表表示干净）。

    **加载即校验、且是抛错不是警告** —— 和 `koujing.校验互斥` 同一个模式。
    理由也一样：这张表是「我们对顾客的承诺」的唯一出处，它错了，
    承诺就已经许出去了，调用方再怎么小心也来不及。
    """
    违规: list[str] = []

    for 类型, t in 转交话术表.items():
        # ── 硬边界 1：时限不能承诺到「结果」上，只能承诺「动作」 ──
        for m in _时限后接动词.finditer(t.话术):
            尾巴 = m.group(1)
            for 禁 in _禁止承诺的动作:
                if 禁 in 尾巴:
                    违规.append(
                        f"{类型}：「{m.group(0)}」把时限挂在了「{禁}」上。"
                        "时限只能承诺动作（回访／联系／到账），"
                        "承诺到结果上就是越权 —— 结果不由我们控制"
                    )
                    break

        # ── 硬边界 2：风控类／丢件类不得给具体时限 ──
        if 类型 in 不给具体时限 and (m := _数字时限.search(t.话术)):
            违规.append(
                f"{类型}：属于刻意不给时限的类型，话术里却出现了「{m.group(0)}」。"
                "数据里客服自己都只写「第一时间」，我们不比客服更敢说"
            )

        # ── 硬边界 3：每一条都得是「含承诺」的，因此必须走客服点发送 ──
        if not 含软承诺(t.话术):
            违规.append(
                f"{类型}：话术里既无时限也无软承诺词。转交话术的作用就是让顾客"
                "知道「有人在管」，没有这句就等于什么都没说"
            )

    return 违规


# 模块导入时校验一次。写在函数外面是有意的：这是数据错误，不是运行时状况，
# 早炸比晚炸好 —— 见 校验转交话术 的文档串。
if _违规 := 校验转交话术():
    raise 转交话术越界(
        "转交话术越界，发给顾客就是越权承诺：\n  - "
        + "\n  - ".join(_违规)
        + "\n（改话术表里对应的条目）"
    )


def 查转交话术(类型: str) -> 转交话术 | None:
    return 转交话术表.get(类型)
