#: H3 转交时要带的分类（§三：「带分类（产品／物流／公关）」）→ 用哪条话术。
#: 这三类都落到「承诺逾期」那一条 —— 分类是给**内部交接单**用的，
#: 对顾客说的话是同一句（都先道歉）。别把分类泄进对客话术里。
H3分类话术: dict[str, str] = {
    "产品": "承诺逾期",
    "物流": "承诺逾期",
    "公关": "承诺逾期",
}


#: H1 内部再分四支用的词表。**H1 一个编号盖不住这件事** —— 它的词表同时
#: 收着「过敏／红肿」（人身安全）和「投诉／曝光」（舆情），两类要说的
#: 是两句话。`转交话术表` 那一列 `触发` 写的「H1 风险词」「H1 ＋ 已就医」
#: 「H1 丢件」，说的就是这个内部再分。
#:
#: 词不是这里编的：四支分别照 `permissions.Z01/Z06/Z02` 的 `关键词` 和
#: `triggers.H1` 收的。**顺序有意义** —— 具体的压过笼统的（「已就医」在
#: 「不良反应」前面、「丢件」在「投诉」前面），和 `_出现` 那处长名优先同一个道理。
_H1分支: tuple[tuple[str, tuple[str, ...]], ...] = (
    # 「医院」而不是「去医院」：数据里客服说的是「去过医院」「去看了医生」，
    # 缺一个字就漏一整支 —— 而漏了它的后果是少说一句退款时效，不是报错。
    ("不良反应已就医", ("就医", "医院", "看过医生")),
    ("不良反应", ("不良反应", "过敏", "刺痛", "红肿", "泛红", "起疹")),
    ("物流丢件赔付", ("丢件", "丢了", "赔付", "找不回来", "快递丢")),
    ("投诉升级", ("投诉", "要主管", "找主管", "公关", "曝光")),
)


def 认转交话术(
    触发编号们: Sequence[触发编号],
    主张: str = "",
    依据编号们: Sequence[str] = (),
) -> 转交话术 | None:
    """这一条转交主张该对顾客说哪句，认不出返回 `None`。

    **这一步是「三层判定」第 3 层在转交这一支上的落点。** 在此之前这张表
    只被模块自检读，判定路径上没有任何人问它 —— 于是「转交要说什么」
    在判定里是一个空洞，而 `转交话术表` 里六句话没有一句曾经走到过顾客面前。

    # 顺序：先触发，再主张

    触发给的是**事实**（谁命中了），主张给的是**这件事是什么**。能用触发
    分辨的就用触发，分不了的才落到主张：

    - **H3 压倒 H1。** 这一条最容易写反，而且写反了不报错。剧本顾客 B
      那一轮 H1（要求投诉）和 H3（逾期）**同轮命中**，按 H1 走会拿到
      「专员会在 24 小时内回访跟进」—— 那是线一（不良反应）那句，
      对着一通已经要投诉的对话许 24 小时，等于把投诉升级成二次投诉。
      `剧本.ts` 第二步的备注记着「v1 在这儿写错过一次」。
      `H3分类话术` 三个分类全指向「承诺逾期」，本身就是这个顺序的证据。
    - **H4 单独走风控**，它和 H1 的语言不重叠。
    - **H1 落到 `_H1分支`**（见那张表的文档串）。
    - **一个硬触发都没有**时才是第 2 层权限矩阵判的转交，那种情况认口径
      会认出 `K20`（`Z02 投诉／要求主管` 那一族）—— 认到就给「投诉升级」。
      这也是 `转交话术表` 里那一行的 `触发` 写的字面值。

    # 认不出就留空，不猜

    和 `H3交接分类` 同一条规矩，但**理由更强**：交接单上分类错了只是多转一手；
    对客话术错了是**直接说给顾客**，而且这些话术**先于客服点发送**，说死了收不回来。

    具体会留空的两种：**H2 单独命中**（`转交话术表` 里没有 H2 那一行 ——
    H2 是情绪信号，规格 §七 的表是按**事项**分的六类，两者本来不同轴），
    以及第 2 层转交里认不出 K20 的那些（`Z03 售后期`、`Z04 质疑正品`、
    `Z07 直播承诺` 三条没有对应的话术行）。那时 `判成.转交话术` 是空串，
    主卡不显示话术块 —— **和今天的行为一样，不是回退，是这条路上本来就
    还没有这句话**。

    `依据编号们` 是 `判成.依据编号`（认口径认到的 K 编号）。
    """
    编号 = set(触发编号们)

    if 触发编号.H3 in 编号:
        return 转交话术表["承诺逾期"]
    if 触发编号.H4 in 编号:
        return 转交话术表["风控核实"]
    if 触发编号.H1 in 编号:
        for 类型, 词表 in _H1分支:
            if any(词 in 主张 for 词 in 词表):
                return 转交话术表[类型]
        return None
    if "K20" in set(依据编号们):
        return 转交话术表["投诉升级"]
    return None


class 转交话术越界(ValueError):
    """话术违反了三条硬边界之一。数据自己讲不通，不是调用方能兜住的。"""


def 校验转交话术(表: Mapping[str, 转交话术] | None = None) -> list[str]:
    """查六条话术有没有越过三条硬边界，返回违规说明（空列表表示干净）。

    **加载即校验、且是抛错不是警告** —— 和 `koujing.校验互斥` 同一个模式。
    理由也一样：这张表是「我们对顾客的承诺」的唯一出处，它错了，
    承诺就已经许出去了，调用方再怎么小心也来不及。

    `表` 留空用模块里的 `转交话术表` —— 参数位是给测试注入用的，和
    `安抚话术.校验安抚话术(表)` 同一个路数。**没有这个口子的话，三条硬边界
    只能对着真表断言「现在是对的」，测不出「错了会不会被拦住」** ——
    而「查得出来」才是这三条存在的意义。
    """
    违规: list[str] = []

    for 类型, t in (转交话术表 if 表 is None else 表).items():
        # ── 硬边界 1：时限不能承诺到「结果」上，只能承诺「动作」 ──
        for m in _时限后接动词.finditer(t.话术):
            尾巴 = m.group(1)
            for 禁 in _禁止承诺的动作:
                if 禁 in 尾巴:
                    违规.append(
                        f"{类型}：「{m.group(0)}」把时限挂在了「{禁}」上。"
                        "时限只能承诺动作（回访／联系／到账），"
                        "承诺到结果上就是越权 —— 结果不由我们控制"
                    )
                    break

        # ── 硬边界 2：风控类／丢件类不得给具体时限 ──
        if 类型 in 不给具体时限 and (m := _数字时限.search(t.话术)):
            违规.append(
                f"{类型}：属于刻意不给时限的类型，话术里却出现了「{m.group(0)}」。"
                "数据里客服自己都只写「第一时间」，我们不比客服更敢说"
            )

        # ── 硬边界 3：每一条都得是「含承诺」的，因此必须走客服点发送 ──
        if not 含软承诺(t.话术):
            违规.append(
                f"{类型}：话术里既无时限也无软承诺词。转交话术的作用就是让顾客"
                "知道「有人在管」，没有这句就等于什么都没说"
            )

    return 违规


# 模块导入时校验一次。写在函数外面是有意的：这是数据错误，不是运行时状况，
# 早炸比晚炸好 —— 见 校验转交话术 的文档串。
if _违规 := 校验转交话术():
    raise 转交话术越界(
        "转交话术越界，发给顾客就是越权承诺：\n  - "
        + "\n  - ".join(_违规)
        + "\n（改话术表里对应的条目）"
    )


def 查转交话术(类型: str) -> 转交话术 | None:
    return 转交话术表.get(类型)
