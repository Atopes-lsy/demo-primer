class 输出类型(StrEnum):
    """四种输出，优先级低 → 高。字段名与前端 `OutputKind` 一致。"""

    AI直发 = "AI直发"
    """不需要客服动手，Primer 自己发。"""

    客服点发送 = "客服点发送"
    """给出成稿，客服看一眼点一下。"""

    报备 = "报备"
    """事该办但越过客服额度，走审批。**顾客无感**，对话还在客服手里。"""

    转交 = "转交"
    """对话交出去，客服不再跟进。"""


#: 主卡只显示最高态。数值小的先判，让高优先级压过低优先级。
优先级: dict[输出类型, int] = {
    输出类型.AI直发: 0,
    输出类型.客服点发送: 1,
    输出类型.报备: 2,
    输出类型.转交: 3,
}

#: 终结性输出 —— 一旦出现，同轮其余动作不再各自执行。
#:
#: **为什么需要这张表。** 光有优先级只能决定「主卡显示哪个」，决定不了
#: 「其余那些动作还做不做」。一轮里可能同时有两条报备和两条转交，
#: 主卡显示「立即转交」—— 那两条报备还提交吗？对话都转出去了，报备给谁审批？
#: 不提交的话，右栏「本轮处置」里写着「已报备」就是假的。
#:
#: 转交的语义就是「整通对话交给专人」，所以它是终结性的：交出之后，
#: 同轮其余动作由接手的专人决定，客服不该再动手。
终结性: frozenset[输出类型] = frozenset({输出类型.转交})

#: 被终结性输出收编后，其余主张改写的说明。
收编说明 = "随对话一并转交"


# ══════════════════════════════════════════════════════════
# 第一层的规则表
# ══════════════════════════════════════════════════════════

#: 触发编号 → 输出类型。
#:
#: H2 情绪**不在这张表里**，是有意的：情绪是语气信号，不决定「这条诉求该怎么处置」，
#: 它约束的是话术怎么写（先安抚再给方案，见 `triggers.H2情绪` 的 说明）。
#: 把它也塞进判定表，会变成「顾客生气所以转交」，那是错的 —— 生气该安抚，不是推走。
触发输出表: dict[触发编号, 输出类型] = {
    触发编号.H1: 输出类型.转交,
    触发编号.H3: 输出类型.报备,  # 逾期要认账 + 安排，走审批，不交出去
    触发编号.H4: 输出类型.报备,  # 风控要核实，走审批
}

#: H1 中危降一档后的输出。
#:
#: 降的是**处置路径**（转交 → 报备），不是「降成不用人管」—— H1 的 说明 里
#: 「须走人工，不得由 AI 代答」对两档都成立。单纯差评威胁如果让 AI 自己回了，
#: 等它变成舆情就来不及了。
H1降一档 = 输出类型.报备

#: 触发编号 → `判成.说明`，让人看清是哪条规则定的。
触发说明: dict[触发编号, str] = {
    触发编号.H1: "H1 风险命中",
    触发编号.H3: "H3 命中：承诺已逾期",
    触发编号.H4: "H4 风控命中：诉求绕过平台流程",
}


