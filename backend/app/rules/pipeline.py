@dataclass(frozen=True, slots=True)
class 降级结果:
    """闸门拦下、且重生成修不动时，交给客服的东西。

    **降级的终点不是空白。** 降级成「需要话术」，如果给客服一张白纸，
    他从零写反而更慢、更容易踩口径 —— 把最后一次被拦的原文连同命中原因
    给他，改比写快，而且改出来的版本天然避开了已经指出的坑。

    这不是省事：`guards.重生成可行` 为 False 的两类（没有依据、谎称已做）
    本来就不是「写得不好」，而是材料或事实的问题。客服拿着原因去查，
    比模型在原地转圈有用。
    """

    话术: str
    """最后一次被拦的原文。客服在这上面改，不是从零写。"""

    原因: tuple[str, ...]
    """命中原因，人话。每条对应一个高危命中。"""

    依据: tuple[依据条目, ...]
    """依据清单 —— 客服要判断这句该不该发，得看得见材料。"""


def 造降级(话术: str, 命中: Sequence[object]) -> 降级结果:
    """从闸门命中造一个降级结果。

    `命中` 传 `guards.闸门命中` 序列。这里用 `object` 接是为了不引入循环导入 ——
    `guards` 已经依赖 `koujing`，`pipeline` 再被依赖回去会成环。
    """
    高危 = [h for h in 命中 if getattr(h, "严重度", "") == "高"]
    return 降级结果(
        话术=话术,
        原因=tuple(
            f"{getattr(h, '闸门', '')} {getattr(h, '详情', '')}；建议{getattr(h, '建议', '')}"
            for h in 高危
        ),
        依据=(),
    )


