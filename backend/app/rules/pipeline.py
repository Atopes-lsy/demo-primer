# ⚠️ **v9 §4.3 判的是话术，不是主张。** 这两条在 v9 里问的是「我们要说的
# 那句话有没有承诺含义／涉不涉个体差异」，而三层判定跑在**话术生成之前**
# —— 话还没有。所以这里只能**预判**：从顾客要什么反推我们答的时候会不会
# 沾上这两样。真正权威的那一关是 `guards`（G2措辞 拦越权承诺、G2边界句
# 强制边界句），它在话术生成之后跑。
#
# 预判必然比事后判宽，这是刻意的：宽出来的部分只是让客服多点一下，
# 漏掉的部分是 AI 把话说出去收不回来。

#: ①「有承诺含义」的预判词。v9 括注的三样：时间／金额／数量。
#:
#: **「退款」「补发」这类词也算。** 不是因为词本身是承诺，而是因为答它们
#: 必然要带上时限或数量（「已为您补发」就含数量和动作）。宁可多算。
_承诺时间 = re.compile(r"什么时候|多久|几天|几号|时效|时限|工作日|小时|当天|今天|明天|尽快")
_承诺金额 = re.compile(r"赔|补偿|退款|退钱|多少钱|多少元|\d+\s*(?:元|块)")
_承诺数量 = re.compile(r"几件|几个|几瓶|几盒|多少件|多少个|数量|补发|换货|补寄")

#: ②「涉个体差异」的预判词。v9 举的三类：孕妇／敏感肌／病史。
#: 覆盖 K01（孕期哺乳）、K10（成分安全·敏感肌）、K19（色号建议）。
_个体差异 = re.compile(
    r"孕妇|孕期|怀孕|哺乳|备孕|敏感肌|过敏体质|肤质|病史|宝宝|小孩|儿童|哺乳期"
)


def 有承诺(主张: str) -> bool:
    """这条主张答起来会不会带上承诺（时间／金额／数量）。见上面那段注释。"""
    return bool(_承诺时间.search(主张) or _承诺金额.search(主张) or _承诺数量.search(主张))


#: 判「涉个体差异」时读 `顾客情况` 里的**哪几行**。
#:
#: **只读「这是谁」。** v9 说读小卡不从主张里抠词，理由是「顾客分两句说也不会漏」
#: —— 顾客的身体情况（怀孕／哺乳／敏感肌／病史）**是这个人的属性**，归「这是谁」。
#: 另外三行（这次要什么／答应过什么／办过什么）说的是**这件事**，不是这个人。
#:
#: 从「这次要什么」里读健康词的代价是实测出来的：演示剧本第 3 步的
#: 「这次要什么：礼盒赠品漏发 ＋ 孕期能否用」会让**同轮的「赠品漏发」也判成
#: 涉个体差异** —— 于是一句补发通知也得带「建议咨询医生」。那是把上一件事的
#: 属性染到了下一件事上。
个体差异所在行: tuple[str, ...] = ("这是谁",)


def 涉个体差异(主张: str, 顾客情况: Sequence[tuple[str, str]] = ()) -> bool:
    """这条主张涉不涉个体差异。

    # 先读顾客情况，再退回主张

    v9 对这件事的要求很明确，而且给的理由值得原样抄下来：

    > **顾客小卡每条消息都读**，所以 LLM 读小卡时**本来就知道顾客是孕妇**。
    > 判断「涉不涉及个体差异」时**读小卡，不从主张里抠关键词** →
    > **顾客分两句说也不会漏**。

    反面例子就是它自己举的那个：S00474「这款洁面乳孕妇能用吗？我怀孕三个月了，
    之前一直在用」——「怀孕三个月」按 v9 的拆法**不拆成主张**，是背景，
    只留在小卡里。所以只看主张的实现在这条上必然漏。

    **但主张那一遍暂时还不能删。** 装配层（真的是它把「自然语言 → 结构化」
    做进小卡的那个组件）现在还没有，`顾客情况` 默认是空的 —— 只读小卡等于
    这道判据永远返回 False，G2 永远不触发。所以现在两条都读，**小卡优先**。
    等装配层能给结构化字段了，把主张那一遍去掉。

    **这是链路里的第三个模型位置**（前两个是 `认口径` 和 `permissions.认权限`）。
    关键词够跑通演示；真上线应该换成一次分类调用 —— 而且这次 v9 已经说了
    输入该是什么（小卡，不是主张）。换掉之后这一层就不再可重放，
    见模块文档串的「可重放的边界」。
    """
    if any(标签 in 个体差异所在行 and _个体差异.search(值) for 标签, 值 in 顾客情况):
        return True
    return bool(_个体差异.search(主张))


# ── 交接分类 ────────────────────────────────────────────────

#: H3 转交时要带的分类（v9 §三：「带分类（产品／物流／公关）」）→ 交给哪个队列。
#:
#: 判据用的是**主张里的词**，按下面的顺序取第一个命中的 —— 顺序有意义的：
#: 「快递丢件了，成分是不是有问题」同时含物流和产品词，该归物流队列。
_H3分类词: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("物流", ("物流", "快递", "发货", "包裹", "签收", "揽收", "丢件", "到货")),
    ("公关", ("曝光", "媒体", "投诉", "微博", "抖音", "小红书", "黑猫", "公关", "举报")),
    ("产品", ("成分", "质量", "色号", "破损", "过敏", "效果", "用法", "肤质", "正品")),
)


def H3交接分类(主张: str) -> str:
    """逾期的事该交接给哪一类专家。认不出返回空串。

    **认不出就留空，不猜一个默认分类。** 交接单上分类错了，比分类空着更糟 ——
    空着专家自己扫一眼就知道归谁，错了会先被转一手。
    """
    for 类, 词表 in _H3分类词:
        if any(w in 主张 for w in 词表):
            return 类
    return ""


#: 第 2 层去向 → 输出类型。
#:
#: **`判不了` 落报备，不是转交** —— §4.2 那张表的去向列写的就是报备，
#: 配套的关键原则是「系统查不到 ≠ 客服办不了，**不要把对话推给上级**」。
#: 报备的语义是「走个审批」，对话仍在客服手里。
#:
#: `在权限内` 不在这张表里：它不是去向，是「继续第 3 层」的信号。
_第2层输出: dict[权限去向, 输出类型] = {
    权限去向.报备: 输出类型.报备,
    权限去向.转交: 输出类型.转交,
    权限去向.判不了: 输出类型.报备,
}


def 三层判定(
    主张列表: Sequence[str],
    触发列表: Sequence[触发],
    六源: Mapping[str, 六源结果] | None = None,
    顾客情况: Sequence[tuple[str, str]] = (),
    权限矩阵: Sequence[权限条目] = 权限条目表,
    权限事实表: Mapping[str, 权限事实] | None = None,
    口径表: Sequence[口径条目] = (),
    认口径函数: Callable[[str], str | None] = lambda _: None,
) -> list[判成]:
    """跑完硬触发和三层，返回每条主张的输出。

    `主张列表` 来自拆主张（LLM）。
    `触发列表` 来自 `triggers.硬触发`，本轮的。
    `六源` 按**主张**索引（`{主张: 六源结果}`），缺的取 `空六源结果`。
    `权限事实表` 同样按主张索引，缺的取 `权限事实()`（各维度都是 `None`，
    于是但凡卡额度的条目都判**判不了 → 报备**）。这是刻意的：见
    `permissions.权限事实` 那段 —— 「在权限内」是要拿事实证明的结论。
    `口径表` / `认口径函数` 只用来填 `判成.依据编号`，**不再决定输出**。

    # 硬触发一命中，三层整个不跑

    见模块文档串。所以这个函数有两种完全不同的返回形态：
    触发命中时**整轮同一种输出**（说明里带是哪条触发的），
    没命中时逐条走三层。`判成.层` 字段区分这两类。

    # `顾客情况` 现在只用在一个地方

    第 3 层的「涉不涉个体差异」，而且 **v9 指定就该读它，不该从主张里抠词**
    —— 见 `涉个体差异` 那段引文。参数位早就留好了，接上的是这一处。

    「答应过什么」那一行迟早也要喂进来（它影响「有没有承诺」），
    但那个得等装配层给出结构化时限，现在还没有。
    """
    # ── 硬触发短路：整轮一个去向，不再往下问 ──
    #
    # **「整轮」不是「逐条」。** 旧实现把触发挂到含证据词的那条主张上、
    # 其余主张继续往下走。v9 §三 那句「不再往下问」的主语是**流程**，
    # 而且它给的理由是：「顾客礼貌地问第二次进度，客服本来就在处理中 ——
    # 直接踢给专家，会让专家队列被普通催单塞满」。把同轮其余主张放行，
    # 等于让 AI 在一条已经要转出的对话里继续说话。
    #
    # ⚠️ **两条硬触发出口和 `_判一条` 一样，`涉及个体差异` / `需边界句` 要一起设。**
    # G2 管的是**话术出稿**，不管这段话术是哪一层决定要发的 —— 转交给专家之后
    # 话还是得有人说，说的人一样需要边界句。只设前者，装配层拿 `需边界句` 当
    # G2 开关时就会把整道闸门跳过。下面用海象运算符是为了**只算一次**、
    # 让「两个字段同一个值」在代码里看得见。
    if 短路 := [t for t in 触发列表 if t.编号 in 短路触发]:
        # H3 同轮也在 → 这是 §三「逾期**且涉风险／公关代言**」那一档，
        # 转交要带分类（H3 单独命中走下面的报备档，不带分类）。
        h3 = next((t for t in 触发列表 if t.编号 == 触发编号.H3), None)
        return [
            判成(
                主张=m,
                输出=输出类型.转交,
                说明="；".join(_触发说明(t) for t in 短路),
                涉及个体差异=(差异 := 涉个体差异(m, 顾客情况)),
                需边界句=差异,
                层="硬触发",
                交接分类=H3交接分类(m) if h3 else "",
            )
            for m in 主张列表
        ]

    # ── H3 逾期：是**提示**，不是闸门 ──
    #
    # ⚠️ **这里原来是一个整轮早返回**（H3 命中 → 整个 `三层判定` 直接返回、
    # 每条主张统一报备），2026-10-01 拆掉（工单 A · 3.1）。三条理由：
    #
    # - v9 §三 的短路名单只有 `H1/H2/H4`，**H3 不在里面**（`短路触发` 那个
    #   `frozenset` 也只有这三个）。H3 的短路是另一个地方单独写的。
    # - 逾期是「**这一单**的事」，不是「这一轮**所有主张**的事」。演示里
    #   `S_DEMO_A` 同一会话、同一天，既有 H3（逾期），又有「含乙醇」该走 AI 直发
    #   —— 整轮报备把它一起冻住，S6 那一幕就演不出来。
    # - v9 给 H3 的原话是「高优先级报备（对话**还在客服手里**）」，
    #   而整轮报备恰恰是把对话冻住，和这半句相反。
    #
    # 去向没有丢：`permissions.E05 客服承诺逾期未做` 就是为这件事写的（§6.2），
    # 它原先 `可认=False` 正是因为 H3 替它挡着。
    #
    # H3 本身不消失：照常进 `触发[]`、照常进留痕，只是不再决定去向 ——
    # 它变成一条**出稿要求**，由 `_判一条` 拼进每条主张的说明。
    h3 = next((t for t in 触发列表 if t.编号 == 触发编号.H3), None)
    逾期提示 = f"{_触发说明(h3)}；开头必须先{H3道歉}" if h3 else ""

    # ── 没有短路触发 → 逐条走三层 ──
    六源 = 六源 or {}
    权限事实表 = 权限事实表 or {}
    return [
        _判一条(
            m,
            六源.get(m) or 空六源结果(m),
            权限事实表.get(m) or 权限事实(),
            权限矩阵,
            认口径函数,
            顾客情况,
            逾期提示=逾期提示,
        )
        for m in 主张列表
    ]


def _触发说明(t: 触发) -> str:
    return f"{触发说明.get(t.编号, str(t.编号))}：{'、'.join(t.证据)}"


def _判一条(
    主张: str,
    记录: 六源结果,
    事实: 权限事实,
    权限矩阵: Sequence[权限条目],
    认口径函数: Callable[[str], str | None],
    顾客情况: Sequence[tuple[str, str]] = (),
    逾期提示: str = "",
) -> 判成:
    """一条主张走完第 1→2→3 层。

    `逾期提示` 来自 `三层判定` 的 H3 分支（空串 ＝ 本轮没逾期）。它是**出稿
    要求**不是去向，所以拼在三条出口的说明后面、跟输出走而不跟层级走 ——
    第 1 层查不到、第 2 层报备、第 3 层直发，三种情况顾客都在等一个交代。
    """
    # 依据编号先认出来 —— 它不决定输出，只进右栏给客服对账。
    编号 = 认口径函数(主张)
    依据编号 = (编号,) if 编号 else ()

    def _带提示(文案: str) -> str:
        """把逾期提示缀在说明后面。三条出口都要过这一道，漏一条就少一句道歉。"""
        return f"{文案}；{逾期提示}" if 逾期提示 else 文案

    # 个体差异**在三条出口上都算**，所以提到前面来算一次。
    #
    # 它不只是第 3 层的判据，也是 `guards.G2边界句` 的输入 —— 而 G2 管的是
    # **话术出稿**这件事，不管这段话术是哪一层决定要发的。报备和转交的时候
    # 话也得有人说，说的人一样需要边界句。所以 `需边界句` 和 `涉及个体差异`
    # 在这三个 `判成(...)` 里必须取同一个值：只设前者不设后者，装配层拿
    # `需边界句` 当开关时就会把 G2 整个跳过。
    差异 = 涉个体差异(主张, 顾客情况)

    # ── 第 1 层 · 系统确认得了吗 ──
    if not 记录.有记录():
        return 判成(
            主张=主张,
            输出=兜底输出,
            说明=_带提示(
                "系统里查不到这条的依据，按保守处理交给你判断；"
                "可以先用一句安全话术稳住顾客，别自己编事实"
            ),
            依据编号=依据编号,
            涉及个体差异=差异,
            需边界句=差异,
            层="第1层",
        )

    # ⚠️ 序号在 `记录.记录` 的**键**上，所以这里必须 `.items()` 而不是 `.values()`。
    # 拍成平元组会把键当场丢掉，而且丢得没有痕迹 —— `源记录` 里没有序号字段，
    # 丢完之后类型上就看不出少了什么，要等右栏渲染或 G3 回查时才发现。
    依据 = tuple(
        依据条目(
            序号=str(源),
            出处=f"{r.table} · {r.row_id}" if r.row_id else r.table,
            摘要=r.content,
            用上=r.用上,
            成分=r.成分,
        )
        for 源, 组 in 记录.记录.items()
        for r in 组
        if r.exists
    )

    # ── 第 2 层 · 这件事归谁办 ──
    权限判定 = 查权限(主张, 事实, 权限矩阵)
    if not 权限判定.能否继续第3层():
        return 判成(
            主张=主张,
            输出=_第2层输出[权限判定.去向],
            说明=_带提示(权限判定.说明),
            依据=依据,
            依据编号=依据编号,
            涉及个体差异=差异,
            需边界句=差异,
            层="第2层",
            权限去向=权限判定.去向.value,
        )

    # ── 第 3 层 · 话怎么说（v9 §4.3 三行） ──
    承诺 = 有承诺(主张)
    if 承诺:
        说明 = "有承诺含义（时间／金额／数量），必须你自己点发送"
    elif 差异:
        说明 = "涉个体差异，必须带回边界句；不许单独发事实"
    else:
        # §七 ① 的原话是「在权限内」，但走到这里的还有一种是**未列明**
        # （矩阵里没有对口的事项）。两者都能继续第 3 层，可不是一回事 ——
        # 说明是给客服读的，不能替矩阵认下一条它没认过的授权。
        # 真实去向在 `判成.权限去向` 里，不靠这句话区分。
        归属 = "在权限内" if 权限判定.去向 is 权限去向.在权限内 else "不涉授权事项"
        说明 = f"有来源、{归属}、无承诺、不涉个体差异 —— 可以直接发"

    return 判成(
        主张=主张,
        输出=输出类型.AI直发 if not (承诺 or 差异) else 输出类型.客服点发送,
        说明=_带提示(说明),
        依据=依据,
        依据编号=依据编号,
        涉及个体差异=差异,
        需边界句=差异,
        层="第3层",
        权限去向=权限判定.去向.value,
    )


def 收敛(判成列表: Sequence[判成]) -> list[判成]:
    """把终结性输出应用到整轮。

    有转交 → 其余主张改写成「随对话一并转交」；没有 → 原样返回。
    见 `终结性` 那段注释解释为什么需要这一步。
    """
    if not any(d.输出 in 终结性 for d in 判成列表):
        return list(判成列表)

    return [
        d
        if d.输出 in 终结性
        else replace(d, 输出=输出类型.转交, 说明=f"{收编说明}（本判为「{d.输出}」）")
        for d in 判成列表
    ]


def 主卡形态(判成列表: Sequence[判成]) -> 输出类型 | None:
    """这一轮主卡该显示哪种输出。空列表返回 None（右栏只显示顾客情况）。"""
    if not 判成列表:
        return None
    return max((d.输出 for d in 判成列表), key=lambda o: 优先级[o])


