"""三层判定 —— 把「事实」和「主张」判成四种输出之一。

前面的 `inbound` / `triggers` 只报告**事实**（什么命中了、证据是哪几个词），
`guards` 只做**出站校验**。中间这段「那这些事实该判成什么」就是这里的事。
分开写是因为它们改动的理由不同：事实层随风险清单变，判定层随业务规则变，
闸门层随口径表变。混在一起，改输出规则就得动规则表。

# 三层

    第一层 · 硬触发层
      输入：H1–H4 的触发事实
      规则：见 `触发输出表`
      输出：一部分主张的输出已经定死，剩下的交给第二层

    第二层 · 主张层
      输入：还没定输出的主张 + 认出来的口径
      规则：见 `口径输出表`
      输出：每条主张一种输出

    第三层 · 兜底层
      输入：前两层都没覆盖的主张
      规则：默认「客服点发送」
      输出：剩余主张的输出

三层跑完还有一步**收敛**：如果有任何一条主张判成转交，同轮其余动作
按终结性处理（见 `终结性`）。

# 为什么兜底层是「客服点发送」而不是「AI直发」

兜底的默认值决定了两类错误的代价。判成 AI直发而判错了 —— AI 替客服说了
不该说的话，**话已经发出去了，收不回来**。判成客服点发送而判错了 ——
客服多点一下，看到内容不对自己会改。所以不确定的一律交给人。

# 可重放的边界

这一层是**纯规则，可重放**：同样的输入跑两遍得出同样的结论。
但它的两个输入里，`主张列表` 来自 LLM 拆解、`认口径` 可能也是模型做的 ——
**那两步不承诺可重放**，只承诺留有完整的调用记录可查。说「判定可重放」时
指的是这一层和它前面的规则层，别把模型那两步算进来。
"""

