@dataclass(frozen=True, slots=True)
class 轮消息:
    """切轮用得到的最小消息视图。字段名与 `ChatMessage` 对应。"""

    角色: str
    """买家 / 客服 / AI。"""
    文本: str
    发送时间: str
    """`YYYY-MM-DD HH:MM:SS`。只用来排序和展示，不参与判定。"""


@dataclass(frozen=True, slots=True)
class 轮次:
    """一轮 = 买家一段连续发言，到客服或 AI 回复为止。

    **为什么需要「轮」这个概念。** 判定入口原先是「一条消息进来」，
    但有三条规则需要不止一条消息才判得了：

    - H2 连发：同一句在最近几条里出现 ≥3 次
    - H3 逾期：跨轮的承诺状态
    - G4 防重复：历史上发出去的所有话

    「一条消息跑一次判定」这个粒度撑不起它们。顾客连发「在吗」「在吗？」
    「在吗！」时，前两条到时都只有 1、2 条消息，永远凑不到阈值 3。

    所以判定入口是**轮**，不是**条**。
    """

    买家消息: tuple[str, ...]
    """这一轮买家的全部发言，按时间升序。给 `triggers.硬触发` 的 `消息` 参数。"""

    开始时间: str
    结束时间: str

    @property
    def 全文(self) -> str:
        """这一轮的合并文本，给 `inbound.扫输入` 用。"""
        return "\n".join(self.买家消息)


def 切轮(消息: Sequence[轮消息]) -> list[轮次]:
    """把消息流切成轮。

    规则：买家发言开始一轮，客服或 AI 发言结束当前轮。连续买家消息归同一轮 ——
    这正是 H2 连发检测需要看到的形状。

    **防抖不在这里做。** 这条函数是纯的（同一输入必得同一输出，可重放）；
    而防抖是个时间窗口，属于运行时：
    「窗口内到达的买家消息合并成一轮，窗口关闭或客服先回复了才触发判定」。
    窗口长度是运行时参数，见 `判定的触发时机` 那段。
    """
    轮列表: list[轮次] = []
    当前: list[轮消息] = []

    def 收尾() -> None:
        if 当前:
            轮列表.append(
                轮次(
                    买家消息=tuple(m.文本 for m in 当前),
                    开始时间=当前[0].发送时间,
                    结束时间=当前[-1].发送时间,
                )
            )
            当前.clear()

    for m in 消息:
        if m.角色 == "买家":
            当前.append(m)
        else:
            收尾()

    收尾()  # 最后一批买家消息还没等到回复，也算一轮 —— 它正是要判定的那一轮
    return 轮列表


