#: 顾客情况的固定五行，顺序不能改 —— 前端默认只展开前两行。
顾客情况五行: tuple[str, ...] = ("这是谁", "这次要什么", "答应过什么", "办过什么", "这单")

#: 按会话缓存的行 —— 不在每轮重读的范围内。
#:
#: 「这是谁」（会员等级）和「这单」（订单信息）在一轮对话里不会变，它们是
#: 会话级快照。每轮重算既浪费，也让留痕无法解释「为什么这一轮的值和上一轮不同」。
#: 另外三行才是每轮要重读的。
按会话缓存: frozenset[str] = frozenset({"这是谁", "这单"})


@dataclass(frozen=True, slots=True)
class 顾客情况行:
    """`StateRow` 的服务端对应物。"""

    标签: str
    值: str
    备注: str = ""
    警示: str = ""
    时限: str = ""
    """**只「答应过什么」这一行有。** ISO 8601，给 H3 用。

    为什么单独一个字段：H3 要比时间，而「值」里写的是「9/26 承诺『今天答复』」
    —— 「今天」是相对承诺发生那一刻而言的，不是相对当前。规则解析极脆，
    LLM 解析又把模型塞到了 H3 前面。所以解析放在装配层（它本来就在做
    「自然语言 → 结构化」），H3 只读这个字段做比较。
    """


def 组装顾客情况(
    基础行: Sequence[顾客情况行],
    触发列表: Sequence[触发] = (),
) -> list[顾客情况行]:
    """两阶段组装：先出基础行，再把 H3 的结果回填成「警示」。

    **为什么分两步。** 「答应过什么」那一行的「警示」是 H3 的**输出**，
    而 H3 的**输入**（`时限`）又来自这一行 —— 直接写会成环。
    顺序定死就解开了：

        阶段 1（装配）：产出基础行，含结构化的 `时限`，不含 `警示`
        阶段 2（硬触发）：H3 读 `时限`，算出逾期天数
        阶段 3（回填）：把逾期天数写回 `警示`

    单向，无环。副作用是装配层可以缓存不变的行（见 `按会话缓存`）——
    因为「警示」是后填的，缓存基础行不会把上一轮的警示带进来。
    """
    行 = list(基础行)

    h3 = next((t for t in 触发列表 if t.编号 == 触发编号.H3), None)
    if h3 is None:
        return 行

    for i, r in enumerate(行):
        if r.标签 == "答应过什么":
            # H3 的证据形如「2026-09-26 23:59 承诺，已过 2 天」，取后半句。
            证据 = h3.证据[0] if h3.证据 else ""
            天数 = 证据.split("已过", 1)[-1].strip() if "已过" in 证据 else ""
            行[i] = replace(r, 警示=f"已逾期 {天数}" if 天数 else "已逾期")
            break

    return 行


def 已发出的话(消息: Iterable[轮消息], 本轮之后: Sequence[轮消息] = ()) -> list[str]:
    """给 `guards.G4防矛盾` 的 `已发出` 参数。

    **AI 代发的必须算进来。** 从顾客角度看，AI 说的和客服说的是同一个人在说话，
    重复就是重复。不算的话，AI 会对着同一个顾客把同一句话说两遍。

    参数名叫 `本轮之后` 有点绕，意思是：传进来的 `消息` 是本轮之前的全部历史，
    本轮自己新产生的内容不在这里面（它还没发出去）。
    """
    本轮文本 = {m.文本 for m in 本轮之后}
    return [
        m.文本
        for m in 消息
        if m.角色 in ("客服", "AI") and m.文本 and m.文本 not in 本轮文本
    ]


