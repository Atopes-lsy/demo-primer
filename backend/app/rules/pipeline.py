#: 防抖窗口（毫秒）。
#:
#: 「一条消息进来就判一次」在连发场景下会连出三次结论，而且前两次都是错的
#: （凑不到 H2 的阈值 3）。所以判定挂在**轮**上，但要有个「这一轮结束了」的信号。
#:
#: 两个信号，谁先到算谁：
#:   1. 窗口超时 —— 买家发完最后一条后静默这么久
#:   2. 客服或 AI 先回复了 —— 那这一轮已经过去了
#:
#: 800ms 是起点，不是定论：太短会把连发拆成两轮（H2 失效），太长会让客服觉得
#: 右栏反应慢。真实值要看线上买家的输入节奏，演示时这个数值得能当场调。
防抖毫秒 = 800
