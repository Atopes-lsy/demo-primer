@dataclass(frozen=True, slots=True)
class 判成:
    """一条主张被判成了什么。字段与前端 `Disposition` 一致。"""

    主张: str
    输出: 输出类型
    说明: str
    """补充说明，如「H1 风险词命中」「涉个体差异，必须带边界句」。"""


def 认口径(主张: str, 口径表: Sequence[口径条目]) -> str | None:
    """把一条主张认到某个口径编号上，认不出返回 None。

    **这是链路里的一个模型位置。** 现在用关键词做，够跑通演示；真上线应该
    换成向量检索（主张 → 口径表条目的 embedding 相似度）或一次 LLM 分类。
    换成模型之后这一层的「可重放」就不成立了，见模块文档串。

    关键词取「话题」名里的字。话题名是人写的，长短不一（「成分安全(酒精/香精)」
    和「预售与尾款」），所以按命中字数从多到少取，让具体的压过笼统的。
    """
    命中: list[tuple[int, str]] = []
    for k in 口径表:
        # 话题名可能带括号补充，如「成分安全(酒精/香精)」—— 括号里也是线索。
        for 段 in k.话题.replace("(", " ").replace(")", " ").replace("/", " ").split():
            # 只取长度 ≥2 的段。「使用」这种两字词误伤面大但胜在能召回，
            # 靠下面按长度排序让更具体的先中。
            if len(段) >= 2 and 段 in 主张:
                命中.append((len(段), k.编号))

    if not 命中:
        return None
    # 命中的字越多越具体。同长度按编号，保证顺序稳定 —— 可重放的要求。
    命中.sort(key=lambda x: (-x[0], x[1]))
    return 命中[0][1]


def 三层判定(
    主张列表: Sequence[str],
    触发列表: Sequence[触发],
    口径表: Sequence[口径条目] = (),
    认口径函数: Callable[[str], str | None] = lambda _: None,
) -> list[判成]:
    """跑完三层，返回每条主张的输出。

    `主张列表` 来自拆主张（LLM）。
    `触发列表` 来自 `triggers.硬触发`，本轮的。
    `认口径函数` 把一条主张映射到口径编号，默认返回 None（全走兜底）。

    **第一层先跑，且不短路。** H1 命中不意味着后面两层不用跑 ——
    风险要归因到具体主张上（见 `triggers` 模块文档串里的说明）。
    """
    结果: dict[str, 判成] = {}

    # ── 第一层 · 硬触发 ──
    # 触发要挂到哪条主张上？靠证据词：H1 的证据是「刺痛」「投诉」这些原词，
    # 哪条主张里有它，就是哪条主张触发的。
    for t in 触发列表:
        输出 = 触发输出表.get(t.编号)
        if 输出 is None:
            continue  # H2 不决定输出
        if t.编号 == 触发编号.H1 and t.严重度 == "中":
            输出 = H1降一档

        for 主张 in 主张列表:
            命中的证据 = [e for e in t.证据 if e and e in 主张]
            if not 命中的证据:
                continue
            结果[主张] = 判成(
                主张=主张,
                输出=输出,
                说明=f"{触发说明.get(t.编号, str(t.编号))}：{'、'.join(命中的证据)}",
            )

    # ── 第二层 · 主张层 ──
    for 主张 in 主张列表:
        if 主张 in 结果:
            continue
        编号 = 认口径函数(主张)
        if 编号 is None or 编号 not in 口径输出表:
            continue
        结果[主张] = 判成(
            主张=主张,
            输出=口径输出表[编号],
            说明=f"依据：口径表 {编号}",
        )

    # ── 第三层 · 兜底 ──
    for 主张 in 主张列表:
        if 主张 in 结果:
            continue
        结果[主张] = 判成(
            主张=主张,
            输出=兜底输出,
            说明="没匹配到口径，按保守处理交给你判断",
        )

    # 保持传入顺序，别让调用方拿到的顺序随字典跑。
    return [结果[m] for m in 主张列表]


def 收敛(判成列表: Sequence[判成]) -> list[判成]:
    """把终结性输出应用到整轮。

    有转交 → 其余主张改写成「随对话一并转交」；没有 → 原样返回。
    见 `终结性` 那段注释解释为什么需要这一步。
    """
    if not any(d.输出 in 终结性 for d in 判成列表):
        return list(判成列表)

    return [
        d
        if d.输出 in 终结性
        else replace(d, 输出=输出类型.转交, 说明=f"{收编说明}（本判为「{d.输出}」）")
        for d in 判成列表
    ]


def 主卡形态(判成列表: Sequence[判成]) -> 输出类型 | None:
    """这一轮主卡该显示哪种输出。空列表返回 None（右栏只显示顾客情况）。"""
    if not 判成列表:
        return None
    return max((d.输出 for d in 判成列表), key=lambda o: 优先级[o])


