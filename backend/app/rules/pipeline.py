def 认口径(主张: str, 口径表: Sequence[口径条目]) -> str | None:
    """把一条主张认到某个口径编号上，认不出返回 None。

    **这是链路里的一个模型位置。** 现在用关键词做，够跑通演示；真上线应该
    换成向量检索（主张 → 口径表条目的 embedding 相似度）或一次 LLM 分类。
    换成模型之后这一层的「可重放」就不成立了，见模块文档串。

    关键词取「话题」名里的字。话题名是人写的，长短不一（「成分安全(酒精/香精)」
    和「预售与尾款」），所以按命中字数从多到少取，让具体的压过笼统的。
    """
    命中: list[tuple[int, str]] = []
    for k in 口径表:
        # 话题名可能带括号补充，如「成分安全(酒精/香精)」—— 括号里也是线索。
        for 段 in k.话题.replace("(", " ").replace(")", " ").replace("/", " ").split():
            # 只取长度 ≥2 的段。「使用」这种两字词误伤面大但胜在能召回，
            # 靠下面按长度排序让更具体的先中。
            if len(段) >= 2 and 段 in 主张:
                命中.append((len(段), k.编号))

    if not 命中:
        return None
    # 命中的字越多越具体。同长度按编号，保证顺序稳定 —— 可重放的要求。
    命中.sort(key=lambda x: (-x[0], x[1]))
    return 命中[0][1]


