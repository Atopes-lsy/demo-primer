"""成分表那一套词汇：什么算同一个物质，以及话术里怎么说「含／不含」。

# 为什么要单独一个模块

`rules/guards.G3来源可查` 要用它，`检索/商品表.含成分` 也要用它。而
`检索/商品表` → `data/装载器` → `api/schemas` → `rules/pipeline` → `rules/guards`
已经是一条链了 —— 反过来让 `guards` 去 import `商品表` 就成环。
所以词汇表落在**叶子模块**上：本模块不 import 任何 app 内的东西。

# 为什么不复用 `rules/koujing`

口径表是从 `口径表_v4_定稿.xlsx` 读进来的**业务数据**；这里的词是
**写死在代码里的判据**。两者的修法和改动频率都不一样，混在一起会让
「口径表改了一版」和「别名表该不该加一条」变成同一件事。

# 抠词在这里是错的

`成分表（完整）` 是顿号分隔的物质名列表，「含不含 X」结构上是**集合成员判断**。
拿子串做的话，17/20 个商品的答案会反过来（`苯氧乙醇` 含「乙醇」）。
详见 `检索/商品表.py` 的模块文档串。
"""

from __future__ import annotations

import re
from collections.abc import Sequence

#: 「酒精」这一类该认的几个叫法。**`苯氧乙醇` 不在里面** —— 它是防腐剂，
#: 不是酒精；收进来就等于对 17/20 的商品说「含酒精」。
#:
#: `变性乙醇` 是**真的酒精**（乙醇 ＋ 变性剂），收它有依据。真表 20 个商品里
#: 只有 `XL21204 测试净澈卸妆水300ml` 含它。其余叫法（「食用酒精」之类）
#: 要不要收，得业务方点头 —— 先只收这三个。
酒精别名 = frozenset({"乙醇", "酒精", "变性乙醇"})

#: 断言「不含」的说法。**必须紧挨在物质名前面**才算 —— 管辖范围是那一个词，
#: 不是整句。「含苯氧乙醇，不含乙醇」里两个断言各管各的。
否定说法 = re.compile(r"(?:不含|不含有|不添加|未添加|未加|不加|没有|无)\s*$")

#: 断言「含」的说法。**故意不收单独的「有」** —— 「有货了」「有货再通知您」
#: 在客服话术里太常见，收进来就等于这道检查满屏误报。
肯定说法 = re.compile(r"(?:含有|含|添加了|加入了|加了)\s*$")

#: 往前看几个字。
#:
#: ⚠️ **这个值不影响判断结果。** 防串句的是下面两个正则末尾的 `$` 锚点：窗口只
#: 往**前**扩字，右端永远钉在物质名前面那一个字上，而候选词最长 3 个字
#: （`不含有`／`添加了`），所以窗口 ≥3 之后行为完全一样。变异检查实测：
#: 调到 999，全套用例一条都不红 —— 那是**等价变异**，不是用例漏了。
#:
#: 留着它是给以后更长的说法留余量（「本产品中并未添加」）。**那天值才需要涨**；
#: 在那之前别把它当成调参的地方 —— 调它不会改变任何一句的判定。
回看 = 6


def 扫断言(话术: str, 物质们: Sequence[str]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """话术里关于成分的断言，跟「物质们」打架的挑出来。

    返回 `(说了「不含」但其实有的, 说了「含」但其实没有的)`，两边都已去重。

    `物质们` 是**商品表那一行解析好的物质名**（`商品表.成分名` 的产出）。
    **它必须是 token，不能是摘要原文** —— 拿原文来查，正确答案和错误答案会被
    一视同仁地放行，那正是这一整套东西要消灭的失败方式。

    两个方向都查：
    - 说了「不含 X」而 X 在表里 → 是对着顾客的**假承诺**（顾客会照它做决定）
    - 说了「含 X」而 X 不在表里 → 同样是在编事实

    别名认的是 `酒精别名`：话术说「酒精」而成分表写的是「变性乙醇」，
    这算**有**；反过来，成分表里只有「苯氧乙醇」时，说「不含酒精」是对的。
    """
    词表 = list(dict.fromkeys([*物质们, *sorted(酒精别名)]))
    说了不含: list[str] = []
    说了含: list[str] = []

    for 词 in 词表:
        # 别名感知的成员判断：词本身，或它的任一别名叫法，出现在物质名里就算有。
        候选 = {词, *酒精别名}
        有 = any(物 in 候选 for 物 in 物质们)

        起点 = 0
        while (i := 话术.find(词, 起点)) >= 0:
            起点 = i + 1
            前面 = 话术[max(0, i - 回看) : i]
            if 否定说法.search(前面):
                if 有 and 词 not in 说了不含:
                    说了不含.append(词)
            elif 肯定说法.search(前面) and not 有 and 词 not in 说了含:
                说了含.append(词)

    return tuple(说了不含), tuple(说了含)
