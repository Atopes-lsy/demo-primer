"""成分表那一套词汇：什么算同一个物质，以及话术里怎么说「含／不含」。

# 为什么要单独一个模块

`rules/guards.G3来源可查` 要用它，`检索/商品表.含成分` 也要用它。而
`检索/商品表` → `data/装载器` → `api/schemas` → `rules/pipeline` → `rules/guards`
已经是一条链了 —— 反过来让 `guards` 去 import `商品表` 就成环。
所以词汇表落在**叶子模块**上：本模块不 import 任何 app 内的东西。

# 为什么不复用 `rules/koujing`

口径表是从 `口径表_v4_定稿.xlsx` 读进来的**业务数据**；这里的词是
**写死在代码里的判据**。两者的修法和改动频率都不一样，混在一起会让
「口径表改了一版」和「别名表该不该加一条」变成同一件事。

# 抠词在这里是错的

`成分表（完整）` 是顿号分隔的物质名列表，「含不含 X」结构上是**集合成员判断**。
拿子串做的话，17/20 个商品的答案会反过来（`苯氧乙醇` 含「乙醇」）。
详见 `检索/商品表.py` 的模块文档串。

# 话术这一侧：断言的作用域是分句

`扫断言` 干的不是「找否定词」，是「这条话术对某个物质名下了什么断言」。
判据是**分句内位置更靠后的那个断言说了算**，于是 `不含酒精和香精` 判成不含
（拦），`不含酒精，香精含量0.1%` 不判，`不含酒精但含香精` 判成含（不误拦）。
函数文档串里记着这条规则踩过的两个坑：**`不含` 里面有一个 `含`**，
以及**「乙醇」出现在「苯氧乙醇」中间** —— 两个都是子串陷阱，形状和上面那条一样。
"""

from __future__ import annotations

import re
from collections.abc import Sequence

#: 「酒精」这一类该认的几个叫法。**`苯氧乙醇` 不在里面** —— 它是防腐剂，
#: 不是酒精；收进来就等于对 17/20 的商品说「含酒精」。
#:
#: `变性乙醇` 是**真的酒精**（乙醇 ＋ 变性剂），收它有依据。真表 20 个商品里
#: 只有 `XL21204 测试净澈卸妆水300ml` 含它。其余叫法（「食用酒精」之类）
#: 要不要收，得业务方点头 —— 先只收这三个。
酒精别名 = frozenset({"乙醇", "酒精", "变性乙醇"})

#: 断言「不含」的说法。
#:
#: ⚠️ **不带 `$` 锚点。** 作用是分句（见下），锚在末尾就等于还是「紧挨着」。
否定说法 = re.compile(r"(?:不含|不含有|不添加|未添加|未加|不加|没有|无)")

#: 断言「含」的说法。**故意不收单独的「有」** —— 「有货了」「有货再通知您」
#: 在客服话术里太常见，收进来就等于这道检查满屏误报。
#:
#: ⚠️ 同样不带锚点。而且它**会在「不含」里面命中一个「含」**（那个字逐字就在
#: 里面），得由 `_断言` 排掉 —— 见那里的注释，这是个真踩过的坑。
肯定说法 = re.compile(r"(?:含有|含|添加了|加入了|加了)")

#: 分句标点。否定词的作用域到分句为止。
#:
#: ⚠️ **顿号不在里面。** 它在分句**内部**并列，所以 `不含酒精、香精` 的否定词
#: 得跨过它管到香精 —— 收进来就等于把这一整节要修的那个漏判又放回去了。
分句标点 = re.compile(r"[，。；！？,;!?…\n]")

#: 断言的两种取值。用字符串而不是 `bool`：调用处 `if 断言 is 不含` 比
#: `if 断言 is False` 读起来少一次心算。
不含 = "不含"
含 = "含"


def 扫断言(话术: str, 物质们: Sequence[str]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """话术里关于成分的断言，跟「物质们」打架的挑出来。

    返回 `(说了「不含」但其实有的, 说了「含」但其实没有的)`，两边都已去重。

    `物质们` 是**商品表那一行解析好的物质名**（`商品表.成分名` 的产出）。
    **它必须是 token，不能是摘要原文** —— 拿原文来查，正确答案和错误答案会被
    一视同仁地放行，那正是这一整套东西要消灭的失败方式。

    两个方向都查：
    - 说了「不含 X」而 X 在表里 → 是对着顾客的**假承诺**（顾客会照它做决定）
    - 说了「含 X」而 X 不在表里 → 同样是在编事实

    别名认的是 `酒精别名`：话术说「酒精」而成分表写的是「变性乙醇」，
    这算**有**；反过来，成分表里只有「苯氧乙醇」时，说「不含酒精」是对的。

    # 断言的作用域是分句，取分句内**位置更靠后**的那个

    原来是「否定词必须紧挨着物质名」。那个判据会漏掉 `不含酒精和香精`
    ——「香精」前面是「酒精和」，一个字都不是否定词。而它是客服最自然的写法，
    且 13/20 的真商品含香精，所以它是**半真半假**的一句。

    改成分句内比位置之后，「不含酒精和香精」判成不含（拦）、
    「不含酒精，香精含量0.1%」不判（后一个断言在别的分句）、
    「不含酒精但含香精」判成含（不误拦）。**不需要单独认转折词** ——
    位置比较天然就把「但／可是／然而」处理了，而列一张转折词表就得一直补。
    """
    词表 = list(dict.fromkeys([*物质们, *sorted(酒精别名)]))
    说了不含: list[str] = []
    说了含: list[str] = []

    for 词, i in _出现(话术, 词表):
        # 别名感知的成员判断：词本身，或它的任一别名叫法，出现在物质名里就算有。
        候选 = {词, *酒精别名}
        有 = any(物 in 候选 for 物 in 物质们)

        断 = _断言(话术[_分句起点(话术, i) : i])
        if 断 is 不含 and 有 and 词 not in 说了不含:
            说了不含.append(词)
        elif 断 is 含 and not 有 and 词 not in 说了含:
            说了含.append(词)

    return tuple(说了不含), tuple(说了含)


def _出现(话术: str, 词表: Sequence[str]) -> list[tuple[str, int]]:
    """话术里出现过的物质名和位置。**长名优先，被长名罩住的那次不算。**

    「本品配方含苯氧乙醇，不含乙醇」里，「乙醇」逐字出现在「苯氧乙醇」中间。
    不排掉的话前半句会被读成「说含乙醇」——而那句话里根本没有乙醇这个断言，
    后半句才是，而且说的是「不含」。

    ⚠️ 这和 `检索/商品表` 那一脚**是同一个陷阱的两次发作**：那边是成分表里
    拿「乙醇」去查被「苯氧乙醇」命中，这边是话术里找「乙醇」先找到了
    「苯氧乙醇」里面那两个字。那边靠整名相等解决，这边靠长名优先。

    `sorted(key=len, reverse=True)` 是这里唯一的机关：先让「苯氧乙醇」占住
    (5,9)，后轮到「乙醇」时那两次区间包含检查就会把里面的 (7,9) 挑出来。
    """
    找到: list[tuple[str, int]] = []
    已占: list[tuple[int, int]] = []
    for 词 in sorted(词表, key=len, reverse=True):
        起点 = 0
        while (i := 话术.find(词, 起点)) >= 0:
            起点 = i + 1
            区间 = (i, i + len(词))
            if any(起 <= 区间[0] and 区间[1] <= 止 for 起, 止 in 已占):
                continue
            已占.append(区间)
            找到.append((词, i))
    return 找到


def _分句起点(话术: str, 位置: int) -> int:
    """`位置` 所在分句的起点 —— 它前面最后一个分句标点之后那一个字。"""
    切 = [m.end() for m in 分句标点.finditer(话术, 0, 位置)]
    return 切[-1] if 切 else 0


def _断言(前面: str) -> str | None:
    """`前面` 这段里对物质名的断言是不含还是含，没有断言就是 `None`。

    **位置更靠后的那个说了算。** 「不含酒精但含香精」里两个都有，靠后的「含」
    管用 —— 这正是它不必认识「但」的原因。

    ⚠️ **「不含」里面有一个「含」，得先把它剔掉。** 不剔的话「本品配方不含」
    里两个断言都落在第 6 个字上，**打平**，而比位置比不出平手该给谁 ——
    实测这一脚把 9 条用例踩红。去掉 `$` 之前它们是同一个终点，去掉之后
    `含` 的起点仍落在 `不含` 的区间里，所以判据是**区间包含**而不是终点相等。
    """
    否们 = list(否定说法.finditer(前面))
    肯们 = [
        m
        for m in 肯定说法.finditer(前面)
        if not any(n.start() <= m.start() < n.end() for n in 否们)
    ]
    否 = max((m.end() for m in 否们), default=None)
    肯 = max((m.end() for m in 肯们), default=None)
    if 否 is None and 肯 is None:
        return None
    # 剔干净之后不会有平手：终点相同且不重叠的两个区间不可能存在。
    return 不含 if (肯 is None or (否 is not None and 否 > 肯)) else 含
