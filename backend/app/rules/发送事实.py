"""发送时的订单事实对照，与 frontend/src/data/事实.ts 的两条断言同口径。

只检查已发货、已签收的明确完成说法；不推断所有自然语言是否真实。
订单不存在时由调用方跳过，不把未知当作冲突。
"""

import re

_已发货 = re.compile(r"(?:已经|已)\s*(?:发出|发货|寄出|发走)|(?:发出|发货|寄出)了")
_已签收 = re.compile(r"(?:已经|已)\s*签收")


def 查订单事实(文本: str, *, 发货时间: str, 订单状态: str) -> str | None:
    if _已发货.search(文本) and not 发货时间:
        return "事实不一致：订单没有发货时间，不能声称已发货。请先核实发出时间。"
    if _已签收.search(文本) and "签收" not in 订单状态:
        return "事实不一致：订单状态未显示签收，不能声称已签收。请先核实物流。"
    return None
