"""闸门 G1–G4 —— 出站校验，纯规则。

话术生成完、发给顾客之前过一遍。**这套闸门是话术模型不必完美的原因**：
生成侧只要大多数时候说得对就行，漏出来的由这里兜住。所以模型选型可以省钱，
闸门不能省。

四个闸门管的不是一回事，别混：

- **G1 禁语** —— 这个词按口径表就是不能出现。查表，最硬。
- **G2 边界** —— G1 是口径表点名的词，G2 是我们从经验里补的绝对化表述。
  **两者机制相同（都是子串扫描），区别在词的来源和严重度**：G1 的词有口径依据，
  G2 的词没有，所以 G2 只对最硬的那几个判高（见 `G2绝对化硬` / `G2绝对化软`）。
- **G3 来源可查** —— 话术里的数字和事实得能追到依据。防的是模型自己编。
- **G4 防矛盾** —— 别和之前说过的话、和顾客情况打架。

**命中之后不是一律重生成。** 修得动的是措辞，修不动的是事实 —— 用 `重生成可行`
分流，别让模型对着一个「没有依据」死磕（见该函数的文档串）。

**G4 的能力边界要说清楚**：语义级的自相矛盾需要模型来判，这里做的是可列举的
几种。真加了模型判官，它也只能当**检查者**不能当**决定者** —— 决定权在规则
和客服手里，否则整套留痕就没有依据了。
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass

from .koujing import 查禁语全, 禁语命中


@dataclass(frozen=True, slots=True)
class 依据条目:
    """话术引用的来源。字段与前端 `Evidence` 一致。"""

    序号: str
    出处: str
    摘要: str
    用上: bool = True


@dataclass(frozen=True, slots=True)
class 闸门命中:
    闸门: str
    名称: str
    严重度: str
    详情: str
    证据: tuple[str, ...]
    建议: str
    可重生成: bool = True
    """这条命中能不能靠「重新生成」修掉。

    默认 True（绝大多数命中是措辞问题）。判 False 的两类见 `重生成可行`。
    """

    def __str__(self) -> str:
        return f"{self.闸门} {self.名称}：{self.详情}"


# ── G2 边界 ────────────────────────────────────────────────
# 形状是「把话说死」。分两组是因为误伤面差得远 —— 见下。
#
#: 真·绝对化：出现即不可接受，判高（阻断 + 触发重生成）。
G2绝对化硬: tuple[str, ...] = (
    "绝对", "100%", "百分之百", "包退", "包换", "包赔", "永不", "绝不",
)
#: 泛化强调：中文里分布极广（「一定要试试」「必须给您补上」「随时联系我」），
#: 判中（只记录不阻断）。原先它们和硬组一起判高，会让正常话术大面积重生成。
#: 「绝不会」不单列 —— 「绝不」是它的子串，列了也是重复命中。
G2绝对化软: tuple[str, ...] = (
    "保证", "肯定", "一定", "必须", "永远", "无条件", "随时",
)
#: 越权承诺：承诺了金额或时限。客服无权在会话里许这些。
#: **这条才是真正拦句式的** —— 上面两组是词，这条匹配的是「我赔你 50 元」这种结构。
G2越权 = re.compile(
    r"(我|我们|这边)(赔|退|补|送|免|给)(你|您)?"
    r"|赔(偿)?(你|您)?\s*\d"
    r"|(退|补|赔)(你|您)?\s*\d+\s*(元|块)"
    r"|\d+\s*(元|块).{0,4}(赔偿|补偿|打款)"
)

# ── G3 来源可查 ────────────────────────────────────────────
#: 话术里带单位的数字。裸数字（如「3 次」）不查，误报太多。
G3带单位数字 = re.compile(r"\d+(?:\.\d+)?\s*(?:个)?(?:工作日|小时|天|元|折|ml|mL|克|g)")

# ── G4 防矛盾 ──────────────────────────────────────────────
#: 一句「已经做过某事」的起头。`已` 和动作之间常隔着礼貌插入语，
#: 字面查 `已安排` 查不到「已经为您安排」。
G4已发生头 = re.compile(r"已(?:经)?(?:为您|给你|给亲|帮您|帮亲|这边|特别为您)?")
#: 可以被「已」修饰的动作词。
G4动作词 = re.compile(r"补发|发出|发货|登记|提交|安排|处理|申请|核实|上报")
#: 句读。一段「已」管辖的范围到句读为止。
G4句读 = re.compile(r"[，。；！？!?,.;\n]")
#: 相似度阈值：两条话术的重合词占比超过这个数，就算同一句说了两遍。
G4重复阈值 = 0.75


def _已发生动作(话术: str) -> list[str]:
    """抽出话术里所有「已经做过」的动作断言。

    不能只取第一个匹配：「已经为您安排补发」里的 `安排` 只是虚动词，
    真正的内容是 `补发`；正则的择一会先吃掉 `安排` 就收工。所以要顺着
    每个「已」往后扫一整段，把这段里的动作词全捞出来。
    """
    动作: list[str] = []
    for m in G4已发生头.finditer(话术):
        段 = G4句读.split(话术[m.end() :], maxsplit=1)[0]
        动作.extend(G4动作词.findall(段))
    return 动作


def _词集(text: str) -> set[str]:
    """按 2-gram 切，中文没有空格，字级切分比词级稳。"""
    干净 = re.sub(r"[\s\W_]+", "", text)
    return {干净[i : i + 2] for i in range(len(干净) - 1)}


def _去空格(text: str) -> str:
    """比对数字时用：「48 小时」和「48小时」是同一个数。"""
    return re.sub(r"\s+", "", text)


def G1禁语(话术: str, 路径: str | None = None) -> list[闸门命中]:
    """扫禁语。返回全部命中，不是第一条 —— 留痕要记全。"""
    return [
        _G1命中(h)
        for h in 查禁语全(话术, 路径)
    ]


def _G1命中(h: 禁语命中) -> 闸门命中:
    return 闸门命中(
        闸门="G1",
        名称="禁语",
        严重度=h.严重度,
        详情=f"命中禁语「{h.禁语}」（口径表 {h.口径}）",
        证据=(h.禁语,),
        建议=f"改为「{h.建议}」",
    )


def G2边界(话术: str) -> list[闸门命中]:
    """查把话说死的措辞和越权承诺。

    **两组词严重度不同，是刻意的。** 硬组（绝对/包退/100%）出现即不可接受；
    软组（保证/一定/必须/随时）在中文里太常见，「必须给您补上」是正常安抚，
    判高会让大面积正常话术被阻断、反复重生成。软组只记录，交给客服自己判断。
    """
    命中: list[闸门命中] = []

    if 词 := [w for w in G2绝对化硬 if w in 话术]:
        命中.append(
            闸门命中(
                闸门="G2",
                名称="边界",
                严重度="高",
                详情="出现把话说死的措辞",
                证据=tuple(词),
                建议="改成留余地的说法：把「绝对」去掉，把「包退」换成「按规则处理」",
            )
        )

    if 词 := [w for w in G2绝对化软 if w in 话术]:
        命中.append(
            闸门命中(
                闸门="G2",
                名称="边界",
                严重度="中",
                详情="出现泛化强调的措辞（中文里很常见，只提示不阻断）",
                证据=tuple(词),
                建议="能改成留余地的说法更好：把「保证」换成「通常」，把「一定」去掉",
            )
        )

    if m := G2越权.search(话术):
        命中.append(
            闸门命中(
                闸门="G2",
                名称="边界",
                严重度="高",
                详情="出现越权承诺，客服无权在会话里许金额或赔付",
                证据=(m.group(0),),
                建议="改为「我帮您提交申请，具体以审核结果为准」",
            )
        )

    return 命中


def G3来源可查(
    话术: str,
    依据: Sequence[依据条目],
    可引用: Sequence[str] = (),
    待核对: Sequence[str] = (),
) -> list[闸门命中]:
    """查话术里的事实性内容能不能追到依据。

    做三件事：
    1. 依据不能是空的 —— 没依据就没法解释「这句话为什么站得住」。
    2. 带单位的数字必须出现在依据或可引用文本里 —— 模型最容易在这里编。
    3. 数字即使追到了出处，如果那个出处本身**业务方还没确认**，也不能放行。

    `可引用` 传口径表的「可以说」「标准话术」等允许引用的原文。
    `待核对` 传口径表里尚未确认的数字（`口径表数据.待核对数字()`）。

    **为什么要有第 3 条。** 口径表自己标着「待改错」，K03/K05/K07 的时效数字
    业务方还没点头。第 2 条会拿这张表给数字背书 —— 话术说「48 小时内发出」，
    表里有「48 小时」，于是放行。那这个闸门就是在为一个没人确认过的数担保。
    第 3 条把它降成中危，转人工核对。
    """
    命中: list[闸门命中] = []

    用上的 = [e for e in 依据 if e.用上]
    if not 用上的:
        命中.append(
            闸门命中(
                闸门="G3",
                名称="来源可查",
                严重度="高",
                详情="这句没有任何依据支撑",
                证据=(),
                建议="补上引用的口径或数据来源，否则不能发",
                # 没材料是事实，不是措辞。重生成改变不了「检索没召回」，
                # 只会把模型困在「生成→被拦→再生成」的圈里。
                可重生成=False,
            )
        )

    可查文本 = "\n".join([e.摘要 for e in 依据] + [e.出处 for e in 依据] + list(可引用))
    可查归一 = _去空格(可查文本)

    候选 = G3带单位数字.finditer(话术)
    编的 = [m.group(0) for m in 候选 if _去空格(m.group(0)) not in 可查归一]

    if 编的:
        命中.append(
            闸门命中(
                闸门="G3",
                名称="来源可查",
                严重度="高",
                详情="话术里的数字在依据里找不到出处",
                证据=tuple(dict.fromkeys(编的)),
                建议="要么删掉这个数字，要么补上来源；不能拿估算当承诺",
            )
        )

    # 待核对用「包含」而不是相等：话术里抽出来的是「3 个工作日」，
    # 待核对记的是整句「1-3 个工作日」。前者是后者的一部分，就算命中。
    # 这里的语义是「这个数来自一段没确认的话」，不是「这个数有出处」。
    没定的 = [
        m.group(0)
        for m in 候选
        if any(_去空格(m.group(0)) in _去空格(x) for x in 待核对)
    ]
    if 没定的:
        命中.append(
            闸门命中(
                闸门="G3",
                名称="来源可查",
                严重度="中",
                详情="话术里的时效数字业务方尚未确认，不能当承诺发出去",
                证据=tuple(dict.fromkeys(没定的)),
                建议="改为「具体时间以实际处理为准」，或先跟业务方核对这个数字",
            )
        )

    return 命中


def G4防矛盾(
    话术: str,
    已发出: Sequence[str] = (),
    顾客情况: Sequence[tuple[str, str]] = (),
) -> list[闸门命中]:
    """查话术和「已经说过的话」「顾客情况」打不打架。

    `已发出` 的定义（调用方按这个过滤，别自己发挥）：
        本轮之前，该会话里 **角色 ∈ {客服, AI}** 且内容类型为文本的全部消息文本。

    **AI 代发的必须算进来。** 从顾客角度看，AI 说的和客服说的是同一个人在说话，
    重复就是重复。不算的话，AI 会对着同一个顾客把同一句话说两遍。

    `顾客情况` 传 (标签, 值) 对，如 `("办过什么", "9/22 已补发 · 物流已揽收 ✓")`。
    """
    命中: list[闸门命中] = []
    本案 = _词集(话术)

    # 1. 同一句话别再发一遍。
    for 旧 in 已发出:
        旧案 = _词集(旧)
        if not 旧案 or not 本案:
            continue
        重合 = len(本案 & 旧案) / min(len(本案), len(旧案))
        if 重合 >= G4重复阈值:
            命中.append(
                闸门命中(
                    闸门="G4",
                    名称="防矛盾",
                    严重度="中",
                    详情="和之前发过的话高度重复",
                    证据=(旧[:40],),
                    建议="换一种说法，或者补上新的进展 —— 重复回复会让顾客觉得没人管",
                )
            )
            break

    # 2. 断言「已经做了某事」，但顾客情况里查不到这件事。
    #
    # 一句话可能断言好几个动作：「已经为您安排补发」里既有「安排」也有「补发」，
    # 而前者只是个虚动词。只要有**任意一个**动作在「办过什么」里有记录，这句话
    # 就站得住；全部查不到才拦。否则正常话术会被大面积误伤。
    办过 = next((v for k, v in 顾客情况 if k == "办过什么"), "")
    if 办过 and (断言 := _已发生动作(话术)):
        动作 = next((a for a in 断言 if a in 办过), None)
        if 动作 is None:
            命中.append(
                闸门命中(
                    闸门="G4",
                    名称="防矛盾",
                    严重度="高",
                    详情=f"话术说已经「{'/'.join(dict.fromkeys(断言))}」，但「办过什么」里没有这回事",
                    证据=(话术[:40], 办过[:40]),
                    建议="先确认动作是否真的做了；没做就不能说已经做了",
                    # 这是**事实错了**，不是措辞问题。重生成只会让它换个说法
                    # 绕过去（「已经补发」→「会尽快处理」），顾客的问题还在原地。
                    # 正确动作是让客服回去查工单。
                    可重生成=False,
                )
            )

    return 命中


def 过闸门(
    话术: str,
    依据: Sequence[依据条目] = (),
    可引用: Sequence[str] = (),
    已发出: Sequence[str] = (),
    顾客情况: Sequence[tuple[str, str]] = (),
    待核对: Sequence[str] = (),
    路径: str | None = None,
) -> list[闸门命中]:
    """跑完 G1–G4，按严重度降序返回。空列表表示放行。"""
    全部 = [
        *G1禁语(话术, 路径),
        *G2边界(话术),
        *G3来源可查(话术, 依据, 可引用, 待核对),
        *G4防矛盾(话术, 已发出, 顾客情况),
    ]
    # 排序要稳定：同一严重度按闸门编号，留痕里两次跑出来的顺序得一样。
    return sorted(全部, key=lambda h: (0 if h.严重度 == "高" else 1, h.闸门))


def 是否放行(命中: Sequence[闸门命中]) -> bool:
    """只有高严重度才拦。中严重度的只记录不阻断 —— 客服自己能判断。"""
    return not any(h.严重度 == "高" for h in 命中)


def 重生成可行(命中: Sequence[闸门命中]) -> bool:
    """值不值得带着反馈重生成。

    **修得动的是措辞，修不动的是事实。** 混成一个循环会出两类事故：

    - **死循环**：G3 判「没有任何依据」是检索没召回，重生成八百遍还是没依据，
      循环转不出去。
    - **掩盖事实错误**：G4 判「谎称已经补发」时，重生成只会教模型换个说法
      把同一个谎绕过去（「已经补发」→「会尽快处理」），顾客的问题还在原地，
      而客服以为系统已经处理完了。

    这两类都判 `可重生成=False`，调用方走降级 —— 把最后一次被拦的原文
    连同命中原因交给客服手改（见 `pipeline.降级结果`）。

    只看向高危命中：中危不阻断，本来就不触发重生成。
    """
    return all(h.可重生成 for h in 命中 if h.严重度 == "高")
