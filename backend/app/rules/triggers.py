#: ⑤ 表达不信任的**关键词回退**。数据里只有 1 条，但 v9 特意为它单列一段：
#: 「你们能不能靠谱点」没有施压词、没有强情绪词，传递的却是「我不再信任
#: 你们了」，比骂一句更该升级 —— 它预示后面会投诉。
#:
#: v9 对这一条的判定方式是「**模型判，必须引用原句**」。所以下面的词表只是
#: 模型不可用时的回退，正式路径是 `H2情绪(..., 认不信任函数=...)`。
#: 和 `pipeline.认口径` 同款处理：参数位留着，换模型时只换函数，不动调用方。
H2不信任词: tuple[str, ...] = (
    "上次也是", "上次就", "能不能靠谱", "可别再", "又来了",
    # 「又是这样」是唯一一条**不带「了」**的固定说法，句式抓不到它。
    # 它是上面那条「不发明新词」原则的例外，理由是它跟「又来了」同性质：
    # 是个完整的成语式表达，没有第二种解释。
    "又是这样",
)
#: 「又…了」是 v9 给的句式草稿，但**照抄会误伤**：`又[^…]{0,6}了` 把
#: 「又买了一套了」也收进来了 —— 那是复购，跟信任无关。
#:
#: 所以这里收窄两处：只认「又 ＋ 否定」，且否定词和「了」之间**至少有一个字**。
#:
#: > **为什么至少一个字。** 不加这条，「又出了」三个字就满足 `{0,6}`，
#: > 于是「又出了新款」（叙述）和「又坏了」（抱怨）会一起命中 —— 这两个
#: > 形状完全一样（又＋动词＋了），**正则分不开**。这正是 v9 把 ⑤ 判给
#: > 模型的原因。加了这条，「又出了新款」落空，代价是「又坏了」也落空。
#: > 这个取舍是故意的：H2 误报的后果是把顾客推给专家、把队列塞满
#: > （v9 明写的担心），漏报的后果是客服自己接着处理。宁可漏。
#: > ⑤ 的正式路径是 `认不信任函数`，这里只是模型不可用时的兜底。
H2又了句式 = re.compile(r"又(?:没|没有|不|是|出|坏|错|忘|丢)[^，。！？,.\s]{1,6}了")

