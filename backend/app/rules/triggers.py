"""硬触发 H1–H4 —— 纯规则，不调模型。

**为什么硬触发要排在拆主张前面。** 规格文档把顺序写成「拆主张 → 硬触发」，
那是叙述顺序不是依赖顺序。这四类的输入全是**原始消息文本和顾客情况**，
没有一条需要「主张」这个中间产物。所以可以先跑。理由只有一条：

- **少一次模型调用就少一个攻击面。** 见 `inbound.py`。

**但 H1 命中不短路拆主张 —— 这里原先写错了。** 早先的版本写着「H1 一旦命中，
输出必然是转交，这时候拆不拆主张对结论毫无影响」，和 `inbound.py` 打架：

- `inbound.py` 说拆主张负责把风险**归到哪条主张上**，供「本轮处置」展示；
- 右栏的实际形态（演示剧本第六步）也确实是「历史主张 + H1 新拆出的转交主张」
  并列，不是清空重来。

归因对客服是有用的 —— 交接时要能说清是哪个风险点触发的转交。所以硬触发
在顺序上仍然先跑（为了少一个攻击面），但不是**代替**拆主张。

这一层只报告**事实**：什么触发了、证据是哪几个词、严重到什么程度。至于
这些事实该判成哪种输出，是 `pipeline.py` 里三层判定的事 —— 混在一起写，
改输出规则就得动规则表，两边会互相绊。

**时间一律外部传入，不取 `datetime.now()`。** 这条是为了让**规则层**的判定
可重放：同一份输入跑两遍得出一模一样的结论，否则演示时没法解释。
边界要说清楚 —— 链路里拆主张和话术生成是模型调用，那两步**不承诺**可重放，
只承诺留有完整的调用记录可查（见 `pipeline.py`）。
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum


class 触发编号(StrEnum):
    H1 = "H1"
    """风险 —— 人身安全、监管、法律、舆情。"""
    H2 = "H2"
    """情绪 —— 情绪词、标点强度、连发催促。"""
    H3 = "H3"
    """逾期 —— 答应过的时限已经过了。"""
    H4 = "H4"
    """风控 —— 绕过平台流程的诉求。"""


@dataclass(frozen=True, slots=True)
class 触发:
    编号: 触发编号
    名称: str
    严重度: str
    """高 / 中。"""
    证据: tuple[str, ...]
    """命中的原词，供「本轮处置」和留痕回放。"""
    说明: str

    def __str__(self) -> str:
        return f"{self.编号} {self.名称}（{self.严重度}）：{'、'.join(self.证据)}"


# ── H1 风险 ────────────────────────────────────────────────
# 分四组，因为严重度不一样：身体反应和监管责任最重，舆情次之。
H1人身: tuple[str, ...] = (
    "刺痛", "泛红", "红肿", "过敏", "发痒", "瘙痒", "烂脸", "毁容",
    "起疹", "爆痘", "灼伤", "灼热", "脱皮", "溃烂", "留疤",
)
H1监管: tuple[str, ...] = (
    "12315", "消协", "工商", "药监", "市场监管", "起诉", "律师", "法院",
    "举报", "违规", "虚假宣传", "质检",
)
H1舆情: tuple[str, ...] = (
    "投诉", "曝光", "黑猫", "微博", "抖音", "小红书", "媒体", "差评", "维权",
)

# ── H2 情绪 ────────────────────────────────────────────────
H2情绪词: tuple[str, ...] = (
    "气死", "无语", "太过分", "恶心", "服了", "失望", "生气", "火大",
    "什么态度", "垃圾服务", "受不了", "忍不了", "离谱",
)
#: 连续标点。`！` 和 `!` 都算，中文输入法下两种都会出现。
H2标点 = re.compile(r"[!！]{2,}|[?？]{2,}")
#: 同一条消息连发几次算催促。2 次是正常补一句，3 次是情绪。
H2连发阈值 = 3

# ── H4 风控 ────────────────────────────────────────────────
H4风控词: tuple[str, ...] = (
    "仅退款", "只退款不退货", "退全款不退货", "白嫖", "薅羊毛", "职业打假",
    "恶意", "刷单", "骗保", "空包",
)
#: 出现这些订单状态时，风控词的权重上升 —— 未发货就要求仅退款，
#: 和已签收后要求仅退款，风险不是一回事。
H4高危订单状态: tuple[str, ...] = ("已签收", "交易成功", "已完成")


def _归一(text: str) -> str:
    """比对连发用的归一化：去掉空白和标点，只留内容。"""
    return re.sub(r"[\s\W_]+", "", text)


def _扫词(texts: Sequence[str], 词表: Sequence[str]) -> tuple[str, ...]:
    """在一组消息里找词表命中，去重且保持词表顺序。"""
    合并 = "\n".join(texts)
    return tuple(w for w in 词表 if w in 合并)


def H1风险(消息: Sequence[str]) -> 触发 | None:
    人身 = _扫词(消息, H1人身)
    监管 = _扫词(消息, H1监管)
    舆情 = _扫词(消息, H1舆情)

    if not (人身 or 监管 or 舆情):
        return None

    证据 = 人身 + 监管 + 舆情
    # 人身伤害和监管责任走紧急转交；单纯差评威胁没那么急，降一档走报备。
    #
    # 注意「降一档」降的是**处置路径**（转交→报备），不是「降成不用人管」——
    # 下面 说明 里那句「须走人工，不得由 AI 代答」对两档都成立。差评威胁
    # 如果让 AI 自己回了，等它变成舆情就来不及了。
    严重度 = "高" if (人身 or 监管) else "中"

    哪几组 = [n for n, v in (("人身反应", 人身), ("监管责任", 监管), ("舆情投诉", 舆情)) if v]
    return 触发(
        编号=触发编号.H1,
        名称="风险",
        严重度=严重度,
        证据=证据,
        说明=f"命中{'、'.join(哪几组)}相关风险词；须走人工，不得由 AI 代答",
    )


def H2情绪(消息: Sequence[str]) -> 触发 | None:
    证据: list[str] = []

    词 = _扫词(消息, H2情绪词)
    证据.extend(词)

    if 标点 := [m.group(0) for t in 消息 if (m := H2标点.search(t))]:
        证据.append(标点[0])

    # 连发：同一条内容重复三次以上，是催促也是情绪信号。
    # 归一化之后再数，免得「在吗」「在吗？」「在吗！」被当成三条不同的消息。
    计数 = Counter(_归一(t) for t in 消息 if _归一(t))
    连发 = [t for t, n in 计数.items() if n >= H2连发阈值]
    if 连发:
        证据.append(f"连发{max(计数.values())}次：{连发[0][:12]}")

    if not 证据:
        return None

    # 有情绪词才叫升级；只有标点或连发，说明急但还没炸。
    严重度 = "高" if 词 or 连发 else "中"
    return 触发(
        编号=触发编号.H2,
        名称="情绪",
        严重度=严重度,
        证据=tuple(证据),
        说明="顾客情绪已升级；话术需先安抚再给方案，不得直接讲规则",
    )


def H3逾期(
    承诺时限: datetime | None,
    当前: datetime,
) -> 触发 | None:
    """答应过的时间已经过了。

    `承诺时限` 取顾客情况「答应过什么」那一行的**结构化 `时限` 字段**，
    不是从「值」的自然语言里现解析。这是硬要求，理由在「今天」这个词上：

    「9/26 承诺『今天答复』」里的「今天」是相对**承诺发生那一刻**（9/26）而言的，
    不是相对当前 —— 要解析它得先知道承诺是什么时候说的，规则解析极脆。
    交给 LLM 解析则把模型塞进了这一层**之前**，「纯规则、微秒级」的前提就没了。

    所以解析职责放在装配层（它本来就在做「自然语言 → 结构化」），
    这一层只做比较。为空表示没有未兑现的承诺。
    """
    if 承诺时限 is None or 承诺时限 >= 当前:
        return None

    天数 = (当前.date() - 承诺时限.date()).days
    严重度 = "高" if 天数 >= 1 else "中"
    return 触发(
        编号=触发编号.H3,
        名称="逾期",
        严重度=严重度,
        证据=(f"{承诺时限:%Y-%m-%d %H:%M} 承诺，已过 {天数} 天",),
        说明="承诺已逾期；回复开头必须先认这个账，不能装作没这回事",
    )


def H4风控(消息: Sequence[str], 订单状态: str = "") -> 触发 | None:
    词 = _扫词(消息, H4风控词)
    if not 词:
        return None

    高危 = 订单状态 in H4高危订单状态
    return 触发(
        编号=触发编号.H4,
        名称="风控",
        严重度="高" if 高危 else "中",
        证据=词 + ((f"订单状态：{订单状态}",) if 高危 else ()),
        说明="诉求绕过平台流程；不得在会话里承诺，须走风控核实",
    )


def 硬触发(
    消息: Sequence[str],
    当前: datetime,
    承诺时限: datetime | None = None,
    订单状态: str = "",
) -> list[触发]:
    """跑完 H1–H4，按严重度降序返回。

    `消息` 传本轮相关的全部文本（通常是买家最近几条），不是单条 ——
    H2 的连发检测需要历史。
    """
    全部 = [
        H1风险(消息),
        H2情绪(消息),
        H3逾期(承诺时限, 当前),
        H4风控(消息, 订单状态),
    ]
    命中 = [t for t in 全部 if t is not None]
    return sorted(命中, key=lambda t: (0 if t.严重度 == "高" else 1, t.编号))


def 命中最高严重度(触发列表: Sequence[触发]) -> str | None:
    """这一轮触发里最重的那一档。没有触发返回 None。"""
    if not 触发列表:
        return None
    return "高" if any(t.严重度 == "高" for t in 触发列表) else "中"
