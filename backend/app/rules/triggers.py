"""硬触发 H1–H4 —— 纯规则，不调模型。

**为什么硬触发要排在拆主张前面。** 规格文档把顺序写成「拆主张 → 硬触发」，
那是叙述顺序不是依赖顺序。这四类的输入全是**原始消息文本和顾客情况**，
没有一条需要「主张」这个中间产物。所以可以先跑。理由只有一条：

- **少一次模型调用就少一个攻击面。** 见 `inbound.py`。

**但 H1 命中不短路拆主张 —— 这里原先写错了。** 早先的版本写着「H1 一旦命中，
输出必然是转交，这时候拆不拆主张对结论毫无影响」，和 `inbound.py` 打架：

- `inbound.py` 说拆主张负责把风险**归到哪条主张上**，供「本轮处置」展示；
- 右栏的实际形态（演示剧本第六步）也确实是「历史主张 + H1 新拆出的转交主张」
  并列，不是清空重来。

归因对客服是有用的 —— 交接时要能说清是哪个风险点触发的转交。所以硬触发
在顺序上仍然先跑（为了少一个攻击面），但不是**代替**拆主张。

这一层只报告**事实**：什么触发了、证据是哪几个词、严重到什么程度。至于
这些事实该判成哪种输出，是 `pipeline.py` 里三层判定的事 —— 混在一起写，
改输出规则就得动规则表，两边会互相绊。

**时间一律外部传入，不取 `datetime.now()`。** 这条是为了让**规则层**的判定
可重放：同一份输入跑两遍得出一模一样的结论，否则演示时没法解释。
边界要说清楚 —— 链路里拆主张和话术生成是模型调用，那两步**不承诺**可重放，
只承诺留有完整的调用记录可查（见 `pipeline.py`）。
"""

from __future__ import annotations

import re
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum


class 触发编号(StrEnum):
    H1 = "H1"
    """风险 —— 人身安全、监管、法律、舆情。"""
    H2 = "H2"
    """情绪／信任升级 —— 六条判据，见 `H2情绪`。"""
    H3 = "H3"
    """逾期 —— 答应过的时限已经过了。"""
    H4 = "H4"
    """风控 —— 绕过平台流程的诉求。"""


@dataclass(frozen=True, slots=True)
class 触发:
    编号: 触发编号
    名称: str
    严重度: str
    """高 / 中。**只影响排序，不影响去向。**

    四个硬触发的去向一律是「转交」（规格 v9 §三），不分档。早先 `pipeline.py`
    里那张 `H1降一档`（中危降成报备）已经删掉 —— 看到这里的「中」时别想着
    再写一次降档。
    """
    证据: tuple[str, ...]
    """命中的原词，供「本轮处置」和留痕回放。"""
    说明: str

    def __str__(self) -> str:
        return f"{self.编号} {self.名称}（{self.严重度}）：{'、'.join(self.证据)}"


