def _扫词(texts: Sequence[str], 词表: Sequence[str]) -> tuple[str, ...]:
    """在一组消息里找词表命中，去重且保持词表顺序。"""
    合并 = "\n".join(texts)
    return tuple(w for w in 词表 if w in 合并)


def _扫句式(texts: Sequence[str], 句式: re.Pattern[str]) -> tuple[str, ...]:
    """在一组消息里找句式命中，去重且按消息顺序。

    顺序取自**消息**而不是词表 —— 句式没有词表可依，且同一句里多个命中
    按出现位置排，比字典序更贴近「顾客先说了什么」。
    """
    见: list[str] = []
    for t in texts:
        for m in 句式.finditer(t):
            if (s := m.group(0)) not in 见:
                见.append(s)
    return tuple(见)


def H1风险(消息: Sequence[str]) -> 触发 | None:
    人身 = _扫词(消息, H1人身)
    监管 = _扫词(消息, H1监管)
    舆情 = _扫词(消息, H1舆情)

    if not (人身 or 监管 or 舆情):
        return None

    证据 = 人身 + 监管 + 舆情
    # 人身伤害和监管责任最重，单纯差评威胁次之。这里原先还写着「次之的
    # 降一档走报备」—— **已经删了**，规格 v9 §三 的表给 H1 的去向是一律
    # 「转交」，没有分档。严重度现在只剩排序作用（见 `触发.严重度`）。
    #
    # 这段注释留着是为了拦住下一次「顺手加个降档」：差评威胁如果让 AI 自己
    # 回了，等它变成舆情就来不及了 —— 下面 说明 那句「不得由 AI 代答」
    # 对两档都成立，所以两档都不该放给 AI。
    严重度 = "高" if (人身 or 监管) else "中"

    哪几组 = [n for n, v in (("人身反应", 人身), ("监管责任", 监管), ("舆情投诉", 舆情)) if v]
    return 触发(
        编号=触发编号.H1,
        名称="风险",
        严重度=严重度,
        证据=证据,
        说明=f"命中{'、'.join(哪几组)}相关风险词；须走人工，不得由 AI 代答",
    )


def _不信任证据(
    消息: Sequence[str],
    认不信任函数: Callable[[str], str | None] | None,
) -> tuple[str, ...]:
    """⑤ 的判据：有模型走模型，没有就退回关键词。

    `认不信任函数` 收一条消息，判它是不是在表达不信任 —— 是就返回**原句**
    （v9 对这条判据的要求就是「模型判，**必须引用原句**」），不是就返回 None。
    引用原句不是形式主义：它是客服复核这条转交时唯一能看的证据，换成
    「模型认为不信任」就等于没有证据。

    **给了函数就不再走关键词回退**，两者不叠加。一条判据只该有一个判定者 ——
    叠加的话「模型说不是、关键词说是」就成了两票对一票，而 v9 要求这条判据
    的结论必须能引到原句上，关键词那票引不出来。
    """
    if 认不信任函数 is not None:
        return tuple(句 for t in 消息 if (句 := 认不信任函数(t)))
    return _扫词(消息, H2不信任词) + _扫句式(消息, H2又了句式)


def H2情绪(
    消息: Sequence[str],
    重复要求: bool = False,
    认不信任函数: Callable[[str], str | None] | None = None,
) -> 触发 | None:
    """情绪／信任升级 —— v9 §三的**六条判据**。

    # 「连续催 3 次以上」已经作废，别再写回来

    这个函数原先数的是「同一条消息连发 ≥3 次」（外加情绪词、连续标点）。
    v9 把那个机制**点名判了死刑**，原话是「实测 138 个会话里根本触发不了 ——
    顾客后续消息大多是在补事实（肤质、时间、照片），不是重复催；而且情绪
    基本在第 1 句就出现了。**这是一条死代码。**」

    所以那不是「阈值调得不好」，是这个信号本身不存在。删掉之前请先读那段。
    **连续标点也一样不在六判据里** —— `"到底什么时候发货！！！"` 不触发，
    这正是 v9 自己举的反例（单次催单该正常处理）。

    # 六判据与触发规则

    | # | 判据 | 谁做 |
    |---|---|---|
    | ① | 时间施压 | 关键词表 |
    | ② | 维权威胁 | 关键词表 |
    | ③ | 要求方案 | 关键词表 |
    | ④ | 真实负面情绪 | 关键词表 ＋ 模型 |
    | ⑤ | 表达不信任 | **模型判，必须引用原句** |
    | ⑥ | 重复要求 | **系统算**（不靠模型） |

    ①~⑤ 命中任一 → 触发。**⑥ 单独命中 → 不触发**（顾客礼貌地问第二次进度，
    客服本来就在处理中；直接踢给专家会让专家队列被普通催单塞满，真正严重的
    问题反而排不上）。⑥＋①~⑤ 任一 → 触发 —— 但这是**推论不是新规则**：
    ①~⑤ 本来就能单独触发，所以 ⑥ 加不加都不改变结论，它只进 `证据`、抬 `严重度`。

    `重复要求` 由调用方算好传进来（同一诉求在本会话内被提出第 2 次且仍未解决）。
    v9 对这一条的要求是「**系统算**」—— 所以不在这层数消息，数连发正是被
    作废的那个机制的老路。

    # 严重度

    `④` 单独命中判**中**，其余判高。依据是 v9 的一句旁注：「④ 单独命中时，
    要看它是不是『纯抱怨』；真正的升级信号是 ①②③⑤⑥，它们隐含『要求推进』」。
    反例是 `S00009`：第 1 句「搞啥啊！物流显示昨天已签收，我根本没收到货！」
    情绪拉满，第 9 句却是「收到了，虚惊一场…券我收下了哈哈」—— 最后是满意的。

    和 `触发.严重度` 的注释一起读：**严重度只影响排序，不影响去向**，
    六条判据命中任一的去向都是转交。
    """
    判据: list[int] = []
    证据: list[str] = []

    def 记(号: int, 名: str, 命中: Sequence[str]) -> None:
        if 命中:
            判据.append(号)
            证据.extend(f"{_圈号[号 - 1]}{名}：{w}" for w in 命中)

    记(1, "时间施压", _扫词(消息, H2时间施压) + _扫句式(消息, H2最晚句式))
    记(2, "维权威胁", _扫词(消息, H2维权威胁))
    记(3, "要求方案", _扫词(消息, H2要求方案))
    记(4, "负面情绪", _扫词(消息, H2负面情绪))
    记(5, "不信任", _不信任证据(消息, 认不信任函数))

    if 重复要求:
        证据.append("⑥重复要求：同一诉求本会话第 2 次提出且未解决")

    # ⑥ 单独命中不触发 —— 见文档串的触发规则。
    if not 判据:
        return None

    严重度 = "高" if (重复要求 or any(号 != 4 for 号 in 判据)) else "中"
    return 触发(
        编号=触发编号.H2,
        名称="情绪／信任升级",
        严重度=严重度,
        证据=tuple(证据),
        说明=f"命中{'、'.join(_圈号[号 - 1] for 号 in 判据)}；须走人工，不得由 AI 代答",
    )


def H3逾期(
    承诺时限: datetime | None,
    当前: datetime,
) -> 触发 | None:
    """答应过的时间已经过了。

    `承诺时限` 取顾客情况「答应过什么」那一行的**结构化 `时限` 字段**，
    不是从「值」的自然语言里现解析。这是硬要求，理由在「今天」这个词上：

    「9/26 承诺『今天答复』」里的「今天」是相对**承诺发生那一刻**（9/26）而言的，
    不是相对当前 —— 要解析它得先知道承诺是什么时候说的，规则解析极脆。
    交给 LLM 解析则把模型塞进了这一层**之前**，「纯规则、微秒级」的前提就没了。

    所以解析职责放在装配层（它本来就在做「自然语言 → 结构化」），
    这一层只做比较。为空表示没有未兑现的承诺。
    """
    if 承诺时限 is None or 承诺时限 >= 当前:
        return None

    天数 = (当前.date() - 承诺时限.date()).days
    严重度 = "高" if 天数 >= 1 else "中"
    return 触发(
        编号=触发编号.H3,
        名称="逾期",
        严重度=严重度,
        证据=(f"{承诺时限:%Y-%m-%d %H:%M} 承诺，已过 {天数} 天",),
        说明="承诺已逾期；回复开头必须先认这个账，不能装作没这回事",
    )


def H4风控(
    消息: Sequence[str],
    订单状态: str = "",
    风控异常: bool = False,
) -> 触发 | None:
    """识别顾客文本或工单已标记的异常包裹。"""
    词 = _扫词(消息, H4风控词)
    if 风控异常:
        词 = 词 + ("工单标记包裹异常",)
    if not 词:
        return None

    高危 = 风控异常 or 订单状态 in H4高危订单状态
    说明 = (
        "工单已标记包裹异常；须走风控核实"
        if 风控异常
        else "诉求绕过平台流程；不得在会话里承诺，须走风控核实"
    )
    return 触发(
        编号=触发编号.H4,
        名称="风控",
        严重度="高" if 高危 else "中",
        证据=词 + ((f"订单状态：{订单状态}",) if 订单状态 in H4高危订单状态 else ()),
        说明=说明,
    )


def 硬触发(
    消息: Sequence[str],
    当前: datetime,
    承诺时限: datetime | None = None,
    订单状态: str = "",
    重复要求: bool = False,
    认不信任函数: Callable[[str], str | None] | None = None,
    风险文本: Sequence[str] | None = None,
    风控异常: bool = False,
) -> list[触发]:
    """跑完 H1–H4，按严重度降序返回。

    `消息` 传本轮相关的全部文本（通常是买家最近几条），不是单条 ——
    历史对 H2 ⑤（「上次也是」）有意义。

    `重复要求`（H2 ⑥）和 `认不信任函数`（H2 ⑤）是**上层算好传下来的**：
    ⑥ 要查会话历史里这条诉求提过几次，⑤ 要模型。两者都不属于「纯规则、
    微秒级」这一层，所以这里只转发，不算。

    # `风险文本`：H1 的窗口和另外三个不是同一个（2026-10-05 加）

    H1 要看**整条会话到此为止**的买家消息，H2／H4 只看本轮。不传 ＝ 两边
    同窗口（＝调用方认为「本轮就是全部」），老行为一个字不变。

    `短路触发` 里三个（H1／H2／H4）原来共用「本轮」这一个窗口，代价实测得到：
    v9 给这个窗口的理由是「顾客礼貌地问第二次进度、客服本来就在处理中，
    直接踢给专家会让专家队列被普通催单塞满」—— 那句话说的是**催单和情绪**，
    也就是 H2。**H1 不是这一类**：它那三族（人身／监管／舆情）说的都是
    **已经发生过的事实**（「全脸发红起疹子」「我要投诉」），事实不会因为
    顾客下一句改成「好的，等你们消息」就没发生过。

    实测（`审计_十条`，2026-10-05）：S00010 第 1 轮买家说「用了面膜全脸发红，
    还起了小疹子，有点痒」（H1 人身），到第 5 轮只剩一句收场白 —— 窗口按本轮算，
    那一轮**四个触发一个都不命中**，屏幕上是一张蓝卡。全量 140 个会话里，
    整段扫得到、末轮扫不到的 **44 条**（H1 18 条／H2 34 条／H4 3 条）。
    H2／H4 保持本轮是刻意的：情绪会平复、风控词要结合当场那句话看，
    它们说的本来就是「此刻的气压」。

    ⚠️ **`风险文本` 不能传整条会话**，要传**切到本轮为止**的那一段
    （`api/判定` 传的是 `截.消息`）—— 传全量等于让判定看见顾客还没说的话。
    """
    全部 = [
        H1风险(风险文本 if 风险文本 is not None else 消息),
        H2情绪(消息, 重复要求=重复要求, 认不信任函数=认不信任函数),
        H3逾期(承诺时限, 当前),
        H4风控(消息, 订单状态, 风控异常),
    ]
    命中 = [t for t in 全部 if t is not None]
    return sorted(命中, key=lambda t: (0 if t.严重度 == "高" else 1, t.编号))


def 命中最高严重度(触发列表: Sequence[触发]) -> str | None:
    """这一轮触发里最重的那一档。没有触发返回 None。"""
    if not 触发列表:
        return None
    return "高" if any(t.严重度 == "高" for t in 触发列表) else "中"
