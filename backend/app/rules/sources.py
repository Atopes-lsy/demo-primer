"""六个来源 —— 三层判定第 1 层「系统确认得了吗」的输入（规格 v9 §4.1）。

**六源是封闭集合。** 规格 §4.1 的表格就六行，没有第七源。这条封闭性是右栏
「依据 · N/6 源命中」那个分母成立的原因，也是「一并列出以示无遗漏」这句话
敢说的原因 —— 六源可以逐个报「有记录／无记录」，是可穷举的。

**源内做不到同样的承诺。** ③ 先例库内部走向量召回（召回 3 条），天然是 top-K 截断的：
「③ 召回了 3 条」不等于「③ 里每一条都看过了」。**但它不进六源**（走 prompt 第 6 块，
spec §0 第 4 条）—— 这条限度说的是 ③ 自己那个库，不是六源。① 按货号精确连接，没这一层。
演示时这两层要分开说。

**这一层只定契约，不做查询。** 真的去查库要等数据层（现在后端还没有），
所以 `空六源结果` 是默认值 —— 它等价于 §4.1 的「查不到」分支，而不是一个错误状态。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum


class 六源(StrEnum):
    """六个来源的编号。**顺序和编号冻结，别改** —— 前端 `EvidenceSource`
    用的是同一套 `'①' | '②' | ... | '⑥'`，两边对不上，右栏那个计数就错了。"""

    商品属性表 = "①"
    口径表 = "②"
    先例库 = "③"
    订单物流售后 = "④"
    不良反应投诉 = "⑤"
    补发换货工单 = "⑥"


#: 编号 → 来源名。与前端 `EVIDENCE_SOURCE`（`types/index.ts`）逐字一致，
#: 改一边就得改另一边 —— 它是「未命中的六源清单」直接渲染的文案。
六源名称: dict[六源, str] = {
    六源.商品属性表: "商品属性表",
    六源.口径表: "口径表",
    六源.先例库: "先例库",
    六源.订单物流售后: "订单／物流／售后表",
    六源.不良反应投诉: "不良反应／投诉记录",
    六源.补发换货工单: "补发换货工单／订单赠品",
}

#: 六个来源的固定顺序。渲染「未命中的六源清单」按它走，不按数据到达顺序 ——
#: 同一份输入跑两遍要得出同样的清单，这是可重放的要求。
六源顺序: tuple[六源, ...] = tuple(六源)


@dataclass(frozen=True, slots=True)
class 源记录:
    """一条查到的记录。字段名就是规格 §4.1 写的 `{exists, table, row_id, content}`。

    **这是结构体不是自然语言** —— 规格特意标了这一句，为的是让「有没有依据」
    变成可判定的事实，而不是让模型去读一段话然后自己判断有没有。
    """

    exists: bool
    table: str = ""
    """表名。G3 要求「引用的表名＋行号必须真实存在」，就是拿这两个字段回查。"""
    row_id: str = ""
    """行号。"""
    content: str = ""
    """这一条提供的事实。第 3 层出稿时的唯一事实来源。"""

    用上: bool = True
    """本轮话术有没有引用它。

    false 的记录进「未命中的六源清单」，**带着摘要一并列出** —— 右栏那块
    展开后第三段就是它。这是 用上 和 exists 分开的原因：一个来源可能查到了
    三条、只用上一条，另两条仍要露面（否则「一并列出以示无遗漏」是句空话）。
    """

    成分: tuple[str, ...] | None = None
    """这一条里的**物质名**，只有 ① 商品属性表 有（`商品表.成分名` 的产出）。

    ⚠️ **不是给右栏看的**，所以它不在规格 §4.1 那四个字段里 —— 它是
    `guards.G3来源可查` 的输入：话术里「含／不含 X」的断言要拿 token 去比，
    **不能拿 `content` 那段文本去比**。「苯氧乙醇」逐字含「乙醇」，
    文本比对会把正确答案和错误答案一视同仁地放行。

    `None` ＝ 这一源没有物质名可比（②③④⑤⑥ 全是 `None`）—— G3 据此**不判**，
    而不是当成空集合去判（空的读出来是「什么成分都没有」）。
    """

    不含名: tuple[str, ...] | None = None
    """这一条里的**「表里说没有」的名字**，只有 ① 商品属性表 有
    （`商品表.不含名` 的产出，来自 `不含（可对顾客说）` 那一列）。

    ⚠️ **和 `成分` 配对使用，单独看没有意义。** 两个一起进 `物质.扫断言` 的
    词表，而「这一行到底有没有」的判据**只看 `成分`** —— 它和这个字段说的事
    正好相反，混着算就全废了。

    它存在的唯一理由是**让长名占住自己在话术里的区间**：话术
    「不含维A类、水杨酸、对苯二酚、二苯酮-3」里的 `水杨酸` 不在成分表中，
    没有这个字段就占不住区间，`水` 会在它中间命中 → 误报「说不含水」。
    完整的事见 `物质.扫断言` 文档串里记的第三次子串陷阱。
    """


@dataclass(frozen=True, slots=True)
class 六源结果:
    """一条主张查完六个来源的结果。

    `记录` 的键**必须齐六个**，哪怕某源一条没有（值给空元组）。这是刻意的：
    靠「键在不在」表达「查没查」，调用方漏查一源时无法静默 —— 而漏查会让
    右栏的分母从 6 变成 5，看上去还是「N/N，没遗漏」，这个是查不出来的。
    """

    主张: str
    记录: dict[六源, tuple[源记录, ...]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if 缺 := [s for s in 六源顺序 if s not in self.记录]:
            raise ValueError(
                f"六源结果必须带齐六个键，缺 {[str(s) for s in 缺]}。"
                "用 `空六源结果(主张)` 造默认值，别手拼 dict。"
            )

    def 命中源(self) -> frozenset[六源]:
        """有记录且用上了的来源。**这是右栏那个 N 的分母来源。**

        计数按**源**不按条：同一个来源可以有多条引用（口径表就常同时命中
        K06 和 K20），只算命中一次。按条计数会让 `命中 + 未命中` 超过 6。
        详见前端 `AdviceCard.EvidenceList`。
        """
        return frozenset(
            s for s, 组 in self.记录.items() if any(r.exists and r.用上 for r in 组)
        )

    def 未命中源(self) -> tuple[六源, ...]:
        """没命中的来源，按编号顺序。展开后第二段那句「另 N 源无记录」取它的长度。"""
        命中 = self.命中源()
        return tuple(s for s in 六源顺序 if s not in 命中)

    def 有记录(self) -> bool:
        """第 1 层的答案：**系统确认得了吗。**

        和 `命中源()` 问的不是一回事，别混：
        - 这里看 `exists`（查到东西没有）—— 决定第 1 层走「查得到」还是「查不到」
        - `命中源()` 还要看 `用上`（话术引没引）—— 只决定右栏那个分数

        一个来源查到了但没被引用，第 1 层算「查得到」：系统确实确认了，
        只是话术没用上它。反过来若六个来源全都查不到，第 1 层就得走
        §4.1 的「不许编 → 交客服点发送」那条路。
        """
        return any(r.exists for 组 in self.记录.values() for r in 组)


def 空六源结果(主张: str) -> 六源结果:
    """六键齐全、全空的默认值。

    数据层接上之前，`三层判定` 对每条主张都用它 —— 于是第 1 层永远报「查不到」，
    整条链最终落到「客服点发送」。**这不是降级，是当前唯一诚实的答案**：
    没有数据层就没有依据，而有依据是 AI 直发的四个前提之一（§七 ①）。
    """
    return 六源结果(主张=主张, 记录={s: () for s in 六源顺序})
