"""报备时自动发给顾客的安抚话术 —— **固定表，不是模型生成**。

# 为什么这条路需要一句话

`输出 == 报备` 时对话仍在客服手里（报备是「走个审批」，不是转交），
但**顾客那边不能一声不吭**：他刚说了「赠品还没给我发呢」，系统至少要接住
这句情绪。`剧本.ts` 第 4 格和第 `31_界面文字清单_给思语.md` §1.2 第 4 条
要的就是这一句，署名写着「安抚话术（**不含承诺，无需客服点**）」。

# 为什么是固定表不是 3c 生成

3c 只管 `客服点发送` 和 `AI直发`（spec §6.5），`转交` 由 `handover.转交话术表`
给 —— **报备原先没人管**（工单 §1.2）。定成固定表而不是让模型写，有三条理由：

1. **这句话先于客服点发送出去。** 说死了后面收不回来，和转交话术同一个性质。
2. **「不含承诺」是可判定的，那就该判定而不是祈祷。** 三条硬约束写在
   `校验安抚话术` 里，**导入时就跑** —— 和 `handover.校验转交话术`、
   `koujing.校验互斥` 同一个模式。生成侧做不到这件事：模型每次都在赌。
3. 它是兜底句，**生成的意义不大**：不带事实、不带数字、不带处理结论，
   只有「抱歉 ＋ 我去核实 ＋ 尽快答复」。

# 按事项分条，认不出落到兜底

`报备` 有五个来源（`permissions.py` 的 E01–E05：超额度补发、价差、保价被拒、
退货运费、承诺逾期），所以不能只写死一句 —— 那句里带着事项（「赠品的事」）。

查表按**关键词最长优先**（和 `permissions.认权限` 同一个分法）。认不出时落到
`兜底安抚`，**而兜底本身也满足三条硬约束** —— 所以这个匹配的失败方向是温和的：
丢的只是针对性，不是安全性。

> ⚠️ 这和 `H3交接分类` 那种「认不出就空一格」**不是一回事**。那边空掉的是
> **信息**（右栏少一格，看的人不知道少了什么），这边丢的只是**措辞**。
> 所以这边按关键词查是可以接受的，那边不是。
"""

from __future__ import annotations

import re
from collections.abc import Mapping

from .koujing import 查禁语全

#: 认不出事项时用这一句。**它也必须过三条硬约束** —— 见 `校验安抚话术`。
兜底安抚 = "亲实在抱歉让您久等，这件事我立刻帮您核实，尽快答复您～"


def _安抚(事项: str) -> str:
    """按事项套那句话。**表里各条只有事项词不同** —— 见下面那张表的注释。"""
    return f"亲实在抱歉让您久等，{事项}的事我立刻帮您核实，尽快答复您～"


#: **匹配词 → 句子里那个名词。** 键是主张里会出现的词，值是顾客看到的那个词。
#:
#: 大多数两条**是同一个词**，所以「不含承诺」是**结构上成立**的，不是逐条看出来的：
#: 三条硬约束挂在句子的骨架上，换的只是中间那个名词。
#: 「赠品」那条必须与 `frontend/src/data/剧本.ts` 和 `31_界面文字清单` 里的
#: 剧本原文**逐字一致** —— `_安抚("赠品")` 拼出来就是它，`test_安抚话术` 拿
#: 剧本原文钉着。
#:
#: # 2026-10-06：从一条扩到十四条（两轮）
#:
#: **第一轮**（1 → 7）。原来只有「赠品」。实测真窗口里**报备处 94% 落到兜底** ——
#: 顾客说的是「退货运费由谁承担」「原路退款未到账」「补发面霜」，一句都不含「赠品」，
#: 于是全拿到那句「**这件事**我立刻帮您核实」。兜底本身合法（这个匹配的失败方向
#: 是温和的），可 94% 都落到兜底就不叫兜底了，叫「这句话没有针对性」。
#: 关键词是从**真主张**里数出来的，不是照 `E01–E05` 的事项名写的。
#:
#: **第二轮**（7 → 14）。复测剩 7 处兜底，摊开是两族，「换货」和「少件／破损」。
#: 第一轮把它们留在兜底的理由是「那几个词做进句子会读成『**少发**的事我立刻帮您
#: 核实』，顾客不会这么说」——**这个判断只对了一半**：词确实不能直接搬，
#: 但那是**名词选错了**，不是这族没法覆盖。「少发」「缺失」「只收到一件」说的是
#: 同一件事，那件事叫**发货**；「碎了」那件事叫**破损**。所以这张表拆成两层：
#: 上面一层找词，下面一层给出句子里那个名词。
#:
#: # 为什么认事项不用 `权限条目.编号`（L01／L02）
#:
#: `报备` 的处置里 `说明` 带着规则名（「补发（不退货）」「换货（需退回）」），
#: 看着像个现成的事项。**它比关键词粗。** `S00158` 轮 1 有两条报备、同走
#: 「换货（需退回）」那条规则：一条主张是「申请将#01赤茶红退货」（该说退货），
#: 另一条是「换货为#05枫叶红」（该说换货）。按规则名认的话两条会拿到同一个名词。
#: 关键词反而分得开 —— 顾客自己用的就是那个词。
#:
#: ⚠️ **「退货运费」那条专为压过「运费」和「退货」而写。** 查表是最长优先，
#: 而「退货运费由谁承担」同时含「运费」和「退货」—— 两条一样长时靠的是
#: 插入顺序（`sorted` 稳定），那种「谁在前谁赢」的判据写在注释里没人看得住。
#: 给一个 4 字的键，长度就把它顶到最前面，与顺序无关。
#:
#: ⚠️ 剩下几处同长的**只能靠顺序**，所以下面按「具体的在前」排，`test_安抚话术`
#: 里两条哨兵钉着「运费」在「退货」前、「补发」在「发货」前。**改顺序要过那两条。**
安抚事项: dict[str, str] = {
    "赠品": "赠品",
    "退货运费": "退货运费",
    "运费": "运费",  # ← 必须在「退货」前面（同长）
    "退款": "退款",
    "退货": "退货",
    "换货": "换货",
    "补发": "补发",  # ← 必须在「发货」前面（同长）
    "小样": "小样",
    # ── 下面这几条**匹配词和名词不是同一个** ──────────────
    # 少件那一族：主张里说的是「少发」「缺失」「只收到」「重新发货」，
    # 那几件事是同一件 —— 顾客在问**发货**这一趟出了什么岔子。
    "少发": "发货",
    "缺失": "发货",
    "只收到": "发货",
    "发货": "发货",
    # 到手是坏的。用「碎」而不是「碎了」：顾客还会说「摔碎了」「碎了一瓶」。
    "破损": "破损",
    "碎": "破损",
}

#: 匹配词 → 安抚话术，由 `安抚事项` 展开。查表用的是它。
安抚话术表: dict[str, str] = {
    词: _安抚(名词) for 词, 名词 in 安抚事项.items()
}

#: 带单位的数字。**这条是硬约束 1.**
#: 比 `guards.G3带单位数字` 宽一点（多了 `元／折／月`）—— 那边要留出
#: 「口径表里确认过的数字」这条活路，这边没有活路：这句话是在任何人
#: 核实之前自动发的，**任何数字都是空头支票**。
_时限 = re.compile(r"\d+(?:\.\d+)?\s*(?:个)?(?:工作日|小时|天|分钟|周|月|元|折|ml|mL|克|g)")


def 查安抚话术(主张: str, 表: Mapping[str, str] | None = None) -> str:
    """这条主张触发的报备，该对顾客说什么。**认不出给 `兜底安抚`。**

    `表` 留空用模块里的 `安抚话术表` —— 参数位是给测试注入用的，
    和 `koujing.加载口径表(路径)` 同一个路数。
    """
    用 = 安抚话术表 if 表 is None else 表
    # 最长优先：`赠品补发` 这种更具体的要压过 `赠品`，否则具体那条永远轮不到。
    for 关键词 in sorted(用, key=len, reverse=True):
        if 关键词 in 主张:
            return 用[关键词]
    return 兜底安抚


def 校验安抚话术(表: Mapping[str, str] | None = None) -> list[str]:
    """查每一句有没有越过三条硬约束，返回违规说明（空列表表示干净）。

    **加载即校验、且是抛错不是警告** —— 和 `handover.校验转交话术` 同一个模式，
    理由也一样：这些话是对顾客的承诺，表错了的话承诺已经许出去了，
    调用方再怎么小心都来不及。

    三条硬约束：

    1. **不许出现时限** —— 见 `_时限` 的文档串
    2. **不许出现「已」** —— 比 G4 更严：不分辨「已」后面接的是不是动作词。
       理由是这句出去的**时机**：它在任何人核实之前自动发出，那个时刻
       **不存在任何「已做过」的事**，所以没有需要分辨的输入。
    3. **不许出现禁语** —— 复用 `koujing.查禁语全`，和闸门 G1 同一张表。
       不共用的话这张表就成了绕过 G1 的旁路：本地校验一过就直接发。
    """
    用: Mapping[str, str] = (
        {**安抚话术表, "兜底": 兜底安抚} if 表 is None else 表
    )
    违规: list[str] = []

    for 关键词, 句 in 用.items():
        if m := _时限.search(句):
            违规.append(
                f"{关键词}：出现了时限「{m.group(0)}」。这句话是在任何人核实之前"
                "自动发出去的，任何时限都是空头支票（口径表 K05）"
            )
        if "已" in 句:
            违规.append(
                f"{关键词}：出现了「已」。这句话发出时**没有任何事已经做过**，"
                "说「已为您核实」就是谎称已办"
            )
        for 禁 in 查禁语全(句):
            违规.append(f"{关键词}：命中禁语「{禁.禁语}」（口径表 {禁.口径}）")

    return 违规


# 模块导入时校验一次。和 `handover.py` 一样写在函数外面：这是**数据错误**
# 不是运行时状况，早炸比晚炸好 —— 晚炸的话那一刻这句话已经发给顾客了。
if _违规 := 校验安抚话术():
    raise ValueError(
        "安抚话术越界，发出去就是空头承诺：\n  - "
        + "\n  - ".join(_违规)
        + "\n（改 安抚话术表 或 兜底安抚 里对应的条目）"
    )
