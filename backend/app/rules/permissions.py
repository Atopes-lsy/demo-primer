"""权限矩阵 —— 三层判定第 2 层「这件事归谁办」的全部输入（规格 v9 §六）。

**为什么要单独一个模块。** §六 是全流程里唯一一张「谁能办什么」的表，
三层判定的第 2 层、右栏的「需要授权」「有风险」两种主卡形态、以及
`docs/开发步骤.md` 里的报备流程，读的都是它。散进 pipeline 就等于抄了三份。

# 三条容易抄错的地方

**1 · `X01` 和 `L03` 方向相反，区别不在「是不是会员权益」。**
「会员权益加赠补发」（会员日加赠／入会加赠／生日礼）**符合已有规则** → 一线直接办；
「赠品／小样追加超额度」**在规则之外多要** → 转交。业务方批注原话：
「这个必须要转交了」。规则内的一线照办，规则外的转交 —— 拿「是不是会员权益」
当判据会刚好判反。

**2 · 价差补差已改为无额度，别按旧版写死金额。** 2026-09-28 业务方确认
「按平台规则自动核算」。所以 `L07` 的 `限额金额` 是 `None`，不是某个数字 ——
`None` 在这里表示**这条不卡金额**，和「金额未知」是两回事（后者在 `权限事实` 里
用 `None` 表示，见下）。

**3 · 「48 小时发出」对所有层级都一样**，不是一线特权。它出现在 §6.1 的
「会员权益加赠补发」行里，但它是**全公司口径**，别实现成一线专属。

# 表怎么读

`权限条目表` 有 22 行，和 §六 的四个小节逐行对应。但**不是每行都能被 `认权限` 认**：

- `可认=True`（**17 行**，`L01–L09` ＋ `E05` ＋ `Z01–Z07`）—— 能被主张认到
- `可认=False`（**5 行**，`E01–E04` ＋ `X01`）—— 是**超额度之后的后果**，不是诉求

> ⚠️ **`E05` 在第一个名单里，看着像走错了行 —— 它是对的。** 2026-10-01
> （工单 A · 3.2）从 `可认=False` 翻成 `True`：原先不可认是因为 H3 整轮短路
> 替它挡在前面，而那个短路已经拆了。「客服没做到承诺」是顾客**会说的话**
> （关键词就一个「逾期」），不是「超额度的后果」，所以它和 L／Z 两族同类。
> 翻的时候这两行的 16／6 没跟着改，2026-10-02 才回来改。

这个区分是必须的。「补发／换货 > 1 件/单」描述的是一个条件，不是顾客会说的话；
顾客说的是「帮我补发一下」。超没超额度由 `权限事实` 判，去向由基行的
`超出后去向` 给。把那 5 行也放进认的过程，会出现「顾客要求补发」被认成
「补发超过 1 件」这种张冠李戴。
"""

