"""权限矩阵 —— 三层判定第 2 层「这件事归谁办」的全部输入（规格 v9 §六）。

**为什么要单独一个模块。** §六 是全流程里唯一一张「谁能办什么」的表，
三层判定的第 2 层、右栏的「需要授权」「有风险」两种主卡形态、以及
`docs/开发步骤.md` 里的报备流程，读的都是它。散进 pipeline 就等于抄了三份。

# 三条容易抄错的地方

**1 · `X01` 和 `L03` 方向相反，区别不在「是不是会员权益」。**
「会员权益加赠补发」（会员日加赠／入会加赠／生日礼）**符合已有规则** → 一线直接办；
「赠品／小样追加超额度」**在规则之外多要** → 转交。业务方批注原话：
「这个必须要转交了」。规则内的一线照办，规则外的转交 —— 拿「是不是会员权益」
当判据会刚好判反。

**2 · 价差补差已改为无额度，别按旧版写死金额。** 2026-09-28 业务方确认
「按平台规则自动核算」。所以 `L07` 的 `限额金额` 是 `None`，不是某个数字 ——
`None` 在这里表示**这条不卡金额**，和「金额未知」是两回事（后者在 `权限事实` 里
用 `None` 表示，见下）。

**3 · 「48 小时发出」对所有层级都一样**，不是一线特权。它出现在 §6.1 的
「会员权益加赠补发」行里，但它是**全公司口径**，别实现成一线专属。

# 表怎么读

`权限条目表` 有 22 行，和 §六 的四个小节逐行对应。但**不是每行都能被 `认权限` 认**：

- `可认=True`（16 行，`L01–L09` ＋ `Z01–Z07`）—— 是**顾客的诉求**，能被主张认到
- `可认=False`（6 行，`E01–E05` ＋ `X01`）—— 是**超额度之后的后果**，不是诉求

这个区分是必须的。「补发／换货 > 1 件/单」描述的是一个条件，不是顾客会说的话；
顾客说的是「帮我补发一下」。超没超额度由 `权限事实` 判，去向由基行的
`超出后去向` 给。把那 6 行也放进认的过程，会出现「顾客要求补发」被认成
「补发超过 1 件」这种张冠李戴。
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from enum import StrEnum


class 权限去向(StrEnum):
    """第 2 层的四态。

    §4.2 的表列了三态（在权限内／超额度／判不了），第四态 `未列明` 是
    「矩阵里没有这一行」—— v9 的示范例子要求它继续往下走，不能并进判不了。
    详见该成员的说明。
    """

    在权限内 = "在权限内"
    """客服直接办 → 继续第 3 层。"""
    报备 = "报备"
    """事该办，但超出我的额度。§6.2。**对话还在客服手里。**"""
    转交 = "转交"
    """§6.2b / §6.3。超出的不是额度而是**规则**，得专家裁定。"""
    判不了 = "判不了"
    """**认出了诉求，但定档要的条件建立不起来**，比如件数未知、金额未知。

    §4.2 的表里这一态的去向是**报备**，不是转交 —— 配套的那句关键原则是
    「系统查不到 ≠ 客服办不了」，意思是**别因为系统查不到就把对话推给上级**。
    报备的语义是「走个审批」，对话仍在客服手里，和转交是两回事。

    注意 §4.2 原文对这一态的解释是「**系统查不到条件**」—— 关键词是
    **条件**。所以它指的是「额度判不了」，不是「表里没这一行」，后者见 `未列明`。
    """
    未列明 = "未列明"
    """**权限矩阵里根本没有对口的事项** —— 认不上任何一行。

    **这一态不等于「判不了」，不能并进上一档。** 原先代码是把两者合一的
    （认不上 → 判不了 → 报备），被 v9 的示范例子直接推翻：

    > 「这个精华里面有乙醇吗？我是孕妇能用吗」
    > 拆法：claim1「含不含乙醇」← 有来源、不涉承诺 → **AI 直接发送**

    成分咨询在 §六 里当然没有对应行 —— 那张表管的是**要授权的事**
    （补发／换货／退款／赔付／升级），不是一张「客服能聊什么」的白名单。
    把「表里没写」读成「不许办」，会让每一个普通的商品咨询都被推去审批。

    所以这一态的去向是**继续第 3 层**，和「在权限内」一样。区别只在留痕：
    右栏要能说清这条是「矩阵说在权限内」还是「矩阵里没提它」——
    被追问「凭什么」时，这两句的答法完全不同。
    """


