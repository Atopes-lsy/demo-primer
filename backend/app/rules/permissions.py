@dataclass(frozen=True, slots=True)
class 权限事实:
    """判额度要用的事实。**每个维度都是三态**：给了值 / 给 `None`（不知道）。

    `None` 和 0 不是一回事：「这单补发 0 件」和「不知道这单补发几件」要分开 ——
    前者在权限内，后者**判不了**，而判不了要走报备（§4.2）。

    这个保守取向和 `三层判定` 第 3 层那条是同一条原则：**「在权限内」是要拿
    事实证明的结论，不是默认值。** 证明不了就不能继续往第 3 层走。
    """

    件数: int | None = None
    金额: float | None = None
    质量问题: bool | None = None


_未知事实 = 权限事实()
"""全 `None` 的事实 —— 「这单的情况我什么都不知道」。

提成模块级常量是为了当 `查权限` 的默认参数：把 `权限事实()` 直接写在参数
默认值里，ruff 的 B008 会拦（默认值里调函数）。`权限事实` 是 frozen 的，
共享同一个实例没有可变风险，也不存在「上一次调用改脏了默认值」这回事。
"""


@dataclass(frozen=True, slots=True)
class 权限判定:
    去向: 权限去向
    条目: 权限条目 | None
    """认到的诉求条目。`None` 表示一条都没认上。"""
    说明: str

    def 能否继续第3层(self) -> bool:
        """「在权限内」和「未列明」继续；报备／转交／判不了在第 2 层定案。

        「未列明」为什么也继续，见 `权限去向.未列明`。
        """
        return self.去向 in (权限去向.在权限内, 权限去向.未列明)


def 认权限(主张: str, 权限矩阵: Sequence[权限条目] = 权限条目表) -> 权限条目 | None:
    """把一条主张认到某个诉求条目上，认不出返回 `None`。

    **和 `pipeline.认口径` 是同一个问题，用同一套解法**：按命中的词长从多到少取，
    让具体的压过笼统的。长度相同按编号 —— `L01` 在 `L03` 前，所以「赠品漏发了」
    这种同时含「漏发」和「赠品」的输入会落到 L01（漏发）而不是 L03（追加）。
    顺序稳定是可重放的要求，不是审美。

    **这是链路里第二个模型位置**（第一个是 `认口径`）。现在用关键词，够跑通
    演示；真上线应该换成向量检索或一次 LLM 分类，那时「判定可重放」这条
    就不再覆盖到这里 —— 说法要跟着改。

    `权限矩阵` 默认整张表；传它是为了让 `三层判定` 能把矩阵一路带下来，
    测试也就能喂一张小表，不必每次都跑全量 22 行。非 `可认` 的行会被忽略
    —— 理由见模块文档串「表怎么读」。
    """
    命中: list[tuple[int, str, 权限条目]] = []
    for k in 权限矩阵:
        if not k.可认:
            continue
        for 词 in k.关键词:
            if 词 in 主张:
                命中.append((len(词), k.编号, k))

    if not 命中:
        return None
    # 词越长越具体；同长按编号，保证顺序稳定。
    命中.sort(key=lambda x: (-x[0], x[1]))
    return 命中[0][2]


def 查权限(
    主张: str,
    事实: 权限事实 = _未知事实,
    权限矩阵: Sequence[权限条目] = 权限条目表,
) -> 权限判定:
    """第 2 层的判定。三态的输出见 `权限去向`。

    顺序是「先认诉求，再判额度」：

    1. 认不上诉求 → **未列明**，继续第 3 层（见 `权限去向.未列明`）
    2. 认上了，但判这条要的事实没给 → **判不了**（§4.2 的「查不到**条件**」）
    3. 事实给的都符合 → **在权限内**，继续第 3 层
    4. 不符合（超额度／非质量问题）→ 按条目的 `超出后去向`
       —— 这一档是 §6.2（报备）和 §6.2b（转交）分岔的地方，**分岔数据在条目上，
       不在这里写 if**，因为它是业务判断，会变。

    **第 1 步和第 2 步都是「系统搞不清楚」，但去向相反，别合并。** 区别是
    「表里没这一行」还是「有一行但条件不够」：前者说明这压根不是个权限问题
    （成分咨询、用法咨询），继续往下走；后者是真的定不了档（件数未知），
    走报备让人去核实。v9 的示范例子把这个区分钉死了 —— 见 `权限去向.未列明`。
    """
    条目 = 认权限(主张, 权限矩阵)
    if 条目 is None:
        return 权限判定(
            去向=权限去向.未列明,
            条目=None,
            说明="权限矩阵里没有对口的事项，按普通咨询处理（矩阵管的是要授权的事，"
            "不是「客服能聊什么」的白名单）",
        )

    # ── 判这条要的事实给了没有 ──
    # 只看**这条**约束的维度。补发不看金额，退款不看件数 —— 拿无关维度上的
    # None 去判会凭空造出「判不了」，把能办的挡回去。
    if 条目.限额件数 is not None and 事实.件数 is None:
        return 权限判定(
            去向=权限去向.判不了,
            条目=条目,
            说明=f"{条目.事项}：件数未知，定不了额度，走报备核实",
        )
    if 条目.限额金额 is not None and 事实.金额 is None:
        return 权限判定(
            去向=权限去向.判不了,
            条目=条目,
            说明=f"{条目.事项}：金额未知，定不了额度，走报备核实",
        )
    if 条目.需质量问题 is not None and 事实.质量问题 is None:
        return 权限判定(
            去向=权限去向.判不了,
            条目=条目,
            说明=f"{条目.事项}：是不是质量问题未知，定不了，走报备核实",
        )

    # ── 逐条比额度 ──
    超了: list[str] = []
    if 条目.限额件数 is not None and 事实.件数 is not None and 事实.件数 > 条目.限额件数:
        超了.append(f"{事实.件数} 件，超过「{条目.限额}」")
    if 条目.限额金额 is not None and 事实.金额 is not None and 事实.金额 > 条目.限额金额:
        超了.append(f"{事实.金额:g} 元，超过「{条目.限额}」")
    if 条目.需质量问题 is True and 事实.质量问题 is False:
        # 不算「超额度」但走同一条出口：都是「事该办，但不是我能定的」。
        超了.append("非质量问题，不能直接承诺包邮")

    if not 超了:
        # **去向取条目自己的，不是无脑「在权限内」。** §6.1 的行是「在权限内」，
        # 但 §6.3 那七行（不良反应／丢件／质疑正品……）的去向来自**小节标题**，
        # 和额度无关 —— 它们压根没有额度。这里写死「在权限内」会让丢件、
        # 投诉这类该转交的诉求被判成客服自己能办。
        # ⚠️ **紧挨着这句的「须转交」原来也是写死的**（2026-10-01 工单 A · 3.2b）。
        # 它对 Z 系七行是对的（那些全是转交），**对 E 系是错的** ——
        # `E01`–`E05` 去向都是报备。原先看不出来，因为 E 系全部 `可认=False`、
        # 这个分支根本走不到；`E05` 一可认（3.2）就走进来了，输出变成
        # 「客服承诺逾期未做（我方还能补）：一线处理，**须转交**」——
        # 去向说报备、说明说转交，而右栏上这是两个不同的按钮，客服照哪个做？
        # 这个错不会让任何测试变红，只会让演示当天有人问「到底是哪个」。
        #
        # 按**去向**分支，别把某个编号硬塞进 if —— E 系四条同病。
        # 走到这里 `条目` 必然不是 None、要的事实也都给了（上面两个早返回挡住了），
        # 所以 去向 只可能是 在权限内／报备／转交 这三个。
        if 条目.去向 is 权限去向.在权限内:
            说明 = f"在权限内：{条目.事项}（{条目.限额}）"
        else:
            去处 = "转交" if 条目.去向 is 权限去向.转交 else "报备"
            说明 = f"{条目.事项}：{条目.层级}处理，须{去处}"
        return 权限判定(去向=条目.去向, 条目=条目, 说明=说明)

    去向 = 条目.超出后去向 or 权限去向.报备
    理由 = "超出规则上限，需专家按规则裁定" if 去向 is 权限去向.转交 else "超出我的额度，走审批"
    return 权限判定(
        去向=去向,
        条目=条目,
        说明=f"{条目.事项}：{'；'.join(超了)} —— {理由}",
    )
