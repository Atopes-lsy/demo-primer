class 权限去向(StrEnum):
    """第 2 层的四态。

    §4.2 的表列了三态（在权限内／超额度／判不了），第四态 `未列明` 是
    「矩阵里没有这一行」—— v9 的示范例子要求它继续往下走，不能并进判不了。
    详见该成员的说明。
    """

    在权限内 = "在权限内"
    """客服直接办 → 继续第 3 层。"""
    报备 = "报备"
    """事该办，但超出我的额度。§6.2。**对话还在客服手里。**"""
    转交 = "转交"
    """§6.2b / §6.3。超出的不是额度而是**规则**，得专家裁定。"""
    判不了 = "判不了"
    """**认出了诉求，但定档要的条件建立不起来**，比如件数未知、金额未知。

    §4.2 的表里这一态的去向是**报备**，不是转交 —— 配套的那句关键原则是
    「系统查不到 ≠ 客服办不了」，意思是**别因为系统查不到就把对话推给上级**。
    报备的语义是「走个审批」，对话仍在客服手里，和转交是两回事。

    注意 §4.2 原文对这一态的解释是「**系统查不到条件**」—— 关键词是
    **条件**。所以它指的是「额度判不了」，不是「表里没这一行」，后者见 `未列明`。
    """
    未列明 = "未列明"
    """**权限矩阵里根本没有对口的事项** —— 认不上任何一行。

    **这一态不等于「判不了」，不能并进上一档。** 原先代码是把两者合一的
    （认不上 → 判不了 → 报备），被 v9 的示范例子直接推翻：

    > 「这个精华里面有乙醇吗？我是孕妇能用吗」
    > 拆法：claim1「含不含乙醇」← 有来源、不涉承诺 → **AI 直接发送**

    成分咨询在 §六 里当然没有对应行 —— 那张表管的是**要授权的事**
    （补发／换货／退款／赔付／升级），不是一张「客服能聊什么」的白名单。
    把「表里没写」读成「不许办」，会让每一个普通的商品咨询都被推去审批。

    所以这一态的去向是**继续第 3 层**，和「在权限内」一样。区别只在留痕：
    右栏要能说清这条是「矩阵说在权限内」还是「矩阵里没提它」——
    被追问「凭什么」时，这两句的答法完全不同。
    """


@dataclass(frozen=True, slots=True)
class 权限条目:
    编号: str
    事项: str
    层级: str
    """一线／二线／专家／风控／高级。§6.5 第 2 条说 A/B/G/S 编号和层级的对应
    待泽晟确认 —— 所以这里存的是**层级名**，不是工号系。"""
    限额: str
    """给人看的原文，原样抄自 §六。判额度看 `限额件数`／`限额金额`，不看这个。"""
    依据: str
    去向: 权限去向
    升级说明: str = ""
    """业务方原话。§六 的依据列里那些引号内容 —— 它们解释了**为什么**这么定，
    演示时被追问「凭什么」就靠这个答。"""
    可认: bool = True
    """能不能被一条顾客主张认到。见模块文档串「表怎么读」。"""
    关键词: tuple[str, ...] = ()
    """认这条诉求用的词。只在 `可认=True` 的行上有意义。"""
    限额件数: int | None = None
    """`None` = 这条不卡件数。"""
    限额金额: float | None = None
    """`None` = 这条不卡金额。**注意和 `权限事实.金额=None`（金额未知）区分**。"""
    需质量问题: bool | None = None
    """`True` = 只有质量问题才在权限内（退货运费那一行）。`None` = 不区分。"""
    超出后去向: 权限去向 | None = None
    """超额度（或不符合条件）时改判成什么。`None` = 这条没有超额度态。"""
    需触发: 触发编号 | None = None
    """**这一行只在本轮命中这个硬触发时才算数。** `None` = 一直算数。

    只给 `E05` 用。它要的不是「顾客说了哪几个字」，而是「**这一单确实有一件
    答应过的事已经过期了**」—— 那件事只有 `H3` 知道，因为 H3 是结构化算出来的
    （拿 `承诺时限` 和当前时间比），不是从措辞里抠词。

    所以 E05 的闸门是 `需触发=触发编号.H3`：H3 没命中，这一行整行出局，
    关键词再像也没用（`三层判定` 在往下传矩阵之前把出局的滤掉）。
    用户 2026-10-04 拍的就是这个：**H3 当闸门 × 承诺类词表**。
    """


