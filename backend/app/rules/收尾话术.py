"""报备审批回来、客服点［一键发送］才发出去的那句话 —— **固定表，不是模型生成**。

# 和 `安抚话术.py` 那一句不是一回事

两句话落在同一条报备线上，但在**两头**，中间隔着「组长批了」那一下：

  安抚话术 —— 顾客刚说完「赠品还没给我发呢」，系统**自动**接住情绪。
              它先于客服动手发出去，署名带着「不含承诺，无需客服点」。
  收尾话术 —— 授权回来了，客服按了［一键发送］，这一句才出去（本模块）。

所以两张表的硬约束**方向相反**，别把一张的规矩搬到另一张上：

  · 安抚话术**禁数字** —— 它发出去的那一刻没有任何事做过，任何时限都是空头
    支票（口径表 K05）。
  · 收尾话术**必须认账、可以给时限** —— 规格 §七 的「正常收尾」档就是这么定的。
    这一单已经逾期两天，上来只报「已为您登记」等于没接住顾客等的那两天。

# 为什么也是固定表，不问模型

`llm/话术生成.py` 的文件头把这条路堵死了：报备的话**不能让模型重写一遍**。
那三条理由在这一句上照样成立 —— 它是**对顾客的承诺**（含时限），说死了收不
回来；而且 `31_界面文字清单_给思语.md` §四 第 4 条**点名改过它**（原来写的是
「专员会在 24 小时内回访跟进」——**「专员回访」是 ④ 转交的说法，③ 报备不能说**）。
让模型每周重写一遍，等于把那条已经纠正过一次的错话重新交给它去赌。

# 按事项分条，认不出落到兜底

报备有五个来源（`permissions.py` 的 E01–E05），所以不能只写死一句 ——
那句里带着事项（「补发这边」）。查表按**关键词最长优先**，和
`安抚话术.查安抚话术` 同一个分法。

⚠️ **兜底那句没有时限。** 认不出事项就说明没人知道这批货几天能出去，
给一个数字就是替仓库许一个它没许过的诺。丢的是针对性，不是安全性。
"""

from __future__ import annotations

from collections.abc import Mapping

from .koujing import 查禁语全

#: 认不出事项时用这一句。**它也必须过两条硬约束** —— 见 `校验收尾话术`。
兜底收尾 = "抱歉让您久等了，这边已经帮您登记好，会尽快安排处理。"

#: 事项关键词 → 审批回来后客服发的那句话。键是**主张里会出现的事项词**。
#:
#: 「赠品」那一条和 `frontend/src/data/剧本.ts` 第 7 格 `待发` 那句**逐字相同** ——
#: 这不是巧合，是接线的验收点：接口给的话会**换掉**剧本那句（`判定.合消息`），
#: 两边不一致的话，演示里最后一句话术会当着观众的面变样。
收尾话术表: dict[str, str] = {
    "赠品": "抱歉让您久等了，补发这边我已经登记好，今天安排发出，48 小时内给您单号。",
}

#: 认账词。**H3 的强制要求**：触发说明里那句「回复开头必须先认这个账」。
#: 逾期两天再来一句公事公办的「已为您登记」，就是没接住顾客等的那两天。
认账词: tuple[str, ...] = ("抱歉", "对不起", "不好意思", "让您久等")


def 查收尾话术(主张: str, 表: Mapping[str, str] | None = None) -> str:
    """这条报备主张审批回来之后，客服该说什么。**认不出给 `兜底收尾`。**

    `表` 留空用模块里的 `收尾话术表` —— 参数位是给测试注入用的，
    和 `安抚话术.查安抚话术` 同一个路数。
    """
    用 = 收尾话术表 if 表 is None else 表
    # 最长优先：`赠品补发` 这种更具体的要压过 `赠品`，否则具体那条永远轮不到。
    for 关键词 in sorted(用, key=len, reverse=True):
        if 关键词 in 主张:
            return 用[关键词]
    return 兜底收尾


def 校验收尾话术(表: Mapping[str, str] | None = None) -> list[str]:
    """查每一句有没有越过两条硬约束，返回违规说明（空列表表示干净）。

    **加载即校验、且是抛错不是警告** —— 和 `handover.校验转交话术`、
    `安抚话术.校验安抚话术` 同一个模式。理由也一样：这句话是对顾客的承诺，
    表错了的话承诺已经许出去了，调用方再怎么小心都来不及。

    两条硬约束：

    1. **必须先认账** —— 见 `认账词`。这一句只在 `报备` 那一档上屏，而报备的
       触发（E05 承诺逾期）本身就是「我方欠着顾客一件事」，不认账就是装作
       没这回事。
    2. **不许出现禁语** —— 复用 `koujing.查禁语全`，和闸门 G1 同一张表。
       不共用的话这张表就成了绕过 G1 的旁路：本地校验一过就直接发。

    ⚠️ **这里**没有**「禁数字」那一条**，别从 `校验安抚话术` 搬过来 ——
    两条约束方向相反的理由写在模块文档串里。
    """
    用: Mapping[str, str] = (
        {**收尾话术表, "兜底": 兜底收尾} if 表 is None else 表
    )
    违规: list[str] = []

    for 关键词, 句 in 用.items():
        if not any(w in 句 for w in 认账词):
            违规.append(
                f"{关键词}：开头没有认账（缺「{'／'.join(认账词)}」之一）。"
                "这一档说的正是「我方欠着顾客一件事」，不认账就是装作没这回事"
            )
        for 禁 in 查禁语全(句):
            违规.append(f"{关键词}：命中禁语「{禁.禁语}」（口径表 {禁.口径}）")

    return 违规


# 模块导入时校验一次。和 `handover.py`、`安抚话术.py` 一样写在函数外面：
# 这是**数据错误**不是运行时状况，早炸比晚炸好 —— 晚炸的话那一刻这句话
# 已经发给顾客了。
if _违规 := 校验收尾话术():
    raise ValueError(
        "收尾话术越界，发出去就是没认账的承诺：\n  - "
        + "\n  - ".join(_违规)
        + "\n（改 收尾话术表 或 兜底收尾 里对应的条目）"
    )
