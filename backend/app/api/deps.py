@lru_cache(maxsize=1)
def 取装载器() -> 装载器:
    """装载业务数据。**第一次调用时读盘**，之后进程内复用。"""
    return 装载器.从文件(取配置().业务数据路径)


@lru_cache(maxsize=1)
def 取商品表() -> 商品表:
    """① 商品属性表，按货号索引的 20 行。

    **和 `取装载器` 读的不是同一个文件** —— ① 单独一份 `商品属性表_v7_定稿.xlsx`，
    业务数据 xlsx 里那八张表没有它。别顺手改成 `业务数据路径`：那样会撞上
    `检索.商品表.商品表坏`（它查 `1_商品属性表` 这张工作表），而报错说的是
    「工作表名字对不上」，看着像是模型线把表名写错了。
    """
    return 装商品表(取配置().商品表路径)


@lru_cache(maxsize=1)
def 取口径表() -> 口径表数据:
    """② 口径表。和前端 `src/data/koujing.ts` 读的是同一份 `data/koujing.json`。"""
    return 加载口径表()


@dataclass(frozen=True, slots=True)
class 模型位:
    """七个模型位置。**默认是真实现**，测试里整套换掉。"""

    拆主张: Callable[..., list[str]]
    """`llm.拆主张.拆主张(消息, 顾客情况)` —— 买家一句话 → 主张列表。"""
    认口径: Callable[..., str | None]
    """`llm.认口径.认口径(主张, 口径表)` —— 一条主张 → 一个口径编号。"""
    查六源: Callable[..., Any]
    """`检索.六源.查六源(主张, 会话, 商品表, 口径表=…, 口径编号=…)` → `六源结果`。"""
    生成话术: Callable[..., Any]
    """`llm.话术生成.生成话术(判成, 顾客情况=…, 触发列表=…, 口径表=…, 已发出=…)`
    → `生成结果`。

    ⚠️ **这个位比前三个贵得多。** 前三个一次判定各花几次调用，而这个是
    **一条主张一次、每稿最多 3 次**（`话术生成.最多调用`）—— 不接进来跑测试
    的话，光 `test_判定.py` 一轮就是十几次真调用，而且结果由采样决定。
    所以它和 `拆主张` 一样**必须**在测试里换掉，没有「接真的也能跑」这个选项。
    """
    认诉求: Callable[..., str]
    """`llm.认诉求.认诉求(消息文本, 已有诉求)` —— 一条买家消息 → 它属于哪个诉求。

    ⚠️ **调用次数是「整个会话里买家消息的条数」**，不是「一条主张一次」。
    归属要在**切轮之前**算完（`切轮` 拿它决定相邻两条买家消息切不切开），
    而 `切轮` 看的是整条会话 —— 所以 `api/判定.归属表` 会从第 1 条买家消息
    走到最后一条。演示两条线是 3 次和 1 次，真会话按条数涨。

    它比 `生成话术` 便宜、比 `拆主张` 贵：同样**必须在测试里换掉**
    （一条真会话十几条买家消息就是十几次真调用），而且它没有「跑不出结果」
    这条路 —— 模型够不着时 `认诉求` 自己退到 `认不出`，**不抛**。
    """
    认权限: Callable[[str], str | None]
    """`llm.认权限.认权限(主张, 权限矩阵)` 绑好矩阵后的形状 —— 一条主张 → 一个
    权限条目编号（第 2 层「**这件事归谁办**」），认不出回 `None`。

    ⚠️ **`None` ＝「未列明」，不是「拒绝」。** 未列明 ＝ 矩阵里没提它，
    第 2 层**继续往下走第 3 层**；而「拒绝」是一个去向。
    第六个位建错的后果是**每条主张都判未列明**，右栏上看不出和「认不出」
    的区别（`工单交接_给接口线_B.md` §六）。

    ⚠️ **它决定去向，所以测试夹具不许喂一个恒回 `None` 的。** 恒回 `None` 会把
    该 `报备` 的主张全变成 `AI直发` —— 夹具的错会在别处红，看起来像单号坏了。
    夹具要用**关键词那条老路**（`tests/假模型.假认权限`），这样接上前后判成一样。

    上线前它**不在请求路径上**（`llm/认权限.py` 写好了但没人传），于是演示
    当天真正跑的**还是关键词那条老路** —— 2026-10-03 接上，见 `api/判定.py` 第 9 步。
    """
    拆需求: Callable[..., list[str]]
    """`llm.拆需求.拆需求(买家话们, 顾客情况=…)` —— 这一趟的买家话 → 需求列表，
    右栏「这次要什么」那一行（2026-10-04 起）。

    ⚠️ **唯一一个「不在判定链路上」的位。** 前六个都在 `api/判定.py` 里按步走，
    它走的是 `api/需求分解.py`，由前端**每点开一个窗口**问一次。它不参与
    三层判定，判成里也没有它（`拆主张` 那个位才管归因）。

    ⚠️ **它比 `认诉求` 还频。** `认诉求` 是「一条真会话十几次」，它是
    「**演示当天每点开一个窗口一次**」—— 114 个窗口全点一遍就是 114 次。
    所以：① 它单独可配模型（`客户端.需求分解模型`，见 `test_选型.py`）；
    ② **测试里必须换掉**，不然 `test_接口.py` 每打一次会话列表／点开一次窗口
    就是一次真网络调用。

    换掉的假实现要**注意别喂「整段话算一条」**：真实现的兜底是空列表
    （由前端回落到原话），假模型恒回一句原文的话，测出来的是「模型给了这个答案」
    而不是「模型坏了会怎样」—— 那两种兜底是两条路。
    """


def 认权限(主张: str) -> str | None:
    """第六个位的真实现：**把权限矩阵闭包进来**，凑成 `Callable[[str], str | None]`。

    矩阵在这一层喂进去、不在 `llm/认权限.py` 里取，是因为那一层不该知道
    「哪张表是权威的」—— 它只管把收到的表发给模型。`权限条目表` 是规则线的
    常量，和 `三层判定` 的默认参数用的是**同一张**，所以接上之后「认哪张表」
    没有第二处答案。
    """
    return 模型认权限(主张, 权限条目表)


def 取模型位() -> 模型位:
    """真实的七个模型位置。

    **不加 `lru_cache`**：这七个都是纯函数引用，`模型位` 本身就是个不可变的值束，
    缓存一个「装着七个模块级函数的盒子」没有任何收益。
    """
    return 模型位(
        拆主张=拆主张,
        认口径=认口径,
        查六源=查六源,
        生成话术=生成话术,
        认诉求=认诉求,
        认权限=认权限,
        拆需求=拆需求,
    )
