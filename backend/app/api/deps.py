"""依赖注入 —— 装载器单例 ＋ 三张参照表 ＋ 七个模型位。

**单例不是性能优化，是正确性。** `装载器.找` 返回的是列表里那**同一个对象**
（理由见 `app/data/装载器.py`）：判定层会把 `顾客情况` / `建议` 补在这个对象上。
每次请求重新装载一遍的话，补上去的东西会在下一个请求里无声消失，而右栏显示
的是「判定结果没了」——看起来像判定接口坏了。

`lru_cache` 而不是模块级全局变量：测试要能 `cache_clear()` 换掉它，
模块级变量只能在导入时定型。

# 模型位为什么在这里

`判定.py` 要调六个模型位置（拆主张／认口径／查六源／生成话术／认诉求／认权限），
`需求分解.py`（2026-10-04 新开的那条路）调第七个（拆需求）。它们
**默认指向 `llm/` / `检索/` 里的真实现** —— 那两个模块是模型线的，接口线只 import 不编辑。

做成一个 `模型位` 束而不是直接在路由里 `from ..llm.拆主张 import 拆主张`：
直连的话测试打 `/api/判定` 会**真的打上十几次 API 调用**（`拆主张` 每条消息一次、
`认口径` 每条主张一次、`认权限` 每条主张一次、`认诉求` 每条买家消息一次、
`生成话术` 每条主张最多三次），
而且结果由厂商采样决定 —— 测试会变成「今天绿明天红」。接到 `Depends` 上，测试一个
`dependency_overrides[取模型位]` 就全换成假的，走的还是同一条路由代码。

⚠️ **第七个位（`拆需求`）不在 `/api/判定` 上** —— 它是 `POST /api/需求分解` 的。
两条路各取各的位，但**共用同一个 `模型位` 束**：假模型只需在一处配齐，
而「这条请求该调哪几位」由路由自己说了算（判定那条路不碰 `拆需求`，
需求分解那条路不碰另外六个）。

⚠️ **假实现是测试写的，不是这里写的。** `工单 §7.2` 那句「桩放在你自己的模块里」
说的是「别放进 `llm/`／`检索/` 去和模型线抢文件」—— 现在那边已经落地了，
生产路径就用真的，测试的假模型住在 `tests/` 里。
"""

