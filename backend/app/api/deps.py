"""依赖注入 —— 装载器单例 ＋ 三张参照表 ＋ 三个模型位。

**单例不是性能优化，是正确性。** `装载器.找` 返回的是列表里那**同一个对象**
（理由见 `app/data/装载器.py`）：判定层会把 `顾客情况` / `建议` 补在这个对象上。
每次请求重新装载一遍的话，补上去的东西会在下一个请求里无声消失，而右栏显示
的是「判定结果没了」——看起来像判定接口坏了。

`lru_cache` 而不是模块级全局变量：测试要能 `cache_clear()` 换掉它，
模块级变量只能在导入时定型。

# 模型位为什么在这里

`判定.py` 要调三个模型位置（拆主张／认口径／查六源）。它们**默认指向
`llm/` / `检索/` 里的真实现** —— 那两个模块是模型线的，接口线只 import 不编辑。

做成一个 `模型位` 束而不是直接在路由里 `from ..llm.拆主张 import 拆主张`：
直连的话测试打 `/api/判定` 会**真的花掉一次 API 调用**（`拆主张` 每条消息一次、
`认口径` 每条主张一次，一轮就是五六次），而且结果由厂商采样决定 ——
测试会变成「今天绿明天红」。接到 `Depends` 上，测试一个
`dependency_overrides[取模型位]` 就全换成假的，走的还是同一条路由代码。

⚠️ **假实现是测试写的，不是这里写的。** `工单 §7.2` 那句「桩放在你自己的模块里」
说的是「别放进 `llm/`／`检索/` 去和模型线抢文件」—— 现在那边已经落地了，
生产路径就用真的，测试的假模型住在 `tests/` 里。
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from functools import lru_cache
from typing import Any

from ..data.装载器 import 装载器
from ..llm.拆主张 import 拆主张
from ..llm.认口径 import 认口径
from ..llm.话术生成 import 生成话术
from ..检索.六源 import 查六源
from ..检索.商品表 import 商品表, 装商品表
from ..rules.koujing import 口径表数据, 加载口径表
from ..配置 import 取配置


@lru_cache(maxsize=1)
def 取装载器() -> 装载器:
    """装载业务数据。**第一次调用时读盘**，之后进程内复用。"""
    return 装载器.从文件(取配置().业务数据路径)


@lru_cache(maxsize=1)
def 取商品表() -> 商品表:
    """① 商品属性表，按货号索引的 20 行。

    **和 `取装载器` 读的不是同一个文件** —— ① 单独一份 `商品属性表_v7_定稿.xlsx`，
    业务数据 xlsx 里那八张表没有它。别顺手改成 `业务数据路径`：那样会撞上
    `检索.商品表.商品表坏`（它查 `1_商品属性表` 这张工作表），而报错说的是
    「工作表名字对不上」，看着像是模型线把表名写错了。
    """
    return 装商品表(取配置().商品表路径)


@lru_cache(maxsize=1)
def 取口径表() -> 口径表数据:
    """② 口径表。和前端 `src/data/koujing.ts` 读的是同一份 `data/koujing.json`。"""
    return 加载口径表()


@dataclass(frozen=True, slots=True)
class 模型位:
    """四个模型位置。**默认是真实现**，测试里整套换掉。"""

    拆主张: Callable[..., list[str]]
    """`llm.拆主张.拆主张(消息, 顾客情况)` —— 买家一句话 → 主张列表。"""
    认口径: Callable[..., str | None]
    """`llm.认口径.认口径(主张, 口径表)` —— 一条主张 → 一个口径编号。"""
    查六源: Callable[..., Any]
    """`检索.六源.查六源(主张, 会话, 商品表, 口径表=…, 口径编号=…)` → `六源结果`。"""
    生成话术: Callable[..., Any]
    """`llm.话术生成.生成话术(判成, 顾客情况=…, 触发列表=…, 口径表=…, 已发出=…)`
    → `生成结果`。

    ⚠️ **这个位比前三个贵得多。** 前三个一次判定各花几次调用，而这个是
    **一条主张一次、每稿最多 3 次**（`话术生成.最多调用`）—— 不接进来跑测试
    的话，光 `test_判定.py` 一轮就是十几次真调用，而且结果由采样决定。
    所以它和 `拆主张` 一样**必须**在测试里换掉，没有「接真的也能跑」这个选项。
    """


def 取模型位() -> 模型位:
    """真实的四个模型位置。

    **不加 `lru_cache`**：这四个都是纯函数引用，`模型位` 本身就是个不可变的值束，
    缓存一个「装着四个模块级函数的盒子」没有任何收益。
    """
    return 模型位(
        拆主张=拆主张,
        认口径=认口径,
        查六源=查六源,
        生成话术=生成话术,
    )
