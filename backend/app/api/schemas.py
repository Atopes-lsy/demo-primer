class StateRow(契约模型):
    """顾客情况的一行。

    **「警示」是回填的，不是装配时算的** —— 它来自硬触发 H3，而 H3 的输入
    （`时限`）又来自这一行，直接写会成环。顺序定死就解开了：

        阶段 1（装配）：产出基础行，含 `时限`，不含 `警示`
        阶段 2（硬触发）：H3 读 `时限`，算出逾期天数
        阶段 3（回填）：把逾期天数写回 `警示`

    对应 `pipeline.组装顾客情况`。
    """

    标签: str
    """行标签，固定五选一。值域见 `pipeline.顾客情况五行`。"""
    值: str
    备注: str | None = None
    警示: str | None = None
    """警示文案，红色显示，如「已逾期 2 天」。**由 H3 回填。**"""
    时限: str | None = None
    """**只「答应过什么」这一行有。** ISO 8601，给 H3 比时间用。

    为什么单独一个字段：「值」里写的是「9/26 承诺『今天答复』」——「今天」是相对
    **承诺发生那一刻**（9/26）而言的，不是相对当前。规则解析极脆，交给 LLM 解析
    又把模型塞到了 H3 前面，「纯规则、微秒级」的前提就没了。所以解析放在装配层
    （它本来就在做「自然语言 → 结构化」），H3 只读这个字段。
    """


class Evidence(契约模型):
    """依据条目。命中的和没命中的都列出来。

    **由 `sources.源记录` 转来，字段对应关系见 `docs/接口契约.md` 的映射表。**
    `源记录` 那边是 v9 §4.1 写死的 `{exists, table, row_id, content}`，字段名是
    英文；这里是线上形状，用前端的中文名。转换在步骤 2 的接口层做。

    两个承诺要分粒度说，别混：

    - **「没有遗漏」做得到 —— 在「六个来源」这个粒度上。** 六源是封闭集合，
      逐个报「有记录／无记录」可穷举。
    - **「源内没有截断」做不到。** ① 和 ③ 内部走向量召回，天然 top-K 截断。

    至于「没有编造」（话术里的事实和数字都能在列出的依据里找到出处）是另一个
    承诺，由 G3 闸门在管。
    """

    序号: 六源
    """来源编号，固定六选一：①②③④⑤⑥。

    **类型是 `sources.六源` 而不是 `str`，这不是顺手写的** ——「六源是封闭集合」
    是这个项目对评委的核心承诺之一（「一并列出以示无遗漏」只有穷举得了才做得到）。
    声明成 `str` 的话，第 7 个来源会以字符串的形式悄悄溜进右栏。
    """
    出处: str
    """表名 ＋ 行号，如「口径表 K05」。"""
    摘要: str
    用上: bool
    """本轮是否用上。false 的进「未命中的六源清单」，带摘要一并列出。

    计数按**来源**不按条：同一个来源可以有多条引用（口径表就常同时命中 K06
    和 K20），只算命中一次。见 `sources.六源结果.命中源`。
    """


class 已代发条目(契约模型):
    """本轮 AI 代发出去的一句话。

    前端把这个形状**内联**在 `Advice.已代发` 里（`types/index.ts`），线上形状
    一致，只是给它起了个名字 —— 出现两次以上的结构给个名字，文档和留痕都要引用。

    为什么要有这一块：AI 直发的意思是客服不用动手，但客服得知道**刚才有句话
    是以他/她的名义发出去的**。顾客那边看到客服说了话，客服这边右栏一片安静，
    等顾客回一句「你刚才不是说可以退吗」就彻底对不上了。
    """

    内容: str
    署名: str
    依据: list[Evidence]


class Advice(契约模型):
    """主卡。三种形态对应客服真正要动手的三种输出。

    这里只有三种形态，`输出类型` 有四种：**「AI直发」不在其中，因为它不需要
    客服动手** —— 见 `已代发`。由 `pipeline.主卡形态` 取本轮最高态再映射：

        AI直发 → 不上主卡（只进 `已代发`）
        客服点发送 → 需要话术
        报备 → 需要授权
        转交 → 有风险

    ⚠️ **`判断` / `标题` / `说明` / `风险标签` 这四句文案后端现在没有真源。**
    契约先定形状；步骤 2 要定一张「形态 × 触发 → 文案」的表。在那之前这四句
    由调用方填。
    """

    形态: Literal["需要话术", "需要授权", "有风险"]
    判断: str
    """主卡顶部胶囊里的 AI 判断，如「这次需要「授权」」。"""
    标题: str
    说明: list[str]
    """正文说明，一行一条。"""
    话术: str | None = None
    """待发的那句话，**两个来源按去向分**：`需要话术` 走模型的成稿；
    `有风险` 取 `handover` 的转交话术。`报备` 时为 `None` —— 它的安抚话术
    由客户端发，落在 `已代发` 里。"""
    风险标签: str | None = None
    """「有风险」时的风险标签，如「⚠ 顾客已登记不良反应 · 情绪升级」。"""
    话术建议: str | None = None
    """「有风险」时的话术建议。"""
    依据: list[Evidence]
    """依据清单，展开后显示。

    **只放查到的**（`源记录.exists=True` 的那些）；没查到的来源由前端按六源
    补空位。这样 `N/6 源命中` 和「另 N 源无记录」在任何后端实现下都成立，
    也不会漏列 —— 后端不需要知道前端要补几个空位。
    """
    已代发: list[已代发条目] | None = None
    """没有就不显示这一块。**只列 ① AI直发 的**，不含客服自己点发送的。"""


class Disposition(契约模型):
    """本轮处置的一条：某条主张被判成了哪种输出。对应 `pipeline.判成`。

    **一个诉求一条，不是一个风险点一条。** 顾客说「用了你们精华脸刺痛，另外赠品
    也没收到」，这是两条主张。反过来的例子：同一个「赠品漏发」既触发 H3 又被认成
    K07，那也是**一条**主张，`输出` 取两者里高的那个，触发详情写在 `说明` 里
    —— 拆成两条的话，客服会去数、会对不上。
    """

    id: str
    """稳定 ID，格式 `${会话ID}-${轮次}-${序号}`，如 `S00005-3-2`。

    **没有它就做不了收敛。** 收敛要把某一轮的非终结主张改写成「随对话一并转交」，
    改的是哪几条得有办法指认 —— 拿 `主张` 原文当键不行，同一个会话里「赠品漏发」
    会在第 2 轮和第 5 轮各出现一次，改错轮次留痕就对不上了。
    """
    轮次: int
    主张: str
    输出: 输出类型
    说明: str | None = None
    """补充说明，如「涉个体差异，必须带回边界句」。

    ⚠️ **这句话会原样进右栏，所以它可以给客服看，不能给顾客看。**
    """

    # ── 以下五个来自规则层重构（2026-09-29），前端 `types/index.ts` 同步加 ──

    涉及个体差异: bool
    需边界句: bool
    """涉个体差异 → 这句必须带回边界句才能发（G2）。

    **和 `涉及个体差异` 取同一个值，两条路都设。** 它不只是第 3 层的判据：
    G2 管的是**话术出稿**，不管这段话术是哪一层决定要发的 —— 报备和转交的时候
    话也得有人说，说的人一样需要边界句。装配层拿它当 G2 的开关。
    """
    层: str
    """这条是**哪一层**定的：硬触发／第1层／第2层／第3层。

    排障时第一个要看的字段：判错了先看它停在哪一层，就知道该改哪张表。
    """
    权限去向: str
    """第 2 层查权限矩阵的结果。空串 = 没走到第 2 层。

    值域见 `app/rules/permissions.py` 的 `权限去向`。**注意 `未列明` 和
    `在权限内` 都能继续第 3 层、但不是一回事** —— 前者是矩阵里没有对口的事项。
    """
    交接分类: str
    """转交时的分类（产品／物流／公关），决定交接给哪个专家队列。

    空串 = 认不出该归哪一类。**认不出就留空，不猜一个默认分类** —— 交接单上
    分类错了比空着更糟：空着专家自己扫一眼就知道归谁，错了会先被转一手。
    """


