    # 代价是「Session 每个字段逐字对应」这句话字面上不成立，所以
    # `tests/test_schemas.py` 里为它留了一行**写明理由**的例外，而不是硬塞个字段
    # 让断言好看。另有两个前端内联的子结构（`报备`/`转交`）在这里提成了命名模型
    # —— 线上形状完全一致，只是给了名字，测试按形状核对。
