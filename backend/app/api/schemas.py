"""接口契约 —— 「一句话进来 → 右栏出什么」的 JSON 形状（开发步骤 步骤 0）。

**这个文件定形状，不做判定、不查数据。** 判定在 `app/rules/`（已完成），
HTTP 路由在步骤 1 起。这里一个函数都没有。

# 三条规矩

**1 · 字段名逐字照 `frontend/src/types/index.ts`，两边一字不差。**
中文名、大小写、可选性全照抄，**不引入映射层** —— 后端叫什么，线上就叫什么。
改这里就得改那里；`tests/test_schemas.py` 会解析那个 TS 文件逐个字段核对，
漏一个直接红。这条是「契约」两个字的全部内容，别用「反正前端能适配」绕过。

**2 · 枚举从 `app/rules/` import，不另抄一份。**
另抄一份的下场是两处各改各的，而线上只会表现成「后端认」或「前端认」
其中一个对 —— 这是最难查的一类不一致。

**3 · 别名（`alias=`）只在 Python 语法不允许时用，且别名与前端字段名逐字相同。**
4 个带括号的金额列（`单价(元)` 等）不是合法的 Python 标识符，只能换个属性名
再挂别名。**这不是映射层**：线上跑出来的 JSON 字段名和前端一模一样。

# 模型顺序是有意的

`Session` 引用了右栏那一组模型，而 Python 的注解在建类时就要能解析到那些名字
—— 所以**右栏那一组必须排在会话数据前面**。看着像倒过来了，是语法逼的。
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from ..rules.inbound import 处置, 类别
from ..rules.pipeline import 输出类型
from ..rules.sources import 六源
from ..rules.triggers import 触发编号


class 契约模型(BaseModel):
    """所有契约模型的基类。"""

    model_config = ConfigDict(
        populate_by_name=True,
        # 不带参数调 `model_dump()` 时走**别名**而不是 Python 属性名。
        #
        # 这是为了防一个具体的错：带 `alias` 的字段（4 个金额列）默认会把
        # `单价元` 输出到线上，前端读 `单价(元)` 读到 undefined —— **而它不会报错**，
        # 界面上只是少了一个数字。设成默认走别名，就不存在「记得加 by_alias」这件事。
        serialize_by_alias=True,
    )


