交接包态 = Literal["等待审批", "已完成", "已转出"]
"""交接包走到哪一步了。取值和前端 `交接包态` 逐字对应。

- `等待审批`：报备交上去了，**这一单还没走完**；
- `已完成`：话发出去了，这一单算走完（由 `发送` 推出来，见 `台账.推进报备单`）；
- `已转出`：不是审批流，是**交出去了**。转交没有「完成」这回事，
  对话归了别人，客服这一侧的活到此为止。

⚠️ **`等待审批` 不是「组长还没批」。** 第 8 步（组长批准了、话还没发）的徽标
也显示它 —— 那一格**没有事件源**（系统里没有任何东西产出「批准」这件事，
只有剧本知道），而 `31 §1.4` 只列了 `等待审批 · 已完成` 两个值，不单开一格。
所以这个值的意思是「**还没走完**」，不是「卡在审批上」。（2026-10-03 拍板：
加第四个值的方案被否了，见 `工单交接_给接口线_C.md` §一 1.3。）
"""


class 交接包(契约模型):
    """报备／转交自动带全的那张单，组长或专员要的东西全在上面。

    ⚠️ **字段名别自己发挥** —— 两边一旦漂开，右栏只是**少显示一行，不会报错**
    （工单 §八 第 4 条）。

    **七行是后端拼的。** 前端那份 `建交接包()` 还在（`data/交接包.ts`）——
    ⚠️ 2026-10-03 拍的是**「留作兜底」，不是删**（`工单交接_给前端线_B.md` §一 1.1 乙）。
    两边同形因此是**必须的**：接口挂了右栏回落到的就是它，屏幕上不该看出换了个人拼。
    行数是固定的七行，顺序也是 —— 右栏按顺序渲染，缺一行不会报错，
    只会少一格。
    """

    状态: 交接包态
    行: list[交接行]
    单号: str
    """工单号，**由后端出，客服零填写**（规格 §7）。

    报备和转交都是 `JJ` 前缀（2026-10-03 拍的，照 31 §3.6 底部）；同一个诉求
    因轮次切分被处理多次也只发一个号（`台账.发号`）。
    """


class 动作请求(契约模型):
    """`POST /api/会话/{id}/报备` 和 `/转交` 的请求体。**只有一个字段。**

    ⚠️ **`轮次` 必填，不给就 422。** 它防的是「**有一张、但属于另一轮**」：
    台账一个会话只留最后那一轮判定，而前端是按轮显示的 —— 拖回上一轮再点按钮，
    后端会照着**最后判的那一轮**立一张单子，**而那张单子看着完全正常**。
    不给「漏传就跳过校验」的机会，那等于退回老行为，而屏幕上根本看不出
    点的是哪一轮。
    """

    轮次: int


class 发送请求(契约模型):
    """`POST /api/会话/{id}/发送` 的请求体。"""

    轮次: int
    """这条话术是**哪一轮**的。理由和 `动作请求` 里那一格同一个 ——
    轮次整条对不上时，客服手上那几个处置 id 属于**另一轮**，后端拿自己那一轮的
    表去比，命中的话就记成了一条发生在别的轮次上的留痕。"""

    话术: str
    采用的处置id: list[str] = []
    """这条话术兑现哪几条主张，填 `Disposition.id`。

    ⚠️ **空数组合法，而且常见** —— 客服自己敲一句话直接发，那是常态。
    别在这里拿「本轮最高态」替客服认领几条主张：那会让留痕记下一件
    没发生过的事。
    """


class 发送响应(契约模型):
    """`POST /api/会话/{id}/发送` 的响应体。

    `兑现主张` 是把 `采用的处置id[]` 翻成人话 —— **前端不用自己拿 id 去猜**，
    而且留痕里要能读出「这条诉求办没办」。
    """

    会话ID: str
    轮次: int
    话术: str
    兑现主张: list[str]
    """按请求里给的顺序，一条 id 一条主张。空数组 = 这句话不兑现任何主张。"""

    报备单态: 交接包态 | None
    """这个会话的**报备单**推到哪儿了。**`None` = 这个会话没有报备单。**

    「答复完了」是报备单生命周期上**前后端都知道**的那一个事件（客服点了
    ［一键发送］／［发送］），所以 `发送` 顺手把它推到 `已完成` —— 不新开路由、
    不发明事件源，`状态` 仍然是后端一个真源。前端拿这个字段改
    `交接包表[会话ID].状态`（`App` 的 `记一笔发送` 成功回调）。

    ⚠️ **`None` 不等于「没推进」**，它是「**没有这张单子**」。三种来源：
    这个会话压根没报备过（138 条真会话、`客服点发送` 那一支）、转交过的
    （`已转出` 是终点，转交不记报备单）、以及请求的轮次和立单那一轮对不上。

    ⚠️ **判据不是「发送过就完成」。** `台账.记发送` 是**追加**的（一轮可以发
    好几条），而 `发送` 也被「客服点发送」那一支用 —— 照「发送过」判会把
    一堆没报备过的会话标成已完成。判据要的是「**这个会话有一张报备单，
    且它答复出去了**」。
    """


