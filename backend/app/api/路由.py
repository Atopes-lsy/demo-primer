"""HTTP 路由。

**步骤 1 只有两个只读接口**，`docs/接口契约.md` 第二节那张表的头两行。

顺序是刻意的：先写这两个最简单的，验证的是「前后端能通」这件事本身 ——
Vite 代理配没配对、CORS 过不过、中文经不经得起 JSON 往返。这些坑在五分钟的
接口上暴露，比在判定接口上暴露便宜得多。

`POST /api/判定` 是步骤 2，写在另一个模块里（它要挂三个还没实现的模型位）。
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends

from ..data.装载器 import 装载器
from ..data.顾客窗口 import 合并窗口
from . import deps, schemas
from .判定 import 整会话顾客情况

router = APIRouter()

业务数据 = Annotated[装载器, Depends(deps.取装载器)]
"""装载好的业务数据。两个只读接口都要它。

写成 `Annotated` 而不是 `装: 装载器 = Depends(...)`：后者是 ruff 的 B008
（函数调用出现在参数默认值里），而 `Annotated` 本来就是 `Depends` 的
现代写法 —— 顺手把 lint 的例外也免了，不用挂 `# noqa`。
"""


@router.get("/healthz", summary="活着没")
def 健康检查(装: 业务数据) -> dict[str, object]:
    """带会话数，不是单纯的 `{"ok": true}`。

    装载器读到空表时 `{"ok": true}` **也是 true** —— 那时候
    「前后端通了没有」这个问题的答案就变成假的了。带上计数，
    `curl` 一眼能看出数据到底在不在。
    """
    return {"ok": True, "会话数": len(装.会话列表)}


@router.get("/api/会话列表", response_model=list[schemas.Session], summary="左侧列表 ＋ 中部聊天区")
def 会话列表(装: 业务数据) -> list[schemas.Session]:
    """窗口列表，按窗口 ID 排序。

    **没有分页、没有筛选**：114 个窗口一次给完，前端左侧列表本来就是全量渲染
    （它现在读的就是一份写死的全量数组）。等真有几千个再说。

    # 2026-10-03 起按顾客合并，138 条会话 → 114 个窗口

    同一个人来过几次，左栏原来是几条互不相干的记录 —— 而右栏那五行「顾客情况」
    本来就是**以前的会话攒出来的**（「这是谁」备注里的「上次 X · 工单」、「答应过
    什么」、「办过什么」全是历史）。看不出是同一个人，那五行就没有出处。

    合并规则、窗口 ID 取哪一段、消息序号为什么必须重编，全写在
    `data/顾客窗口.py` 的模块文档串里 —— **这里只调它，一条判断都不写**。
    装载器一行没动：它仍然是 138 条原始真相（`/healthz` 也照旧报 140）。

    # `POST /api/判定` 对窗口只能看见末段

    窗口 ID 是末段的会话 ID，而 `装.找(会话ID)` 返回的是那条**原始会话**。
    今天无害：138 条真会话走的是「还没跑判定」那条路（`PrimerPanel.未判定`），
    判定按钮根本不显示，只有两条演示线（各自一段）会真的调判定。
    接真实判定之前必须先决定「判窗口还是判段」。

    # 每条都带「顾客情况」

    之前这一栏对**当时列表里全部 140 条**都是 `null`，于是除两条演示线之外，
    点开哪一条右栏都只有一句「这条会话还没跑判定」—— 而那是**产品要的那块模块
    根本不出现**，不是「还没接上」的样子。

    现在每条都在这里装配一遍五行（`判定.整会话顾客情况`，纯规则、不碰模型）。
    **这不是「给 138 条会话跑了判定」**，判定仍然只接在两条演示线上；变的是
    「顾客情况」这一栏从空变成了装配得出来的那五行。右栏因此变成：
    顾客情况有内容 ＋ 下面照实说还没跑判定。

    多传的那个 `票表` 是该窗口**所有段**的工单（`窗口ID → {工单号: 票}`），
    用来认前段许下的承诺 —— 不传的话有三个真实窗口会报出假逾期，见
    `装配._未兑现`。

    # 为什么是 `model_copy` 不是就地写回

    `装.会话列表` 是**进程内共享的那一份**，`装.找()` 返回的还是同一个对象
    （它的文档串记着这件事）。就地写 `会话.顾客情况 = ...` 的话，这次请求的
    产物会留在装载器里，而装载器声明自己只读 —— 更实际的问题是：下一次请求
    拿到的是上一轮留下的行，改装配逻辑也擦不掉它。

    `合并窗口` 也是这个道理：它产出的每条窗口都是 `model_copy` 出来的新对象，
    装载器里那份不受影响（`data/顾客窗口.py` 模块文档串的「只读」一节）。
    """
    窗口们, 票表 = 合并窗口(装.会话列表)
    return [
        窗口.model_copy(update={"顾客情况": 整会话顾客情况(窗口, 票表.get(窗口.会话ID))})
        for 窗口 in 窗口们
    ]
