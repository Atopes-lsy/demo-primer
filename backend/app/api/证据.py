"""证据映射 —— `源记录` / `依据条目` → 线上形状 `schemas.Evidence`。

**全项目唯一一处真正的映射。** 两边字段名不一样，是刻意的：

    `sources.源记录`（英文）   v9 §4.1 写死的 `{exists, table, row_id, content}`
    `guards.依据条目`（中文）  链路下游用的形状
    `schemas.Evidence`（中文） 出线形状，前端 `types/index.ts` 逐字对应

放接口层，**别扩散到别处** —— 多一处映射就多一处漂移的地方。

# 为什么是两个函数不是一个

`工单交接_给接口线.md` §五 那张表头写「`源记录` → `Evidence`」，但表里的字段
（`序号` / `出处` / `摘要`）是 `依据条目` 的。两者对不上，而且**都对不上对方**：

- `源记录` **没有 `序号`** —— 序号是 `六源结果.记录` 那个 dict 的**键**。
  拿到一批 `源记录` 时序号已经丢了（`pipeline.判成.依据` 的文档串记着这件事，
  那也是它坚持收 `依据条目` 不收 `源记录` 的原因）。
- `依据条目` **没有 `table` / `row_id`** —— 它在链路更下游，出处早就拼成
  「口径表 K05「赠品补发承诺」」这样的整句了。

两个来源都在链路里，所以这里出**两个**映射，各补各的。硬凑成一个的话，
要么六源那边丢了出处，要么对着 `源记录` 找 `序号` 当场 AttributeError。

# 哪一条边喂哪一份

两个函数各有一个生产调用方，**都在 `判定.py`，喂的是右栏里两块不同的地方**：

- **`从六源`** → `Advice.依据`（主卡那份六源清单）。理由在 `Advice.依据`
  的文档串里写着「只放查到的」—— 而 `六源结果` 才是「查到了什么」的那份记录，
  `判成.依据` 只是它对某一条主张的投影。用后者的话，右栏那个 `N/6 源命中`
  会变成「有几条主张引用了它」，两回事。
- **`从依据条目`** → `已代发[].依据`（那几句以客服名义发出去的话）。它要答的是
  **另一问**：「**这一句**话引的是哪几条」。所以它取 `判成.依据` 而不是六源 ——
  那条主张查到的记录里，只有它真引的那些才算数（`判定._依据` 按模型自报压过
  `用上`，两个函数对 `用上` 的口径是同一个）。

⚠️ **别把两块换成同一个函数「统一下来」。** 换成 `从六源` 的话，右栏那句
「亲，这款不含乙醇哦～」下面会挂着**整轮查到的六源**（包括孕妇能不能用那条的
K01）—— 客服顺着翻到「孕期/哺乳期使用」，而那句话跟成分毫无关系。
换成 `从依据条目` 的话，主卡那份清单会丢掉没被引用的来源，
`N/6 源命中` 的分母就从 6 变成「引了几源」，而展开后那段「未命中的六源清单」
会恒为空 —— **两处都看着对**。
"""

from __future__ import annotations

from collections.abc import Iterable

from ..rules import guards, sources
from .schemas import Evidence

#: `摘要` 的字符上限。超了截断并加省略号。
#:
#: 「太长就截断，**截断要说**」（`工单 §五`）。不说的话，客服读到一句戛然而止的
#: 话，会以为材料本身就到此为止 —— 而 G3 恰恰在管「话术里的事实能不能在依据里
#: 找到出处」。`…` 就是那个「说」。
#:
#: 60 是个起点不是定论：右栏那条依据是**一行**，长了会被 CSS 截掉 ——
#: 而 CSS 截断不带省略号的样子，和「这句话本来就这么短」长得一样。
摘要上限 = 60


def _摘要(原文: str) -> str:
    """截断到 `摘要上限`，超了补省略号。

    恰好等于上限的原样出去 —— 「刚好装得下」和「装不下」是两回事。
    """
    原文 = 原文 or ""
    return 原文 if len(原文) <= 摘要上限 else 原文[:摘要上限] + "…"


def _出处(记录: sources.源记录) -> str:
    """`table` ＋ `row_id` → 「口径表 K05」。

    G3 要求「引用的表名＋行号必须真实存在」，出处就是拿这两个字段回查的 ——
    所以这里**只拼接，不美化**：多个空格、多个书名号都会让回查落空。

    行号为空时只给表名。① 商品属性表就是这种：它按「成分栏」定位，
    没有 K 编号那种行号。
    """
    return f"{记录.table} {记录.row_id}".strip()


def 从六源(结果: sources.六源结果) -> list[Evidence]:
    """`六源结果` → `list[Evidence]`。

    **只放查到的**（`exists=True`）。没查到的来源由**前端**按六源补空位 ——
    两边都补的话数量对不上，右栏的 `N/6 源命中` 会变成漏列
    （`schemas.Advice.依据` 的文档串 + `工单 §四`）。

    `用上=False` 的**要出**：它进「未命中的六源清单」，带着摘要一并列出。
    `exists` 和 `用上` 问的是两件事 —— 查到但没引用，第 1 层仍算「查得到」，
    只是右栏那个分数不算它（`六源结果.命中源` 的文档串）。

    顺序按 `六源顺序`，不按数据到达顺序：同一份输入跑两遍要得出同样的清单。
    """
    return [
        Evidence(序号=源, 出处=_出处(记录), 摘要=_摘要(记录.content), 用上=记录.用上)
        for 源 in sources.六源顺序
        for 记录 in 结果.记录[源]
        if 记录.exists
    ]


def 从依据条目(条目们: Iterable[guards.依据条目]) -> list[Evidence]:
    """`依据条目` → `list[Evidence]`。

    `序号` 要从 `str` **转成 `sources.六源`**（`工单 §五`）。声明成 `str` 的话，
    第 7 个来源会以字符串的形式悄悄溜进右栏 —— 而「六源是封闭集合」是这个项目
    对评委的核心承诺之一，「一并列出以示无遗漏」只有穷举得了才做得到。

    转不动就 `ValueError`，**不兜底成某一源**：兜底的话那句错话长得完全正常，
    而右栏那个分母还是 6。

    `成分` **丢掉**（`guards.依据条目.成分` 的文档串专门为它写了警告）：
    它是 G3 的输入，对客服没有意义，进了 `Evidence` 还要连累前端跟着改。
    这里不是「记得别传」——是压根没有传的路径，`Evidence` 没这个字段。
    """
    出: list[Evidence] = []
    for 条 in 条目们:
        try:
            源 = sources.六源(条.序号)
        except ValueError as 错:
            # 包一层：枚举自己那句 `'⑦' is not a valid 六源` 没说出**为什么**
            # 这件事要紧。丢在演示前一天的红，得一眼看出是「第 7 个来源」
            # 而不是「某个枚举写错了」。
            raise ValueError(
                f"依据条目的「序号」不是六个来源之一：{条.序号!r}（出处：{条.出处}）。"
                "六源是封闭集合，右栏那个分母是 6 —— 第七个来源不许溜进去。"
                "序号应当是 '①'–'⑥' 之一。"
            ) from 错
        出.append(
            Evidence(序号=源, 出处=条.出处, 摘要=_摘要(条.摘要), 用上=条.用上)
        )
    return 出
