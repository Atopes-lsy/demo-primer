"""动作接口的台账 —— `报备`／`转交`／`发送` 读的那几样。

# 为什么必须有这一份

三个动作接口的输入都**不足以自己算出结果**：

- `报备`／`转交` 要的七行里，「诉求」来自 `本轮处置`、「升级分类」来自
  `交接分类` 和 H1 的命中词 —— 这些都是**上一跳判出来的**，请求体里没有；
- `发送` 收的是 `采用的处置id[]`（`S_DEMO_A-1-1` 这种），**没有服务端那张
  id → 主张 的表，它就是一堆没人认得的字符串**。而 `Disposition.id` 这个字段
  存在的全部理由就是这一句话（`schemas.Disposition.id` 的文档串）。

所以 `POST /api/判定` 把自己的产物往 `api/留痕.py` 写一份，动作接口从这里读。
这和 `deps.取装载器` 那条「单例不是性能优化，是正确性」是同一个形状：
**这份状态必须活过单次请求。**

# ⚠️ 这一份是 `api/留痕` 的投影，不是第二个真源

2026-10-06（步骤 6）改的。改之前这里自己留一份 `_存档`／`_已发送`／`_报备单`，
判定同时写两边 —— 而两边一旦不同步，**没有任何东西会报错**：
判定写了这边、动作读的是那边，单子照样立得起来，只是七行里的数字是上一轮的。

现在判定只写留痕（`api/判定` 第 13 步 → `留痕.记`），这里全部现算：

    判定存档    ← `留痕.最近(sid)` 现场拼（顾客情况／本轮处置／触发 原样搬）
    已发送      ← `留痕.事件(sid)` 里 `动作=="发送"` 的那些，按轮次过滤
    报备单态    ← 同一份事件流水**折叠**出来

**公共名字和签名逐字保留**（`判定存档`、`取`、`已发送`、`发号`、`记报备`、
`推进报备单`、`清空`）—— `tests/test_动作.py` 那 17 条一个字都不用改。

# 但有两样**不**是留痕的投影，别顺手挪过去

`_单号` 和 `_计数` 是**动作接口自己的账**：`发号` 按「(会话, 诉求集合)」发号、
按日期全店排。它不来自任何一次判定 —— 同一个诉求报两次是同一个号，
而两次判定之间有几次判定跟它毫无关系。搬进留痕的话，重判一轮就会把号重发一遍。

# 进程内，没有落盘

演示是一个进程、一条时间线，所以就是一个模块级字典。**真要重启不丢，
那是另一件事**（要建持久化，`docs/开发步骤.md` 里没有这一步）。

`清空()` 是给测试的：不清的话上一条测试写的存档和发的号会落到下一条头上，
而那种红看起来像「单号生成坏了」。
"""

from __future__ import annotations

import threading
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date, datetime

from . import schemas, 留痕


@dataclass(frozen=True, slots=True)
class 判定存档:
    """一次 `POST /api/判定` 的产物。**只留动作接口用得上的那几样。**

    `顾客情况`／`本轮处置`／`触发` 是留痕里那三块的**同一批对象**
    （`组响应` 刚造出来的），不是重算的 —— 重算就是把判定跑两遍，
    而 `认口径` 是模型，两遍可以不一样。

    ⚠️ **`当前` 要留着。** 单号的日期取它，不取 `date.today()`：
    演示的「今天」是 2026-09-29，录制却在别的日子 —— 取真实时钟的话，
    屏幕上会出现「9/29 已逾期 2 天」和一张 `JJ20261003…` 的单子并排。
    （和 `剧本.ts` 的 `演示今天` 是同一条理由。）
    """

    会话ID: str
    轮次: int
    当前: datetime
    顾客情况: tuple[schemas.StateRow, ...]
    本轮处置: tuple[schemas.Disposition, ...]
    触发: tuple[schemas.触发条目, ...]


#: 一把锁。`sync def` 的路由跑在线程池里，两个请求真的会同时进来 ——
#: 拆开读写的后果是发号那一段竞态（两个请求拿到同一个序号，或者跳号）。
#:
#: ⚠️ **它只管 `发号` 那一张表。** 事件的追加和读取走 `留痕.锁` ——
#: 两把锁各锁各的真源，没有一处要同时拿两把（`发号` 不读留痕，
#: `已发送` 不碰号池）。
锁 = threading.Lock()

_单号: dict[tuple[str, tuple[str, ...]], str] = {}
_计数: dict[str, int] = {}

#: 事件流水的动作名。**和 `schemas.留痕动作` 的 `Literal` 同源**，
#: 改一个字就是「那一栏永远是空的」—— 而空数组看着像「客服什么都没点」。
_报备 = "报备"
_转交 = "转交"
_发送 = "发送"
_完成 = "完成"


def 取(会话ID: str) -> 判定存档 | None:
    """这个会话**最近判过的那一轮**。没有 = 还没判过（路由回 409）。

    ⚠️ **「最近判过」不是「轮次最大」。** 拖回去重判第 1 轮之后再点按钮，
    后端给的该是第 1 轮那一份（屏幕上就是它）—— 而 `留痕._轮` 是个字典，
    靠 `max(键)` 会给出第 2 轮。`留痕.最近` 记的是**最后写进去的**那一轮，
    这里逐字沿用那条契约（`test_动作.py` 有一条钉着「回拖到上一轮」）。
    """
    记录 = 留痕.最近(会话ID)
    if 记录 is None:
        return None
    return 判定存档(
        会话ID=记录.会话ID,
        轮次=记录.轮次,
        当前=记录.当前,
        顾客情况=记录.顾客情况,
        本轮处置=记录.本轮处置,
        触发=记录.触发,
    )


def 记发送(会话ID: str, 轮次: int, 采用的处置id: Sequence[str], 话术: str) -> None:
    """留痕：这句发出去的话兑现了哪几条主张。**追加，不覆盖** —— 一轮可以发好几条。

    兑现的**顺序照请求里给的顺序**（下面 `已发送` 按它展开），不乱排：
    右栏那一栏是按处置的先后排的，回出来换个序，留痕里「这条话术兑现哪几条」
    就对不上客服点的时候看到的样子。
    """
    留痕.追加动作(
        会话ID,
        留痕.动作事件(
            动作=_发送, 轮次=轮次, 话术=话术, 兑现=tuple(采用的处置id)
        ),
    )


def 已发送(会话ID: str, 轮次: int) -> list[tuple[str, str]]:
    """`(处置id, 话术)`，按发送顺序。给测试和排障看，接口不返回它。

    展开成「一条兑现一行」是照改之前那份 `_已发送` 的形状来的 ——
    那边是 `extend((编号, 话术) for 编号 in 采用的处置id)`，一次请求落一行。
    """
    return [
        (编号, e.话术)
        for e in 留痕.事件(会话ID)
        if e.动作 == _发送 and e.轮次 == 轮次
        for 编号 in e.兑现
    ]


def 发号(会话ID: str, 主张们: Sequence[str], 当天: date) -> str:
    """给这组诉求发一个工单号，**同一组诉求永远拿同一个号**（工单 §五）。

    - **按诉求去重**，不按会话：同一个诉求因轮次切分被处理多次也只生成一个号
      （v8 §七），但同一会话里的**另一件事**该拿新号 —— 拿会话当键的话，
      一个会话永远只有一张单子，第二件事会被并进第一张。
      键是 `(会话ID, 去重排序后的主张)`：主张换个顺序不该换个号。
    - **序号按日期全店排**，不按会话各数各的：演示里 A 拿 `…001`、B 拿 `…002`，
      这就是 31 §3.6 底部那两个号。
    - 前缀一律 `JJ`。报备和转交**同一种号**（2026-10-03 拍的）——
      31 §3.6 底部给的是两个 `JJ…`，而前端原来的 `BH` 是它自己拼的。
    """
    键 = (会话ID, tuple(sorted(set(主张们))))
    with 锁:
        if 已有 := _单号.get(键):
            return 已有
        天 = 当天.strftime("%Y%m%d")
        _计数[天] = _计数.get(天, 0) + 1
        号 = f"JJ{天}{_计数[天]:03d}"
        _单号[键] = 号
        return 号


def _立单轮次(流水: Sequence[留痕.动作事件]) -> int | None:
    """这条流水里**最后立的那张报备单**是第几轮的。没立过就是 `None`。

    ⚠️ **只看 `报备`，不看 `转交`。** 转交也走 `发号`、也有一张单子形状的东西，
    但它**没有「完成」这一步** —— `已转出` 是终点（`data/交接包.ts` 那段论证过）。
    把转交算进来的话，转交过的会话再发一条消息，`推进报备单` 会凭空追加一个
    「完成」，那张单子的状态从 `None` 变成 `已完成`，而屏幕上它压根不是报备单。

    # ⚠️ 这里是「最后追加的那个报备」，**不是 `max(轮次)`**

    改投影的时候我在这处踩过一次，记在这儿：旧实现是 `_报备单[会话ID]` **一个槽、
    后写的盖先写的**，`推进报备单` 对着那个槽比轮次 —— 所以「哪张单子说了算」
    跟的是**追加先后**。改成 `max(轮次)` 之后，顺着「先报备第 3 轮、再补报备
    第 2 轮」这条序（`判定请求.轮次` 支持回补历史轮次）两句话就**反了**：

        旧：推进(2) 回 `已完成`、推进(3) 回 `None`   ← 槽里是第 2 轮那张
        新：推进(2) 回 `None`、推进(3) 回 `已完成`   ← `max` 说是第 3 轮

    反的那句落在真实屏幕上：客服补判了第 2 轮、报了备、发了话，
    那张单子的徽标**停在「等待审批」**（`发送响应.报备单态` 回 `null`，
    前端不动它）。`test_另一轮报备是另一张单子` 只演 1→2 升序，
    **单调的时候两种取法一样**，所以它绿着盖住了这个洞 —— 补了一条倒序的
    （`test_报备倒着补一轮那张单子照样推得动`）。

    转交和报备混着来也不受影响：这里只挑 `报备`，别的动作跳过去。
    """
    return next((e.轮次 for e in reversed(流水) if e.动作 == _报备), None)


def _已走完(流水: Sequence[留痕.动作事件], 轮次: int) -> bool:
    """第 `轮次` 那张单子推到底了没有。"""
    return any(e.动作 == _完成 and e.轮次 == 轮次 for e in 流水)


def 记报备(会话ID: str, 轮次: int, *, 单号: str = "") -> schemas.交接包态:
    """`报备` 立单了 → 记一张等审批的单子。**回它现在的状态。**

    ⚠️ **回状态、不是回 `None`，这一格是有用的。** 报备接口拿它当响应的 `状态`
    —— 同一轮再点一次时，那张单子可能**已经走完了**（客服报完、话也发了，
    又手滑点了一下［一键报备］）。响应写死 `等待审批` 的话，右栏徽标会从
    「已完成」跳回去，而屏幕上那张单子从头到尾一个字节都没变。

    **转交不记** —— 见 `_立单轮次` 和 `推进报备单`。

    `单号` 只是给留痕留个痕（`动作[].单号`），状态不靠它算 —— 状态由
    「有没有一条同轮的 `完成`」决定。可选是因为 `记报备` 还有直接调用它的测试
    （`test_动作.test_另一轮报备是另一张单子`），那条路没有号可给。
    """
    流水 = 留痕.追加动作(
        会话ID, 留痕.动作事件(动作=_报备, 轮次=轮次, 单号=单号)
    )
    return "已完成" if _已走完(流水, 轮次) else "等待审批"


def 记转交(会话ID: str, 轮次: int, *, 单号: str = "") -> None:
    """`转交` 了 → **只留一条痕，不立单、不推进。**

    转交那张单子没有生命周期（`已转出` 是终点），所以它不是报备单，
    也不该让 `推进报备单` 有东西可推 —— 这一点由 `_立单轮次` 只看 `报备` 保证。
    """
    留痕.追加动作(
        会话ID, 留痕.动作事件(动作=_转交, 轮次=轮次, 单号=单号)
    )


def 推进报备单(会话ID: str, 轮次: int) -> schemas.交接包态 | None:
    """这句话发出去了 → 这张报备单走到头。回它现在的状态。

    **没有报备单、或者这张单子不是这一轮的 → `None`**，不凭空造一张：
    「这个会话有报备单」和「它答复出去了」是两件事，都得成立才推得动。
    调用点（`动作.发送`）拿到 `None` 就照着 `None` 回，前端那边也不会去动
    那张单子 —— 见 `schemas.发送响应.报备单态`。

    ⚠️ **转交过的会话在这儿回 `None`。** 见 `_立单轮次`。

    ⚠️ **推第二遍不追加第二条 `完成`。** 一轮可以发好几条消息
    （`test_动作.test_报备单发第二条话还是已完成`），第二条再追加一个事件的话，
    留痕的 `动作[]` 里会多出一条**客服没做过的事** —— 而状态那一格照样是
    `已完成`，所以光看状态查不出来。状态是幂等的，事件不是，所以幂等要显式写。

    ⚠️ **「检查 ＋ 追加」必须在同一把锁里做完**（`留痕.追加动作若`）。分开成
    「先读一眼、再决定加不加」的话，两个 `POST /发送` 同时进来会双双通过检查、
    各追加一条 —— 上面那段警告的事就发生了，而且**只在并发下发生**。
    旧实现是一把锁里读改写，改投影时不能把这个性质丢掉。
    """
    判: list[schemas.交接包态 | None] = []

    def _推(流水: tuple[留痕.动作事件, ...]) -> 留痕.动作事件 | None:
        if _立单轮次(流水) != 轮次:
            判.append(None)
            return None
        判.append("已完成")
        if _已走完(流水, 轮次):
            return None  # 已经推到底了，别记第二条「完成」
        return 留痕.动作事件(动作=_完成, 轮次=轮次)

    留痕.追加动作若(会话ID, _推)
    return 判[0]


def 清空() -> None:
    """测试用：号池 ＋ 留痕一起清。**别在应用代码里调它。**

    号池在这儿清、判定产物在 `留痕.清空()` 里清 —— 两处都要清，少一个的话
    上一条测试的号（或上一轮的判定）会落到下一条头上，而那种红看起来像
    「单号生成坏了」／「轮次算错了」，排查方向全错。
    """
    with 锁:
        _单号.clear()
        _计数.clear()
    留痕.清空()
