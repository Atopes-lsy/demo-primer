"""动作接口的台账 —— `判定` 写，`报备`／`转交`／`发送` 读。

# 为什么必须有这一份

三个动作接口的输入都**不足以自己算出结果**：

- `报备`／`转交` 要的七行里，「诉求」来自 `本轮处置`、「升级分类」来自
  `交接分类` 和 H1 的命中词 —— 这些都是**上一跳判出来的**，请求体里没有；
- `发送` 收的是 `采用的处置id[]`（`S_DEMO_A-1-1` 这种），**没有服务端那张
  id → 主张 的表，它就是一堆没人认得的字符串**。而 `Disposition.id` 这个字段
  存在的全部理由就是这一句话（`schemas.Disposition.id` 的文档串）。

所以 `POST /api/判定` 把自己的产物往这儿写一份，动作接口读它。这和
`deps.取装载器` 那条「单例不是性能优化，是正确性」是同一个形状：
**这份状态必须活过单次请求。**

# 进程内，没有落盘

演示是一个进程、一条时间线，所以就是一个模块级字典。**真要重启不丢，
那是另一件事**（要建持久化，`docs/开发步骤.md` 里没有这一步）。

`清空()` 是给测试的：不清的话上一条测试写的存档和发的号会落到下一条头上，
而那种红看起来像「单号生成坏了」。
"""

from __future__ import annotations

import threading
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date, datetime

from . import schemas


@dataclass(frozen=True, slots=True)
class 判定存档:
    """一次 `POST /api/判定` 的产物。**只留动作接口用得上的那几样。**

    `顾客情况`／`本轮处置`／`触发` 是响应里那三块的**同一批对象**
    （`组响应` 刚造出来的），不是重算的 —— 重算就是把判定跑两遍，
    而 `认口径` 是模型，两遍可以不一样。

    ⚠️ **`当前` 要留着。** 单号的日期取它，不取 `date.today()`：
    演示的「今天」是 2026-09-29，录制却在别的日子 —— 取真实时钟的话，
    屏幕上会出现「9/29 已逾期 2 天」和一张 `JJ20261003…` 的单子并排。
    （和 `剧本.ts` 的 `演示今天` 是同一条理由。）
    """

    会话ID: str
    轮次: int
    当前: datetime
    顾客情况: tuple[schemas.StateRow, ...]
    本轮处置: tuple[schemas.Disposition, ...]
    触发: tuple[schemas.触发条目, ...]


@dataclass(frozen=True, slots=True)
class 报备单:
    """客服点［一键报备］立起来的那张单。**一个会话同时只有一张。**

    # 为什么记轮次

    `判定存档` 一个会话只留**最近那一轮**，报备单跟着它走 —— 但「跟着走」不能
    只靠会话 ID：同一个会话**另一件事**报备时会拿到**新单号**（`发号` 的键是
    诉求），那是一张**新单子**，该重新等审批。只按会话记的话，新单子会继承
    上一张那个 `已完成`，而那张单子刚立起来、还没人批过。

    所以每次报备都拿这一轮的轮次比一比：**同一轮再点一次不动它**
    （客服手滑点两下［一键报备］，号都不变，状态也不该变），
    **另一轮就是另一张单子**，重新 `等待审批`。
    """

    轮次: int
    状态: schemas.交接包态


#: 一把锁。`sync def` 的路由跑在线程池里，两个请求真的会同时进来 ——
#: 拆开读写的后果是发号那一段竞态（两个请求拿到同一个序号，或者跳号）。
锁 = threading.Lock()

_存档: dict[str, 判定存档] = {}
_单号: dict[tuple[str, tuple[str, ...]], str] = {}
_计数: dict[str, int] = {}
_已发送: dict[tuple[str, int], list[tuple[str, str]]] = {}
_报备单: dict[str, 报备单] = {}


def 记(响应: schemas.判定响应, *, 当前: datetime) -> None:
    """把这一轮写进台账。**同一会话后写的盖掉先写的** —— 右栏一次只显示一轮。"""
    with 锁:
        _存档[响应.会话ID] = 判定存档(
            会话ID=响应.会话ID,
            轮次=响应.轮次,
            当前=当前,
            顾客情况=tuple(响应.顾客情况),
            本轮处置=tuple(响应.本轮处置),
            触发=tuple(响应.触发),
        )


def 取(会话ID: str) -> 判定存档 | None:
    """这个会话**最近判过的那一轮**。没有 = 还没判过（路由回 409）。"""
    with 锁:
        return _存档.get(会话ID)


def 记发送(会话ID: str, 轮次: int, 采用的处置id: Sequence[str], 话术: str) -> None:
    """留痕：这句发出去的话兑现了哪几条主张。**追加，不覆盖** —— 一轮可以发好几条。"""
    with 锁:
        _已发送.setdefault((会话ID, 轮次), []).extend((编号, 话术) for 编号 in 采用的处置id)


def 已发送(会话ID: str, 轮次: int) -> list[tuple[str, str]]:
    """`(处置id, 话术)`，按发送顺序。给测试和排障看，接口不返回它。"""
    with 锁:
        return list(_已发送.get((会话ID, 轮次), ()))


def 发号(会话ID: str, 主张们: Sequence[str], 当天: date) -> str:
    """给这组诉求发一个工单号，**同一组诉求永远拿同一个号**（工单 §五）。

    - **按诉求去重**，不按会话：同一个诉求因轮次切分被处理多次也只生成一个号
      （v8 §七），但同一会话里的**另一件事**该拿新号 —— 拿会话当键的话，
      一个会话永远只有一张单子，第二件事会被并进第一张。
      键是 `(会话ID, 去重排序后的主张)`：主张换个顺序不该换个号。
    - **序号按日期全店排**，不按会话各数各的：演示里 A 拿 `…001`、B 拿 `…002`，
      这就是 31 §3.6 底部那两个号。
    - 前缀一律 `JJ`。报备和转交**同一种号**（2026-10-03 拍的）——
      31 §3.6 底部给的是两个 `JJ…`，而前端原来的 `BH` 是它自己拼的。
    """
    键 = (会话ID, tuple(sorted(set(主张们))))
    with 锁:
        if 已有 := _单号.get(键):
            return 已有
        天 = 当天.strftime("%Y%m%d")
        _计数[天] = _计数.get(天, 0) + 1
        号 = f"JJ{天}{_计数[天]:03d}"
        _单号[键] = 号
        return 号


def 记报备(会话ID: str, 轮次: int) -> schemas.交接包态:
    """`报备` 立单了 → 记一张等审批的单子。**回它现在的状态。**

    ⚠️ **回状态、不是回 `None`，这一格是有用的。** 报备接口拿它当响应的 `状态`
    —— 同一轮再点一次时，那张单子可能**已经走完了**（客服报完、话也发了，
    又手滑点了一下［一键报备］）。响应写死 `等待审批` 的话，右栏徽标会从
    「已完成」跳回去，而屏幕上那张单子从头到尾一个字节都没变。

    **转交不记** —— 见 `推进报备单`。
    """
    with 锁:
        旧 = _报备单.get(会话ID)
        if 旧 is not None and 旧.轮次 == 轮次:
            return 旧.状态  # 同一轮再点一次：号都不换，状态也不该换（见 `报备单`）
        新 = 报备单(轮次=轮次, 状态="等待审批")
        _报备单[会话ID] = 新
        return 新.状态


def 推进报备单(会话ID: str, 轮次: int) -> schemas.交接包态 | None:
    """这句话发出去了 → 这张报备单走到头。回它现在的状态。

    **没有报备单、或者这张单子不是这一轮的 → `None`**，不凭空造一张：
    「这个会话有报备单」和「它答复出去了」是两件事，都得成立才推得动。
    调用点（`动作.发送`）拿到 `None` 就照着 `None` 回，前端那边也不会去动
    那张单子 —— 见 `schemas.发送响应.报备单态`。

    ⚠️ **转交过的会话在这儿回 `None`。** `已转出` 是终点，没有「完成」这一步
    （`frontend/src/data/交接包.ts` 那段文档论证过），所以 `转交` 压根不记报备单。
    """
    with 锁:
        单 = _报备单.get(会话ID)
        if 单 is None or 单.轮次 != 轮次:
            return None
        _报备单[会话ID] = 报备单(轮次=单.轮次, 状态="已完成")
        return "已完成"


def 清空() -> None:
    """测试用：把五张表都清掉。**别在应用代码里调它。**"""
    with 锁:
        _存档.clear()
        _单号.clear()
        _计数.clear()
        _已发送.clear()
        _报备单.clear()
