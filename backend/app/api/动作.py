"""四个按钮接后端（`docs/开发步骤.md` 步骤 4）。

    POST /api/会话/{sid}/报备    → 交接包（等待审批）
    POST /api/会话/{sid}/转交    → 交接包（已转出）
    POST /api/会话/{sid}/发送    → 记下这条话术兑现哪几条主张

⚠️ **路径参数只能叫 `sid`，不能叫 `{会话ID}`。** 而且这条错了**不会报错**：
Starlette 认参数的 `PARAM_REGEX` 是 `[a-zA-Z_][a-zA-Z0-9_]*`，`{会话ID}`
匹配不上，于是那一段被当成**字面量**编译进路由正则 —— 打过来的
`/api/会话/S_DEMO_A/报备` 匹配不上 `/api/会话/{会话ID}/报备` 这个字符串，
**整个路由 404**。报错信息是「Not Found」，看着像路径写错或路由没挂上，
而两条都不是。中文段（`/api/会话/`）没问题，只有**花括号里的名字**必须是 ASCII。

**第四个按钮（草稿检查）不在这儿，是有意的。** 2026-10-03 拍的口径是「本地两道」：
禁语要**每次编辑后**重查（前端自己的注释就这么写的），每按一次键一次往返不值当；
而 `api/schemas.py` 那条「后端刻意不声明 `草稿` 字段」的定调也是同一个方向。
契约文档那行跟着改了 —— 见 `docs/接口契约.md` §二。

# 三个路由都要先判定

`报备`／`转交` 的七行里有四行是**上一跳判出来的**（诉求、升级分类、承诺与逾期），
`发送` 收到的 `采用的处置id[]` 更是只有服务端那张表才认得。所以三者都读
`api/台账`，读不到就 **409**，不是空单子、也不是静默忽略。理由和 `/api/判定`
那条「会话不存在回 404 不回空判定」是同一个：**空结果和没结果是两件事，
在界面上长得一样，排查方向却相反。**

# 交接包的七行是这儿拼的

前端的 `建交接包()`（`frontend/src/data/交接包.ts`）本来干这件事。⚠️ **它没被删** ——
2026-10-03 拍的是**乙：留作兜底**（`PrimerPanel` 里 `接口交接包 ?? 建交接包(...)`），
后端一挂［一键报备］不至于让右栏**安静地少一块**。所以这一份和那一份要能一格一格对上
`docs/31_界面文字清单_给思语.md` §3.6 那两列 —— 那是演示当天右栏要出现的字面，
**两份实现谁供的都得是它**。`tests/test_动作.py` 逐字钉着它们。
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException

from ..data.装载器 import 装载器
from ..rules.pipeline import 输出类型
from ..rules.triggers import 触发编号
from . import deps, schemas, 台账

router = APIRouter()

业务数据 = Annotated[装载器, Depends(deps.取装载器)]
"""报备／转交要从会话上取两样东西：订单（行 2 商品）和工单（行 1 的单名）。

**判定产物不在这儿取** —— 那些在台账里。混着取的话，两个来源差一轮的时候
（判定判的是第 2 轮，而会话对象上是第 3 轮覆盖过的）屏幕上会出现一张
上一轮的旧单子，而它看着完全正常。
"""

#: 工单类别 → 交接单上那个单名。**只差一个字，但不能省。**
#:
#: 31 §3.6 行 1 要的是「**补发**工单（赠品漏发）」，而工单表里那一列写的是
#: 「补发换货」。没在表里的类别按 `{类别}工单` 拼（物流工单、不良反应工单）。
_单名: dict[str, str] = {"补发换货": "补发"}

#: 行 6 是一句**规矩**，不是这一单的数据。
#:
#: 补发单不重新采集收件信息，按原订单发。写死在这里是有意的 —— 真去拼一遍
#: 省市区只是把同一个常量换个地方写。（前端那份也是写死的，两边同源。）
收件信息 = "按原订单（不重新采集）"


@router.post("/api/会话/{sid}/报备", response_model=schemas.交接包, summary="一键报备")
def 报备(sid: str, 请求: schemas.动作请求, 装: 业务数据) -> schemas.交接包:
    """报备 ＋ 自动带全的交接包，状态 `等待审批`。

    ⚠️ **回的是七行 ＋ 单号，不是只回一个号。** 工单 §二 那张表把这一行写成
    「生成工单号」，可 31 §3.6 的**顾客 A 那一列就是报备那一列**（S10 演的是
    ［一键报备］，字幕写着「交接包自动带全」）。两边同形，前端那个
    `建交接包()` 才删得干净。

    立完单顺手记进台账（`台账.记报备`）—— 它和那张单子在同一个轮次上，
    `发送` 之后靠它把状态推到 `已完成`。记的动作在 `_交接` 里（状态的来源是那儿）。
    """
    return _交接(sid, 请求.轮次, 装, 转交=False)


@router.post("/api/会话/{sid}/转交", response_model=schemas.交接包, summary="立即转交")
def 转交(sid: str, 请求: schemas.动作请求, 装: 业务数据) -> schemas.交接包:
    """转交 ＋ 自动带全的交接包，状态 `已转出`。

    **不记报备单** —— `已转出` 是终点，没有「完成」这一步（见 `台账.推进报备单`）。
    """
    return _交接(sid, 请求.轮次, 装, 转交=True)


@router.post(
    "/api/会话/{sid}/发送", response_model=schemas.发送响应, summary="记下这条话术兑现哪几条主张"
)
def 发送(sid: str, 请求: schemas.发送请求) -> schemas.发送响应:
    """**不查禁语、不查事实。** 那两道在本地（见模块文档串），这里是留痕。

    一个认不出的处置 id ＝ **400，不静默丢掉**：丢掉的话这一句在留痕里变成
    「一条主张都没兑现」，而那和「客服确实什么都没兑现」长得一模一样。

    顺手把这张报备单推到 `已完成`（`台账.推进报备单`）—— 「答复完了」是报备单
    生命周期上前后端都知道的那一个事件。**没有报备单就是 `None`**，不是「没推进」：
    见 `schemas.发送响应.报备单态`。
    """
    存档 = _存档或409(sid, 请求.轮次)
    表 = {条.id: 条.主张 for 条 in 存档.本轮处置}
    找不到 = [编号 for 编号 in 请求.采用的处置id if 编号 not in 表]
    if 找不到:
        raise HTTPException(
            status_code=400,
            detail=f"这些处置 id 不在第 {存档.轮次} 轮：{'、'.join(找不到)}",
        )
    台账.记发送(sid, 存档.轮次, 请求.采用的处置id, 请求.话术)
    return schemas.发送响应(
        会话ID=sid,
        轮次=存档.轮次,
        话术=请求.话术,
        兑现主张=[表[编号] for 编号 in 请求.采用的处置id],
        # 走 `存档.轮次` 而不是 `请求.轮次`：上面刚校验过两个相等，取哪个都一样，
        # 但取 `存档` 那个和报备单记的轮次是同一个来源。
        报备单态=台账.推进报备单(sid, 存档.轮次),
    )


def _存档或409(会话ID: str, 轮次: int) -> 台账.判定存档:
    """台账里那一轮。**没有、或者不是你要的那一轮 → 409。**

    ⚠️ **第二个 409 防的和第一个不是一回事。**

    - 第一个（还没判定过）防的是「后端手上什么都没有」；
    - 第二个（轮次对不上）防的是「**有一张、但属于另一轮**」。

    后者才是安静的那种：拖回上一轮再点按钮，后端照样能照最后判的那一轮立一张
    单子，**而那张单子看着完全正常** —— 七行都有、单号也在，台上没人看得出来
    它说的不是屏幕上这一轮的事。两个 `detail` 也得说得出区别，否则排障时会
    把「这一轮没东西可报」和「你点的那一轮不是后端手上这一轮」当成同一件事。
    """
    存档 = 台账.取(会话ID)
    if 存档 is None:
        raise HTTPException(
            status_code=409,
            detail=f"{会话ID} 还没判定过 —— 先打 POST /api/判定，动作接口读的是它的产物",
        )
    if 存档.轮次 != 轮次:
        raise HTTPException(
            status_code=409,
            detail=(
                f"{会话ID} 你点的是第 {轮次} 轮，台账里是第 {存档.轮次} 轮"
                " —— 先把这一轮判一遍（POST /api/判定）再点"
            ),
        )
    return 存档


def _交接(会话ID: str, 轮次: int, 装: 装载器, *, 转交: bool) -> schemas.交接包:
    会话 = 装.找(会话ID)
    if 会话 is None:
        # 和 `/api/判定` 一样：**404 不是空单子**（工单 §四 第 1 步的同一理由）。
        raise HTTPException(status_code=404, detail=f"没有这个会话：{会话ID}")

    存档 = _存档或409(会话ID, 轮次)
    要的 = 输出类型.转交 if 转交 else 输出类型.报备
    立单 = [条 for 条 in 存档.本轮处置 if 条.输出 == 要的]
    if not 立单:
        # 这一轮判出来的东西里没有该走这条路的。**不拿别的去向顶替** ——
        # A 第 3 轮（道谢）点报备，出来的要是第 2 轮那张赠品单，屏幕上看着
        # 一切正常，而台下的问题「刚才那一轮到底报了没有」就没人答得上来了。
        动作 = "转交" if 转交 else "报备"
        raise HTTPException(
            status_code=409, detail=f"{会话ID} 第 {存档.轮次} 轮没有要{动作}的主张"
        )

    单号 = 台账.发号(会话ID, [条.主张 for 条 in 立单], 存档.当前.date())
    # 报备：立完单顺手记进台账，**状态从台账取回来**，不写死 `等待审批` ——
    # 同一轮再点一次时那张单子可能已经走完了（客服报完、话也发了，又手滑点了
    # 一下），退回 `等待审批` 的话右栏徽标会跳回去，而单子一个字节都没变。
    状态: schemas.交接包态 = "已转出" if 转交 else 台账.记报备(会话ID, 轮次)
    return schemas.交接包(
        状态=状态,
        行=_七行(存档, 会话, 立单, 转交=转交),
        单号=单号,
    )


def _七行(
    存档: 台账.判定存档, 会话: schemas.Session, 立单: list[schemas.Disposition], *, 转交: bool
) -> list[schemas.交接行]:
    """交接包的七行，顺序固定。

    顺序是 `31 §3.6` 那张表的行序，右栏照着渲染 —— **调顺序等于改界面**。

    四行取自这一份 `存档`（诉求、升级分类、答应过什么、办过什么），
    两行取自会话（商品、单名），一行是常量。**别把「取自会话」的那两行改成
    从存档取** —— 存档里没有订单和工单，那两样本来就在会话上。
    """
    主张们 = [条.主张 for 条 in 立单]
    答应 = next((行 for 行 in 存档.顾客情况 if 行.标签 == "答应过什么"), None)
    办过 = next((行 for 行 in 存档.顾客情况 if 行.标签 == "办过什么"), None)
    订单 = 会话.订单
    工单 = 会话.工单

    # 单名：「补发换货」→「补发」。工单没了就整格退成「工单」，不猜一个类别。
    类别 = 工单.kind if 工单 is not None else ""
    单名 = _单名.get(类别, 类别)
    事由 = _转交事由(存档)

    # 警示原样是「已逾期 2 天」，交接单上要的是「逾期 2 天」。
    # 这一个字是照着 31 §3.6 行 4 去的（它写的就是「· 逾期 2 天」）——
    # **别顺手把 `顾客情况` 里那份也改掉**：那边「已逾期」是给客服读的整句，
    # 两处各有各的读者。
    逾期 = (答应.警示 or "").removeprefix("已") if 答应 else ""

    return [
        schemas.交接行(
            标签="工单类型",
            值=_单名值(转交=转交, 单名=单名, 事由=事由, 主张们=主张们),
            来源="会话.工单.kind ＋ 本轮处置（转交取 H1 命中词，报备取主张）",
        ),
        schemas.交接行(
            标签="商品",
            值=f"{订单.商品货号} {订单.商品名称}" if 订单 is not None else "—",
            来源="会话.订单.商品货号 ／ 商品名称",
        ),
        schemas.交接行(
            标签="诉求",
            值=" · ".join(主张们) or "—",
            来源="本轮处置（输出为报备／转交那几条的主张）",
        ),
        schemas.交接行(
            标签="答应过什么",
            值=" · ".join(x for x in (答应.值 if 答应 else "", 逾期) if x) or "—",
            来源="顾客情况「答应过什么」的值与警示",
        ),
        schemas.交接行(
            标签="办过什么",
            值=(办过.值 if 办过 else "") or "—",
            来源="顾客情况「办过什么」的值",
        ),
        schemas.交接行(标签="收件信息", 值=收件信息, 来源="固定文案"),
        schemas.交接行(
            标签="升级分类",
            值=(
                " · ".join(x for x in (事由, *_队列(立单)) if x) or "—"
                if 转交
                else _报备分类(单名, 主张们, 逾期)
            ),
            来源=(
                "本轮处置的交接分类 ＋ H1 命中词"
                if 转交
                else "工单类别 ＋ 本轮处置的主张 ＋「答应过什么」的警示"
            ),
        ),
    ]


def _单名值(*, 转交: bool, 单名: str, 事由: str, 主张们: list[str]) -> str:
    """行 1 工单类型。两个分支的括号里**装的不是同一样东西**：

        转交  转交工单（投诉）        ← H1 命中的风险词
        报备  补发工单（赠品漏发）    ← 报备那条的主张

    看着对称，来源完全不同 —— B 那两条主张里**没有一条叫「投诉」**，
    照报备那样拿主张填，出来的是「转交工单（要求投诉）」，而 31 要的是
    「转交工单（投诉）」。

    两头都缺时退成光秃秃的类别名（「转交工单」／「补发工单」／「工单」），
    **不塞一个默认事由**。
    """
    if 转交:
        return f"转交工单（{事由}）" if 事由 else "转交工单"
    单 = f"{单名}工单" if 单名 else "工单"
    return f"{单}（{主张们[0]}）" if 主张们 else 单


def _转交事由(存档: 台账.判定存档) -> str:
    """H1 命中的那个风险词（「投诉」「曝光」…）。没命中 H1 就是空串。

    **只认 H1（风险），不认 H2（情绪／信任）。** B 那一轮三条硬触发都命中了，
    而 H2 的证据是「②维权威胁：投诉」这种带序号的整句 —— 拿它填进
    行 1 和行 7，出来的是「转交工单（②维权威胁：投诉）」。
    """
    命中 = next((条 for 条 in 存档.触发 if 条.编号 == 触发编号.H1), None)
    return (命中.证据[0] if 命中 is not None and 命中.证据 else "").strip()


def _队列(立单: list[schemas.Disposition]) -> list[str]:
    """转交该归哪个专家队列，如 `["物流类"]`。

    ⚠️ **公关不算。** 31 §3.6 要的是「投诉 · 物流类」，不是「投诉 · 公关类」——
    前半截「投诉」说的就是公关这件事，再来一个「公关类」是同一句话说两遍。
    所以这里取**非公关**的那些 `交接分类`（`H3交接分类` 判出来的，认不出是空串）。

    一条不剩（全认不出，或只有公关）时回空 —— 行 7 就只剩事由那半截。
    多个非公关分类全列出来，**不挑一个**：挑出来的那个一定是对的另一半，
    而漏掉的那一类没有专家认领。
    """
    队列 = [条.交接分类 for 条 in 立单 if 条.交接分类 and 条.交接分类 != "公关"]
    return [f"{类}类" for 类 in dict.fromkeys(队列)]


def _报备分类(单名: str, 主张们: list[str], 逾期: str) -> str:
    """报备那一版的升级分类，如 `补发-赠品漏发（逾期）`。

    三段各有各的用处，**都不是可选的**：单名说这是哪一类单子，主张说报的是
    什么事，括号里说急不急（组长扫一眼就知道该先看哪张）。

    认不出单名时不硬凑一个前缀（就剩「赠品漏发（逾期）」），逾期没有就不带括号。
    """
    主体 = "-".join(x for x in (单名, 主张们[0] if 主张们 else "") if x)
    return f"{主体}（逾期）" if 主体 and 逾期 else (主体 or "—")
