"""主卡文案表 —— 「形态 × 触发 → 文案」。

`接口契约.md` §七 第 1 条挂着的未定项：

> **主卡那四句文案后端没有真源。** `判断` / `标题` / `说明` / `风险标签`
> 现在由调用方填。要做一张「形态 × 触发 → 文案」的表，落在步骤 2。

这里就是那张表。

# 为什么是数据不是 `if`

演示当天想改一句标题，改这张表一行就行；写成 `if` 的话要改代码、跑测试、
再起服务 —— 而那时候没时间。这条要求是 `工单交接_给接口线.md` §六 明写的。

# 「有风险」的标题是拼出来的

另外两个形态的标题是**固定**的（「涉个体差异」「越过额度」），失败原因是
同一类。只有「有风险」的标题在回答「**为什么**有风险」，而每一轮的原因
都不一样 —— 所以它由命中触发的短语拼出来：

    H3 ＋ H1  →  ⚠ 承诺已逾期 · 顾客要求投诉
    H3 ＋ H1 ＋ H2  →  ⚠ 承诺已逾期 · 顾客要求投诉 · 情绪升级

顺序由 `触发短语` 这张表定，**不由 `硬触发` 的返回顺序定**：那边按严重度排，
同级的相对顺序依赖遍历顺序，拿它拼标题就不是可重放的了。
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Sequence

from ..rules.pipeline import 输出类型
from ..rules.triggers import 触发, 触发编号


@dataclass(frozen=True, slots=True)
class 文案:
    """一个形态的默认文案。`风险标签` / `话术建议` 只有「有风险」用得上。"""

    判断: str
    标题: str
    说明: tuple[str, ...] = ()
    风险标签: str | None = None
    话术建议: str | None = None


#: 三个形态各一句。`判断` 和 `标题` 逐字照 `工单交接_给接口线.md` §六。
主卡文案表: dict[str, 文案] = {
    "需要话术": 文案(
        判断="这次需要「话术」",
        标题="✍️ 这条得你来发 · 涉个体差异",
        说明=("这话涉个体差异，必须带回边界句；", "话术已备好，你确认后发送"),
    ),
    "需要授权": 文案(
        判断="这次需要「授权」",
        标题="🔒 这事该办，我帮你走授权",
        说明=("这事该办，但越过你的额度；", "走审批 —— 顾客无感，对话还在你手里"),
        # 报备和转交的区别就在这一句：「专家会回访」是转交的说法，
        # 报备不能说（`docs/31` §四 第 4 条记着这个坑）。
        话术建议="话术建议：先道歉，说明已走加急审批，发出后物流单号同步给您",
    ),
    "有风险": 文案(
        判断="这次需要「转交」",
        # 这个标题是**兜底**：正常情况下由触发拼（见 `取主卡文案`）。
        # 一个触发都没有却判成了转交是可能的 —— 权限矩阵直接判转交那一类
        # （投诉／要求主管走的就是这条），它不经过 H1–H4。
        标题="⚠ 涉风险，整通对话转出",
        说明=("涉风险档 —— 不许诺时限；", "同轮其余主张随对话一并转交"),
        风险标签="⚠ 涉风险场景",
        # 规格 §七 的转交话术表：投诉／承诺逾期涉风险**刻意不给时限**。
        # 说了时限而专员没做到，就是把投诉升级成二次投诉。
        话术建议="话术建议：先道歉，说明已升级给专员优先处理；**不给回访时限**",
    ),
}

#: 触发编号 → 标题里的短语。**顺序即显示顺序**：最要紧的排最前。
#:
#: 逾期排第一是因为它是**事实**（记录对得上），另外两个是**信号**
#: （一句话的措辞和语气）。标题先说事实。
触发短语: dict[触发编号, str] = {
    触发编号.H3: "承诺已逾期",
    触发编号.H1: "顾客要求投诉",
    触发编号.H2: "情绪升级",
    触发编号.H4: "疑似风控场景",
}

#: 输出类型 → 主卡形态。形状照 `schemas.Advice` 的文档串：
#:
#:     AI直发 → 不上主卡（只进 `已代发`）
#:     客服点发送 → 需要话术
#:     报备 → 需要授权
#:     转交 → 有风险
#:
#: `AI直发` 的值是 `None` —— 它不需要客服动手，那句话**已经发出去了**。
#: 给它编一个形态的话，主卡会跳出一张要客服点什么的卡片，而没有任何东西可点。
形态映射: dict[输出类型, str | None] = {
    输出类型.AI直发: None,
    输出类型.客服点发送: "需要话术",
    输出类型.报备: "需要授权",
    输出类型.转交: "有风险",
}


def 取形态(输出: 输出类型 | None) -> str | None:
    """`pipeline.主卡形态` 的结果 → 主卡形态名。

    `None` 进去 `None` 出来：那一轮没有主张，右栏只显示顾客情况。
    """
    return 形态映射.get(输出) if 输出 is not None else None


def 取主卡文案(形态: str, 触发列表: Sequence[触发] = ()) -> 文案:
    """按形态取文案。「有风险」的标题额外由命中的触发拼出来。

    形态不在表里就 `KeyError` —— 它是三选一的封闭集合，第四个值一定是
    调用方的 bug，静默给一句「需要话术」的话，错的那一轮看起来完全正常。
    """
    条 = 主卡文案表[形态]
    if 形态 != "有风险":
        return 条

    # 按 `触发短语` 的键序去取，不按 `触发列表` 的顺序 —— 可重放。
    短语 = [词 for 编号, 词 in 触发短语.items() if any(t.编号 is 编号 for t in 触发列表)]
    return replace(条, 标题="⚠ " + " · ".join(短语)) if 短语 else 条
