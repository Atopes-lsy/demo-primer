"""主卡文案表 —— 「形态 × 触发 → 文案」。

`接口契约.md` §七 第 1 条挂着的未定项：

> **主卡那四句文案后端没有真源。** `判断` / `标题` / `说明` / `风险标签`
> 现在由调用方填。要做一张「形态 × 触发 → 文案」的表，落在步骤 2。

这里就是那张表。

# 为什么是数据不是 `if`

演示当天想改一句标题，改这张表一行就行；写成 `if` 的话要改代码、跑测试、
再起服务 —— 而那时候没时间。这条要求是 `工单交接_给接口线.md` §六 明写的。

# 两张表：形态给「做什么」，缘由给「为什么」

`主卡文案表` 一个形态一句，回答的是**客服要做什么**（点发送／走审批／转出去），
这一句和原因无关。`缘由文案表` 回答的是**为什么会落到这一档** ——
清单 §3.4 的 S16 表里 ② 和 ③ 各有三条判据，正文就得跟着说对是哪一条。
查不到缘由时落回形态那一句（那是兜底，见 `主卡文案表` 的 ⚠️）。

# 「有风险」的标题是拼出来的

「需要话术」「需要授权」的缘由是**枚举得完的**（三条和三条，见 `缘由文案表`）。
只有「有风险」的原因在回答「**为什么**有风险」，而每一轮的组合都不一样 ——
所以它由命中触发的短语拼出来：

    H3 ＋ H1  →  ⚠ 承诺已逾期 · 顾客要求投诉
    H3 ＋ H1 ＋ H2  →  ⚠ 承诺已逾期 · 顾客要求投诉 · 情绪升级

顺序由 `触发短语` 这张表定，**不由 `硬触发` 的返回顺序定**：那边按严重度排，
同级的相对顺序依赖遍历顺序，拿它拼标题就不是可重放的了。

⚠️ **H1 那一格按证据词落在哪一族分句**（`H1短语表`）—— 上面两个例子都是
舆情那一族（`我要投诉`）。身体反应和监管责任各有各的说法，理由见那张表。
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Sequence

from ..rules.pipeline import 输出类型, 缘由
from ..rules.triggers import H1人身, H1监管, H1舆情, 触发, 触发编号


@dataclass(frozen=True, slots=True)
class 文案:
    """一个形态的默认文案。`风险标签` / `话术建议` 只有「有风险」用得上。"""

    判断: str
    标题: str
    说明: tuple[str, ...] = ()
    风险标签: str | None = None
    话术建议: str | None = None


#: 三个形态各一句。`判断` 和 `标题` 逐字照 `工单交接_给接口线.md` §六。
#:
#: ⚠️ **`AI直发` 不在这张表里**，因为它不做卡（见 `形态映射`）。
#: 2026-10-04 短暂有过一个 `AI 拟稿` 形态，当天撤掉。
#:
#: ⚠️ **这张表是「缘由不明」时的兜底**，真实那一路走 `缘由文案表`。
#: 缘由在 `pipeline.判成.缘由` 上，`组响应` 一路传下来 —— 查得到就用那一句，
#: 查不到才落回这里。所以别把这里的正文当成「屏幕上会显示的话」。
主卡文案表: dict[str, 文案] = {
    "需要话术": 文案(
        判断="这次需要「话术」",
        标题="✍️ 这条得你来发 · 涉个体差异",
        说明=("这话涉个体差异，必须带回边界句；", "话术已备好，你确认后发送"),
    ),
    "需要授权": 文案(
        判断="这次需要「授权」",
        标题="🔒 这事该办，我帮你走授权",
        说明=("这事该办，但越过你的额度；", "走审批 —— 顾客无感，对话还在你手里"),
        # 报备和转交的区别就在这一句：「专家会回访」是转交的说法，
        # 报备不能说（`docs/31` §四 第 4 条记着这个坑）。
        话术建议="话术建议：先道歉，说明已走加急审批，发出后物流单号同步给您",
    ),
    "有风险": 文案(
        判断="这次需要「转交」",
        # 这个标题是**兜底**：正常情况下由触发拼（见 `取主卡文案`）。
        # 一个触发都没有却判成了转交是可能的 —— 权限矩阵直接判转交那一类
        # （投诉／要求主管走的就是这条），它不经过 H1–H4。
        标题="⚠ 涉风险，整通对话转出",
        说明=("涉风险档 —— 不许诺时限；", "同轮其余主张随对话一并转交"),
        风险标签="⚠ 涉风险场景",
        # 规格 §七 的转交话术表：投诉／承诺逾期涉风险**刻意不给时限**。
        # 说了时限而专员没做到，就是把投诉升级成二次投诉。
        话术建议="话术建议：先道歉，说明已升级给专员优先处理；**不给回访时限**",
    ),
}

#: 手上**没有稿子**时，把「稿子已备好」那一行换成这一句（`取主卡文案` 的 `有稿`）。
#:
#: 只有「需要话术」那一档用得上：另外两档的正文里没有一句承诺稿子 ——
#: `报备` 的安抚话术是固定表里的、由客户端发（**它本来就没有稿子**，拿这句
#: 去换会把「走审批」那句对的话说成「AI 没写出稿」）。
没出稿句 = "AI 这次没写出稿 —— 这条得你从零来写"

#: 「形态 × 缘由」→ 卡面正文。**这张表才是屏幕上会显示的那些话。**
#:
#: # 为什么需要它（2026-10-05）
#:
#: 清单 §3.4 的 S16 表把 ② 的触发条件列成三条（有承诺 ／ 涉个体差异 ／
#: 系统查不到）、③ 也三条（超额度 ／ 判不了 ／ 承诺逾期）。原先只有上面那张
#: 形态表，一个形态一句话。**实测前十条真实会话**：四张蓝卡的
#: `涉及个体差异` 全是 `False`（理由是「有承诺」或「查不到」），
#: 两张黄卡的真实去向是 `判不了`（件数／金额未知）——
#: 卡上都写着另一种理由，而**卡面自己看不出来**。
#:
#: 客服是照这一行做事的：写「涉个体差异」他就去补边界句，写「越过额度」
#: 他就去走审批。说错理由不只是难听，是指错方向。
#:
#: 键是 `(形态, 缘由)`，值是**在形态默认那一条上改**（`replace`）——
#: `判断` 和 `话术建议` 跟着形态走，只有「为什么」那两句按缘由换。
缘由文案表: dict[tuple[str, str], 文案] = {
    # ── ② 客服点发送：三条判据各说各的 ──
    ("需要话术", 缘由.有承诺): replace(
        主卡文案表["需要话术"],
        标题="✍️ 这条得你来发 · 涉承诺",
        说明=(
            "这话要带时间／金额／数量，AI 不能自己发；",
            "话术已备好，你确认后发送",
        ),
    ),
    ("需要话术", 缘由.查不到): replace(
        主卡文案表["需要话术"],
        标题="✍️ 这条得你来发 · 系统查不到",
        说明=(
            "系统里没有这条的依据，别自己编事实；",
            "可以先用一句安全话术稳住顾客，话术已备好",
        ),
    ),
    # `("需要话术", 缘由.涉个体差异)` **特意不写**：上面那张形态表的默认
    # 那一句就是它（标题逐字照 `工单交接_给接口线.md` §六）。再抄一遍的话，
    # 演示当天改其中一处，另一处会静默留着旧话。
    ("需要话术", 缘由.闸门压低): replace(
        主卡文案表["需要话术"],
        标题="✍️ 这条得你来发 · 稿子没过检查",
        说明=(
            "AI 写的稿子被拦下了，发不出去；",
            "旁边列着命中原因，照着改一版再发",
        ),
    ),
    # 上面那格说的是**改**（稿子在，被拦了），这一格说的是**写**（压根没有）。
    # 两者在 `生成结果.去向` 上是同一个值 —— 降级地板抬的 —— 所以从前共用
    # 上面那格，卡面就指着「旁边列着命中原因」而旁边**一条都没有**。
    # 判别在 `api/判定._主卡缘由`，那里记着为什么不合并。
    #
    # 最后一行用 `没出稿句` 这个常量，和 `取主卡文案` 换上去的是**同一句** ——
    # 那一格讲的就是「没有稿子」，换一遍是空操作（见那个函数的 `有稿`）。
    ("需要话术", 缘由.没出稿): replace(
        主卡文案表["需要话术"],
        标题="✍️ 这条得你来发 · AI 没写出稿",
        说明=("模型这次够不着（或没答上来）；", 没出稿句),
    ),
    # ── ③ 报备：也是三条 ──
    # 「超额度」那一句就是形态默认，同上不抄第二遍。
    ("需要授权", 缘由.判不了): replace(
        主卡文案表["需要授权"],
        标题="🔒 这事该办，但定不了档",
        说明=(
            "定档要用的事实系统里没有（件数／金额／是不是质量问题）；",
            "走审批核实 —— 顾客无感，对话还在你手里",
        ),
    ),
    ("需要授权", 缘由.承诺逾期): replace(
        主卡文案表["需要授权"],
        标题="🔒 答应过的事没做到，走加急审批",
        说明=(
            "这事已经逾期了，我方还能补；",
            "先道歉，再走审批 —— 顾客无感，对话还在你手里",
        ),
    ),
}


#: 触发编号 → 标题里的短语。**顺序即显示顺序**：最要紧的排最前。
#:
#: 逾期排第一是因为它是**事实**（记录对得上），另外两个是**信号**
#: （一句话的措辞和语气）。标题先说事实。
#:
#: ⚠️ **H1 那一格只是兜底，正常走 `H1短语表`** —— 它是四族词共用一个出口，
#: 一句话盖不住。见那张表。
触发短语: dict[触发编号, str] = {
    触发编号.H3: "承诺已逾期",
    触发编号.H1: "顾客要求投诉",
    触发编号.H2: "情绪升级",
    触发编号.H4: "疑似风控场景",
}

#: H1 的证据词落在哪一族 → 标题里的短语。**顺序即显示顺序**，拼法和
#: `triggers.H1风险` 里 `证据 = 人身 + 监管 + 舆情` 同一个序。
#:
#: # 为什么 H1 要分族（2026-10-05 加）
#:
#: `H1` 是三族词共用一个出口：身体反应（`发红`／`疹子`／`刺痛`）、监管
#: （`12315`／`举报`／`药监`）、舆情（`投诉`／`曝光`）。而标题原先只有
#: 一句「顾客要求投诉」—— 那是**舆情**那一族的说法。
#:
#: 实测 140 条会话：H1 命中 18 条，**其中 14 条的证据里一个舆情词都没有**
#: （11 条是身体反应：`发红`／`疹子`／`爆痘`／`刺刺`；5 条是监管：`举报`／
#: `12315`，两条会话两族都占）。也就是说**绝大多数 H1 卡面上写着「顾客要求
#: 投诉」，而顾客根本没提过投诉**。客服照着那句话去准备应对投诉，该做的
#: 其实是先问身体 —— 和 `缘由文案表` 治的是同一种病（说错理由 ≠ 难听，
#: 是指错方向）。`触发.说明` 早就是按族说的（「命中人身反应相关风险词」），
#: 只有卡面这一句没跟上。
#:
#: ⚠️ **舆情那一句逐字没动**：演示线二（`我要投诉`）和 `工单 §六` 那两个
#: 例子都落在这一族上，改的是另外两族以前借用了它。
H1短语表: tuple[tuple[tuple[str, ...], str], ...] = (
    (H1人身, "顾客已报告不良反应"),
    (H1监管, "涉监管渠道"),
    (H1舆情, "顾客要求投诉"),
)

#: 输出类型 → 主卡形态。形状照 `schemas.Advice` 的文档串：
#:
#:     AI直发 → None（不做卡）
#:     客服点发送 → 需要话术
#:     报备 → 需要授权
#:     转交 → 有风险
#:
#: # `AI直发` 不给主卡 —— 2026-10-04 一天里改了两次，两次都对
#:
#: **上午加了一张 `AI 拟稿`。** 理由是实测出来的：真窗口上 AI 直发的那句话
#: **一个字都没发出去**。真窗口没有剧本，`App.handleSendPending` 对它们直接
#: 空手而回，聊天区一个字节都不会自己动 —— 实测同一批数据里 `已代发`
#: **一条都没有**（那要求本轮末尾有一条 `角色 == "AI"` 的消息，而真数据的角色
#: 只有 `买家`／`客服`）。于是屏幕上出现的是：`主卡` 是 `null` ⇒ 前端落进那支
#: 空态 ⇒ 右栏写「本轮无需客服动作 / **AI 已自行处理**或无事可做」。
#: 三处实测都是这一态：S00285（「申请退货」）、S00364（「会员积分如何兑换商品」）、
#: S00322（「积分商城入口在哪」）。**这三条谁都没发出去过。**
#:
#: **下午撤了。** 因为那张卡**违背了 `AI直发` 这一档的定义**：清单 §3.4 的
#: S16 表里，① 那一档客服「什么都不用做」。给它一张要点的卡，四档就变成
#: 「三张卡 ＋ 一个空档」，客服端看到的仍然是「每轮都有一张卡要点」。
#:
#: **撤掉之后「屏幕上写着假话」这件事并没有不解决** —— 换了个地方解决：
#: 空态文案从「AI 已自行处理」（说的是**已经**，而实际一个字没发）改成
#: 「AI 可自行答复」（说的是**能**）。话没发出去是事实，文案照实说就行，
#: 不该拿一张卡去遮。
#:
#: 所以旧注释里那句「成稿写完直接扔掉」**仍然成立**（`跑话术生成` 为 AI直发
#: 的主张写的稿子确实没有地方装）—— 那是另一个问题，**别拿加卡来解决它**。
形态映射: dict[输出类型, str | None] = {
    输出类型.AI直发: None,
    输出类型.客服点发送: "需要话术",
    输出类型.报备: "需要授权",
    输出类型.转交: "有风险",
}


def 取形态(输出: 输出类型 | None) -> str | None:
    """`pipeline.主卡形态` 的结果 → 主卡形态名。

    **两种 `None` 都落到「不做卡」，但说的不是一件事**，调用方要分清楚
    自己在处理哪一种（前端的空态文案靠 `已判定` 那一支区分，见
    `PrimerPanel.tsx`）：

    - 输入 `None`：**本轮一条主张都没有**，没什么可判的，右栏只显示顾客情况。
    - 输入 `AI直发`：**判过了，这一档本来就什么都不用做**（清单 §3.4：客服
      「什么都不用做」）。空态那句「AI 可自行答复」说的是这一种。
    """
    return 形态映射.get(输出) if 输出 is not None else None


def 取主卡文案(
    形态: str,
    触发列表: Sequence[触发] = (),
    缘由值: str = "",
    *,
    有稿: bool = True,
) -> 文案:
    """按**形态 × 缘由**取文案。「有风险」的标题额外由命中的触发拼出来。

    `缘由值` 是 `pipeline.判成.缘由` 的字符串值（`组响应` 从主卡那条主张上
    取）。**空串或表里没有这一格，就落回 `主卡文案表` 的形态默认那一句** ——
    那条是兜底，不是「屏幕上的话」，见 `主卡文案表` 的 ⚠️。

    「有风险」不看缘由：它的原因是**每一轮都不一样**的触发组合，
    由 `触发短语` 拼，缘由那七档里没有它对应的值。

    形态不在表里就 `KeyError` —— 它是三选一的封闭集合（`AI直发` 那档不做卡，
    走的是 `取形态` 返回 `None`，压根到不了这里），给一个别的值一定是调用方
    的 bug，静默给一句「需要话术」的话，错的那一轮看起来完全正常。

    # `有稿`：卡面**承诺了稿子**，手上却是空的

    三档正文里承诺过稿子的只有「需要话术」那几格（「话术已备好」「照着改一版
    再发」）—— `有稿=False` 时把它们的**最后一行**换成 `没出稿句`。标题和第一行
    一个字不动：那一句说的是**为什么落到这一档**，而它多半还是对的
    （「涉个体差异」就是涉个体差异），错的只是那句动作语。

    ⚠️ **只有「需要话术」换。** `报备` 的安抚话术是固定表里的、由客户端发，
    它**本来就没有稿子**、正文里也一个字没承诺过 —— 一视同仁地换，第 2 轮那张
    黄卡会从「先道歉，再走审批」变成「AI 没写出稿」。`转交` 同理，
    它的话术从 `handover` 的固定表来，不走模型。

    ⚠️ 和 `缘由.没出稿` 那一格**不冲突**：那一格的最后一行就是 `没出稿句`，
    换上去是空操作（这一条是常量而不是两处抄一遍的理由）。
    """
    条 = 缘由文案表.get((形态, 缘由值)) or 主卡文案表[形态]
    if not 有稿 and 形态 == "需要话术" and 条.说明:
        条 = replace(条, 说明=(*条.说明[:-1], 没出稿句))
    if 形态 != "有风险":
        return 条

    # 按 `触发短语` 的键序去取，不按 `触发列表` 的顺序 —— 可重放。
    # 一条触发可能占**不止一格**（H1 按命中的族来，见 `H1短语表`），所以是
    # `extend` 加一层 `_触发词`，不是一个编号换一个词。
    短语: list[str] = []
    for 编号 in 触发短语:
        for t in 触发列表:
            if t.编号 is 编号:
                短语.extend(_触发词(t))
    return replace(条, 标题="⚠ " + " · ".join(短语)) if 短语 else 条


def _触发词(t: 触发) -> list[str]:
    """一条触发在标题里占的那几个词。

    H1 看**证据落在哪一族**（它三族共用一个编号）；其余三个编号一句话。
    空证据（只在测试里造得出来 —— `H1风险` 是扫到词才返回 `触发` 的）退回
    `触发短语` 那一格，也就是老的「顾客要求投诉」。
    """
    if t.编号 is not 触发编号.H1:
        return [触发短语[t.编号]]
    return [词 for 表, 词 in H1短语表 if any(w in 表 for w in t.证据)] or [
        触发短语[触发编号.H1]
    ]
