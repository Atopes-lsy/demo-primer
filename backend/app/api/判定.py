# H2 ⑥：重复要求
# ══════════════════════════════════════════════════════════


def 判重复要求(
    会话: schemas.Session,
    本轮买家消息: tuple[str, ...],
    历史消息: list[schemas.ChatMessage],
) -> bool:
    """H2 判据 ⑥：同一诉求在本会话内第 2 次提出，且仍未解决。

    # 为什么在接口层

    `triggers.硬触发` 的 `重复要求` 参数是**上层算好传下来的**（那个函数的
    文档串专门写了这条）—— 因为要数的是整个会话的历史，而规则层手里只有
    本轮。会话说到底只有路由这里拿得到。

    # 「同一诉求」怎么算

    用**权限矩阵的关键词**，不另起一张词表。矩阵那 22 行是照着「顾客要办什么事」
    写的（`L01` 的 `漏发赠品／漏发／少发／没收到`），**那正是「诉求」的定义**，
    再抄一份只会两边漂移。

    历史里**买家和客服的话都算**：顾客提过的诉求，客服的那句「您反馈的赠品
    漏发我们已经登记补发了」是同样硬的证据 —— 而且当天顾客往往只在开头提过一次，
    之后全是客服在复述。

    # 「仍未解决」

    工单没办结。没有工单的会话（纯咨询）没有「已解决」可言，按未解决处理 ——
    误报的后果只是多进一条证据、抬一档严重度；漏报的后果是「同一件事问了两遍
    还没人管」被静默吞掉，那才是这个产品要解决的问题。

    ⚠️ **⑥ 单独命中不触发 H2**（顾客礼貌地问第二次进度不该被踢给专家）。
    所以这里报 `True` 不会自己造成转交，它只在 ①–⑤ 也命中时进证据、抬严重度。
    """

    def 诉求们(文本们: list[str]) -> set[str]:
        合并 = "\n".join(文本们)
        return {
            k.编号
            for k in permissions.权限条目表
            # 不可认的行（E01–E04、X01）关键词是空的，这里跟着忽略 ——
            # 和 `permissions.认权限` 同一个口径。
            if k.可认 and any(词 in 合并 for 词 in k.关键词)
        }

    现在 = 诉求们(list(本轮买家消息))
    if not 现在:
        return False
    之前 = 诉求们([m.message_text for m in 历史消息])
    # 各自都是一整轮的全部发言，所以「同一个诉求词在两边都出现过」就是
    # 「提了两次」。按编号取交集，不按词 —— 顾客第一次说「漏发」、
    # 第二次说「没收到」，是同一件事。
    if not (现在 & 之前):
        return False

    工单 = 会话.工单
    if 工单 is None:
        return True
    票 = 工单.ticket
    状态 = getattr(票, "工单状态", "") or getattr(票, "任务状态", "")
    return 状态 != 已办结


