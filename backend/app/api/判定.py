@dataclass(frozen=True, slots=True)
class 判定会话:
    """`POST /api/判定` 真正要看的会话。

    左栏现在展示的是按顾客合并后的「窗口」，前端的轮次也是按这个窗口数出来的。
    但装载器里的索引仍然是原始会话：窗口 ID 取末段 ID，`装.找("SB")` 只能取到
    末段那一小截。两边一旦各看各的，轮次号会静默错位，前端第 2 轮发来，后端却
    夹到末段第 1 轮去判。

    所以判定入口先按 `/api/会话列表` 的同一条规则合出窗口；找得到窗口就判窗口，
    找不到再退回原始会话（保留直接按原始会话 ID 调试的能力）。
    """

    会话: schemas.Session
    票表: 票表类型 | None = None


def 找判定会话(装: 装载器, 会话ID: str) -> 判定会话 | None:
    """按前端左栏同源的窗口取会话，取不到再退回原始会话。"""
    窗口们, 票表 = 合并窗口(装.会话列表)
    for 窗口 in 窗口们:
        if 窗口.会话ID == 会话ID:
            return 判定会话(窗口, 票表.get(会话ID))

    原始 = 装.找(会话ID)
    return 判定会话(原始) if 原始 is not None else None


