def _处置(
    判成们: list[pipeline.判成],
    会话ID: str,
    轮次号: int,
    去向们: dict[int, pipeline.输出类型],
    话术们: dict[int, str] | None = None,
) -> list[schemas.Disposition]:
    """`判成` → `Disposition`。序号从 1，和 `轮次` 一起拼成 `id`。

    ⚠️ `id` 是收敛的锚：同一会话里「赠品漏发」会在第 2 轮和第 5 轮各出现一次，
    没有 `id` 就指认不出改的是哪一条（`schemas.Disposition.id` 的文档串）。

    ⚠️ **`输出` 填的是最终去向，不是 `判成.输出`。** 两者会不一样：
    闸门压低（spec §4.3）把 `AI直发` 变成 `客服点发送` —— 也就是
    「这条本来能自动发，但有句话业务方没核对过，得你点一下」。
    填 `判成.输出` 的话右栏会显示 `AI直发` 而实际上没有自动发出去，
    客服等一个不会发生的动作。`话术生成.可直发` 的文档串把这件事
    交给调用方：「接口线分派去向都由它说话」。
    """
    return [
        schemas.Disposition(
            id=f"{会话ID}-{轮次号}-{序号}",
            轮次=轮次号,
            主张=条.主张,
            输出=去向们.get(序号 - 1, 条.输出),
            说明=条.说明 or None,
            涉及个体差异=条.涉及个体差异,
            需边界句=条.需边界句,
            层=条.层,
            权限去向=条.权限去向,
            交接分类=条.交接分类,
            话术=(话术们 or {}).get(序号 - 1) or None,
        )
        for 序号, 条 in enumerate(判成们, start=1)
    ]


def _话术们(
    判成们: list[pipeline.判成], 生成结果们: dict[int, Any]
) -> dict[int, str]:
    """每条主张这一轮要说出去的那句话，按判成下标存。`_处置` 拿它填 `Disposition.话术`。

    按**最终去向**（`_最终去向`）分两个来源：

    - 走模型的那两种（`AI直发`／`客服点发送`）→ `生成结果.话术`；
    - `报备` → `安抚话术.查安抚话术` 的固定表。**它不进 `生成结果`**
      （`跑话术生成` 只喂 `_走模型的去向`），所以这一条不补的话，
      报备那几轮的 `话术` 恒为 `None`。

    `转交` 不在这儿：它的话归 `主卡.话术`（`组响应` 从 `判成.转交话术` 取），
    而且转交话术一律走客服点发送，不按主张发。

    # 为什么补这一条（2026-10-05）

    `安抚话术.py` 那张表**写完之后生产路径上一次都没调用过** —— 只有测试在问它
    （`grep 查安抚话术` 只有 `tests/` 命中）。真窗口上这表现为「报备那一轮右栏
    一个字都没有」（S00002 第 3 轮、S00006 第 2 轮实测都是空）：客服不知道该对
    顾客说什么，而报备的语义是「**对话还在你手里**」—— 一句话不说就是把顾客
    晾在那儿，正好是这句话要防的那件事。

    客户端 2026-10-05 起拿它当 AI 气泡自动发出去（它自己不会走客服的手，
    `文案.py` 的 `有稿` 那段也写着「由客户端发」），所以这一格必须有值。
    """
    话术们: dict[int, str] = {i: r.话术 for i, r in 生成结果们.items()}
    for 下标, 判 in enumerate(判成们):
        if 下标 in 话术们:
            continue
        if _最终去向(下标, 判, 生成结果们) is pipeline.输出类型.报备:
            话术们[下标] = 安抚话术.查安抚话术(判.主张)
    return 话术们


def _出处键(出处: str) -> str:
    """比出处用的归一化键。**只用来比对，不改线上输出。**

    `出处` 在链路里有**两种拼法**，指的是同一件事：

        `pipeline` 造 `依据条目`：`f"{table} · {row_id}"`   「口径表 · K10」
        `证据._出处` 造 `Evidence`：`f"{table} {row_id}"`    「口径表 K10」

    模型自报的出处抄的是 prompt（prompt 渲染的是 `依据条目` 那一种），
    拿它去比 `Evidence` 的出处，整串相等**一条都命不中** —— 而后果不是报错：
    右栏每一条都变成「没用上」，`N/6` 恒为 `0/6`，没有任何东西会响。

    空格的差别就是全部差别（`·` 两侧各一个空格），所以键＝去掉空格和 `·`。
    **别去动两边的拼法**把这件事「修掉」：`_出处` 的文档串专门写了它只拼接
    不美化（G3 要拿它回查 `table` / `row_id`），而 `依据条目` 的出处是给人
    读的整句（`口径表 K05「赠品补发承诺」`），两边各有各的用途。
    """
    return 出处.replace(" ", "").replace("·", "")


def _自报映射(
    判成们: list[pipeline.判成], 生成结果们: dict[int, Any]
) -> dict[str, frozenset[str]]:
    """主张 → 模型自报的出处（`_出处键` 归一化后的键）。

    **不在表里 = 这条主张没走 3c**（`报备`／`转交` 的话术来自固定表），
    和「走了 3c 但一条都没自报」（空集）是**两件事** —— 所以调用方拿 `None`
    和空集要分开处理，见 `_用上按自报`。

    两个消费者各有各的入口（`_依据` 收 `六源结果`、`_已代发` 收 `依据条目`），
    但**问的是同一个问题**「这句话引了哪几条」。各算一份的话，
    同一个 K10 会在同一屏的两块里一个 `true` 一个 `false`，而两处都看着对。
    """
    return {
        判成们[下标].主张: frozenset(_出处键(出) for 出 in 结果.用到的依据)
        for 下标, 结果 in 生成结果们.items()
        if 下标 < len(判成们)
    }


def _用上按自报(
    条: schemas.Evidence, 自报过: frozenset[str] | None
) -> schemas.Evidence:
    """把一条 `Evidence` 的 `用上` 换成模型自报的结果。

    `自报过 is None`（这条主张没走 3c）时**原样返回**：模型没跑，没有自报
    可依，而那时 `源记录.用上` 的 `True` 是**诚实的** —— 报备那三条硬边界
    是照 ⑥ 工单写的，依据确实用上了，只是用的人不是模型。
    """
    if 自报过 is None:
        return 条
    return 条.model_copy(update={"用上": _出处键(条.出处) in 自报过})


def _依据(
    结果们: list[sources.六源结果],
    判成们: list[pipeline.判成],
    生成结果们: dict[int, Any],
) -> list[schemas.Evidence]:
    """本轮所有主张的六源记录，去重后按 `六源顺序` 排。

    **只放查到的**（`从六源` 里那个 `exists` 过滤），没查到的来源由**前端**
    按六源补空位 —— 工单 §四 专门为这件事写了警告：两边都补的话数量对不上，
    右栏那个 `N/6 源命中` 会变成漏列。

    `用上=False` 的**留在里面**：它就是右栏展开后那段「未命中的六源清单」。
    同一条记录被两条主张都查到、其中一条没用上时取「用上」——
    「本轮用上了没有」是**轮**的粒度，一条用上就算用上。

    # `用上` 取哪一边：两套取值，按主张分（spec §6.4）

    - **走过 3c 的主张**（`生成结果们` 里有下标）→ 取**模型自报**
      （`生成结果.用到的依据`）：右栏问的是「这句话引了哪几条」。
    - **没走 3c 的主张**（`报备` 的话术来自固定表，`转交` 的走客服点发送）
      → 保持检索层原值（`源记录.用上`，恒 `True`）。那个 `True` 在这里是
      **诚实的**：报备那三条硬边界是照 ⑥ 工单写的，依据确实被用上了，
      只是用的人不是模型 —— 而模型没自报不代表没用上，只是因为**它压根没跑**。

    ⚠️ **别写成「一刀切取模型自报」**：`报备` 那条没有自报可取，一刀切会把
    整轮依据全压成 `False`，右栏 `N/6` 变 `0/6` 并宣称「另 6 源无记录」——
    而 ⑥ 工单是查到了的，那句安抚话术正是照它写的。
    不接自报又是另一个极端：`源记录.用上` 恒 `True`，`用上` 就成了常量，
    「查到」和「引用」被悄悄合并成一个词（`六源.py` 的文件头）。
    """
    自报 = _自报映射(判成们, 生成结果们)

    见: dict[tuple[str, str], schemas.Evidence] = {}
    for 结果 in 结果们:
        自报过 = 自报.get(结果.主张)
        for 条 in 证据.从六源(结果):
            条 = _用上按自报(条, 自报过)
            键 = (str(条.序号), 条.出处)
            if 键 not in 见 or (条.用上 and not 见[键].用上):
                见[键] = 条

    排名 = {源: i for i, 源 in enumerate(sources.六源顺序)}
    return sorted(见.values(), key=lambda e: (排名[e.序号], e.出处, e.摘要))


#: 本轮以 **AI 的名义**发出去的那两种去向。
#:
#: `客服点发送` 不在里面 —— 那句要过客服的手，发出去是**客服**发的。
#: `转交` 也不在：`handover.py` 第 3 条硬边界是「转交话术一律走客服点发送」，
#: 它压根不产出 AI 消息。
_AI的名义 = frozenset({pipeline.输出类型.AI直发, pipeline.输出类型.报备})


def _最终去向(
    下标: int, 判: pipeline.判成, 生成结果们: dict[int, Any]
) -> pipeline.输出类型:
    """这条主张**最终**去哪 —— 闸门压低（spec §4.3）之后的那个值。

    `生成结果.去向` 才是最终去向（`话术生成.可直发` 的文档串把这件事交给
    调用方：「接口线分派去向都由它说话」）。`判成.输出` 是**压低之前**的。

    ⚠️ **一处取错，整屏看着都正常。** 这条原来只长在 `_代发的判成们` 里，
    另外三处（`_处置` 早就在用 `生成结果.去向`，`_主卡条` 和 `组响应` 却
    还在读 `判成.输出`）各写各的 —— 2026-10-05 实测 S00007 就劈在上面：
    处置写着 `客服点发送`（压低抬上去的），主卡却是 `None`，右栏显示
    「AI 可自行答复」而那句话**已经被拦下、没人发**。所以只留这一个出口。
    """
    出稿 = 生成结果们.get(下标)
    return 出稿.去向 if 出稿 is not None else 判.输出


def _代发的判成们(
    判成们: list[pipeline.判成], 生成结果们: dict[int, Any]
) -> list[pipeline.判成]:
    """本轮以 AI 名义发出去的那几条判成，**按主张顺序**。

    用的是**最终去向**（`_最终去向`）不是 `判成.输出`：4.3 压低会把一条
    判成 `AI直发` 的主张变成 `客服点发送`，而那条**不会有** AI 消息。照
    `判成.输出` 数的话它白占一个位子，后面每一条 AI 消息都配到**前一条**
    主张的依据上 —— 配错不报错，右栏只是挂着一份看着合理的错依据。
    """
    return [
        判 for i, 判 in enumerate(判成们) if _最终去向(i, 判, 生成结果们) in _AI的名义
    ]


def _已代发(
    截断结果: 截断,
    判成们: list[pipeline.判成],
    生成结果们: dict[int, Any],
) -> list[schemas.已代发条目]:
    """本轮 AI 代发出去的话，连同**它是哪条主张的**。

    不是现编的：那几条消息**本来就在对话里**（`角色 == "AI"`），这里只是把它们
    挑出来。为什么非挑不可 —— 顾客那边看到客服说了话，客服这边右栏一片安静，
    等顾客回一句「你刚才不是说可以退吗」就彻底对不上了
    （`schemas.已代发条目` 的文档串）。

    ⚠️ **只数本轮末尾那段，不数整段历史。** 「已代发」回答的是「刚才有没有
    以你的名义发过话」；把上一轮的也列出来的话，客服会以为那是新发的。

    # 依据是**配**出来的，不是从话里反解出来的

    一开始这里留空，理由是「从一句话反解出完整 `Evidence` 是猜」—— 那个理由
    对反解成立，但**这里不需要反解**：本轮以 AI 名义发出去的话，就是本轮那几条
    `AI直发`／`报备` 的主张的成稿（前者走 3c、后者走 `安抚话术` 的固定表，
    两张都**不经过客服的手**）。两张都在 `判成们` 里躺着，按**主张顺序配消息
    顺序**就是 1:1，没有猜的成分。

    配上之后依据取那条主张自己的 `判成.依据`，正是
    `证据.从依据条目` 一直在等的那条生产调用方。

    # `用上` 和 `主卡.依据` 是同一把尺子（`_自报映射`）

    不是照搬 `依据条目.用上` —— 那是 `源记录.用上`，检索层**恒 `True`**。
    照搬的话同一个 K10 会在**同一屏的两块**里一个 `true` 一个 `false`：
    主卡里它「本轮没引用」（按模型自报压过），这里它「用上了」。两处都看着对。

    这块尤其要紧：前端读 `用上` 只有一处（`AdviceCard` 的 `EvidenceList`，
    它 `.filter(e => e.用上)` 拿命中的、剩下的算「另 N 源无记录」）。
    恒真的话那块要么复用它、把没引的也算成引了，要么自己另写一套过滤。

    ⚠️ **消息比主张多的时候留空，不猜。** 多出来的那句可能是人工客服冒充 AI
    发的，也可能是上一轮漏截的 —— 两种都不该挂上一条编的依据，而右栏那边
    「有依据」和「没依据」看起来一样可信。
    """
    if 截断结果.末条买家 < 0:
        return []
    消息们 = [
        条
        for 条 in 截断结果.消息[截断结果.末条买家 + 1 :]
        if 条.角色 == "AI" and 条.message_text
    ]
    主张们 = _代发的判成们(判成们, 生成结果们)
    自报 = _自报映射(判成们, 生成结果们)

    出: list[schemas.已代发条目] = []
    for i, m in enumerate(消息们):
        依据: list[schemas.Evidence] = []
        if i < len(主张们):
            自报过 = 自报.get(主张们[i].主张)
            依据 = [
                _用上按自报(条, 自报过)
                for 条 in 证据.从依据条目(主张们[i].依据)
            ]
        出.append(
            schemas.已代发条目(内容=m.message_text, 署名=m.署名 or "", 依据=依据)
        )
    return 出


#: 话术要走模型的那两种去向。另外两种有固定表（spec §6.5）——
#: `转交` 走 `handover.转交话术表`（三条硬边界在导入自检里），
#: `报备` 走 `安抚话术.查安抚话术`。那两句都是**先于客服点发送发出去的**，
#: 让模型重写一遍等于把那些边界再赌一次。
_走模型的去向 = frozenset({pipeline.输出类型.AI直发, pipeline.输出类型.客服点发送})


def 该回写条(响应: schemas.判定响应) -> str | None:
    """这一轮有没有资格进先例库，有的话**要写的那句 `话术`**。

    **四条条件全中才算「正常收尾且未越界」**（spec §六）：闸门为空、本轮没有
    `转交`、没有 `报备`、话术不是「有风险」那一档。后三条合成一条就够 ——
    走向量的两种去向是 `_走模型的去向`，另外两种（转交／报备）一旦出现，
    这一轮就不是客服正常答完的。

    **只回话术，不回情境。** 情境是**本轮买家原话**（`判定` 调用点的 `本轮.全文`），
    和取材那边同构（spec §三：索引文本一律是「那一轮买家说了什么」）——
    而 `主张` 是模型拆出来的半句话，拿它当索引文本等于把库和取材分成两套口径。

    取**话术最长**的那个处置：一轮里可能好几条处置，全写进去会得到几条情境
    一模一样的先例（去冗那一关本来也会挡，与其靠那一道不如明写）。
    **并列时取靠前的那条**（plain `max`，先遇到的先赢）—— 和取材 `_成条` 的
    `max(reversed(...))`（并列取靠后的）不是同一把尺子，别照着那边改这边。
    """
    if 响应.闸门:
        return None
    if 响应.主卡 is not None and 响应.主卡.形态 == "有风险":
        return None
    if any(条.输出 not in _走模型的去向 for 条 in 响应.本轮处置):
        return None
    候选 = max(
        (条.话术 for 条 in 响应.本轮处置 if 条.话术),
        key=len,
        default=None,
    )
    return 候选


def 跑话术生成(
    判成们: list[pipeline.判成],
    模型: Any,
    *,
    顾客情况: list[tuple[str, str]],
    触发列表: list[triggers.触发],
    口径表: Any,
    已发出: list[str],
) -> dict[int, Any]:
    """给每条该走模型的判成写一句话。返回 `{判成下标: 生成结果}`。

    **一条主张一次**（spec §三）—— 不是一轮一次。同一轮里「含乙醇」和
    「孕妇能否用」各写各的：合起来写一句的话，那句会同时回答两个问题，
    而其中一个涉个体差异，整句就得带边界句。

    ⚠️ **只喂 `_走模型的去向`。** 另外两种去向真实现会抛 `不支持的去向`
    （`话术生成.py` 顶上就抛，**一次网络调用都不发**）—— 那是「调用方分派错了」
    的信号。在这里先滤掉，比让它抛出来好：抛的话整个 `POST /api/判定` 500，
    而本轮其实有一条完全正常的 AI直发 主张被连累得也没出稿。
    """
    出: dict[int, Any] = {}
    for 下标, 判 in enumerate(判成们):
        if 判.输出 not in _走模型的去向:
            continue
        出[下标] = 模型.生成话术(
            判,
            顾客情况=顾客情况,
            触发列表=触发列表,
            口径表=口径表,
            已发出=已发出,
        )
    return 出


def _主卡条(判成们: list[pipeline.判成], 生成结果们: dict[int, Any]) -> int | None:
    """主卡那句话是哪条主张的（`判成们` 的下标）。空轮返回 `None`。

    按 `优先级` 取最高。**取的是最终去向**（`_最终去向`）——
    `组响应` 拿这个下标去取形态、话术、闸门、缘由四样，用 `判成.输出` 挑的话，
    被闸门抬上去的那条挑不中，四样一起配到另一条主张上（S00007 实测）。
    和 `pipeline.主卡形态` 是同一把尺子，只是量的是压低**之后**的高度。

    ⚠️ 取的是**最高态**不是「第一条」：线一第 1 轮第一条是 `含乙醇`（AI直发），
    按第一条取会拿到那句讲成分的。
    """
    if not 判成们:
        return None
    return max(
        range(len(判成们)),
        key=lambda i: pipeline.优先级[_最终去向(i, 判成们[i], 生成结果们)],
    )


def _轮去向(
    判成们: list[pipeline.判成], 生成结果们: dict[int, Any]
) -> pipeline.输出类型 | None:
    """这一轮主卡该显示哪种输出 —— 空轮返回 `None`（右栏只显示顾客情况）。

    **和 `pipeline.主卡形态` 的差别只有一个：量的是最终去向。** 那个函数读
    `判成.输出`，在压低发生的那一轮会给出低一档的答案 —— S00007 里 G4 把
    一条 `AI直发` 抬成了 `客服点发送`，它给出 `AI直发` ⇒ 不做卡 ⇒ 右栏写
    「AI 可自行答复」，而那句话已经被拦下、一个字都没发出去。

    两个函数都留着是**故意的**：`pipeline.主卡形态` 是纯规则层的「这一轮
    判得多重」，不依赖 `生成结果`（单测、离线都拿它说话），别把它改掉。
    """
    if not 判成们:
        return None
    return max(
        (_最终去向(i, 判, 生成结果们) for i, 判 in enumerate(判成们)),
        key=lambda o: pipeline.优先级[o],
    )


def _主卡缘由(
    主卡条: int | None,
    判成们: list[pipeline.判成],
    生成结果们: dict[int, Any],
) -> str:
    """主卡那条主张**为什么**是这个输出（`文案.取主卡文案` 的第三个入参）。

    取主卡条自己的 `判成.缘由`，只有一种情况要改：**最终去向比判成的高** ——
    理由不在 `判成` 上。但**那个不等式有两个来源**，卡面说的是哪一个得分开：

    - 命中带 `降级去向`（G3 没核对过的话术、G4 修不动的高危命中）→
      `缘由.闸门压低`。**稿子有，是被拦下的。**
    - `话术生成._收尾` 的降级地板 → `缘由.没出稿`。**稿子压根没有** ——
      模型够不着／第一枪没答上来，`命中` 还是初始化那个空元组，
      一条闸门都没跑过。

    ⚠️ **不分开的后果是卡面指错方向。** 两者都写成「稿子没过检查 · 旁边列着
    命中原因」的话，前者的客服去改那句话、后者的客服去翻一个**空的**列表，
    而他要做的是从零写。

    **判据「降级 且 一条命中都没有」为什么够用**（`话术生成.生成话术` 的循环
    只给得出这几种出口）：跑过闸门且干净会走 `是否放行` 那一支，
    `降级=False`，压根到不了地板；重试那条路上的两个降级出口
    （喂回高危后再问、封顶）**都带着上一轮的 `命中`**。所以
    `降级 且 命中==()` 只剩「第一枪就没答上来」——够不着模型，或模型回了个
    空串。那两种情况下 `上一稿` 还是初始的 `""`（它在该函数里初始化，
    不从外面传），**一个字都没写过**。
    """
    if 主卡条 is None:
        return ""
    判 = 判成们[主卡条]
    if _最终去向(主卡条, 判, 生成结果们) is not 判.输出:
        出稿 = 生成结果们.get(主卡条)
        if 出稿 is not None and 出稿.降级 is not None and not 出稿.命中:
            return pipeline.缘由.没出稿.value
        return pipeline.缘由.闸门压低.value
    return 判.缘由


def _闸门(主卡条: int | None, 生成结果们: dict[int, Any]) -> list[schemas.闸门命中]:
    """主卡那句话过闸门的结果。没出稿时是空的 —— 那是「没有待发的话」，
    不是「这句话没问题」，两者的区别在 `Advice.话术` 上看得出来。"""
    if 主卡条 is None or 主卡条 not in 生成结果们:
        return []
    return [
        schemas.闸门命中(
            闸门=命中.闸门,  # type: ignore[arg-type]
            名称=命中.名称,
            严重度=命中.严重度,
            详情=命中.详情,
            证据=list(命中.证据),
            建议=命中.建议,
            可重生成=命中.可重生成,
            降级去向=命中.降级去向,
        )
        for 命中 in 生成结果们[主卡条].命中
    ]


def 组响应(
    *,
    会话: schemas.Session,
    轮次号: int,
    顾客情况: list[pipeline.顾客情况行],
    安全事件: list[inbound.安全事件],
    触发列表: list[triggers.触发],
    判成们: list[pipeline.判成],
    依据: list[schemas.Evidence],
    已代发: list[schemas.已代发条目],
    生成结果们: dict[int, Any] | None = None,
) -> schemas.判定响应:
    """把十一 步的产物拼成 `判定响应`。

    ⚠️ **`已代发` 只在 `主卡` 里，顶层没有**（工单 §四）。顶层再放一份就是同一份
    数据传两遍，两份一旦不同步，右栏两处会显示不一样的内容 —— **而两处都看着对**。
    """
    生成结果们 = 生成结果们 or {}
    主卡条 = _主卡条(判成们, 生成结果们)
    # ⚠️ **形态、话术、闸门、缘由四样必须同源**（都取主卡条 + 最终去向）。
    # 形态原来走 `pipeline.主卡形态(判成们)`，读的是压低**之前**的输出 ——
    # 那次分叉让 S00007 的右栏「AI 可自行答复」配一条其实被拦下的主张。
    形态 = 文案.取形态(_轮去向(判成们, 生成结果们))

    主卡 = None
    if 形态 is not None:
        出稿 = 生成结果们.get(主卡条) if 主卡条 is not None else None
        # 主卡那句话有**两个来源，按去向分**，两条路互斥：
        #
        # - 走模型的那两种（`AI直发`／`客服点发送`）→ `生成结果`。它是**主卡那条
        #   主张**的成稿（spec §三：一条主张一次生成，主卡只是挑一条显示）。
        #   拿 `判成们[0]` 的会串台 —— 线一第 1 轮第一条是「含乙醇」，
        #   右栏会显示一句讲成分的话配「涉个体差异」的标题。
        # - `转交` → `判成.转交话术`（`handover` 的固定表，不走模型）。
        #   这一句以前没有：`转交` 既不在 `_走模型的去向` 里，也没人问
        #   `handover` 要，于是主卡是 `有风险` 那一轮右栏**永远没有话术**，
        #   而 `31_界面文字清单` §四 那一格写的正是要显示它。
        #
        # 两条路不可能同时有值：`转交` 是终结性的，`收敛` 之后整轮都是转交，
        # 而 `跑话术生成` 跑在 `收敛` **之后** —— 那一轮它一条都没生成。
        #
        # 都没值时留 `None`（`报备` 的安抚话术由客户端发、`AI直发` 已经发出去了；
        # 或者转交但 `handover` 认不出该说哪句）。前端对 `None` 的做法是不显示话术块。
        话术 = 出稿.话术 if 出稿 is not None else ""
        if not 话术 and 主卡条 is not None:
            话术 = 判成们[主卡条].转交话术
        # ⚠️ **`有稿` 要在取文案之前算出来**，它定的就是卡面那几句话 ——
        # 卡面说「话术已备好」而这里的 `话术` 是空的时候，屏幕上只剩一句保证
        # 和一个按下去什么都没有的「采用」（`AdviceCard` 对空话术整块不渲染）。
        # 和 `形态`／`闸门`／`缘由` 一样：这一屏的字**全都按最终值取**。
        条 = 文案.取主卡文案(
            形态,
            触发列表,
            _主卡缘由(主卡条, 判成们, 生成结果们),
            有稿=bool(话术),
        )
        主卡 = schemas.Advice(
            形态=形态,  # type: ignore[arg-type]
            判断=条.判断,
            标题=条.标题,
            说明=list(条.说明),
            风险标签=条.风险标签,
            话术建议=条.话术建议,
            话术=话术 or None,
            依据=依据,
            已代发=已代发 or None,
        )

    return schemas.判定响应(
        会话ID=会话.会话ID,
        轮次=轮次号,
        顾客情况=[_行(r) for r in 顾客情况],
        安全事件=[
            schemas.安全事件条目(
                类别=事件.类别, 命中=事件.命中, 处置=事件.处置, 说明=事件.说明
            )
            for 事件 in 安全事件
        ],
        触发=[
            schemas.触发条目(
                编号=t.编号, 名称=t.名称, 严重度=t.严重度, 证据=list(t.证据), 说明=t.说明
            )
            for t in 触发列表
        ],
        本轮处置=_处置(
            判成们,
            会话.会话ID,
            轮次号,
            {i: r.去向 for i, r in 生成结果们.items()},
            # 报备那句不在 `生成结果` 里，`_话术们` 从固定表补 —— 见那个函数。
            话术们=_话术们(判成们, 生成结果们),
        ),
        主卡=主卡,
        # 闸门管的是「AI 这句话为什么没发出去」，所以它跟着**主卡那句话**走：
        # `主卡.话术` 是这轮唯一一句待发的话，命中就是它被拦的原因。
        # 把本轮所有主张的命中并起来的话，右栏会说「这句话有三处问题」，
        # 而那三处分别属于三句不同的话 —— `闸门命中` 上没有主张字段，
        # 拼在一起就再也拆不开了。
        闸门=_闸门(主卡条, 生成结果们),
    )


