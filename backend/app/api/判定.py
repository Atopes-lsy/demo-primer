def 整会话顾客情况(
    会话: schemas.Session,
    票表: dict[str, schemas.TaggedTicket] | None = None,
) -> list[schemas.StateRow]:
    """一条会话装配好的顾客情况五行 —— **只跑第 4～6 步，第 7 步往后一步都不跑**。

    `GET /api/会话列表` 用它。目的只有一个：点开哪一条，右栏都有「顾客情况」
    这块模块，而不是除两条演示线之外一片空白。

    # 为什么这条便宜到能一次装配 140 条

    第 4～6 步（装配 → 硬触发 → 回填）**全是规则**，第 7 步 `拆主张` 才是这条
    流水线第一次碰模型。所以全部装配一遍是几十毫秒，而给它们跑一次判定是
    几百次模型调用。

    # 三处与整条判定**故意不一样**，每一处都得能解释

    1. **切轮不走模型。** `归属` 传 `None`，`切轮` 退回纯结构切法：买家发言开始
       一轮、客服或 AI 收尾。整条判定那条路的 `归属` 是 `认诉求` 一条买家消息
       一次认出来的，这里认不起 —— 114 个窗口几百次调用，而 `/api/会话列表`
       没有留给它的超时预算。

       两边切出来的轮**可能不同**，但**这五行上一个字都不差**：唯一用到轮的是
       「这次要什么」，而它 2026-10-04 起是**攒**的（`装配.这次要什么`）——
       轮怎么切不影响拍平之后的顺序和内容，只有「起演格切到哪儿」和
       「去不去尾」（`已说完`）影响它。`test_判定.列表这条路切轮不走模型`
       当场把这件事量了一遍。

       退回结构切法不是「降级到差不多」：`认诉求` 够不着模型时给所有消息同一个
       标签，`切轮` 收到的正是这个结构切法的结果（`pipeline.切轮` 的文档串写着
       这件事）。所以列表页看到的是**那条兜底路上的同一份**，不是第三种切法。
    2. **只算 H3 一个硬触发。** H1／H2／H4 的产出（`触发列表`）在右栏没有落点：
       它们只喂 `三层判定` 主卡，而这一路根本不跑判定。H3 是四个里唯一一个
       **回填进顾客情况**的（`pipeline.组装顾客情况`），所以这不是「挑一个算」，
       是「只算有落点的那个」。结论因此和跑完整条判定逐字相同 —— 另外三个改不了
       这五行。
    3. **「当前时间」取会话最后一条消息的时间。** 逾期要拿一个「现在」去比，
       而 `/api/会话列表` 没有时间参数；取真实时钟又会把 2026-09 的数据放到
       2026-10 的天平上称 —— 屏幕上会出现「9/27 承诺，已逾期 8 天」而旁边每一行
       别的日期都是九月（`台账.py` 顶上也记着同一个坑）。取会话自己的末刻，
       判出来的是「**这条会话结束的时候，那个承诺就已经过期了**」—— 那是数据
       内部就有的事实，而且同一条会话每次请求答得一模一样。
       `最近时间` 解析不动时**跳过 H3**，不退回 `datetime.now()`：拿不到「现在」
       就不该断言「逾期」。

    # `票表`：这个人的**所有来访**，才认得出前段许下的承诺

    `GET /api/会话列表` 传（`路由.py` 从 `合并窗口` 拿得到 `窗口ID → 票表`），
    整条判定那条路**不传** —— 它拿到的是 `装.找(会话ID)` 那一段，本来就只有
    一次来访的票。不传时行为等同加这个参数之前。

    认错的代价是**假逾期**：上一次的补发早就发出去了，屏幕上却说
    「答应过的没做到」—— 实测三个真实窗口会这样。理由在 `装配._未兑现`。

    # 它不声称自己判过

    右栏在这五行下面是「这条会话还没跑判定」（`PrimerPanel.未判定`）—— 那不是
    兜底文案，是实话：主张、主卡、去向确实一条都没算过。
    """
    # 切到**最后一次来访**为止：窗口的消息是几段接起来的（`顾客窗口._合成窗口`），
    # 前面几段是更早的来访。不切的话「这次要什么」会把上回她要的也算进这一次
    # （`装配.这次要什么` 攒的是喂进去的每一句），而屏幕上多出来的那截
    # 每一个字看着都像真的。
    #
    # 单段窗口 `起演格` 就是 0（`顾客窗口.合并窗口` 显式写出来），切片是空操作。
    本次消息 = 会话.消息[会话.起演格 or 0 :]
    轮们 = pipeline.切轮(装配.轮消息们(本次消息))

    末刻 = 装配.解析时间(会话.最近时间)
    # `现在=末刻` 在这一路是个空操作（会话里没有比末刻更晚的消息），传它是为了
    # 让「还没说出口的承诺不算承诺」这条规矩**两条路一样** —— 详见 `装配.现在`。
    基础行 = 装配.装配顾客情况(会话, 轮们, 票表, 现在=末刻)

    逾期 = None if 末刻 is None else triggers.H3逾期(装配.取承诺时限(基础行), 末刻)

    return [_行(r) for r in pipeline.组装顾客情况(基础行, [] if 逾期 is None else [逾期])]


