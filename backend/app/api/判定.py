@dataclass(frozen=True, slots=True)
class 截断:
    """「看到第 N 轮为止」的那段消息，以及这段里本轮的形状。"""

    消息: list[schemas.ChatMessage]
    """从头截到本轮结束。**含本轮末尾那条客服／AI 回复** —— 理由见 `切到`。"""
    本轮: pipeline.轮次 | None
    """本轮的买家发言。`None` = 没截到第 N 轮。"""
    末条买家: int
    """`消息` 里本轮最后一条买家消息的下标。`-1` = 本轮买家的还没出现。

    给 `已代发` 用：本轮 AI 代发出去的话，就是这一条**之后**的 AI 消息。
    """


def 切到(
    消息: list[schemas.ChatMessage],
    第几轮: int,
    归属: Mapping[int, str] | None = None,
) -> 截断:
    """截到第 N 轮结束，**含那一轮末尾的客服／AI 回复**。

    # 为什么不能直接拿 `切轮` 的结果当截断

    `pipeline.切轮` **把客服和 AI 的消息全都丢掉**，只留买家的 —— 这是对的，
    它要的是「哪几轮买家说了什么」。但那个返回值没法回答「第 2 轮的时候，
    屏幕上有什么」：客服那句「今天安排发出，48 小时内给您单号」不在里面，
    而那正是 H3 要读 `时限` 的那条消息。用它截的话，第 2 轮看到的对话里
    承诺凭空消失了，逾期也就跟着消失。

    # 但「哪几条是一轮」只由 `切轮` 说了算

    这条函数原先自己走一遍消息流，于是成了**第二套切法** —— 归属只喂给
    `切轮` 的话，两套对同一条消息流会切出不同的轮：`全部轮` 有 2 轮，而这里
    认的第 1 轮是「三条买家消息并起来」的那一轮，它不在 `切轮` 的轮表里，
    `全部轮.index(本轮)` 直接抛 `ValueError`（接口 500，而报错指向的是组响应，
    不是切法分家）。

    所以现在这里**不判边界**：边界问 `切轮`，自己只干两件它干不了的活 ——
    把「第 N 轮」翻回下标、把这一轮**末尾那条客服／AI 回复**捞回来。

    那一刀的取法：本轮最后一条买家消息**紧后面**那条，是「回复」的话就含上
    （`[买家, 客服]` 里的客服）；是买家的话说明这一轮是被**归属**切开的
    （`[买家·甲, 买家·乙]`），到上一条为止 —— 那里根本没有回复可含。

    # 截不到就 `本轮=None`

    第 99 轮、或者空会话，都走这条。调用方退回最后一轮 —— **不抛**：
    演示时前端多按一次不该让右栏变红。`消息` 这时给整段（和原实现一致）。
    """
    轮们 = pipeline.切轮(装配.轮消息们(消息), 归属)
    if not 轮们:
        return 截断(list(消息), None, _末条买家下标(消息, None))

    目标 = 轮们[第几轮 - 1] if 1 <= 第几轮 <= len(轮们) else None
    if 目标 is None:
        # 末条买家照旧报全流最后一条：调用方退回最后一轮时拿它挑 `已代发`，
        # 而那是「末尾那段 AI 消息」的起点。
        return 截断(list(消息), None, _末条买家下标(消息, 轮们[-1]))

    末条买家 = _末条买家下标(消息, 目标)
    有回复 = (
        0 <= 末条买家 < len(消息) - 1 and 消息[末条买家 + 1].角色 != "买家"
    )
    结尾 = 末条买家 + 1 if 有回复 else 末条买家
    return 截断(消息[: 结尾 + 1], 目标, 末条买家)


