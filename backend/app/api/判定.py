def 归属表(
    消息: list[schemas.ChatMessage],
    认诉求函数: Callable[..., str],
) -> dict[int, str]:
    """第几条消息属于哪个诉求。键是 **`消息` 序列里的绝对下标**。

    这就是 `pipeline.切轮` 的 `归属` 参数。键的解释由那边钉死（不是「第几条
    买家消息」—— 两套解释都能跑，只是切出来的轮不同，而不会有任何东西报错，
    `test_切轮.py` 有一条专门用「两套解释结果不同」的输入钉它）。

    # 清单是攒出来的，不是查出来的

    `认诉求` 要一份「已有诉求」，而那是会话级状态。这里**每请求重算**：从第 1 条
    买家消息走到最后一条，把认出来的标签攒下来喂给下一条。不另存一份 ——
    同一份会话在两次请求里认出的轮必须一样，而存下来的那份会随进程的历史漂。

    ⚠️ **攒的是「本会话出现过的诉求」，不是「当前未解决的诉求」。** 数据里没有
    任何「这个诉求已经解决了」的信号：工单说的是「办过什么」，而认出来的标签
    压根不挂工单。所以「未解决」那半判不了。松一点的影响是**少切几刀**
    （模型可能把新消息认到一条其实已经处理完的诉求上）—— 比反过来松：筛错方向
    的话，同一件事会被切成两轮，各判一次、右栏出两块。

    # 为什么走整条会话，不只本轮

    归属要赶在 `切轮` 之前算完，而 `切轮` 切的是**全部**轮 —— 第 N 轮是哪一轮
    由它数出来。只算到本轮为止的话，同一条消息流会因为「这次问的是第几轮」
    切出两张轮表，而轮次号挂在每条处置的 `id` 上。

    代价是一次判定多 N 次模型调用（N ＝ 会话里买家消息的条数，演示两条线是
    3 和 1）。

    # 认不出来不抛

    `认诉求` 自己兜住了「模型够不着」（退到 `认不出`），空消息返回空串。
    两者在 `切轮` 眼里都是「**这条没有意见**」，不造成切分 —— 所以这里不需要
    再包一层 `try`：真让它抛出来的只会是别的 bug，而被吞掉的那种 bug 会变成
    「切轮悄悄退回结构切法」，那就和「模型位没接上」长得一模一样了。
    """
    已有: list[str] = []
    归属: dict[int, str] = {}
    for i, m in enumerate(消息):
        if m.角色 != "买家":
            continue
        标签 = 认诉求函数(m.message_text, 已有)
        归属[i] = 标签
        if 标签 and 标签 not in 已有:
            已有.append(标签)
    return 归属


