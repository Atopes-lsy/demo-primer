@router.post("/api/判定", response_model=schemas.判定响应, summary="一句话进来，右栏出什么")
def 判定(
    请求: schemas.判定请求,
    装: 业务数据,
    商表: 商品属性表,
    模型: 模型位置,
) -> schemas.判定响应:
    原始会话 = 装.找(请求.会话ID)
    判定对象 = (
        找判定会话(装, 请求.会话ID)
        if 请求.看到消息数 is not None
        else (判定会话(原始会话) if 原始会话 is not None else None)
    )
    if 判定对象 is None:
        # ⚠️ **不返回空判定。**「会话不存在」和「这个会话没触发任何东西」在界面上
        # 都是右栏空白，但前者是前端传错了 ID —— 返回空判定的话，排查方向会指向
        # 判定逻辑，而那是对的（工单 §四 第 1 步）。
        raise HTTPException(status_code=404, detail=f"没有这个会话：{请求.会话ID}")
    会话 = 判定对象.会话

    if 请求.看到消息数 is not None:
        if 请求.看到消息数 > len(会话.消息):
            raise HTTPException(status_code=422, detail="看到消息数超出了该窗口的消息范围")
        可见消息 = 会话.消息[: 请求.看到消息数]
        会话 = 会话.model_copy(update={"消息": 可见消息})
        # 合并窗口的 ID 是末段 ID；回放历史时要按当前可见消息所在的原始来访取订单/工单。
        当段 = 装.找(可见消息[-1].会话ID)
        if 当段 is not None:
            起点 = next(i for i, m in enumerate(可见消息) if m.会话ID == 当段.会话ID)
            会话 = 会话.model_copy(
                update={"订单": 当段.订单, "工单": 当段.工单, "起演格": 起点}
            )

    当前 = (
        请求.当前时间
        or (装配.解析时间(会话.消息[-1].发送时间) if 请求.看到消息数 is not None and 会话.消息 else None)
        or datetime.now()
    )

    # ── 2 · 认诉求 → 轮次截断 ───────────────────────────────
    #
    # ⚠️ **归属只算一次，`切轮` 和 `切到` 共用同一张表。** 两处各算一份的话，
    # 模型两次采样不同（或一次成功一次失败）就会切出两张轮表 —— 而那不是
    # 「有一边错」，是 `全部轮.index(本轮)` 抛 `ValueError`，整个接口 500。
    #
    # 归属走**整条会话**、不只本轮：第 N 轮是哪一轮由 `切轮` 数出来，
    # 只认本轮的后果在 `归属表` 的文档串里。
    归属 = None if 请求.看到消息数 is not None else 归属表(会话.消息, 模型.认诉求)
    全部轮 = pipeline.切轮(装配.轮消息们(会话.消息), 归属)
    if 请求.看到消息数 is not None:
        轮次号 = len(全部轮)
        if 请求.轮次 is not None and 请求.轮次 != 轮次号:
            raise HTTPException(status_code=409, detail="轮次与可见消息不一致，请重新读取窗口")
        本轮 = 全部轮[-1] if 全部轮 else None
        截 = 截断(会话.消息, 本轮, _末条买家下标(会话.消息, 本轮))
    elif 请求.轮次 is not None:
        截 = 切到(会话.消息, 请求.轮次, 归属)
        本轮 = 截.本轮 if 截.本轮 is not None else (全部轮[-1] if 全部轮 else None)
    else:
        本轮 = 全部轮[-1] if 全部轮 else None
        末条买家 = _末条买家下标(会话.消息, 本轮)
        截 = 截断(会话.消息, 本轮, 末条买家)
    # 请求的轮次截不到（第 99 轮）时退回最后一轮：**报真实的那一轮号**，
    # 不回显 99 —— 前端拿着 99 去拼 `id` 会拼出 `S_DEMO_A-99-1`，
    # 那是个不存在的处置。
    if 请求.看到消息数 is None:
        轮次号 = 全部轮.index(本轮) + 1 if 本轮 is not None else (请求.轮次 or 0)

    # ── 3 · 输入安全层 ──────────────────────────────────────
    安全事件 = inbound.扫输入(本轮.全文) if 本轮 is not None else []

    # ── 4 · 装配基础行（**必须早于 5**）──────────────────────
    #
    # 「这次要什么」要**到本轮为止**的轮，不是整条会话。后端手上这份是**写全了的
    # 会话** —— 演示线的后面几轮消息此刻已经躺在里面了，喂整份就会把还没演到的
    # 轮漏进第 1 格（屏幕上多出她还没说出口的话）。`轮次号` 上面第 2 步已经算好。
    #
    # `已说完=False`：这条路一轮一答，问的是「她此刻说到哪儿了」—— 这一轮最后
    # 那句就是**当前要办的那句**，按「收场白」去掉等于把最新的诉求抹掉。
    # 列表页那条路反过来（`整会话顾客情况`，那次来访早就过去了）。
    #
    # `现在=当前`：**「答应过什么」也要到本轮为止。** 理由是同一件事的另一面
    # ——「这次要什么」怕的是她还没说出口的话漏进第 1 格，「答应过什么」怕的是
    # **客服还没说的那句**漏进来（它会带着一条更新的、往往还没到期的承诺，
    # 把真正逾期的那条顶掉）。两条路各防各的，洞是同一个。
    本次轮 = (
        pipeline.切轮(装配.轮消息们(会话.消息[会话.起演格 or 0 :]))
        if 请求.看到消息数 is not None
        else 全部轮[:轮次号]
    )
    基础行 = 装配.装配顾客情况(
        会话,
        本次轮,
        判定对象.票表,
        已说完=False,
        现在=当前,
    )

    # 第 2 层比额度要用的三个事实（件数／金额／质量问题）。
    #
    # ⚠️ **只跟会话走，不跟轮次走** —— 它读的是工单，工单上写的是「这一单」
    # 而不是「这一轮」。所以算一次就够，别挪进下面按主张循环里。
    #
    # 三个维度都可能取到 `None` ＝「不知道」，那时**卡额度的条目判不了 → 报备**
    # （`permissions.权限事实` 那段）。`None` 和 `0` 不是一回事：物流工单没有
    # 数量列，是「不知道」不是「0 件」。
    事实 = 装配.取权限事实(会话)

    # H1 的窗口 ＝ **整条会话到此为止**，不是本轮。理由是 H1 那三族说的是
    # 已经发生过的事实（不良反应／监管／投诉），下一句收场白改不掉它。
    # 走 `截.消息`（切到本轮为止）**不是** `会话.消息` —— 后者含顾客还没
    # 说的那几句，拿它扫 H1 等于让判定偷看后面几轮。
    # H2／H4 不用这个窗口，它们照旧只看本轮，理由见 `triggers.硬触发`。
    #
    # ⚠️ **第 5 步和第 9 步必须传同一份。** 第 5 步拿它扫 H1 的词，第 9 步拿它
    # 认「H1 的话该怎么说」（`三层判定` → `handover.认转交话术`）—— 两处窗口
    # 不一样，就会出现**触发说得出「顾客过敏了」、卡上却说不出该对过敏说什么**
    # 的分叉，而且不报错。切成变量就是为了让「同一份」在代码里看得见。
    风险文本 = [m.message_text for m in 截.消息 if m.角色 == "买家"]

    # ── 5 · 硬触发 ─────────────────────────────────────────
    触发列表 = triggers.硬触发(
        list(本轮.买家消息) if 本轮 is not None else [],
        当前,
        # H3 的输入。**来自第 4 步**，顺序换不得。
        承诺时限=装配.取承诺时限(基础行),
        订单状态=会话.订单.订单状态 if 会话.订单 is not None else "",
        重复要求=判重复要求(
            会话,
            本轮.买家消息 if 本轮 is not None else (),
            _本轮之前(截.消息, 本轮),
        ),
        # ⑤「表达不信任」的正式路径是**模型判、必须引用原句**（v9 §三）。
        # `llm/` 里还没有这个模块，所以走关键词回退 —— `_不信任证据` 专门为
        # 「模型还没接上」留了这条路（`H2不信任词` ＋ `H2又了句式`）。
        认不信任函数=None,
        风险文本=风险文本,
        # 售后退货工单里的「风控核实／拆封少件／空包」是已核验的结构化风险，
        # 不能只等顾客恰好说出「仅退款」这几个词。
        风控异常=装配.是异常包裹工单(会话),
    )

    # ── 6 · 回填「警示」──────────────────────────────────────
    顾客情况 = pipeline.组装顾客情况(基础行, 触发列表)
    情况 = [(r.标签, r.值) for r in 顾客情况]

    # ── 7 · 拆主张（模型位）─────────────────────────────────
    主张列表 = 模型.拆主张(本轮.全文, 情况) if 本轮 is not None else []

    # ⚠️ **短路触发命中时，这一轮不许是空的**（2026-10-05 补）。
    #
    # `拆主张` 那一侧从 2026-10-05 起「空数组也是一个真答案」（寒暄、道谢、
    # 收场白不拆，见那边的模块文档串）—— 那条规矩本身是对的，但它和硬触发
    # 短路撞出了一个够得着的状态：`三层判定` 的短路是对**主张列表**做列表
    # 推导，列表空 → 一条 `判成` 都产不出来 → `组响应` 走到 `取形态(None)`
    # → **`主卡` 是 `None`**。右栏那张红卡整个消失，而同一份响应里 `触发[]`
    # 明写着 `H1`。
    #
    # 实测（十条复验）`S00010` 就是这个：顾客第 1 条说用了面膜全脸发红、
    # 起疹子，末轮她只说「行，等你们回访，麻烦尽快」。**H1 的去向是 §三 的
    # 「整通对话转出」**，那是会话级的事，不该被「这一句拆不出诉求」挡掉 ——
    # 顾客身上已经发生的事，一次都不许因为下一句是收场白而消失（H1 的窗口
    # 改成按会话累积的也正是这个理由，见第 5 步那段）。
    #
    # 退回「整条消息算一条」＝ `拆主张._兜底` 那条老规矩。红卡的「为什么」
    # 得挂在一条主张上 —— 那也是 `拆主张` 模块文档串里那条约束（风险要归到
    # 哪一条主张上才有的展示），`H1` 命中时它照跑不短路就是这个原因。
    if (
        本轮 is not None
        and not 主张列表
        and 本轮.全文.strip()
        and any(t.编号 in pipeline.短路触发 for t in 触发列表)
    ):
        主张列表 = [本轮.全文.strip()]

    # ── 8 · 六源（模型位）───────────────────────────────────
    #
    # ⚠️ **认口径每条主张只调一次**，结果存下来给下面两处用。
    #
    # 看着啰嗦，但少了这一步就是那个具体的错：`查六源` 和 `三层判定` 都想知道
    # 「这条主张认到哪个编号」，各自调一次的话，同一条主张会有**两次认口径的
    # 结果**。`认口径` 是模型，两次可以不一样 —— 那时右栏 ② 挂的是 K10 的话术、
    # 而 `依据编号` 写的是 K16，**两处都看着对**（`检索.六源` 的模块文档串
    # 专门为这件事写了「为什么调用方要把编号传进来」）。
    # ⚠️ **两个口径表变量，不是一个。** `口径表数据` 是那张表**连同元数据**
    # （`.取(编号)`、`.待核对数字()`），`口径表` 只是它里面的行元组。
    #
    # 认口径和三层判定要行元组，`生成话术` 要外面那层壳（它得调
    # `.待核对数字()` 拿业务方没确认的时效数字）。传错的那个不会在类型上
    # 报错 —— `生成话术` 直到用上才炸 `'tuple' object has no attribute '取'`，
    # 而那一声是从 `llm/组装提示.py` 里发出来的，看着像模型线的错。
    口径表数据 = deps.取口径表()
    口径表 = 口径表数据.口径表
    口径编号: dict[str, str | None] = {
        主张: 模型.认口径(主张, 口径表) for 主张 in 主张列表
    }
    六源: dict[str, sources.六源结果] = {
        主张: 模型.查六源(
            主张, 会话, 商表, 口径表=口径表, 口径编号=口径编号[主张]
        )
        for 主张 in 主张列表
    }

    # ── 9 · 三层判定（模型位）───────────────────────────────
    判成们 = pipeline.三层判定(
        主张列表,
        触发列表,
        六源=六源,
        顾客情况=情况,
        # H1 认「该对顾客说哪句」用的窗口 —— **和第 5 步同一份**，
        # 理由见上面那段。
        风险文本=风险文本,
        # 第 2 层比额度的那三个事实。**按主张索引**（接口是 `Mapping[str, …]`），
        # 而事实本身是整单的 —— 所以每一条主张喂的是同一份。
        #
        # ⚠️ 少了这一句，`权限事实()` 各维度全是 `None`，`查权限` 在「逐条比
        # 额度」之前就撞上 `判不了` 早返回：**§6.2 的「超额度」和 §4.2 的
        # 「系统查不到」在屏幕上糊成同一种卡**，`L01→E01`（补发超 1 件 → 报备）、
        # `L03→X01`（赠品追加超 1 件 → 转交）这两条分岔一次都没跑过。
        # 2026-10-04 之前这里就是缺的，`权限事实表` 全项目**没有产出者**。
        权限事实表={主张: 事实 for 主张 in 主张列表},
        口径表=口径表,
        # 查上一次的结果，**不再问一次模型** —— 见上面那段。
        认口径函数=口径编号.get,
        # 第 2 层「这件事归谁办」。走口子而不是 `rules.permissions.认权限` 的
        # 关键词 —— 2026-10-03 之前它**不在请求路径上**，演示当天真正跑的
        # 还是关键词那条老路（`工单交接_给接口线_B.md` §六）。
        # ⚠️ 模型这个位回 `None` 时判**未列明**（继续第 3 层），**不是拒绝**，
        # 也**不回退**到关键词 —— 要退回关键词只有「模型够不着」一条路，
        # 而那一步在 `llm/认权限.py` 里。
        认权限函数=模型.认权限,
    )

    # ── 10 · 收敛 ──────────────────────────────────────────
    判成们 = pipeline.收敛(判成们)

    # ── 11 · 话术生成（模型位，逐主张）──────────────────────
    #
    # 放在三层判定**之后**：它要 `判成.依据`（4.1 修完之后带着序号）、
    # `判成.依据编号`、`判成.涉及个体差异`，这三样都要判完才有。
    # 放在收敛**之后**：收敛掉的主张不该再花一次模型调用。
    生成结果们 = 跑话术生成(
        判成们,
        模型,
        顾客情况=情况,
        触发列表=触发列表,
        口径表=口径表数据,
        # G4 要拿它查「这话是不是刚说过」。传的是**本轮之前**的历史 ——
        # 本轮自己新产生的话还没发出去，算进来的话每一稿都会撞自己。
        已发出=pipeline.已发出的话(
            装配.轮消息们(_本轮之前(截.消息, 本轮))
        ),
    )

    # ── 12 · 组响应 ────────────────────────────────────────
    响应 = 组响应(
        会话=会话,
        轮次号=轮次号,
        顾客情况=顾客情况,
        安全事件=安全事件,
        触发列表=触发列表,
        判成们=判成们,
        依据=_依据(
            [六源[m] for m in 主张列表 if m in 六源], 判成们, 生成结果们
        ),
        已代发=_已代发(截, 判成们, 生成结果们),
        生成结果们=生成结果们,
    )

    # ── 12.5 · 回写先例库（③，spec §六）────────────────────
    #
    # **整段包起来**：嵌入要网络，而这一步是锦上添花那一环 —— 它炸了绝不能让
    # 判定 500，最坏是这条没进库。`回写` 自己也兜了一层，这儿是第二层。
    #
    # 情境取 `本轮.全文`（**买家这一轮的原话**，和取材同构），答法取响应里那句
    # `话术`（模型刚写出来的那一稿，不是日志原话）。`本轮` 可能是 `None`
    # （这条会话一轮都没有）—— 那就不写。
    答法 = 该回写条(响应)
    if 答法 and 本轮 is not None:
        try:
            先例库.回写(本轮.全文, 答法, 响应.会话ID, 响应.轮次)
        except Exception:  # noqa: BLE001 —— 见上面那段
            pass

    # ── 13 · 记台账（动作接口读它）──────────────────────────
    #
    # 报备／转交那七行里有四行是**这一跳判出来的**，`发送` 收到的
    # `采用的处置id[]` 更是只有这张表才认得（见 `api/台账` 的模块文档串）。
    # **同一会话后写的盖掉先写的**：右栏一次只显示一轮，客服点按钮时看见的
    # 是最后判的那一轮，后端要是留着旧的那份，屏幕上那张单子和上一轮
    # 一模一样，而两轮的诉求根本不是一回事。
    #
    # 写的是**已经组好的响应**，不是重算一遍 —— `认口径` 是模型，算两遍
    # 可以不一样（第 8 步那段注释说的是同一件事）。
    台账.记(响应, 当前=当前)
    return 响应


def _末条买家下标(
    消息: list[schemas.ChatMessage], 本轮: pipeline.轮次 | None
) -> int:
    """本轮最后一条买家消息在 `消息` 里的下标。`-1` = 找不到。

    不传 `请求.轮次` 时走这条：那一刻不知道要截到第几轮，只知道**最后一轮
    是哪个**（`切轮` 给的），所以反过来找它的最后一条买家发言。
    用 `结束时间` 对而不是拿文本比 —— 同一句「在吗」可以发两遍。
    """
    if 本轮 is None:
        return -1
    for i in range(len(消息) - 1, -1, -1):
        if 消息[i].角色 == "买家" and 消息[i].发送时间 == 本轮.结束时间:
            return i
    return -1


def _本轮之前(消息: list[schemas.ChatMessage], 本轮: pipeline.轮次 | None) -> list[schemas.ChatMessage]:
    """本轮开头**之前**的全部消息，给 `判重复要求` 当历史。

    历史到本轮第一条买家发言为止。把本轮自己的话算进去的话，一句「赠品没到」
    会因为自己而变成「说了两次」—— ⑥ 就永远是 `True` 了。
    """
    if 本轮 is None:
        return list(消息)
    for i, m in enumerate(消息):
        if m.角色 == "买家" and m.发送时间 == 本轮.开始时间:
            return 消息[:i]
    return list(消息)
