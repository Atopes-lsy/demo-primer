#: 留痕这张脱敏表 —— `inbound.PII模式` **剔掉「银行卡号」那一条**。
#:
#: ⚠️ **自己编译一份，不去拿 `inbound._PII` 那个下划线名字。** 从 `PII模式`
#: 编译是**同一个来源**（那是公开的），借用私有名则是把两个模块耦死 ——
#: 模型线改个内部分组，这边静默少脱敏一种号码。
#:
#: # 为什么单剔「银行卡号」
#:
#: 那一条是 `(?<!\d)\d{16,19}(?!\d)` —— 一个**形状**启发式，不是号码格式。
#: 而这份赛题数据里的**订单号恰好是 19 位**（`6920470451725491723`），于是
#: 它命中的全是业务标识，不是个人信息：
#:
#:     关联订单号那一列        **819 / 998 行**命中（113 个会话）
#:     买家原话正文里写着      **25 条**（「你好，订单6920…723的退款咋还没到账啊」）
#:
#: 留着它的后果是**留痕开始说假话**，而且是四处一起说：
#:
#:   ① `轮消息[].文本`／`判成[].主张` 里的订单号变成 `692************1723`，
#:      同一轮右栏（`判定响应`）里是原文 —— 留痕和它要留痕的那件事对不上；
#:   ② `台账.取` 读的就是洗过的那份，**交接包「诉求」那一行会带着星号递出去**，
#:      而客服拿着它是要去查订单的；
#:   ③ `模型调用[].提示` 号称「发出去的那一份」，可 `组装提示` 里
#:      `- {e.出处}：{e.摘要}` 那几行发出去时没打码 —— 逐字复现变成假的；
#:   ④ 拿留痕复现模型看见了什么，会看到一串模型从没见过的星号。
#:
#: **代价说清楚：买家真在正文里写了银行卡号，留痕会原样记下。** 这份数据里
#: 那一条的**真命中是 0 条**（819 条全是订单号），而 `扫输入` 只扫买家正文 ——
#: 所以剔掉它对现有链路是无操作，只是不再消费这个形状。将来要真管银行卡，
#: 该给它一条认得出号码格式的规则（Luhn），而不是「16 到 19 位数字」。
#:
#: 其余三条（手机号／身份证号／邮箱）**照旧全在**，而且是从 `PII模式` 现算的 ——
#: 模型线将来往那张表里加人，这边自动就跟上了。
_PII找 = tuple(
    (re.compile(p), n) for p, n, _ in inbound.PII模式 if n != "银行卡号"
)


def 全篇脱敏(原文: str) -> str:
    """**整段**原文里所有敏感片段打码，不只 `扫输入` 抓出来的那几个。

    `inbound.脱敏` 盖的是「扫到的那一小段」，可留痕存的是**整段对话原文** ——
    手机号夹在一句寒暄中间时，扫出来的那一小段脱了敏，整段里那个号还在。
    留痕是长期保存的审计材料，原样存手机号等于把它变成泄露源
    （`inbound.脱敏` 的文档串记着这条）。

    ⚠️ **不改回放。** `切轮` 只看 `角色` 和 `发送时间`，文本改成什么样
    都不影响切出来的边界 —— 验收里那条「拿留痕重放切轮」照跑。
    `归属` 里的诉求串也会被它过一遍，而那一串在演示两条线上**没有一个片段
    匹配得上 PII 表**（2026-10-06 拿 A 两轮 ＋ B 一轮实测：整份留痕里被改动的
    字符串是零个），所以重放喂进去的还是原样的键。
    ⚠️ **「零个」只对演示那两条线成立 —— 别说成「在真数据上是无操作」。**
    138 条真会话里 25 条买家原话带着 19 位订单号，剔掉「银行卡号」那条之前
    它们全会被打成星号（上面 `_PII找` 那段记着这次收窄的来龙去脉）。

    ⚠️ **本该住在 `rules/inbound.py`**（挨着 `脱敏`，共用同一张表）。
    本单（步骤 6）不碰 `rules/`，所以先放这儿；将来挪过去时删这一个函数、
    改 `_PII找` 一处即可。
    """
    if not 原文:
        return 原文
    出 = 原文
    for 正则, _ in _PII找:
        出 = 正则.sub(lambda m: inbound.脱敏(m.group(0)), 出)
    return 出


def _洗过(值: Any) -> Any:
    """一棵「dataclass／pydantic 模型／字符串／序列」上的**每个字符串**过一遍脱敏。

    # 为什么是「整棵扫」而不是「一格一格挑着脱」

    进留痕的买家原话有两条路：`轮消息` 那条是直的，另一条是**模型和规则
    抄回来的** —— `判成[].主张`、`说明`、`本轮处置[].话术`、`主卡` 那些。
    第二条路上抄回来的东西原样就是一句买家话，这不是理论：

        `llm/拆主张._兜底` 在模型够不着或答坏时**整条消息算一条主张**，
        于是「我的手机号是 13800138000」会原样落进 `判成[].主张`。

    一格一格挑着脱，就得先知道一共有哪些格；这份记录有一百多个字符串，
    其中一半是模型写的，**漏一个格是看不出来的**（留痕里那一栏看着完全正常，
    只是里面躺着一个号）。所以整棵扫。

    ⚠️ **洗的是「存进去的那一份」，不是「读出来的时候」。** 读取那一侧有三条路
    （两个只读接口 ＋ 台账给动作接口的投影），读取时脱的话漏掉一条就是一条
    生 prompt 出了线。

    ⚠️ **三个调用点都得用同一个函数**：`记`（整份记录）、`收模型调用`
    （模型调用桶 —— 它住在 `留痕记录` 外面，整份记录那道扫不到）、
    `追加动作`（动作流水，同样在外面）。三处各写一份的话，改了一处忘一处。

    ⚠️ **枚举成员不算字符串，得原样放行。** `六源`／`输出类型` 那些是
    `str` 的枚举子类，`isinstance(值, str)` 对它们**成立** —— 一旦被
    `全篇脱敏` 接着（它 `.sub()` 回一个纯 `str`），那一格的类型就从
    「枚举成员」悄悄变成「字符串」。两种值长得一样、比较也相等，
    所以只有 FastAPI 序列化时那句
    `PydanticSerializationUnexpectedValue(Expected 'enum'…)` 会露头
    （`test_留痕.test_洗过不碰枚举成员` 钉着）。
    """
    if isinstance(值, Enum):
        return 值
    if isinstance(值, str):
        return 全篇脱敏(值)
    if isinstance(值, BaseModel):
        return 值.model_copy(update={名: _洗过(v) for 名, v in 值})
    if is_dataclass(值) and not isinstance(值, type):
        return replace(值, **{f.name: _洗过(getattr(值, f.name)) for f in fields(值)})
    if isinstance(值, tuple):
        return tuple(_洗过(x) for x in 值)
    if isinstance(值, list):
        return [_洗过(x) for x in 值]
    return 值


