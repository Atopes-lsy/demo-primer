def 收模型调用(调用: 客户端.模型调用) -> None:
    """`llm.客户端.记录钩子` 接的就是它。**没开工就丢掉。**

    ⚠️ **脱敏在这一层做，不在 `记` 那一层。** 桶是**住在 `留痕记录` 外面的
    一个结构**（`ContextVar` 里那个 list）：`记` 里那道整棵扫描扫的是记录本身，
    扫不到桶里的东西 —— 而且桶比记录先存在（`开工` 之后每次调用都往里塞）。
    两边都该洗，因为**这是两个容器**；共用的是同一个 `_洗过`。
    """
    桶 = 收集中.get()
    if 桶 is None:
        return
    桶.append(_洗过(调用))


def 接模型钩子() -> None:
    """把 `收模型调用` 接上 `llm/客户端` 的口子。

    **由 `main.启动装配` 调，不做模块级副作用** —— 模块级的话，`llm/` 会在
    import 期间就和 `api/` 缠上，而那是要挡住的那个方向
    （`llm/` 不许反向 import `api/`；这里是 `api/` 去设一个口子，方向是对的）。

    测试走 `ASGITransport` **不触发 lifespan**，所以测试里这个钩子一直是
    `None` —— 正是要的：单测不该顺手去打真模型。
    """
    客户端.记录钩子 = 收模型调用


