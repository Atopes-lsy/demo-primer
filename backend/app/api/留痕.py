# 读
# ══════════════════════════════════════════════════════════


def 事件(会话ID: str) -> tuple[动作事件, ...]:
    """这个会话的动作流水，**按发生顺序**。"""
    with 锁:
        return tuple(_动作.get(会话ID, ()))


def 最近(会话ID: str) -> 留痕记录 | None:
    """**最后写进去的那一轮**（不是轮次最大的那一轮）。`台账.取` 走它。"""
    with 锁:
        轮次 = _最近写的.get(会话ID)
        if 轮次 is None:
            return None
        return _轮.get(会话ID, {}).get(轮次)


def 取(会话ID: str, 轮次: int) -> 留痕记录 | None:
    """指定的那一轮。没有就是没有 —— 调用方自己决定 404 还是 409。"""
    with 锁:
        return _轮.get(会话ID, {}).get(轮次)


def 全部(会话ID: str) -> list[留痕记录]:
    """这个会话判过的每一轮，**按轮次升序**。

    ⚠️ **排序是接口契约的一部分，不是顺手。** `_轮` 是个 dict，插入序 ＝
    「判过的先后」；拖回去重判第 2 轮会把它的位置往后挪，而
    `GET /留痕` 的验收里有一条「两跑逐字节一样」—— 顺序不稳定的话，
    同一份数据两次序列化出来的字节不同，那条会红得莫名其妙。
    """
    with 锁:
        return [r for _, r in sorted(_轮.get(会话ID, {}).items())]


def 清空() -> None:
    """测试用：三张表都清掉。**别在应用代码里调它。**

    ⚠️ **不动 `客户端.记录钩子`** —— 那是**接线**不是数据。摘掉它会让
    「钩子装上了没有」这件事和「这把测试清干净了没有」纠缠在一起，
    而两者失败的兆头完全不同（一个是「一条调用都没记上」，
    一个是「记到了上一条测试的头上」）。
    """
    with 锁:
        _轮.clear()
        _最近写的.clear()
        _动作.clear()
    收集中.set(None)


def _六源条(主张: str, 结果: sources.六源结果) -> schemas.留痕六源:
    """一条主张查完六源 → 线上形状。**六条固定，按 `六源顺序`。**

    `查回` 是「这个来源上查到了几条记录」，**不是召回条数** —— `检索/六源`
    是关键词 ＋ 货号连接，一次查询直接取回，没有候选集也没有截断，
    所以**六源这一路**没有这个数。⚠️ **但 ③ 先例库那条路是真 top-K**
    （`召回条数 = 3`），它不进六源、也没进这张表 —— 见 `schemas.留痕源数`
    的文档串，别把两件事并成一句「后端没有召回条数」。

    `依据` 走 `证据.从六源` —— **全项目唯一一处「源记录 → Evidence」的映射**，
    右栏那份「依据 · N/6 源命中」走的就是它。这里另拼一份的话，同一条依据
    在两处会有两个分数，而两边都看着对（`api/证据.py` 的模块文档串）。

    ⚠️ **`序号`／`出处`／`摘要` 和右栏逐字相同，`用上` 可能不同，这不是漂移。**
    右栏那份是 `判定._依据` 出来的，它把 `用上` 换成了**模型自报**的结果
    （「这句话引了哪几条」）；这里记的是**检索层原样**（「查到了什么」）。
    两问不同源。要判「这一轮引了什么」看 `判成[].依据编号` 和
    `生成[].用到的依据`，别看这一格。

    ⚠️ **「逐字相同」这半句是 2026-10-06 复查改出来的，靠的是 `_PII找` 剔掉了
    「银行卡号」那条。** 在那之前，`出处` 里的 19 位订单号会被打成
    `692************5076`，和右栏对不上 —— 这一格说的是业务标识，
    不是买家的自由文本，本来就没什么可脱的。`test_十九位订单号不打码` 钉着。
    """
    return schemas.留痕六源(
        主张=主张,
        每源=[
            schemas.留痕源数(
                源=源,
                查回=len(结果.记录[源]),
                有记录=any(r.exists for r in 结果.记录[源]),
            )
            for 源 in sources.六源顺序
        ],
        依据=证据.从六源(结果),
    )


def _判成条(d: pipeline.判成) -> schemas.留痕判成:
    """一条判成 → 线上形状。**只搬，不判** —— 留痕不许改判定结果。"""
    return schemas.留痕判成(
        主张=d.主张,
        输出=d.输出,
        说明=d.说明,
        层=d.层,
        权限去向=d.权限去向,
        交接分类=d.交接分类,
        缘由=d.缘由,
        依据编号=list(d.依据编号),
        涉及个体差异=d.涉及个体差异,
    )


def _生成条(主张: str, g: 生成结果) -> schemas.留痕生成:
    """一句成稿怎么来的 → 线上形状。**`主张` 是传进来的** ——

    `生成结果` 上**没有 `主张` 字段**，它是按判成下标索引的
    （`跑话术生成` 回 `{判成下标: 生成结果}`），名称得从 `判成们[下标]` 上取。
    少了这一格，留痕里那句「重生成试了几轮」就不知道该挂在谁头上。

    ⚠️ **`命中` 走 `dataclasses.asdict`，不是手抄八个字段。**

    `生成结果.命中` 是 `guards.闸门命中`（规则层的 dataclass），线上那一栏是
    `schemas.闸门命中`（契约模型），**pydantic 不会自己把 dataclass 当 dict 收**
    （`ValidationError: Input should be a valid dictionary`）。两个办法：
    手抄八个字段名，或者 `asdict` 让它自己展开。

    选 `asdict` 是因为**两边字段逐个同名**（2026-10-06 核过，
    `test_留痕.test_闸门两个形状字段逐个同名` 钉着）—— 手抄的话，
    规则层加一个字段，这里静默地少记一格，而留痕里那一栏**看着就是完整的**。
    代价是 pydantic 的默认行为会**忽略多出来的键**，所以那条同名断言是必须的。

    ⚠️ **`降级` 压成 `bool`。** 线上要答的是「这一稿是不是被闸门拦到降级了」；
    降级的去向 `g.去向` 上就有，具体哪道闸门 `g.命中` 上有 ——
    再搬一份 `降级结果` 就是把同一份数据传三遍。
    """
    return schemas.留痕生成(
        主张=主张,
        去向=g.去向,
        调用次数=g.调用次数,
        命中=[schemas.闸门命中(**asdict(h)) for h in g.命中],
        用到的依据=list(g.用到的依据),
        降级=g.降级 is not None,
    )


