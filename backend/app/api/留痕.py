def 开工() -> None:
    """判定入口调一次。

    **顺带把上一次剩的半截清掉**：路由中途抛 409／422 时桶里已经攒了几次
    调用，下一次请求要是接着这个桶往下收，那些调用会记到下一轮头上 ——
    而留痕里看上去就是「这一轮多问了两次模型」。
    """
    收集中.set([])


def 记(
    *,
    响应: schemas.判定响应,
    当前: datetime,
    请求: schemas.判定请求,
    起演格: int | None,
    归属: Mapping[int, str] | None,
    轮消息: Sequence[pipeline.轮消息],
    轮次边界: Sequence[pipeline.轮次],
    六源: Mapping[str, sources.六源结果],
    判成们: Sequence[pipeline.判成],
    生成结果们: Mapping[int, 生成结果],
) -> 留痕记录:
    """把这一轮写进留痕。**全 keyword-only** —— 十来个参数里有一半是
    `Sequence`／`Mapping`，位置传参时把 `轮消息` 和 `轮次边界` 传反了不会报错
    （两个都是 list），而留痕里两栏互换之后**两边都看着像那么回事**。

    `生成结果们` 是 **`{判成下标: 生成结果}`**，`跑话术生成` 的原样 ——
    它只给「走模型的那两种去向」出稿，所以**键是不连续的**，当列表用会错位。

    收模型调用在最后一步：**它必须在 `组响应` 之后**，因为 `话术生成` 那几次
    调用是第 11 步发生的；提前取走的话，最贵的那几次一条都记不上。
    """
    调用 = 收集中.get() or []
    收集中.set(None)  # 取走即清：这一轮的桶到这儿为止

    记录 = 留痕记录(
        会话ID=响应.会话ID,
        轮次=响应.轮次,
        当前=当前,
        请求轮次=请求.轮次,
        看到消息数=请求.看到消息数,
        起演格=起演格,
        顾客情况=tuple(响应.顾客情况),
        安全事件=tuple(响应.安全事件),
        触发=tuple(响应.触发),
        本轮处置=tuple(响应.本轮处置),
        主卡=响应.主卡,
        闸门=tuple(响应.闸门),
        归属=tuple((i, m) for i, m in (归属 or {}).items()),
        # ⚠️ 上面那行**不排序**。`归属` 走的是 dict 的插入序，也就是
        # `归属表` 认出来的顺序（买家消息在会话里的先后）—— 排序之后，
        # 「同一张表跑两遍字节一致」照样过，但重放时喂给 `切轮` 的
        # 那张表**键的遍历顺序变了**，而 `切轮` 的文档串只说「同输入同输出」，
        # 没说「输入顺序无所谓」。留着原样最省事。
        轮消息=tuple(
            schemas.留痕消息(角色=m.角色, 文本=m.文本, 发送时间=m.发送时间)
            for m in 轮消息
        ),
        轮次边界=tuple(
            schemas.留痕边界(
                轮次=i,
                开始时间=r.开始时间,
                结束时间=r.结束时间,
                买家消息=list(r.买家消息),
            )
            for i, r in enumerate(轮次边界, start=1)
        ),
        六源=tuple(_六源条(主张, 结果) for 主张, 结果 in 六源.items()),
        判成=tuple(_判成条(d) for d in 判成们),
        # 按判成下标升序 —— `_生成条` 要从 `判成们` 上取主张，顺序乱了那句
        # 成稿会挂到别人的主张上，而两栏各自看着都正常。
        生成=tuple(
            _生成条(判成们[i].主张, 生成结果们[i]) for i in sorted(生成结果们)
        ),
        模型调用=tuple(
            schemas.留痕调用(
                位=c.位,
                模型=c.模型,
                系统=c.系统,
                提示=c.提示,
                回答=c.回答,
                要JSON=c.要JSON,
                输入token=c.输入token,
                输出token=c.输出token,
            )
            for c in 调用
        ),
    )

    # ⚠️ **脱敏是这一道做的，上面每一格都是原样搬进来的**（`轮消息` 也好、
    # 模型抄回来的 `主张` 也好）。理由见 `_洗过`：一格一格挑着脱漏得掉一格。
    记录 = _洗过(记录)

    with 锁:
        _轮.setdefault(记录.会话ID, {})[记录.轮次] = 记录
        _最近写的[记录.会话ID] = 记录.轮次
    return 记录


def 追加动作(会话ID: str, 事件: 动作事件) -> tuple[动作事件, ...]:
    """记一个按钮，**在同一把锁里追加并回快照**。

    回快照而不是回 `None`：`发送` 那条路要「推完报备单立刻知道它现在什么状态」，
    分开两次取的话，中间夹进来一个请求的结果读到的就不是自己那次写的
    （`台账.记发送` 的原有形状）。
    """
    with 锁:
        流水 = _动作.setdefault(会话ID, [])
        流水.append(_洗过(事件))
        return tuple(流水)


def 追加动作若(
    会话ID: str,
    改: Callable[[tuple[动作事件, ...]], 动作事件 | None],
) -> tuple[动作事件, ...]:
    """**同一把锁里「看一眼流水 → 决定加不加」**，`改` 回 `None` 就是不加。回加完的流水。

    给的是「检查 ＋ 追加」这一对，不是两个分开的函数 —— 那两个函数各自上锁，
    合起来就是一个读-改-写竞态：两个 `POST /发送` 同时进来，两边都看到
    「还没有完成事件」，于是各追加一条，`动作[]` 里就多出一条**客服没做过的事**
    （`台账.推进报备单` 的文档串自己警告着这一条）。旧实现是一把锁里做的，
    改成投影时不能把这个性质丢掉。

    `改` 拿到的是**只读的一份快照**，顺手在里面 `append` 不会生效 ——
    想加东西就把它 `return` 出来。
    """
    with 锁:
        流水 = _动作.setdefault(会话ID, [])
        if (新 := 改(tuple(流水))) is not None:
            流水.append(_洗过(新))
        return tuple(流水)


