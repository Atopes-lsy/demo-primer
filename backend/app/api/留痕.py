# 路由
# ══════════════════════════════════════════════════════════
#
# ⚠️ **路径参数只能叫 `sid` 和 `n`，不能叫 `{会话ID}` / `{轮次}`。**
# `docs/开发步骤.md` 和工单正文写的都是 `{轮次}`，而 Starlette 认参数的
# `PARAM_REGEX` 是 `[a-zA-Z_][a-zA-Z0-9_]*` —— 中文名匹配不上，那一段被当
# **字面量**编进路由正则，`/api/会话/S_DEMO_A/留痕/2` 永远打不通，报错长相是
# 「Not Found」，**看着像路由没挂上**。同一个坑步骤 4 吃过（`api/动作.py` 头部）。


def _会话或404(装: 装载器, 会话ID: str) -> None:
    """这个 ID 存在吗。**不存在 → 404，不是空数组。**

    理由同 `/api/判定` 那条 404：`[]` 和「这个会话什么都没判过」在界面上
    长得一样，而前者是 ID 传错了，排查方向会指向留痕本身。

    ⚠️ **`装.找` 查的是原始会话，判定的入口查的是合并后的窗口 ——
    这两个集合不重合，但「存在性」是重合的。** 窗口 ID 取的是末段 ID
    （`data/顾客窗口`），所以 114 个窗口 ID 一个不落地都在 140 个原始 ID 里
    （2026-10-06 核过）—— 窗口能过的那一关，这里也能过。
    """
    if 装.找(会话ID) is None:
        raise HTTPException(status_code=404, detail=f"没有这个会话：{会话ID}")


def _轮次或409(会话ID: str, n: int) -> 留痕记录:
    """这一轮。**没有 → 409，且要说得出「有哪些」。**

    ⚠️ **409 不是 404。** 会话在、只是这一轮没判过 —— 那不是「地址不对」，
    是「东西还没有」，跟 `动作._存档或409` 是同一条分工。

    ⚠️ **`detail` 里要列出手上的轮次。** 「空结果和没结果长得一样，
    排查方向却相反」：说一句「只有第 [2] 轮」的话，看日志的人立刻知道
    是轮次传错了还是压根没判过。
    """
    记录 = 取(会话ID, n)
    if 记录 is not None:
        return 记录
    有 = [r.轮次 for r in 全部(会话ID)]
    手上 = f"只有第 {有} 轮" if 有 else "一轮都还没判过"
    raise HTTPException(
        status_code=409,
        detail=(
            f"{会话ID} 没有第 {n} 轮的留痕 —— {手上}"
            "。先打 POST /api/判定 判这一轮"
        ),
    )


@router.get(
    "/api/会话/{sid}/留痕",
    response_model=list[schemas.留痕轮次],
    summary="这个会话判过的每一轮",
)
def 查留痕(sid: str, 装: 业务数据) -> list[schemas.留痕轮次]:
    """**按轮次升序**，一轮一条。没有就是空数组（不是 404／409）——
    会话在不在是另一个问题，那一个用 404 回答。"""
    _会话或404(装, sid)
    流水 = 事件(sid)
    return [
        r.到线上([e for e in 流水 if e.轮次 == r.轮次]) for r in 全部(sid)
    ]


@router.get(
    "/api/会话/{sid}/留痕/{n}",
    response_model=schemas.留痕轮次,
    summary="其中一轮的全部产物",
)
def 查一轮(sid: str, n: int, 装: 业务数据) -> schemas.留痕轮次:
    """序号是**从 1 数的轮次号**（`pipeline.切轮` 那个），不是数组下标。"""
    _会话或404(装, sid)
    记录 = _轮次或409(sid, n)
    return 记录.到线上([e for e in 事件(sid) if e.轮次 == 记录.轮次])
