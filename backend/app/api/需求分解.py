"""`POST /api/需求分解` —— 这一趟她要办哪几件事。右栏「这次要什么」那一行的产出者。

# 为什么单开一条路

那一行原来是把**原话攒起来**（`装配.这次要什么`）—— 三次开口就是三句引文连成
一串，其中还夹着「在吗」和「好的，谢谢啦」。2026-10-04 改成让模型拆
（`llm/拆需求.py`）。跑在哪儿是选过的，两个选项各自的代价：

- **塞进 `GET /api/会话列表`**（一次装配 114 个窗口那条路）：那条路现在纯规则、
  18 ms 出结果，加上模型就是 114 次调用排在一个请求里 —— 而且模型没答上来时
  它连「原话」那份都还没给出去。**否掉。**
- **点开哪个窗口就问哪个**（本模块）：一次一个请求，一行一答。延迟落在用户已经
  点进去的那一屏上，而模型没答上来时那一行有原话兜底 —— 列表接口早就给了一份。

# 它不在判定链路上

`api/判定.py` 那六个模型位它一个都不碰，`判成` 里也没有它（归因是 `拆主张` 的
事）。**它产出的是给人看的一行字**，没有任何规则读它 —— 这句话在
`llm/拆需求.py` 的模块文档串里也写了一遍，两处都写是因为最容易的坏法是
「顺手拿它去判点什么」。

# 和列表那条路必须答同一个问题

`GET /api/会话列表` 的顾客情况里已经有一份「这次要什么」（原话）。**不传
`看到几句买家话` 时，两条路切的是同一条会话、同一批买家话、同一个 `已说完`**，
所以模型答上来的那一次，是在同一个输入上换了个产出者 —— 不是「换了个看法」。

对不上的话后果很隐蔽：模型答一句、屏幕换个值，而**没人知道换的是不是同一件事**。
`tests/test_需求分解.py` 里有一条把两边的输入摆在一起核。
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException

from ..data import 装配
from ..data.装载器 import 装载器
from ..rules import pipeline
from . import deps, schemas

router = APIRouter()

业务数据 = Annotated[装载器, Depends(deps.取装载器)]
模型位置 = Annotated[deps.模型位, Depends(deps.取模型位)]

#: 多条需求之间的连接符。**和 `装配.这次要什么` 逐字一致** ——
#: 那个函数把原话连起来用的是它，这边把拆出来的需求连起来也得用它。
#: 两边不一样的话，「模型没答上来」和「答上来了」在屏幕上会是两种观感，
#: 而这一行的值本来该只差内容。
连接符 = " ＋ "

#: 「这次要什么」那一行的标签。**喂给模型时要把它剔掉**（见下面第 4 步）——
#: 它是这一趟的原话，正是要拆的那几句话本身。
这次要什么 = "这次要什么"


@router.post("/api/需求分解", response_model=schemas.需求分解响应, summary="这一趟她要办哪几件事")
def 需求分解(
    请求: schemas.需求分解请求,
    装: 业务数据,
    模型: 模型位置,
) -> schemas.需求分解响应:
    会话 = 装.找(请求.会话ID)
    if 会话 is None:
        # 和 `/api/判定` 同一条规矩：**不返回一个空值了事**。「会话不存在」和
        # 「这一趟她什么都没说」在右栏都是「那一行没变」，但前者是前端传错了 ID。
        raise HTTPException(status_code=404, detail=f"没有这个会话：{请求.会话ID}")

    # 切片和 `判定.整会话顾客情况` 同一句：给进来的是**窗口**时，前面几段是更早的
    # 来访（`顾客窗口._合成窗口`）。给进来的是原始会话（真窗口那条路走的就是它）
    # 时 `起演格` 是 `None`，这一步是空操作 —— 那一段本来就全是这一次来访。
    本次消息 = 会话.消息[会话.起演格 or 0 :]

    # `切轮` 不走模型（`归属` 不给）：这里只关心「她说了哪几句」，轮怎么切不影响
    # 那几句的顺序和内容。和 `整会话顾客情况` 同一个取舍，那边有量过的证据。
    轮们 = pipeline.切轮(装配.轮消息们(本次消息))

    # ⚠️ **切的是买家话，不是消息。** 两边对同一条会话的编号对不上（后端多一条
    # 开头的承诺、剧本多一条现场发的），数条数会在第 1 格就切到空 —— 那种错在
    # 屏幕上和「模型今天不灵」一模一样。见 `需求分解请求.看到几句买家话`。
    全部话 = 装配.本次买家话(轮们, 已说完=False)

    # 「看全了」＝ 这一趟已经过完 ＝ 末句是收场白。**去尾这条规矩住在
    # `本次买家话` 里**，这儿只是按它要的口径把参数传进去，不在路由里再写一遍。
    前几句 = 请求.看到几句买家话
    if 前几句 is None or 前几句 >= len(全部话):
        话们 = 装配.本次买家话(轮们)
    else:
        话们 = 全部话[:前几句]

    # 和 `/api/判定` 第 7 步喂给 `拆主张` 的是同一个形状（`(标签, 值)` 的行）：
    # 「这是谁」「办过什么」这些上下文，是「她那句『那个还没到』指的是哪件事」
    # 的全部依据。
    #
    # ⚠️ **「这次要什么」那一行剔掉。** 它是**这一趟的原话攒起来的**，
    # 而这几句话正是要拆的输入 —— 抄进提示里等于把答案摆在模型眼前让它照抄，
    # 拆出来就是一串引文，正是这一改要摆脱的东西。
    基础行 = 装配.装配顾客情况(会话, 轮们)
    需求 = 模型.拆需求(话们, [(r.标签, r.值) for r in 基础行 if r.标签 != 这次要什么])

    return schemas.需求分解响应(会话ID=请求.会话ID, 值=连接符.join(需求))
