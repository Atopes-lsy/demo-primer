"""演示会话 `S_DEMO_A`／`S_DEMO_B` —— **合成的**，不在赛题数据里。

# 为什么必须另造一份

契约写死了「消息不从请求里传，后端按 `会话ID` 自己查」，而这两个 ID
**不在真数据里**：实测 138 个真实会话全是 `S00001…`。这两个 ID 只活在前端
`frontend/src/data/剧本.ts` 里。不造，`POST /api/判定` 连第一步都过不去。

**为什么不塞进 `data/` 那四份真文件。** 两个好处：「哪些是合成的」一眼能看出来；
`test_装载器_真数据.py` 那边核的是真数据（138/113/80 三个计数），不该被搅动。

# 这里只放事实

消息、订单、工单。**不放判定结论。** `剧本.ts` 每一步的 `改动` 里存着「该出什么
处置」（形态、本轮处置、警示、依据……），那是**验收标准**，不是数据 ——
喂进去等于把被测的东西喂给被测者：链路全写错了右栏照样对。

# 那条 9/25 的承诺消息，是补出来的

`剧本.ts` 把这段历史写成了常量（第 170 行「两条线共用的那段历史」：
承诺 9/25「48 小时内发出」、时限 9/27、今天 9/29），**界面上从来没有过承载它的
消息**。但判定层的 `时限` 只能从消息里解析出来
（`工单交接_给接口线.md` §三：扫客服消息找最晚一条未兑现的承诺并解析出 `时限`），
而 `时限` 空着 = H3 永远不命中 —— 那和「今天没逾期」在界面上**一模一样**。

所以把它补成一条真的客服消息：发送时间取**补发工单的创建时间**（「登记补发」和
「承诺 48 小时」是同一个动作的两半），正文里带上承诺的原文片段。它是事实，
不是期望值：`时限` 仍然要靠装配层解析出来，不是现成写在这儿。

# 和剧本的一处出入

`剧本.ts` 线一的序号是 `1,2,4,5,6,7` —— **第 3 号空着**（第五步「等客服点发送」
没有消息，序号跟着缺了一格）。这里**重编成连续的 1–7**：
`切轮` 和 `已发出的话` 都按序号扫，断号不会报错，只会让某一轮凭空消失。
前端那边的序号不用跟着改，它只是回放的格子，不是契约。
"""

from __future__ import annotations

from typing import Any

from .装载器 import 聊天记录表, 订单表

#: 承诺原文片段。装配层要在客服消息里找它，**两边必须逐字一致** ——
#: 少一个空格就是「找不到承诺」，而那也是「今天没逾期」的样子。
承诺原文片段 = "48 小时内发出"

_店铺 = "测试美妆旗舰店"


def _聊天(
    会话ID: str,
    序号: int,
    发送时间: str,
    角色: str,
    文本: str,
    买家昵称: str,
    *,
    scene_major: str,
    scene_minor: str,
    关联订单号: str,
    关联工单号: str = "",
    署名: str | None = None,
) -> dict[str, Any]:
    """`聊天记录` 工作表的一行。

    `署名` **只在 AI 消息上传**：它是「这句话不是客服说的」的唯一标记，
    `已代发` 靠它挑。给每条都塞一个空串的话，客服自己说的话也会被当成 AI 代发。
    """
    行: dict[str, Any] = {
        "会话ID": 会话ID,
        "消息序号": 序号,
        "message_id": f"{会话ID}.{序号}",
        "发送时间": 发送时间,
        "角色": 角色,
        "买家昵称": 买家昵称,
        "发送方": 买家昵称 if 角色 == "买家" else ("Primer" if 角色 == "AI" else "客服"),
        "店铺": _店铺,
        "scene_major": scene_major,
        "scene_minor": scene_minor,
        # 判定层要分辨「买家最后一句之后有没有人回过」，这个标记就是干这个的。
        "is_target_buyer_message": 1 if 角色 == "买家" else 0,
        "message_text": 文本,
        "内容类型": "文本",
        "chat_content": "[]",
        "category": "service",
        "image_path": None,
        "关联订单号": 关联订单号,
        "关联工单号": 关联工单号,
    }
    if 署名 is not None:
        行["署名"] = 署名
    return 行


