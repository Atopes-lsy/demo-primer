def 并进(表: dict[str, list[dict[str, Any]]]) -> dict[str, list[dict[str, Any]]]:
    """把两条演示会话并进一份真数据表，**返回新表**。

    就地改的话，`读工作簿` 的产物会被改脏 —— 而它下一行就要交给 `装成会话`，
    中间没有第二个人能看见这次污染。

    追加而不是插到前面：`装成会话` 最后按会话 ID 排序，顺序本来就由它定。
    演示的 ID 是 `S_DEMO_*`，排在 `S00001…` 后面，看着也顺。

    **真表里没有的表照样出现**（比如只传了一张聊天记录的空表）——
    缺表当空是 `装成会话` 的约定，这里不替它做主。
    """
    合并 = {名: list(行们) for 名, 行们 in 表.items()}
    for 名, 行们 in 演示表().items():
        合并.setdefault(名, []).extend(行们)
    return 合并
