"""装配层 —— 会话 ＋ 本轮 → `pipeline.顾客情况行` 五行。

# 为什么需要这一层

`pipeline.组装顾客情况` 早就存在，但它的 `基础行` 入参**一直没有产出者**：
全项目 grep 下来只有它自己的定义和调用点。这个模块就是那个产出者。

# 解析放在这里，不放规则层也不放模型

`pipeline.顾客情况行.时限` 的文档串定了这件事：H3 是「纯规则、微秒级」的，
它只能做 `当前时间 > 承诺时限` 比较。而「9/25 承诺『48 小时内发出』」是自然语言 ——
规则解析极脆（「今天」「尽快」都解析不动），LLM 解析又把模型塞到了 H3 前面，
前提就没了。

所以「自然语言 → 结构化」在这层做完，H3 只读一个 `datetime`。

# 三步单向，别把 `警示` 填在这

   阶段 1（本层）：产出基础行，含结构化的 `时限`，**不含 `警示`**
   阶段 2（H3）　：读 `时限`，算出逾期天数
   阶段 3（回填）：`pipeline.组装顾客情况` 把天数写回 `警示`

`警示` 是阶段 3 的产出，本层填了就成环 —— 环的坏处不是死循环（不会），
是**装配层和 H3 各有一份真相**：H3 换了算法，屏幕上还是本层写的那行旧的，
而它看着完全正常。

# 会话级快照 vs 每轮重读

`pipeline.按会话缓存` 钉死了「这是谁」和「这单」是**会话级快照** ——
它们只从 `会话` 取值，不看 `本轮`。所以两轮之间逐字相同。
另外三行每轮重读。**别把五行都当每轮算**：除了浪费，留痕里也解释不了
「为什么这一轮的值和上一轮不同」。

# 已知缺口：「这是谁」推不出会员等级

`31_界面文字清单_给思语.md` §3.2 那张表写的是「老客 · 复购 1 次」，但
**业务数据的 8 张工作表里没有任何会员等级／复购次数的列**（实测过）。
这一行只能给到 `买家昵称`，备注给「上次接触」——那倒是推得出来的
（工单的创建日 ＋ 类型）。

补真值要么等新数据加列，要么由别的层算好传进来。**别在这层写死
「老客 · 复购 1 次」**：那是演示的期望值，不是这份数据的事实，
写死之后换一份数据它照样那么说 —— 而它看着完全正常。
"""

from __future__ import annotations

import re
from datetime import datetime, time, timedelta
from typing import Any, Sequence

from ..api import schemas
from ..rules.permissions import 权限事实
from ..rules.pipeline import 顾客情况行, 轮次, 轮消息

#: 「答应过什么」那一行在五行里的位置 —— 组装时回填 `警示` 找的就是它。
答应过什么 = "答应过什么"

#: 承诺的形状：`48 小时内发出`。**捕获整段**用作「值」里引号中的话术 ——
#: `剧本.ts` 第 190 行 `承诺话术 = '48 小时内发出'`，两边要逐字一致。
#:
#: 只有「N 小时内 ＋ 发出／发货」这一种。窄是刻意的：宽泛的「尽快」「今天」
#: 解析不出确定的时刻，而 `时限` 是个 `datetime`，编一个比留空更坏 ——
#: 留空至少看得出来是「没有未兑现的承诺」。
_承诺 = re.compile(r"(\d+)\s*小时内\s*(?:发出|发货)")

#: 承诺期限落在**当日末**而不是「承诺时刻 ＋ N 小时」。
#:
#: 「48 小时内发出」承诺的是一个**日子**，不是 9/27 15:20 这个**时刻** ——
#: 顾客理解的是「9/27 这天结束前」。`剧本.ts` 第 172 行也是这么倒推的
#: （承诺 9/25 ＋ 48 小时 → 时限 **9/27 24:00**）。
#:
#: 用 `time.max` 而不是 `datetime(2026,9,27,24,0)`：后者看起来更像那句人话，
#: 但 `fromisoformat` 解析不了 24 点，而 `时限` 要以 ISO 串过线。
_当日末 = time(23, 59, 59)

#: 五类工单在「办过什么」里的动词。数据不是 if —— 加一类工单改这里一行。
办过什么动词: dict[str, str] = {
    "补发换货": "补发",
    "线下打款": "打款",
    "物流": "物流处理",
    "不良反应": "不良反应登记",
    "售后退货": "退货",
}


def 轮消息们(消息: list[schemas.ChatMessage]) -> list[轮消息]:
    """`ChatMessage` → `切轮` 收的最小视图。字段名两边一致，逐个搬。

    # 为什么在装配层，不在 `api/判定.py`

    原来它是那边的一个私有函数（`_轮消息们`），2026-10-03 搬到这儿 —— 因为
    用它的人变成了两个：整条判定（`api/判定.py` 第 2、11 步）**和**
    `data/顾客窗口._以前一行`（认前段那一句「要什么」）。放在路由层的话，
    `顾客窗口 → api.判定` 会把数据层反向拖回路由层，而那边还要跑模型、
    动五张表 —— 数据层只该依赖纯函数。

    `切轮` 要的三样（`角色`／`文本`／`发送时间`）`ChatMessage` 全有，
    只是名字不同（`message_text`），所以这里逐个搬而不是直接传。
    """
    return [
        轮消息(角色=m.角色, 文本=m.message_text, 发送时间=m.发送时间) for m in 消息
    ]


def 月日(取值: str) -> str:
    """`2026-09-25 15:20:08` → `9/25`。

    **不补前导零**：`剧本.ts` 的 `承诺日 = '9/25'`、`时限 = '9/27 24:00'`
    都不补，右栏上「9/25 承诺」和「09/25 承诺」是两种观感。解析不动就原样返回 ——
    那说明数据的时间和我们的约定不一样，看得见比看不见好。
    """
    关 = re.match(r"\d{4}-(\d{2})-(\d{2})", 取值 or "")
    return f"{int(关.group(1))}/{int(关.group(2))}" if 关 else (取值 or "")


def _这是谁(会话: schemas.Session) -> 顾客情况行:
    """会话级快照。数据里没有会员等级／复购次数，只给得出昵称（见模块文档串）。"""
    备注 = 会话.店铺
    if 会话.工单 is not None:
        票 = 会话.工单.ticket
        类型 = getattr(票, "工单类型", "") or getattr(票, "问题类型", "")
        备注 = f"上次 {月日(票.创建时间)}" + (f" · {类型}登记" if 类型 else "")
    return 顾客情况行(标签="这是谁", 值=会话.买家昵称 or "（无昵称）", 备注=备注)


def 本轮买家原话(轮: 轮次 | None) -> str:
    """一轮里买家说的话，多条连发用 ` ＋ ` 连起来；没有买家发言写「无」。

    **「一轮」的口径**，不是「一次来访」的口径 —— 后者是 `这次要什么`。
    用它的是 `顾客窗口._以前一行`：每一段历史取一行（2026-10-04 起那几行只
    进接口返回、不上屏）。

    没有买家发言时写「无」而不是「（本轮没有买家发言）」（2026-10-03 改）：
    这一格是**值**，顾客情况里没有买家发言就是没有；带括号那句是把内部状态
    说给顾客听。真数据里 `S2` 那种只有一条系统推送的会话就吃这一支 ——
    系统推送不是顾客说的话，拿它顶上等于右栏替顾客编了一句诉求。
    """
    if 轮 is None or not 轮.买家消息:
        return "无"
    return " ＋ ".join(轮.买家消息)


def 本次买家话(轮们: Sequence[轮次] | None, *, 已说完: bool = True) -> list[str]:
    """**本次来访**买家说过的话，**一句一条**。

    `这次要什么` 的值就是这几句连起来的；`POST /api/需求分解` 交给模型拆的
    也是这几句。**两处同源是刻意的**（2026-10-04 抽出来）：模型那条路要是
    自己再切一遍，模型坏了回落到原话时，屏幕上那行和模型收到的输入就不是
    同一批话 —— 而那种错看着只是「模型今天不灵」。

    `已说完` 的含义写在 `这次要什么` 那边（去尾）。空列表 ＝ 本次来访
    没有买家发言，**不是错误状态**（空会话、只有客服开场的会话都走这一支）。
    """
    句们 = [句 for 轮 in (轮们 or ()) for 句 in 轮.买家消息]
    if 已说完:
        # `or 句们` 就是「至少留一句」：只剩一条买家消息的来访，去掉就没东西了。
        句们 = 句们[:-1] or 句们
    return 句们


def 这次要什么(轮们: Sequence[轮次] | None, *, 已说完: bool = True) -> 顾客情况行:
    """**本次来访**买家说过的话，攒起来 —— 这次来访已经说完的话，最后一句去掉。

    「本次来访」是哪几轮由调用方切好（`api/判定.py` 按 `起演格` 切，
    窗口里前面几段是更早的来访，不算这一次）。

    # `已说完`：**这一路答的是「已经过去的一次来访」还是「正在走的这一轮」**

    默认真（列表页：来过的次数、说的话都已经在数据里了）。`POST /api/判定`
    传假 —— 它一轮一答，答的是「她此刻说到哪儿了」，这时候最后一句
    **正是要靠它办事的那句**，去掉就是把最新的诉求从屏幕上抹掉。

    # 为什么是「攒」不是「最近一句」（2026-10-04 改）

    最近一句在真数据上是坏的：**24 个「来过不止一次」的窗口，最后一次来访的
    最后一条买家消息 24/24 全是收场白**（谢谢／好／麻烦了／收到／行吧行吧／
    等你们消息）。照最近一句取，这一行整列都是一句道谢，顾客真正提过的事
    一句都不在里面 —— 判定答得再对也没用，右栏上就是「懂了，谢谢美女呢」。

    # 去尾：只看位置，不查词、不跑模型

    「收场白」本来是语义，词表挡不住（「好了」是收场白，「好了，我寄回去了」
    不是）。这里退一步用位置：**一次来访的最后一句是收场白**。
    24/24 成立。代价写在这儿 —— **这条对还在进行中的会话是偏的**：
    她刚说完、客服还没接的那句会被当成收场白去掉。今天不吃这个亏
    （真接口喂的全是已经说完的历史窗口，演示线那一行走剧本），
    以后真接活会话，判据得重挑（大概是「这一轮有没有客服接过话」）。

    **至少留一句**：只剩一条买家消息时留着它，不切成空。单段窗口里不少见 ——
    攒空了会把「无」当成她的诉求显示出来。

    # 谁读这一行的值

    **没有规则读它。** `pipeline.个体差异所在行` 只认「这是谁」，为什么
    不认这一行写在那边（把上一件事的属性染到下一件事上，实测过）。

    # 这是**回落值**（2026-10-04 起）

    右栏那一行现在默认由模型拆（`llm.拆需求`，走 `POST /api/需求分解`）。
    模型够不着、答得不成样子、或者那次压根没问，屏幕上都落回这一份 ——
    所以它没退休，**它是兜底**。两边的输入是同一批话（`本次买家话`）。
    """
    句们 = 本次买家话(轮们, 已说完=已说完)
    if not 句们:
        return 顾客情况行(标签="这次要什么", 值="无")
    return 顾客情况行(标签="这次要什么", 值=" ＋ ".join(句们))


def _未兑现(
    会话: schemas.Session,
    关联工单号: str,
    票表: dict[str, schemas.TaggedTicket] | None = None,
) -> bool:
    """那条承诺兑现了没有。

    目前只有一种判定得动的情况：承诺挂在**补发换货工单**上，而那张工单的
    `补发物流单号` 还空着 —— 就是还没发出，承诺没兑现。

    # `票表` 是认**前段**承诺的唯一依据（2026-10-03 加）

    一条窗口是多段拼起来的（`data/顾客窗口.py`），而承诺消息挂的
    `关联工单号` 可能是**上一次来访**那张工单。不传 `票表` 时这里只看得见
    `会话.工单`（末段那张），号对不上就落到下面「当作未兑现」那条 ——
    实测**有三个真实窗口因此报出假逾期**：上一次的补发早就发出去了，
    屏幕上却说「答应过的没做到」。

    `票表` 是该窗口**所有段**的工单（`工单号 → 标好的工单`），
    传进来就先按号认票，认到了就不看它挂在哪一段上。

    号认不到、或者认到的那张不是补发换货单时**当作未兑现**：
    逾期报出来最多是虚报一次，漏报则是「答应过的没做到」被静默吞掉 ——
    后者才是这个产品要解决的问题。
    """
    工单 = 会话.工单
    if 票表 and 关联工单号:
        # 号空着不查：空号不是键，`票表.get("")` 不该被当成一次命中。
        工单 = 票表.get(关联工单号) or 工单
    if 工单 is None or 工单.kind != "补发换货":
        return True
    if 关联工单号 and getattr(工单.ticket, "工单号", "") != 关联工单号:
        return True
    return not getattr(工单.ticket, "补发物流单号", "")


def _答应过什么(
    会话: schemas.Session,
    票表: dict[str, schemas.TaggedTicket] | None = None,
) -> 顾客情况行:
    """在**客服已经发出去的话**里找最晚一条还没兑现的承诺。

    为什么扫消息而不是查别的表：承诺是客服**说出口**的，说出口才成立。
    工单／订单说的是「办了什么」，承诺说的是「答应了什么」——
    `docs/一句话进来的流程.md` §1.1 把这两件事分成了两行。

    ⚠️ 「最晚一条」按 `消息序号` 排，不按数据到达顺序：xlsx 的行序不保证
    等于消息序（`装载器` 那边专门排过一道）。

    ⚠️ 只看**客服**。AI 不能许诺时限（口径表 K05）—— 它那几条安抚话术
    正文里一个时间词都没有，把它算进来的话，`已代发` 那句
    「亲实在抱歉让您久等…尽快答复您～」会被找出一条并不存在的承诺。
    """
    for 条 in sorted(会话.消息, key=lambda m: m.消息序号, reverse=True):
        if 条.角色 != "客服":
            continue
        关 = _承诺.search(条.message_text or "")
        if 关 is None or not _未兑现(会话, 条.关联工单号, 票表):
            continue
        小时 = int(关.group(1))
        承诺时刻 = 解析时间(条.发送时间)
        if 承诺时刻 is None:
            continue
        到期 = 承诺时刻 + timedelta(hours=小时)
        return 顾客情况行(
            标签=答应过什么,
            值=f"{月日(条.发送时间)} 承诺「{关.group(0)}」",
            时限=datetime.combine(到期.date(), _当日末).isoformat(),
        )

    # 没有未兑现的承诺是**合法状态**（新会话就是这样进来的），不是坏了。
    return 顾客情况行(标签=答应过什么, 值="没有未兑现的承诺")


def 解析时间(取值: str) -> datetime | None:
    """`2026-09-25 15:20:08` → `datetime`。解析不动返回 `None`，
    **不编一个当前时间顶上** —— 那会造出一条不存在的承诺。"""
    try:
        return datetime.fromisoformat((取值 or "").replace(" ", "T", 1))
    except ValueError:
        return None


def 办过什么(会话: schemas.Session) -> 顾客情况行:
    """`会话.工单`。五类工单各有各的「状态」列名，取不到就认 `任务状态`
    （`schemas.ReshipTicket.工单状态` 的文档串记着这件事，不归一化）。"""
    工单 = 会话.工单
    if 工单 is None:
        return 顾客情况行(标签="办过什么", 值="没有工单记录")

    票 = 工单.ticket
    if 工单.kind == "补发换货":
        # 补发的「办到哪了」就是发没发出去 —— 状态列写「待发货」，
        # 而顾客关心的是「发出没有」。
        状态 = "已发出" if getattr(票, "补发物流单号", "") else "未发出"
    else:
        状态 = getattr(票, "工单状态", "") or getattr(票, "任务状态", "") or "处理中"

    动词 = 办过什么动词.get(工单.kind, 工单.kind)
    return 顾客情况行(
        标签="办过什么",
        值=f"{月日(票.创建时间)} 已登记{动词} · {状态}",
        备注=f"工单 {getattr(票, '工单号', '')}",
    )


def _这单(会话: schemas.Session) -> 顾客情况行:
    """会话级快照。订单状态**跟着数据走**，不写死 ——
    写死的话改订单就要回来找这一行，而它藏在这层里，最容易漏。"""
    订单 = 会话.订单
    if 订单 is None:
        return 顾客情况行(标签="这单", 值="没有订单记录", 备注=会话.店铺)
    金额 = f"¥{订单.实付金额元:g}"
    return 顾客情况行(
        标签="这单",
        值=f"{订单.订单号} · {金额} · {订单.订单状态}",
        备注=f"{订单.商品货号} {订单.商品名称}",
    )


def 装配顾客情况(
    会话: schemas.Session,
    轮们: Sequence[轮次] | None,
    票表: dict[str, schemas.TaggedTicket] | None = None,
    *,
    已说完: bool = True,
) -> list[顾客情况行]:
    """五行，顺序照 `pipeline.顾客情况五行`，**顺序不能改**。

    `轮们` 是**本次来访**的轮（切到哪儿由调用方定），只有「这次要什么」用得到；
    给 `None` 或空表示「没有可判的轮」（空会话、纯客服开场的会话）——
    这不是错误状态，五行照样出得来，只是「这次要什么」会说没有买家发言。
    `已说完` 一并转给它，含义写在那边。

    # `票表` 是可选的第三参，默认 `None`

    给得出「这个人的所有来访」时才传（`GET /api/会话列表` 传，
    `POST /api/判定` 不传 —— 那条路拿到的本来就只有一段，见 `路由.py`）。
    不传时行为**和加这个参数之前逐字相同**：只看 `会话.工单`，
    也就是「这次来访」那张。所以 `test_装配.py` 里那些两个参数的调法不用动。
    """
    return [
        _这是谁(会话),
        这次要什么(轮们, 已说完=已说完),
        _答应过什么(会话, 票表),
        办过什么(会话),
        _这单(会话),
    ]


def 取承诺时限(行们: list[顾客情况行]) -> datetime | None:
    """从五行里取「答应过什么」的 `时限`，给 `triggers.H3逾期` 用。

    解析留在这层（它本来就是干「自然语言 → 结构化」的），路由层只拿结果 ——
    路由不该知道 `时限` 是个 ISO 串还是个 `datetime`。
    """
    行 = next((r for r in 行们 if r.标签 == 答应过什么), None)
    if 行 is None or not 行.时限:
        return None
    try:
        return datetime.fromisoformat(行.时限)
    except ValueError:
        # 本层自己产的 ISO 串解析不动，说明有人手改过它。返回 None 会让 H3
        # 静默放过一条已逾期的承诺 —— 但那比抛异常好：抛异常整条判定链断掉，
        # 右栏全空，而演示现场没有时间读 traceback。
        return None


def 取权限事实(会话: schemas.Session) -> 权限事实:
    """从会话数据里算出第 2 层比额度要用的三个事实，给 `permissions.查权限` 用。

    和 `取承诺时限` 同一个套路：**自然语言 → 结构化**在这层做完，规则层只读数。
    区别是它读的是工单表（那边读的是顾客情况那一行）。

    # 三个维度的来源，以及为什么是这三个

    | 维度 | 来源 | 为什么是它 |
    |---|---|---|
    | `件数` | `ReshipTicket.数量` | 工单上就是「这次补发／换货几件」，是 `限额件数` 唯一对得上的列 |
    | `金额` | `PayoutTicket.退款金额元` | `L08 小额退款` 比的是**这次退多少**，不是这单买了多少钱 |
    | `质量问题` | `ReshipTicket.售后原因` 含「质量」 | 2026-10-04 拍的口径，见下 |

    `数量` 只有 `ReshipTicket` 有、`售后原因` 也是，所以下面两个 `getattr`
    **天然限定在补发换货单上**，物流／不良反应／售后退货／线下打款那四类取不到
    —— 它们各自有别的列（`LogisticsTicket` 整张表没有数量列），取到 `None`
    正是「不知道」，不是「0」。这是 `权限事实` 三态要的。

    # 金额**不拿 `Order.实付金额元` 顶替**

    那是这单买了多少钱，不是这次退多少。拿它顶替的话，200 元的单退 5 元也会
    被判成超 100 的限额 —— **凭空造出来的超额度**，而超额度要走报备／转交。
    没有退款金额的工单就留在 `None`（判不了 → 报备），别猜。

    # 质量问题：含「质量」才算，`False` 和 `None` 分开

    2026-10-04 拍的口径：售后原因里**含「质量」两个字**才认。所以
    「换货-到手破损」判 `False`（这条不是按质量问题立的单），不是 `True` ——
    「破损该不该算质量问题」是一句业务口径，没人拍过。
    没有这一列（如物流工单）时才给 `None`，那才是「不知道」。

    # 工单状态不看

    单子已经办完（已发出／已完结）不改变「这一单涉及几件」这个事实，
    所以这里不按状态过滤。要改成只看未结单的话，改这一处就够。
    """
    工单 = 会话.工单
    if 工单 is None:
        return 权限事实()

    票 = 工单.ticket
    原因 = getattr(票, "售后原因", None)
    return 权限事实(
        件数=getattr(票, "数量", None),
        金额=getattr(票, "退款金额元", None),
        质量问题=None if not 原因 else ("质量" in 原因),
    )
