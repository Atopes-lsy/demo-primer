"""装配层 —— 会话 ＋ 本轮 → `pipeline.顾客情况行` 五行。

# 为什么需要这一层

`pipeline.组装顾客情况` 早就存在，但它的 `基础行` 入参**一直没有产出者**：
全项目 grep 下来只有它自己的定义和调用点。这个模块就是那个产出者。

# 解析放在这里，不放规则层也不放模型

`pipeline.顾客情况行.时限` 的文档串定了这件事：H3 是「纯规则、微秒级」的，
它只能做 `当前时间 > 承诺时限` 比较。而「9/25 承诺『48 小时内发出』」是自然语言 ——
规则解析极脆（「今天」「尽快」都解析不动），LLM 解析又把模型塞到了 H3 前面，
前提就没了。

所以「自然语言 → 结构化」在这层做完，H3 只读一个 `datetime`。

# 三步单向，别把 `警示` 填在这

   阶段 1（本层）：产出基础行，含结构化的 `时限`，**不含 `警示`**
   阶段 2（H3）　：读 `时限`，算出逾期天数
   阶段 3（回填）：`pipeline.组装顾客情况` 把天数写回 `警示`

`警示` 是阶段 3 的产出，本层填了就成环 —— 环的坏处不是死循环（不会），
是**装配层和 H3 各有一份真相**：H3 换了算法，屏幕上还是本层写的那行旧的，
而它看着完全正常。

# 会话级快照 vs 每轮重读

`pipeline.按会话缓存` 钉死了「这是谁」和「这单」是**会话级快照** ——
它们只从 `会话` 取值，不看 `本轮`。所以两轮之间逐字相同。
另外三行每轮重读。**别把五行都当每轮算**：除了浪费，留痕里也解释不了
「为什么这一轮的值和上一轮不同」。

# 已知缺口：「这是谁」推不出会员等级

`31_界面文字清单_给思语.md` §3.2 那张表写的是「老客 · 复购 1 次」，但
**业务数据的 8 张工作表里没有任何会员等级／复购次数的列**（实测过）。
这一行只能给到 `买家昵称`，备注给「上次接触」——那倒是推得出来的
（工单的创建日 ＋ 类型）。

补真值要么等新数据加列，要么由别的层算好传进来。**别在这层写死
「老客 · 复购 1 次」**：那是演示的期望值，不是这份数据的事实，
写死之后换一份数据它照样那么说 —— 而它看着完全正常。
"""

from __future__ import annotations

import re
from datetime import datetime, time, timedelta
from typing import Any

from ..api import schemas
from ..rules.pipeline import 顾客情况行, 轮次

#: 「答应过什么」那一行在五行里的位置 —— 组装时回填 `警示` 找的就是它。
答应过什么 = "答应过什么"

#: 承诺的形状：`48 小时内发出`。**捕获整段**用作「值」里引号中的话术 ——
#: `剧本.ts` 第 190 行 `承诺话术 = '48 小时内发出'`，两边要逐字一致。
#:
#: 只有「N 小时内 ＋ 发出／发货」这一种。窄是刻意的：宽泛的「尽快」「今天」
#: 解析不出确定的时刻，而 `时限` 是个 `datetime`，编一个比留空更坏 ——
#: 留空至少看得出来是「没有未兑现的承诺」。
_承诺 = re.compile(r"(\d+)\s*小时内\s*(?:发出|发货)")

#: 承诺期限落在**当日末**而不是「承诺时刻 ＋ N 小时」。
#:
#: 「48 小时内发出」承诺的是一个**日子**，不是 9/27 15:20 这个**时刻** ——
#: 顾客理解的是「9/27 这天结束前」。`剧本.ts` 第 172 行也是这么倒推的
#: （承诺 9/25 ＋ 48 小时 → 时限 **9/27 24:00**）。
#:
#: 用 `time.max` 而不是 `datetime(2026,9,27,24,0)`：后者看起来更像那句人话，
#: 但 `fromisoformat` 解析不了 24 点，而 `时限` 要以 ISO 串过线。
_当日末 = time(23, 59, 59)

#: 五类工单在「办过什么」里的动词。数据不是 if —— 加一类工单改这里一行。
办过什么动词: dict[str, str] = {
    "补发换货": "补发",
    "线下打款": "打款",
    "物流": "物流处理",
    "不良反应": "不良反应登记",
    "售后退货": "退货",
}


def _月日(取值: str) -> str:
    """`2026-09-25 15:20:08` → `9/25`。

    **不补前导零**：`剧本.ts` 的 `承诺日 = '9/25'`、`时限 = '9/27 24:00'`
    都不补，右栏上「9/25 承诺」和「09/25 承诺」是两种观感。解析不动就原样返回 ——
    那说明数据的时间和我们的约定不一样，看得见比看不见好。
    """
    关 = re.match(r"\d{4}-(\d{2})-(\d{2})", 取值 or "")
    return f"{int(关.group(1))}/{int(关.group(2))}" if 关 else (取值 or "")


def _这是谁(会话: schemas.Session) -> 顾客情况行:
    """会话级快照。数据里没有会员等级／复购次数，只给得出昵称（见模块文档串）。"""
    备注 = 会话.店铺
    if 会话.工单 is not None:
        票 = 会话.工单.ticket
        类型 = getattr(票, "工单类型", "") or getattr(票, "问题类型", "")
        备注 = f"上次 {_月日(票.创建时间)}" + (f" · {类型}登记" if 类型 else "")
    return 顾客情况行(标签="这是谁", 值=会话.买家昵称 or "（无昵称）", 备注=备注)


def _这次要什么(本轮: 轮次 | None) -> 顾客情况行:
    """本轮买家原话。多条连发用 ` ＋ ` 连起来 —— 那正是 H2 要看的形状。"""
    if 本轮 is None or not 本轮.买家消息:
        return 顾客情况行(标签="这次要什么", 值="（本轮没有买家发言）")
    return 顾客情况行(标签="这次要什么", 值=" ＋ ".join(本轮.买家消息))


def _未兑现(会话: schemas.Session, 关联工单号: str) -> bool:
    """那条承诺兑现了没有。

    目前只有一种判定得动的情况：承诺挂在**补发换货工单**上，而那张工单的
    `补发物流单号` 还空着 —— 就是还没发出，承诺没兑现。

    关联的工单不在这条会话上、或者不是补发换货单时**当作未兑现**：
    逾期报出来最多是虚报一次，漏报则是「答应过的没做到」被静默吞掉 ——
    后者才是这个产品要解决的问题。
    """
    工单 = 会话.工单
    if 工单 is None or 工单.kind != "补发换货":
        return True
    if 关联工单号 and getattr(工单.ticket, "工单号", "") != 关联工单号:
        return True
    return not getattr(工单.ticket, "补发物流单号", "")


def _答应过什么(会话: schemas.Session) -> 顾客情况行:
    """在**客服已经发出去的话**里找最晚一条还没兑现的承诺。

    为什么扫消息而不是查别的表：承诺是客服**说出口**的，说出口才成立。
    工单／订单说的是「办了什么」，承诺说的是「答应了什么」——
    `docs/一句话进来的流程.md` §1.1 把这两件事分成了两行。

    ⚠️ 「最晚一条」按 `消息序号` 排，不按数据到达顺序：xlsx 的行序不保证
    等于消息序（`装载器` 那边专门排过一道）。

    ⚠️ 只看**客服**。AI 不能许诺时限（口径表 K05）—— 它那几条安抚话术
    正文里一个时间词都没有，把它算进来的话，`已代发` 那句
    「亲实在抱歉让您久等…尽快答复您～」会被找出一条并不存在的承诺。
    """
    for 条 in sorted(会话.消息, key=lambda m: m.消息序号, reverse=True):
        if 条.角色 != "客服":
            continue
        关 = _承诺.search(条.message_text or "")
        if 关 is None or not _未兑现(会话, 条.关联工单号):
            continue
        小时 = int(关.group(1))
        承诺时刻 = _解析时间(条.发送时间)
        if 承诺时刻 is None:
            continue
        到期 = 承诺时刻 + timedelta(hours=小时)
        return 顾客情况行(
            标签=答应过什么,
            值=f"{_月日(条.发送时间)} 承诺「{关.group(0)}」",
            时限=datetime.combine(到期.date(), _当日末).isoformat(),
        )

    # 没有未兑现的承诺是**合法状态**（新会话就是这样进来的），不是坏了。
    return 顾客情况行(标签=答应过什么, 值="没有未兑现的承诺")


def _解析时间(取值: str) -> datetime | None:
    """`2026-09-25 15:20:08` → `datetime`。解析不动返回 `None`，
    **不编一个当前时间顶上** —— 那会造出一条不存在的承诺。"""
    try:
        return datetime.fromisoformat((取值 or "").replace(" ", "T", 1))
    except ValueError:
        return None


def _办过什么(会话: schemas.Session) -> 顾客情况行:
    """`会话.工单`。五类工单各有各的「状态」列名，取不到就认 `任务状态`
    （`schemas.ReshipTicket.工单状态` 的文档串记着这件事，不归一化）。"""
    工单 = 会话.工单
    if 工单 is None:
        return 顾客情况行(标签="办过什么", 值="没有工单记录")

    票 = 工单.ticket
    if 工单.kind == "补发换货":
        # 补发的「办到哪了」就是发没发出去 —— 状态列写「待发货」，
        # 而顾客关心的是「发出没有」。
        状态 = "已发出" if getattr(票, "补发物流单号", "") else "未发出"
    else:
        状态 = getattr(票, "工单状态", "") or getattr(票, "任务状态", "") or "处理中"

    动词 = 办过什么动词.get(工单.kind, 工单.kind)
    return 顾客情况行(
        标签="办过什么",
        值=f"{_月日(票.创建时间)} 已登记{动词} · {状态}",
        备注=f"工单 {getattr(票, '工单号', '')}",
    )


def _这单(会话: schemas.Session) -> 顾客情况行:
    """会话级快照。订单状态**跟着数据走**，不写死 ——
    写死的话改订单就要回来找这一行，而它藏在这层里，最容易漏。"""
    订单 = 会话.订单
    if 订单 is None:
        return 顾客情况行(标签="这单", 值="没有订单记录", 备注=会话.店铺)
    金额 = f"¥{订单.实付金额元:g}"
    return 顾客情况行(
        标签="这单",
        值=f"{订单.订单号} · {金额} · {订单.订单状态}",
        备注=f"{订单.商品货号} {订单.商品名称}",
    )


def 装配顾客情况(会话: schemas.Session, 本轮: 轮次 | None) -> list[顾客情况行]:
    """五行，顺序照 `pipeline.顾客情况五行`，**顺序不能改**。

    `本轮` 给 `None` 表示「没有可判的轮」（空会话、纯客服开场的会话）——
    这不是错误状态，五行照样出得来，只是「这次要什么」会说没有买家发言。
    """
    return [
        _这是谁(会话),
        _这次要什么(本轮),
        _答应过什么(会话),
        _办过什么(会话),
        _这单(会话),
    ]


def 取承诺时限(行们: list[顾客情况行]) -> datetime | None:
    """从五行里取「答应过什么」的 `时限`，给 `triggers.H3逾期` 用。

    解析留在这层（它本来就是干「自然语言 → 结构化」的），路由层只拿结果 ——
    路由不该知道 `时限` 是个 ISO 串还是个 `datetime`。
    """
    行 = next((r for r in 行们 if r.标签 == 答应过什么), None)
    if 行 is None or not 行.时限:
        return None
    try:
        return datetime.fromisoformat(行.时限)
    except ValueError:
        # 本层自己产的 ISO 串解析不动，说明有人手改过它。返回 None 会让 H3
        # 静默放过一条已逾期的承诺 —— 但那比抛异常好：抛异常整条判定链断掉，
        # 右栏全空，而演示现场没有时间读 traceback。
        return None
