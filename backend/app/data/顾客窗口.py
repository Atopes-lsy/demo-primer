"""按顾客合并会话 —— 同一个人多次来访，写进**一个**窗口。

# 为什么要有这一层

`顾客情况` 那五行本来就是**以前的会话攒出来的**：「这是谁」的备注写着
「上次 5/6 · 补发登记」、「答应过什么」扫的是客服历史上许过的诺、
「办过什么」「这单」读的是挂在会话上的工单和订单。可数据是**按会话**给的 ——
同一个人在 5/5、5/7、5/9 来了三次，左栏就是三条互不相干的记录，
看不出那是同一个人，那五行的「历史」也就没有出处。

实测：138 条真会话只有 **112 个不同 `买家昵称`**，其中 **24 个昵称有 2–3 条
会话**（共 50 条），**88 个只有一条**。合并后左栏 112 行（＋两条演示线）。

# 为什么在**路由层**合，不在装载器里合

`装载器` 是这份数据的**原始真相**：`tests/test_装载器_真数据.py` 拿它钉 138／
998／113／80，`POST /api/判定` 靠 `装.找(会话ID)` 取会话。把合并放进去的话，
**26 个非末段 ID 会从 `装.找()` 里静默消失** —— 而那句话没有任何东西拦得住，
错误是安静的。所以合并只发生在「读出来渲染成列表」这一步。

# 窗口 ID 取**末段**的会话 ID，这是有意的

`装载器.找(会话ID)`、`api/台账.py` 的存档键（`_存档` 按会话 ID）、
`api/动作.py` 全按会话 ID 索引。取末段就不用加任何一层 ID 映射。

**代价要记住**：`POST /api/判定` 对合并窗口只能看见**末段**（`装.找` 返回的是
那条原始会话）。今天无害 —— 138 条真会话走的是「还没跑判定」那条路，按钮根本
不显示 —— 但接真实判定之前必须先决定「判窗口还是判段」。

# 窗口里的消息，序号是重编过的

原始数据里 `消息序号` **每个会话各自 1..n**（实测 138/138 如此）。直接拼接会
重号，而 `装配._答应过什么` 正是靠 `sorted(key=消息序号, reverse=True)` 找
「最晚一条承诺」—— 不重编就会把三段的消息交错着排，挑出错的承诺。

# 只读

本模块**不碰** `装载器.py`，也不改传进来的任何 `Session`（逐条 `model_copy`）。
`GET /api/会话列表` 靠这条保证装载器里那份永远是干净的。
"""

from __future__ import annotations

from collections import defaultdict
from typing import Any

from ..api import schemas
from ..rules import pipeline
from . import 装配

#: 一条窗口的票表：`工单号 → 标好的工单`。**该窗口所有段**的工单，不只是末段的。
#:
#: 它是 `装配._未兑现` 认前段承诺的唯一依据 —— 见那个函数的文档串，
#: 没有它的话有三个真实窗口会报出假逾期。
票表类型 = dict[str, schemas.TaggedTicket]


def _段序(会话: schemas.Session) -> tuple[str, str]:
    """组内排序键：先按 `最近时间`，再按会话 ID 兜底。

    `最近时间` 理论上不会并列（实测真数据里没出现过），但**并列时不能靠
    `sorted` 的稳定性**：那取决于输入顺序，而输入顺序来自 `装载器` 的分组，
    是另一件事。并列了就用 ID 定一个确定的先后 —— 谁在末段是个**语义**
    （窗口 ID、「这单」「办过什么」全取它），不能靠运气。
    """
    return (会话.最近时间 or "", 会话.会话ID)


def _以前一行(段: schemas.Session) -> schemas.以前会话:
    """一段历史 → 「以前来过」里的一行。

    三样都是从**现成的纯函数**里取的，不另写判断：

    - `要什么` 走 `装配.这次要什么`，喂的是那一段的**第一轮** ——
      不用「第一条买家消息」（真数据里大量会话第一句是「在吗」），
      也不用末轮（实测 `S00034` 的末轮是道谢，放上去等于没说）。
    - `办过什么` 走 `装配.办过什么`，和五行第三行**同一个函数、同一张动词表**。
      那一段没有工单时留空，不留「没有工单记录」：这一块是总结，空着比占一行实话。
    """
    轮们 = pipeline.切轮(装配.轮消息们(段.消息))
    要什么 = 装配.这次要什么(轮们[0] if 轮们 else None)

    办过: str | None = None
    工单号: str | None = None
    if 段.工单 is not None:
        办过 = 装配.办过什么(段).值
        工单号 = getattr(段.工单.ticket, "工单号", "") or None

    return schemas.以前会话(
        日期=装配.月日(段.最近时间 or ""),
        要什么=要什么.值,
        办过什么=办过,
        工单号=工单号,
    )


def _票表(段们: list[schemas.Session]) -> 票表类型:
    """这一段里所有工单，按工单号索引。号空的不进 —— 索引不到它，白占一个键。"""
    表: 票表类型 = {}
    for 段 in 段们:
        if 段.工单 is None:
            continue
        if 号 := getattr(段.工单.ticket, "工单号", ""):
            表[号] = 段.工单
    return 表


def _合成窗口(段们: list[schemas.Session]) -> schemas.Session:
    """多段 → 一个窗口。

    身份字段（`会话ID`／`订单`／`工单`／`店铺`／`stage`／`摘要`／`最近时间`／
    `未读`）**全取末段**：「这单」「办过什么」说的是**这一次**来访，
    更早那几次的工单存在于「以前来过」那一块里（和票表里）。

    更早那几段的**消息**则全部接在前面 —— 那是「写在一个对话窗口里」的字面意思，
    也是「演示从最后一次会话开始」（`起演格`）能成立的前提。
    """
    末段 = 段们[-1]
    前段们 = 段们[:-1]

    消息 = [m for 段 in 段们 for m in 段.消息]
    重编号 = [m.model_copy(update={"消息序号": 序}) for 序, m in enumerate(消息, start=1)]

    return 末段.model_copy(
        update={
            "消息": 重编号,
            "以前": [_以前一行(段) for 段 in 前段们],
            "起演格": sum(len(段.消息) for 段 in 前段们),
        }
    )


def 合并窗口(
    会话们: list[schemas.Session],
) -> tuple[list[schemas.Session], dict[str, 票表类型]]:
    """会话列表 → （窗口列表，`窗口ID → 票表`）。

    **按 `买家昵称` 分组**，组内按 `最近时间` 升序，末段那个当窗口的身份。

    # 昵称是唯一能用的身份键，这是本方案接受的风险

    数据里**没有买家 ID 之类更强的键**（8 张工作表都翻过），而昵称本身是
    `魏h**` 这种打码形式 —— 理论上两个不同的人可能撞成一个窗口。真接上业务
    系统时该换成买家 ID，那之前只能按昵称认。

    好在同一昵称下的 `店铺` **实测 24/24 组完全一致**，没有把两家店的人并到
    一起这种情况。

    # 单段组也要过一道 `model_copy`

    `以前=[]`、`起演格=0` 得**由这一层写出来**，不能指望「字段默认是 `None`，
    前端自己兜」—— 前端靠 `undefined` 区分「这一份是剧本兜的底」（整块不渲染）
    和「接口说了没有历史」（渲染「无」）。写 `None` 的话两者长得一样，
    演示两条线的卡片会凭空多出一块「无」。

    # 顺序

    按**窗口 ID**（＝末段 ID）排。输入是 `装载器` 按会话 ID 排好的，但分组之后
    窗口的身份是末段，再按输入的先后排就和返回的 ID 对不上了。
    """
    组: dict[str, list[schemas.Session]] = defaultdict(list)
    for 会话 in 会话们:
        组[会话.买家昵称].append(会话)

    窗口们, 表 = [], {}
    for 段们 in 组.values():
        段们.sort(key=_段序)
        窗口 = 段们[-1].model_copy(update={"以前": [], "起演格": 0}) if len(段们) == 1 else _合成窗口(段们)
        窗口们.append(窗口)
        表[窗口.会话ID] = _票表(段们)

    窗口们.sort(key=lambda s: s.会话ID)
    return 窗口们, 表
