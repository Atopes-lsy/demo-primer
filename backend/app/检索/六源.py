"""六个来源逐个查 —— 三层判定第 1 层「系统确认得了吗」的输入。

# 这一层判的是「记不记」，不是「判成什么」

相关性判断发生在**记录产不产生**这一步：不相关就不进 `记录`。所以出去的每一条
都是 `exists=True`、`用上=True`，不存在 `exists=False` 的占位记录
—— 那种记录是「为了凑 `N/6` 硬塞」的产物，而它的后果不对称：

- `用上` 填错只是分数虚高（右栏多显示一条依据）
- `exists` 填错是**放行一条没依据的话**

所以口径一律「宁缺勿滥」：多记一条只是好看，少记一条是第 1 层判成「查不到」
→ 落客服点发送 → 保守但安全。**认不出就不记。**

# 四个源怎么查

| 源 | 判据 |
|---|---|
| ① 商品属性表 | `会话.订单.商品货号` → 按货号连接。**不看主张** —— 有订单就有 ① |
| ② 口径表 | 复述 `认口径` 的结果。本模块不认，只搬 |
| ③ 先例库 | **不走六源** —— 它是风格来源（`检索/先例库.py`），不进事实依据 |
| ④ 订单／物流／售后 | 有订单，**且**主张涉发货／物流／签收 |
| ⑤ 不良反应／投诉 | `工单.kind == "不良反应"`，**且**主张涉健康 |
| ⑥ 补发换货工单 | `工单.kind == "补发换货"`，**且**主张涉补发／赠品 |

④⑤⑥ 的相关性判据是**关键词**，和 `rules.permissions.认权限` 同一路数
—— 都是「先用词表跑通演示，真上线换模型」的位置。换的时候只换 `_记不记`
那几个词表，不动签名。

# ② 为什么要调用方把编号传进来

`认口径` 是一次 LLM 调用，调用方（`api/路由.py`）为了填 `判成.依据编号`
本来就要调它一次。让本模块再调一次的话，同一条主张会有**两次认口径的结果**，
而右栏的 ② 和 `依据编号` 分别取其中之一 —— 两次结果不同时，右栏会显示
「② 是 K10 的话术」却把 `依据编号` 写成 K16，两处都「看着对」。

所以 `查六源` 收的是**已经认好的编号**，不自己认。多个参数这件事不影响
工单 §五 冻的签名：那两个都是 keyword-only 且带默认值，
`查六源(m, 会话, 商品表)` 照样成立（只是 ② 空）。
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Any

from ..rules.koujing import 口径条目
from ..rules.sources import 六源, 六源结果, 六源顺序, 源记录
from .商品表 import 不含名, 商品表, 成分名

if TYPE_CHECKING:
    # 只给类型检查器看。`app/检索` 是数据侧，运行时不依赖 HTTP 契约那一层
    # （`api/schemas.py` 反过来 import `rules`，真引进来就绕成一个圈了）。
    from ..api.schemas import Session


# ══════════════════════════════════════════════════════════
# ④⑤⑥ 的相关性词表
# ══════════════════════════════════════════════════════════
#
# ⚠️ 这三张表是**相关性**判据，不是**分类**判据 —— 命中一个词就记，
# 多记一个的代价只是右栏多一行。所以宁可收宽一点，别让明明相关的记录漏掉
# （漏掉的后果见模块文档串）。
#
# 但也不能收到什么都算：`_发货物流签收` 里如果只写「到」，那么「到期」「收到
# 谢谢」全会命中 —— 词表里**不收单字**，也不收「好」「谢」这类客套字。

#: ④ 发货／物流／签收。
#:
#: 「漏发」2026-10-02 补进来：「补寄」「重发」本来就在表里，同义的「漏发」却不在 ——
#: 清单 §1.3 把主张从「赠品未发货」改成「赠品漏发」后，这张表**一个词都不中**，
#: ④ 整条不记，依据块里就少了订单那条事实。漏发货本来就是发货的事，收进来。
_发货物流签收 = (
    "发货", "发出", "物流", "快递", "包裹", "单号", "签收", "收货", "到货",
    "揽收", "派送", "派件", "运输", "配送", "送达", "包邮", "运费", "退货运费",
    "没收到", "未收到", "没到", "未到", "迟迟", "补寄", "重发", "漏发",
)

#: ⑤ 健康／不良反应。**只收「已经出了事」的词**，不收「敏感肌」这类肤质词
#: —— 肤质是体质不是事件，`pipeline.涉个体差异` 管那一头。
_健康 = (
    "过敏", "不适", "泛红", "发红", "刺痛", "刺痒", "发痒", "痒", "红肿",
    "闷痘", "爆痘", "起痘", "长痘", "痘痘", "烂脸", "脱皮", "灼", "发烫",
    "就医", "医院", "医生", "停用", "不良反应", "副作用", "症状",
)

#: ⑥ 补发／赠品。
_补发赠品 = (
    "补发", "补寄", "换货", "换发", "重发", "追加", "加赠",
    "赠品", "小样", "礼品", "漏发", "少发", "少件", "错发", "发错", "发漏",
)


def 查六源(
    主张: str,
    会话: Session | None,
    商品表: 商品表,
    *,
    口径表: Sequence[口径条目] = (),
    口径编号: str | None = None,
) -> 六源结果:
    """一条主张查完六个来源。

    `会话` 给 `None` 时只有 ① 和 ② 可能命中 —— ④⑤⑥ 全部走会话。
    那两个参数（`口径表` / `口径编号`）见模块文档串；不传时 ② 空。
    """
    # 起手就带齐六个键。`六源结果.__post_init__` 也会拦漏键，但那道在
    # **构造那一刻**才响 —— 而漏键的典型原因是这里少写了一行赋值，
    # 一行 `{源: () for 源 in 六源顺序}` 让那件事根本发生不了。
    记录: dict[六源, tuple[源记录, ...]] = dict.fromkeys(六源顺序, ())

    记录[六源.商品属性表] = _查商品属性表(会话, 商品表)
    记录[六源.口径表] = _查口径表(口径表, 口径编号)
    # ③ 先例库：**不进六源**（`开发步骤.md` §7.1 §丙）。它有真东西了（139 条真人客服
    # 答法，2026-10-05 建的库），但那东西进的是 prompt 第 6 块，不是这儿 ——
    # `六源结果.有记录()` 只看 exists，③ 一进来就会替「查得到」背书。
    记录[六源.订单物流售后] = _查订单(会话, 主张)
    记录[六源.不良反应投诉] = _查工单(会话, 主张, "不良反应", _健康)
    记录[六源.补发换货工单] = _查工单(会话, 主张, "补发换货", _补发赠品)

    return 六源结果(主张=主张, 记录=记录)


# ── ① 商品属性表 ──────────────────────────────────────────
#
# **不看主张。** 有订单就查得到，查得到就记 —— 工单 §四 那张表里 ① 的判据
# 只有「`会话.订单.商品货号` → 查商品表」这一步。加主张过滤的后果是
# 「含乙醇」之外的主张全都查不到 ①，而 ① 是第 1 层最主要的依据来源。


def _查商品属性表(会话: Session | None, 表: 商品表) -> tuple[源记录, ...]:
    货号 = 会话.订单.商品货号 if 会话 is not None and 会话.订单 else ""
    商品 = 表.get(货号) if 货号 else None
    if 商品 is None:
        return ()

    # ⚠️ 五列的**列名照抄表头**，不是 `商品` 的字段名 —— 这段文字会原样进
    # 右栏和第 3 层的 prompt，标签得和客服能在 xlsx 里翻到的那一列对上。
    return (
        源记录(
            exists=True,
            table="商品属性表",
            row_id=商品.货号,
            # 物质名走**另一条路**：`content` 是给人读的，这两个是给 G3 比对用的。
            # 少 `成分` 的话，话术里「不含香精」这类断言在 G3 那儿就无从判（=不判）；
            # 少 `不含名` 的话，判是判了，但**判错** —— `水` 会顶替 `水杨酸`
            # （第三次子串陷阱，见 `物质.扫断言` 文档串）。两个一起给才算给全。
            成分=成分名(表, 商品),
            不含名=不含名(商品),
            content="\n".join(
                (
                    f"商品名称：{商品.名称}",
                    f"成分表（完整）：{商品.成分表}",
                    f"不含（可对顾客说）：{商品.不含可对顾客说}",
                    f"孕妇慎用成分：{商品.孕妇慎用成分}",
                    f"不适用/需谨慎：{商品.不适用需谨慎}",
                )
            ),
        ),
    )


# ── ② 口径表 ──────────────────────────────────────────────


def _查口径表(口径表: Sequence[口径条目], 编号: str | None) -> tuple[源记录, ...]:
    """把认到的这条口径**复述成一条记录**。`content` 取那条**规矩**，不取话术。

    ⚠️ **2026-10-05 之前这里取的是 `条目.标准话术`，那是个闭环。** 同一份
    `标准话术` 在 `组装提示` 里被当成【范例·照着这个语气写】喂给模型，模型
    逐字照抄 → 话术＝标准话术；而这条记录的 `content` 也＝标准话术，它往上走
    成主卡的依据摘要 → **卡上「依据 ② 口径表 K01」的摘要就是它上面那句话术**。
    同一句在一张卡上出现两遍，依据没在解释这句话，它在重复这句话。prompt 里
    也一样：那句话同时躺在【依据】和【范例】两块里。

    该给的是**出处**：这条口径允许说到哪一步、墙在哪儿。剧本（＝验收基准）
    一直这么写，K01「不得说「孕妇可以用」，须建议咨询医生」／K10「不得说
    「放心使用」「所有肤质都能用」」／K05「还没发出，不得再承诺时限」。
    `标准话术` 照样进 prompt（`取可引用` 和【范例】直接读口径表，不经过这里），
    所以**改这里不会抽掉模型照着写的范例**。
    """
    if not 编号:
        return ()
    # **编号必须真在表里。** 模型编一个 K99 出来时不能照单全收 ——
    # 那条 `content` 无处可取，硬凑一条空的就是在放行一句话。
    条目 = next((k for k in 口径表 if k.编号 == 编号), None)
    if 条目 is None:
        return ()
    # 禁语是那张表里唯一**成形**的「不许说什么」，逐条摆出来就是这堵墙。
    # 空的时候退到 `可以说`（上界）—— 二十条口径现在都有禁语，这是道保险，
    # 免得将来加一条没填禁语的，卡上挂出个光秃秃的「不得说」。
    规矩 = (
        "不得说" + "".join(f"「{词}」" for 词 in 条目.禁语)
        if 条目.禁语
        else 条目.可以说
    )
    return (
        源记录(
            exists=True,
            table="口径表",
            row_id=条目.编号,
            content=规矩,
        ),
    )


# ── ④ 订单／物流／售后 ────────────────────────────────────


def _查订单(会话: Session | None, 主张: str) -> tuple[源记录, ...]:
    if 会话 is None or 会话.订单 is None or not _沾边(主张, _发货物流签收):
        return ()
    订单 = 会话.订单
    return (
        源记录(
            exists=True,
            table="订单",
            row_id=订单.订单号,
            content=_要点(
                f"商品：{订单.商品名称}（{订单.商品货号}）× {订单.数量}",
                f"订单状态：{订单.订单状态}",
                f"下单时间：{订单.下单时间}",
                f"付款时间：{订单.付款时间}",
                f"发货时间：{订单.发货时间}",
                f"快递公司：{订单.快递公司}",
                f"物流单号：{订单.物流单号}",
                f"赠品：{订单.赠品}",
                f"买家留言：{订单.买家留言}",
            ),
        ),
    )


# ── ⑤ 不良反应 ／ ⑥ 补发换货 ──────────────────────────────
#
# 两个源走同一个函数：判据形状一样（`kind` 对不对 ＋ 主张沾不沾边），
# 只有具体是哪一类和哪一张词表不同。写成两个函数的话，下面这段「kind 取自
# `工单.kind`（不是表名）、表名要带上『工单』后缀」的逻辑会各抄一份 ——
# 而 `kind` 和表名的对应关系已经有一处会错了（`schemas.TicketKind`）。


def _查工单(
    会话: Session | None,
    主张: str,
    kind: str,
    词表: tuple[str, ...],
) -> tuple[源记录, ...]:
    if 会话 is None or 会话.工单 is None:
        return ()
    工单 = 会话.工单
    # ⚠️ 比的是 `kind`（"不良反应"），不是表名（"不良反应工单"）。
    # `schemas.TaggedTicket` 那儿的对应关系是「工作表名去掉『工单』后缀」。
    if 工单.kind != kind or not _沾边(主张, 词表):
        return ()

    票 = 工单.ticket
    字段: dict[str, Any] = (
        票.model_dump() if hasattr(票, "model_dump") else dict(票)  # type: ignore[arg-type]
    )
    return (
        源记录(
            exists=True,
            table=f"{kind}工单",
            row_id=str(字段.get("工单号", "")),
            content=_要点(
                *(f"{名}：{值}" for 名, 值 in 字段.items() if 名 not in _管道字段)
            ),
        ),
    )


#: 工单行里**不进 content** 的列。
#:
#: 会话 ID 和买家昵称是这行属于谁，店铺和处理人是谁在处理，关联订单号在 ④ 里
#: 已经有了 —— 它们答不了「这条主张的事实依据是什么」，塞进去只会把真正有用的
#: 几列（症状描述、补发物流单号）稀释掉。**按列名排除而不是按类别白名单**：
#: 五类工单的专有列各不相同，白名单要维护五份，而漏一列的后果是那条事实没了。
_管道字段 = frozenset({"会话ID", "买家昵称", "店铺", "关联单号", "关联订单号", "完成时间"})


def _沾边(主张: str, 词表: tuple[str, ...]) -> bool:
    return any(词 in 主张 for 词 in 词表)


def _要点(*行: str) -> str:
    """拼 content：丢掉空值那几行，用换行分隔。

    **空的行要丢，不是留个「发货时间：」在那儿。** 未发货的订单 `发货时间` 是
    空串，留着的话第 3 层看到的是一行没有值的标签 —— 而「空的」和「没这一列」
    在模型眼里长得一样。
    """
    return "\n".join(行 for 行 in 行 if not 行.endswith(("：", "：None")))
