"""① 商品属性表 —— 按**货号**索引的 20 行。

# 为什么是连接不是检索

`会话.订单.商品货号` → 翻到那一行。20 个货号和真实订单的 20 个货号一一对应
（实测），所以这是一个**精确连接**：命中就是命中，没有 top-K，没有相似度阈值。

这条区别演示时要主动讲：「① 查过了」在这里真的等于「① 里每一行都看过了」，
`rules/sources.py` 文档串警告的那个截断风险在这一源上不存在。

# 五列，少一列就抛

`商品` 只带 `content` 要用的五列（工单 §4.1 点名的那五列），其余十四列不读
—— 没有消费方的东西先不搬。**列名对不上在装载时就抛**，理由见 `商品表坏`。

> ⚠️ **本模块最容易踩的一脚**：`不含（可对顾客说）` 那一列里**没有乙醇**
> （它列的是维A类／水杨酸／对二苯酚／二苯酮-3／皂基）。所以「不含乙醇」
> 只能从 `成分表（完整）` 做**否定判断**得到 —— 照 `不含` 列去匹配会查空。
> 本模块按货号无条件返回整行，不做任何主张匹配，所以这个坑踩不到；
> 但**读 `content` 的那一侧**（第 3 层出稿）要记得看的是 `成分表`。

# 物质名：抠词 vs 整名

`成分表（完整）` 是**顿号分隔的物质名列表**，所以「含不含 X」这个问题
在结构上是个集合成员判断，不是子串搜索。差别的量级（20 个真商品实测）：

| 判据 | 对「含乙醇吗」判 True 的 |
|---|---|
| 抠词 `"乙醇" in 成分表` | **17 个**（苯氧乙醇害的，全错） |
| 整名相等，不带别名 | 0 个（**漏了** XL21204 的 `变性乙醇`） |
| 整名相等 ＋ `酒精别名` | 1 个（XL21204，对） |

**17/20 含苯氧乙醇**，而「苯氧乙醇」逐字含「乙醇」—— 所以抠词不是偶尔错，
是绝大部分都错。另一头 `变性乙醇` 里也含「乙醇」但那不是 token，
**别名表因此不是可选项**。

判据只有 `含成分` 一个入口，别在别处写 `in 成分表`。消费方在
`rules/guards.G3来源可查`（它验话术里「含／不含 X」的断言），
token 经 `依据条目.成分` 传过去。
"""

from __future__ import annotations

import re
from collections.abc import Collection
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..data.装载器 import 读工作簿

#: ① 在 `商品属性表_v7_定稿.xlsx` 里的工作表名。**写死**，见 `商品表坏`。
工作表名 = "1_商品属性表"

#: 本模块要的六列（货号 ＋ content 的五列）→ `商品` 的字段名。
#: 左边是**表头原文**，一个字都不能改 —— 改了就取不到，而取不到会抛。
用的列: dict[str, str] = {
    "商品货号": "货号",
    "商品名称": "名称",
    "成分表（完整）": "成分表",
    "不含（可对顾客说）": "不含可对顾客说",
    "孕妇慎用成分": "孕妇慎用成分",
    "不适用/需谨慎": "不适用需谨慎",
}


class 商品表坏(ValueError):
    """表读不进来：缺工作表，或缺列。

    **为什么是抛而不是给个空值。** 缺列时悄悄少拼一截 `content`，第 1 层照样判
    「查得到」、右栏照样显示一条 ① 的依据 —— **没有任何东西会红**，只是看的人
    以为自己看到的是全部。缺工作表时返回空表更糟：空表的意思是「20 个货号一个
    都查不到」，那句话会一路传成「第 1 层查不到 → 交客服点发送」，看着像正常的
    保守处理。

    两种都不是能靠下游兜住的错，所以在装载这一层就断。
    """


@dataclass(frozen=True, slots=True)
class 商品:
    """① 里的一行，只留出稿要用的六列。"""

    货号: str
    名称: str
    成分表: str
    """`成分表（完整）`。**「不含 X」要从这里做否定判断** —— 化妆品按法规要求
    全成分标注，所以「全成分表里没有」＝「不含」。被问到就这么答。"""
    不含可对顾客说: str
    """`不含（可对顾客说）`。是我们**被允许说**不含的那几样，不是成分全集
    —— 别拿它当否定判断的依据（它里面就没有乙醇）。"""
    孕妇慎用成分: str
    不适用需谨慎: str


#: 货号 → 商品。`装商品表` / `从表` 的返回类型。
商品表 = dict[str, 商品]


def 从表(表: dict[str, list[dict[str, Any]]]) -> 商品表:
    """`读工作簿` 的产出 → 按货号索引的商品表。

    和 `data.装载器.装载器.从表` 同一个形状：I/O 和转换分开，转换这一半
    不需要真 xlsx 就能测。
    """
    if 工作表名 not in 表:
        raise 商品表坏(
            f"工作簿里没有「{工作表名}」这张工作表（有的是 {list(表)}）。"
            "名字对不上时**不能当空表处理** —— 见 商品表坏 的文档串。"
        )

    行们 = 表[工作表名]
    if not 行们:
        raise 商品表坏(f"「{工作表名}」是空的。20 行商品属性是 ① 的全部内容。")

    表头 = set(行们[0])
    if 缺 := [列 for 列 in 用的列 if 列 not in 表头]:
        raise 商品表坏(
            f"「{工作表名}」缺这些列：{缺}。\n"
            "它们进 content，少一列就是一条看着完整、实际短一截的依据，"
            "而且不会有任何东西报错。表头改了名的话，改 `用的列` 跟着改。"
        )

    索引: 商品表 = {}
    for 行 in 行们:
        值 = {别名: _文本(行.get(列)) for 列, 别名 in 用的列.items()}
        if not 值["货号"]:
            # 表尾常有一整行空（见 test_空货号的行跳过）。
            continue
        索引[值["货号"]] = 商品(**值)
    return 索引


def 装商品表(路径: Path | str) -> 商品表:
    """读 `商品属性表_v7_定稿.xlsx`（或任何同形状的表）→ 按货号索引。

    文件不在会抛 `data.装载器.业务数据缺失`，那是**另一个**错：缺文件是路径问题，
    `商品表坏` 是表本身的问题，两者的修法不一样。
    """
    return 从表(读工作簿(Path(路径)))


def 查商品(表: 商品表, 货号: str) -> 商品 | None:
    """按货号取一行。查不到返回 `None`。

    **查不到不造空记录。** 第 1 层拿 `六源结果.有记录()` 当判据，
    凭空造一条 `exists=True` 的空记录等于放行一条没依据的话。
    """
    return 表.get(货号 or "")


def _文本(值: Any) -> str:
    """xlsx 的空单元格读出来是 `None`，`商品` 的字段都是 `str`。"""
    return "" if 值 is None else str(值).strip()


# ══════════════════════════════════════════════════════════
# 物质名
# ══════════════════════════════════════════════════════════

#: 成分表的分隔符。**只有顿号** —— 真表 20 行里数过：
#:   `、` 163 处（真的在分隔物质）
#:   `/`  8 处（**全在名字内部**：`鲸蜡基PEG/PPG-10/1聚二甲基硅氧烷`、
#:        `辛酸/癸酸甘油三酯`、`PEG-6辛酸/癸酸甘油酯类`）
#:   `；`  1 处（在 `XL19805` 那句改指说明的**话里**，不是在分隔物质）
#:
#: 顺手把 `/` 也切了的话，那些名字会劈成两半，而两半看着都还挺像个成分名。
分隔符 = "、"

#: 改指行：`成分表（完整）` 里写的不是列表，是**指到别的货号**。
#: `XL19805`（14 单）、`XL19806`（13 单）都是 —— 不是边角料。
改指 = re.compile(r"[见同]\s*([A-Z]{2}\d{5})")

# 别名表在 `rules/物质.py` —— 那边是叶子模块，`rules/guards.py` 也要用它，
# 而本模块隔着 `data/装载器` 绕回 `rules/guards`，让 guards 反过来 import 本模块会成环。


def 成分名(表: 商品表, 商品: 商品) -> tuple[str, ...]:
    """`成分表（完整）` → 物质名元组。**按顿号切，整名相等，不抠词。**

    改指行（礼盒／双支装）**顺着货号追**，追出来的物质名取并集 ——
    礼盒里就是那几支单品，只追第一个会让「含不含牛油果树果脂」答错。

    ⚠️ 追不到（指向的货号不在表里）或**绕圈**都抛 `商品表坏`。
    返回空元组是不行的：空的读出来是「什么成分都没有」，
    下游会把它当成「不含 X」，正好是这一整节要消灭的失败方式。

    括号注释不剥。真表里带括号的两行**只有那两个改指行**，
    正常行的物质名里没有括号 —— 剥反而是为一个不存在的输入写代码。
    """
    return _追(表, 商品, frozenset())


def _追(表: 商品表, 商品: 商品, 见过: frozenset[str]) -> tuple[str, ...]:
    if 商品.货号 in 见过:
        raise 商品表坏(
            f"成分表的改指绕圈了：{' → '.join([*见过, 商品.货号])}。"
            "真表里没有这种数据，但环形数据不该变成挂起 —— 演示当天挂起比报错难查。"
        )
    指们 = 改指.findall(商品.成分表)
    if not 指们:
        return _切(商品.成分表)
    return _并集(表, 指们, 见过 | {商品.货号})


def _并集(表: 商品表, 指们: list[str], 见过: frozenset[str]) -> tuple[str, ...]:
    """几个单品各自的物质名合起来，**按首次出现的顺序去重**。

    去重不是洁癖：`XL19805` 的两支单品有 8 个共同成分（水、甘油、卡波姆…），
    不去重的话同一个物质名会出现两次，下游任何按物质名去重的逻辑都会看花眼。
    """
    结果: list[str] = []
    for 号 in 指们:
        件 = 表.get(号)
        if 件 is None:
            raise 商品表坏(
                f"改指指向「{号}」，但商品表里没有这个货号。"
                "追不到就不能返回空 —— 空的会被下游读成「不含任何成分」。"
            )
        for 物 in _追(表, 件, 见过):
            if 物 not in 结果:
                结果.append(物)
    return tuple(结果)


def _切(成分表: str) -> tuple[str, ...]:
    return tuple(物 for x in 成分表.split(分隔符) if (物 := x.strip()))


def 含成分(
    表: 商品表,
    商品: 商品,
    名称: str,
    *,
    别名: Collection[str] = (),
) -> bool:
    """这个商品里有没有「名称」这个物质。**整名相等，不做子串匹配。**

    `别名` 是「哪些叫法算同一个物质」。问酒精要传 `酒精别名`：

        含成分(表, 商品, "酒精", 别名=酒精别名)   # 精华 → False，卸妆水 → True

    不传的话 `变性乙醇` 认不出来 —— 那把真含酒精的卸妆水说成了不含。
    """
    候选 = {名称, *别名}
    return any(物 in 候选 for 物 in 成分名(表, 商品))
