"""③ 先例库 —— 给话术生成做风格参照的一堆**过往话术**。

**⚠️ 条目有两个来路，别当成一种**（`先例.来源`）：

| 来源 | 谁写的 | 盘上那个 139 条的库 |
|---|---|---|
| `取材来源` | **真人客服**的原话，从 `聊天记录` 里挑出来的 | 全是它 |
| `回写来源` | **模型自己当轮写的那一稿**（spec §六） | 一条都没有 |

分这个不是为了好看：两个来路在 prompt 里**摆成两块、抬头不一样**。回写那条要是
顶着「真人客服怎么说的」的名，模型就会照抄自己上一轮的输出（`S00226` 那次）。

**不是事实来源。** 先例进 prompt 只走 `组装提示` 的**第 6 块那两个子块**，
**不进 `六源`** —— `六源结果.有记录()` 只看 `exists` 不看是哪一源，③ 一旦进六源，
一条「只有先例有记录」的主张会在第 1 层判「查得到」，判定结果整个会动。
右栏 `N/6` 第 3 位照旧是 `0`。

**库里不许有带单位的数字和「已＋动作」。** 理由在 `guards.G3来源可查` 那一带：
它拼的可查文本是**全部**依据的摘要，不按 `用上` 过滤 —— 库里留着「48 小时」，
它会替话术里同一个数字**背书**，而 ③ 根本不是出处。取材和回写**各跑一遍**同一
套滤（`_该丢`）：挡的失败模式不一样，一个挡库，一个挡当轮那稿。

**尺子就是 `guards.G3带单位数字`**（工作日／小时／天／元／折／ml／mL／克／g，
`个` 是可选的量词），所以它**看不见的数字不在管辖内**：建出来的 139 条里留着
**17 条**带数字的，**六类不重不漏**：

| 类 | 条数 | 下标 |
|---|---|---|
| 快递单号 | 3 | 18／51／58 |
| 色号 `#xx` | 5 | 5／23／25／38／67 |
| 「20 片」 | 3 | 88／95／137 |
| 「6 个月」 | 2 | 93／105 |
| 「1-2 分钟」 | 2 | 96／98 |
| B5 面膜规格 | 2 | 107／119 |

**那是这把尺子的边界，不是漏做** —— 真正的兜底是 prompt 口径（事实照本单依据）。

**阈值是实测切的**（`先例阈值`），不是估的 —— 两堆分数在 0.598–0.645 这段重叠，
任何单一阈值都分不干净。校准过程和那 1 条漏进来的噪声写在
`docs/superpowers/specs/2026-10-05-先例库-design.md` §4.1。
"""

