仓库根 = Path(__file__).resolve().parents[3]

#: 库文件。**和 `data/koujing.json` 同一套算法**（`rules/koujing.py:16`）。
默认库路径 = 仓库根 / "data" / "先例库.json"

#: 运行期真正读的那个路径。**测试靠改它把库挪走**（`tests/conftest.py` 那条
#: autouse），所以要是个模块级变量，不能把 `默认库路径` 到处硬编。
库路径 = 默认库路径

#: 库文件的格式版本。**对不上就当空库**，不是迁移 —— 库里装的是向量，重建一次
#: 比写迁移便宜。
库版本 = 1

#: 召回阈值。**实测切的**（2026-10-05 建出 139 条真库后量的 top-1）：
#: 真命中 11 条落在 0.880–0.598，噪声 10 条落在 0.645–0.345，两堆在这段重叠。
#: 0.63 收进 9/11 条真命中、放过 1/10 条噪声（0.645 那条「乙醇」）；0.72 会把
#: 「退货／尾款／物流／换色号」整类挡在外面。**它是优先级，不是过滤器。**
先例阈值 = 0.63

#: 去冗阈值（**情境**余弦）。同一件事被十几个买家问过，答法一模一样。
召回去重 = 0.95

#: 召回几条。3 条是 few-shot 的常见量 —— 再多会把 prompt 撑成先例的复读现场。
召回条数 = 3

#: 占位话：客服用它拖时间，没有任何信息。**看开头**。
占位头 = ("稍等", "亲稍等", "亲亲稍等", "在的呢", "正在为您查询", "为您查询")

#: 空壳话：欢迎语／招呼语。**看包含** —— 它们不以这几个词开头。
#:
#: 这两张表分开是 2026-10-05 实测逼出来的：只看开头时漏过去 9 条欢迎语，
#: 其中一条在「帮我看看订单发货没」上拿了 **0.803** —— 比真命中还高。
空壳词 = ("欢迎光临", "有什么可以帮", "有什么能帮", "很高兴为您服务")

#: 不高于这个长度的一律丢。客服那 495 条里有一批「亲亲稍等哦」。
寒暄长度 = 20

#: 嵌入函数的形状。`检索/先例库` 只认这一个口子，测试注假的就是换它。
嵌入函数 = Callable[[Sequence[str]], list[list[float]]]

#: **库里的条目只有两个来路。** `先例.来源` 是**封闭集合**，别加第三个 ——
#: `组装提示` 按它分块渲染（`== 取材来源` 和 `== 回写来源` 两个等值筛），
#: 多出一个值会让那条**从两块里同时消失**，而屏幕上只表现为「先例少了一条」。
#: `先例.__post_init__` 挡着这件事。
取材来源 = "取材"
"""`从聊天记录取材` 建的 —— **真人客服的原话**。盘上那个 139 条的库全是它。"""

回写来源 = "回写"
"""`回写` 收的 —— **模型自己当轮写的那一稿**（spec §六）。

⚠️ **它不是真人客服说的**，只是这一轮正常收尾了，所以收进来给后面几轮当参照。
它顶不了「别人家客服怎么说的」那个名 —— `S00226` 轮 2 那次就是这么翻车的：
模型看到顶着「真人客服」抬头的先例，其实是它自己上一遍的稿子，于是照抄了一遍。
"""


@dataclass(frozen=True, slots=True)
class 先例:
    """库里的**一条**：某轮买家问了什么（情境），客服答了什么（答法）。

    `场景` 是 `scene_major/scene_minor`，**只用来查，不参与召回**。
    `向量` 是 `情境` 的嵌入（索引文本 ＝ 情境，不是答法 —— 召回问的是
    「这一轮买家要什么」，不是「当年客服怎么说的」）。
    `来源` 见 `取材来源`／`回写来源` —— 它记的是**这条哪来的**，不是**这条好不好**。
    """

    情境: str
    答法: str
    会话ID: str
    场景: str = ""
    向量: tuple[float, ...] = ()
    来源: str = 取材来源
    """⚠️ **必须排在最后。** `tests/test_先例库.py` 里有一处是**五个位置参数**
    （`先例("问退货", "答退货", "S1", "补发换货/破损换货", (0.123…, 1.0))`），
    插在 `向量` 前面会让那个元组落进 `来源`、`向量` 变空 —— 错得静悄悄。"""

    def __post_init__(self) -> None:
        """**来源是封闭集合，认不出就当场炸。**

        别把这条当洁癖：`组装提示` 是按 `来源` 分两块渲染的，用的是两个**等值筛**
        —— 多出一个值（拼错、或哪个构造点漏传了）会让那条**两块都不进**，
        而屏幕上只表现为「先例少了一条」，谁都看不出来。
        构造点只有三处，抛在最早最准的地方。
        """
        if self.来源 not in (取材来源, 回写来源):
            raise ValueError(
                f"不认识的来源：{self.来源!r}（只认 {取材来源!r}／{回写来源!r}）"
            )


#: 召回返回的**一条投影**：库里那条剪掉向量，只留摆进 prompt 要用的三样。
#:
#: **为什么另起一个类型、不直接把 `先例` 交出去**：`先例` 背着 1024 个浮点，
#: 那是库的事、不是渲染层的事。让 `组装提示` 看得见向量，下一个人就会拿它算点
#: 别的；这个类把「prompt 那一层能拿到什么」说死了。
@dataclass(frozen=True, slots=True)
class 召回条目:
    情境: str
    答法: str
    来源: str = 取材来源


#: 召回函数的口子。**`llm/组装提示` 从这里转发**，`话术生成` 拿它当默认参数的形状。
#:
#: ⚠️ **这一行必须待在 `召回条目` 后面。** 它是**赋值语句、运行期求值**
#: （`Callable[...]` 不是注解，`from __future__ import annotations` 管不着它），
#: 搬回上面常量区会在 **import 期** `NameError`，而且炸的是全仓不是这一处。
召回函数 = Callable[[str, int], Sequence[召回条目]]


def _压平(文本: str) -> str:
    """多行拼成一行。

    买家连着发的几行是拼起来当情境的，客服那句也可能带换行 —— 而召回条目要
    逐条拼进 prompt 第 6 块（`"- 买家：… ／ 客服：…"`），句里带换行会把那个
    列表拼散。**取材和回写都过这一道**，两边一样。
    """
    return re.sub(r"\s+", " ", 文本 or "").strip()


def _该丢(答法: str) -> bool:
    """这条答法够不够格进库。**取材和回写共用这一把尺子。**

    挡的六类：太短／占位话／空壳话／口径禁语／带单位数字／「已＋动作」没凭据。
    后两类是**硬要求**（模块文档串那段），前四类是素材质量问题。
    """
    if len(答法) <= 寒暄长度 or 答法.startswith(占位头):
        return True
    if any(w in 答法 for w in 空壳词):
        return True
    if koujing.查禁语全(答法):
        return True
    if guards.G2措辞(答法):
        return True
    if guards.G3带单位数字.search(答法):
        return True
    return bool(guards.已发生动作(答法))


def 从聊天记录取材(表: Mapping[str, Sequence[Mapping[str, Any]]]) -> tuple[先例, ...]:
    """`聊天记录` 那张表 → 一批先例。**一轮一条，一轮最多一条。**

    逐行过状态机：买家话一到手就当「新情境」，客服话攒起来，下一个买家话或会话
    结束时结算。**买家连着发的几行并作同一轮**（后一行是补充，不是新问题）——
    只有「上一轮客服回过」才翻篇。不引 `pipeline.切轮` —— 那个切的是**演示会话
    的轮次**（带规则带索引），这儿要的是「买家一句、客服一句」这个最粗的形状。
    """
    按会话: dict[str, list[Mapping[str, Any]]] = {}
    for 行 in 表.get(聊天记录表, ()):
        会话ID = str(行.get("会话ID") or "")
        if 会话ID:
            按会话.setdefault(会话ID, []).append(行)

    出: list[先例] = []
    for 会话ID in sorted(按会话):
        买家话 = ""
        客服行们: list[Mapping[str, Any]] = []
        for 行 in sorted(按会话[会话ID], key=lambda r: r.get("消息序号") or 0):
            角色 = 行.get("角色")
            文本 = _压平(str(行.get("message_text") or ""))
            if 角色 == "买家":
                if 客服行们:  # 上一轮客服回过 —— 结算，翻篇
                    出.extend(_成条(会话ID, 买家话, 客服行们))
                    买家话, 客服行们 = 文本, []
                else:  # 买家连着发 —— 并进同一轮
                    买家话 = f"{买家话} {文本}".strip()
            elif 角色 == "客服" and 买家话:
                客服行们.append(行)
        出.extend(_成条(会话ID, 买家话, 客服行们))
    return tuple(出)


def _成条(
    会话ID: str, 买家话: str, 客服行们: Sequence[Mapping[str, Any]]
) -> tuple[先例, ...]:
    """一轮 → 最多一条。**取最长的那个客服行。**

    2026-10-05 实测：63 个客服说了两句的轮次里 58 个是「先安抚后说正事」，
    短的（「亲亲稍等哦」）没有信息量。一样长取靠后的 —— `reversed` 是为了让
    `max` 在并列时选中后面那个。
    """
    if not 买家话 or not 客服行们:
        return ()
    答法行 = max(
        reversed(客服行们), key=lambda r: len(_压平(str(r.get("message_text") or "")))
    )
    答法 = _压平(str(答法行.get("message_text") or ""))
    if not 答法 or _该丢(答法):
        return ()
    return (
        先例(
            情境=买家话,
            答法=答法,
            会话ID=会话ID,
            场景=f"{答法行.get('scene_major', '')}/{答法行.get('scene_minor', '')}",
            来源=取材来源,
        ),
    )


def 余弦(甲: Sequence[float], 乙: Sequence[float]) -> float:
    """余弦相似度。**维度对不上或有一头是空的一律回 0** —— 宁可不召回，
    不许拿两条不同维度的向量瞎比（那会得到 0.7 这种看着正常的数）。"""
    if not 甲 or not 乙 or len(甲) != len(乙):
        return 0.0
    点 = sum(x * y for x, y in zip(甲, 乙))
    长 = math.sqrt(sum(x * x for x in 甲)) * math.sqrt(sum(y * y for y in 乙))
    return 点 / 长 if 长 else 0.0


def _答法克隆(甲: str, 乙: str) -> bool:
    """两句答法是不是「同一套话换了个客服名」。

    **判据用字面（2-gram 重合率），不另存答法向量**：存了库文件翻倍，也会让
    「索引文本 ＝ 情境」这条拍板变得含糊。尺子借用 G4 那把
    （`guards.G4重复阈值`）—— 它量的就是「同一句发了两遍」。
    """
    甲集, 乙集 = guards.词集(甲), guards.词集(乙)
    if not 甲集 or not 乙集:
        return False
    return len(甲集 & 乙集) / min(len(甲集), len(乙集)) >= guards.G4重复阈值


def 嵌条目(条目们: Sequence[先例], *, 嵌: 嵌入函数 = 嵌文本) -> tuple[先例, ...]:
    """给每条嵌上情境向量。**条数对不上就抛** —— 那说明返回顺序也不是我们以为的
    那个顺序，静默配上等于把整个库配错。"""
    if not 条目们:
        return ()
    向量们 = 嵌([t.情境 for t in 条目们])
    if len(向量们) != len(条目们):
        raise ValueError(f"嵌入回来的条数对不上：{len(向量们)} ≠ {len(条目们)}")
    return tuple(replace(t, 向量=tuple(v)) for t, v in zip(条目们, 向量们))


def 去冗(条目们: Sequence[先例]) -> tuple[先例, ...]:
    """同一件事被问过十几次，只留先到的那条。贪心，顺序敏感 —— 所以取材那边
    按 `会话ID` 排过序，重建两次是同一份结果。"""
    留: list[先例] = []
    for 条 in 条目们:
        if 条.向量 and any(余弦(条.向量, 有.向量) >= 召回去重 for 有 in 留 if 有.向量):
            continue
        留.append(条)
    return tuple(留)


# ── 库文件 ────────────────────────────────────────────────

_活库: list[先例] | None = None
_活库模型 = ""
#: 回写的幂等键 → 那一轮写的条目。**形状照 `api/台账._已发送`。**
_回写表: dict[tuple[str, int], 先例] = {}
锁 = threading.RLock()

#: 读不了库时要说一声 —— 静默当空库和「库里没有贴得上的先例」在屏幕上长得一样。
日志 = logging.getLogger(__name__)


def _读库(路径: Path | None = None) -> tuple[list[先例], str]:
    """盘上的库 → `(条目, 嵌入模型)`。**读不了就 `([], "")`，绝不抛。**

    调用方（`取库`）拿它当「没库」处理 —— 判定链路跑在半路上，库文件坏了
    不该让客服那一屏整个白掉。
    """
    路径 = 路径 or 库路径
    try:
        原 = json.loads(路径.read_text(encoding="utf-8"))
        if int(原.get("版本", 0)) != 库版本:
            return [], ""
        条目 = [
            先例(
                情境=str(x["情境"]),
                答法=str(x["答法"]),
                会话ID=str(x["会话ID"]),
                场景=str(x.get("场景", "")),
                向量=tuple(float(v) for v in x["向量"]),
                # **`x.get` 的默认值不是偷懒，是兼容**：`data/先例库.json`（139 条）
                # 是加 `来源` 之前建的，盘上**没有这个键**。取默认值 ⇒ 老库照读、
                # 不用跑一次 `--重建`（那要重发 139 次嵌入，还会把向量换一批）。
                # 那 139 条本来就都是取材建的，所以默认值给「取材」是**事实**不是将就。
                来源=str(x.get("来源", 取材来源)),
            )
            for x in 原["条目"]
        ]
    except FileNotFoundError:
        return [], ""  # 还没建库 —— 常态，不出声
    except Exception as 错:  # noqa: BLE001 —— 见文档串
        日志.warning("先例库读不了，当空库：%r", 错)
        return [], ""
    return 条目, str(原.get("嵌入模型", ""))


def 取库() -> list[先例]:
    """活库。**第一次读盘，之后就在内存里**（139 条 × 1024 维 ≈ 1.1 MB）。

    ⚠️ **嵌入模型对不上就当空库**：库和当次的模型不是一个空间，余弦比出来的
    分数是随机的 —— 那种错表现为「召回到了不相干的东西」，不像一个错误。
    """
    global _活库, _活库模型
    with 锁:
        if _活库 is None:
            _活库, _活库模型 = _读库()
        if _活库模型 and _活库模型 != 先例库模型():
            return []
        return _活库


def 写库(条目们: Sequence[先例], *, 嵌入模型: str, 路径: Path | None = None) -> int:
    """库 → 盘。**分量 `round(v, 6)`** —— 不圆是 3.05 MB，圆到 6 位是 1.45 MB；
    对 0.63／0.95 这两个阈值来说 6 位是碾压级的精度，压掉的是浮点尾巴。"""
    路径 = 路径 or 库路径
    数据 = {
        "版本": 库版本,
        "嵌入模型": 嵌入模型,
        "条数": len(条目们),
        "条目": [
            {
                "情境": t.情境,
                "答法": t.答法,
                "会话ID": t.会话ID,
                "场景": t.场景,
                "来源": t.来源,
                "向量": [round(v, 6) for v in t.向量],
            }
            for t in 条目们
        ],
    }
    路径.write_text(json.dumps(数据, ensure_ascii=False), encoding="utf-8")
    return len(条目们)


def 清空() -> None:
    """丢掉活库和回写表，下次 `取库()` 重新读盘。**给测试用。**

    **两样一起清**：只清库的话，下一条测试的第一次回写会被上一条留下的幂等键
    挡掉，而表现是「回写没生效」，很难往缓存上想。
    """
    global _活库, _活库模型
    with 锁:
        _活库, _活库模型 = None, ""
        _回写表.clear()


# ── 召回（读侧）────────────────────────────────────────────


def 召回先例(
    主张: str,
    k: int = 召回条数,
    *,
    嵌: 嵌入函数 = 嵌文本,
    库: Sequence[先例] | None = None,
) -> tuple[召回条目, ...]:
    """主张 → 最多 `k` 条 `召回条目`（交给 `组装提示`，由那一层分块渲染）。

    **这一层不拼字符串。** 从前它把每条拼成 `买家：… ／ 客服：…` 再交出去；
    现在交的是条目本身 —— 因为**怎么摆进 prompt 取决于 `来源`**（真人素材和
    本店自己的稿子要分两块），而那是渲染的决定，不是检索的决定。

    **一个包都不发**的三种情况先返回：库没加载／没密钥／条目为空。这不是优化 ——
    `话术生成.生成话术` 的默认参数就是它，测试里那二十几处调用全靠这三条不打网络。

    **任何异常一律吞掉返回 `()`**：判定链路跑在半路上，召回是**锦上添花**那一环，
    它坏了不该让客服那一屏白掉。

    ⚠️ **来源是混排的，`k` 也是共用的。** 一条回写条目只要能过阈值和两道去冗，
    就会占掉 `k` 里的一格、把一条取材条目挤出去 —— `S00226` 现场就是这样。
    这是**认下来的取舍**（条数 3 和阈值 0.63 都是实测拍板的，不在这儿动），
    写在这儿的目的是别让下一个人以为是写错了。
    """
    if not k:
        return ()
    try:
        条目们 = 库 if 库 is not None else 取库()
        # 密钥检查在**发请求之前** —— 这一条也是测试友好性的载重件：`库` 是显式
        # 传进来的时候（测试里就是这么传的）也得先看密钥，否则那几条「没密钥不
        # 发请求」的测试会真打出去。
        if not 条目们 or not 先例库密钥():
            return ()
        向量们 = 嵌([主张])
        if not 向量们:
            return ()
        主张向量 = 向量们[0]
        候选 = sorted(
            ((余弦(主张向量, t.向量), t) for t in 条目们 if t.向量),
            key=lambda 对: 对[0],
            reverse=True,
        )
    except Exception:  # noqa: BLE001 —— 见文档串
        return ()

    取: list[先例] = []
    for 分, t in 候选:
        if 分 < 先例阈值:
            break
        # 两道去冗：情境近的、答法克隆的，都跳过看下一条（保证 3 条不克隆）
        if any(余弦(t.向量, 有.向量) >= 召回去重 for 有 in 取):
            continue
        if any(_答法克隆(t.答法, 有.答法) for 有 in 取):
            continue
        取.append(t)
        if len(取) >= k:
            break
    # **在这里剪掉向量**（`召回条目` 不带向量）：过了这道门，向量就没用了。
    return tuple(召回条目(情境=t.情境, 答法=t.答法, 来源=t.来源) for t in 取)


# ── 回写（spec §六）────────────────────────────────────────


def 回写(
    情境: str,
    答法: str,
    会话ID: str,
    轮次: int,
    *,
    嵌: 嵌入函数 = 嵌文本,
    兜底答法: str | None = None,
    允许重复: bool = False,
) -> bool:
    """这一轮正常收尾了 → 把模型刚写的那稿收进库。**返回写没写进去。**

    四道门：该丢（数字／已＋动作／寒暄，和取材同一把尺子）→ 幂等
    （`(会话ID, 轮次)` 见过了）→ 嵌不动 → 库里已有同一件事。**全都不抛**：
    调用方那一整段包在 `try/except` 里是为了防判定 500，这儿自己也兜住，
    因为「回写失败」不是错误，是常态（没密钥、没网、重复）。

    第五道是**嵌入模型对不上**（库是另一个模型嵌的）：那种条目留在库里只会让
    余弦变成随机数，正是 `取库` 那条守卫要防的事。它和上面四道不一样的**只有
    一点：幂等键也不记** —— 模型改回来之后，这一轮还得能写进去。

    **嵌一次并追加进内存索引**：不嵌的话那条在本次进程里永远召不回，
    回写就只剩计数意义。

    # 两个开关，都只给演示会话（调用方 `api/判定._回写参数` 决定）

    `兜底答法`：那一稿过不了 `_该丢` 时改用它顶上。**它自己也要过 `_该丢`**
    （下一段就是），过不了就照旧不写 —— 这不是免检通道，是「演示不能赌模型
    当天写出多长、带不带单位数字」。不给（`None`）时一个字都不变。

    `允许重复`：**幂等键和库内去重两道一起让开**，同一 `(会话ID, 轮次)` 判几次
    写几条。演示回放要的就是「每一次都真的涨一条」。放开的代价是库里会躺着
    逐字重复的条目 —— **读侧不用动**：`召回先例` 那两道去冗（情境 0.95 ＋
    `_答法克隆`）本来就会把它们滤掉，`test_重复条目在召回那边被滤掉` 钉着
    这件事。默认 `False` ⇒ 真会话走的一直是原来那一支。
    """
    情境, 答法 = _压平(情境), _压平(答法)
    # 兜底句要**先压平再查**，不然一个带换行的兜底句会绕过长度和别的判据。
    if 兜底答法 is not None and _该丢(答法):
        答法 = _压平(兜底答法)
    if not 情境 or not 答法 or _该丢(答法):
        return False
    with 锁:
        if not 允许重复 and (会话ID, 轮次) in _回写表:
            return False
        库 = 取库()
        # ⚠️ **嵌入模型对不上就不写**（`取库` 那条守卫）。那时 `取库()` 每次回的
        # 是一个**新造的 `[]`**，不是活库 —— 往它 append 等于扔进垃圾桶：条目一条
        # 都没进库，返回的却是 `True`，而上面那行幂等键已经记下了，**这一轮在这
        # 个进程里就再也写不进来**（模型改回来也救不回：键只看 `(会话ID, 轮次)`）。
        # 所以先 `取库()` 把模型真正读出来，对不上就当场收手 —— 键也不记。
        if _活库模型 and _活库模型 != 先例库模型():
            return False
        try:
            向量们 = 嵌([情境])
        except Exception:  # noqa: BLE001 —— 见文档串
            return False
        if not 向量们:
            return False
        向量 = tuple(向量们[0])
        # ⚠️ **同一句话嵌出来是同一个向量**，所以回放第二次在这里是余弦 1.0 ——
        # `允许重复` 光让开幂等键还不够，这一道也得一起让。
        if not 允许重复 and any(余弦(向量, t.向量) >= 召回去重 for t in 库 if t.向量):
            return False
        条 = 先例(
            情境=情境, 答法=答法, 会话ID=会话ID, 向量=向量, 来源=回写来源
        )
        库.append(条)
        _回写表[(会话ID, 轮次)] = 条
    return True


# ── 建库入口 ──────────────────────────────────────────────


def _重建() -> int:
    """取材 → 嵌 → 去冗 → 写库。**真数据这一跑要 180 次嵌入调用**（18 个请求），
    只在素材或嵌入模型变了才跑。

    **去冗之后一条不剩就不写库**（回 0 ⇒ 退出码 0）：取材变空恰恰是最容易发生的
    事（`聊天记录` sheet 改名、业务数据换成另一份），而 `写库` 会把盘上那个好库
    整个覆盖掉 —— 不写才是对的，「没东西可写」不是失败。
    缩水（180 → 10 这种）**不拦**，只把旧条数和新条数一起打到 stdout 上让人看见：
    条数对不对是人的判断，不是这条入口的判断。
    """
    from ..配置 import 取配置
    from ..data.装载器 import 读工作簿

    表 = 读工作簿(取配置().业务数据路径)
    粗 = 从聊天记录取材(表)
    细 = 去冗(嵌条目(粗))
    print(f"取材 {len(粗)} 条 → 去冗 {len(细)} 条 → {库路径}")
    if not 细:
        print(
            f"去冗之后一条不剩 —— **不写库**，{库路径} 原样不动。"
            "先看 `聊天记录` 那张 sheet 和取材的滤表，别让一个空取材把好库覆盖成空库。"
        )
        return 0
    旧条数 = len(_读库()[0])
    缩水 = "（比旧库少，确认一下是不是预期）" if len(细) < 旧条数 else ""
    print(f"库里旧 {旧条数} 条 → 这次写 {len(细)} 条{缩水}")
    写库(细, 嵌入模型=先例库模型())
    return len(细)


if __name__ == "__main__":
    if "--重建" in sys.argv:
        # 回条数 ＝ 写了这么多条；回 0 ＝ 空取材**拒绝写库** —— 两种都是 0。
        # 不能写成 `0 if _重建() else 1`：`_重建()` 回 0 时那个表达式给的是 **1**，
        # 而「没东西可写」不是失败（见 `_重建` 文档串）。真出错（读不了工作簿、
        # 嵌不动）是抛出来的，Python 自己会给非零退出码。
        _重建()
        raise SystemExit(0)
    print("用法：python -m app.检索.先例库 --重建", file=sys.stderr)
    raise SystemExit(2)
