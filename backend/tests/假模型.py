"""一个按顺序吐答案的假模型 —— 模型位的测试都用它。

**测试里不打真模型。** 打真的会有三个后果：测试变慢、跑一次花一次钱、
以及**结论随模型版本漂** —— 今天绿的明天红，而红的理由和代码无关。
所以每个模型位都留了一个 `问=` 的口子（keyword-only 带默认值），
测试塞一个假的进去。

它同时把收到的 prompt 记下来：**prompt 是模型位唯一的产出**，
不看它在问什么，测的就只剩解析。

（原先这个辅助函数在 `test_llm.py` 里有一份。第三处要用到它的时候提了出来 ——
三份拷贝的坏处不是多敲几行，是**它们会各自漂**，而这个函数的形状决定了
「假模型的接口和真模型一不一样」，漂了就会出现在某处能测、在另一处测不了。）
"""

from __future__ import annotations

from collections.abc import Sequence

from app.llm.客户端 import 问答函数
from app.rules import permissions
from app.rules.permissions import 权限条目


def 假认权限(主张: str, 权限矩阵: Sequence[权限条目]) -> str | None:
    """`模型位.认权限` 的假实现：**走关键词那条老路**，只把答案换成编号。

    和 `假模型` 不是一类东西 —— 它不吐文本、也不记 prompt，因为它要顶掉的那个
    位（`deps.模型位.认权限`）的形状是
    `Callable[[str, Sequence[权限条目]], str | None]`，不是「问一句答一句」。

    ⚠️ **矩阵那一格必须用起来，不能收下就丢。** 它就是本轮的活矩阵，真模型
    也是**在收到的这张表里挑**（`llm/认权限.认权限`）；收下不看、转头去认全表，
    假实现就比真实现宽松 —— `E05` 会在 H3 不在的回合被它认出来，而真链路
    那会儿根本看不见这一行。见 `app/rules/permissions._认到条目`。

    ⚠️ **它必须回编号，不能回 `None` 了事。** 恒回 `None` ＝ 模型说「认不出」，
    第 2 层就一律判 `未列明`、继续第 3 层 —— 该 `报备`／`转交` 的主张会全部
    变成 `AI直发`，而右栏上看着只是「去向和家长不一样」，不会报错。
    走关键词的话，接这个位前后判出来的是同一个结果，测试才有对照。
    """
    条目 = permissions.认权限(主张, 权限矩阵)
    return 条目.编号 if 条目 is not None else None


def 假拆需求(*_参数: object, **_其余: object) -> list[str]:
    """`模型位.拆需求` 的假实现：**谁调它谁红**。

    第七个位不在判定链路上（它只属于 `POST /api/需求分解`，见 `deps.模型位` 的
    字段文档串）。而 `test_判定.py` ／ `test_动作.py` 的夹具是**整套 `模型位`
    一起换**的，所以那几处必须给它一个值 —— 但给不出一个「合理的假答案」：
    在那两条路上**正确的行为是根本不来问**。

    真被叫到就是接线错了：判定那条路会平白多花一次模型调用（真数据里一条会话
    一次），而右栏上**看不出任何区别**。所以这里直接抛，让它在测试里响。
    """
    raise AssertionError("判定／动作这条路上不该问需求分解 —— 它只属于 POST /api/需求分解")


def 假模型(*回答: str | Exception) -> tuple[问答函数, list[tuple[str, str]]]:
    """一个按顺序吐答案的假模型，同时把收到的 prompt 记下来。

    用完最后一个答案后**停在最后一个上**（`min(序号, len-1)`）——
    重试类的测试要的是「一直吐同一句」，不是越界炸掉。

    传 `Exception` 实例就抛它，用来造 `LLM不可用` 那条路。
    """
    记录: list[tuple[str, str]] = []
    序号 = 0

    def 问(提示: str, 系统: str = "") -> str:
        nonlocal 序号
        记录.append((系统, 提示))
        答案 = 回答[min(序号, len(回答) - 1)]
        序号 += 1
        if isinstance(答案, Exception):
            raise 答案
        return 答案

    return 问, 记录
