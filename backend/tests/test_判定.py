#: 就测不出来。见 `test_没出稿那轮卡面不说稿子被拦`。
假降级们: dict[str, bool] = {}

#: `_假生成话术` 最近一次收到的命中，给 `test_闸门搬得了命中的每个字段` 用。
上次命中: list[Any] = []


@contextmanager
def 假模型改回(**换成: Any) -> Any:
    """临时换掉假模型的某个行为，退出时还原。

    就地改模块级变量而不还原的话，**下一条测试会继承这一条设的命中** ——
    它会以「主卡话术不对」的样子红，而问题出在上一条测试没收拾干净。
    """
    旧 = {名字: globals()[名字] for 名字 in 换成}
    globals().update(换成)
    try:
        yield
    finally:
        globals().update(旧)


def _假生成话术(
    判成: Any,
    顾客情况: Any = (),
    触发列表: Any = (),
    口径表: Any = None,
    已发出: Any = (),
    **_: Any,
) -> Any:
    """假模型。话术里带上主张，好断言「主卡那句话术是哪条主张的」。

    **`转交`／`报备` 抛** —— 和真实现一致（`话术生成.不支持的去向`）。
    假模型要是在这两种去向上也乖乖返回，路由把该派给固定表的活派给了模型
    也测不出来。
    """
    生成调用.append(判成.主张)
    if 判成.输出 not in (输出类型.AI直发, 输出类型.客服点发送):
        raise 不支持的去向(f"{判成.输出} 不归话术生成管")
    # ⚠️ **收 `口径表数据`（带 `.待核对数字()`），不是里面那个行元组。**
    # 这条断言是补上的：路由一开始传的是行元组，而假模型 `**_` 全吞了 ——
    # 测试全绿，真模型一路上跑到 `组装提示.取可引用` 才炸
    # `'tuple' object has no attribute '取'`，报错还从模型线的文件里发出来。
    # 假实现**该用真实现的参数**，不然它就不是替身，是个更宽松的假门。
    assert hasattr(口径表, "待核对数字"), f"口径表传错了：{type(口径表)}"
    命中 = tuple(假命中们)
    上次命中.clear()
    上次命中.extend(命中)
    没出稿 = 假降级们.get(判成.主张, False)
    return 生成结果(
        # 没出稿时话术是**空串** —— 客服手上没有可改的稿子（真实现同一形状）。
        话术="" if 没出稿 else f"【假话术】{判成.主张}",
        去向=输出类型(假去向.get(判成.主张, 判成.输出)),
        命中=命中,
        用到的依据=假用到依据.get(判成.主张, ()),
        降级=pipeline.造降级("", ()) if 没出稿 else None,
        调用次数=1,
    )


def _假命中(编号: str = "G2", *, 降级去向: str = "") -> Any:
    """一条中危命中。

    `降级去向` 默认空串 ＝ **只提示、不改变去向**（`guards.闸门命中` 的文档串）。
    给一个值就是「命中自己把去向抬起来」那条路 —— 卡面「稿子没过检查」说的
    正是它，所以断言那句话的用例得喂一条这样的命中，不然它验的是
    **没出稿**那个形状（两者在 `生成结果.去向` 上撞成同一个值）。
    """
    return 闸门命中(
        闸门=编号,
        名称="措辞",
        严重度="中",
        详情="用了绝对化词",
        证据=("一定",),
        建议="换个说法，别把话说死",
        可重生成=True,
        降级去向=降级去向,
    )


