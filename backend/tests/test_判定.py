    会 = 装载器.从表(_承诺表(末条时刻)).会话列表[0]
    行 = next(r for r in 整会话顾客情况(会) if r.标签 == "答应过什么")
    assert 行.时限 == 承诺到期, "承诺没解析出来，下面断的就是别的东西了"
    assert 行.警示 == 期望


