#: 走过 3c 的主张，`用上` 取**模型自报**；没走 3c 的（`报备`／`转交`）保持
#: 检索层原值。两套取值并存是 spec §6.4 的原话：
#:
#: - 过闸门那一侧（`guards.过闸门` 收的 `依据`）归一成 `True`
#:   —— 闸门问的是「检索有没有材料」，而 `判成` 第 1 层已经认证过了
#: - 进右栏那一侧取模型自报 —— 右栏问的是「这句话引了哪几条」
#:
#: ⚠️ **`报备` 那条没有自报可取。** 它的话术来自固定表、根本没进模型，
#: 拿不到「模型引了哪几条」。所以它只能保持 `源记录.用上`（恒 `True`）——
#: 而那个 `True` 在这里是**诚实的**：那三条硬边界是照 ⑥ 工单写的，
#: 依据确实被用上了，只是用的人不是模型。


@pytest.mark.usefixtures("装了")
async def test_用上取的是模型自报不是检索层的常量() -> None:
    """`Evidence.用上` 得回答「这句话引了没有」，不是「查没查到」。

    不接自报的话它是**恒 `True`** 的 —— `源记录.用上` 在检索层永远是 `True`
    （`六源.py` 的文件头：出去的每一条都是 `exists=True`、`用上=True`）。
    恒真的后果不是屏幕上多个勾：右栏 `N/6 源命中` 恒等于「查到了几源」，
    展开后那段「未命中的六源清单」恒为空 —— **「查到」和「引用」被一个常量
    合并成了一个词**，而两处都看着对。

    线一第 1 轮：`含乙醇` 自报 ② 口径表 K10，`孕妇能否使用` 自报空。
    于是 K10 那行 `用上`、① 商品属性表和 K01 那行不 `用上`。
    """
    with 假模型改回(假用到依据={"含乙醇": ("口径表 · K10",)}):
        主卡 = (await 判("S_DEMO_A", 轮次=1))["主卡"]

    自报的 = [e for e in 主卡["依据"] if e["出处"] == "口径表 K10"]
