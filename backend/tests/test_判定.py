#: `生成话术` 被调过的主张，按调用顺序记。
#:
#: 记它是因为**多调一次就是多一次 API 调用**，而演示那天每分钟都在烧钱；
#: 更糟的是「该生成的那条没生成」不会报错，只会让主卡少一句 `话术`。
生成调用: list[str] = []


#: 下一次 `_假生成话术` 该回哪些命中。默认为空 ＝ 回一稿干净的。
假命中们: list[Any] = []

#: 主张 → **压低后**的去向。没列的主张照 `判成.输出` 原样回。
#:
#: 只用来验「`生成结果.去向` 和 `判成.输出` 不一样时，路由听谁的」。
#: 压低**规则**本身（G3 怎么把 AI直发 压成客服点发送）是模型线的东西，
#: 在 `test_话术生成.py` 里测；在这里重写一遍规则的话，两边各有一份，
#: 改了一边另一边还是绿的。
假去向: dict[str, str] = {}

#: 主张 → 模型自报的出处（`生成结果.用到的依据`）。没列的主张自报空。
#:
#: **默认空是有意义的**：它等于「模型说这条话我没引任何依据」，
#: 而那正是 `Evidence.用上` 该照着填的东西（spec §6.4）。
假用到依据: dict[str, tuple[str, ...]] = {}

#: `_假生成话术` 最近一次收到的命中，给 `test_闸门搬得了命中的每个字段` 用。
上次命中: list[Any] = []


@contextmanager
def 假模型改回(**换成: Any) -> Any:
    """临时换掉假模型的某个行为，退出时还原。

    就地改模块级变量而不还原的话，**下一条测试会继承这一条设的命中** ——
    它会以「主卡话术不对」的样子红，而问题出在上一条测试没收拾干净。
    """
    旧 = {名字: globals()[名字] for 名字 in 换成}
    globals().update(换成)
    try:
        yield
    finally:
        globals().update(旧)


def _假生成话术(
    判成: Any,
    顾客情况: Any = (),
    触发列表: Any = (),
    口径表: Any = None,
    已发出: Any = (),
    **_: Any,
) -> Any:
    """假模型。话术里带上主张，好断言「主卡那句话术是哪条主张的」。

    **`转交`／`报备` 抛** —— 和真实现一致（`话术生成.不支持的去向`）。
    假模型要是在这两种去向上也乖乖返回，路由把该派给固定表的活派给了模型
    也测不出来。
    """
    生成调用.append(判成.主张)
    if 判成.输出 not in (输出类型.AI直发, 输出类型.客服点发送):
        raise 不支持的去向(f"{判成.输出} 不归话术生成管")
    # ⚠️ **收 `口径表数据`（带 `.待核对数字()`），不是里面那个行元组。**
    # 这条断言是补上的：路由一开始传的是行元组，而假模型 `**_` 全吞了 ——
    # 测试全绿，真模型一路上跑到 `组装提示.取可引用` 才炸
    # `'tuple' object has no attribute '取'`，报错还从模型线的文件里发出来。
    # 假实现**该用真实现的参数**，不然它就不是替身，是个更宽松的假门。
    assert hasattr(口径表, "待核对数字"), f"口径表传错了：{type(口径表)}"
    命中 = tuple(假命中们)
    上次命中.clear()
    上次命中.extend(命中)
    return 生成结果(
        话术=f"【假话术】{判成.主张}",
        去向=输出类型(假去向.get(判成.主张, 判成.输出)),
        命中=命中,
        用到的依据=假用到依据.get(判成.主张, ()),
        调用次数=1,
    )


