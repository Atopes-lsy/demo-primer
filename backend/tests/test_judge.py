# ── 依据的形状：序号得带得出来 ──────────────────────────────

def test_依据带得出六源序号():
    """**序号在 `六源结果.记录` 的键上，不在 `源记录` 上。**

    `源记录.__slots__` 就 `exists/table/row_id/content/用上` 五个字段，没有序号 ——
    序号是那个 dict 的**键**。所以 `_判一条` 里要是用 `.values()` 把它拍平，
    序号在拍平那一步就没了，之后无论谁接手都凑不出 `Evidence.序号`：
    G3 那句「引用的表名＋行号必须真实存在」没了回查的锚，右栏的依据清单
    也标不出「这是第几源查到的」。

    刻意填**两个源**：只填①的用例，写死 `序号="①"` 的假修法也能过。
    """
    主张 = "这个精华有乙醇吗"
    记录 = dict(空六源结果(主张).记录)
    记录[六源.商品属性表] = (
        源记录(exists=True, table="商品属性表", row_id="P07", content="无乙醇"),
    )
    记录[六源.不良反应投诉] = (
        源记录(
            exists=True,
            table="不良反应／投诉记录",
            row_id="R12",
            content="同批次 1 例过敏反馈",
        ),
    )
    结论 = _判定(
        主张列表=[主张],
        消息=[主张],
        六源表={主张: 六源结果(主张=主张, 记录=记录)},
    )[0]

    实收 = [(e.序号, e.出处, e.摘要) for e in 结论.依据]
    assert 实收 == [
        ("①", "商品属性表 · P07", "无乙醇"),
        ("⑤", "不良反应／投诉记录 · R12", "同批次 1 例过敏反馈"),
    ], "每条依据带自己的序号，顺序按六源顺序 —— 同一份输入跑两遍要一样"


def test_依据的用上原样搬运源记录():
    """`源记录.用上` 是检索层判的「这条跟本主张相关」，**不是**「话术引没引」。

    出货之后模型自报用没用到，是在这之上再改一层；判定这一层只负责别丢。
    它同时是 G3 的载重件：`G3来源可查` 拿 `[e for e in 依据 if e.用上]` 当
    「有没有支撑」的判据，全 False 就判高危「没有任何依据支撑」。
    """
    主张 = "这个精华有乙醇吗"
    记录 = dict(空六源结果(主张).记录)
    记录[六源.商品属性表] = (
        源记录(exists=True, table="商品属性表", row_id="P07", content="无乙醇", 用上=True),
        源记录(exists=True, table="商品属性表", row_id="P08", content="另一条没被采用", 用上=False),
    )
    结论 = _判定(
        主张列表=[主张],
        消息=[主张],
        六源表={主张: 六源结果(主张=主张, 记录=记录)},
    )[0]

    assert all(isinstance(e, 依据条目) for e in 结论.依据), "转换得真的发生"
    assert [e.用上 for e in 结论.依据] == [True, False], "用上不能被抹平成同一个值"


def test_造降级带得出依据():
    """`降级结果.依据` 的文档串写着「客服要判断这句该不该发，得看得见材料」——
    但早先的签名里没有依据可传，那个字段有文档、有意义、恒空。

    **空元组是合法取值**（G3 报「没有任何依据」时本来就该是空的），
    所以测的是「填得进去」，不是「不许空」。
    """
    依据 = (依据条目(序号="①", 出处="商品属性表 · P07", 摘要="无乙醇"),)
    命中 = [
        闸门命中(
            闸门="G4",
            名称="防矛盾",
            严重度="高",
            详情="话术谎称已补发，而工单里没有这条",
            证据=("已经为您安排补发",),
            建议="改为「我帮您提交申请，具体以审核结果为准」",
            可重生成=False,
        )
    ]
    降 = 造降级("已经为您安排补发", 命中, 依据=依据)

    assert 降.依据 == 依据, "客服改稿时要看得见材料"
    assert 降.话术 == "已经为您安排补发", "原文要留着，改比从零写快"
    assert len(降.原因) == 1 and "G4" in 降.原因[0]
