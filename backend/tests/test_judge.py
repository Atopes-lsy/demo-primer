"""硬触发 → 三层判定 → 收敛，整条链的测试。

**为什么单独一个文件：** `pipeline.py` 在这次重构之前是**零测试零调用点** ——
改它的时候没有任何东西会红，所以这些用例是它唯一的安全网。跟 `test_rules.py`
的分工是：那个文件盯的是单条规则（H 触发准不准、G 闸门拦不拦），
这个文件盯的是**规则之间怎么接**（命中之后去哪一层、哪一层能改判谁）。

写法上刻意**不手搓 `触发(...)` 对象，一律调真的 `硬触发`**。手搓的话
「H2 命中 → 转交」这条接线断了也测不出来 —— 测的就只剩 `三层判定` 自己
那一半，而这次重构改的恰恰是接线。代价是每个用例都得给 `消息`，
所以统一走 `_判定` 这个口子。

数据层还没上，所以依据一律用 `_查到()` 现造。构造出来的 `六源结果` 除了
**结构合法**之外不代表任何真实数据 —— 真实的查询要等 `docs/开发步骤.md`
的步骤 1。
"""

from __future__ import annotations

from datetime import datetime

from app.rules.guards import 依据条目, 闸门命中
from app.rules.permissions import 权限事实
from app.rules.pipeline import (
    三层判定,
    收敛,
    涉个体差异,
    输出类型,
    造降级,
)
from app.rules.sources import 六源, 六源结果, 源记录, 空六源结果
from app.rules.triggers import 硬触发

#: 所有用例共用一个「现在」。逾期与否是拿它比出来的，写死在用例里，
#: 不取 `datetime.now()` —— 否则测试会随运行日期改变结论。
现在 = datetime(2026, 9, 28, 10, 0)

#: 一个已经过去两天的承诺时限，用来点 H3。
逾期时限 = datetime(2026, 9, 26, 23, 59)


def _判定(
    主张列表: list[str],
    消息: list[str],
    承诺时限: datetime | None = None,
    顾客情况: list[tuple[str, str]] | None = None,
    六源表: dict[str, 六源结果] | None = None,
    权限事实表: dict[str, 权限事实] | None = None,
) -> list:
    """跑「硬触发 → 三层判定」，返回 `判成` 列表。"""
    触发列表 = 硬触发(消息=消息, 当前=现在, 承诺时限=承诺时限)
    return 三层判定(
        主张列表,
        触发列表,
        六源=六源表,
        顾客情况=顾客情况 or (),
        权限事实表=权限事实表,
    )


def _查到(主张: str, 内容: str = "成分表：水、甘油、丁二醇") -> 六源结果:
    """造一份「查得到」的六源结果 —— 只填①商品属性表，其余五源空。

    第 1 层问的是 `有记录()`（有没有查到东西），所以填一源就够它走
    「查得到」那条路；`命中源()` 会因此只有 1/6，那是右栏的事不是这里的事。
    """
    空 = 空六源结果(主张)
    记录 = dict(空.记录)
    记录[六源.商品属性表] = (
        源记录(exists=True, table="商品属性表", row_id="P07", content=内容),
    )
    return 六源结果(主张=主张, 记录=记录)


