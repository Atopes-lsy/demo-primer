def test_个体差异只读这是谁不读这次要什么():
    """**从「这次要什么」里读健康词会把上一件事的属性染到下一件事上。**

    实测来源是演示剧本第 3 步：那一轮的「这次要什么」写的是
    「礼盒赠品漏发 ＋ 孕期能否用」，而本轮同时有「赠品漏发」这条主张 ——
    整张小卡一起读的话，一句补发通知也会被判成涉个体差异，
    于是一句「已经帮您补发」得配上「建议咨询医生」。

    顾客的身体情况是**这个人的属性**，归「这是谁」；「这次要什么」说的是
    **这件事**。v9 那句「读小卡不从主张抠词」要的是别漏（顾客分两句说），
    不是把整张小卡的词往每条主张上套。
    """
    小卡 = [("这是谁", "新客 · 首次到店"), ("这次要什么", "礼盒赠品漏发 ＋ 孕期能否用")]
    assert 涉个体差异("赠品漏发", 小卡) is False, "「这次要什么」里的孕期不该染到赠品上"
    assert 涉个体差异("赠品漏发", [("这是谁", "怀孕三个月")]) is True


