"""拿**真** `业务数据.xlsx` 打一遍装载器。

# 和 `test_装载器.py` 的分工

那边用合成行测「行 → 会话 的转换对不对」，和文件系统无关。
这边只回答另一个问题：**那份真文件装进来是什么样**。

两个问题的红线不一样：**这边是数据换版本就该红，那边是逻辑坏了才红**。
混在一起的话，赛题发个新版本来，一堆本该稳定的逻辑测试跟着红，红在哪条
全靠读名字分辨。

# 文件缺了就是失败，不 skip

2026-09-29 之前这份文件在仓库外，这里因此是 `pytest.skip` —— 当时的理由是
「别人 checkout 下来本来就没有它，fail 会让人以为代码坏了」。**那个理由
现在不成立了**：文件搬进了仓库根的 `data/`（`配置.默认业务数据`），
checkout 即得。

而给一个**仓库内**的文件留静默跳过是更坏的交易：它被删掉或被改名时，
这 7 条会从报告里消失 —— 全绿和「都通过了」长得一模一样，没人会发现少了
一层。缺了就红，红信息里带着路径，这是更好的结果。

文件真被指到别处（`PRIMER_XLSX`）时，报错来自 `读工作簿` 的
`业务数据缺失` —— 那条消息里带着它实际去找的路径。

# 这里钉的是三个数

138 / 113 / 80。它们都**不是**代码里的常量 —— 是赛题数据的事实。改了说明
要么数据换了版本，要么装载器把行丢了（比如按 `会话ID` 过滤时把空的那批
一起滤掉了）。第二种是安静的错，正是这条测试要拦的。
"""

from __future__ import annotations

import pytest

from app.api import schemas
from app.data.装载器 import 装成会话, 读工作簿
from app.配置 import 取配置

#: 赛题数据的三个事实。**不是我们定的** —— 数据换版本就该改这里。
会话数 = 138
订单数 = 113
工单数 = 80

工单表名 = ["补发换货工单", "线下打款工单", "物流工单", "不良反应工单", "售后退货工单"]


@pytest.fixture(scope="module")
def 表() -> dict[str, list[dict[str, object]]]:
    """读一次，模块内共用。

    **没有 `路径.exists()` 那一层判断了**（见模块文档串）：文件缺了就让它抛
    `业务数据缺失`，那条消息里带着实际去找的路径。
    """
    return 读工作簿(取配置().业务数据路径)


def test_装出138个会话且都不空(表) -> None:
    会话们 = 装成会话(表)
    assert len(会话们) == 会话数
    assert len({s.会话ID for s in 会话们}) == 会话数, "有会话 ID 重复，分组键用错了"
    assert all(s.消息 for s in 会话们), "出现了没有消息的会话"


def test_消息一条没丢(表) -> None:
    """998 条 = 聊天记录工作表的行数。

    装载器按 `会话ID` 分组，`会话ID` 为空的那些行会被丢掉 —— 这个过滤是必要的
    （空行、说明行），但如果哪天过滤条件写宽了，丢的就不只是空行。
    """
    总数 = sum(len(s.消息) for s in 装成会话(表))
    assert 总数 == len(表["聊天记录"])


def test_113个会话有订单(表) -> None:
    会话们 = 装成会话(表)
    有订单 = [s for s in 会话们 if s.订单 is not None]
    assert len(有订单) == 订单数
    assert len({s.订单.订单号 for s in 有订单}) == 订单数, "订单挂重了"


def test_80个会话有工单(表) -> None:
    会话们 = 装成会话(表)
    有工单 = [s for s in 会话们 if s.工单 is not None]
    assert len(有工单) == 工单数


def test_没有会话同时有两张工单(表) -> None:
    """契约写的是「一个会话至多一笔订单、至多一张工单」，所以 `Session` 里
    `工单` 是单值不是数组。

    **这条是那个契约前提的证据。** 数据哪天变成一个会话两张工单，单值字段
    会静默丢掉后一张 —— 右栏少显示一张工单，而没有任何东西会报错。
    """
    行数 = sum(len(表.get(名, [])) for 名 in 工单表名)
    assert 行数 == 工单数, "五张工单表的行数和「有工单的会话数」对不上"


def test_系统推送那16条装得进来(表) -> None:
    """这批是**这次契约改动加第四个角色的直接理由**。

    如果哪天有人把 `系统推送` 从 `SenderRole` 里去掉，这里会以
    「ValidationError: 角色 不是合法取值」的形式当场红 —— 而不是等到
    加载器在演示前夜静静地少 16 条消息。
    """
    条数 = sum(
        1
        for s in 装成会话(表)
        for m in s.消息
        if m.角色 == "系统推送"
    )
    assert 条数 == 16


def test_真数据里的角色和内容类型都在枚举里(表) -> None:
    """枚举少一个值的话，上面那些测试会以校验错的形式红；这条把原因说清楚。

    数据集是赛题定的，我们不控制它加什么 —— 所以「枚举够不够」这件事得有人
    定期问一次，而不是等某天装载器抛一个 pydantic 的 ValidationError。
    """
    角色允许 = set(schemas.SenderRole.__args__)
    角色们 = {m["角色"] for m in 表["聊天记录"]}
    assert 角色们 <= 角色允许, f"数据里有枚举装不下的角色：{角色们 - 角色允许}"

    类型允许 = set(schemas.ContentType.__args__)
    类型们 = {m["内容类型"] for m in 表["聊天记录"]}
    assert 类型们 <= 类型允许, f"数据里有枚举装不下的内容类型：{类型们 - 类型允许}"
