# ── 并列写法：「不含 A 和 B」────────────────────────────
#
# 20 个真商品里 13 个含香精，所以「不含酒精和香精」是**半真半假**的一句：
# 前半句真、后半句假。而它可以两个方向都从旧判据漏过去 —— 旧判据要求否定词
# 紧挨着物质名，而「香精」前面是「酒精和」，一个字都不是否定词。


def test_G3并列写法也要拦():
    """「不含 A 和 B」是客服最自然的写法，否定词得管到**整串**。

    ⚠️ **旧判据下词序决定结果**：「不含香精和酒精」拦得住（香精紧挨着否定词），
    「不含酒精和香精」放行 —— 是同一句话的两个写法。
    """
    for 说法 in ("本品不含酒精和香精", "本品不含酒精、香精", "本品不含香精和酒精"):
        命中 = G3来源可查(说法, 商品依据(精华物质))
        assert any("香精" in h.证据 for h in 命中), f"该拦没拦：{说法} → {命中}"


def test_G3分句之外的不算():
    """否定词的作用域到分句为止，**不跨句**。

    「本品不含酒精，香精含量0.1%」后半句是个陈述，不是否定。让「不含」跨过分号
    去管香精的话，这句会被读成「说不含香精」——**误拦**。误拦和漏放一样糟：
    客服被冤枉两次之后就不看这道闸了。

    顿号不是分句标点（`不含酒精、香精` 里的它是并列，得继续管）。
    """
    assert G3来源可查("本品不含酒精，香精含量0.1%", 商品依据(精华物质)) == []
    assert G3来源可查("本品不含酒精。香精是有的", 商品依据(精华物质)) == []


def test_G3分句内后出现的断言说了算():
    """没有标点时，**后出现的断言覆盖前面的**。

    「不含酒精但含香精」——「但」把前半句翻了过来。取分句内位置更靠后的断言，
    这里就读成「含香精」，而香精确实有 → 是真话，放行。

    **这一条不需要单独识别转折词**：位置比较天然把「但／可是／然而」处理掉了，
    而列一张转折词表就得一直往里补词。反过来说，假话也按同一个规则拦：
    「不含香精但含酒精」读成「说不含香精」→ 拦。
    """
    assert G3来源可查("本品不含酒精但含香精", 商品依据(精华物质)) == []
    assert G3来源可查("本品含香精但不含酒精", 商品依据(精华物质)) == []

    命中 = G3来源可查("本品不含香精但含酒精", 商品依据(精华物质))
    assert any("香精" in h.证据 for h in 命中), f"该拦没拦：{命中}"


