# ── G3 · 待核对数字 ─────────────────────────────────────────
#
# 「这个数**有**出处」和「这个出处**被业务方确认过**」是两件事。K03/K05/K07
# 的时效数字业务方还没点头（口径表元数据里标着「待核对」），所以追到出处也
# 不能放行 —— 否则闸门就是在替一个没人确认过的数担保。
#
# ⚠️ **这一整块在 2026-10-01 之前一条都没生效过。** `候选` 是
# `G3带单位数字.finditer(话术)` 返回的**惰性迭代器**，上面 `编的` 那个推导式
# 把它整个取完之后，下面 `没定的` 再 for 一遍拿到的是空的 —— 于是
# 「待核对」分支恒不命中，而且**没有任何测试会发现**，因为漏的是「少报一条中危」，
# 不报错、不影响放行、右栏只是安静地少一行。下面两条就是钉这件事的。


def test_G3待核对数字要报中危():
    """追得到出处、但那个出处业务方还没确认 —— 报中危，并且给出降级去向。

    **中危不是「随便提一下」。** `降级去向` 必须非空：不阻断不等于可以
    AI 直发，调用方要拿这个字段把去向压到客服点发送（`话术生成.可直发`）。
    """
    依据 = [依据条目("②", "口径表 K05", "补发一般在48小时内发出")]
    命中 = G3来源可查("会在48小时内发出", 依据, 待核对=("48 小时",))
    assert 命中, "待核对数字没被报出来 —— 大概率是 `候选` 迭代器被上面取空了"
    assert any(h.严重度 == "中" and h.可重生成 is False for h in 命中), (
        "待核对是修不动的，重生成改变不了它"
    )
    assert all(h.降级去向 for h in 命中), "待核对必须给降级去向，否则调用方会当普通提示放过去"


def test_G3待核对和编造互不吞并():
    """一句话里两个数字，一个是编的、一个是有出处但没确认的 —— **两条都要报**。

    这条钉的是两个分支**共用同一个 `候选`** 这件事。上面那条只证明了
    「单独一个待核对数能报出来」；一旦有人把 `候选` 改回迭代器，
    上面那条还是绿的（`编的` 为空，取不完也没关系），只有这条会红。
    """
    依据 = [依据条目("②", "口径表 K05", "补发一般在48小时内发出")]
    命中 = G3来源可查("会在48小时内发出，3个工作日到账", 依据, 待核对=("48 小时",))
    详情 = " ".join(h.详情 for h in 命中)
    assert "找不到出处" in 详情, "编造的那个数（3个工作日）漏了"
    assert "尚未确认" in 详情, "待核对的那个数（48小时）被编造分支吞了"


# ── G3 · 成分断言（物质名不像数字，抠词在这里正好失效） ──
#
# G3 原先**只扫带单位的数字**。话术里的「不含香精」这种断言一个闸门都不验，
# 而 13/20 的商品含香精、17/20 含苯氧乙醇 —— K10 那句「成分安全(酒精/香精)」
# 说的正是这两样。
#
# ⚠️ **这条检查不能用子串做。** 「苯氧乙醇」逐字含「乙醇」，
