#: 前段那张**补发**工单的号。后段那张是**物流**单 `WL000000001`，两个号必须不同：
#: 「认得出那句承诺挂的是前段那张票」正是这一组数据要测的事（`装配._未兑现`）。
合并补发单号 = "BF000000001"


def 造合并表(前段补发物流单号: str | None = "YT0000000000001") -> dict[str, list[dict[str, Any]]]:
    """同一个人来两次的合成表 —— 测按顾客合并窗口（`data/顾客窗口.py`）。

    前段 `SA` 5/5：补发小样没收到 → 客服许了「48 小时内发出」；
    后段 `SB` 5/9：收到了，谢谢。合并之后左栏只剩 `SB` 一条，
    前段那两条消息压成 `以前` 里的一行、并计入 `起演格`。

    身份字段（订单、工单）**只挂在后段上**，这是刻意的：窗口的身份取末段，
    `这单`／`办过什么` 说的就是这一次来访。前段那张票只活在 `以前` 和票表里。

    # 参数是这组数据的重点：前段那张补发单**发没发出去**

    - 有值 = 货发出了 = 那句承诺兑现了，**不该**报逾期（默认）；
    - `None` = 还没发 = 该报红字。

    `test_接口.py` 拿这两个方向夹住 `装配._未兑现` 的 `票表` 那一路：
    **不传票表**的话，窗口的 `工单` 是后段那张**物流**单，拿它去核补发单
    核不上，于是货早发出去了屏幕上还顶着「已逾期 2 天」。
    """
    前段票 = 造工单("补发换货工单", "SA", 工单号=合并补发单号)
    前段票.update(
        {
            "买家昵称": 合并昵称,
            "关联订单号": "XL90000",
            # 必须是 5/5：`以前[0].日期` 取的就是这行工单的创建日。
            "创建时间": "2026-05-05 10:03:00",
            "补发物流单号": 前段补发物流单号,
        }
    )

    后段票 = 造工单("物流工单", "SB", 工单号="WL000000001")
    后段票["买家昵称"] = 合并昵称

    return {
        "聊天记录": [
            造聊天("SA", 1, 买家昵称=合并昵称, message_text="说好的赠品小样没收到"),
            造聊天(
                "SA", 2, "客服", 买家昵称=合并昵称,
                message_text="亲抱歉！这边 48 小时内发出",
                # 挂在**前段那张票**上 —— 这正是「承诺和末段的工单对不上」的由来。
                关联工单号=合并补发单号,
            ),
            造聊天(
                "SB", 1, 买家昵称=合并昵称,
                发送时间="2026-05-09 10:01:00", message_text="收到了，谢谢",
            ),
            造聊天(
                "SB", 2, "客服", 买家昵称=合并昵称,
                发送时间="2026-05-09 10:02:00", message_text="不客气～有需要随时找我",
            ),
        ],
        "订单": [造订单("SB", 订单号="XL90001", 买家昵称=合并昵称)],
        "补发换货工单": [前段票],
        "物流工单": [后段票],
    }


