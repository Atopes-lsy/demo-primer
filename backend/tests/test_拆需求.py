"""`拆需求`（`app/llm/拆需求.py`）—— 右栏「这次要什么」那一行的产出者。

钉三件事，都是「错了不会报错、只在演示当天露馅」的：

1. **一句买家话都没有时不打模型。** 没有可拆的输入，问一次也只会得到一句客套
   废话；而那条路本来就该落到调用方的原话兜底。
2. **模型出岔子退到空列表，不退到「整段话算一条」。** 后者是一句原话顶在
   「需求」的位置上 —— 比难看更坏，它看着像是拆过的。
3. **去重和条数上限。** 这一行在右栏只有**一行宽**，重复的和超出的会把
   真正的那几条挤掉。

真模型一个都不打：`问=` 收一个两参数函数就顶得上（`客户端.问答函数`）。
"""

from __future__ import annotations

import pytest

from app.llm.拆需求 import 最多条数, 拆需求


def 答(回: str):
    """一个只会照本宣科的「模型」。顺便把收到的提示记下来给用例查。"""
    收过的: list[tuple[str, str]] = []

    def 问(提示: str, 系统: str) -> str:
        收过的.append((提示, 系统))
        return 回

    return 问, 收过的


# ══════════════════════════════════════════════════════════
# 一 · 不打模型的那条路
# ══════════════════════════════════════════════════════════


def test_一句买家话都没有时不打模型() -> None:
    问, 收过的 = 答('{"需求": ["不该走到这儿"]}')
    assert 拆需求([], 问=问) == []
    assert 拆需求(["", "   "], 问=问) == []
    assert 收过的 == [], "空输入不该问模型"


# ══════════════════════════════════════════════════════════
# 二 · 拆出来的是什么形状
# ══════════════════════════════════════════════════════════


def test_模型给几条就是几条() -> None:
    问, _ = 答('{"需求": ["精华是否含乙醇", "孕期能否使用", "赠品补发"]}')
    需求 = 拆需求(["你好，这个精华里有乙醇吗，我怀孕了能用吗", "上周那单赠品一直没收到"], 问=问)
    assert 需求 == ["精华是否含乙醇", "孕期能否使用", "赠品补发"]


def test_提示里一句一行且带着顾客情况() -> None:
    """合成一段的话模型会去猜哪儿是句子的结尾 —— 而本模块整件事就是边界。

    `顾客情况` 也要进提示：同一句「能用吗」，孕妇和普通顾客不是一件事。
    """
    问, 收过的 = 答('{"需求": ["孕期能否使用"]}')
    拆需求(
        ["在吗", "这款能用吗"],
        (("这是谁", "孕 28 周"), ("这次要什么", "礼盒赠品漏发")),
        问=问,
    )
    提示, _ = 收过的[0]
    assert "- 在吗\n- 这款能用吗" in 提示
    assert "这是谁：孕 28 周" in 提示


def test_去重且保持开口顺序() -> None:
    """模型偶尔把同一条写两遍；这一行只有一行宽，重复的直接挤掉别人的位置。"""
    问, _ = 答('{"需求": ["赠品补发", "孕期能否使用", "赠品补发", "  ", "孕期能否使用"]}')
    assert 拆需求(["随便一句"], 问=问) == ["赠品补发", "孕期能否使用"]


def test_超过条数上限就截断() -> None:
    问, _ = 答('{"需求": ["一", "二", "三", "四", "五", "六"]}')
    assert len(拆需求(["随便一句"], 问=问)) == 最多条数


# ══════════════════════════════════════════════════════════
# 三 · 兜底（模型那条路怎么坏都不许抛）
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "回",
    [
        '{"主张": ["字段名写错了"]}',  # 有 JSON、字段不对
        '["需求", "不是对象"]',  # 顶层不是对象
        '{"需求": "不是数组"}',
        "抱歉，我不能回答这个问题",  # 压根不是 JSON
        "",
    ],
)
def test_模型答得不成样子就退到空列表(回: str) -> None:
    问, _ = 答(回)
    assert 拆需求(["这款能用吗"], 问=问) == [], f"这一份该退到空列表：{回!r}"


def test_模型够不着也退到空列表不抛() -> None:
    from app.llm.客户端 import LLM不可用

    def 问(提示: str, 系统: str) -> str:
        raise LLM不可用("网络断了")

    assert 拆需求(["这款能用吗"], 问=问) == []


def test_别的异常照旧往外抛() -> None:
    """**只吞「模型不可用」和「答得不对」这两类。**

    `TypeError`／`ValueError` 是解析那份的，别的一律放出去 ——
    全吞掉的话，本模块自己写错的代码会伪装成「模型今天心情不好」。
    """

    def 问(提示: str, 系统: str) -> str:
        raise RuntimeError("这个不该被吞")

    with pytest.raises(RuntimeError):
        拆需求(["这款能用吗"], 问=问)
