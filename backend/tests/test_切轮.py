"""`pipeline.切轮` —— 消息流切成轮。

# 为什么归属要进 `切轮`

节点 3.5 把「判归属」那半交给了 `认诉求`（模型），**「按归属标签分组」那半留在
`切轮` 里 —— 仍是纯规则**（`一句话进来的流程.md` 节点 3.5 的「顺序影响」）。

所以本文件测的是**纯规则那一半**：给一张「第几条消息属于哪个诉求」的表，
消息流该怎么切。模型准不准不在这儿测。

# 收窄的那个承诺

`切轮` 的文档串原先写着「这条函数是纯的（同一输入必得同一输出，可重放）」，
而整段「规则层可重放」的论证**建立在它之上**。`认诉求` 进来之后，那个承诺
收窄成「**切轮之后的**规则层可重放」—— 因为 `归属` 是从模型那里来的。

注意收窄的**只是「不需要额外输入」，不是「同样输入同样输出」**：
`归属` 一旦给定，`切轮` 对它仍然是纯的（同一份消息 ＋ 同一张归属表 → 同一个结果）。
"""

from __future__ import annotations

from app.rules.pipeline import 切轮, 轮消息


def m(角色: str, 文本: str, 第几条: int) -> 轮消息:
    return 轮消息(角色=角色, 文本=文本, 发送时间=f"2026-09-29 10:{第几条:02d}:00")


#: 两段买家发言被一句客服隔开 —— 结构上本来就是两轮。
甲乙丙 = [
    m("买家", "赠品没到", 1),
    m("买家", "已经三天了", 2),
    m("客服", "我帮您看看", 3),
    m("买家", "好的", 4),
]


# ══════════════════════════════════════════════════════════
# 一 · 不给归属时，行为一点不变
# ══════════════════════════════════════════════════════════


def test_不给归属就是现在的切法() -> None:
    """工单 §3.3：**接口线现在写的调用不用改就能继续跑。**

    它写的是 `轮次 = 请求.轮次 或 切轮(消息)[-1]` —— 参数是加的不是换的，
    所以「演示有退路」这句话才成立。
    """
    轮们 = 切轮(甲乙丙)
    assert [r.买家消息 for r in 轮们] == [("赠品没到", "已经三天了"), ("好的",)]


def test_归属给空字典和不给一样() -> None:
    """空表＝一条意见都没有，不能因为「传了表」就把轮切碎。"""
    assert 切轮(甲乙丙, {}) == 切轮(甲乙丙)
    assert 切轮(甲乙丙, {}) == 切轮(甲乙丙, None)


# ══════════════════════════════════════════════════════════
# 二 · 客服发言照样结束一轮（归属是「多一条」不是「换一条」）
# ══════════════════════════════════════════════════════════


def test_客服发言照样结束一轮() -> None:
    """工单 §3.1 说的是「分组依据**多一条**」。

    所以客服／AI 发言结束当前轮这条留着 —— 哪怕前后两条买家消息属于
    同一个诉求，中间隔着客服的话仍是两轮。**别把这条顺手删掉**：
    删了 `轮次` 会跨客服回复，`判定.py` 拿 `切轮(消息)[-1]` 取本轮的用法
    会一次带走一整段历史。
    """
    轮们 = 切轮(甲乙丙, {0: "赠品补发", 1: "赠品补发", 3: "赠品补发"})
    assert len(轮们) == 2, "客服那一句没能把轮断开"


# ══════════════════════════════════════════════════════════
# 三 · 归属把连续的买家发言切开
# ══════════════════════════════════════════════════════════


def test_相邻两条归属不同就切开() -> None:
    """**这是这一整节要的新行为。**

    顾客连发「赠品没到」「另外我要开发票」—— 结构上是一轮（中间没有客服），
    但那是**两件事**，得分成两轮：H2 的窗口按诉求算、G4 防重复也按诉求算，
    混在一轮里两条诉求共用一个窗口，两边都不准。
    """
    消息 = [m("买家", "赠品没到", 1), m("买家", "另外我要开发票", 2)]
    轮们 = 切轮(消息, {0: "赠品补发", 1: "开发票"})
    assert [r.买家消息 for r in 轮们] == [("赠品没到",), ("另外我要开发票",)]


def test_同一诉求的连续发言不切开() -> None:
    """上一条的另一半：**归属相同就不切。**

    这正是 H2 连发检测要看到的形状 —— 顾客连发「在吗」「在吗？」「在吗！」
    三条属于同一个诉求，得留在同一轮里才凑得到阈值 3。
    """
    消息 = [m("买家", "在吗", 1), m("买家", "在吗？", 2), m("买家", "在吗！", 3)]
    轮们 = 切轮(消息, {0: "催促发货", 1: "催促发货", 2: "催促发货"})
    assert [r.买家消息 for r in 轮们] == [("在吗", "在吗？", "在吗！")]


def test_三件事连发切成三轮() -> None:
    消息 = [m("买家", "赠与没到", i + 1) for i in range(3)]
    轮们 = 切轮(消息, {0: "赠品补发", 1: "开发票", 2: "脸部过敏"})
    assert len(轮们) == 3


# ══════════════════════════════════════════════════════════
# 四 · 判不出来时不切
# ══════════════════════════════════════════════════════════


def test_键缺失的那条不切开() -> None:
    """工单 §3.3：**归属判不出来时（模型挂了、超时）不会整条链断掉。**

    「没有意见」不等于「意见是空的」，所以它**不造成切分** —— 跟随前一条。
    反过来做（缺一条就切一刀）的后果是模型一抖，一轮碎成好几轮，
    而屏幕上看起来什么都没变。
    """
    消息 = [m("买家", "赠品没到", 1), m("买家", "已经三天了", 2)]
    assert [r.买家消息 for r in 切轮(消息, {0: "赠品补发"})] == [("赠品没到", "已经三天了")]
    # 和「两条都打了同一个标签」结果一样 —— 缺键就是跟随前一条。
    assert 切轮(消息, {0: "赠品补发"}) == 切轮(消息, {0: "赠品补发", 1: "赠品补发"})


def test_空标签当作没说() -> None:
    """`认诉求` 对空消息返回空串（「没有诉求可谈」）。

    它和键缺失是同一件事：**没意见**，不造成切分。当成一个真标签的话，
    一条纯图片消息会在它旁边切出一轮空轮次来。
    """
    消息 = [m("买家", "赠品没到", 1), m("买家", "  ", 2)]
    assert [r.买家消息 for r in 切轮(消息, {0: "赠品补发", 1: ""})] == [
        ("赠品没到", "  ")
    ]


# ══════════════════════════════════════════════════════════
# 五 · 键是什么（定了要写下来）
# ══════════════════════════════════════════════════════════


def test_键是消息在入参里的下标() -> None:
    """**键是 `消息` 序列里的绝对下标，不是「第几条买家消息」。**

    这个区别会静默出错：两套解释都能跑，只是切出来的轮不同，而没有任何东西
    会报错。所以要一条**两套解释结果不同**的输入来钉 —— 序列里得有非买家消息
    把两个下标错开：

        下标：  0      1              2
              客服   买家「赠品没到」  买家「已经三天了」
        买家序号：     0              1

    同一条归属表 `{0:"甲", 1:"甲", 2:"乙"}`：
    - 按**绝对下标**：买家落在 1、2 → 取到「甲」和「乙」→ **切成两轮**
    - 按**买家序号**：买家落在 0、1 → 都取到「甲」→ 不切，**一轮**

    所以下面那条断言红了，就是键的解释被改成了买家序号。
    """
    消息 = [m("客服", "您好", 1), m("买家", "赠品没到", 2), m("买家", "已经三天了", 3)]
    assert [r.买家消息 for r in 切轮(消息, {0: "甲", 1: "甲", 2: "乙"})] == [
        ("赠品没到",),
        ("已经三天了",),
    ]


def test_归属不改变轮的时间() -> None:
    """开始／结束时间仍取那一轮买家消息的首尾。"""
    消息 = [m("买家", "甲", 1), m("买家", "乙", 2)]
    轮们 = 切轮(消息, {0: "甲诉求", 1: "乙诉求"})
    assert [(r.开始时间, r.结束时间) for r in 轮们] == [
        ("2026-09-29 10:01:00", "2026-09-29 10:01:00"),
        ("2026-09-29 10:02:00", "2026-09-29 10:02:00"),
    ]
