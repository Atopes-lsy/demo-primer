def test_全部话术都不含时限() -> None:
    """**不许出现时限** —— 这话是在客服点发送**之前**出去的。

    东西还没发出去就先许一个时限，等于用一句自动回复制造一次新的逾期
    （口径表 K05 说的就是这件事）。
    """
    assert 校验安抚话术() == [], "真实表自己就不合法了"


@pytest.mark.parametrize(
    "坏话术",
    [
        "亲实在抱歉让您久等，24 小时内给您核实答复～",
        "亲别急，3 个工作日内帮您核实～",
        "亲，48小时后答复您～",
    ],
)
def test_校验能查出时限(坏话术: str) -> None:
    """**这条红了才说明校验在干活。**

    上面那条「真实表合法」是个恒真断言 —— 校验函数要是恒返回空列表，
    它照样绿。所以这里喂三条带时限的进去，必须被报出来。
    """
    assert 校验安抚话术({"{坏}": 坏话术}), f"没查出时限：{坏话术}"


@pytest.mark.parametrize(
    "坏话术",
    [
        "亲，已为您登记补发，请放心～",
        "亲，已经帮您核实过了，稍等～",
        "亲，这边已经安排处理了～",
    ],
)
def test_校验能查出已发生表述(坏话术: str) -> None:
    """**不许出现「已 + 动作」。**

    比 G4 更严：这里**整句话里不许出现「已」**。理由是这句出去的时机 ——
    它是在任何人核实之前自动发的，那个时刻**不存在任何「已做过」的事**，
    所以不用去分辨「已」后面接的是不是动作词。

    （G4 得分辨，因为它查的是客服写的自由文本，那里「已」可能只是「已知悉」
    之类。这条是固定表，不用给不存在的输入写代码。）
    """
    assert 校验安抚话术({"{坏}": 坏话术}), f"没查出「已」：{坏话术}"


def test_校验能查出禁语() -> None:
    """禁语复用口径表的 `查禁语全` —— 和闸门 G1 **同一张表**。

    不共用的话，安抚话术会变成一条绕过 G1 的旁路：它是固定表，
    本地校验过了就直接发，闸门那道在不在它身上都无所谓。

    ⚠️ 这里用的是 `放心使用`（K10 的真禁语，实测命中），**不是**「孕妇可以用」
    那种看着像的写法 —— `孕妇可以直接用` 逐字**不**含 `孕妇可以用`，
    拿它当反例会得到一条恒绿的测试。
    """
    assert 校验安抚话术({"{坏}": "亲，放心使用哦，我们保证没问题～"}), "没查出禁语"


def test_真实表过得了三道校验() -> None:
    """导入时那次校验没抛，但这儿再显式钉一次 —— 免得有人把导入时的
    校验删掉（那样测试会静默变成「什么都没查」）。"""
    assert not any("已" in 句 for 句 in 安抚话术表.values())
    assert 校验安抚话术() == []
