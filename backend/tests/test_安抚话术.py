def test_赠品那条就是剧本里那句() -> None:
    """演示当天屏幕上要出现的就是这一句，验收拿剧本原文核。"""
    assert 查安抚话术("赠品未按9月25日承诺的48小时内发出") == 剧本原文


def test_认不出事项给兜底() -> None:
    """**认不出的失败方向是温和的**：兜底本身也满足三条硬约束，只是少一点针对性。
    这和 `H3交接分类` 那种「认不出就空一格」不一样 —— 那边空的是信息，
    这边空的只是措辞。所以按关键词查在这里是可以接受的。
    """
    果 = 查安抚话术("我的脸用了之后过敏了")
    assert 果 == 兜底安抚
    assert "赠品" not in 果, "兜底不该提到具体事项"


#: 2026-10-06 从**真后端**数出来的：114 条窗口 482 轮，29 处报备。
#: 这些是那些报备的 `主张` 原话，一条一条抄下来的（`POST /api/判定` 的
#: `本轮处置[].主张`）—— **不是照 `E01–E05` 的事项名编的**。
#:
#: 每条后面是**句子里该说的那个名词**，不是主张里那个词 —— 两者不同的那几条
#: （「少发」→ 发货、「碎了」→ 破损）正是第二轮扩表要办的事。
真主张 = [
    ("退货运费由谁承担", "退货运费"),
    ("退货运费8.8元尚未支付", "退货运费"),
    ("运费报销款项尚未收到", "运费"),
    ("报销退货运费", "退货运费"),
    ("退货是否需要买家承担运费", "运费"),
    ("申请将#01赤茶红退货换货为#05枫叶红", "退货"),
    ("原路退款未到账", "退款"),
    ("退款仍未到账", "退款"),
    ("补发面霜", "补发"),
    ("赠测试修护精华小样5ml未收到", "小样"),
    ("赠品未按9月25日承诺的48小时内发出", "赠品"),
    # ── 第二轮补上的（原来这七处全落兜底）──────────────────
    ("换货为#05枫叶红", "换货"),
    ("包裹少发洗发水", "发货"),
    ("眼影盘缺失", "发货"),
    ("订单6920675656664226609少发一件商品", "发货"),
    ("两件商品只收到一件", "发货"),
    ("重新发货", "发货"),
    ("面霜瓶子碎了，玻璃渣混着精华洒得到处都是", "破损"),
]


@pytest.mark.parametrize("主张,事项", 真主张)
def test_真主张查得到针对性的那句(主张: str, 事项: str) -> None:
    """**2026-10-06 两轮扩表要证的正是这一条。**

    扩表之前这些全落到兜底 —— 顾客说「退货运费由谁承担」，自动发出去的是
    「**这件事**我立刻帮您核实」。针对性丢了，而 94% 都落到兜底就不叫兜底了。
    """
    assert 查安抚话术(主张) == _安抚(事项), f"「{主张}」没认成「{事项}」"


#: 第二轮那七处里**名词和主张里的词不一样**的。单独钉一条是因为它们看着像
#: 「查表错了」：`查安抚话术("包裹少发洗发水")` 返回的话里没有「少发」两个字。
def test_匹配词和句子里的名词可以不是同一个() -> None:
    """主张里说的是「少发」／「缺失」／「只收到」，句子里说的是「发货」。

    这三个词指的是同一件事 —— 顾客在问**发货**这一趟出了什么岔子，
    所以句子里那个名词就该是「发货」。「少发的事我立刻帮您核实」是
    照主张里的词直搬的结果，读着像内部工单，不像客服说的话。
    """
    assert "少发" not in 查安抚话术("包裹少发洗发水")
    assert 查安抚话术("包裹少发洗发水") == _安抚("发货")
    assert 安抚事项["少发"] != "少发"
    assert 安抚事项["碎"] != "碎"
    # **「分开写」得是少数。** 多数条目匹配词和名词还是同一个，才谈得上
    # 「不含承诺是结构上成立的」—— 要是过半都分开写，那这句话就退化成
    # 「逐条看过」了，句子的骨架也就不再是那个骨架。
    分开的 = [词 for 词, 名 in 安抚事项.items() if 词 != 名]
    assert len(分开的) * 2 < len(安抚事项), f"分开写的太多了：{分开的}"


def test_退货运费压得过运费和退货() -> None:
    """「退货运费由谁承担」同时含「运费」和「退货」—— 取**更长**的那条键。

    钉住它是因为那两条键一样长（都是 2 字），单靠「最长优先」分不出来；
    「退货运费」是 4 字，长度就把它顶到最前，**与表里的先后无关**。
    """
    assert 查安抚话术("退货运费由谁承担") == _安抚("退货运费")
    assert 查安抚话术("减免退货运费") == _安抚("退货运费")


def test_运费和退货同长时取运费() -> None:
    """「退货是否需要买家承担运费」两条 2 字键都中，**长度分不出来**。

    取的是「运费」—— 这一条走的是 `sorted` 的稳定性（键一样长时保持表里的
    插入顺序），所以**表里「运费」必须排在「退货」前面**。这一条是那一处的
    哨兵：谁把两张键调个位置，这里会红。
    """
    assert 查安抚话术("退货是否需要买家承担运费") == _安抚("运费")


def test_补发压得过发货() -> None:
    """「补发货」两条 2 字键都中，**长度分不出来** —— 取「补发」，更具体的那条。

    同 `test_运费和退货同长时取运费`：靠的是 `安抚事项` 里的插入顺序，
    所以**「补发」必须排在「发货」前面**。第二轮扩表加「发货」时最容易踩的
    就是这一脚，加了之后这条哨兵才会红。
    """
    assert 查安抚话术("补发货") == _安抚("补发")
    assert 查安抚话术("重新补发") == _安抚("补发")


def test_关键词最长优先() -> None:
    """和 `permissions.认权限` 同一个分法：具体的压过笼统的。

    「赠品补发」同时含「补发」和「赠品」时，取更长的那条 —— 否则
    「赠品」那条永远轮不到。
    """
    具体 = {**安抚话术表, "赠品补发": "具体那条"}
    assert 查安抚话术("赠品补发", 具体) == "具体那条"


