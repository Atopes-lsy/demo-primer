def test_认出口权限条目编号() -> None:
    问, _ = 假模型("L01")
    assert 认权限("上次那个赠品还没给我发", _小表(), 问=问) == "L01"


def test_明确漏发压过模型误判的赠品追加() -> None:
    """「赠品没看到」和「追加赠品」方向相反，不能让宽泛的赠品词盖住缺失。"""
    问, _ = 假模型("L03")
    assert 认权限("收到货了，但是赠品没看到", 权限条目表, 问=问) == "L01"


def test_模型回NONE就是认不出() -> None:
    """**认不出比认错强**（`认口径` 那句同一条）。

    这里的代价还高一层：认错一行 = 去向判错 —— 该报备的被当成在权限内，
    客服当场就替公司应下了一个他没权限应的事。
    """
    问, _ = 假模型("NONE")
    assert 认权限("这个精华里有乙醇吗", _小表(), 问=问) is None


def test_模型多嘴也能认出来() -> None:
    """模型不会老老实实只回三个字符。取第一个真在表里的编号。"""
    问, _ = 假模型("编号：L01。")
    assert 认权限("上次那个赠品还没给我发", _小表(), 问=问) == "L01"


def test_编出来的编号不认() -> None:
    """模型回了个表里没有的 Z99 —— 不照单全收。

    照收的后果是第 2 层拿着一个查无此条的编号去找条目，要么炸要么静默判成
    未列明，而**右栏不会显示任何异常**。
    """
    问, _ = 假模型("Z99")
    assert 认权限("这个精华里有乙醇吗", _小表(), 问=问) is None


def test_不可认的行认不上() -> None:
    """`可认=False` 的行（`E01–E04`／`X01`）**是「超额度的后果」不是诉求**。

    模型就算把它捡回来也不能算 —— 否则「顾客要求补发」会被认成
    「补发超过 1 件」这种张冠李戴（`permissions.py` 模块文档串）。
    """
    问, _ = 假模型("E01")
    assert 认权限("这个精华里有乙醇吗", _小表(), 问=问) is None


