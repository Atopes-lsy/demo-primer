def test_模型不可用退回关键词认得出() -> None:
    """工单 §八 第 3 条：**离线演示靠它。**

    「赠品漏发」关键词认得出 L01（`关键词=("漏发赠品", "漏发", "补发", ...)`）
    —— 所以够不着模型时给出的必须是 `L01`，不是 `None`。

    退成 `None` 的后果不是报错，是**判定的那一档静默挪了一格**：
    未列明继续第 3 层，而 L01 认上之后要走额度判断、超了要报备。
    """
    问, _ = 假模型(LLM不可用("连接超时"))
    assert 认权限("漏发", _小表(), 问=问) == "L01"


def test_模型不可用且关键词也认不出才返回None() -> None:
    """两条路都走不通才是 `None`（＝未列明）。"""
    问, _ = 假模型(LLM不可用("连接超时"))
    assert 认权限("这个精华里有乙醇吗", _小表(), 问=问) is None


def test_模型不可用不抛() -> None:
    """和 `认口径` 同一条：抛的后果是演示当天模型一抖、右栏整个白掉。"""
    问, _ = 假模型(LLM不可用("连接超时"))
    认权限("漏发", _小表(), 问=问)  # 不抛就算过


def test_退回用的是同一张矩阵不是全量表() -> None:
    """退回时读的必须是**调用方传进来的那张表**，不是模块里的全量表。

    读全量表的话，喂小表的测试会拿到一个它没定义的编号 —— 而那种错只在
    单测里出现，生产上永远看不见（生产传的就是全量表）。**正因为生产上
    看不见，这条只能靠单测钉。**

    用一个真表里没有的编号 `Q99` 当探针：认得出它 = 读的是传进来的表；
    再用真表里有、这张假表里没有的词试一次 = 没读全量表。
    """
    假表 = (
        权限条目(
            编号="Q99",
            事项="只在假表里有的事",
            层级="一线",
            限额="—",
            依据="§测试",
            去向=权限去向.转交,
            关键词=("只在假表里的词",),
        ),
    )
    问, _ = 假模型(LLM不可用("连接超时"))
    assert 认权限("只在假表里的词", 假表, 问=问) == "Q99"

    问2, _ = 假模型(LLM不可用("连接超时"))
    assert 认权限("漏发", 假表, 问=问2) is None, "退回读的是全量表 —— 它不该认得 L01"
