def test_prompt里有主张() -> None:
    问, 记录 = 假模型("L01")
    认权限("上次那个赠品还没给我发", _小表(), 问=问)
    assert "上次那个赠品还没给我发" in 记录[0][1]


def test_prompt里每条可认的都齐全() -> None:
    """编号和事项都要在 —— 只给编号等于让模型背一张它没见过的表。"""
    问, 记录 = 假模型("L01")
    认权限("上次那个赠品还没给我发", _小表(), 问=问)
    提示 = 记录[0][1]
    for k in _小表():
        if not k.可认:
            continue
        assert k.编号 in 提示, f"prompt 里少了 {k.编号}"
        assert k.事项 in 提示, f"prompt 里少了 {k.编号} 的事项"


def test_不可认的行不进prompt() -> None:
    """**不收的就不给看。** 给了再指望模型别选，是在赌它每次都听话。"""
    问, 记录 = 假模型("L01")
    认权限("上次那个赠品还没给我发", _小表(), 问=问)
    提示 = 记录[0][1]
    assert "E01" not in 提示
    assert "补发／换货 > 1 件/单" not in 提示


def test_真表里可认的都有十七行() -> None:
    """换掉关键词的**前提**是模型看得见全部 17 行。

    少一行 = 那条诉求永远认不上 = 静默掉进「未列明」继续第 3 层。
    """
    可认 = [k for k in 权限条目表 if k.可认]
    assert len(可认) == 17, "表变了要重新数这两行文档串里的数"
    问, 记录 = 假模型("L01")
    认权限("上次那个赠品还没给我发", 权限条目表, 问=问)
    提示 = 记录[0][1]
    for k in 可认:
        assert k.编号 in 提示, f"prompt 里少了 {k.编号}"


def test_表是空的不问模型() -> None:
    """没表可认时**一次网络调用都不该发**。"""
    问, 记录 = 假模型("L01")
    assert 认权限("上次那个赠品还没给我发", (), 问=问) is None
    assert 记录 == []


def test_表里一条可认的都没有也不问模型() -> None:
    问, 记录 = 假模型("L01")
    只有不可认 = tuple(k for k in _小表() if not k.可认)
    assert 认权限("上次那个赠品还没给我发", 只有不可认, 问=问) is None
    assert 记录 == []


