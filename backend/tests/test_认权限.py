"""`llm/认权限.py` —— 第 2 层「这件事归谁办」的模型位。

**测试里不打真模型**（同 `test_llm.py` 开头那段）。`问=` 是 keyword-only
带默认值的口子，塞一个假的进去。

这里钉的是**这一侧的逻辑**：prompt 里该有什么、模型吐出来的东西怎么解析、
够不着模型时退到哪儿。模型准不准不在这儿 —— 那走 `tests/test_认权限对照表.py`
和一排 22 行的实测。

# 和 `认口径` 最要命的一处不同

`认口径` 够不着模型时退到 `None` ＝「认不出」，这一次调用就白跑了；
**`认权限` 退到的是关键词那条老路**（`permissions.认权限`）。理由在工单 §八 第 3 条：
离线演示靠它。所以 `LLM不可用` 那几条测试断的不是 `None`，是**关键词的答案**。
"""

from __future__ import annotations

from app.llm.客户端 import LLM不可用
from app.llm.认权限 import 认权限
from app.rules.permissions import 权限条目, 权限条目表, 权限去向
from tests.假模型 import 假模型


def _小表() -> tuple[权限条目, ...]:
    """两张可认、一张不可认 —— 用来钉「不可认的行不进 prompt 也不被接受」。"""
    return (
        权限条目(
            编号="L01",
            事项="补发（不退货）：漏发赠品／少发正装／少件",
            层级="一线",
            限额="1 件/单",
            依据="补发换货工单 13/24 由 A 系处理",
            去向=权限去向.在权限内,
            关键词=("漏发赠品", "漏发", "补发"),
        ),
        权限条目(
            编号="Z01",
            事项="超出权限的赔付",
            层级="专家",
            限额="—",
            依据="§6.3",
            去向=权限去向.转交,
            关键词=("赔付",),
        ),
        权限条目(
            编号="E01",
            事项="补发／换货 > 1 件/单",
            层级="—",
            限额="—",
            依据="§6.2",
            去向=权限去向.报备,
            可认=False,
            关键词=("超过一件",),
        ),
    )


