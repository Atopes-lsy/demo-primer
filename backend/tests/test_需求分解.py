"""`POST /api/需求分解` —— 右栏「这次要什么」那一行的产出者。

**和 `test_拆需求.py` 不是一回事**，两份都要有：那边测的是模型那一半（提示词
怎么写、答得不合法怎么办、去重和条数上限），这边测的是**交给它的是哪几句话**。
分开才看得出是哪一头坏的。

钉三件事，都是「错了不报错、只在演示当天露馅」的：

1. **切的是买家话，不是消息条数。** 后方那条演示会话比剧本多一条**开头**的
   客服承诺（`data/演示会话.py`「是补出来的」一节），剧本比它多一条**现场发**
   的（第 5 格客服点发送那句，后端根本没有）。按条数切，第 1 格就切到那条客服
   消息上 —— 交出去的是**空**买家话，模型不答，屏幕上那一行纹丝不动
   （没答上来就是留原值），看上去只是「模型今天不灵」。
2. **「看全了」和「只看到一半」去尾不一样。** 前者是这一趟过完了，末句是收场白
   （`好的，谢谢啦`），得去掉；后者末句**正是要靠它办事的那句**，去掉就是把
   最新的诉求从屏幕上抹掉。
3. **和 `GET /api/会话列表` 切的是同一批话。** 不传参数时两边必须逐字对上 ——
   模型答上来的那一次是在同一个输入上换了个产出者，不是换了个看法。

真模型一个都不打：`dependency_overrides` 换成假的，走的还是这条路由的同一份代码。
"""

