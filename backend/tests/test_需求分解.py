#: 演示会话 `S_DEMO_A` 的买家话，按开口顺序。**末句是收场白**。
#: 在这儿另抄一份是故意的：下面每条断言都拿它当对照，改剧本时这一份跟着红，
#: 比「断言里再数一遍」多一次「这里说的和剧本还是不是一回事」的提醒。
线一买家话 = [
    "你好，这个精华里有乙醇吗，我怀孕了能用吗",
    "对了，我上次那个赠品还没给我发呢",
    "好的，谢谢啦",
]

#: 模型（假的）这一趟拆出来的。**三句买家话拆成三条需求** —— 第一句里本来就
#: 有两件事，这正是「拆」相对「抄」的全部意义。
线一需求 = ["精华含不含乙醇", "怀孕能不能用", "赠品补发"]


def _假(回: Sequence[str]):
    """假 `拆需求`：把收到的买家话和顾客情况记下来，回一句定好的。

    记下来是**这一整份测试的要点** —— 路由这一层的活儿全是「交给它哪几句话」，
    只看返回值的话，交错了输入也照样绿。
    """
    收过: list[tuple[list[str], list[tuple[str, str]]]] = []

    def 拆需求(
        买家话们: Sequence[str],
        顾客情况: Sequence[tuple[str, str]] = (),
        **_: Any,
    ) -> list[str]:
        收过.append((list(买家话们), list(顾客情况)))
        return list(回)

    return 拆需求, 收过


@pytest.fixture(scope="module")
def 真装() -> 装载器:
    """真数据 ＋ 两条演示会话。路由按 `会话ID` 自己查消息，所以必须走 `从文件`。"""
    return 装载器.从文件(取配置().业务数据路径)


@pytest.fixture
def 装了(真装: 装载器) -> Iterator[tuple[Any, list[tuple[list[str], list]]]]:
    """真装载器 ＋ 假 `拆需求`。**其余六个位用真的** —— 这条路由一个都不碰它们。"""
    假, 收过 = _假(线一需求)
    真的 = deps.取模型位()
    main.app.dependency_overrides[deps.取装载器] = lambda: 真装
    main.app.dependency_overrides[deps.取模型位] = lambda: deps.模型位(
        拆主张=真的.拆主张,
        认口径=真的.认口径,
        查六源=真的.查六源,
        生成话术=真的.生成话术,
        认诉求=真的.认诉求,
        认权限=真的.认权限,
        拆需求=假,
    )
    try:
        yield 假, 收过
    finally:
        # **`finally` 而不是裸 yield 后面清**：断言红了会抛出去，那行清理跑不到，
        # 覆盖会留到下一条测试头上 —— 而它们各自看着都还是绿的。
        main.app.dependency_overrides.clear()


async def 打(会话ID: str = "S_DEMO_A", **其余: Any) -> Any:
    交通 = ASGITransport(app=main.app)
    async with AsyncClient(transport=交通, base_url=测试基地址) as 客户端:
        return await 客户端.post("/api/需求分解", json={"会话ID": 会话ID, **其余})


