async def test_和列表那条路切的是同一批话(装了, 真装: 装载器) -> None:
    """**这条是两条路的接缝。**

    `GET /api/会话列表` 给的那份「这次要什么」是**原话**，模型答上来之后
    右栏把它换成拆过的。两份必须来自同一批话 —— 各切各的话，屏幕上那一行
    会在模型答上来的那一刻**换成另一个问题的答案**，而两处都「看着对」。

    核法：把列表那条路那个值按连接符拆开，和这边交给模型的话逐句比。
    """
    _, 收过 = 装了
    会话 = 真装.找("S_DEMO_A")
    assert 会话 is not None
    行 = next(r for r in 装配.装配顾客情况(会话, _全轮(真装)) if r.标签 == "这次要什么")

    await 打()
    列表的 = 行.值.split(" ＋ ")
    assert 列表的 == 收过[0][0], f"两条路切的不是同一批话：{列表的}"


