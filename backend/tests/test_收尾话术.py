"""报备的收尾话术 —— `app/rules/收尾话术.py`。

# 这是什么

`输出 == 报备` 那一轮，**审批回来、客服按了［一键发送］才发出去**的那一句。
它在 `主卡.话术` 上（不是 `已代发`），前端拿它当 `待发` 那句摆给客服看。

# 和 `test_安抚话术.py` 那一句什么关系

同一条报备线的**两头**，中间隔着「组长批了」那一下：

    安抚话术 —— 顾客刚说完，系统自动发（`已代发`，署名带「无需客服点」）。
    收尾话术 —— 授权回来，客服自己按发送（本模块）。

⚠️ **所以两张表的硬约束方向相反，两边各有一组测试钉住，别互相搬：**

    安抚话术：**禁时限**、**禁「已」** —— 发出去那一刻没有任何事做过。
    收尾话术：**必须认账**、**可以给时限** —— 那件事已经走完审批了。

`test_收尾话术能给时限` 和 `test_收尾话术允许用已字` 这两条就是在钉后半句：
哪天有人照 `安抚话术` 把规矩抄过来，这两条会红。

# 这里钉的是哪一侧

**校验本身也要被钉。** 一个恒返回空列表的校验函数看起来和真的没区别，
所以下面专门有**喂违规话术进去**的测试 —— 它红了才说明校验在干活。
"""

from __future__ import annotations

import re

import pytest

from app.rules import 收尾话术 as 模块
from app.rules.收尾话术 import (
    兜底收尾,
    收尾话术表,
    查收尾话术,
    校验收尾话术,
)

#: 剧本原文，`frontend/src/data/剧本.ts:891` —— 第七步 `待发` 里那句。
#: **拿这个核，不拿工单核**：`剧本.ts` 是验收基准，表要照剧本改，不是剧本照表改。
#:
#: ⚠️ 这一条**两边必须逐字一致**，而且和 `handover` 那种「剧本兜底、接口给真话」
#: 不一样：这里接口给的**就是这一句**（`收尾话术表["赠品"]`）。所以脚本里
#: `话术来源: {6: {轮次: 2, 取: '主卡话术'}}` 一旦真读到接口，屏幕上换掉的和
#: 兜底的是同一串字 —— **换不换看不出区别，错了也看不出区别**。就靠这条测试守着。
剧本原文 = "抱歉让您久等了，补发这边我已经登记好，今天安排发出，48 小时内给您单号。"


# ══════════════════════════════════════════════════════════
# 一 · 查表
# ══════════════════════════════════════════════════════════


def test_赠品那条就是剧本里那句() -> None:
    """演示最后一句答复逐字对上 —— 验收拿剧本原文核。"""
    assert 查收尾话术("赠品漏发") == 剧本原文


def test_认不出事项给兜底() -> None:
    """报备有五个来源（`permissions` 的 E01–E05），只写死一句不够。

    认不出的失败方向是温和的：兜底也过得了两条硬约束，只是**没有时限** ——
    见下面 `test_兜底不给时限`。
    """
    果 = 查收尾话术("我要退货，运费谁出")
    assert 果 == 兜底收尾
    assert "赠品" not in 果, "兜底不该提到具体事项"


def test_关键词最长优先() -> None:
    """和 `permissions.认权限`、`安抚话术.查安抚话术` 同一个分法：
    具体的压过笼统的。否则「赠品」那条永远轮不到更具体的那条。"""
    具体 = {**收尾话术表, "赠品补发": "具体那条"}
    assert 查收尾话术("赠品补发", 具体) == "具体那条"


# ══════════════════════════════════════════════════════════
# 二 · 和安抚话术**相反**的两条 —— 防止规矩被搬过来
# ══════════════════════════════════════════════════════════


def test_收尾话术能给时限() -> None:
    """**这句可以带时限** —— 规格 §七 的「正常收尾」档就是这么定的。

    和 `test_安抚话术.全部话术都不含时限` 看着矛盾，其实是两种时机：
    安抚话术出去的时候事还没办，任何时限都是空头支票（口径表 K05）；
    这一句出去的时候审批已经走完，时限是**批过的**那一个。

    这条要是红了：有人把 `校验安抚话术` 的「禁数字」那条搬过来了。
    """
    assert 校验收尾话术() == [], "真实表自己就不合法了"
    # 换一张只有带时限话术的表，也必须过 —— 证明校验**不查**数字。
    assert 校验收尾话术({"{测}": "抱歉让您久等了，48 小时内给您单号。"}) == []


def test_收尾话术允许用已字() -> None:
    """**「已」在这句里是合法的** —— 那件事真做过了。

    `安抚话术` 整句话禁「已」，因为发出去的那一刻**不存在任何「已做过」的事**。
    这一句的时机正相反：「已经帮您登记好」说的是审批回来之后真的做了的事，
    去掉「已」反而变成「我将要帮你登记」，把那件已经落实的事说成还没做。

    这条要是红了：有人把 `校验安抚话术` 的「禁已」那条搬过来了。
    """
    assert 校验收尾话术({"{测}": "抱歉让您久等了，已经帮您登记好了。"}) == []


def test_兜底不给时限() -> None:
    """认不出事项就说明**没人知道这批货几天能出去**。

    给一个数字就是替仓库许一个它没许过的诺 —— 认不出的代价只该是**少一点
    针对性**，不该是多一个没有来源的承诺。这条守着那个方向。
    """
    assert not re.search(r"\d", 兜底收尾), f"兜底里不该有数字：{兜底收尾!r}"


# ══════════════════════════════════════════════════════════
# 三 · 两条硬约束
# ══════════════════════════════════════════════════════════


def test_全部话术都先认账() -> None:
    """这一档的触发（E05 承诺逾期）本身就是「我方欠着顾客一件事」。

    不认账就是装作没这回事 —— 逾期两天再回一句公事公办的「已为您登记」，
    等于没接住顾客等的那两天。
    """
    assert 校验收尾话术() == [], "真实表自己就不合法了"


@pytest.mark.parametrize(
    "坏话术",
    [
        "已为您登记补发，今天安排发出，48 小时内给您单号。",
        "这边已经帮您登记好了，会尽快安排处理。",
        "您的赠品我们已经在处理了。",
    ],
)
def test_校验能查出没认账(坏话术: str) -> None:
    """**这条红了才说明校验在干活。**

    上面那条「真实表合法」是个恒真断言 —— 校验函数要是恒返回空列表，
    它照样绿。所以这里喂三条不认账的进去，必须被报出来。

    ⚠️ 这三条**都带「已」字**是故意的：它们是合法句式（这一档允许「已」），
    唯一的毛病就是没认账。要是校验把「禁已」抄了过来，这三条也会被报出来 ——
    那就分不清它到底查的是哪一条了。
    """
    assert 校验收尾话术({"{坏}": 坏话术}), f"没查出没认账：{坏话术}"


def test_校验能查出禁语() -> None:
    """禁语复用口径表的 `查禁语全` —— 和闸门 G1 **同一张表**。

    不共用的话，收尾话术会变成一条绕过 G1 的旁路：它是固定表，
    本地校验过了就直接发给顾客，闸门那道在不在它身上都无所谓。

    ⚠️ 用 `放心使用`（K10 的真禁语），**不是**「孕妇可以用」那种看着像的写法 ——
    `孕妇可以直接用` 逐字**不**含 `孕妇可以用`，拿它当反例会得到一条恒绿的测试
    （这个坑 `test_安抚话术.py` 里已经踩过一次）。
    """
    坏 = "抱歉让您久等了，放心使用，我们保证没问题。"
    assert 校验收尾话术({"{坏}": 坏}), f"没查出禁语：{坏}"


def test_兜底那一句也在查(monkeypatch: pytest.MonkeyPatch) -> None:
    """`表=None` 时**兜底那句也要一起查**。

    只查主表的话，兜底就成了唯一一个没人查的出口 —— 而它恰恰是**认不出事项
    时唯一会发出去的那句**，也就是最该查的那句。

    换掉 `兜底收尾` 再调一次：它是个模块级全局，`校验收尾话术` 得**当场读**它，
    不能在 import 时就把那句快照进 `用` 里。
    """
    monkeypatch.setattr(模块, "兜底收尾", "已为您登记，请稍候。")
    assert 校验收尾话术(), "兜底被换成不认账的了，校验却没报"
