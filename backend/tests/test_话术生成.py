def test_判成说明不进prompt也不进话术() -> None:
    """`判成.说明` 会原样进右栏，所以**它可以给客服看，不能给顾客看**
    （`pipeline.判成.说明` 的文档串、spec §三）。

    做法不是「告诉模型别抄」，是**根本不给它抄的东西**：说明不进 prompt。
    下面这个假模型把 prompt 原样吐回来 —— 模型复读输入是真实存在的失败模式，
    它正好把「prompt 里有没有这句话」变成可断言的事：没有，复读出来就没有。
    """

    def 复读(提示: str, 系统: str = "") -> str:
        return 提示

    果 = 生成话术(造判成(说明=给客服的话), (), (), 口径表, (), 问=复读)
    assert 给客服的话 not in 果.话术


