def test_重试只喂高危不喂中危() -> None:
    """spec §六：**中危不阻断，喂进去会让模型去改本来没问题的句子。**

    这句同时命中三条：G1 禁语（高危）、G2 边界句（高危）、G2 措辞（中危）。
    第二次的 prompt 里该有前两条的意见，不该有 G2 措辞那条。
    """
    问, 记录 = 假模型("亲，孕妇可以用哦，我保证没问题～")
    生成话术(造判成(涉个体差异=True), (), (), 口径表, (), 问=问)

    assert len(记录) == 3, "G2 措辞是中危，不该让它多跑一轮"
    第二次 = 记录[1][1]
    assert "孕妇可以用" in 第二次, "高危那条（G1 禁语）要喂回去"
    # 中危那条的**详情**和**建议**各钉一次 —— 只钉详情的话，「喂了详情没喂建议」
    # 这种半吊子改动照样绿。
    #
    # ⚠️ 不能用 `"保证" not in 第二次` 来钉建议：上一稿里本来就有「保证」，
    # 它出现在【上一稿】那块是对的。要钉的是建议**那句独有的措辞**。
    assert "泛化强调" not in 第二次, "中危那条（G2 措辞）的详情不该喂"
    assert "留余地" not in 第二次, "中危那条的建议也不该喂"


