def test_可引用和prompt里是同一份原文() -> None:
    """spec §6.3：同一份「可以说／标准话术」走两条路 —— 一条进 prompt、
    一条进闸门当 `可引用`，**两处必须是同一份原文**。

    取岔了会出现「prompt 里能说、闸门说数字没出处」这种自相矛盾的话术：
    模型照着 prompt 写，闸门照着另一份判，两边都觉得自己对。
    """
    判 = 造判成(编号=("K05",))
    可 = 取可引用(判, 口径表)
    K05 = 口径表.取("K05")
    assert 可 == (K05.可以说, K05.标准话术)

    提示 = 组装提示(判, 口径表=口径表)
    for 文 in 可:
        assert 文 in 提示


