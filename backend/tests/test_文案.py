三个形态 = ("需要话术", "需要授权", "有风险")


def _触发(
    编号: 触发编号, 严重度: str = "高", 说明: str = "", 证据: tuple[str, ...] = ()
) -> 触发:
    """一条触发。**`证据` 只有 H1 用得上** —— 它按证据落在哪一族分句
    （`H1短语表`），其余三个编号一句话说完。"""
    return 触发(编号=编号, 名称=编号.name, 严重度=严重度, 证据=证据, 说明=说明)


