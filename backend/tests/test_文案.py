"""主卡文案表（`app/api/文案.py`）。

`接口契约.md` §七 第 1 条挂着的未定项：

> **主卡那四句文案后端没有真源。** `判断` / `标题` / `说明` / `风险标签`
> 现在由调用方填。要做一张「形态 × 触发 → 文案」的表，落在步骤 2。

这个文件测那张表。**钉的不是「文案好不好」，是「文案在不在数据里」** ——
写死在函数里的话，演示当天想改一句标题就得改代码、跑测试、再起服务，
而那时候没时间。
"""

from __future__ import annotations

import pytest

from app.api import 文案 as 文案模块
from app.rules.pipeline import 输出类型
from app.rules.triggers import 触发, 触发编号

三个形态 = ("需要话术", "需要授权", "有风险")


def _触发(编号: 触发编号, 严重度: str = "高", 说明: str = "") -> 触发:
    return 触发(编号=编号, 名称=编号.name, 严重度=严重度, 证据=(), 说明=说明)


# ══════════════════════════════════════════════════════════
# 一 · 三种形态的对照表（工单 §六 那张）
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize("形态", 三个形态)
def test_三个形态都有文案(形态: str) -> None:
    assert 文案模块.取主卡文案(形态).判断
    assert 文案模块.取主卡文案(形态).标题


def test_判断逐字照工单() -> None:
    """`工单交接_给接口线.md` §六 那张表 —— 三个形态各一句。"""
    assert 文案模块.取主卡文案("需要话术").判断 == "这次需要「话术」"
    assert 文案模块.取主卡文案("需要授权").判断 == "这次需要「授权」"
    assert 文案模块.取主卡文案("有风险").判断 == "这次需要「转交」"


def test_话术和授权两句标题逐字照工单() -> None:
    assert 文案模块.取主卡文案("需要话术").标题 == "✍️ 这条得你来发 · 涉个体差异"
    assert 文案模块.取主卡文案("需要授权").标题 == "🔒 这事该办，我帮你走授权"


def test_三个形态的判断互不相同() -> None:
    """三句话一样的话，主卡顶部那颗胶囊就白占了位置。"""
    判断们 = {文案模块.取主卡文案(s).判断 for s in 三个形态}
    assert len(判断们) == 3


def test_未知形态不返回一句瞎话() -> None:
    """形态是 `Literal` 封死的三选一，传进来第四个值是调用方的 bug ——
    静默给一句「需要话术」的话，错的那一轮看起来完全正常。"""
    with pytest.raises(KeyError):
        文案模块.取主卡文案("需要通知")


# ══════════════════════════════════════════════════════════
# 二 · 「有风险」的标题由触发拼
# ══════════════════════════════════════════════════════════


def test_逾期加投诉拼出两个短语() -> None:
    """线二那一轮（H1 ＋ H3）—— 标题要说清**为什么**有风险。

    这是 `有风险` 和另外两个形态的区别：另外两个的标题是固定的
    （「涉个体差异」「越过额度」），只有这一个的原因每次都不同。
    """
    标题 = 文案模块.取主卡文案(
        "有风险", [_触发(触发编号.H3), _触发(触发编号.H1)]
    ).标题
    assert 标题 == "⚠ 承诺已逾期 · 顾客要求投诉"


def test_三个触发拼出工单里那句完整的() -> None:
    """`工单 §六` 的 `⚠ 承诺已逾期 · 顾客要求投诉 · 情绪升级` 就是
    H3 ＋ H1 ＋ H2 三个都在的样子。"""
    标题 = 文案模块.取主卡文案(
        "有风险",
        [_触发(触发编号.H1), _触发(触发编号.H2), _触发(触发编号.H3)],
    ).标题
    assert 标题 == "⚠ 承诺已逾期 · 顾客要求投诉 · 情绪升级"


def test_触发顺序不影响标题() -> None:
    """同一份输入跑两遍要得出同样的清单 —— 可重放的要求。

    顺序由表定，不由 `硬触发` 的返回顺序定：那边按严重度排，
    同级的相对顺序依赖遍历顺序，拿它拼标题就不可重放了。
    """
    正序 = 文案模块.取主卡文案("有风险", [_触发(触发编号.H3), _触发(触发编号.H1)])
    倒序 = 文案模块.取主卡文案("有风险", [_触发(触发编号.H1), _触发(触发编号.H3)])
    assert 正序.标题 == 倒序.标题


def test_没有触发时退回形态的默认标题() -> None:
    """「有风险」而一个触发都没有，是可能的：**权限越界**那一类
    （矩阵直接判转交，不经过 H1–H4）。退回默认标题，
    而不是拼出一句只剩 `⚠ ` 的话。"""
    标题 = 文案模块.取主卡文案("有风险", []).标题
    assert 标题 and 标题 != "⚠ "


def test_两个形态不因为触发而改标题() -> None:
    """「需要话术」「需要授权」的标题和触发无关 —— 传了触发也不该动。"""
    for 形态 in ("需要话术", "需要授权"):
        assert (
            文案模块.取主卡文案(形态, [_触发(触发编号.H3)]).标题
            == 文案模块.取主卡文案(形态).标题
        )


# ══════════════════════════════════════════════════════════
# 三 · 输出类型 → 形态
# ══════════════════════════════════════════════════════════


def test_三种输出各自映射到形态() -> None:
    assert 文案模块.取形态(输出类型.客服点发送) == "需要话术"
    assert 文案模块.取形态(输出类型.报备) == "需要授权"
    assert 文案模块.取形态(输出类型.转交) == "有风险"


def test_AI直发不上主卡() -> None:
    """`AI直发` 不需要客服动手 —— 它只进 `已代发`。

    ⚠️ 给它编一个形态的话，主卡会跳出一张要客服点什么的卡片，
    而那句话**已经发出去了**（`schemas.Advice` 的文档串）。
    """
    assert 文案模块.取形态(输出类型.AI直发) is None


def test_没有判定时没有主卡() -> None:
    """空列表（这一轮没有主张）—— 右栏只显示顾客情况，不显示主卡。"""
    assert 文案模块.取形态(None) is None


def test_形态映射和文案表对得上() -> None:
    """映射里指的每个形态都得在文案表里 —— 对不上的话，
    取文案那一步才 KeyError，而那时候已经过了好几层。"""
    for 输出 in 输出类型:
        形态 = 文案模块.取形态(输出)
        if 形态 is not None:
            assert 形态 in 文案模块.主卡文案表


def test_最高态优先() -> None:
    """一轮里同时有 `客服点发送` 和 `转交` 时，主卡显示转交 ——
    `pipeline.主卡形态` 取最高态，这里顺着它映射。"""
    from app.rules.pipeline import 主卡形态

    形态 = 文案模块.取形态(
        主卡形态(
            [
                _判成(输出类型.客服点发送),
                _判成(输出类型.转交),
            ]
        )
    )
    assert 形态 == "有风险"


def _判成(输出: 输出类型):
    from app.rules.pipeline import 判成

    return 判成(主张="x", 输出=输出, 说明="", 依据=(), 层="第3层")
