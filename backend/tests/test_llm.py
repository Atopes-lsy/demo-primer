"""两个模型位：`llm/认口径.py` 和 `llm/拆主张.py`。

**测试里不打真模型。** 打真的会有三个后果：测试变慢、跑一次花一次钱、
以及**结论随模型版本漂**——今天绿的明天红，而红的理由和代码无关。
所以两个函数都留了一个 `问=` 的口子（keyword-only 带默认值），
测试塞一个假的进去。

留这个口子也是工单 §六 要的：6.1 喂**定死的输入**才叫单测，
真模型那条路走 6.2 的端到端，两者验的不是一件事。

这里钉的是**这一侧的逻辑**：prompt 里该有什么、模型吐出来的东西怎么解析、
吐得不对时退到哪儿。模型准不准不在这儿测。
"""

from __future__ import annotations

import pytest

from app.llm.客户端 import LLM不可用
from app.llm.拆主张 import 拆主张
from app.llm.认口径 import 认口径
from app.rules.koujing import 加载口径表
from tests.假模型 import 假模型

口径表 = 加载口径表().口径表


# ══════════════════════════════════════════════════════════
# 一 · 认口径
# ══════════════════════════════════════════════════════════


def test_认出口径编号() -> None:
    问, _ = 假模型("K10")
    assert 认口径("含乙醇", 口径表, 问=问) == "K10"


def test_认不出返回None() -> None:
    """工单 §五：**认不出就返回 `None`，不要猜一个。**

    `依据编号` 空着比挂错强 —— 挂错了客服对不上账，而且**不会有任何东西报错**。
    """
    问, _ = 假模型("NONE")
    assert 认口径("今天天气不错", 口径表, 问=问) is None


def test_模型多嘴也能认出来() -> None:
    """模型不会老老实实只回四个字符。

    解析取**第一个真在表里的编号**，而不是要求整个回答就等于编号
    —— 后者会让一句「编号：K10」直接掉进「认不出」，而那是同一件事。
    """
    问, _ = 假模型("编号：K10。")
    assert 认口径("含乙醇", 口径表, 问=问) == "K10"


def test_编出来的编号不认() -> None:
    """模型回了个表里没有的 K99 —— **不能照单全收**。

    照收的后果是右栏挂一条查无此条的「依据：口径表 K99」，
    点进去什么都没有，而整个链路没有一处会报错。
    """
    问, _ = 假模型("K99")
    assert 认口径("含乙醇", 口径表, 问=问) is None


def test_prompt里要有全部二十条() -> None:
    """工单 §五：口径表只有 20 条，**每次全塞 prompt**。

    不走向量（20 条上是负优化）、不调分词、不算 embedding —— 少塞一条的后果
    是那条口径永远认不出来，而它不会报错，只会「今天这个顾客怎么没挂上依据」。
    """
    问, 记录 = 假模型("K10")
    认口径("含乙醇", 口径表, 问=问)
    _, 提示 = 记录[0]
    assert len(口径表) == 20, "口径表本身就该是 20 条 —— 变了要重新想这个设计"
    for k in 口径表:
        assert k.编号 in 提示, f"prompt 里少了 {k.编号}"
        assert k.话题 in 提示, f"prompt 里少了 {k.编号} 的话题名"
    assert "不含酒精/香精" in 提示 or "酒精" in 提示, "「可以说」那一段要进 prompt"


def test_prompt里要有主张() -> None:
    问, 记录 = 假模型("K10")
    认口径("含乙醇", 口径表, 问=问)
    assert "含乙醇" in 记录[0][1]


def test_表是空的不问模型() -> None:
    """没表可认时**一次网络调用都不该发**。"""
    问, 记录 = 假模型("K10")
    assert 认口径("含乙醇", (), 问=问) is None
    assert 记录 == []


def test_模型不可用返回None() -> None:
    """够不着模型时退到 `None`（＝认不出），不是抛。

    抛的后果是演示当天模型一抖，`POST /api/判定` 直接 500，右栏整个白掉
    —— 而「认不出」这个答案本来就是合法的，`None` 会让这条主张照常往下走。
    """
    问, _ = 假模型(LLM不可用("连接超时"))
    assert 认口径("含乙醇", 口径表, 问=问) is None


