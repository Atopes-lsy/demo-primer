def test_拆出多个事实点() -> None:
    """一条主张 ＝ 一个**事实点**（工单 §3.4）：一句话里三件事就是三条。"""
    问, _ = 假模型('{"主张": ["赠品没收到", "脸部过敏", "要开发票"]}')
    assert 拆主张("赠品没到，脸还过敏了，另外要开发票", (), 问=问) == [
        "赠品没收到",
        "脸部过敏",
        "要开发票",
    ]


def test_去重() -> None:
    """**主张文本就是主键** —— 前端拿它当 React key（`key={d.主张}`）。

    重复项的后果是同一轮里两条主张撞 key，右栏**少显示一条**，而且不报错。
    所以去重放在这一侧，不指望模型每次都听话。
    """
    问, _ = 假模型('{"主张": ["赠品没收到", "赠品没收到", "要开发票"]}')
    assert 拆主张("赠品没到，赠品没到，要开发票", (), 问=问) == ["赠品没收到", "要开发票"]


def test_空条目要丢掉() -> None:
    问, _ = 假模型('{"主张": ["赠品没收到", "  ", "", "要开发票"]}')
    assert 拆主张("...", (), 问=问) == ["赠品没收到", "要开发票"]


def test_prompt里要带消息和顾客情况() -> None:
    """顾客情况是拆主张的输入之一（规格节点 3）。

    同一句「能用吗」，孕妇和普通顾客拆出来的事实点不一样 ——
    模型得知道这是谁在问。
    """
    问, 记录 = 假模型('{"主张": ["孕妇能否用"]}')
    拆主张("这款能用吗", (("这是谁", "孕 28 周"), ("这次要什么", "礼盒赠品漏发")), 问=问)
    _, 提示 = 记录[0]
    assert "这款能用吗" in 提示
    assert "孕 28 周" in 提示
    assert "礼盒赠品漏发" in 提示


@pytest.mark.parametrize(
    ("名字", "回答"),
    [
        ("模型吐了段白话", "这件商品不含乙醇，可以放心使用。"),
        ("JSON 缺字段", '{"主张": 3}'),
        ("JSON 不是对象", '["赠品没到"]'),
        ("空数组", '{"主张": []}'),
        ("直接抛错", LLM不可用("503")),
    ],
)
def test_拆不出来就整条当一条(名字: str, 回答) -> None:
    """**兜底是「整条消息算一条主张」，不是空列表。**

    空列表的后果是这一轮**一条主张都没有** —— 右栏一片空白，客服以为没事，
    而顾客刚才说了一整段。整条当一条至少让三层判定跑起来：大概率判成
    「客服点发送」（有承诺或有个体差异），偶尔判成报备。保守，但不是沉默。
    """
    问, _ = 假模型(回答)
    断言 = 拆主张("赠品没到，脸还过敏了", (), 问=问)
    assert 断言 == ["赠品没到，脸还过敏了"], f"{名字}：兜底没走对"


def test_空消息返回空列表() -> None:
    """消息本来就是空的（一条纯图片、或者只有空格）时**返回空**，不兜底。

    兜底成 `[""]` 的话会多出一条主张文本是空串的记录，前端那个
    `key={d.主张}` 拿到空 key，而且右栏会显示一行没有标题的处置。
    """
    问, _ = 假模型("")
    assert 拆主张("   ", (), 问=问) == []


def test_兜底的那一条要洗干净() -> None:
    """整条当一条时前后空白要去掉 —— 它要进右栏当标题显示。"""
    问, _ = 假模型(LLM不可用("超时"))
    assert 拆主张("  赠品没到，脸还过敏了\n", (), 问=问) == ["赠品没到，脸还过敏了"]
