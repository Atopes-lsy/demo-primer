# 三 · 成分表切物质名 —— 苯氧乙醇那一脚
# ══════════════════════════════════════════════════════════
#
# 20 个真商品里 **17 个含苯氧乙醇**，而「苯氧乙醇」逐字含「乙醇」。
# 所以「乙醇 in 成分表」这个判据在 17/20 上是**错的**，而不是偶尔错。
#
# 另一头 `XL21204 测试净澈卸妆水` 真的含 `变性乙醇`（酒精）—— 它是**唯一**
# 一个真含酒精的产品。所以这对判据在它身上的表现是：
#   抠词「乙醇 in 成分表」→ True（蒙对了，但理由不对）
#   整名「乙醇 in 成分名」→ False（**错了**，漏掉变性乙醇）
# 两条都是错的，只是错法不同 —— 这就是为什么别名表不是可选项。

#: 真表里的三行。逐字抄自 `商品属性表_v7_定稿.xlsx`。
精华成分 = "、".join((
    "水", "甘油", "丁二醇", "透明质酸钠", "泛醇", "积雪草提取物",
    "神经酰胺NP", "角鲨烷", "卡波姆", "黄原胶", "香精", "苯氧乙醇",
))
卸妆水成分 = "、".join((
    "水", "变性乙醇", "PEG-6辛酸/癸酸甘油酯类", "丁二醇", "甘油",
    "泊洛沙姆184", "氯化钠", "香精", "苯氧乙醇",
))
#: 唇釉那条是冲着 `/` 来的：`鲸蜡基PEG/PPG-10/1聚二甲基硅氧烷` 整个是一个名字。
唇釉成分 = "、".join((
    "辛基十二醇", "聚丁烯", "二异硬脂醇苹果酸酯", "氢化聚异丁烯",
    "鲸蜡基PEG/PPG-10/1聚二甲基硅氧烷", "CI 15850", "CI 77491",
    "生育酚乙酸酯", "香精", "苯氧乙醇",
))


def 造三件():
    """精华（不含酒精）＋ 卸妆水（真含）＋ 唇釉（斜杠在名字里）。"""
    return 从表(造表(
        造行("XL10302", **{"成分表（完整）": 精华成分}),
        造行("XL21204", 商品名称="测试净澈卸妆水300ml", **{"成分表（完整）": 卸妆水成分}),
        造行("XC30101", 商品名称="测试丝绒唇釉 #01赤茶红", **{"成分表（完整）": 唇釉成分}),
    ))


def test_成分名按顿号切() -> None:
    表 = 造三件()
    物质 = 成分名(表, 表["XL10302"])
    assert 物质[0] == "水" and 物质[-1] == "苯氧乙醇"
    assert len(物质) == 12
    assert "香精" in 物质


def test_斜杠不是分隔符() -> None:
    """**8 处 `/` 全在名字内部**（真表里数过）。

    `鲸蜡基PEG/PPG-10/1聚二甲基硅氧烷`、`辛酸/癸酸甘油三酯` ——
    照常见写法顺手切了 `/`，这些名字会被劈成两半，而劈完的两半
    看着都还挺像个成分名。**不会有任何东西报错。**
    """
    表 = 造三件()
    物质 = 成分名(表, 表["XC30101"])
    assert "鲸蜡基PEG/PPG-10/1聚二甲基硅氧烷" in 物质, "名字被 `/` 劈开了"
    assert not any("PPG-10/1" in x and len(x) < 20 for x in 物质)


def test_变性乙醇是一个整token() -> None:
    表 = 造三件()
    物质 = 成分名(表, 表["XL21204"])
    assert "变性乙醇" in 物质
    assert "乙醇" not in 物质, "整个表里没有「乙醇」这个 token —— 它是「变性乙醇」"


def test_苯氧乙醇不是酒精() -> None:
    """**这一条是整件事的目的。**

    精华的最后一个成分是苯氧乙醇（防腐剂）。问「含酒精吗」的正确答案是**不含**，
    而抠词的答案正好相反。

    `酒精别名` 那三个词里**没有苯氧乙醇** —— 少这一条，「不含酒精」这个
    对顾客说出去的承诺就是假的。
    """
    表 = 造三件()
    assert 含成分(表, 表["XL10302"], "酒精", 别名=酒精别名) is False
    assert 含成分(表, 表["XC30101"], "乙醇", 别名=酒精别名) is False, "唇釉也只有苯氧乙醇"


def test_卸妆水是真含酒精() -> None:
    """`XL21204` 是 20 个商品里**唯一**真含酒精的（写的是 `变性乙醇`）。

    这条钉的是别名表的必要性：整名相等，但**不带别名**，
    这里会答「不含」—— 把一个真含酒精的产品说成不含。
    """
    表 = 造三件()
    assert 含成分(表, 表["XL21204"], "酒精", 别名=酒精别名) is True
    assert 含成分(表, 表["XL21204"], "乙醇", 别名=酒精别名) is True, "别名要认出来"
    assert 含成分(表, 表["XL21204"], "变性乙醇") is True, "不带别名直接问也要对"


def test_含成分是整名相等不是子串() -> None:
    表 = 造三件()
    assert 含成分(表, 表["XL10302"], "苯氧乙醇") is True
    assert 含成分(表, 表["XL10302"], "水") is True
    assert 含成分(表, 表["XL10302"], "甘油") is True
    assert 含成分(表, 表["XL10302"], "乙醇") is False, "「乙醇」是「苯氧乙醇」的子串，但不相等"
    assert 含成分(表, 表["XL10302"], "积雪草") is False, "半个名字不算"
    assert 含成分(表, 表["XL10302"], "硅油") is False, "没这个 token"


# ══════════════════════════════════════════════════════════
# 三·五 · `不含（可对顾客说）` —— 「表里说没有」的那一半
# ══════════════════════════════════════════════════════════
#
# 这一列原来是纯给人读的（只进 `content`）。G3 的第三次子串陷阱就是因为它
# **不在词表里**：话术里一个不在成分表里的名字（`水杨酸`）占不住自己的区间，
# 于是 `水` 在它中间命中，判成「说不含水」—— 而那句「不含维A类、水杨酸…」
# 逐字抄的就是这一列。详见 `app/rules/物质.py` 里 `扫断言` 的第三次发作。
#
# ⚠️ **它进的是词表，不是判据。** 「有没有」只看 `成分名`。


def test_不含名剥前缀并按顿号切() -> None:
    """`不含：` 前缀和顿号都是**列的写法**，不是名字的一部分。

    前缀不剥的话「不含：维A类（视黄醇）」会整个进词表 —— 它永远匹配不上；
    而「不含」两个字进词表更没道理：它不是物质名，却会在每一句「不含 X」里
    被 `_出现` 当成一个候选名字找出来。
    """
    assert 不含名(造三件()["XL10302"]) == (
        "维A类（视黄醇）", "视黄醇", "维A类", "水杨酸", "对苯二酚", "二苯酮-3", "皂基",
    )


def test_不含名把括注拆开() -> None:
    """`维A类（视黄醇）` 括号里是**同一个东西的另一个叫法**，模型两个都可能写。

    整名／括号外／括号里三个都收是**扩词表** —— 而 `有` 的判据不看这些名字，
    所以多收一个只会让它更好占区间，造不出新的误报。这一列「宁可多收」
    的底气就在这儿。
    """
    名 = 不含名(造三件()["XL10302"])
    assert "维A类" in 名 and "视黄醇" in 名, f"括注没拆：{名}"


def test_不含名不追改指() -> None:
    """`成分名` 要顺货号追，是因为 `成分表（完整）` 那一列真写着「见 XL10501」。

    `不含（可对顾客说）` **不写那种话** —— 20 行实测零例外，礼盒和双支装
    各自把七样列全（而且比单品多列了酒精和香精）。所以这一列**各是各的**：
    同一个 `不含名` 函数吃不到 `表` 参数，追不进去。
    """
    表 = 从表(造表(
        造行("XL10302"),
        造行("XL19806", 商品名称="【预售】测试修护精华双支装30ml*2",
             **{"成分表（完整）": "同 XL10302（本品为同款精华 2 支装）",
                "不含（可对顾客说）":
                    "不含：酒精、香精、维A类（视黄醇）、水杨酸、对苯二酚、二苯酮-3、皂基"}),
    ))
    assert 成分名(表, 表["XL19806"]) == 成分名(表, 表["XL10302"]), "成分表是指针，要追"
    assert "酒精" in 不含名(表["XL19806"])
    assert "酒精" not in 不含名(表["XL10302"]), "`不含` 列不是指针，别跟着追"


# ══════════════════════════════════════════════════════════
# 四 · 改指行：礼盒的成分表是**指针**，不是列表
# ══════════════════════════════════════════════════════════
#
# `XL19805`（14 单）、`XL19806`（13 单）是**订单量最大的货号之一** ——
# 不是边角料。它们的「成分表（完整）」写的是：
#   `按内含单品各自的成分表执行（面霜50ml 见 XL10501；精华30ml 见 XL10302）`
#   `同 XL10302（本品为同款精华 2 支装）`
# 按 `、` 切只会切出一坨垃圾 token，然后静默答「不含」。


def 造礼盒():
    return 从表(造表(
        造行("XL10302", **{"成分表（完整）": 精华成分}),
        造行("XL10501", 商品名称="测试舒缓修护面霜50ml",
             **{"成分表（完整）": "水、甘油、角鲨烷、牛油果树果脂、泛醇、积雪草提取物、"
                                 "神经酰胺NP、鲸蜡硬脂醇、聚二甲基硅氧烷、卡波姆、香精、苯氧乙醇"}),
        造行("XL19806", 商品名称="【预售】测试修护精华双支装30ml*2",
             **{"成分表（完整）": "同 XL10302（本品为同款精华 2 支装）"}),
        造行("XL19805", 商品名称="【预售】测试焕活紧致礼盒(面霜50ml+精华30ml)",
             **{"成分表（完整）":
                "按内含单品各自的成分表执行（面霜50ml 见 XL10501；精华30ml 见 XL10302）"}),
    ))


def test_改指行顺着货号追() -> None:
    """`XL19806` 说「同 XL10302」→ 它的物质名就是 XL10302 的。"""
    表 = 造礼盒()
    assert 成分名(表, 表["XL19806"]) == 成分名(表, 表["XL10302"])


def test_礼盒取两个单品的并集() -> None:
    """`XL19805` 指了两个单品 → 两边的成分表都要算进来。

    只追第一个的话，「这个礼盒含不含牛油果树果脂」会答「不含」，
    而面霜里明明有。**并集**才是对的 —— 礼盒里就是这两样东西。
    """
    表 = 造礼盒()
    物质 = 成分名(表, 表["XL19805"])
    assert "牛油果树果脂" in 物质, "面霜那一支的成分"
    assert "透明质酸钠" in 物质, "精华那一支的成分"
    assert "苯氧乙醇" in 物质, "两支都有，去重后只该出现一次"
    assert len(物质) == len(set(物质)), "并集要去重"
    assert "鲸蜡硬脂醇" in 物质


def test_礼盒问酒精也是不含() -> None:
    """追到最后还是那两支单品，所以答案和单品一致。"""
    表 = 造礼盒()
    assert 含成分(表, 表["XL19805"], "酒精", 别名=酒精别名) is False
    assert 含成分(表, 表["XL19806"], "酒精", 别名=酒精别名) is False


def test_改指指向查不到的货号要报错() -> None:
    """改指追不到就**不能当空表返回**。

    返回空的意思是一句「不含任何成分」，而它会被下游读成「不含 X」——
    对着一个成分未知的商品说「不含」，正是这一整节要消灭的失败方式。
    """
    表 = 从表(造表(造行("XL19806", **{"成分表（完整）": "同 XL99999（编的）"})))
    with pytest.raises(商品表坏, match="XL99999"):
        成分名(表, 表["XL19806"])


def test_改指绕圈不会死循环() -> None:
    """两个货号互指。真表里没有，但**环形数据不该变成挂起** —— 演示当天
    挂起比报错难查得多。"""
    表 = 从表(造表(
        造行("XL10302", **{"成分表（完整）": "同 XL10501"}),
        造行("XL10501", **{"成分表（完整）": "同 XL10302"}),
    ))
    with pytest.raises(商品表坏, match="绕圈|XL10302"):
        成分名(表, 表["XL10302"])
