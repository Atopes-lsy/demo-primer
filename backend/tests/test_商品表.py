"""`app/检索/商品表.py` —— ① 商品属性表的读入与按货号索引。

**合成数据，不碰真 xlsx。** 理由和 `test_装载器.py` 一样：拿真文件测转换逻辑的话，
赛题换一版数据这个文件就跟着红，而它本该只在**逻辑**变了的时候红。

这里钉的是两件事：
1. 索引怎么建（按货号、跳过空行）
2. **列取错了会不会出声** —— 这是本文件的重点，见 `test_缺列要报错`。
"""

from __future__ import annotations

import pytest

from app.检索.商品表 import 从表, 查商品

#: 真表 20 列里本模块要用的 6 列。顺序照 `商品属性表_v7_定稿.xlsx` 的工作表。
用的列 = (
    "商品货号",
    "商品名称",
    "成分表（完整）",
    "不含（可对顾客说）",
    "孕妇慎用成分",
    "不适用/需谨慎",
)


def 造行(货号: str = "XL10302", **覆写: str) -> dict[str, str]:
    """一行商品属性。默认值照抄真表里 `XL10302 测试修护精华液30ml` 那一行。"""
    行 = {
        "商品货号": 货号,
        "商品名称": "测试修护精华液30ml",
        "成分表（完整）": "水、甘油、丁二醇、透明质酸钠、泛醇、积雪草提取物、"
        "神经酰胺NP、角鲨烷、卡波姆、黄原胶、香精、苯氧乙醇",
        "不含（可对顾客说）": "不含：维A类（视黄醇）、水杨酸、对苯二酚、二苯酮-3、皂基",
        "孕妇慎用成分": "无已知慎用成分（维A类／水杨酸／对苯二酚／二苯酮-3 均不含）",
        "不适用/需谨慎": "不建议与高浓度酸类、A醇类叠加使用",
    }
    行.update(覆写)
    return 行


def 造表(*行: dict[str, str]) -> dict[str, list[dict[str, str]]]:
    """把行们装成 `读工作簿` 的形状（工作表名 → 行列表）。"""
    return {"1_商品属性表": list(行) or [造行()]}


# ══════════════════════════════════════════════════════════
# 一 · 索引
# ══════════════════════════════════════════════════════════


def test_按货号索引() -> None:
    """① 是一次按货号的连接（工单 §2.2），所以索引的键必须是货号本身。"""
    表 = 从表(造表(造行("XL10302"), 造行("XL10501", 商品名称="测试舒缓修护面霜50ml")))
    assert set(表) == {"XL10302", "XL10501"}
    assert 表["XL10501"].名称 == "测试舒缓修护面霜50ml"


def test_五列都取到() -> None:
    """工单 §4.1 点名了 content 至少拼这五列，少一列都是「依据不全」。"""
    商品 = 从表(造表())[ "XL10302"]
    assert 商品.货号 == "XL10302"
    assert 商品.名称 == "测试修护精华液30ml"
    assert "苯氧乙醇" in 商品.成分表
    assert "水杨酸" in 商品.不含可对顾客说
    assert "无已知慎用成分" in 商品.孕妇慎用成分
    assert "A醇类" in 商品.不适用需谨慎


def test_空货号的行跳过() -> None:
    """openpyxl 读出来的表尾常有一整行 `None`（`_读表` 会把它们变成空串）。

    不跳过的话会多出一个货号为 `""` 的条目，`查商品(表, "")` 从此命中 ——
    而「订单没有货号」和「货号是空串」在调用方看来会长得一模一样。
    """
    表 = 从表(造表(造行(), 造行(货号="")))
    assert set(表) == {"XL10302"}


def test_查不到返回None() -> None:
    """查不到就是查不到 —— 返回 `None`，**不造一条空记录**。

    第 1 层拿 `六源结果.有记录()` 当判据，凭空造一条 `exists=True` 的空记录
    等于放行一条没有依据的话（工单 §四 的 ⚠️）。
    """
    表 = 从表(造表())
    assert 查商品(表, "XL99999") is None
    assert 查商品(表, "XL10302") is not None


