def test_缺列要报错() -> None:
    """**本文件最重要的一条。**

    五列里少任何一列，`content` 就会悄悄短一截 —— 而第 1 层照样判「查得到」、
    右栏照样显示一条 ① 的依据。**没有任何东西会红**，只是那句依据少了
    「孕妇慎用成分」那半句，而看的人以为自己看到的是全部。

    所以缺列在**装载时**就抛，不等到出稿。
    """
    缺了一列 = {k: v for k, v in 造行().items() if k != "孕妇慎用成分"}
    with pytest.raises(ValueError, match="孕妇慎用成分"):
        从表(造表(缺了一列))


def test_没有那张工作表要报错() -> None:
    """工作表名写死是 `1_商品属性表`（真表里就叫这个）。

    名字对不上时**不能返回空表** —— 空表的意思是「20 个货号一个都查不到」，
    而那句话会一路传成「第 1 层查不到 → 交客服点发送」，看着像正常的保守处理。
    """
    with pytest.raises(ValueError, match="1_商品属性表"):
        从表({"聊天记录": []})


