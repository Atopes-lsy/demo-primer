def test_H1分支词先看主张再看窗口() -> None:
    """**本轮说了什么优先，本轮什么都没说才回头找。**

    `主张` 是这一轮那句话，`风险文本` 是 H1 自己扫过的那个窗口（整条会话到此
    为止的买家话）。真形状是 `S00010`：第 1 轮「全脸发红，还起了小疹子」，
    末轮只剩「行，等你们回访，麻烦尽快」—— 只看主张，四个分支一个都不沾。
    """
    窗口 = ["你好，我用了面膜以后全脸发红，还起了小疹子，有点痒", "行，等你们回访"]

    # 主张里认得出 → 用它，窗口不参与。本轮说「我要投诉」就是投诉那一支，
    # 哪怕她前几轮说过过敏（`_H1分支` 里「不良反应」排在「投诉升级」前面，
    # 认错方向的话，对着一通要投诉的对话说的是不良反应那句）。
    条 = 认转交话术([触发编号.H1], "你们再不处理我就投诉", 风险文本=窗口)
    assert 条 is not None and 条.类型 == "投诉升级"

    # 主张里认不出（收场白）→ 窗口兜底。这句话里写着「建议您先停用，
    # 若持续加重请及时就医」，是全项目唯一一处对不良反应的处置建议。
    条 = 认转交话术([触发编号.H1], "行，等你们回访，麻烦尽快", 风险文本=窗口)
    assert 条 is not None and 条.类型 == "不良反应"
    assert "及时就医" in 条.话术

    # 窗口也没说 → 照旧留空，不猜。
    assert (
        认转交话术([触发编号.H1], "行，等你们回访", 风险文本=["你们到底管不管"])
        is None
    )


