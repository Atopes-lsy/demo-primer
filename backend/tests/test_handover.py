"""转交对客话术 —— `app/rules/handover.py`。

# 这个文件为什么存在

`handover.py` 从 2026-10-01 写完到 2026-10-02，**`tests/` 下没有任何文件 import 它**
（`开发步骤.md` §5b 记着这件事：`grep handover tests/` 只命中 `.pyc`）。
它的三条硬边界写成的是**模块导入时的自检**（`if _违规 := 校验转交话术(): raise`），
于是那段自检**一次都没跑过** —— 三条硬边界当时是「一段没被验证过的代码」，
不是三条被证明成立的约束。

**光 import 就够一半**：这个文件一被 pytest 收走，模块级那句就执行了，
表要是越界，整个文件在收集期就红。所以上面那句话现在由这个文件本身保证 ——
不是靠断言，是靠「它跑得起来」。

# 这里钉的四件事

1. **自检查得出来** —— 喂三张各违反一条硬边界的表进去，三条各要有一条断言。
   一个恒返回空列表的校验函数看起来和真的没区别（`test_安抚话术.py` 同款理由）。
2. **`认转交话术` 的分支顺序** —— 尤其是 **H3 压倒 H1**。这一条写反了不报错，
   只会对着一通要投诉的对话说「24 小时内回访」。
3. **剧本那两句逐字** —— `剧本.ts` 是验收基准，两边对不上就是演示当天对不上。
4. **认不出的那几支留空**，别悄悄猜一句（H2 单独命中、`Z03/Z04/Z07` 那几类）。
"""

from __future__ import annotations

