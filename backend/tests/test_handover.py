def test_H3压倒H1() -> None:
    """**这一条最容易写反，而且写反了不报错。**

    顾客 B 那一轮 H1（要求投诉）和 H3（逾期）同轮命中。按 H1 走会拿到
    「专员会在 24 小时内回访跟进」—— 那是顾客 A（不良反应）那句，
    对着一通已经要投诉的对话许 24 小时，等于把投诉升级成二次投诉。
    `剧本.ts` 第二步的备注记着「v1 在这儿写错过一次」。
    """
    条 = 认转交话术([触发编号.H1, 触发编号.H3], "赠品漏发")
    assert 条 is not None
    assert 条.类型 == "承诺逾期"
    assert 条.话术 == 剧本原文
    assert "24 小时" not in 条.话术, "对要投诉的顾客许 24 小时就是二次投诉"


def test_H4单独走风控() -> None:
    条 = 认转交话术([触发编号.H4], "仅退款，怀疑是空包裹")
    assert 条 is not None
    assert 条.类型 == "风控核实"
    assert 条.时限 is None, "风控类刻意不给时限"


def test_H1按主张再分四支() -> None:
    """H1 一个编号盖不住这件事：它的词表同时收着「过敏／红肿」（人身安全）
    和「投诉／曝光」（舆情），两类要说是两句话。"""
    就医 = 认转交话术([触发编号.H1], "用了之后过敏了，已经去过医院")
    assert 就医 is not None and 就医.类型 == "不良反应已就医"

    过敏 = 认转交话术([触发编号.H1], "用了之后脸又红又痒，起疹了")
    assert 过敏 is not None and 过敏.类型 == "不良反应"

    丢件 = 认转交话术([触发编号.H1], "快递丢件了，要求赔付")
    assert 丢件 is not None and 丢件.类型 == "物流丢件赔付"

    投诉 = 认转交话术([触发编号.H1], "你们再不处理我就曝光你们")
    assert 投诉 is not None and 投诉.类型 == "投诉升级"


def test_H1里就医压过过敏() -> None:
    """顺序在 `_H1分支` 里是有意义的：具体的压过笼统的。
    「过敏了，去过医院」两个词都在，该走**已就医**那条（它多一句退款时效）。"""
    条 = 认转交话术([触发编号.H1], "过敏很严重，已经就医了")
    assert 条 is not None and 条.类型 == "不良反应已就医"


def test_H1认不出就留空不猜() -> None:
    """认不出的失败方向必须是留空。

    `H3交接分类` 认不出只是空一格（信息），这里认错是**直接说给顾客听的**，
    而且这些话术先于客服点发送，说死了收不回来 —— 所以宁可不说。
    """
    assert 认转交话术([触发编号.H1], "你们到底管不管") is None


def test_H2单独命中留空() -> None:
    """⚠️ **这是一处已知的空缺，不是漏写。**

    H2 短路也进转交，但 `转交话术表` 里没有 H2 那一行 —— 规格 §七 那张表是
    按**事项**分的六类（不良反应／风控／丢件／投诉／逾期），H2 是**信号**，
    两者本来就不同轴。补它得先有一个业务方能认的措辞，不是代码里挑一句。
    今天的行为：`判成.转交话术` 空串，主卡不显示话术块。
    """
    assert 认转交话术([触发编号.H2], "你们能不能靠谱点，上次也是这样") is None


def test_一个触发都没有时认K20() -> None:
    """第 2 层权限矩阵判的转交（`Z02 投诉／要求主管` 那一族）不经过 H1–H4，
    认口径会认出 K20 —— 这是 `转交话术表` 里那一行的 `触发` 写的字面值。"""
    条 = 认转交话术([], "要求主管给个说法", ["K20"])
    assert 条 is not None and 条.类型 == "投诉升级"
    assert 条.时限 is None


def test_第2层认不出也留空() -> None:
    """`Z03 售后期`／`Z04 质疑正品`／`Z07 直播承诺` 三条没有对应的话术行。"""
    assert 认转交话术([], "怀疑是假货", ["K09"]) is None


