"""转交对客话术 —— `app/rules/handover.py`。

# 这个文件为什么存在

`handover.py` 从 2026-10-01 写完到 2026-10-02，**`tests/` 下没有任何文件 import 它**
（`开发步骤.md` §5b 记着这件事：`grep handover tests/` 只命中 `.pyc`）。
它的三条硬边界写成的是**模块导入时的自检**（`if _违规 := 校验转交话术(): raise`），
于是那段自检**一次都没跑过** —— 三条硬边界当时是「一段没被验证过的代码」，
不是三条被证明成立的约束。

**光 import 就够一半**：这个文件一被 pytest 收走，模块级那句就执行了，
表要是越界，整个文件在收集期就红。所以上面那句话现在由这个文件本身保证 ——
不是靠断言，是靠「它跑得起来」。

# 这里钉的四件事

1. **自检查得出来** —— 喂三张各违反一条硬边界的表进去，三条各要有一条断言。
   一个恒返回空列表的校验函数看起来和真的没区别（`test_安抚话术.py` 同款理由）。
2. **`认转交话术` 的分支顺序** —— 尤其是 **H3 压倒 H1**。这一条写反了不报错，
   只会对着一通要投诉的对话说「24 小时内回访」。
3. **剧本那两句逐字** —— `剧本.ts` 是验收基准，两边对不上就是演示当天对不上。
4. **认不出的那几支留空**，别悄悄猜一句（H2 单独命中、`Z03/Z04/Z07` 那几类）。
"""

from __future__ import annotations

from app.rules.handover import (
    不给具体时限,
    查转交话术,
    校验转交话术,
    认转交话术,
    转交话术,
    转交话术表,
)
from app.rules.triggers import 触发编号

#: `剧本.ts:911` / `演示会话._线二()` 第 3 条 —— 顾客 B 那一轮客服说的话。
#: **拿这个核，不拿 `handover.py` 核**：表要照剧本改，不是剧本照表改。
剧本原文 = "抱歉让您等了这么久。这边已经把情况升级给专员，会优先处理。"


def _坏(话术: str, 类型: str = "{测}") -> dict[str, 转交话术]:
    """一张只装一条的表，用来喂 `校验转交话术`。

    **`校验转交话术(表=…)` 那个参数位就是为这几条测试开的。** 没有它，
    校验只能对着真表断言「现在是对的」，测不出「错了会不会被拦住」——
    而后者才是三条硬边界存在的意义。

    `类型` 是**键也是值**：硬边界 2 判的是 `类型 in 不给具体时限`，
    所以喂那条时键必须写真实的类型名，不能是占位符。
    """
    return {
        类型: 转交话术(
            类型=类型, 触发="", 话术=话术, 时限=None, 时限出处="测试注入"
        )
    }


# ══════════════════════════════════════════════════════════
# 一 · 自检本身
# ══════════════════════════════════════════════════════════


def test_真表过得了自己的自检() -> None:
    """表里六句现在都没越界。**这条红了先看 `handover.py` 的表，别改测试。**"""
    assert 校验转交话术() == []


def test_硬边界1_时限挂在解决上要拦住() -> None:
    """§七 硬边界 1：「24 小时」是对**回访**的承诺，不是对**解决**的承诺。

    这条由 `_时限后接动词` 那个正则兜着 —— 它是 §6.4 那类禁语的同族
    （时限 ＋ 承诺动词），只是没进禁语表，因为它约束的是转交话术这个局部。
    """
    违规 = 校验转交话术(_坏("我们会 24 小时内解决您的问题。"))
    assert any("解决" in v for v in 违规), f"没拦住越权承诺：{违规}"


def test_硬边界1_时限挂在回访上是合法的() -> None:
    """**反向也要钉**：白名单版本（只允许「回访／联系」后面接时限）
    上线前炸过两条合法话术 —— 「24 小时内电话回访」和
    「退款 1-3 个工作日回到原支付渠道」。合法说法是开放集合，列不完；
    越权说法是封闭的一小撮。所以判据是黑名单，这条测试守着它别被改回白名单。
    """
    assert 校验转交话术(_坏("专员会在 24 小时内电话回访您。")) == []
    assert 校验转交话术(_坏("退款 1-3 个工作日回到原支付渠道。")) == []


def test_硬边界2_风控丢件给了具体时限要拦住() -> None:
    """数据里客服自己都刻意只写「第一时间」，我们不比客服更敢说。

    判据是**白名单不是正则**（`不给具体时限`）—— 风控和丢件属于「结果不可控」，
    给了时限反而制造二次违约，这是规格的意图，不是文本特征。
    """
    for 类型 in 不给具体时限:
        assert 校验转交话术({类型: 转交话术表[类型]}) == [], "真表自己就不合法"
        坏 = _坏("会在 24 小时内处理好。", 类型=类型)
        assert any("不给时限" in v for v in 校验转交话术(坏)), f"{类型} 没拦住"


def test_硬边界3_既无时限也无软承诺要拦住() -> None:
    """没有这句就等于什么都没说 —— 转交话术的作用就是让顾客知道「有人在管」。"""
    违规 = 校验转交话术(_坏("好的，我知道了。"))
    assert any("软承诺" in v for v in 违规), f"没拦住空话：{违规}"


def test_真表里只有不良反应那两条带24小时() -> None:
    """把硬边界 2 直接钉在真表上，不靠人肉核。

    `开发步骤.md` 步骤 2 那节写着「`S_DEMO_B` 那句话术里**绝对不能出现
    『24 小时』** —— 而它现在没有测试盯着，所以是人工核的」。这条就是那个测试。
    """
    带时限 = [t.类型 for t in 转交话术表.values() if "24 小时" in t.话术]
    assert 带时限 == ["不良反应", "不良反应已就医"]
    for 类型 in 不给具体时限:
        assert not any(c.isdigit() for c in 转交话术表[类型].话术), (
            f"{类型} 属于刻意不给时限的类型，正文里不该有数字"
        )


