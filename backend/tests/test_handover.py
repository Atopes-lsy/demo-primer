#: `剧本.ts:911` / `演示会话._线二()` 第 3 条 —— 顾客 B 那一轮客服说的话。
#: **拿这个核，不拿 `handover.py` 核**：表要照剧本改，不是剧本照表改。
剧本原文 = "抱歉让您等了这么久。这边已经把情况升级给专员，会优先处理。"


def _坏(话术: str, 类型: str = "{测}") -> dict[str, 转交话术]:
    """一张只装一条的表，用来喂 `校验转交话术`。

    **`校验转交话术(表=…)` 那个参数位就是为这几条测试开的。** 没有它，
    校验只能对着真表断言「现在是对的」，测不出「错了会不会被拦住」——
    而后者才是三条硬边界存在的意义。

    `类型` 是**键也是值**：硬边界 2 判的是 `类型 in 不给具体时限`，
    所以喂那条时键必须写真实的类型名，不能是占位符。
    """
    return {
        类型: 转交话术(
            类型=类型, 触发="", 话术=话术, 时限=None, 时限出处="测试注入"
        )
    }


