def test_工单的金额列走别名() -> None:
    """带括号的列名只能靠 `alias` —— 线上键必须是 `退款金额(元)`。

    这条防的是「装载器顺手把键改名成 Python 属性名」，那样前端读到 undefined
    而且不报错，界面上只是少一个数字。
    """
    表 = {
        "聊天记录": [造聊天("S1", 1)],
        "线下打款工单": [造工单("线下打款工单", "S1")],
    }
    线 = 装载器.从表(表).会话列表[0].model_dump(mode="json")
    assert 线["工单"]["ticket"]["退款金额(元)"] == 23.5
    assert "退款金额元" not in 线["工单"]["ticket"]


def test_一个会话拿到的是自己那张工单() -> None:
    """五张表都是平表，挂接靠 `会话ID` 而不是行序。"""
    表 = {
        "聊天记录": [造聊天("S1", 1), 造聊天("S2", 1)],
        "物流工单": [造工单("物流工单", "S2", 工单号="WL567743389")],
    }
    会话 = {s.会话ID: s for s in 装载器.从表(表).会话列表}
    assert 会话["S1"].工单 is None
    assert 会话["S2"].工单 is not None
    assert 会话["S2"].工单.ticket.工单号 == "WL567743389"


