def test_订单挂到对应会话() -> None:
    表 = {
        "聊天记录": [造聊天("S1", 1), 造聊天("S2", 1)],
        "订单": [造订单("S2", 订单号="XL2", 单价元=无)],
    }
    表["订单"][0]["单价(元)"] = 799
    会话 = 装载器.从表(表).会话列表
    前, 后 = sorted(会话, key=lambda s: s.会话ID)
    assert 前.订单 is None, "S1 没有订单，不该挂上别人的"
    assert 后.订单 is not None and 后.订单.订单号 == "XL2"


