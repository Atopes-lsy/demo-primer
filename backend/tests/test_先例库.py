def _写(tmp_path, 条们=None, *, 嵌入模型="text-embedding-v4", 版本=1):
    路径 = tmp_path / "先例库.json"
    数据 = {
        "版本": 版本,
        "嵌入模型": 嵌入模型,
        "条数": len(条们 or ()),
        "条目": [
            {"情境": t.情境, "答法": t.答法, "会话ID": t.会话ID, "场景": t.场景,
             "向量": list(t.向量)}
            for t in (条们 or ())
        ],
    }
    路径.write_text(json.dumps(数据, ensure_ascii=False), encoding="utf-8")
    return 路径


