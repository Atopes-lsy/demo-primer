def _表(*行: dict) -> dict:
    return {聊天记录表: list(行)}


def test_一轮一条_情境买家话答法客服话() -> None:
    表 = _表(
        造聊天("S1", 1, "买家", message_text="快递到哪了"),
        造聊天("S1", 2, "客服", message_text="亲，这边看到包裹已到苏州转运中心，明天派送~"),
    )
    (条,) = 先例库.从聊天记录取材(表)
    assert 条.情境 == "快递到哪了"
    assert 条.答法 == "亲，这边看到包裹已到苏州转运中心，明天派送~"
    assert 条.会话ID == "S1"
    assert 条.场景 == "补发换货/破损换货"
    assert 条.向量 == ()


