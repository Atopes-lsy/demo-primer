    assert 桩 is not 先例库.嵌文本
    with pytest.raises(RuntimeError):
        桩(["一段文本"])

    # 同一组入参：不传 `嵌` 卡在桩上，注入假嵌入就写得进去 —— 后半句顺带
    # 证明前半句那个 `False` **不是** `_该丢` 挡的。
    先例库.清空()
    monkeypatch.setattr(先例库, "库路径", tmp_path / "不存在.json")
