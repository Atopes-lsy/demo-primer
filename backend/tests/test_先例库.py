"""③ 先例库 —— 取材、去冗、召回、回写。

# 这个文件里**一条网络请求都不许有**

`召回先例` 是 `话术生成.生成话术` 的默认参数，而 `data/先例库.json` 随仓库提交，
所以「库读不到 / 没密钥 / 没条目时立刻返回 `()`」这三条不是优化，是**测试能不能
跑的前提**（`tests/conftest.py` 那条 autouse 就是干这个的）。要测真库的走
`tests/test_先例库_真数据.py`。
"""

from __future__ import annotations

import pytest

from app.data.装载器 import 聊天记录表
from app.检索 import 先例库
from tests.造数据 import 造聊天


def _表(*行: dict) -> dict:
    return {聊天记录表: list(行)}


def test_一轮一条_情境买家话答法客服话() -> None:
    表 = _表(
        造聊天("S1", 1, "买家", message_text="快递到哪了"),
        造聊天("S1", 2, "客服", message_text="亲，这边看到包裹已到苏州转运中心，明天派送~"),
    )
    (条,) = 先例库.从聊天记录取材(表)
    assert 条.情境 == "快递到哪了"
    assert 条.答法 == "亲，这边看到包裹已到苏州转运中心，明天派送~"
    assert 条.会话ID == "S1"
    assert 条.场景 == "补发换货/破损换货"
    assert 条.向量 == ()


def test_一轮里客服说了两句取最长的那句() -> None:
    """实测逼出来的一条：63 个两句话的轮次里 58 个是「先安抚后说正事」。"""
    表 = _表(
        造聊天("S1", 1, "买家", message_text="赠品怎么还没发"),
        造聊天("S1", 2, "客服", message_text="亲亲稍等哦"),
        造聊天("S1", 3, "客服", message_text="亲，赠品和主单分开发了，这边催一下仓库今天出库~"),
    )
    (条,) = 先例库.从聊天记录取材(表)
    assert 条.答法.startswith("亲，赠品和主单分开发了")


def test_两句一样长取靠后的那句() -> None:
    """`max(reversed(行们), key=len)` —— 一样长时 `max` 取先遇到的，所以要反着喂。

    两句都卡在 27 字（`寒暄长度 = 20` 是硬门槛，短句两条都会被丢掉，
    那样这条测的就成了 `_该丢`）。
    """
    表 = _表(
        造聊天("S1", 1, "买家", message_text="这个怎么弄啊"),
        造聊天("S1", 2, "客服", message_text="亲，您说的这个情况我这边记下了，等下叫专员来帮您看哈~"),
        造聊天("S1", 3, "客服", message_text="亲，您说的这个情况我这边记下了，等下叫同事来帮您看哦~"),
    )
    (条,) = 先例库.从聊天记录取材(表)
    assert 条.答法 == "亲，您说的这个情况我这边记下了，等下叫同事来帮您看哦~"


def test_客服先说话不算一条() -> None:
    """买家话是情境，客服说了话但买家还没说过 → 没有情境，成不了条。"""
    表 = _表(
        造聊天("S1", 1, "客服", message_text="亲，您上次问的补发已经发出去了哈~"),
        造聊天("S1", 2, "买家", message_text="好的"),
    )
    assert 先例库.从聊天记录取材(表) == ()


def test_系统推送不算客服() -> None:
    """服务助手在数据里的角色是 `系统推送`，16 条 —— 它说的话不是客服答的。"""
    表 = _表(
        造聊天("S1", 1, "买家", message_text="我要退货"),
        造聊天("S1", 2, "系统推送", message_text="您的订单已进入退货流程，请耐心等待哦"),
    )
    assert 先例库.从聊天记录取材(表) == ()


def test_两个会话不串台() -> None:
    表 = _表(
        造聊天("S2", 1, "买家", message_text="尺码不对"),
        造聊天("S1", 1, "买家", message_text="颜色不对"),
        造聊天("S1", 2, "客服", message_text="亲，您说的这个颜色的问题我这边记下了，帮您问下仓库哈~"),
        造聊天("S2", 2, "客服", message_text="亲，您说的这个尺码的问题我这边记下了，帮您问下仓库哈~"),
    )
    条们 = 先例库.从聊天记录取材(表)
    assert [(t.会话ID, t.情境) for t in 条们] == [("S1", "颜色不对"), ("S2", "尺码不对")]


def test_多行买家话拼成一段() -> None:
    """买家连着发两行（后面的行是补充）→ 情境是拼起来的，客服只答一次。"""
    表 = _表(
        造聊天("S1", 1, "买家", message_text="这个精华里有乙醇吗"),
        造聊天("S1", 2, "买家", message_text="我脸过敏了"),
        造聊天("S1", 3, "客服", message_text="亲，成分表里没有乙醇，担心过敏的话建议先用一小块试一下哈~"),
    )
    (条,) = 先例库.从聊天记录取材(表)
    assert 条.情境 == "这个精华里有乙醇吗 我脸过敏了"


@pytest.mark.parametrize(
    "答法,理由",
    [
        ("亲，在的呢~", "太短（寒暄）"),
        ("亲亲稍等哦，我这边马上帮您核实一下这个情况哈~", "占位头"),
        ("亲亲您好，欢迎光临测试美妆旗舰店，我是客服岚岚，有什么可以帮到您的呢~", "空壳词"),
        ("亲，这款孕妇可以用哦，我们家成分都很温和的哈~", "禁语（K01）"),
        ("亲，48 小时内给您补发，麻烦您留意一下物流信息哈~", "带单位数字"),
        ("亲，这边已经给您补发过了，物流单号稍后发给您哈~", "「已＋动作」没凭据"),
    ],
)
def test_该丢的六类(答法: str, 理由: str) -> None:
    """**六条都卡在 20 字以上**（除了「太短」那条）—— 短句会被长度那道先拦下，
    测试就成了「长度管用吗」，六道里另外五道一条都没被验到。

    这六条 **2026-10-05 逐条真跑过 `_该丢`**：每条都是被自己那道拦的
    （`占位头` 看开头、`空壳词` 看包含，两张表分开是实测逼出来的）。
    """
    表 = _表(
        造聊天("S1", 1, "买家", message_text="我要退货"),
        造聊天("S1", 2, "客服", message_text=答法),
    )
    assert 先例库.从聊天记录取材(表) == (), 理由


def test_压平把换行和连空格收成一个空格() -> None:
    assert 先例库._压平("  亲\n\n这边  看到  ") == "亲 这边 看到"
    assert 先例库._压平(None or "") == ""
