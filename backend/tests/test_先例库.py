class _记一笔:
    """假嵌入：**记一笔再返回空**。

    ⚠️ **不许写成 `raise AssertionError`。** `召回先例` 把 `Exception` 全吞了
    （网络异常、5xx、超时、JSON 坏了都归它），`AssertionError` 也是 `Exception`
    的子类 —— 抛出去的断言会被一起吞掉，测试**假绿**。
    """

    def __init__(self, 给: dict[str, list[float]] | None = None) -> None:
        self.收到: list[str] = []
        self._给 = 给 or {}

    def __call__(self, 文本们):
        文本 = list(文本们)
        self.收到.extend(文本)
        return [self._给.get(t, [0.0, 0.0]) for t in 文本]


