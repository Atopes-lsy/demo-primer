class _记一笔:
    """假嵌入：**记一笔再返回空**。

    ⚠️ **不许写成 `raise AssertionError`。** `召回先例` 把 `Exception` 全吞了
    （网络异常、5xx、超时、JSON 坏了都归它），`AssertionError` 也是 `Exception`
    的子类 —— 抛出去的断言会被一起吞掉，测试**假绿**。
    """

    def __init__(self, 给: dict[str, list[float]] | None = None) -> None:
        self.收到: list[str] = []
        self._给 = 给 or {}

    def __call__(self, 文本们):
        文本 = list(文本们)
        self.收到.extend(文本)
        return [self._给.get(t, [0.0, 0.0]) for t in 文本]


@pytest.fixture
def 有密钥(monkeypatch: pytest.MonkeyPatch) -> None:
    """**凡是要走到「嵌」那一步的测试都得挂上它。**

    `召回先例` 在没密钥时立刻返回 `()`（那是给线上用的短路，也是测试不打网络的
    保证）。而这把密钥只用来过 `not 先例库密钥()` 那道判断 —— `嵌` 是注进去的
    假的，一个包都发不出去。不挂的话，这些测试在**没设 `PRIMER_LLM_KEY` 的机器
    上全红**，而红的样子是「召回不回东西」，离真正的错很远。
    """
    monkeypatch.setenv("PRIMER_LLM_KEY", "测试用的假密钥")


