def test_去冗相似情境只留先到的那条() -> None:
    """0.98/0.99 这种同义改写的合成对：留先到的，后面的丢。"""
    近 = [1.0, 0.0]
    也近 = [1.0, 0.1]  # cos ≈ 0.995
    远 = [0.0, 1.0]
    条们 = [
        先例库.先例("问退货", "答一", "S1", 向量=tuple(近)),
        先例库.先例("问怎么退", "答二", "S2", 向量=tuple(也近)),
        先例库.先例("问补发", "答三", "S3", 向量=tuple(远)),
    ]
    留 = 先例库.去冗(条们)
    assert [t.情境 for t in 留] == ["问退货", "问补发"]


