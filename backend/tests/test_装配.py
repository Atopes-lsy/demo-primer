@pytest.mark.parametrize("会话ID", ["S_DEMO_A", "S_DEMO_B"])
def test_答应过什么照剧本(装, 会话ID: str) -> None:
    """`剧本.ts` 第 205 行：`9/25 承诺「48 小时内发出」`。

    两条线**共用同一段历史**（剧本第 170 行），所以逐字相同。
    """
    会话 = 装.找(会话ID)
    assert 会话 is not None
    assert _取(装配顾客情况(会话, _轮(会话, 1)), "答应过什么").值 == (
        "9/25 承诺「48 小时内发出」"
    )


@pytest.mark.parametrize("会话ID", ["S_DEMO_A", "S_DEMO_B"])
def test_时限是ISO串且落在9月27日(装, 会话ID: str) -> None:
    """`剧本.ts` 第 172 行：承诺 9/25 ＋「48 小时内发出」= 时限 9/27 24:00。

    落到 **9/27 这一天**是关键，不是 9/27 的哪个时刻 —— H3 按 `date()` 相减
    算天数，日期差一天，「已逾期 2 天」就变成「已逾期 1 天」。
    """
    会话 = 装.找(会话ID)
    assert 会话 is not None
    时限 = _取(装配顾客情况(会话, _轮(会话, 1)), "答应过什么").时限
    assert datetime.fromisoformat(时限).date().isoformat() == "2026-09-27"


def test_时限不放在备注里(装) -> None:
    """`types/index.ts:312` 声明的是 `StateRow.时限?: string`，是个**字段**。

    `剧本.ts` 的 `答应过什么()` 把时限写进了 `备注`，那是前端的假数据；
    契约这边是字段。两边都写的话，界面会显示两遍，而且改一处漏一处。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    assert _取(装配顾客情况(会话, _轮(会话, 1)), "答应过什么").备注 == ""


def test_承诺只认未兑现的() -> None:
    """工单发出去了，那条承诺就兑现了 —— 再报逾期是虚报。

    H3 是「你答应过的没做到」，做到了就不该命中。
    """
    assert 取承诺时限([]) is None


def test_没有承诺消息时时限留空不炸(装) -> None:
    """缺了承诺的消息是**合法状态**（新会话就是这么进来的），
    不能抛异常 —— 它只是没有未兑现的承诺，不是「坏了」。

    这两种情况在日志里必须分得开，所以才留空而不是编一个日期。
    """
    会话 = schemas.Session(
        会话ID="S_空", 买家昵称="路人", 店铺="测试美妆旗舰店", stage="正在接待",
        消息=[], 摘要="", 最近时间="",
    )
    行 = _取(装配顾客情况(会话, None), "答应过什么")
    assert 行.时限 == ""
    assert 行.值


