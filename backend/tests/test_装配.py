@pytest.mark.parametrize("会话ID", ["S_DEMO_A", "S_DEMO_B"])
def test_固定五行且顺序不能改(装, 会话ID: str) -> None:
    """顺序是 `顾客情况五行` 定的，前端默认只展开前两行 ——
    换了顺序等于把「办过什么」折叠起来、把「这次要什么」摊在最上面。"""
    会话 = 装.找(会话ID)
    assert 会话 is not None
    行们 = 装配顾客情况(会话, _轮(会话, 1))
    assert [r.标签 for r in 行们] == list(顾客情况五行)


def test_五行就是五个不重不漏(装) -> None:
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    行们 = 装配顾客情况(会话, _轮(会话, 1))
    assert len(行们) == 5
    assert len({r.标签 for r in 行们}) == 5


def test_每行都有值(装) -> None:
    """空字符串在右栏上就是一块空白 —— 看不出是「没这一项」还是「坏了」。"""
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    for r in 装配顾客情况(会话, _轮(会话, 1)):
        assert r.值, f"「{r.标签}」是空的"


