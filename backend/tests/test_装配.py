def _轮(会话, 序号: int):
    """**到第 `序号` 轮为止**的轮们（从 1 起）。

    2026-10-04 起 `装配顾客情况` 收的是「本次来访的轮们」而不是一轮 ——
    「这次要什么」攒的就是喂进来这些轮里的买家话。所以这里给的是**前缀**：
    第 2 轮含第 1 轮。只关心别的四行的用例照样拿它当个像样的入参使。
    """
    轮们 = 切轮(
        [轮消息(角色=m.角色, 文本=m.message_text, 发送时间=m.发送时间) for m in 会话.消息]
    )
    return 轮们[:序号]


def _取(行们, 标签: str):
    return next(r for r in 行们 if r.标签 == 标签)


