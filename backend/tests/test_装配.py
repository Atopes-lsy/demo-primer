def test_这是谁和这单是会话级快照(装) -> None:
    """`pipeline.按会话缓存` 钉死了这两行不在每轮重读的范围内。

    两轮之间它们逐字相同 —— 不同的话，留痕里解释不了「为什么这一轮的值
    和上一轮不同」：顾客的会员等级和订单信息在一轮对话里不会变。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    第1轮 = 装配顾客情况(会话, _轮(会话, 1))
    第2轮 = 装配顾客情况(会话, _轮(会话, 2))
    for 标签 in ("这是谁", "这单"):
        assert _取(第1轮, 标签) == _取(第2轮, 标签), f"「{标签}」不该每轮重算"


def test_这次要什么跟着轮次变(装) -> None:
    """另外三行是每轮重读的 —— 这一行是「每轮」最明显的那个。

    `已说完=False` 是 `POST /api/判定` 那条路的口径：一轮一答，问的是
    「她此刻说到哪儿了」，这一轮最后那句正是要办的那句，不能当收场白去掉。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    第1轮 = _取(装配顾客情况(会话, _轮(会话, 1), 已说完=False), "这次要什么")
    第2轮 = _取(装配顾客情况(会话, _轮(会话, 2), 已说完=False), "这次要什么")
    assert "乙醇" in 第1轮.值 and "赠品" not in 第1轮.值
    # 攒：第 2 轮是在第 1 轮后面**接上**，不是换掉
    assert 第2轮.值.startswith(第1轮.值)
    assert "赠品" in 第2轮.值


def test_这次要什么去掉最后一句(装) -> None:
    """`GET /api/会话列表` 那条路的口径（默认 `已说完=True`）。

    **去的是收场白，不是最新那句诉求。** 实测 24 个「来过不止一次」的窗口，
    最后一次来访的最后一条买家消息 24/24 是道谢一类；不去尾的话这一行整列
    都是一句「懂了，谢谢美女呢」。演示会话第 3 轮就是那句「好的，谢谢啦」。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    值 = _取(装配顾客情况(会话, _轮(会话, 3)), "这次要什么").值
    assert "乙醇" in 值 and "赠品" in 值
    assert "谢谢" not in 值, "收场白没去掉"


def test_只说了一句就留着那一句(装) -> None:
    """去尾**去不成空** —— 攒空了会把「无」当成她的诉求显示出来。"""
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    轮们 = _轮(会话, 1)
    assert len(轮们[0].买家消息) == 1
