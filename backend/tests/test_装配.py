#: 演示里的「现在」。不是真实日期 —— 整条时间线落在 `剧本.ts` 的 `演示今天`。
演示当前 = datetime(2026, 9, 29, 10, 3, 0)


@pytest.fixture(scope="module")
def 装():
    from app.配置 import 取配置

    return 装载器.从文件(取配置().业务数据路径)


def _轮(会话, 序号: int):
    """第 `序号` 轮（从 1 起）。前端演示里第 1、2 轮是两块不同的屏。"""
    轮们 = 切轮(
        [轮消息(角色=m.角色, 文本=m.message_text, 发送时间=m.发送时间) for m in 会话.消息]
    )
    return 轮们[序号 - 1]


def _取(行们, 标签: str):
    return next(r for r in 行们 if r.标签 == 标签)


