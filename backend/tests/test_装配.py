# 二之二 · `本次买家话` —— 交给模型拆的就是这几句
# ══════════════════════════════════════════════════════════


def test_本次买家话和那一行同源(装) -> None:
    """`POST /api/需求分解` 交给模型拆的，和屏幕上回落显示的是**同一批话**。

    各切各的话，模型坏了回落到原话时，屏幕那行和模型收到的输入对不上 ——
    而那种错看着只是「模型今天不灵」。所以这里钉的是同源：**连起来逐字相同**。

    `已说完` 两种口径都要对，因为两条路用的是同一个参数：
    列表页／真窗口默认去尾，演示那条路（`≤ 到消息`）不去。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    for 已说完 in (True, False):
        for 序号 in (1, 2, 3):
            轮们 = _轮(会话, 序号)
            话们 = 本次买家话(轮们, 已说完=已说完)
            assert 话们, f"第 {序号} 轮该有买家话"
            值 = _取(装配顾客情况(会话, 轮们, 已说完=已说完), "这次要什么").值
            assert " ＋ ".join(话们) == 值


def test_本次买家话去尾去掉的是收场白(装) -> None:
    """去尾是**同一个判断**，不是两条路各写一遍。

    各写一遍的坏处：模型那条路去了尾、原话这条没去（或者反过来），
    屏幕上就是「模型拆的三件事」和「回落时多一句道谢」两种口径。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    轮们 = _轮(会话, 3)
    没去 = 本次买家话(轮们, 已说完=False)
    去了 = 本次买家话(轮们, 已说完=True)
    assert 没去[-1] == "好的，谢谢啦"
    assert 去了 == 没去[:-1], "去尾该只去掉最后一句"


def test_没有买家发言就是空列表不是无() -> None:
    """空列表 ＝ 「没有可拆的输入」，调用方据此**连模型都不问**。

    这里要是回 `["无"]`，`拆需求` 会拿着「无」去问一遍模型 —— 白花一次调用，
    还把「这一趟她什么都没说」写成一条需求。空会话、只有客服开场的会话
    （真数据里有）都走这一支。
    """
    assert 本次买家话([]) == []
    assert 本次买家话(None) == []


