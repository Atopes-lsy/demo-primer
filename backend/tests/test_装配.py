@pytest.mark.parametrize("会话ID", ["S_DEMO_A", "S_DEMO_B"])
def test_取承诺时限喂给H3判出高严重度(装, 会话ID: str) -> None:
    """**装配层和 H3 之间那条线，就是这一个测试。**

    装配层产出 `时限` → H3 读它 → 回填 `警示`。断在哪一环，
    `警示` 都是空的，而空 `警示` 看起来和「今天没逾期」一模一样。
    """
    会话 = 装.找(会话ID)
    assert 会话 is not None
    行们 = 装配顾客情况(会话, _轮(会话, 1))

    触发 = H3逾期(取承诺时限(行们), 演示当前)
    assert 触发 is not None, "H3 没命中 —— 演示里的 ③ 报备整块演不出来"
    assert 触发.严重度 == "高"
    assert 触发.证据[0].endswith("已过 2 天")


def test_回填之后警示是已逾期2天(装) -> None:
    """`剧本.ts` 第 192 行 `逾期 = '已逾期 2 天'`，`docs/31` §3.2 也是这个值。"""
    会话 = 装.找("S_DEMO_A")
