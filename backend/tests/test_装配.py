"""装配层（`app/data/装配.py`）。

`pipeline.组装顾客情况` 存在，但它的 `基础行` 入参**一直没有产出者** ——
全项目 grep 下来只有它自己的定义和调用点。这个文件测的就是那个产出者。

钉三件事，都是「错了不会报错、只在演示当天露馅」的：

1. **五行齐、顺序照 `顾客情况五行`。** 少一行不会炸，右栏只是少一栏。
2. **`时限` 有值且是 ISO 串。** H3 读它比时间；空着 = H3 永不命中 ——
   而「H3 不命中」和「今天没逾期」在界面上**一模一样**。
3. **`警示` 是空的。** 它是 H3 的回填产出（`pipeline.组装顾客情况`），
   这层填了会成环。`pipeline.组装顾客情况` 的文档串专门解释了三步为什么单向。
"""

from __future__ import annotations

