# ── 客服真写的那些形状（`_承诺` 2026-10-05 放宽） ──────────────
#
# 旧的 `_承诺` 只认「N 小时内 ＋ 发出／发货」，**在真数据上几乎一条都不中**：
# 140 个会话里解析得出 `时限` 的只有 3 个（两个还是演示会话）。一条都不进
# `时限` ⇒ H3 永不命中 ⇒ `E05` 整行出局（`permissions.活矩阵`）⇒
# 「答应过的事没做到」在真数据上一次都报不出来。
#
# 下面这些句子**逐字来自那 140 条客服消息**，按出现次数挑的。

#: 会话 ID 单独一个，免得和别的合成会话撞上。
承诺形状ID = "S_承诺形状"


def _许过(文本: str, 时刻: str = "2026-09-25 15:20:08"):
    """客服说过这么一句 → 「答应过什么」那一行。

    走 `装载器.从表` 不手搓 `schemas.Session`：发送时间怎么解析、关联工单号
    空着算不算，都是装载那一层的活，在这儿重写一遍就等于**在测试里写第二份
    实现** —— 它和真实现一起漂，测试还是绿的。
    """
    行 = {**造聊天(承诺形状ID, 1, "客服", 发送时间=时刻, message_text=文本)}
    会话 = 装载器.从表({聊天记录表: [行]}).会话列表[0]
    return _取(装配顾客情况(会话, None), "答应过什么")


@pytest.mark.parametrize(
    ("文本", "到期"),
    [
        ("亲，这边 48 小时内发出～", "2026-09-27"),
        ("专员会在 24 小时内给您结果", "2026-09-26"),
        ("预计 2 天内就能到", "2026-09-27"),
        ("48小时内无走件更新", "2026-09-27"),
        # 区间取**最后一头**：承诺的是第 3 天，不是第 1 天。
        ("打款 1-3 个工作日内到账", "2026-09-30"),
        ("3 个工作日内仍未到账", "2026-09-30"),
    ],
)
def test_客服真写的形状都收得进来(文本: str, 到期: str) -> None:
    """收进来是一条承诺**能被 H3 看见**的唯一入口（`时限` 空着就永不命中）。

    承诺时刻是 9/25 15:20（周五）。`工作日` 那两条落在 **9/30 周三** ——
    「3 个工作日」要跳过周六周日，按日历天数算成 9/28 就会报出假逾期。
    这正是 `_承诺到期` 那个 while 存在的理由。
    """
    行 = _许过(文本)
    assert 行.时限, f"没认出来：{文本}"
    assert datetime.fromisoformat(行.时限).date().isoformat() == 到期, 行.值
    assert datetime.fromisoformat(行.时限).time() == time(23, 59, 59), "期限落在当日末"


