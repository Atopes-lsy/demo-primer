def test_这是谁和这单是会话级快照(装) -> None:
    """`pipeline.按会话缓存` 钉死了这两行不在每轮重读的范围内。

    两轮之间它们逐字相同 —— 不同的话，留痕里解释不了「为什么这一轮的值
    和上一轮不同」：顾客的会员等级和订单信息在一轮对话里不会变。
    """
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    第1轮 = 装配顾客情况(会话, _轮(会话, 1))
    第2轮 = 装配顾客情况(会话, _轮(会话, 2))
    for 标签 in ("这是谁", "这单"):
        assert _取(第1轮, 标签) == _取(第2轮, 标签), f"「{标签}」不该每轮重算"


def test_这次要什么跟着轮次变(装) -> None:
    """另外三行是每轮重读的 —— 这一行是「每轮」最明显的那个。"""
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    第1轮 = _取(装配顾客情况(会话, _轮(会话, 1)), "这次要什么")
    第2轮 = _取(装配顾客情况(会话, _轮(会话, 2)), "这次要什么")
    assert 第1轮 != 第2轮
    assert "乙醇" in 第1轮.值
    assert "赠品" in 第2轮.值


def test_这次要什么就是本轮买家原话(装) -> None:
    会话 = 装.找("S_DEMO_A")
    assert 会话 is not None
    轮 = _轮(会话, 1)
    assert _取(装配顾客情况(会话, 轮), "这次要什么").值 == " ＋ ".join(轮.买家消息)


