def test_prompt里要有消息和已有的诉求清单() -> None:
    """归属判的是「这条消息属不属于下面这几件里的一件」，所以**清单必须进 prompt**。

    少塞清单的后果不是报错，是模型永远只能起新诉求 —— 每个诉求各分一轮，
    而屏幕上看起来一切正常。
    """
    问, 记录 = 假模型("赠品补发")
    认诉求("对了，我上次那个赠品还没给我发呢", 清单, 问=问)
    _, 提示 = 记录[0]
    assert "我上次那个赠品还没给我发呢" in 提示
    assert "赠品补发" in 提示
    assert "孕期能否使用" in 提示


def test_清单为空时prompt也要说清楚() -> None:
    """空清单不能渲染成一片空白 —— 模型会以为那句话被截断了。"""
    问, 记录 = 假模型("赠品补发")
    认诉求("赠品没到", (), 问=问)
    _, 提示 = 记录[0]
    assert "赠品没到" in 提示
    assert "没有" in 提示 or "暂无" in 提示 or "（无）" in 提示
