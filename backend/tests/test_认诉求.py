"""节点 3.5：`认诉求` —— 一条消息归到哪个诉求上。

# 为什么它不能并进 `拆主张`

催促可能**拆不出任何主张**（「还要多久」不是一个能独立处置的事实点，
按 v8 §二该拆出零条），但它的归属是必须的：H2 的窗口要它、G4 防重复要它、
小卡要它。**归属问题在主张列表为空时依然存在**，所以不能靠 `拆主张` 的输出来带。

# 三个词别混（`一句话进来的流程.md`）

诉求 ⊃ 轮 ⊃ 主张。诉求是**可跨轮跨天**的那一件事，主张是**一条消息里**的事实点。

# 这里钉的是哪一侧

和 `test_llm.py` 同一个分法：prompt 里该有什么、模型吐出来的东西怎么解析、
吐得不对时退到哪儿。**模型准不准不在这儿测** —— 那要真数据，是端到端的事。
"""

from __future__ import annotations

from app.llm.客户端 import LLM不可用
from app.llm.认诉求 import 认不出, 认诉求
from tests.假模型 import 假模型

清单 = ["赠品补发", "孕期能否使用"]


# ══════════════════════════════════════════════════════════
# 一 · 归属
# ══════════════════════════════════════════════════════════


def test_清单里能对上就原样返回那一个() -> None:
    """工单 §4.2：「返回的是清单里那一个，**逐字相同**」。

    逐字相同不是洁癖：这个返回值就是诉求的身份，清单是跨消息存活的那一份
    —— 改写一个字，同一个诉求在下一轮就变成了另一个。
    """
    问, _ = 假模型("赠品补发")
    归 = 认诉求("对了，我上次那个赠品还没给我发呢", 清单, 问=问)
    assert 归 == "赠品补发"
    assert 归 in 清单


def test_对不上就起一个新诉求() -> None:
    """工单 §4.2：「返回的标签不在清单里」。"""
    问, _ = 假模型("开发票")
    assert 认诉求("另外帮我开个发票", 清单, 问=问) == "开发票"


def test_模型改写了清单里的标签就不算命中() -> None:
    """工单 §2.4：**「补发」和「补发赠品」是两个诉求，会分出两轮。**

    所以这里**不做模糊归并** —— 模型回了个近义的说法，就当新诉求起一条。
    替它归并等于替它决定「这两件事是一件事」，而那正是它会出错的地方。

    代价是模型不听话时多分一轮；prompt 里已经写了「属于某一条就原样照抄」，
    那一条比这里的兜底更该管用。
    """
    问, _ = 假模型("补发赠品")
    归 = 认诉求("赠品没到", ["补发"], 问=问)
    assert 归 == "补发赠品"
    assert 归 != "补发", "不能替模型把新标签归并到清单里的旧标签上"


def test_模型加了引号也算命中() -> None:
    """模型爱把答案包在引号里。**剥掉最外面一层成对的引号再比。**

    这和上一条不矛盾，两件事分得开：
    - **引号是格式脏**（模型在「引用」它的答案），剥掉它不改动一个字
    - **改写是语义脏**（「补发赠品」vs「补发」），那是另一件事，不能替它归并

    不剥的话「「赠品补发」」会变成一条新诉求 —— 和「赠品补发」明明是同一件事，
    却分成了两轮。
    """
    问, _ = 假模型("「赠品补发」")
    assert 认诉求("赠品没到", 清单, 问=问) == "赠品补发"


def test_清单为空也能起一个新诉求() -> None:
    """工单 §4.2：「不炸，返回一个新标签」。会话第一条消息就是这条路。"""
    问, _ = 假模型("孕期能否使用")
    assert 认诉求("我怀孕了，这个能用吗", (), 问=问) == "孕期能否使用"


def test_标签两头空白要洗掉() -> None:
    """模型爱在答案两头加空白或换行，那不该变成一个带空格的诉求身份。"""
    问, _ = 假模型("  赠品补发\n")
    assert 认诉求("赠品没到", 清单, 问=问) == "赠品补发"


