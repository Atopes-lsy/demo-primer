def test_模型不可用退到同一个标签() -> None:
    """**这是本模块最要紧的一条兜底。**

    模型挂了的时候，每条消息各自成了新诉求 → **每条消息各自成了一轮** ——
    而「轮」正是 H2 连发检测要看到的形状（顾客连发「在吗」「在吗？」「在吗！」
    时，各自成轮就永远凑不到阈值 3）。

    所以退到**同一个**标签：它们全落进一个诉求，`切轮` 的归属分组退化成
    「不分组」，等于今天那条纯结构的切法（工单 §3.3 要的正是这个退路）。
    """
    问, _ = 假模型(LLM不可用("连接超时"))
    甲 = 认诉求("赠品没到", (), 问=问)
    乙 = 认诉求("我的脸过敏了", (), 问=问)
    assert 甲 == 乙 == 认不出


def test_模型吐了个空的也退到认不出() -> None:
    问, _ = 假模型("")
    assert 认诉求("赠品没到", 清单, 问=问) == 认不出


def test_空消息返回空() -> None:
    """消息本来就是空的（一条纯图片、或只有空格）时返回空串 —— 没有诉求可谈。

    不返回 `认不出`：那会把一条纯图片也塞进「当前未解决的诉求」里，
    而它根本没有诉求。和 `拆主张` 对空消息返回 `[]` 是同一个分法。
    """
    问, 记录 = 假模型("赠品补发")
    assert 认诉求("   ", 清单, 问=问) == ""
    assert 记录 == [], "空消息不该发网络调用"


