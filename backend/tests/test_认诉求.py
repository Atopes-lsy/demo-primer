def test_不做缓存每次都问模型() -> None:
    """工单 §2.3：**别在 `llm/` 里做缓存或全局状态。**

    缓存会让它从「同样输入同样输出」变成「取决于这个进程之前跑过什么」——
    留痕就再也解释不了某一轮为什么判成那样。而清单一向由调用方传进来，
    这里本来就没有需要记的东西。
    """
    问, 记录 = 假模型("赠品补发")
    认诉求("赠品没到", 清单, 问=问)
    认诉求("赠品没到", 清单, 问=问)
    assert len(记录) == 2, "第二次没问模型 —— 说明这里存了状态"


def test_同样输入同样输出且不动调用方的清单() -> None:
    """工单 §4.2 第 4 条。顺带钉住**不修改调用方传进来的清单** ——
    那份清单是装配层的会话状态，被这里就地改了，下一轮读到的就是脏的。
    """
    原件 = ["赠品补发", "孕期能否使用"]
    问, _ = 假模型("赠品补发")
    第一次 = 认诉求("赠品没到", 原件, 问=问)
    第二次 = 认诉求("赠品没到", 原件, 问=问)
    assert 第一次 == 第二次 == "赠品补发"
    assert 原件 == ["赠品补发", "孕期能否使用"], "改了调用方传进来的清单"


