def test_闸门对注入那条路也开着() -> None:
    """口子**只能在本轮活着的行里挑** —— 它得先收到那张活矩阵。

    ⚠️ **上面那条测过的是「模型挑中被闸掉的行 → 未列明」，那是**半个**保证。**
    它保证 E05 不会在没有 H3 的时候生效，但保证不了**接下来该认到谁**。
    真实场景里「赠品至今未补发」这句同时匹配 `E05`（承诺逾期）和 `L01`
    （补发／漏发赠品）：

    - H3 在场 → 该 E05，报备 ＋ 强制先道歉；
    - H3 不在 → 该 `L01`，限额 1 件、超出后 **报备**。

    两种都对。坏的是**第三种**：模型拿到的是**整张表**（`deps.认权限` 把
    `权限条目表` 闭包进去了），于是它在两类措辞里都挑中 `E05`；H3 不在的那轮
    `E05` 已被滤掉，编号换不到条目 → `未列明` → **放去第 3 层**。
    结果是 `L01` 的限额**整个回合没人比** —— 一件也好十件也好，
    都成 `AI直发`／`客服点发送`。这不是「少一句说明」，是**限额被绕过去了**。

    根子在于闸门开的不是地方。`活矩阵` 的文档串说闸门「开在传矩阵这一步，
    两条路同一个闸门」，可**注入那条路根本没收到矩阵** —— 它挑的时候看的
    是 `deps` 里那张全表，闸门开在了它后面。所以这里钉的是**口子收到的表**：
    不是「结果是 L01」这种可以靠事后补救凑出来的东西。

    口子在这里按**它收到的表**去挑，就是在模拟真模型 —— `llm/认权限.认权限
    (主张, 权限矩阵)` 本来就是这个形状，是 `deps.认权限` 那个转接头把矩阵
    提前绑死了、形状掉成了 `Callable[[str], str | None]`。
    """
    收到: list[Sequence[权限条目]] = []

    def 口子(主张: str, 权限矩阵: Sequence[权限条目]) -> str | None:
        收到.append(权限矩阵)
        # 按收到的表挑，和真模型一致（它看不见没发给它的行）
        条目 = 认权限(主张, 权限矩阵)
        return 条目.编号 if 条目 is not None else None

    判定 = 查权限("赠品至今未补发", 认权限函数=口子)

    assert [k.编号 for k in 收到[0]] == [k.编号 for k in 活矩阵()], (
        f"口子收到的不是活矩阵（E05 还在里面就是没滤）:{[k.编号 for k in 收到[0]]}"
    )
    assert 判定.条目 is not None and 判定.条目.编号 == "L01", (
        f"H3 不在，这句该落到 L01：{判定.说明}"
    )


