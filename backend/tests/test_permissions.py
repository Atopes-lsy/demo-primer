"""权限矩阵（第 2 层）的测试。

`permissions.py` 是这三层里最容易「看着对、跑起来反」的一份 —— 22 行表格
里每行都有 `限额` 和 `超出后去向` 两个字段，而**哪些行有额度、哪些行压根
没有额度这回事**，从字段本身看不出来（§6.3 那七行的去向来自小节标题，
不是额度）。所以这里测的是**几个已经判反过的坑**，不是逐行覆盖率：

- 「认不上诉求」曾经被判成「判不了 → 报备」，于是每一句普通咨询都被推给上级

逐行断言 22 行的字段值没有意义（表格改一个字就得改测试，而表格本来就该能改）
—— 真正要钉住的是**读表的规则**。
"""

from __future__ import annotations

from app.rules.permissions import (
    权限事实,
    权限去向,
    权限条目,
    权限条目表,
    查权限,
    认权限,
)

# ── 认诉求（认权限） ────────────────────────────────────────

def test_认不上诉求是未列明而不是判不了():
    """**这条是本次重构最容易搞反的地方。**

    原先「认不上」和「判不了」是同一态，去向都是报备 —— 结果是顾客随便问
    「这个精华有乙醇吗」都被推到「已提交组长审批」，因为成分表根本不在
    §六 那张表里（矩阵管的是**要授权的事**，不是「客服能聊什么」的白名单）。

    v9 的示范例子直接推翻了它：含不含乙醇是**有来源、不涉承诺**，
    该 AI 直接发。所以认不上是**未列明**：继续第 3 层，跟「在权限内」同路，
    只在留痕里区分。
    """
    判定 = 查权限("这个精华有乙醇吗")
    assert 判定.去向 is 权限去向.未列明
    assert 判定.能否继续第3层(), "未列明要继续第 3 层，不能停在报备"
    assert 判定.条目 is None


def test_判不了停在报备不继续第3层():
    """判不了 ≠ 未列明。判不了是**认上了、但条件查不到**（§4.2
    「查不到**条件**」：几件／多少钱／是不是质量问题）。

    这时候我们不能替顾客办，所以停在报备 —— 见 `权限事实` 那段：
    「在权限内」是要拿事实证明的结论，不是默认值。
    """
    判定 = 查权限("补发一下")  # 事实什么都不给 → 件数未知
    assert 判定.去向 is 权限去向.判不了
    assert not 判定.能否继续第3层()


def test_无关维度未知不算判不了():
    """补发不看金额，退款不看件数。

    拿**无关维度**上的 `None` 去判会凭空造出「判不了」，把客服本来能办的
    事挡回去 —— 补发的额度是 1 件/单，顾客这单花了多少钱跟它没关系。
    """
    判定 = 查权限("补发一下", 权限事实(件数=1))  # 金额仍是 None
    assert 判定.去向 is 权限去向.在权限内, "金额未知不该拦住补发"


def test_具体词压过笼统词():
    """同时含「漏发」和「赠品」时归**漏发**（L01），不是赠品追加（L03）。

    两个词一样长，靠编号先后定的 —— 与 `pipeline.认口径` 的 `(-len, 编号)`
    同一个解法。顺序稳定是可重放的要求，所以这条要钉住：换个遍历顺序就漂了。
    对照下一条：不含「漏发」时同样的「赠品」落到 L03。
    """
    漏发 = 认权限("赠品漏发了")
    追加 = 认权限("再追加两个赠品")
    assert 漏发 is not None and 漏发.编号 == "L01"
    assert 追加 is not None and 追加.编号 == "L03"


def test_不可认的行认不到():
    """`E01–E05`／`X01` 是「超额度之后的**后果**」，不是顾客会说的诉求。

    顾客不会说「我要求补发超过 1 件」，只会说「帮我补发一下」—— 把后果行
    也放进认的过程，「顾客要求补发」会被认成「补发超过 1 件」。

    ⚠️ 今天那六行的 `关键词` 都是空的，所以这道闸门**目前是预防性的**：
    真正的额度问题由 L01 这类行的 `超出后去向` 表达。这条测试是拦住
    「哪天顺手给 E 行补上关键词」。
    """
    行 = 权限条目(
        编号="E99",
        事项="合成行，只为测 `可认` 这道闸门",
        层级="一线",
        限额="> 1 件/单",
        依据="测试",
        去向=权限去向.报备,
        可认=False,
        关键词=("漏发",),
    )
    assert 认权限("漏发了", (行,)) is None


# ── 判额度（查权限） ────────────────────────────────────────

def test_没超额度时去向取条目自己的():
    """§6.3 那七行（丢件／投诉／质疑正品……）**压根没有额度这回事**。

    所以「没超额度 → 在权限内」这种写法会把丢件判成客服自己能办。
    这台逻辑的正确形态是「没触发超额 → 去向 = 条目自己的去向」，
    而 §6.3 那些行的去向来自**小节标题**（必须转交），与额度无关。
    """
    判定 = 查权限("快递丢件了")
    assert 判定.条目 is not None and 判定.条目.编号 == "Z06"
    assert 判定.去向 is 权限去向.转交
    assert not 判定.能否继续第3层()


def test_超额度改判超出后去向():
    """L01 补发 1 件/单，2 件就超 —— 超了以后走 `超出后去向`（报备）。"""
    判定 = 查权限("补发一下", 权限事实(件数=2))
    assert 判定.去向 is 权限去向.报备
    assert 判定.条目 is not None and 判定.条目.编号 == "L01"


def test_矩阵里每条在权限内的行都认得出():
    """「在权限内」的行必须带关键词，否则它永远认不上、是死配置。

    这和 `test_rules.py` 里「替换说法每一条都够得着」是同一类检查：
    数据里有一条永远走不到的配置，等于少一条规则而没人知道。
    """
    死的 = [
        k.编号
        for k in 权限条目表
        if k.可认 and k.去向 is 权限去向.在权限内 and not k.关键词
    ]
    assert not 死的, f"这些行没有关键词，永远认不上：{死的}"
