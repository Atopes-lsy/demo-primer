@pytest.mark.parametrize("源", list(六源))
def test_出现的记录一律exists且用上(源: 六源) -> None:
    """**记进来的每一条都是 `exists=True`、`用上=True`。**

    `exists` 的闸门在**记不记**这一步：不相关就不进 `记录`，进来的必然是真查到了。
    所以这里不会出现 `exists=False` 的占位记录 —— 那种记录是「凑 N/6」的产物。

    `用上` 在这个阶段恒等于 `exists`：话术还没生成，没人能回答「引没引用」
    （3c 才做得到）。这里按 `判成.依据` 的文档串取**检索层判的相关性**那个口径
    —— 而相关性已经在上面每个源的判据里用过了，所以恒真。
    第 3 层出稿之后若发现某条没被引用，改的是那一侧，不回写这里。
    """
    有补发 = 装载器.从表(
        {
            "聊天记录": [造聊天("S1", 1)],
            "订单": [造订单("S1", 商品货号="XL10302")],
            "补发换货工单": [造工单("补发换货工单", "S1", 工单号="BH001")],
        }
    ).会话列表[0]
    结果 = 查六源("赠品未发货", 有补发, 商品表, 口径表=口径表, 口径编号="K05")
    for 号, 组 in 结果.记录.items():
        for r in 组:
            assert r.exists, f"{号} 记了一条 exists=False 的"
            assert r.用上, f"{号} 记了一条 用上=False 的"
            assert r.content, f"{号} 的记录没有 content"


def test_有记录与命中源一致() -> None:
    """`有记录()` 看 `exists`、`命中源()` 还要看 `用上` —— 两者在这里同进同出。

    第 1 层用前者，右栏的 `N/6` 用后者。它们在这一层**必须一致**，
    否则会出现「右栏显示 0/6，但判定说查得到」这种对不上的画面。
    """
    结果 = 查六源("含乙醇", 造会话(), 商品表, 口径表=口径表, 口径编号="K10")
    assert 结果.有记录()
    assert 结果.命中源() == frozenset({六源.商品属性表, 六源.口径表})
