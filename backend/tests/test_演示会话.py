def test_两条演示会话都装得出来(会话们) -> None:
    assert [s.会话ID for s in 会话们] == ["S_DEMO_A", "S_DEMO_B"]


def test_昵称照剧本(会话们) -> None:
    assert 取会话(会话们, "S_DEMO_A").买家昵称 == "小鹿"
    assert 取会话(会话们, "S_DEMO_B").买家昵称 == "阿沅"


def test_订单挂上了(会话们) -> None:
    """订单号是派生的交接包单号的来源，错了右栏那张包就对不上。"""
    a, b = 取会话(会话们, "S_DEMO_A"), 取会话(会话们, "S_DEMO_B")
    assert a.订单 is not None and b.订单 is not None
    assert (a.订单.订单号, a.订单.商品货号, a.订单.商品名称) == (
        "20260925001", "XL10302", "测试修护精华液30ml",
    )
    assert (b.订单.订单号, b.订单.商品货号, b.订单.商品名称) == (
        "20260925002", "XL10501", "测试舒缓修护面霜50ml",
    )
    # 「已签收」说的是**正装**那一件；赠品那件没发，靠 `发货时间` 空着表达
    # （见 `演示会话._订单` 的文档串）。两件货两条命，别把这两格当成互相矛盾。
    assert a.订单.订单状态 == b.订单.订单状态 == "已签收"
    assert a.订单.发货时间 == b.订单.发货时间 == ""


def test_补发工单挂上了(会话们) -> None:
    """`时限` 的锚点是这张工单的创建时间，号也是交接包引用的那个。"""
    for 会话ID, 工单号, 创建时间 in (
        ("S_DEMO_A", "BF20260925001", "2026-09-25 15:20:08"),
        ("S_DEMO_B", "BF20260925002", "2026-09-25 16:44:51"),
    ):
        工单 = 取会话(会话们, 会话ID).工单
        assert 工单 is not None and 工单.kind == "补发换货"
        assert 工单.ticket.工单号 == 工单号
        assert 工单.ticket.创建时间 == 创建时间
        assert 工单.ticket.工单状态 == "待发货", "「待发货」就是「承诺还没兑现」"
        assert 工单.ticket.补发物流单号 == "", "还没发出，所以是空的"


