"""演示会话（`app/data/演示会话.py`）的形状与事实。

**为什么另造一份而不动真数据。** 契约写死了「消息不从请求里传，后端按 `会话ID`
自己查」，而 `S_DEMO_A`／`S_DEMO_B` **不在真数据里** —— 实测 138 个真实会话
全是 `S00001…`。这两个 ID 只活在前端 `frontend/src/data/剧本.ts` 里。

这份测试钉三件事，都是「誊错了不会报错、只会在演示当天露馅」的那种：

1. **序号从 1 起、连续。** `切轮` 和 `已发出的话` 都按序号扫，断号不会报错，
   只会让某一轮凭空消失。
2. **事实对得上剧本。** 号、状态、时间逐字核。
3. **期望值没混进来。** `剧本.ts` 的每步存着「该出什么处置」，那是验收标准。
   喂进数据等于把被测的东西喂给被测者。

真数据那三个计数（138/113/80）在 `test_装载器_真数据.py`，和这里无关 ——
这份文件绿不绿，和赛题发不发新数据无关。
"""

from __future__ import annotations

import pytest

from app.data import 演示会话
from app.data.装载器 import 装载器, 聊天记录表
from app.rules.pipeline import 轮消息, 切轮
