def test_数据里没有警示没有逾期字样(表) -> None:
    """`警示` 是 H3 的回填产出（见 `pipeline.组装顾客情况`）。

    数据里但凡出现「已逾期」这种字眼，就说明有人把验收标准誊进来了 ——
    而它会让「H3 没接通」这件事在演示时看着像通了。
    """
    文本 = "\n".join(
        str(值) for 行 in 表.get(聊天记录表, []) for 值 in 行.values()
    )
    for 字样 in ("已逾期", "逾期", "报备", "转交", "需要话术", "需要授权"):
        assert 字样 not in 文本, f"演示数据里出现了判定结论「{字样}」"


