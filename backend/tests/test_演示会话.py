@pytest.mark.parametrize("会话ID", ["S_DEMO_A", "S_DEMO_B"])
def test_序号从1起且连续(会话们, 会话ID: str) -> None:
    """⚠️ `切轮` 和 `已发出的话` 都按序号扫，**断号不会报错**，
    只会让某一轮凭空消失 —— 而「某一轮没了」在右栏上看就是「没事发生」。"""
    序号 = [m.消息序号 for m in 取会话(会话们, 会话ID).消息]
    assert 序号 == list(range(1, len(序号) + 1))


def test_线一七条线二三条(会话们) -> None:
    """线一：承诺 ＋ 两个来回 ＋ 道谢。线二：承诺 ＋ 一句「我要投诉」＋ 转交。"""
    assert len(取会话(会话们, "S_DEMO_A").消息) == 7
    assert len(取会话(会话们, "S_DEMO_B").消息) == 3


def test_剧本里跳掉的序号在这是补上的(会话们) -> None:
    """`剧本.ts` 线一的序号是 1,2,4,5,6,7 —— **第 3 号是空的**。

    因为剧本按「步」走，第五步（等客服点发送）没有消息，序号就跟着缺了一格。
    后面还压着那 7 条消息，谁也看不出缺。誊成后端数据时**重编**成连续的，
    前端那边的序号不用跟着改 —— 它只是回放的格子，不是契约。
    """
    序号 = [m.消息序号 for m in 取会话(会话们, "S_DEMO_A").消息]
    assert 序号 == [1, 2, 3, 4, 5, 6, 7]


