#: 两条线共用的那段历史 —— 9/25 登记补发时客服那句承诺。
#: `剧本.ts` 把它写成了常量（`承诺话术 = '48 小时内发出'`，第 190 行），
#: 界面上从没有过这条消息；但判定层要从**消息**里解析出 `时限`
#: （`工单交接_给接口线.md` §三），所以演示数据得把它补成一条真的客服消息。
承诺原文片段 = "48 小时内发出"


@pytest.fixture
def 表() -> dict[str, list[dict[str, object]]]:
    return 演示会话.演示表()


@pytest.fixture
def 会话们(表):
    return 装载器.从表(表).会话列表


def 取会话(会话们, 会话ID: str):
    return next(s for s in 会话们 if s.会话ID == 会话ID)


