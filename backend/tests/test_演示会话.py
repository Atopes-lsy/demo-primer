def _轮消息(会话) -> list[轮消息]:
    return [轮消息(角色=m.角色, 文本=m.message_text, 发送时间=m.发送时间)
            for m in 会话.消息]


def test_线一切得出三轮(会话们) -> None:
    """1：问成分；2：提赠品；3：道谢。第 1、2 轮正是演示里那两块屏。"""
    轮们 = 切轮(_轮消息(取会话(会话们, "S_DEMO_A")))
    assert [r.买家消息 for r in 轮们] == [
        ("你好，这个精华里有乙醇吗，我怀孕了能用吗",),
        ("对了，我上次那个赠品还没给我发呢",),
        ("好的，谢谢啦",),
    ]


def test_线二切得出一轮(会话们) -> None:
    """承诺那句是客服发的，不占一轮 —— 买家的发言只有那一条。"""
    轮们 = 切轮(_轮消息(取会话(会话们, "S_DEMO_B")))
    assert [r.买家消息 for r in 轮们] == [
        ("上次说好的赠品到现在都没到，你们到底管不管？我要投诉",),
    ]


def test_承诺那句不在任何一轮里(会话们) -> None:
    """它是 9/25 的历史，不是这一轮买家说的话。

    要是被算进第 1 轮的「买家消息」，`拆主张` 会从客服自己的承诺里拆出主张 ——
    于是「48 小时内发出」变成一条顾客诉求。
    """
    轮们 = 切轮(_轮消息(取会话(会话们, "S_DEMO_A")))
    assert all(承诺原文片段 not in 文 for r in 轮们 for 文 in r.买家消息)


