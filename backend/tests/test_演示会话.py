def test_演示ID就是演示表里那两个(表) -> None:
    """`演示ID` 是「哪些会话算演示」的**唯一出处** —— `api/判定` 拿它决定
    回写走哪一支（`_回写参数`）。

    誊错了不报错：那一条的回写就悄悄退回普通支，而普通支和演示支在屏幕上
    长得一模一样，只有那个 +1 不来。
    """
    assert set(演示会话.演示ID) == {行["会话ID"] for 行 in 表[聊天记录表]}


def test_兜底话术是给线一第1轮那件事的() -> None:
    """兜底句只在「模型那一稿被 `_该丢` 挡下」时才用得上，**配错了不报错** ——
    一句讲赠品的答复会落到问成分那一轮上，顶着自己的名进库被后面几轮当参照。

    所以「哪条会话有兜底句」得是明的：线一有（问成分 ＋ 怀孕能不能用），
    线二没有（它整轮转交，`该回写条` 压根不放行，写了也到不了）。
    """
    assert set(演示会话.兜底回写) == {"S_DEMO_A"}
    assert set(演示会话.兜底回写) <= set(演示会话.演示ID)


def test_兜底话术自己得过得了闸门() -> None:
    """⚠️ **这条是防它烂掉的。** 兜底句是手写的，`回写` 里还要再查一遍
    `_该丢` —— 过不了的话「演示线一第 1 轮必定 +1」就变成「必定写不进去」，
    而那时屏幕上只是那个 +1 不来，什么错都不报。

    `回写` 里那道复查是**兜底**（防手滑），不是这道测试的替代品：一道在跑之前
    拦，一道在写之前拦，两道的时机不一样。
    """
    from app.检索 import 先例库

    for 会话ID, 句 in 演示会话.兜底回写.items():
        assert not 先例库._该丢(句), f"{会话ID} 的兜底句过不了 `_该丢`：{句!r}"
        assert len(句) > 先例库.寒暄长度, "太短的会被长度那道先拦下"
