def test_去重的键是诉求不是会话() -> None:
    """去重的键是 `(会话, 诉求集合)` —— **同会话的另一件事该拿新号**。

    拿会话当键的话，一个会话永远只有一张单子，第二件事会被并进第一张。

    **直接调 `台账.发号`。** 走路由碰不到这个分岔：演示那两条线各自只有
    一件事要报备／转交（A 第 2 轮的赠品、B 第 1 轮的两条），拿会话当键和拿
    诉求当键出来的**是同一串号** —— 这条用例会以「绿」的样子盖住 §五 没落地。
    """
    天 = date(2026, 9, 29)
    一号 = 发号("S1", ["赠品漏发"], 天)
    assert 发号("S1", ["赠品漏发"], 天) == 一号, "同一件事重复报，号不变（客服手滑点两下）"
    assert 发号("S1", ["发票没开"], 天) != 一号, "同一会话里的另一件事要拿新号"
    assert 发号("S2", ["赠品漏发"], 天) != 一号, "另一个会话的同一件事也是新号"

    # 顺序和重复都不该改键 —— 主张列表是**集合**，不是序列。
    # 「漏发」「赠品漏发」两条一起报，两次判定的顺序不保证一样。
    assert 发号("S3", ["a", "b"], 天) == 发号("S3", ["b", "a"], 天)
    assert 发号("S3", ["a", "b"], 天) == 发号("S3", ["a", "a", "b"], 天)

    # 号是按日期全店排的，不是每个会话各自从 1 数。
    assert 发号("S4", ["x"], date(2026, 9, 30)) == "JJ20260930001"


