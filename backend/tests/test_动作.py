async def _打(方法: str, 路径: str, **体: Any) -> Any:
    交通 = ASGITransport(app=main.app)
    async with AsyncClient(transport=交通, base_url=测试基地址) as 客户端:
        return await 客户端.request(方法, 路径, **({"json": 体} if 体 else {}))


async def 判定一次(会话ID: str = "S_DEMO_A", 轮次: int | None = None) -> dict[str, Any]:
    """先跑一次判定 —— 台账就是它写进去的。**动作接口都要求先有这一下。**"""
