@pytest.mark.usefixtures("装了")
async def test_发送记下这条话术兑现哪几条主张() -> None:
    """`采用的处置id[]` 存在的**唯一理由**（契约 §二 那一行）。

    客服点了［采用］再点［发送］，这一句对应哪几条主张要记下来 ——
    留痕回放时「这条诉求办没办」全靠它。所以响应把 `主张` 一并回出来，
    前端不用自己拿 id 去猜。
    """
    体 = await 判定一次("S_DEMO_A", 轮次=1)
    处置 = {d["主张"]: d["id"] for d in 体["本轮处置"]}
    assert 处置, "前提：这一轮判出了东西"

    选 = 处置["孕妇能否用"]
    响应 = await 发送("S_DEMO_A", "感谢您告诉我们……", [选])
    assert 响应.status_code == 200, 响应.text
    回 = 响应.json()
    assert 回["兑现主张"] == ["孕妇能否用"], 回
    assert 回["会话ID"] == "S_DEMO_A"
    assert 回["轮次"] == 1
    assert 回["话术"] == "感谢您告诉我们……", "话术原样回，前端拿它落地那条消息"

    # 留痕那一份**真写进去了**，不只是回了个响应。
    # 没有这一条的话，「记下」就是一句只在文档串里的承诺 —— 响应本身就够前端用了，
    # 谁也不会发现台账那一份其实没写。
    assert 台账.已发送("S_DEMO_A", 1) == [(选, "感谢您告诉我们……")]


