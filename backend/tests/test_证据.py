def test_依据条目映射过来字段原样() -> None:
    条 = 从依据条目([
        依据条目(序号="②", 出处="口径表 K05「赠品补发承诺」", 摘要="还没发出，不得再承诺时限",
                 用上=True, 成分=None),
    ])
    assert len(条) == 1
    assert 条[0].序号 is 六源.口径表
    assert 条[0].出处 == "口径表 K05「赠品补发承诺」"
    assert 条[0].用上 is True


def test_依据条目的序号转成枚举() -> None:
    条 = 从依据条目([依据条目(序号="⑥", 出处="补发换货工单 BF1", 摘要="9/25 已登记补发")])
    assert isinstance(条[0].序号, 六源) and 条[0].序号 is 六源.补发换货工单


def test_第七个来源溜不进来() -> None:
    """⚠️ 这是 §五 那条「类型要转」真正防的东西。

    `依据条目.序号` 是 `str`，谁都能塞个 `"⑦"` 或 `"K05"` 进去。不在这里
    当场拦住的话，它会一路走到右栏，而右栏那个分母是 6。
    """
    with pytest.raises(ValueError, match="第七|不是六源|序号"):
        从依据条目([依据条目(序号="⑦", 出处="天上掉下来的", 摘要="x")])


def test_空依据条目列表给空列表() -> None:
    assert 从依据条目([]) == []


def test_依据条目的长摘要也截断() -> None:
    条 = 从依据条目([依据条目(序号="①", 出处="商品属性表", 摘要="长" * 200)])
    assert 条[0].摘要.endswith("…")


