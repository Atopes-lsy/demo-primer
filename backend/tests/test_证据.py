"""证据映射（`app/api/证据.py`）。

**全项目唯一一处真正的映射**：`sources.源记录` 用英文名（`exists` / `table` /
`row_id` / `content`，v9 §4.1 写死的），线上形状 `schemas.Evidence` 用中文名。
放在接口层，别扩散到别处。

# 工单里那张表有两处对不上，这里是实际的做法

`工单交接_给接口线.md` §五 的表头写「`源记录` → `Evidence`」，但表里的字段
（`序号` / `出处` / `摘要`）是 **`guards.依据条目`** 的字段：

- `源记录` **没有 `序号`**（`__slots__` 里没有）—— 序号是 `六源结果.记录`
  那个 dict 的**键**。「拿到一批 `源记录`」本身就意味着序号已经丢了。
- `依据条目` 有 `序号: str` 和 `出处: str`，但**没有 `table` / `row_id`**
  —— 它在链路更下游，早就拼好了。

两个来源都在链路里，所以这里出**两个**映射函数，各补各的。硬凑成一个的话，
要么丢 `table`/`row_id`（六源那边就少了出处），要么对着 `源记录` 找 `序号`
（AttributeError）。
"""

from __future__ import annotations

import pytest

from app.api.证据 import 从依据条目, 从六源, 摘要上限
from app.api.schemas import Evidence
from app.rules.guards import 依据条目
from app.rules.sources import 六源, 六源结果, 六源顺序, 源记录


def _结果(*, 商品属性表: tuple[源记录, ...] = (), 口径表: tuple[源记录, ...] = ()):
    """其余四源给空元组 —— 六键必须齐，这是 `六源结果.__post_init__` 的要求。"""
    记录 = {s: () for s in 六源顺序}
    记录[六源.商品属性表] = 商品属性表
    记录[六源.口径表] = 口径表
    return 六源结果(主张="含乙醇", 记录=记录)


# ══════════════════════════════════════════════════════════
# 一 · 从六源结果
# ══════════════════════════════════════════════════════════


def test_只放查到的() -> None:
    """`Advice.依据` **只放查到的**（`exists=True`）。

    没查到的来源由**前端**按六源补空位 —— 两边都补的话数量对不上，
    右栏那个 `N/6 源命中` 会变成漏列。
    """
    条 = 从六源(_结果(商品属性表=(
        源记录(exists=True, table="商品属性表", row_id="成分栏", content="不含乙醇"),
        源记录(exists=False, table="商品属性表", row_id="", content=""),
    )))
    assert len(条) == 1
    assert 条[0].摘要 == "不含乙醇"


def test_查到但没用上的也要出() -> None:
    """`用上=False` 的进「未命中的六源清单」，**带着摘要一并列出** ——
    右栏展开后第三段就是它。这是 `用上` 和 `exists` 分开的原因：
    一个来源可能查到三条、只用上一条，另两条仍要露面，
    否则「一并列出以示无遗漏」是句空话。
    """
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K10", content="禁语清单", 用上=False),
    )))
    assert len(条) == 1 and 条[0].用上 is False


def test_出处拼成表名加行号() -> None:
    """G3 要求「引用的表名＋行号必须真实存在」，出处就是拿这两个字段回查的。"""
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content="赠品补发承诺"),
    )))
    assert 条[0].出处 == "口径表 K05"


def test_没有行号时只给表名() -> None:
    """① 商品属性表按 `成分栏` 定位，没有 K 编号那种行号。"""
    条 = 从六源(_结果(商品属性表=(
        源记录(exists=True, table="商品属性表", row_id="", content="成分栏"),
    )))
    assert 条[0].出处 == "商品属性表"


def test_序号是六源枚举不是字符串() -> None:
    """⚠️ `工单 §五`：**类型要转**。那边是 `str`，这边是 `sources.六源`。

    声明成 `str` 的话，第 7 个来源会以字符串的形式悄悄溜进右栏 ——
    而「六源是封闭集合」是这个项目对评委的核心承诺之一。
    """
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content="x"),
    )))
    assert isinstance(条[0].序号, 六源)
    assert 条[0].序号 is 六源.口径表


def test_顺序按六源顺序不按数据到达顺序() -> None:
    """同一份输入跑两遍要得出同样的清单 —— 可重放的要求。"""
    条 = 从六源(_结果(
        口径表=(源记录(exists=True, table="口径表", row_id="K05", content="② 先给"),),
        商品属性表=(源记录(exists=True, table="商品属性表", row_id="", content="① 后给"),),
    ))
    assert [e.序号 for e in 条] == [六源.商品属性表, 六源.口径表]


def test_六源全空时是空列表() -> None:
    """六个来源一条都没查到 —— `Advice.依据` 就是空的，前端补六个空位。
    这里返回 `[空条目]` 之类的东西会让前端多数出一源。"""
    assert 从六源(_结果()) == []


