def test_成分不进出线形状() -> None:
    """⚠️ `工单 §五`：**丢掉**。

    `源记录.成分` 是 G3 的输入（物质名比对），对客服没有意义。带出去还要
    连累 `frontend/src/types/index.ts` 跟着改 —— `guards.依据条目` 的文档串
    专门为这个字段写了警告。
    """
    条 = 从六源(_结果(商品属性表=(
        源记录(exists=True, table="商品属性表", row_id="", content="不含乙醇",
               成分=("乙醇", "苯氧乙醇")),
    )))
    线上 = 条[0].model_dump(mode="json")
    assert "成分" not in 线上
    assert set(线上) == {"序号", "出处", "摘要", "用上"}


