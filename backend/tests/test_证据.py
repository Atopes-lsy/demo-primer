def test_长摘要被截断且看得出来被截了() -> None:
    """⚠️ `工单 §五`：「太长就截断，**截断要说**」。

    不说的话，客服读到一句戛然而止的话，会以为材料本身就到此为止 ——
    而 G3 恰恰在管「话术里的事实能不能在依据里找到出处」。
    """
    长 = "禁" * (摘要上限 + 50)
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content=长),
    )))
    assert len(条[0].摘要) < len(长)
    assert 条[0].摘要.endswith("…")


def test_短摘要原样不动() -> None:
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content="还没发出，不得再承诺时限"),
    )))
    assert 条[0].摘要 == "还没发出，不得再承诺时限"


def test_正好等于上限的不截断() -> None:
    """边界：恰好 `摘要上限` 个字，原样出去 —— 多截一个字不算错，
    但「刚好装得下」和「装不下」是两回事，测试得说清是哪一种。"""
    正好 = "字" * 摘要上限
    条 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content=正好),
    )))
    assert 条[0].摘要 == 正好


