def test_两条路出来的都是Evidence() -> None:
    """右栏不关心这条依据是从哪条路来的 —— 它只认 `Evidence`。
    两条路各出一个类型的话，前端得写两套渲染。"""
    甲 = 从六源(_结果(口径表=(
        源记录(exists=True, table="口径表", row_id="K05", content="x"),
    )))[0]
    乙 = 从依据条目([依据条目(序号="②", 出处="口径表 K05", 摘要="x")])[0]
    assert isinstance(甲, Evidence) and isinstance(乙, Evidence)
    assert 甲.model_dump().keys() == 乙.model_dump().keys()
